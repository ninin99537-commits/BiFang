console.log('\n[V1] C1/C2/C3：不给键→不动 / 给了但某条不在→保留 / 某条在→按条目合并');
{
  // C1：整层不给键
  const c1 = 跑({ 上一幕核验: 核验, 下一幕: { 节拍: '受挫' } });
  check('C1 不给「伏笔」键 → 三条一条不少', 编号们(c1.账本), [1, 2, 3]);
  check('C1 字段也没动', c1.账本.伏笔[0]?.状态, '潜伏');

  // C2：给了数组但只含 #2
  const c2 = 跑({ 伏笔: [{ 编号: 2, 内容: '铜扣', 状态: '待兑现' }], 上一幕核验: 核验, 下一幕: { 节拍: '受挫' } });
  check('C2 没提到的 #1/#3 仍在', 编号们(c2.账本), [1, 2, 3]);
  check('C2 #2 按新值', c2.账本.伏笔.find(x => x.编号 === 2)?.状态, '待兑现');
  check('C2 #1 状态未被动', c2.账本.伏笔.find(x => x.编号 === 1)?.状态, '潜伏');

  // C3：条目内漏写字段 → 沿用旧值（P0.95）；显式空值 → 真清空
  const c3 = 跑({ 伏笔: [{ 编号: 1, 状态: '发酵' }], 上一幕核验: 核验, 下一幕: { 节拍: '受挫' } });
  check('C3 漏写 内容 → 沿用「钥匙」', c3.账本.伏笔.find(x => x.编号 === 1)?.内容, '钥匙');
  check('C3 写了的 状态 → 以新值为准', c3.账本.伏笔.find(x => x.编号 === 1)?.状态, '发酵');
}

console.log('\n[V2] 幽灵条目：身份键缺失 / 编号打错 → 不新增，且 拒绝 有记录');
{
  // ① 无编号无内容
  const a = 跑({ 伏笔: [{ 状态: '发酵' }], 上一幕核验: 核验, 下一幕: { 节拍: '受挫' } });
  check('① 条目数不变（没有新增 #4）', 编号们(a.账本), [1, 2, 3]);
  ok('① 拒绝 有记录', a.拒绝.some(x => x.includes('既没有编号也没有内容')));
  check('① 没有签新编号', a.账本.下一伏笔编号, 4);

  // ② 编号打错（9 不存在）+ 没给内容
  const b = 跑({ 伏笔: [{ 编号: 9 }], 上一幕核验: 核验, 下一幕: { 节拍: '受挫' } });
  check('② 条目数不变', 编号们(b.账本), [1, 2, 3]);
  ok('② 拒绝 点名编号打错', b.拒绝.some(x => x.includes('#9') && x.includes('拒收')));

  // ③ 内容打错一个字（当成新伏笔）—— 有内容，属于"合法新条目"，但**不该**因为打错字就变新条目。
  //    这一条只能靠身份键拦住；内容不同 + 无编号 = 契约允许的新伏笔，所以这里验的是"至少不静默"：
  const c = 跑({ 伏笔: [{ 内容: '钥匙钥匙' }], 上一幕核验: 核验, 下一幕: { 节拍: '受挫' } });
  ok('③ 它被当成新伏笔签发（契约允许），但能看到新增', c.账本.伏笔.length === 4 && c.变化.伏笔.some(x => x.includes('新增')));
}

