let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

const 核验 = { 已执行: true, 顶回冲突: '', 说明: '', 主角死亡: false };
const 伏 = (部分: Record<string, any>): any => ({
  编号: 0, 内容: '', 埋设层: 1, 埋设章: 1, 状态: '发酵', 回收窗口: '', 关联冲突: '',
  公开线头: '', 承诺: undefined, ...部分,
});
/** 旧账本：#1 钥匙 / #2 铜扣 / #3 旧信，下一编号 4 */
const 旧账 = (): 导演账本 =>
  ({
    ...emptyData(),
    已分析轮数: 9,
    下一伏笔编号: 4,
    章回: { 章号: 1, 主题: 'x', 计划高潮: '', 进度: '推进', 起始场: 1, 幕纲: ['第1幕｜类型: 事件｜目标:a'], 当前幕号: 1 } as any,
    伏笔: [
      伏({ 编号: 1, 内容: '钥匙', 状态: '潜伏' }),
      伏({ 编号: 2, 内容: '铜扣', 状态: '发酵' }),
      伏({ 编号: 3, 内容: '旧信', 状态: '发酵' }),
    ],
    冲突: [{ 名: '北坡', 对立面: 'WLF', 赌注: '据点', 强度: 7, 阶段: '僵持', 下一步: '', 顶回次数: 1 } as any],
    弧线: [{ 角色: '艾莉', 缺口: '不信任', 阶段: '挣扎', 下一步契机: '' } as any],
    角色命运: [{ 角色ID: '艾莉', 状态: '活跃', 位置: '木屋', 独立目标: [], 当前关系: [], 持久后果: [] } as any],
  } as 导演账本);

const 跑 = (载荷: any) => 应用引擎输出(旧账(), 载荷, 20, {});
const 编号们 = (账: 导演账本) => 账.伏笔.map(x => x.编号).sort((a, b) => a - b);

