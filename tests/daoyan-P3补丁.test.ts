console.log('\n[V9] 累积事实的可见性：只写新增 → 出声，但仍按替换写入（不改语义）');
{
  const 旧 = 旧账() as any;
  旧.伏笔[0].知情角色 = ['艾莉'];
  旧.伏笔[0].关联角色 = ['乔尔'];
  旧.伏笔[0].兑现条件 = ['条件A'];
  旧.角色命运[0].独立目标 = ['修好发电机'];
  const 跑旧 = (载荷: any) => 应用引擎输出(旧, { 上一幕核验: 核验, 下一幕: { 节拍: '受挫' }, ...载荷 }, 20, {});

  // ① 只写新增 → 记拒绝，但值仍是替换后的新值（行为不变）
  const a = 跑旧({ 伏笔: [{ 编号: 1, 知情角色: ['乔尔'] }] });
  ok('① 只写新增 → 拒绝 有记录', a.拒绝.some(x => x.includes('知情角色') && x.includes('少了 艾莉')));
  ok('① 记录里点名"累积事实/写全量"', a.拒绝.some(x => x.includes('累积事实') && x.includes('写全量')));
  check('① 行为不变：仍然是替换', a.账本.伏笔.find(x => x.编号 === 1)?.知情角色, ['乔尔']);

  // ② 含旧值全部 → 不许记拒绝
  const b = 跑旧({ 伏笔: [{ 编号: 1, 知情角色: ['艾莉', '乔尔'] }] });
  ok('② 含旧值全部 → 不记拒绝', !b.拒绝.some(x => x.includes('知情角色')));

  // ③ 显式清空 → 不许记拒绝（合法的清空表达）
  const c = 跑旧({ 伏笔: [{ 编号: 1, 知情角色: [] }] });
  ok('③ 显式清空 → 不记拒绝', !c.拒绝.some(x => x.includes('知情角色')));
  check('③ 显式清空 → 真的清空', c.账本.伏笔.find(x => x.编号 === 1)?.知情角色, []);

  // ④ 可改写清单（兑现条件）替换 → 不许记拒绝
  const d = 跑旧({ 伏笔: [{ 编号: 1, 兑现条件: ['条件B'] }] });
  ok('④ 可改写清单替换 → 不记拒绝', !d.拒绝.some(x => x.includes('兑现条件')));

  // ⑤ 命运册的三个累积事实字段同样生效
  const e = 跑旧({ 角色命运: [{ 角色ID: '艾莉', 独立目标: ['找到弟弟'] }] });
  ok('⑤ 命运.独立目标 只写新增 → 拒绝 有记录', e.拒绝.some(x => x.includes('独立目标') && x.includes('少了 修好发电机')));
  check('⑤ 行为不变：仍是替换', e.账本.角色命运.find(x => x.角色ID === '艾莉')?.独立目标, ['找到弟弟']);

  // ⑥ 字段没出现 → 不记（不写就是没变）
  const f = 跑旧({ 伏笔: [{ 编号: 1, 状态: '发酵' }] });
  ok('⑥ 没写这些字段 → 不记拒绝', !f.拒绝.some(x => x.includes('累积事实')));
}

