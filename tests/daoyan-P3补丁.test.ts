console.log('\n[V5] 校验器：必须同时有 上一幕核验 + 下一幕');
{
  const 抛错 = (载荷: any) => {
    try {
      校验导演载荷(载荷);
      return '';
    } catch (e: any) {
      return String(e?.message ?? e);
    }
  };
  check('{上一幕核验, 下一幕} → 通过', 抛错({ 上一幕核验: {}, 下一幕: {} }), '');
  check('最小合法空补丁（只这两样 + 四本账全不给）→ 通过', 抛错({ 上一幕核验: { 已执行: true }, 下一幕: { 节拍: '受挫' } }), '');
  ok('缺 下一幕 → 抛错（触发重试）', 抛错({ 上一幕核验: {} }).includes('下一幕'));
  ok('缺 上一幕核验 → 抛错', 抛错({ 下一幕: {} }).includes('上一幕核验'));
  ok('只有 {章回:{}} → 抛错（残骸不再算通过）', 抛错({ 章回: {} }).includes('缺少必需的键'));
  ok('数组 / null → 抛错', 抛错([]).includes('不是 JSON 对象') && 抛错(null).includes('不是 JSON 对象'));
}

