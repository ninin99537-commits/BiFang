// 剧情导演 · 收束出口（2026-11-12 P0.7）
//
// 真机病根（需求方 30 个快照 + zcode 探针）：`章回.进度 = '已完结'` 在 src/ 里**零写入点**。
// 于是「收束」是这套状态机里唯一一个**没有代码出口**的状态，而它同时踩了三个坑：
//   ① 契诃夫/收束调度硬排除「日常」→ 演日常，债就永远不还；
//   ② `章长度提醒` 在收束态直接 return → 唯一带计量的收章声音，在最该响时消失；
//   ③ 「幕纲落后或该收章」只说"该收章"，没有任何代码判据。
// 真机：第 69 场进收束，之后 10+ 场日常，整章 78 场不出章。
//
// 本批做四件：
//   1. 收束起始场（代码填）+ 代码写「已完结」—— 全账本唯一一处代码推进章回状态；
//   2. 章长度提醒在收束/已完结态继续说话（改成计量 + 催"开新章"）；
//   3. 收束出口硬裁决：禁"躲债节拍"、真空账本只能收尾、预算用尽强制收章；
//   4. 生活幕提醒让位（否则与硬裁决当场对打）。
//
// 白名单刻意**不碰**终局五步用到的节拍（第1步=阴影、第3/5步=余波、第2步=受挫、第4步=高潮），
// 所以只禁「日常 / 小胜」两个 —— 与五步零冲突。
