  const 退出 = 应用引擎输出(同章继续.账本, { 章回: 章({ 进度: '推进' }) }, 42, {});
  check('退出收束: 清空起点', 退出.账本.章回?.收束起始场, undefined);

  const 换章 = 应用引擎输出(退出.账本, { 章回: 章({ 章号: 3, 进度: '收束' }) }, 43, {});
  check('换章后进收束: 重记本场', 换章.账本.章回?.收束起始场, (Number(退出.账本.已分析轮数) || 0) + 1);
