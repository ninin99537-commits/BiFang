// 剧情导演 · 台上判定(2026-11-12 架构深化 ④)
//
// 起因是一份架构评审里最扎的一条:
//   「这一轮到底下不下令」有五份抄本 —— 注入层的 7 道闸(权威)、index.ts 的暂停注入、
//   update.ts 的暂停注入、面板的指令预览、球状态的计算运行状态。而**面板那份只查了两道闸**,
//   于是熔断期面板摊开一整段本幕指令, 正文一个字节都拿不到:
//   面板上那句"这一场要演什么"是一条**不会发生的命令**。
//
// 这个用例文件钉两件事:
//   ① 七道闸的**顺序**是语义(挪一条就改变真机行为), 用 `台上判定顺序` 钉死;
//   ② 每道闸单独命中、以及两两相遇时谁压过谁 —— 以前这些只能靠读一个 130 行 if 链来确认。
//
// 反面教材(这次一并替换掉的): 旧用例用 `界面源.includes('平静刚结束.value')` 这种源码 grep
// 来证明"面板用的是同一个判断"。它能证明那句话出现过, 证明不了熔断/剧终时面板会怎样 —— 而后者才是真机 bug。
