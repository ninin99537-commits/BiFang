console.log('\n[3] 适配器: 注入层只读这份结论(闸一道都不许在注入层重写)');
{
  const 账 = { ...emptyData(), 当前指令: { 编号: 1, 节拍: '高潮', 硬性要求: 'x' } as any } as any;
  const 默认 = SettingsSchema.parse({});
  const 平静 = { ...默认, 导演: { ...默认.导演, 平静模式: true } };
  const 撒手 = { ...默认, 导演: { ...默认.导演, 自动接管: false } };
  const 停用 = { ...默认, 启用导演: false };
  const 有红线 = { ...默认, 导演: { ...默认.导演, 平静模式: true, 红线: ['不写性暴力'] } };

  check('正常 → 文本非空(本幕指令)', 应注入的指令文本(账, 默认, false).length > 0, true);
  check('停用 → 空串', 应注入的指令文本(账, 停用, false), '');
  check('撒手 → 空串(连红线也不注)', 应注入的指令文本(账, 撒手, false), '');
  check('已剧终 → 空串', 应注入的指令文本({ ...账, 已剧终: true }, 默认, false), '');
  check('待决死亡 → 空串', 应注入的指令文本({ ...账, 待决死亡: true }, 默认, false), '');
  check('暂停注入(调用方传入) → 空串', 应注入的指令文本(账, 默认, true), '');
  check('已跳过 → 空串', 应注入的指令文本({ ...账, 当前指令: { ...账.当前指令, 已跳过: true } }, 默认, false), '');
  check('无指令 → 空串', 应注入的指令文本(emptyData(), 默认, false), '');

  // 平静: 没有红线时文本也是空串, 但**种类是只红线** —— 面板靠种类区分"为什么空"
  check('平静 + 无红线 → 文本空', 应注入的指令文本(账, 平静, false), '');
  check('平静 + 无红线 → 种类仍是只红线', 此刻台上(账, 平静, false).种类, '只红线');
  ok('平静 + 有红线 → 注入块里有红线', 应注入的指令文本(账, 有红线, false).includes('不写性暴力'));
  ok('红线块里写明理由(短原因)', 应注入的指令文本(账, 有红线, false).includes('这一段没有导演编排'));
  check('平静前作废 → 文本空(旧编排不注回去)', 应注入的指令文本({ ...账, 平静场数: 36 }, 默认, false), '');
  ok(
    '平静前作废 + 有红线 → 红线块里的理由是"平静刚结束"',
    应注入的指令文本({ ...账, 平静场数: 36 }, { ...默认, 导演: { ...默认.导演, 红线: ['不写性暴力'] } }, false).includes(
      '平静刚结束',
    ),
  );

  // 面板与注入是同一个出口: 台上文本 的文本 === 应注入的指令文本
  for (const [名, 设] of [['默认', 默认], ['平静', 平静], ['撒手', 撒手], ['停用', 停用], ['平静+红线', 有红线]] as const) {
    check(`面板拿到的预览 === 注入文本(${名})`, 台上文本(账, 设, false).文本, 应注入的指令文本(账, 设, false));
  }
}

