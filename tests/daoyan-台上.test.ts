import { 应注入的指令文本, 台上文本, 此刻台上 } from '../src/剧情导演/注入';
import { emptyData } from '../src/剧情导演/快照';
import { SettingsSchema } from '../src/剧情导演/schema';
import 注入源 from '../src/剧情导演/注入.ts?raw';
import 界面源 from '../src/剧情导演/悬浮球界面.vue?raw';

(globalThis as any)._ = {
  clamp: (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), hi),
  cloneDeep: (v: any) => (v === undefined ? undefined : JSON.parse(JSON.stringify(v))),
};
(globalThis as any).localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

/** 只改一个开关 */
const 输入 = (改: Partial<台上输入> = {}): 台上输入 => ({ ...空台上输入(), ...改 });

// ---------------------------------------------------------------------------
console.log('\n[1] 闸的顺序就是语义(挪一条就会改变真机行为)');
{
  check('七道闸 + 下单, 顺序被钉死', [...台上判定顺序], [
    '停用',
    '已剧终',
    '群聊',
    '自动接管关闭',
    '暂停注入',
    '平静',
    '熔断',
    '无指令',
    '已跳过',
    '平静刚结束',
  ]);
  // 顺序之所以重要, 举两个真机例子:
  //   · 「已剧终」必须压在「平静」之前 —— 剧终后连红线也不该再往上下文里塞东西;
  //   · 「自动接管关闭」必须压在「平静」之前 —— 否则"完全撒手"会被平静的红线块悄悄打破。
  check('已剧终 + 平静 → 空(不是只红线)', 判定台上(输入({ 已剧终: true, 平静模式: true })).种类, '空');
  check('撒手 + 平静 → 空(不是只红线)', 判定台上(输入({ 自动接管: false, 平静模式: true })).种类, '空');
  check('群聊 + 撒手 → 群聊先判', 判定台上(输入({ 群聊: true, 自动接管: false })).原因, '群聊');
  check('已跳过 + 平静前作废 → 已跳过先判', 判定台上(输入({ 指令已跳过: true, 平静前作废: true })).原因, '已跳过');
  check('平静 + 熔断 → 平静先判(两者都只出红线, 但原因不同)', 判定台上(输入({ 平静模式: true, 引擎暂停: true })).原因, '平静');
  check('熔断 + 平静前作废 → 熔断先判', 判定台上(输入({ 引擎暂停: true, 平静前作废: true })).原因, '熔断');
}

