console.log('\n[2] 每道闸单独命中: 种类 + 原因 + 两套文案都在');
{
  const 各闸: { 名: string; 改: Partial<台上输入>; 种类: string }[] = [
    { 名: '停用', 改: { 启用导演: false }, 种类: '空' },
    { 名: '已剧终', 改: { 已剧终: true }, 种类: '空' },
    { 名: '群聊', 改: { 群聊: true }, 种类: '空' },
    { 名: '自动接管关闭', 改: { 自动接管: false }, 种类: '空' },
    { 名: '暂停注入', 改: { 暂停注入: true }, 种类: '空' },
    { 名: '待决死亡(与暂停注入同口径)', 改: { 待决死亡: true }, 种类: '空' },
    { 名: '平静', 改: { 平静模式: true }, 种类: '只红线' },
    { 名: '熔断', 改: { 引擎暂停: true }, 种类: '只红线' },
    { 名: '无指令', 改: { 有指令: false }, 种类: '空' },
    { 名: '已跳过', 改: { 指令已跳过: true }, 种类: '空' },
    { 名: '平静刚结束', 改: { 平静前作废: true, 平静场数: 36 }, 种类: '只红线' },
  ];
  for (const 项 of 各闸) {
    const 结论 = 判定台上(输入(项.改));
    check(`[${项.名}] 种类`, 结论.种类, 项.种类);
    ok(`[${项.名}] 有机器可读原因`, 结论.原因.length > 0);
    ok(`[${项.名}] 有给用户看的一句话`, 结论.说明.length > 0);
    // 只红线的三道闸必须带"注入块括号里那一小句" —— 少一个, 正文会收到一句没有理由的红线块
    if (项.种类 === '只红线') ok(`[${项.名}] 带短原因(进注入文本的括号)`, 结论.短原因.length > 0);
    else check(`[${项.名}] 空态不需要短原因`, 结论.短原因, '');
  }
  // 平静场数只影响文案, 不影响判定
  ok('说明里带上平静场数', 判定台上(输入({ 平静模式: true, 平静场数: 58 })).说明.includes('58'));
  ok('平静刚结束的说明也带场数', 判定台上(输入({ 平静前作废: true, 平静场数: 36 })).说明.includes('36'));
  ok('待决死亡的说明指向面板上的抉择', 判定台上(输入({ 待决死亡: true })).说明.includes('死亡'));
  // 默认输入 = 正常下令
  check('什么都没挡 → 下令', 判定台上(空台上输入()).种类, '下令');
  check('下令时 原因/说明/短原因 都为空', [判定台上(空台上输入()).原因, 判定台上(空台上输入()).说明, 判定台上(空台上输入()).短原因], ['', '', '']);
}

