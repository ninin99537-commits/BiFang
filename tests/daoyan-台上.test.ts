console.log('\n[5] 面板顶层不能有重名声明(这一轮真踩过)');
{
  // 真事: 把 `台上` 搬进面板时留下了一行旧声明, 于是 SFC 里有两个 `const 台上`。
  // `tsc` 不看 .vue, 用例只把 .vue 当文本读 —— 两关都绿, 只有 `pnpm build` 报
  // "[vue/compiler-sfc] Identifier '台上' has already been declared"。
  // 这条就是补上那个空缺: 只查**顶层**(顶格写)的声明, 缩进里的局部同名不算。
  const 脚本 = /<script setup[^>]*>([\s\S]*?)<\/script>/.exec(界面源)?.[1] ?? '';
  ok('抓到了 script setup 块', 脚本.length > 1000);
  const 名字 = [...脚本.matchAll(/^(?:const|let|function|async function)\s+([^\s=({:;]+)/gm)].map(m => m[1]);
  ok('确实扫到了足够多的顶层声明(防空转)', 名字.length > 50);
  const 计数 = new Map<string, number>();
  for (const 名 of 名字) 计数.set(名, (计数.get(名) ?? 0) + 1);
  const 重名 = [...计数.entries()].filter(([, 次数]) => 次数 > 1).map(([名]) => 名);
  check('顶层声明没有重名(重复声明会让整个插件构建失败)', 重名, []);
}

