// 人设工坊 · 自动填充判据(2026-10-15 用户报「角色名、人物索引文本框里的内容不会自动变」)
//
// 判据(来自用户原话「一直都是第一个人设的内容」):
//   1. 框空 → 填
//   2. ★ **框里还是上一次自动填的值 → 必须允许覆盖**(这就是那个 bug 的正身)
//   3. 用户手改过(值与自动值不同) → 不许覆盖
//   4. ★ **对照/反例**: 把判据换成旧写法「非空就不填」, 判据 2 必须变红 ——
//      否则说明这个测试压根没测到用户报的那条。
import { 该自动填 } from '../src/人设工坊/lib/自动填';

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  }
  else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}

console.log('\n[1] 三种状态都要测(只测一种的话这个 bug 会原样通过)');
{
  check('空框 → 填', 该自动填('', ''), true);
  check('空框(只有空白) → 填', 该自动填('   ', '林千昭'), true);
  check('★ 还是上次自动值 → 允许覆盖(用户没动过)', 该自动填('林千昭', '林千昭'), true);
  check('★ 用户手改过 → 不许覆盖', 该自动填('我自己起的名字', '林千昭'), false);
  check('两边都有空白也算没动过', 该自动填('  林千昭  ', '林千昭'), true);
}

console.log('\n[2] ★ 复现用户那条: 连着生成两个人设');
{
  // 第一次: 框空 → 自动填「林千昭」
  let 框 = '';
  let 自动值 = '';
  if (该自动填(框, 自动值)) {
    框 = '林千昭';
    自动值 = '林千昭';
  }
  check('第一个角色自动带出', 框, '林千昭');

  // 第二次: 结果换成「周砚」。**框里还是「林千昭」, 非空** ——
  // 旧判据「非空就不填」在这里直接 return, 于是框永远停在林千昭。
  if (该自动填(框, 自动值)) {
    框 = '周砚';
    自动值 = '周砚';
  }
  check('★ 第二个角色能自动带出(用户报的那条)', 框, '周砚');
}

console.log('\n[3] ★ 对照组: 旧判据在这条上必须变红');
{
  // 旧写法: if (框.trim()) return;  即「非空 → 不填」
  const 旧判据 = (当前: string, _上次自动值: string) => !String(当前 ?? '').trim();
  // 用同一组输入喂两个判据, 结果必须不同 —— 否则这个测试没有分辨力。
  check('旧判据在「还是自动值」上给 false(所以它会卡住)', 旧判据('林千昭', '林千昭'), false);
  check('新判据在同一输入上给 true(所以它能更新)', 该自动填('林千昭', '林千昭'), true);
  check('两者对「用户手改过」的结论一致(这条不是靠牺牲手改换来的)', 旧判据('我起的', '林千昭'), 该自动填('我起的', '林千昭'));
}

console.log(`\n人设工坊自动填: ${pass} 通过, ${fail} 失败`);
process.exit(fail === 0 ? 0 : 1);
