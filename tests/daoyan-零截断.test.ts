// 剧情导演 · 零截断(2026-11-11)
//
// 用户要求:「不要有任何的代码截断」。以前"零截断"只钉在**拼装层**(prompts/注入 不含 slice),
// 但账本归一化那一层还在**静默切字**:
//   - 字段表 的 `字段.上限`(主题 60 / 冲突名 30 / 角色ID 40 / 书纲ID 12 …)与 `条数上限`(40 条);
//   - 引擎规则 把必演内容切到 24 字、知情核对切到 40/160/200/120;
//   - 书纲 把 ID 切到 12、角色ID 切到 40、拒绝信息里切 20;
//   - 账本数据 的拒绝信息切 20/16; 取料 的提醒把"事"切到 12。
// 这些切口有两个实际后果: ① 面板按全名 `find` 找不到被切过名的条目(手改静默失效);
// ② 导演看到的和账本里存的不是同一句话, 它据此判断"这不就是我上轮写的吗"。
//
// 这份用例钉住三件事:
//   ① 账本/提示词/注入/导演输入这条路**一个字段都不切**(源码钉子 + 行为用例);
//   ② 保留下来的"有界"只有两种, 都不是截断: **保留多少条**(历史档案/最近 N 条)与**报错预览**(带字数标注);
//   ③ 补读窗口之外的楼层缺口必须**说出来**(跳读条数进导演输入)。
import { createPinia, setActivePinia } from 'pinia';
import type { 导演账本 } from '../src/剧情导演/schema';
import { SettingsSchema } from '../src/剧情导演/schema';
import { emptyData } from '../src/剧情导演/快照';
import { 应用引擎输出 } from '../src/剧情导演/账本数据';
import { buildDirectorMessages } from '../src/剧情导演/prompts';
import { 规范化知情核对 } from '../src/剧情导演/引擎规则';
import 字段表源 from '../src/剧情导演/字段表.ts?raw';
import 引擎源 from '../src/剧情导演/引擎规则.ts?raw';
import 书纲源 from '../src/剧情导演/书纲.ts?raw';
import 账本源 from '../src/剧情导演/账本数据.ts?raw';
import 取料源 from '../src/剧情导演/取料.ts?raw';
import 快照源 from '../src/剧情导演/快照.ts?raw';

(globalThis as any)._ = {
  clamp: (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), hi),
  cloneDeep: (v: any) => (v === undefined ? undefined : JSON.parse(JSON.stringify(v))),
};
(globalThis as any).localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

const 账本 = (部分: Partial<导演账本> = {}): 导演账本 => ({ ...emptyData(), 已分析轮数: 10, ...部分 });
const 长 = (n: number) => '长'.repeat(n);

// ---------------------------------------------------------------------------
// ① 源码钉子: 内容通路上一个字都不许切
// ---------------------------------------------------------------------------
console.log('\n[1] 源码: 账本归一化 / 装配 / 书纲 / 拒绝信息 都不再有 slice');
{
  // 字段表里唯一允许的 slice 是 `ID.slice(名.length)` —— 那是"看名字后面那个字符是不是分隔符", 不是切内容
  ok('字段表: 没有切字', !字段表源.includes('text.slice(') && !字段表源.includes('.slice(0, '));
  ok('字段表: 上限配置项已删', !字段表源.includes('字段.上限') && !字段表源.includes('字段.条数上限'));
  // 2026-11-12 收窄（需求方裁定 #55）：一刀切的"没有任何 slice"过严 ——
  // 本例自己的注释（:14）就写着"有界只包括**保留多少条**（历史档案/最近 N 条）与报错预览"，
  // 而拒绝回执的 `拒绝回执上限 = 5` 正是"保留多少条"。改成白名单式：
  // **只放行"保留条数"这一处**，其余含 slice 的行一律算违规 —— 不写通用放行正则，
  // 否则以后谁写个切字符串的 slice 也能混过去。
  // 限条数真的生效由行为用例兜底：`daoyan-拒绝回路` [4]（塞 8 条 → ≤5 且终态类优先）。
  const 引擎违规行 = 引擎源
    .split('\n')
    .filter(行 => 行.includes('.slice(') && !/\.slice\(0, 拒绝回执上限\)/.test(行));
  check('引擎规则: 除"保留条数"外没有任何 slice', 引擎违规行, []);
  ok('书纲: 没有任何 slice', !书纲源.includes('.slice('));
  ok('账本数据: 拒绝信息不切内容', !账本源.includes('规范.内容.slice(') && !账本源.includes('项.事项.slice('));
  ok('取料: 结构提醒不切"事"', !取料源.includes('条.事.slice('));
  // 「有界保留」这一层要留着: 它管的是**保留多少条**(历史档案/代价账), 不是把一条切掉
  ok('有界保留还在(档案条数/代价账)', 账本源.includes('.slice(-归档记录上限)') && 账本源.includes('.slice(-代价保留条数)'));
}

// ---------------------------------------------------------------------------
// ② 行为: 长文本原样进账本
// ---------------------------------------------------------------------------
console.log('\n[2] 行为: 超长字段原样保留(以前会被切到 30~60 字)');
{
  const 长主题 = 长(100);
  const 长名 = 长(80);
  const 应用 = 应用引擎输出(
    账本(),
    { 章回: { 章号: 1, 主题: 长主题, 计划高潮: '', 进度: '推进' }, 冲突: [{ 名: 长名, 对立面: 长名, 赌注: 'x', 强度: 5, 阶段: '铺垫' }] },
    3,
  );
  check('章回主题 100 字一个字不少', 应用.账本.章回?.主题, 长主题);
  check('冲突名 80 字一个字不少', 应用.账本.冲突[0]?.名, 长名);

  // 冲突名被切过的话, 面板按全名 find 就找不到那一条 —— 这里是同一件事的反证
  ok('按全名还能找到那一条', !!应用.账本.冲突.find(条 => 条.名 === 长名));

  const 知情 = 规范化知情核对([{ 角色: 长(50), 事: 长(300), 知道吗: '知道', 证据: 长(400), 处理: 长(200) }]);
  check('知情核对: 角色 50 字不切', 知情[0]?.角色.length, 50);
  check('知情核对: 事 300 字不切', 知情[0]?.事.length, 300);
  check('知情核对: 证据 400 字不切', 知情[0]?.证据.length, 400);
  check('知情核对: 处理 200 字不切', 知情[0]?.处理.length, 200);

  const 数组 = 应用引擎输出(账本(), { 章回: { 章号: 1, 主题: 'x', 计划高潮: '', 进度: '推进', 幕纲: Array.from({ length: 60 }, (_, i) => `第${i}幕`) } }, 3);
  check('幕纲 60 条一条不丢(条目数上限也删了)', 数组.账本.章回?.幕纲?.length, 60);
}

// ---------------------------------------------------------------------------
// ③ 跳读缺口: 补读窗口之外的楼层缺口要写进导演输入
// ---------------------------------------------------------------------------
console.log('\n[3] 补读窗口之外: 缺口要说出来, 不许静默当作"什么都没发生"');
{
  const 造 = (跳读条数?: number) =>
    buildDirectorMessages({
      账本: 账本(),
      reply: '【最新回复】\n正文',
      replyCount: 1,
      跳读条数,
      context: '玩家输入',
      worldbook: '',
      playerName: null,
      playerDesc: '',
      破限: false,
      头部填充: false,
      头部填充文本: '',
      防截断: false,
      预填充: false,
    })
      .map(m => m.content)
      .join('\n');
  ok('有跳读 → 明说"没有读到"并给出条数', 造(5).includes('有 5 条更早的回复**没有读到**'));
  ok('有跳读 → 提醒它们已经发生过', 造(5).includes('已经发生过了'));
  ok('没有跳读 → 一个字都不提', !造(0).includes('没有读到'));
  ok('取料把跳读条数传进去了', 取料源.includes('跳读条数: 跳读'));
  ok('跳读会在控制台提示', 取料源.includes('条更早的回复没读'));
}

// ---------------------------------------------------------------------------
// ④ 面板手改不再挪锚点
// ---------------------------------------------------------------------------
console.log('\n[4] 面板手改: 写回原锚点, 不把锚点挪到最新楼');
{
  ok('有原锚点判断', 快照源.includes('原锚点有效'));
  // 2026-11-13 H-3: 判据从"写成功没成功"改成"那一楼还在不在"（原锚点有效且楼层在才只写原处）
  ok('原锚点无效/楼层被删时退回最新楼', /原锚点有效 && 楼层还在\(原锚点\)\) return 写\(原锚点\)[\s\S]{0,120}写\(最新\)/.test(快照源));
  ok('注释写清两个后果', 快照源.includes('重新推进') && 快照源.includes('删楼回退'));
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0) process.exit(1);
