// 彼方 · W1 名字归一 + W2 工具 schema 收紧 —— 批次: 第二轮(方案 §23 W1/W2, 改判 §25)。
//
// 2026-11-18 需求方改判: **合并的条件必须是"证据", 不是"相似"。**
// 相似只配换来一行提示, 不配换来一张卡的消失。
//
// 证据 → 自动合并(三桶):
//   1. 完全同名(简繁归一后一致)
//   2. 去姓前缀包含(允许跨轮次)
//   3. 同一回复内名字相近 + 内容重合度 ≥ 80%
// 相似 → 只报告(不合并):
//   跨轮次的近名(如已有「艾莉」遇到新的「埃莉」)
//
// 需求方点名的四组必测:
//   · 张三/张四        → 跨轮次近名 → **不合并**, 只报告(这是改判的核心动机)
//   · 艾莉/艾莉丝      → 跨轮次"包含"→ **不合并**(改判后去掉了模糊包含, 只认"等于")
//   · 乔尔/乔尔·米勒   → 去姓前缀 → **合并**(证据)
//   · 艾莉/埃莉(同回复内, 内容一字不差) → **合并**(证据)
