console.log('\n[C] 端到端: 用户实测那一轮(同回复内 埃莉/杰西/艾莉)');
{
  const 同一张 = 卡({ 位置: '广场东角' });
  const 数据 = emptyData();
  数据.名单 = ['埃莉', '杰西'];
  数据.NPC = { 埃莉: 同一张, 杰西: 卡({ 位置: '酒馆' }) };
  const parsed = {
    剧情时间: { 开始: '2026-01-02 12:00', 结束: '2026-01-02 12:30' },
    NPC: {
      埃莉: 同一张,
      杰西: 卡({ 位置: '酒馆' }),
      艾莉: 同一张, // 同回复内 + 内容一字不差
    },
  };
  const { 数据: 新, 摘要 } = applyUpdate(数据, parsed, '玩家', true, true);
  eq('[C] 名单里没有"艾莉"', 新.名单.includes('艾莉'), false);
  eq('[C] 名单长度没变', 新.名单.length, 2);
  eq('[C] 卡数没变', Object.keys(新.NPC).length, 2);
  ok('[C] 「艾莉」没有单独建卡', 新.NPC['艾莉'] === undefined);
  ok('[C] 摘要里更新的是"埃莉"', 摘要.更新.includes('埃莉') && !摘要.更新.includes('艾莉'), JSON.stringify(摘要.更新));
  eq('[C] 没有疑似重复(这一轮全是证据)', 摘要.疑似重复, []);
}

