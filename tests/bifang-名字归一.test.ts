let pass = 0;
let fail = 0;
function ok(名: string, 条件: boolean, 备注?: string) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  FAIL ${名}${备注 ? `  (${备注})` : ''}`);
  }
}
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  FAIL ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}

/** 造一张够完整的卡 */
function 卡(额外: Record<string, any> = {}) {
  return {
    身份锚点: '28岁巡逻队成员',
    当前在做: '巡逻',
    当前状态: '警觉',
    位置: '广场',
    近期关键事件: '2026-01-02 广场集合',
    生活状态: '吃饭(2026-01-02 08:00)',
    接下来想做: '换岗',
    当前目标: '保住差事',
    未完成事项: [],
    心事: '弟弟的学费',
    藏起来的打算: '查清真相',
    ...额外,
  };
}

// ─────────────────────────────────────────────────────────────
console.log('\n[A] 需求方点名的四组正反例(改判的核心)');
{
  // ① 张三/张四 —— 跨轮次近名 → 不合并, 只报告
  const 张三 = 卡({ 位置: '张三家', 心事: '老大的事' });
  const 张四 = 卡({ 位置: '酒馆', 心事: '别的事', 当前在做: '喝酒', 当前状态: '放松' });
  const r1 = 归一名('张四', ['张三'], [], 张四, { 张三 });
  eq('[A/①] 张三 vs 张四 → **不合并**', r1.合并到, null);
  eq('[A/①] 但报疑似重复', r1.疑似重复, '张三');
  eq('[A/①] 名字保持原样', r1.名, '张四');
  ok('[A/①] 没有合并依据', r1.理由 === null);

  // ② 艾莉/艾莉丝 —— 跨轮次的"包含"→ 不合并(改判后只认"去姓后等于", 不认模糊包含)
  const r2 = 归一名('艾莉丝', ['艾莉'], [], 卡(), { 艾莉: 卡() });
  eq('[A/②] 艾莉 vs 艾莉丝 → **不合并**', r2.合并到, null);
  ok('[A/②] 名字保持原样', r2.名 === '艾莉丝');

  // ③ 乔尔/乔尔·米勒 —— 去姓前缀 → 合并(证据)
  const r3 = 归一名('乔尔·米勒', ['乔尔'], [], 卡(), { 乔尔: 卡() });
  eq('[A/③] 乔尔·米勒 → 并入「乔尔」', r3.合并到, '乔尔');
  eq('[A/③] 依据是去姓前缀', r3.理由, '去姓前缀');
  // 反向也成立(先来的是全名)
  const r3b = 归一名('乔尔', ['乔尔·米勒'], [], 卡(), { '乔尔·米勒': 卡() });
  eq('[A/③] 反向: 乔尔 → 并入「乔尔·米勒」', r3b.合并到, '乔尔·米勒');
  // 中文三字名 **不再**做去姓合并(P1-13): 「林淑仪」→「淑仪」是猜, 不是确定操作
  const r3c = 归一名('淑仪', ['林淑仪'], [], 卡(), { 林淑仪: 卡() });
  eq('[A/③] P1-13: 中文三字去姓 → **不合并**', r3c.合并到, null);
  eq('[A/③] P1-13: 但报疑似重复', r3c.疑似重复, '林淑仪');

  // ④ 艾莉/埃莉 同回复内 + 内容一字不差 → 合并(证据)
  const 同一张 = 卡({ 位置: '广场东角' });
  const r4 = 归一名('艾莉', [], ['埃莉'], 同一张, { 埃莉: 同一张 });
  eq('[A/④] 同回复内内容一致 → 合并', r4.合并到, '埃莉');
  eq('[A/④] 依据是同回复内容一致', r4.理由, '同回复内容一致');

  // ④ 反向: 同回复内名字相近但内容差异大 → 不合并
  const 甲卡 = 卡({ 位置: '广场', 心事: '弟弟' });
  const 乙卡 = 卡({ 位置: '酒馆', 心事: '仇人', 当前在做: '喝酒', 当前状态: '醉', 接下来想做: '回家' });
  const r5 = 归一名('艾莉', [], ['埃莉'], 甲卡, { 埃莉: 乙卡 });
  eq('[A/④] 同回复内但内容差异大 → 不合并', r5.合并到, null);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[B] 三条证据判据各自的边界');
{
  // 完全同名(含简繁)
  eq('[B] 完全同名 → 不需要合并(合并到为 null)', 归一名('艾莉', ['艾莉']).合并到, null);
  eq('[B] 简繁差异 → 采用已有写法', 归一名('小麗', ['小丽']).名, '小丽');
  eq('[B] 简繁合并的理由是"同名"', 归一名('小麗', ['小丽']).理由, '同名');
  eq('[B] 简繁差异(艾莉/艾莉)', 归一名('艾莉', ['艾莉']).名, '艾莉');

  // 单字名字: 不比编辑距离(否则任何两个单字都距离 1)
  const r = 归一名('乙', ['甲'], [], 卡(), { 甲: 卡() });
  eq('[B] 甲 vs 乙 → 不合并', r.合并到, null);
  eq('[B] 也不报疑似(单字不判)', r.疑似重复, null);

  // 差两个字
  const r2 = 归一名('汤米', ['乔尔'], [], 卡(), { 乔尔: 卡() });
  eq('[B] 乔尔 vs 汤米 → 不合并', r2.合并到, null);
  eq('[B] 也不报疑似(距离>1)', r2.疑似重复, null);

  // 内容重合度函数本身(分母是"两边字段数的较大值", 复查 P1-12)
  const a = { x: '1', y: '2', z: '3' };
  eq('[B] 完全相同 → 重合度 1', 内容重合度(a, { ...a }), 1);
  eq('[B] 无公共字段 → 重合度 0', 内容重合度(a, { p: '1' }), 0);
  eq('[B] 三个里一个相同 → 1/3', 内容重合度(a, { x: '1', y: 'X', z: 'X' }), 1 / 3);
  // P1-12 的核心: 分母是较大值, 不是交集
  // 张三 10 字段 vs 张四 2 字段, 这 2 个恰好相同 → 2/10 = 0.2(不是 2/2 = 1.0)
  const 张三卡 = { f1: 'a', f2: 'b', f3: 'c', f4: 'd', f5: 'e', f6: 'f', f7: 'g', f8: 'h', f9: 'i', f10: 'j' };
  const 张四卡 = { f1: 'a', f2: 'b' };
  eq('[B/P1-12] 10 字段 vs 2 字段(2 个相同) → 0.2, 不是 1.0', 内容重合度(张三卡, 张四卡), 0.2);
  eq('[B/P1-12] 共有字段数 = 2', 共有字段数(张三卡, 张四卡), 2);
  eq('[B/P1-12] 全同的 4 字段卡 → 1.0', 内容重合度({ a: '1', b: '2', c: '3', d: '4' }, { a: '1', b: '2', c: '3', d: '4' }), 1);

  // 疑似重复提示的文案
  ok('[B] 提示文案含"未合并"', 疑似重复提示('埃莉', '艾莉').includes('未合并'));
  ok('[B] 提示文案含"手动确认"', 疑似重复提示('埃莉', '艾莉').includes('手动确认'));
}

