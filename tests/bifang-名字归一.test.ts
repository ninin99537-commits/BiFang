console.log('\n[B2] 复查 P1-12: 短卡刷满分不再导致静默合并');
{
  // 模型给新人「张四」只写 2 个字段, 恰好和「张三」这两个字段相同
  const 张三卡 = { 位置: '广场', 当前在做: '巡逻' };
  const 张四卡 = { 位置: '广场', 当前在做: '巡逻' };
  // 同一回复内 + 名字相近(距离1) + 内容"看起来全同"
  // 旧逻辑: 2/2 = 1.0 >= 0.8 → 合并(张四的卡消失, 且无疑似提示)
  // 新逻辑: 共有字段 2 < 3 → 不做内容判定 → 不合并
  const r = 归一名('张四', [], ['张三'], 张四卡, { 张三: 张三卡 });
  eq('[B2/P1-12] 共有字段不足 3 个 → **不合并**', r.合并到, null);
  eq('[B2/P1-12] 名字保持原样', r.名, '张四');

  // 真重复: 各 4 字段全同 → 仍然合并(证据够)
  const 埃莉卡 = { 位置: '广场', 当前在做: '巡逻', 当前状态: '警觉', 心事: '弟弟' };
  const 艾莉卡 = { 位置: '广场', 当前在做: '巡逻', 当前状态: '警觉', 心事: '弟弟' };
  const r2 = 归一名('艾莉', [], ['埃莉'], 艾莉卡, { 埃莉: 埃莉卡 });
  eq('[B2/P1-12] 4 字段全同 → 仍合并', r2.合并到, '埃莉');
  eq('[B2/P1-12] 依据仍是同回复内容一致', r2.理由, '同回复内容一致');

  // 边界: 恰好 3 个共有字段, 全同 → 合并
  const 甲3 = { a: '1', b: '2', c: '3' };
  eq('[B2/P1-12] 恰好 3 个共有字段全同 → 合并', 归一名('李四', [], ['李斯'], 甲3, { 李斯: { ...甲3 } }).合并到, '李斯');
  // 边界: 3 个共有但只有 2 个相同 → 2/3 = 0.67 < 0.8 → 不合并
  eq('[B2/P1-12] 3 个共有但 2 同 → 不合并', 归一名('李四', [], ['李斯'], { a: '1', b: '2', c: 'X' }, { 李斯: { a: '1', b: '2', c: '3' } }).合并到, null);
}

