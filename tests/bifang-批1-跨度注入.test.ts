import { 剧情跨度 } from '../src/彼方_NPC幕后生命状态系统/剧情时间';
import { buildInjectionPrompt, buildUpdateMessages } from '../src/彼方_NPC幕后生命状态系统/prompts';

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  }
  else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean, note?: string) {
  check(label + (note ? `  (${note})` : ''), !!cond, true);
}

/** 造一段注入文本（纯函数，不碰运行时） */
function 造注入(spanText: string, storyTime: string, cards: Record<string, any>, physio = true) {
  return buildUpdateMessages({
    reply: `【最新回复】\n${storyTime || ''} 院子里很安静。`,
    replyCount: 1,
    tracked: Object.keys(cards),
    inSceneHint: Object.keys(cards),
    currentCards: cards,
    currentStoryTime: '2026-11-10 08:00',
    storyTimeHint: storyTime,
    storySpan: spanText,
    physioEnabled: physio,
  }).messages.map(m => m.content).join('\n');
}

const 造卡 = () => ({
  当前在做: '在院子里劈柴, 劈到一半停下来擦汗',
  当前状态: '神色疲惫, 说话有点哑',
  位置: '院子',
  身份锚点: '35岁急诊科护士, 独自抚养5岁女儿, 三班倒作息',
  近期关键事件: '2026-11-10 在商场给孩子买了玩偶',
  生活状态: '吃饭(2026-11-10 12:00); 洗漱(2026-11-10 08:00)',
  当前目标: '想盘下店面',
});

const 取跨度行 = (文本: string) => 文本.split('\n').find(l => l.includes('距上次更新已过')) ?? '(没找到)';

// ---------------------------------------------------------------- [1] 跨度三档 + 边界
console.log('\n[1] 跨度三档与边界（A2）');
{
  const 上 = '2026-11-10 08:00';
  check('4 小时 → 短档', 剧情跨度(上, '2026-11-10 12:00')?.档, '短');
  check('24 小时 → 中档', 剧情跨度(上, '2026-11-11 08:00')?.档, '中');
  check('72 小时 → 长档', 剧情跨度(上, '2026-11-13 08:00')?.档, '长');
  check('6 小时整 → 短档（边界含）', 剧情跨度(上, '2026-11-10 14:00')?.档, '短');
  check('48 小时整 → 中档（边界含）', 剧情跨度(上, '2026-11-12 08:00')?.档, '中');
  check('48 小时 + 1 分 → 长档', 剧情跨度(上, '2026-11-12 08:01')?.档, '长');
}

