// ---------------------------------------------------------------- [10] 注入一致性三档（V1）
console.log('\n[10] 注入一致性三档（V1：长字段前缀 / 生活状态相对化 / 批1 不偷加列）');
{
  const 卡 = 造卡();
  const 注入 = buildInjectionPrompt([['乔尔', 卡]], { 剧情时间: '2026-11-10 20:00', 生理监测: true });
  const 表头行 = 注入.split('\n').find(l => l.startsWith('名字')) ?? '';
  const 数据行 = 注入.split('\n').find(l => l.startsWith('乔尔')) ?? '';
  const 列们 = 表头行.split(' | ');
  const 值们 = 数据行.split(' | ');
  const 取列 = (名: string) => { const i = 列们.indexOf(名); return i < 0 ? null : 值们[i]; };

  const 长值 = 取列('当前在做') ?? '';
  ok('长字段「当前在做」是卡值前缀', 卡.当前在做.startsWith(长值), 长值);

  const 生活 = 取列('生活状态') ?? '';
  ok('生活状态列走相对化（含"约 …前"）', 生活.includes('前'), 生活);
  ok('生活状态列 ≠ 卡原值（证明走了相对化）', 生活 !== 卡.生活状态);

  ok('空列不出现（动态列）', !列们.includes('怀孕') && !列们.includes('好感'));
  ok('批1 不改注入表列结构（心事尚未进注入）', !列们.includes('心事'));
}

