// ---------------------------------------------------------------- [4] 文案必须带"约"与"按正文时刻估算"
console.log('\n[4] 文案硬要求（V11：不许写精确值）');
{
  const 上 = '2026-11-10 08:00';
  for (const [名, 时刻] of [['短', '2026-11-10 12:00'], ['中', '2026-11-11 08:00'], ['长', '2026-11-13 08:00']] as const) {
    const r = 剧情跨度(上, 时刻);
    ok(`${名}档带"约 "`, !!r?.文本.includes('约 '));
    ok(`${名}档带"按正文时刻估算"`, !!r?.文本.includes('按正文时刻估算'));
    ok(`${名}档不含"恰好"`, !r?.文本.includes('恰好'));
  }
}

// ---------------------------------------------------------------- [5] 三段注入样例
console.log('\n[5] 三段注入样例：正常档 / 长档 / 空值跳过');
{
  const 中 = 剧情跨度('2026-11-10 08:00', '2026-11-11 08:00');
  const 中行 = 取跨度行(造注入(中!.文本, '2026-11-11 08:00', { 乔尔: 造卡() }));
  ok('中档：出现「距上次更新已过」', 中行.includes('距上次更新已过'));
  ok('中档：带"约"与"按正文时刻估算"', 中行.includes('约 ') && 中行.includes('按正文时刻估算'));
  ok('中档：出现档位说明', 中行.includes('超过 6 小时、两天以内'));

  const 长 = 剧情跨度('2026-11-10 08:00', '2026-11-13 08:00');
  const 长文本 = 造注入(长!.文本, '2026-11-13 08:00', { 乔尔: 造卡() });
  const 长行 = 取跨度行(长文本);
  ok('长档：含"超过两天"', 长行.includes('超过两天'));
  ok('长档：Step5 明说落三字段', 长文本.includes('「当前在做 / 当前状态 / 位置」'));
  ok('长档：严禁塞近期关键事件', 长文本.includes('严禁**把补出来的经历塞进「近期关键事件」'));
  ok('长档：未完成事项只装离散承诺', 长文本.includes('离散、能兑现的承诺'));
  ok('长档：转折落当前目标', 长文本.includes('转折落「当前目标」'));

  const 跳文本 = 造注入('跳过（无时间）', '', { 乔尔: 造卡() });
  const 跳行 = 取跨度行(跳文本);
  ok('空值：走「跳过（无时间）」', 跳行.includes('跳过（无时间）'));
  ok('空值：不是 0（不出现"约 0"）', !跳行.includes('约 0'));
  ok('空值：这一行没被省略', 跳行 !== '(没找到)');
  ok('空值：Step5 明说跳过的处置', 跳文本.includes('若用户消息里标注「跳过（无时间）」'));
}

