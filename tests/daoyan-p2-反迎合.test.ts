(globalThis as any)._ = {
  clamp: (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), hi),
  cloneDeep: (v: any) => (v === undefined ? undefined : JSON.parse(JSON.stringify(v))),
};

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}
const 账本 = (部分: Partial<导演账本> = {}): 导演账本 => ({ ...emptyData(), 已分析轮数: 10, ...部分 });
const 已执行 = { 已执行: true, 顶回冲突: '', 说明: '', 主角死亡: false };
const 未执行 = { 已执行: false, 顶回冲突: '', 说明: '', 主角死亡: false, 核验来源: '明确' as const };
const 构造 = (下一幕: any, 部分: Record<string, any> = {}) =>
  构造本幕指令({ 旧指令: null, 下一幕, 账本: 账本(), 核验: 已执行, 档位: 3, 红线: [], 楼层: 30, 暂停注入: false, ...部分 });

console.log('\n[2.4] 必演与参考分层');
{
  check('字符串也能当必演', 规范化必演('她已经走了')?.内容, '她已经走了');
  check('空内容 → null', 规范化必演({ 内容: '  ' }), null);
  const r = 构造({ 节拍: '受挫', 硬性要求: '下雨', 必演: { 内容: '林晚已经离开小镇', 命运: true, 角色ID: '林晚' } });
  check('必演进指令', r.指令?.必演?.内容, '林晚已经离开小镇');
  const 文本 = build本幕指令({ ...账本(), 当前指令: r.指令 }, SettingsSchema.parse({}));
  ok('渲染成【本幕已确定】', 文本.includes('【本幕已确定】这一幕确定发生：林晚已经离开小镇'));
  ok('仍以【本幕参考】开头', 文本.startsWith('【本幕参考】'));
  const 镜头外 = 构造({ 节拍: '受挫', 必演: { 内容: '老周病逝', 命运: true, 角色ID: '老周', 镜头外: true } });
  const 镜头外文本 = build本幕指令({ ...账本(), 当前指令: 镜头外.指令 }, SettingsSchema.parse({}));
  ok('2.5 镜头外 → 正文只演得知', 镜头外文本.includes('镜头外完成') && 镜头外文本.includes('得知'));
  check('没给必演 → 无', 构造({ 节拍: '阴影' }).指令?.必演 ?? null, null);
  ok('提示词写明"写成已成立的事实"', SYSTEM_PROMPT.includes('写成已经成立的事实'));
  ok('提示词写明可以安排在镜头外', SYSTEM_PROMPT.includes('镜头外'));
}

