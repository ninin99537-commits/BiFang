console.log('\n[2.6] 命运必演没演出来: 沿用 → 第 2 轮既成事实 → 封顶不交回玩家');
{
  const 第一轮 = 构造({ 节拍: '受挫', 必演: { 内容: '林晚离开小镇', 命运: true, 角色ID: '林晚' } });
  const 旧1 = 第一轮.指令!;
  // 导演下一轮没再写必演, 且上一幕没执行
  const 第二轮 = 构造({ 节拍: '阴影' }, { 旧指令: 旧1, 核验: 未执行 });
  check('沿用', 第二轮.指令?.必演?.内容, '林晚离开小镇');
  check('未执行轮 1', 第二轮.指令?.必演?.未执行轮, 1);
  check('还不是既成事实', 第二轮.指令?.必演?.既成事实, false);
  const 第三轮 = 构造({ 节拍: '阴影' }, { 旧指令: 第二轮.指令, 核验: 未执行 });
  check('第 2 轮没演 → 既成事实', 第三轮.指令?.必演?.既成事实, true);
  const 文本 = build本幕指令({ ...账本(), 当前指令: 第三轮.指令 }, SettingsSchema.parse({}));
  ok('渲染成"开场时已经发生"', 文本.includes('本幕开场时这件事**已经发生**'));
  // 封顶(升级 2 次后)仍未执行 —— 用第二轮的指令(命运必演还在沿用期; 第三轮之后的那一轮是"撤下", 见 daoyan-第二轮优化)
  const 封顶 = 构造({ 节拍: '阴影' }, { 旧指令: { ...第二轮.指令!, 核验升级次数: 2 }, 核验: 未执行 });
  // 2026-11-12 硬约束通道: 核验纠偏是代码裁定 → 硬约束; 反向断言看 裁定∪建议。
  const 裁定 = (r: any) => (r?.指令?.硬约束 ?? []).join('\n');
  const 正文可见 = (r: any) => `${裁定(r)}\n${r?.指令?.硬性要求 ?? ''}`;
  ok('RED: 封顶不交回玩家', !正文可见(封顶).includes('把选择交回玩家'));
  ok('封顶走命运不撤回', 裁定(封顶).includes('命运事件不撤回'));
  // 已执行 → 不沿用
  const 演了 = 构造({ 节拍: '余波' }, { 旧指令: 第三轮.指令, 核验: 已执行 });
  check('已执行 → 不再沿用', 演了.指令?.必演 ?? null, null);
  // 普通必演没执行 → 不强求
  const 普 = 构造({ 节拍: '受挫', 必演: { 内容: '下了一场雨', 命运: false } });
  check('普通必演没执行 → 不沿用', 构造({ 节拍: '阴影' }, { 旧指令: 普.指令, 核验: 未执行 }).指令?.必演 ?? null, null);
  // 普通封顶(2026-11-11 修订): 不再"把选择交回玩家"(那是给正文的放行信号), 改成单点目标
  const 普封顶 = 构造({ 节拍: '阴影' }, { 旧指令: { ...普.指令!, 核验升级次数: 2 }, 核验: 未执行 });
  ok('非命运封顶不再交回玩家', !正文可见(普封顶).includes('交回玩家'));
  ok('非命运封顶收成单点目标', 裁定(普封顶).includes('只演这一件事'));
  // 跳过本幕的旧指令不沿用
  check('跳过的指令不沿用', 构造({ 节拍: '阴影' }, { 旧指令: { ...旧1, 已跳过: true }, 核验: 未执行 }).指令?.必演 ?? null, null);
}

