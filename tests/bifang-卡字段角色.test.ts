//
// ── 这个批解决什么 ──
//
//  同一个问题"这个键该不该出现在 X 里"原来在**四处各答一遍**：
//
//  | 问题 | 原来答在哪 |
//  |---|---|
//  | 该不该进楼层快照？ | `快照.ts` 的三行 `delete cleaned['…']` |
//  | 该不该进近期轨迹 diff？ | `轨迹.ts` 的 `运行时键` Set 五个字面量 |
//  | 该不该发给更新 AI？ | `更新输入.ts` 的一行 `delete card['…']` |
//  | 该不该被当成 NPC 名字？ | `模型请求.ts` 的六个 `name === '…'` |
//
//  四处口径**互不一致**，复查查出五处矛盾。其中一处是真 bug：
//  `未完成事项变动` 的注释说"不该入库"，但快照清理表里没它 → **每层都存**。
//
// ── 判据 ──
//
//  **一条属性用例**：任何"运行期键"都不出现在快照与轨迹里。
//  这条替代原来三处手写断言（"快照里没有最后更新"/"轨迹排除人设参考"…）——
//  那种写法只覆盖了**写断言的人想到的那几个键**，新增一个运行时键没人管。
