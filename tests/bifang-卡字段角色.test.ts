  // ── 起点数据：一份"什么字段都有"的旧卡 ──
  //  ⚠ 用**真实管线**（`applyUpdate`）而不是手写卡、也不是直接调 `合并()`：
  //    手写卡只会包含"我想到的键"；直接调 `合并()` 会绕过 `应用更新` 里的后处理
