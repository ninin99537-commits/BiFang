// ─────────────────────────────────────────────────────────────
console.log('\n[自证] 加回任意一条被删的说明 → 白名单判据必须红');
{
  // ── 这条是本批要求的自证 ──
  //  加回去的那条**不属于**白名单三类（它是"这个开关是什么"的二次解释），
  //  所以"每一条都在白名单里"必须失败。
  const 加回 = 源
    + '\n<p class="bf-hint">只影响自动更新；点「立即更新」时仍然分析到最新一层。</p>'
    + '\n<p class="bf-hint">每 N 条回复更新一次；更新时读取最近 N 条 AI 回复。</p>';

  const 段落们2 = 取说明段落(加回);
  const 未命中2 = 段落们2.filter(x => !白名单.some(w => x.纯.includes(w.片段)));

  eq('[自证] 加回两条后条数 +2', 段落们2.length, 段落们.length + 2);
  eq('[自证] 其中 2 条不在白名单里（所以核心判据会红）', 未命中2.length, 2);
  ok('[自证] 未命中的正是那两条',
    未命中2.some(x => x.纯.includes('只影响自动更新')) && 未命中2.some(x => x.纯.includes('每 N 条回复')),
    未命中2.map(x => x.纯.slice(0, 30)).join(' | '));
}

