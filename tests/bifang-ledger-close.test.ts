let pass = 0;
let fail = 0;
function ok(名: string, 条件: boolean) {
  if (条件) {
    pass++;
    console.log(`  ✓ ${名}`);
  }
  else {
    fail++;
    console.log(`  ✗ ${名}`);
  }
}
function check(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
    console.log(`  ✓ ${名}`);
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}

/** 造一条期望事务: 键序与源码一致(编号/时间/内容/状态/结果), check 才能直接比 JSON */
function 事务(编号: string, 时间: string, 内容: string, 状态: string, 结果?: string) {
  return 结果 === undefined ? { 编号, 时间, 内容, 状态 } : { 编号, 时间, 内容, 状态, 结果 };
}
/** 一份全新的空诊断(期望值也按这个键序写: 重复丢弃/重复命中终态/复活拦截/相对锚) */
function 空诊断() {
  return { 重复丢弃: 0, 重复命中终态: 0, 复活拦截: [], 相对锚: [] };
}

