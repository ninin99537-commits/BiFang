// 剧情导演 · 阶段 D —— 镜头外推进(低频 / 少数关键 NPC / 复用同一次调用)
//
// 覆盖设计文档 §10 阶段 D 的完成标准:
//   NPC 在不出场时仍能按自己的目标改变计划; 这些变化有证据、位置与知识约束, 并能对主角线产生后续影响。
// 以及"不引入逐 NPC 每轮调用"的硬约束(实施提示词: 只为少数关键 NPC 做低频镜头外推进)。
import { createPinia, setActivePinia } from 'pinia';
import type { 导演账本 } from '../src/剧情导演/schema';
import { emptyData } from '../src/剧情导演/快照';
import { 挑镜头外候选, 渲染镜头外块, 校验镜头外改动, 该推进了, 镜头外间隔幕数, 单次镜头外上限, 镜头外审计行 } from '../src/剧情导演/镜头外';

(globalThis as any)._ = {
  clamp: (value: number, lower: number, upper: number) => Math.min(Math.max(value, lower), upper),
  cloneDeep: (value: any) => (value === undefined ? undefined : JSON.parse(JSON.stringify(value))),
};
(globalThis as any).localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}
function 账本(部分: Partial<导演账本> = {}): 导演账本 {
  return { ...emptyData(), ...部分 };
}
function 命运(部分: Record<string, any> = {}): any {
  return {
    角色ID: '甲',
    状态: '活跃',
    状态证据: [{ 记忆引用: 'AM0001', 楼层: 5, 公开摘要: '证据', 定位: '已核' }],
    状态历史: [],
    独立目标: ['找到失踪的兄长'],
    当前关系: [],
    永久后果: [],
    承诺与债务: [],
    已知事实引用: ['主角救过他一命'],
    未竟计划: [],
    最后变化: null,
    最后变化楼层: 0,
    ...部分,
  };
}

console.log('\n[D1] 挑人: 只挑有独立目标的关键 NPC, 且**不在场**、**没死**');
{
  const 账 = 账本({
    角色命运: [
      命运({ 角色ID: '有目标的', 独立目标: ['找到兄长'], 最后变化楼层: 0 }),
      命运({ 角色ID: '没目标的', 独立目标: [], 未竟计划: [] }),
      命运({ 角色ID: '死掉的', 状态: '死亡', 独立目标: ['复活报仇'] }),
      命运({ 角色ID: '在场的', 独立目标: ['自己的事'] }),
    ],
  });
  const 候选 = 挑镜头外候选({ 账本: 账, 当前幕: 20, 在场: ['在场的'] });
  const ids = 候选.map(项 => 项.角色ID);
  ok('有目标的不在场者入选', ids.includes('有目标的'));
  ok('没目标的不入选(推不出内容)', !ids.includes('没目标的'));
  ok('死者不入选(不得推进行动计划)', !ids.includes('死掉的'));
  ok('在场者不入选(由本幕指令处理)', !ids.includes('在场的'));
}

console.log('\n[D2] 低频节流: 同一个 NPC 至少隔若干幕才推一次(**按幕计数**, 不是楼层)');
{
  // 纠偏: 节流字段是 `最后推进幕`(幕计数)。旧实现用 `最后变化楼层`(楼层号) 与幕数相减,
  // 一个 100 楼出现过的角色会被判成"刚推进过", 于是永远轮不到镜头外推进。
  const 账 = 账本({
    角色命运: [命运({ 角色ID: '刚动过', 独立目标: ['x'], 最后推进幕: 18 })],
  });
  check('刚动过(上一幕才推) → 不推', 挑镜头外候选({ 账本: 账, 当前幕: 19 }).length, 0);
  check('隔够幕数 → 推', 挑镜头外候选({ 账本: 账, 当前幕: 18 + 镜头外间隔幕数 }).length, 1);
  check('该推进了(纯函数口径一致)', 该推进了(账.角色命运[0], 18 + 镜头外间隔幕数), true);
  check('不该推进(太近)', 该推进了(账.角色命运[0], 19), false);
  check('从没推进过(最后推进幕 0) → 立即可以推', 该推进了(命运({ 最后推进幕: 0 }), 1), true);
  // 关键对照: 楼层号很大但从未推进过 → 仍然可以推(旧实现会把它当成"刚推进过")
  const 楼层大账 = 账本({
    角色命运: [命运({ 角色ID: '老角色', 独立目标: ['找人'], 最后变化楼层: 100, 最后推进幕: 0 })],
  });
  check('楼层 100 但从未推进过 → 可以推', 挑镜头外候选({ 账本: 楼层大账, 当前幕: 6 }).length, 1);
}

console.log('\n[D3] 单次上限: 只推少数几个(不是逐 NPC 每轮调用)');
{
  const 账 = 账本({
    角色命运: Array.from({ length: 10 }, (_, i) => 命运({ 角色ID: `NPC${i}`, 独立目标: ['自己的事'], 最后变化楼层: 0 })),
  });
  const 候选 = 挑镜头外候选({ 账本: 账, 当前幕: 50 });
  check(`最多 ${单次镜头外上限} 个`, 候选.length, 单次镜头外上限);
  ok('不是全部 10 个', 候选.length < 10);
}

console.log('\n[D4] 离场者优先: 他们只能靠镜头外推进, 否则永远不动');
{
  const 账 = 账本({
    角色命运: [
      命运({ 角色ID: '活跃的', 状态: '活跃', 独立目标: ['a'], 最后变化楼层: 0 }),
      命运({ 角色ID: '离开的', 状态: '离开', 独立目标: ['b'], 最后变化楼层: 0 }),
      命运({ 角色ID: '失踪的', 状态: '失踪', 独立目标: ['c'], 最后变化楼层: 0 }),
    ],
  });
  const 候选 = 挑镜头外候选({ 账本: 账, 当前幕: 50 });
  check('离场者排在最前', [候选[0].角色ID, 候选[1].角色ID].sort(), ['失踪的', '离开的'].sort());
  ok('离场候选带位置约束', 候选[0].约束.some(c => c.includes('别处') || c.includes('回归事件')));
}

console.log('\n[D5] 约束: 位置(离场) + 知识(只知道自己知道的事) + 受伤');
{
  const 账 = 账本({
    角色命运: [
      命运({ 角色ID: '离者', 状态: '离开', 独立目标: ['找家人'], 已知事实引用: ['甲', '乙'], 最后变化楼层: 0 }),
      命运({ 角色ID: '伤者', 状态: '受伤', 独立目标: ['复仇'], 最后变化楼层: 0 }),
    ],
  });
  const 候选 = 挑镜头外候选({ 账本: 账, 当前幕: 50 });
  const 离者 = 候选.find(项 => 项.角色ID === '离者')!;
  const 伤者 = 候选.find(项 => 项.角色ID === '伤者')!;
  ok('离场者有位置约束', 离者.约束.some(c => c.includes('不能无回归事件出现在主角场景')));
  ok('离场者有知识约束', 离者.约束.some(c => c.includes('不得凭空知道主角的私下行动')));
  ok('受伤者有能力约束', 伤者.约束.some(c => c.includes('带伤行动')));
  // 渲染块: 目标与约束都原样进提示词
  const 块 = 渲染镜头外块(候选);
  ok('渲染块标题在', 块.includes('【镜头外推进'));
  ok('渲染块含目标原文', 块.includes('找家人'));
  ok('渲染块含约束原文', 块.includes('不得凭空知道主角的私下行动'));
  ok('渲染块要求说明对主角线的影响', 块.includes('怎样影响主角线'));
  ok('渲染块禁止降智/瞬移', 块.includes('降智'));
  check('空候选 → 空块(不占 token)', 渲染镜头外块([]), '');
}

console.log('\n[D6] 写回守卫: 拒绝路径可观察(死者/无证据离场者/无目标)');
{
  const 账 = 账本({
    角色命运: [
      命运({ 角色ID: '死者', 状态: '死亡', 独立目标: ['复仇'] }),
      命运({ 角色ID: '无证据离场者', 状态: '离开', 状态证据: [] }),
      命运({ 角色ID: '正常者', 状态: '活跃' }),
    ],
  });
  ok('死者被拒', (校验镜头外改动(账, '死者', ['复仇']) ?? '').includes('已死亡'));
  ok('无证据离场者被拒', (校验镜头外改动(账, '无证据离场者', ['找家人']) ?? '').includes('没有可用证据'));
  ok('不在命运册的被拒', (校验镜头外改动(账, '路人', ['x']) ?? '').includes('不在命运册'));
  ok('没有目标被拒', (校验镜头外改动(账, '正常者', []) ?? '').includes('没有任何目标'));
  check('合规改动放行', 校验镜头外改动(账, '正常者', ['自己的目标']), null);
}

console.log('\n[D7] 审计行: 让"这一轮谁在镜头外动了"可见');
{
  const 候选 = [{ 角色ID: '甲', 理由: 'r', 独立目标: ['x'], 约束: [] }, { 角色ID: '乙', 理由: 'r', 独立目标: ['y'], 约束: [] }];
  ok('有候选时报出名字', 镜头外审计行(候选).includes('甲') && 镜头外审计行(候选).includes('乙'));
  ok('无候选时说明原因', 镜头外审计行([]).includes('无候选'));
}

console.log('\n[D8] 死亡角色的"遗产/影响"仍可被记录(推进计划 ≠ 死者行动)');
{
  const 账 = 账本({ 角色命运: [命运({ 角色ID: '死者', 状态: '死亡', 独立目标: ['未竟的复仇'] })] });
  // 死者不进镜头外候选(不能行动)
  check('死者不进候选', 挑镜头外候选({ 账本: 账, 当前幕: 50 }).length, 0);
  // 但它的未竟计划仍在账本里(供导演安排"遗产/他人接手"这类后续影响)
  check('未竟计划仍留在命运册', 账.角色命运[0].独立目标, ['未竟的复仇']);
  // 且写回守卫明确拒绝把它当成"还在行动"
  ok('守卫明确拒绝推进死者', (校验镜头外改动(账, '死者', ['复仇']) ?? '').includes('只能记录其遗产'));
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0) process.exit(1);
