// 共用 · 设置会话（C8）—— 批次 2026-11-20（需求方 #500 第 3 件）。
//
// ── 这个文件证明什么 ──
//
//  设计稿 §5 的核心：
//
//  > 今天测不了"两窗口互相覆盖"：单例状态让同进程两个 case 互相污染，
//  > 也造不出"两个独立挂载点"。
//
//  会话化之后，**同进程造两个会话打一个假存储**，就能证明：
//
//  | # | 能证明的条目 | 今天为什么证明不了 |
//  |---|---|---|
//  | 1 | **基线隔离**：两会话各有基线 | 单例共享 |
//  | 2 | **深合并而非整键替换**：`接口` 子对象里一方改模型、另一方改地址，两个改动并存 | 整键覆盖会丢一个 |
//  | 3 | **删除不复活**：一方删预设、另一方改别的字段，删掉的不会被深合并加回来 | 单例下无法并发 |
//  | 4 | **读失败关闸门**：读失败后 `写()` 存储一个字节没变 | **彼方今天缺这条** |
//  | 5 | **销毁后无效**：`销毁()` 后 `写()` 是 no-op | 单例没有销毁概念 |
import { 建设置会话 } from '../src/共用/设置写回';

let pass = 0;
let fail = 0;
function ok(名: string, 条件: boolean, 附注?: string) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}${附注 ? `  (${附注})` : ''}`);
  }
}
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}

/**
 * 假存储 —— 模拟"全局变量里的一份设置"。
 *
 * `读写次数` 用来验证"500ms 窗口内不重复摸存储"。
 */
function 造假存储(初始: any = undefined, 选项: { 读会抛错?: boolean } = {}) {
  let 份 = 初始 === undefined ? undefined : JSON.parse(JSON.stringify(初始));
  let 会抛错 = !!选项.读会抛错;
  const 计数 = { 读: 0, 写: 0 };

  return {
    端口: {
      读: () => {
        计数.读++;
        if (会抛错)
          throw new Error('模拟：存储读不出来');
        return 份 === undefined ? undefined : JSON.parse(JSON.stringify(份));
      },
      写: (新份: any) => {
        计数.写++;
        份 = JSON.parse(JSON.stringify(新份));
      },
    },
    取: () => (份 === undefined ? undefined : JSON.parse(JSON.stringify(份))),
    计数,
    /** 手动改存储（模拟"另一个设备写了"） */
    塞: (新份: any) => {
      份 = JSON.parse(JSON.stringify(新份));
    },
    /** 切换"读会抛错"（模拟存储中途坏掉） */
    设为抛错: (值: boolean) => {
      会抛错 = 值;
    },
  };
}

/** 一份"5 套预设"的初始设置（与设计稿的场景一致） */
function 初始设置() {
  return {
    接口: { 地址: 'https://api.example.com', 模型: 'm1', 密钥: 'sk-xxx' },
    接口预设: {
      甲: { 地址: 'a', 模型: 'ma' },
      乙: { 地址: 'b', 模型: 'mb' },
      丙: { 地址: 'c', 模型: 'mc' },
      丁: { 地址: 'd', 模型: 'md' },
      戊: { 地址: 'e', 模型: 'me' },
    },
    更新: { 世界书写入: '角色卡主世界书', 生理监测: true },
    提示词: { 自定义段: [] },
  };
}

