console.log('\n[★ 核心] 两个会话打一个存储：两边改动并存、互不覆盖');
{
  // ── 这条是 C8 的全部价值 ──
  //  今天单例状态下，两个挂载点共享同一组状态，这个场景**根本构造不出来**。
  const 存储 = 造假存储(初始设置());

  const s1 = 建设置会话(存储.端口, 初始设置());
  const s2 = 建设置会话(存储.端口, 初始设置());

  const a = s1.读();
  const b = s2.读();

  eq('[前置] 两个会话都读到 5 套预设', Object.keys(a.接口预设).length, 5);
  eq('[前置] 两个会话读到的是同一份内容', a, b);

  // s1 只改模型
  const s1新 = JSON.parse(JSON.stringify(a));
  s1新.接口.模型 = 'm2';
  const 写了1 = s1.写(s1新);

  // s2 只改世界书写入（它手里还是读到的旧值，模型仍是 m1）
  const s2新 = JSON.parse(JSON.stringify(b));
  s2新.更新.世界书写入 = '聊天世界书';
  const 写了2 = s2.写(s2新);

  ok('[前置] s1 确实写了', 写了1);
  ok('[前置] s2 确实写了', 写了2);

  const 最终 = 存储.取();
  eq('★ s1 的改动在（模型 = m2）', 最终.接口.模型, 'm2');
  eq('★ s2 的改动也在（世界书写入 = 聊天世界书）', 最终.更新.世界书写入, '聊天世界书');
  eq('★ 预设仍是 5 套（没被谁清掉）', Object.keys(最终.接口预设).length, 5);
  eq('★ s1 没覆盖 s2 的地址', 最终.接口.地址, 'https://api.example.com');
  eq('★ 密钥没丢', 最终.接口.密钥, 'sk-xxx');
}

