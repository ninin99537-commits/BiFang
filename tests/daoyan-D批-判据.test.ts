console.log('\n[D-2] 提醒侧「收束已用」与引擎侧相等（同一轮同一个数）');
{
  const 收束起始场 = 34;
  const 当前场 = 41; // 41 - 34 + 1 = 8 = 预算
  const 账本 = 账({ 已分析轮数: 当前场 - 1, 章回: 章回({ 进度: '收束', 起始场: 1, 收束起始场, 当前幕号: 1 }) });

  const 提醒侧 = 收束已用场数(账本, 当前场);
  // 引擎侧：构造本幕指令会打印「已进入「收束」N 场(预算 8)」是提醒口径；这里直接比同一个函数在两个场号下的值
  const 引擎口径 = 收束已用场数(账本, 当前场);
  check('提醒侧 = 8', 提醒侧, 8);
  check('两侧相等', 引擎口径, 提醒侧);
  // `判收章` 也要吃同一个场号（D-2 的一半）：演了几场必须按传入场号算
  check('判收章(账本, 41) 演了几场 = 41', 判收章(账本, 当前场).演了几场, 41);
  check('判收章(账本) 退回旧口径 = 40', 判收章(账本).演了几场, 40);
  // 而且收束预算那句真的会响
  const 提醒 = 结构提醒(账本, 当前场);
  ok(`收束预算那句出现（已进入「收束」${提醒侧} 场 / 预算 ${收束预算场}）`, 提醒.some(x => x.includes(`已进入「收束」${提醒侧} 场`) && x.includes(`预算 ${收束预算场}`)));
}

console.log('\n[D-3] 40 场那条提醒在 5 幕幕纲下可达（阈值 = max(幕纲数×3, 章长度阈值)）');
{
  const 五幕 = Array.from({ length: 5 }, (_, i) => `第${i + 1}幕｜类型: 事件｜目标:t`);
  /**
   * 可达窗口说明（这条要报给需求方裁）：
   * 阈值改成 max(幕纲数×3, 40) 之后，`超期` 要等 41 场才成立 —— 而 `超期` 一成立，
   * `选收章发言者` 就是 `幕纲落后`（它更具体：第几幕/推不动了），`章长度` 按 P0.8 的互斥**让位**。
   * 所以「已经演了 N 场还没进入收束」这句能出现的窗口，正好是 **第 40 场**（长=40 达标、超期尚未成立）。
   * 改之前这个窗口根本不存在（16 场就超期），所以 D-3 的病确实治好了；但"第 41 场也说"做不到，
   * 除非把互斥优先级反过来（那是产品判断，不是判据对齐）。
   */
  const 四十 = 结构提醒(账({ 已分析轮数: 39, 章回: 章回({ 幕纲: 五幕, 当前幕号: 5, 起始场: 1 }) }), 40);
  ok('第 40 场 → 出现「已经演了 40 场还没进入收束」（改前这句永不出现）', 四十.some(x => x.includes('已经演了 40 场还没进入收束')));

  const 四十一 = 结构提醒(账({ 已分析轮数: 40, 章回: 章回({ 幕纲: 五幕, 当前幕号: 5, 起始场: 1 }) }), 41);
  ok('第 41 场 → 由「幕纲落后」说（更具体），章长度让位', 四十一.some(x => x.includes('幕纲明显落后') || x.includes('幕号已经推不动了')));
  ok('第 41 场 → 章长度那句不重复说（互斥仍成立）', !四十一.some(x => x.includes('已经演了 41 场还没进入收束')));
  // 第 39 场：还没到 40 → 不说话
  const 三十九 = 结构提醒(账({ 已分析轮数: 38, 章回: 章回({ 幕纲: 五幕, 当前幕号: 5, 起始场: 1 }) }), 39);
  ok('第 39 场 → 还不到阈值，不说这句', !三十九.some(x => x.includes('还没进入收束')));
  // 反例：不许把 章长度阈值 调小
  const 源 = readFileSync('src/剧情导演/提醒.ts', 'utf8');
  ok('章长度阈值 仍是 40（没为了让那句出现而调小）', /export const 章长度阈值 = 40;/.test(源));
}

console.log('\n[D-4] 「连着几幕高张力」提醒与引擎同口径（集合 + 阈值都统一）');
{
  const 造 = (最近节拍: string[]) => 账({ 张力: { 当前: 0, 距上次高潮楼层: 0, 连续低张力: 0, 最近节拍 } } as any);
  const 停在高点 = (账本: 导演账本) => 结构提醒(账本, 41).some(x => x.includes('停在高点'));

  check('受挫×3 → 提醒出声（以前集合里没有受挫，一声不响）', 停在高点(造(['受挫', '受挫', '受挫'])), true);
  check('高潮×2 → 提醒不出声（以前阈值是 2，会喊）', 停在高点(造(['小胜', '高潮', '高潮'])), false);
  check('高潮×3 → 提醒出声', 停在高点(造(['小胜', '高潮', '高潮', '高潮'])), true);
  check('受挫×2 → 不出声（阈值 3）', 停在高点(造(['小胜', '受挫', '受挫'])), false);
  // 同口径的硬证据：引擎在 受挫×3 时也会强制余波
  const 引擎 = 构造本幕指令({
    旧指令: null, 下一幕: { 节拍: '小胜' },
    账本: 账({ 张力: { 当前: 9, 距上次高潮楼层: 0, 连续低张力: 0, 最近节拍: ['受挫', '受挫', '受挫'] } } as any),
    核验: 核验 as any, 档位: 3, 红线: [], 楼层: 41, 暂停注入: false, 结构规则优先: true,
  });
  check('引擎在 受挫×3 时强制余波（两侧同口径）', 引擎.指令?.节拍, '余波');
}

console.log('\n[D-5] 「最迟章到了」只催办、不当轮引爆；逾期才引爆');
{
  const 造账 = (章号: number) =>
    账({ 已分析轮数: 9, 章回: 章回({ 章号, 进度: '推进' }),
      伏笔: [伏笔({ 编号: 5, 内容: '玉佩', 目标窗口: { 最早章: 2, 最迟章: 3 } })] });

  const 到点 = 造账(3);
  check('最迟章 = 当前章 → 最迟已到 = false（只催办）', 评估窗口(到点.伏笔[0], 3).最迟已到 ?? false, false);
  const 构造到点 = 构造本幕指令({ 旧指令: null, 下一幕: { 节拍: '小胜' }, 账本: 到点, 核验: 核验 as any, 档位: 3, 红线: [], 楼层: 9, 暂停注入: false });
  check('到点 → 节拍不动（仍是导演给的「小胜」）', 构造到点.指令?.节拍, '小胜');
  ok('到点 → 仍然催办', 构造到点.催办更新.includes(5));

  const 逾期 = 造账(4);
  const 构造逾期 = 构造本幕指令({ 旧指令: null, 下一幕: { 节拍: '小胜' }, 账本: 逾期, 核验: 核验 as any, 档位: 3, 红线: [], 楼层: 9, 暂停注入: false });
  check('逾期(章 4 > 最迟 3) → 改成兑现伏笔', 构造逾期.指令?.节拍, '兑现伏笔');

  // 反例：不许把「取到期伏笔」的催办也弄哑
  const 应用 = 应用引擎输出(到点, { 上一幕核验: 核验, 下一幕: { 节拍: '小胜' } } as any, 9, {});
  ok('到点那一轮没有被拒绝/拦下（照常出账本）', !!应用.账本);
}

