let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

const 核验 = { 已执行: true, 顶回冲突: '', 说明: '', 主角死亡: false };
const 伏笔 = (部分: Record<string, any>): any => ({
  编号: 1, 内容: 'x', 埋设层: 1, 埋设章: 1, 状态: '发酵', 回收窗口: '', 关联冲突: '',
  公开线头: '', 埋设证据: [], 中间回响: [], 兑现证据: [], 知情角色: [], 关联角色: [],
  目标窗口: null, 兑现条件: [], 候选兑现: [], 误导说明: [], 误导证据: [], 跨度: '中', ...部分,
});
const 章回 = (部分: Record<string, any>): any => ({
  章号: 1, 主题: 'x', 计划高潮: '', 进度: '推进', 起始场: 1, 当前幕号: 1,
  幕纲: ['第1幕｜类型: 事件｜目标:a'], ...部分,
});
const 账 = (部分: Partial<导演账本> = {}): 导演账本 => ({ ...emptyData(), 已分析轮数: 40, ...部分 } as 导演账本);

