// ---------------------------------------------------------------- [A6] 硬上限
console.log('\n[A6] 硬上限：K层 ≤ 6 / NPC ≤ 6 / 每 NPC 字段 ≤ 3 / 字符 ≤ 1200');
{
  check('K层上限 = 6', 轨迹上限.K层, 6);
  check('NPC 上限 = 6', 轨迹上限.NPC, 6);
  check('每 NPC 字段上限 = 3', 轨迹上限.每NPC字段, 3);
  check('字符上限 = 1200', 轨迹上限.字符, 1200);

  // 造 10 份快照（超过 K=6）：只有最近 6 份参与
  const 多 = Array.from({ length: 10 }, (_, i) => 快照((i + 1) * 10, { 甲: 卡({ 位置: `地点${i}` }) }));
  const r = 生成近期轨迹(多);
  check('10 份快照 → 只取最近 6 份', r.用了快照数, 6);

  // 造 12 个 NPC：只写 6 个
  const 很多人: Record<string, Record<string, any>> = {};
  for (let i = 0; i < 12; i++)
    很多人[`NPC${i}`] = 卡({ 位置: `甲地${i}` });
  const 很多人的后: Record<string, Record<string, any>> = {};
  for (let i = 0; i < 12; i++)
    很多人的后[`NPC${i}`] = 卡({ 位置: `乙地${i}` });
  const r2 = 生成近期轨迹([快照(10, 很多人), 快照(20, 很多人的后)]);
  const 行数 = r2.文本.split('\n').length - 1; // 减去表头
  ok('12 个 NPC → 最多写 6 行', 行数 <= 6, `${行数} 行`);

  // 一个 NPC 变 6 个字段：只写 3 个
  const 全变前 = { 甲: 卡({ 当前在做: 'A1', 当前状态: 'B1', 位置: 'C1', 心事: 'D1', 身份锚点: 'E1', 接下来想做: 'F1' }) };
  const 全变后 = { 甲: 卡({ 当前在做: 'A2', 当前状态: 'B2', 位置: 'C2', 心事: 'D2', 身份锚点: 'E2', 接下来想做: 'F2' }) };
  const r3 = 生成近期轨迹([快照(10, 全变前), 快照(20, 全变后)]);
  ok('一个 NPC 变 6 个字段 → 最多写 3 个', r3.写出条数 <= 3, `${r3.写出条数} 条`);

  // 字段顺序按 CARD_FIELDS（当前在做 在 位置 之前；**用 indexOf 前先确认两者都在**，
  // 否则 -1 < -1 或 -1 < x 会让断言假绿/假红 —— 这是我上一版踩的坑）
  const 有在做 = r3.文本.includes('当前在做');
  const 有位置 = r3.文本.includes('位置');
  ok('前 3 个字段里同时含 当前在做 与 位置（核心三字段优先，位置不被挤掉）', 有在做 && 有位置, r3.文本);
  ok('输出按 CARD_FIELDS 序（当前在做 在 位置 之前）',
    有在做 && 有位置 && r3.文本.indexOf('当前在做') < r3.文本.indexOf('位置'), r3.文本);
}

// ---------------------------------------------------------------- [B1] 注入量不随楼层增长
