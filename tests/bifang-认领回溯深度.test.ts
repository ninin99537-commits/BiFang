// 彼方 · 认领兜底不能只回溯 500 层 —— 批次 2026-11-19 波2（复查「发现12」P2）。
//
// ── 这个 bug 是什么 ──
//  认领兜底写的是 `for (id = 最后; id > 最后 - 500; id--)`。
//  如果最近那份快照正好在 **500 层之外**（长期聊天 + 最近几百层没触发更新），
//  这个循环扫不到它 → 候选仍是 null → **返回空状态**。
//
//  后果：用户的 NPC 名单/NPC 卡全部消失，**而数据其实还在**（就在那一层的变量里）。
//  下一次更新会以空状态为基底 → 等于把历史全丢了。
//
// ── 为什么这条判据必须真跑 ──
//  "上限从 500 改成 5000"读代码能看出来。但**它真的能扫到吗**只有跑起来才知道 ——
//  而这里有个陷阱：假宿主如果对任何楼层都返回快照，那"扫得到"是假绿。
//  所以探针必须让**只有那一层**有快照，其余楼层都返回空。
import { createPinia, setActivePinia } from 'pinia';
import { loadData, STORAGE_KEY } from '../src/彼方_NPC幕后生命状态系统/快照';

setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function ok(名: string, 条件: boolean, 附注?: string) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}${附注 ? `  (${附注})` : ''}`);
  }
}
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}

/** 静默跑，并收集 warn */
function 静默收警告<T>(fn: () => T): { 结果: T; 警告: string[] } {
  const 原I = console.info;
  const 原W = console.warn;
  const 原E = console.error;
  const 原T = console.table;
  const 警告: string[] = [];
  console.info = () => {};
  console.warn = (...a: any[]) => 警告.push(a.join(' '));
  console.error = () => {};
  console.table = () => {};
  try {
    return { 结果: fn(), 警告 };
  }
  finally {
    console.info = 原I;
    console.warn = 原W;
    console.error = 原E;
    console.table = 原T;
  }
}

/**
 * 造一个「快照在很深楼层」的聊天。
 *
 * ⚠ **只有 `快照楼层` 那一层有快照**，其余楼层返回空 ——
 *   否则"扫得到"是假绿（假宿主对任何层都返回快照，测不出回溯深度）。
 */
function 造深楼层聊天(最后楼层: number, 快照楼层: number, 索引: number[] = []) {
  setActivePinia(createPinia());
  const 存: any = { global: {}, chat: {}, message: {}, script: undefined };
  存.chat['彼方'] = { 版本: 3, 快照楼层: 索引, 清空层: 0 };
  if (快照楼层 >= 0 && 快照楼层 <= 最后楼层) {
    存.message[快照楼层] = {
      [STORAGE_KEY]: {
        版本: 3,
        楼层: 快照楼层,
        原编号: 快照楼层,
        NPC: { 泰丝: { 当前在做: '整理货单' } },
        名单: ['泰丝'],
        剧情时间: '2026-01-02 12:30',
      },
    };
  }
  let 读次数 = 0;
  const host: any = {
    vars: {
      get: (arg: any) => {
        读次数++;
        return arg?.type === 'chat' ? 存.chat : (arg?.type === 'message' ? 存.message[arg.message_id] : 存.global);
      },
      update: (fn: any, arg: any) => {
        const 新 = fn(arg?.type === 'chat' ? 存.chat : 存.global);
        if (arg?.type === 'chat')
          存.chat = 新;
        else
          存.global = 新;
      },
      del: () => {},
      insertOrAssign: () => {},
      scriptId: () => 't',
    },
    chat: {
      lastMessageId: () => 最后楼层,
      messages: (id: number) => (id === 快照楼层
        ? [{ message_id: id, role: 'assistant', is_hidden: false, message: 'x' }]
        : []),
    },
  };
  return { host, 存, 取读次数: () => 读次数 };
}

// ─────────────────────────────────────────────────────────────
console.log('\n[深楼层] 快照在 800 层外，必须仍能找到');
{
  // ── 旧版上限 500 → #200 < 1000-500=500 → 扫不到 → 返回空状态 ──
  const { host, 取读次数 } = 造深楼层聊天(1000, 200);
  const { 结果: data } = 静默收警告(() => loadData(host, true));

  eq('800 层外的快照被找到了', Object.keys(data?.NPC ?? {}), ['泰丝']);
  // **自证**：不是返回空状态（否则"找到了"这条可能是空的）
  ok('[自证] NPC 名单不是空的', (data?.名单 ?? []).length > 0);
  // 读次数应该 > 500（证明它真的扫过了旧上限之外）
  ok('[自证] 读了超过 500 层（越过旧上限）', 取读次数() > 500, `${取读次数()} 次`);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[深楼层] 自证：旧上限 500 时，同一场景找不到');
{
  // 用纯逻辑复刻旧版循环，证明那个 bug 是真的
  const 旧版能扫到 = (最后: number, 快照层: number, 上限: number) =>
    快照层 > 最后 - 上限 && 快照层 <= 最后;

  eq('[自证] 旧版(500)扫不到 #200（1000-500=500）', 旧版能扫到(1000, 200, 500), false);
  eq('[自证] 新版(5000)能扫到', 旧版能扫到(1000, 200, 5000), true);
  ok('[自证] 两者确实不同', 旧版能扫到(1000, 200, 500) !== 旧版能扫到(1000, 200, 5000));
}

// ─────────────────────────────────────────────────────────────
console.log('\n[深楼层] 真的没有快照时，必须有明确 warn（不许静默）');
{
  // ── 这条防的是什么 ──
  //  "扫不到"和"没存过"在结果上一样（都返回空状态），
  //  但**用户需要知道是哪一种** —— 否则他看到"状态空了"完全不知道该怎么办。
  const { host } = 造深楼层聊天(1000, -1); // 没有任何快照
  const { 结果: data, 警告 } = 静默收警告(() => loadData(host, true));

  const 认领警告 = 警告.filter(w => /没有找到任何可认领的快照/.test(w));
  eq('扫不到时有明确 warn', 认领警告.length, 1);
  ok('warn 里说了扫了几层', /扫了 \d+ 层/.test(认领警告[0] ?? ''), 认领警告[0]?.slice(0, 80));
  ok('warn 里给了用户下一步（手动保存重建）', /手动保存/.test(认领警告[0] ?? ''));
  eq('返回空状态（这是对的）', Object.keys(data?.NPC ?? {}).length, 0);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[深楼层] 上限有界：一万层聊天也不许扫穿');
{
  // ── 这条防的是"为了修 bug 把性能搞坏" ──
  //  如果无脑改成"扫穿整条聊天"，一万层就是一万次 `vars.get`。
  //  正确做法：给一个大但**有界**的上限，并在扫不到时明确告警。
  //
  //  ⚠ **索引帮不上忙**（我第一版想用它缩小范围，错了）：
  //    删楼后快照会往下移动任意距离（`/cut` 删多少移多少），
  //    索引记的旧编号**不能用来推断它现在在哪**。
  //    实测：索引 [190]、最后 99、快照实际在 90 时，按索引算下界=99，只扫一层就停了。
  const { host, 取读次数 } = 造深楼层聊天(10000, 9900);
  const { 结果: data } = 静默收警告(() => loadData(host, true));
  const 读了 = 取读次数();

  eq('找到快照（9900 在 2000 层内）', Object.keys(data?.NPC ?? {}), ['泰丝']);
  ok('[自证] 有界：读了不到 2100 次（不是一万次）', 读了 < 2100, `${读了} 次`);
  ok('[自证] 但确实扫了超过 100 层（不是只扫一层）', 读了 > 100, `${读了} 次`);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[深楼层] 索引的旧编号不能用来缩小扫描范围');
{
  // ── 这条是给"想优化"的人看的 ──
  //  我第一版实现过：索引里有记录就从索引最大楼层往下扫。
  //  **那是错的** —— 实测：索引 [190]、最后 99、快照实际在 90 时，
  //  按索引算下界 = 99，**只扫一层就停了**，把原来能扫到的 90 也丢了。
  //
  //  这条判据用 `bifang-snapshot-adopt.test.ts` 的 [2] 段守着（索引重建为当前这一楼）。
  //  这里只钉一个纯逻辑事实：删楼后快照的位置与索引记的编号**无关**。
  const 删楼后快照位置 = (原楼层: number, 删掉几层: number) => 原楼层 - 删掉几层;
  eq('[自证] 删 100 层后，原 #190 的快照现在在 #90', 删楼后快照位置(190, 100), 90);
  ok('[自证] 索引记的 #190 与它现在的位置 #90 无关',
     删楼后快照位置(190, 100) !== 190);
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
process.exit(fail > 0 ? 1 : 0);
