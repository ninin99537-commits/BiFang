// 剧情导演 · 核验口径(2026-11-11)
//
// 起因: 用户实测"一直未落实"(四道指令连判未执行 → 升级 → 封顶 → 指令越写越软)。
// 查下来注入没坏(酒馆页面里 extension_prompts 挂着整道指令), 真正的原因是**两套严格度打架**:
//   - 注入把节拍渲染成「1. 本幕节拍**参考**: 受挫」, 落在"第 1~4 项是演法建议, 不必逐字照做"的伞下;
//   - 核验(导演提示词 Step 1)却拿它判生死 —— "要求受挫, 实际又赢了 = 未执行"。
// 于是正文按用户 2026-10-29 要来的软化办(那条软化是为了让玩家能跨日, 理由成立), 导演每次都判没演,
// 一路升级到封顶, 指令最后自己写着"可以把选择交回玩家" —— 越判越软, 越软越不演。
//
// 这份用例钉住四件事(按层分):
//   ① 注入层: 节拍是**这一幕的结构要求**, 不在"不必逐字照做"的豁免里; 演法(第 2~4 项)继续软;
//   ② 升级/封顶: 话术必须是正文**能执行**的(单点目标), 不再有"换个实现路径"(它没有上一道指令的记忆)、
//      也不再"把决定权交回玩家"(那是放行信号);
//   ③ 导演层: 核验只按「必演 + 节拍」判; 确定要发生的事**必须写进必演**, 只写硬性要求等于没写;
//   ④ 取料层: 上一道指令没有必演时, 结构提醒要把这件事摆回导演面前。
import type { 导演账本 } from '../src/剧情导演/schema';
import { emptyData } from '../src/剧情导演/快照';
import { 构造本幕指令, 节拍结构 } from '../src/剧情导演/引擎规则';
import { build本幕指令, SYSTEM_PROMPT } from '../src/剧情导演/prompts';
import { 结构提醒 } from '../src/剧情导演/取料';
import { SettingsSchema } from '../src/剧情导演/schema';
import { createPinia, setActivePinia } from 'pinia';

(globalThis as any)._ = {
  clamp: (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), hi),
  cloneDeep: (v: any) => (v === undefined ? undefined : JSON.parse(JSON.stringify(v))),
};
(globalThis as any).localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

const 设置 = SettingsSchema.parse({});
// 2026-11-12 硬约束通道: 核验纠偏是**代码裁定**, 现在住 `硬约束`; `硬性要求` 只放导演散文。
// 正向断言看 裁定; 反向断言(某句不该出现在正文)看 裁定∪建议 —— 漏到哪一边都是漏。
const 裁定 = (r: any) => (r?.指令?.硬约束 ?? []).join('\n');
const 正文可见 = (r: any) => `${裁定(r)}\n${r?.指令?.硬性要求 ?? ''}`;
const 账本 = (部分: Partial<导演账本> = {}): 导演账本 => ({ ...emptyData(), 已分析轮数: 10, ...部分 });
const 已执行 = { 已执行: true, 顶回冲突: '', 说明: '', 主角死亡: false, 核验来源: '明确' as const };
const 未执行 = { ...已执行, 已执行: false };
const 指令 = (部分: Record<string, any> = {}): any => ({
  编号: 3,
  节拍: '受挫',
  硬性要求: '去码头对账',
  伏笔现场: '',
  禁止事项: '',
  生成楼层: 5,
  核验升级次数: 0,
  已跳过: false,
  代码调整: [],
  档位: 3,
  红线: [],
  ...部分,
});
const 构造 = (下一幕: any, 部分: Record<string, any> = {}) =>
  构造本幕指令({ 旧指令: null, 下一幕, 账本: 账本(), 核验: 已执行, 档位: 3, 红线: [], 楼层: 30, 暂停注入: false, ...部分 });

// ---------------------------------------------------------------------------
// ① 注入层: 节拍是结构要求, 不在"不必照做"的豁免里
// ---------------------------------------------------------------------------
console.log('\n[1] 注入: 节拍从"演法建议"里摘出来(核验按它判, 就不能按建议发)');
{
  // 2026-11-12: fixture 补两个字段, 让三条新契约都能被验到 ——
  // ① 禁止事项(否则第 4 项按设计不渲染) ② 硬约束(否则【本幕硬约束】块不出现)
  const 文本 = build本幕指令(
    账本({
      当前指令: 指令({
        禁止事项: '不要写雨的拟人化',
        硬约束: ['【连败让步】冲突「北坡」本轮必须让玩家赢（玩家体验优先）。'],
      }),
    }),
    设置,
  );
  ok('节拍写成"结构要求"', 文本.includes('1. 这一幕的结构要求：受挫'));
  ok('带结构语义(受挫 = 损失真实)', 文本.includes(节拍结构.受挫));
  // 2026-11-12 伞收窄: 第 4 项（导演的禁令）摘出伞外 —— 它没有"写法"可换，留在伞里等于说"这条禁令可以不做"。
  ok('"不必逐字照做"只修饰第 2~3 项', 文本.includes('第 2~3 项是导演给的演法建议'));
  ok('不再有"第 1~4 项…不必逐字照做"(旧口径)', !文本.includes('第 1~4 项'));
  // 2026-11-12: 第 4 项改成「4. 导演不建议写」(明确是导演的意见, 不是平台偏好), 且空则不渲染。
  // 2026-11-12: 第 4 项从「不建议写」(读起来像平台偏好) 改成「导演的禁令」，并摘出"建议"伞。
  ok('剧情参考/伏笔现场/导演的禁令仍在渲染里', /2\. 剧情参考/.test(文本) && /3\. 伏笔现场/.test(文本) && /4\. 导演的禁令/.test(文本));
  // 代码裁定不进「2~4 项」: 它在【本幕硬约束】块里, 且**排在结构要求之前**
  ok('硬约束块存在且写明必须遵守', 文本.includes('【本幕硬约束】（以下由代码裁定'));
  ok('硬约束块排在「1. 结构要求」之前', 文本.indexOf('【本幕硬约束】（以下由代码裁定') < 文本.indexOf('1. 这一幕的结构要求'));
  ok('写清"结果不能换成相反"', 文本.includes('结果不能换成相反'));
  ok('仍以【本幕参考】开头(世界书清理按它识别)', 文本.startsWith('【本幕参考】'));
}

// ---------------------------------------------------------------------------
// ② 升级/封顶: 话术必须是正文能执行的
// ---------------------------------------------------------------------------
console.log('\n[2] 升级: 不再要求"换个实现路径"(正文看不见上一道指令)');
{
  const 升 = 构造({ 节拍: '受挫' }, { 旧指令: 指令(), 核验: 未执行 });
  check('升级次数 +1', 升.指令?.核验升级次数, 1);
  ok('收成"只做一件事"', 裁定(升).includes('这一幕只做一件事'));
  ok('不再说"换个实现路径"', !正文可见(升).includes('换个实现路径'));
  ok('不再说"换个写法"(旧话术)', !正文可见(升).includes('换个写法'));
  ok('无必演时, 单点目标退回节拍', 裁定(升).includes('节拍「受挫」要求的结果'));
  ok('结果不许反转写进正文', 裁定(升).includes('结果不许换成相反'));

  const 有必演 = 构造({ 节拍: '受挫', 必演: { 内容: '洛基引爆抽能装置后脱身', 命运: false } }, { 旧指令: 指令(), 核验: 未执行 });
  ok('有必演时点名那一条', 裁定(有必演).includes('洛基引爆抽能装置后脱身'));
}

console.log('\n[3] 核验缺省(模型没回答): 记账信息留在上游, 不塞给正文');
{
  // 记账信息留在上游(核验.说明 / 面板); 正文只从 `硬约束` 拿到"只做一件事", 拿不到"没明确回答"。
  const 缺 = 构造({ 节拍: '受挫' }, { 旧指令: 指令(), 核验: { ...未执行, 核验来源: '缺省' } });
  ok('缺省也照常收成单点目标', 裁定(缺).includes('这一幕只做一件事'));
  ok('正文里没有"没明确回答"这句元话术', !正文可见(缺).includes('没明确回答'));
}

console.log('\n[4] 封顶: 不再"把决定权交回玩家"(那是放行信号)');
{
  const 封 = 构造({ 节拍: '受挫' }, { 旧指令: 指令({ 核验升级次数: 2 }), 核验: 未执行 });
  check('封顶不再加升级次数', 封.指令?.核验升级次数, 2);
  ok('只演这一件事', 裁定(封).includes('只演这一件事'));
  ok('正文里没有"交回玩家"', !正文可见(封).includes('交回玩家'));
  ok('正文里没有"降低目标"的说法', !正文可见(封).includes('最小的那一步'));
  ok('明确禁止连续重复', 裁定(封).includes('禁止连续重复'));
  ok('调整里写明不再升级', (封.调整 ?? []).some(x => x.includes('不再升级')));

  const 封有必演 = 构造({ 节拍: '受挫', 必演: { 内容: '通行证发出追踪蜂鸣', 命运: false } }, { 旧指令: 指令({ 核验升级次数: 2 }), 核验: 未执行 });
  ok('封顶也点名必演', 裁定(封有必演).includes('通行证发出追踪蜂鸣'));
}

// ---------------------------------------------------------------------------
// ③ 导演层: 核验只按 必演+节拍 判; 确定要发生的事必须进必演
// ---------------------------------------------------------------------------
console.log('\n[5] 导演提示词: 核验口径与注入口径对齐');
{
  ok('只按两项判', SYSTEM_PROMPT.includes('只按【上一道指令】的两项判'));
  ok('点了必演与节拍', SYSTEM_PROMPT.includes('「必演」') && SYSTEM_PROMPT.includes('「节拍」'));
  ok('演法细节不同不算未执行', SYSTEM_PROMPT.includes('细节写得不一样'));
  ok('没有必演就只按节拍判', SYSTEM_PROMPT.includes('就只按节拍判'));
  ok('Step1 仍保留"要求受挫, 实际又赢了 = 未执行"', SYSTEM_PROMPT.includes('要求受挫, 实际又赢了'));
  ok('确定要发生的事只有写进必演才被当真', SYSTEM_PROMPT.includes('只有写进「必演」才会被当真'));
  ok('Step3 要求同时写必演', SYSTEM_PROMPT.includes('同时写进「下一幕.必演」'));
  ok('节拍说明与代码共用一份(受挫语义)', SYSTEM_PROMPT.includes(节拍结构.受挫));
}

// ---------------------------------------------------------------------------
// ④ 取料层: 上一道指令没有必演 → 摆回导演面前
// ---------------------------------------------------------------------------
console.log('\n[6] 结构提醒: 没有必演的指令, 核验只剩节拍可判');
{
  const 提醒 = (部分: Record<string, any>) => 结构提醒(账本({ 当前指令: 指令(部分) }), 12);
  ok('没有必演 → 提醒补必演', 提醒({ 必演: null }).some(x => x.includes('没有「必演」')));
  ok('提醒里给出下一步(写进下一幕.必演)', 提醒({ 必演: null }).some(x => x.includes('下一幕.必演')));
  ok('有必演 → 不提醒', !提醒({ 必演: { 内容: '通行证发出蜂鸣', 命运: false } }).some(x => x.includes('没有「必演」')));
  ok('已跳过 → 不提醒(那道指令本来就没生效)', !提醒({ 已跳过: true }).some(x => x.includes('没有「必演」')));
  ok('冷启动/没有指令 → 不提醒', !结构提醒(账本(), 12).some(x => x.includes('没有「必演」')));
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0) process.exit(1);
