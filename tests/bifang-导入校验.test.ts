// 彼方 · 导入时每个 NPC 的值也必须是对象 —— 批次 2026-11-19 波2（复查「发现9」P2）。
//
// ── 这个 bug 是什么 ──
//  原来只校验 `载荷.NPC` 是对象，不校验它的**每个值**。于是
//  `{"NPC": {"甲": "一段字符串"}}` 能通过校验并写进快照 ——
//  之后选中「甲」时面板按 `card['字段']` 取值全是 undefined，**人物页空白**，
//  **畸形数据常驻**，而且没有任何提示说明它是怎么来的。
//
// ── 为什么是「整份拒绝」而不是「跳过坏的那条」──
//  这是"导入一份备份"，用户期待的是**完整恢复**。
//  悄悄丢掉几条，用户会以为备份里本来就没有那个人 —— 那比拒绝更糟。
import lodash from 'lodash';
import { createPinia, setActivePinia } from 'pinia';
import { 导入数据 } from '../src/彼方_NPC幕后生命状态系统/数据变更';

(globalThis as any)._ = lodash;
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function ok(名: string, 条件: boolean, 附注?: string) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}${附注 ? `  (${附注})` : ''}`);
  }
}
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}

function 静默<T>(fn: () => T): T {
  const 原I = console.info;
  const 原W = console.warn;
  const 原E = console.error;
  const 原T = console.table;
  console.info = () => {};
  console.warn = () => {};
  console.error = () => {};
  console.table = () => {};
  try {
    return fn();
  }
  finally {
    console.info = 原I;
    console.warn = 原W;
    console.error = 原E;
    console.table = 原T;
  }
}

/** 假环境：记录是否真的落盘 / 同步了世界书 */
function 造环境() {
  const 记 = { 保存次数: 0, 同步次数: 0 };
  const 环境: any = {
    // ⚠ 不能是 '关闭' —— 那会让 `同步世界书` 直接 return，测不到同步
    世界书写入: '角色卡主世界书',
    保存: () => { 记.保存次数++; return true; },
    清空: () => ({ 成功: true, 清空层: 0 }),
    同步世界书: () => { 记.同步次数++; },
    现在: () => 1,
  };
  return { 环境, 记 };
}

const 原数据: any = {
  NPC: { 旧人: { 位置: '家' } },
  名单: ['旧人'],
  统计: { 更新次数: 1, 最后更新: 1 },
  剧情时间: '',
  清空层: 0,
  锚点楼层: 0,
  处理到楼层: 0,
};

// ─────────────────────────────────────────────────────────────
console.log('\n[导入] NPC 的值不是对象 → 整份拒绝，一条都不写');
{
  // ── 这条是本次修复的核心 ──
  const { 环境, 记 } = 造环境();
  const 文本 = JSON.stringify({ 名单: ['甲'], NPC: { 甲: '一段字符串' } });
  const 结果 = 静默(() => 导入数据(文本, 原数据, 环境));

  ok('返回了失败', typeof 结果.失败 === 'string');
  eq('没有落盘', 记.保存次数, 0);
  eq('没有同步世界书', 记.同步次数, 0);
  eq('数据没被替换（还是原来那份）', 结果.数据, 原数据);
  ok('说明里指出了是哪一条', /甲/.test(结果.说明), 结果.说明);
  ok('说明里说了它是什么类型', /string/.test(结果.说明), 结果.说明);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[导入] null / 数组 / 数字 也要拒绝');
{
  // ── 为什么逐个测三种 ──
  //  `typeof null === 'object'`、`typeof [] === 'object'` —— 这两种最容易漏。
  const 用例: Array<[string, any, string]> = [
    ['null', null, 'null'],
    ['数组', [1, 2], '数组'],
    ['数字', 42, 'number'],
  ];
  for (const [名, 值, 该出现的类型词] of 用例) {
    const { 环境, 记 } = 造环境();
    const 文本 = JSON.stringify({ 名单: ['甲'], NPC: { 甲: 值 } });
    const 结果 = 静默(() => 导入数据(文本, 原数据, 环境));

    ok(`值是 ${名} → 拒绝`, typeof 结果.失败 === 'string', 结果.说明);
    eq(`值是 ${名} → 没落盘`, 记.保存次数, 0);
    ok(`说明里写了类型「${该出现的类型词}」`, 结果.说明.includes(该出现的类型词), 结果.说明);
  }
}

// ─────────────────────────────────────────────────────────────
console.log('\n[导入] 自证：合法数据照常导入（防判据误伤）');
{
  // ── 这条防的是"把校验写太严，合法备份也进不来" ──
  const { 环境, 记 } = 造环境();
  const 文本 = JSON.stringify({ 名单: ['甲', '乙'], NPC: { 甲: { 位置: '家' }, 乙: { 位置: '店' } } });
  const 结果 = 静默(() => 导入数据(文本, 原数据, 环境));

  eq('[自证] 合法数据导入成功（没有失败）', 结果.失败, undefined);
  eq('[自证] 真的落盘了', 记.保存次数, 1);
  eq('[自证] 真的同步世界书了', 记.同步次数, 1);
  eq('[自证] 名单是 2 个人', 结果.数据.名单, ['甲', '乙']);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[导入] 自证：旧校验分不出畸形与合法（证明 bug 是真的）');
{
  // 复刻旧校验：只判 NPC 是对象，不判每个值
  const 旧校验通过 = (载荷: any) =>
    Array.isArray(载荷.名单) && !!载荷.NPC && typeof 载荷.NPC === 'object' && !Array.isArray(载荷.NPC);

  const 畸形 = { 名单: ['甲'], NPC: { 甲: '一段字符串' } };
  const 合法 = { 名单: ['甲'], NPC: { 甲: { 位置: '家' } } };

  eq('[自证] 旧校验放行畸形数据（这就是那个 bug）', 旧校验通过(畸形), true);
  eq('[自证] 旧校验也放行合法数据', 旧校验通过(合法), true);
  eq('[自证] 旧校验分不出这两者（所以它没用）', 旧校验通过(畸形) === 旧校验通过(合法), true);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[导入] 多条坏数据时，说清有几条、分别是哪几条');
{
  // ── 这条防的是"只说格式不对，用户没法修他的备份文件" ──
  const { 环境 } = 造环境();
  const 文本 = JSON.stringify({ 名单: ['甲', '乙', '丙'], NPC: { 甲: 'x', 乙: 1, 丙: { 位置: '家' } } });
  const 结果 = 静默(() => 导入数据(文本, 原数据, 环境));

  ok('说清有 2 个坏条目', /有 2 个 NPC/.test(结果.说明), 结果.说明);
  ok('点名了甲', /甲/.test(结果.说明), 结果.说明);
  ok('点名了乙', /乙/.test(结果.说明), 结果.说明);
  ok('没把好的丙说成坏的', !/丙（/.test(结果.说明), 结果.说明);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[导入] 自证：既有校验没被破坏');
{
  // ── 加新校验时不许把老的挤掉 ──
  const { 环境 } = 造环境();

  const 非JSON = 静默(() => 导入数据('这不是 JSON', 原数据, 环境));
  ok('[自证] 非 JSON 仍然被拒', /不是合法的 JSON/.test(非JSON.说明), 非JSON.说明);

  const 缺NPC = 静默(() => 导入数据(JSON.stringify({ 名单: ['甲'] }), 原数据, 环境));
  ok('[自证] 缺 NPC 仍然被拒', /缺少/.test(缺NPC.说明), 缺NPC.说明);

  const NPC是数组 = 静默(() => 导入数据(JSON.stringify({ 名单: ['甲'], NPC: [1, 2] }), 原数据, 环境));
  ok('[自证] NPC 是数组仍然被拒', /缺少/.test(NPC是数组.说明), NPC是数组.说明);

  const 名单不是数组 = 静默(() => 导入数据(JSON.stringify({ 名单: '甲', NPC: { 甲: {} } }), 原数据, 环境));
  ok('[自证] 名单不是数组仍然被拒', /缺少/.test(名单不是数组.说明), 名单不是数组.说明);
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
process.exit(fail > 0 ? 1 : 0);
