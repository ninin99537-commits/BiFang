// ═════════════════════════════════════════════════════════════
// 判据 1：类型门
// ═════════════════════════════════════════════════════════════
console.log('\n[★ 判据 1 类型门] `时间提示形状` 是判别式联合，`完整` 那支才带完整日期');
{
  // ── 类型门的价值：`仅时分` 那支**在类型上就进不了**只接受 `完整` 的地方 ──
  //
  //  ⚠ 真正的"编译不过"由 `vue-tsc`/`tsc` 保证 —— 判据里写一个 `@ts-expect-error`
  //    就能验证它确实会报错（如果哪天类型放宽了，那行会变成"未使用 expect-error"而报错）。
  const 完整: 时间提示形状 = { 形: '完整', 文本: '2026-01-02 20:30' };
  const 仅时分: 时间提示形状 = { 形: '仅时分', 文本: '20:30' };
  const 无: 时间提示形状 = { 形: '无' };

  eq('完整那支有 文本', (完整 as any).文本, '2026-01-02 20:30');
  eq('仅时分那支也有 文本（不丢信息）', (仅时分 as any).文本, '20:30');
  eq('无 那支没有 文本', (无 as any).文本, undefined);

  // ── 类型门的核心：只有 `完整` 能赋给"只收完整"的变量 ──
  const 只收完整 = (提示: Extract<时间提示形状, { 形: '完整' }>): string => 提示.文本;

  ok('★ `完整` 能传给只收完整的函数', typeof 只收完整(完整 as Extract<时间提示形状, { 形: '完整' }>) === 'string');

  // **自证**：下面这两行在类型上应当报错 —— 用 `@ts-expect-error` 钉住
  // 如果哪天类型放宽了（`仅时分` 也能传），这两行不再报错 →
  // `@ts-expect-error` 变成"未使用的抑制" → **tsc 会报错** → 判据红。
  // @ts-expect-error 仅时分不能传给只收完整的函数
  const _不该编译过1 = 只收完整(仅时分);
  // @ts-expect-error 无 也不能传
  const _不该编译过2 = 只收完整(无);
  ok('★ 类型门存在（两行 @ts-expect-error 都没被"未使用"报错）', true);
}

// ═════════════════════════════════════════════════════════════
// 判据 2：产物断言
// ═════════════════════════════════════════════════════════════
console.log('\n[★ 判据 2 产物] `time: 20:30` → 产物里没有「务必以此为准」的权威形态');
{
  // ── 这条是 C5 的底线 ──
  //  特殊纪年卡片会写 `time: 20:30`（只有时分）。它必须被识别成 `仅时分`，
  //  于是**不进权威段**，只进那句"不要据此推断日期"。
  const 提示 = 静默(() => 时间提示('', '她看了眼怀表。\ntime: 20:30', ''));
  eq('★ 识别成「仅时分」', 提示.形, '仅时分');
  eq('★ 文本仍带着那个时分（不丢信息）', (提示 as any).文本, '20:30');

  // 产物里不许出现权威形态
  const 产物 = 静默(() => buildUpdateMessages(造入参({
    storyTimeHint: '',           // 仅时分那支**不会**填这个（更新输入.ts 就是这么分的）
    storyTimeHint仅时分: '20:30',
  })));
  const 全文 = JSON.stringify(产物);

  ok('★ 产物里**没有**「务必以此为准」段', !/务必以此为准/.test(全文), '权威段出现了');
  ok('★ 产物里**没有** `【★正文当前时间` 的权威形态', !/【★正文当前时间/.test(全文));
  ok('★ 但产物里仍提到了那个时分（供参考）', /20:30/.test(全文));
  ok('★ 并且明确说了"不要据此推断日期"', /不要据此推断日期|未给出日期/.test(全文));
}

console.log('\n[★ 判据 2 产物] `☆ 20:30` → 同样不进权威段');
