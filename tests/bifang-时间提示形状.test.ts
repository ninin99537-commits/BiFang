// 彼方 · C5：时间提示改判别式联合 —— 批次 2026-11-20（需求方 #482）。
//
// ── 底线只有一条 ──
//
//  **`20:30` 永远不能出现在「务必以此为准」后面。**
//
//  "务必以此为准"配一个残缺值，比没有时间更糟 ——
//  模型会自己编个日期，而规则同时写着"严禁自创时间线"。
//
// ── 三处的处理 ──
//
//  | 消费方 | 仅时分时 |
//  |---|---|
//  | 跨度计算 | 显式走"跳过（无时间）" |
//  | `最后剧情时刻` 持久字段 | **不写**（保持旧值） |
//  | 提示词权威段 | **整块降级成参考句** |
//
// ── 判据三层（需求方 #482 都要求）──
//
//  1. **类型门**：`渲染权威段` 只接受 `{ 形: '完整' }` —— 传 `仅时分` **编译不过**
//  2. **产物断言**：造 `time: 20:30` / `☆ 20:30` → 产物里没有 `【★正文当前时间` 的权威形态
//  3. **变异自证**：把类型门放宽回接受 `仅时分` → 第 2 层必须红
import { createPinia, setActivePinia } from 'pinia';
import { 时间提示 } from '../src/彼方_NPC幕后生命状态系统/聊天取料';
import { buildUpdateMessages } from '../src/彼方_NPC幕后生命状态系统/prompts';
import type { 时间提示形状 } from '../src/彼方_NPC幕后生命状态系统/聊天取料';

setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function ok(名: string, 条件: boolean, 附注?: string) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}${附注 ? `  (${附注})` : ''}`);
  }
}
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}

const 原I = console.info;
const 原W = console.warn;
const 原E = console.error;
const 静默 = <T>(fn: () => T): T => {
  console.info = () => {};
  console.warn = () => {};
  console.error = () => {};
  try {
    return fn();
  }
  finally {
    console.info = 原I;
    console.warn = 原W;
    console.error = 原E;
  }
};

