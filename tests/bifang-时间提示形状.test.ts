// ═════════════════════════════════════════════════════════════
// 判据 2b：三处的行为（跨度 / 持久字段 / 权威段）
// ═════════════════════════════════════════════════════════════
console.log('\n[★ 判据 2b] 「仅时分」时 `storyTimeHint` 为空 → 跨度显式跳过、持久字段不写');
{
  // ── 这条验证的是 `更新输入.ts` 那个分流 ──
  //
  //  `storyTimeHint = 时间提示结果.形 === '完整' ? 文本 : ''`
  //  于是仅时分时它是空串 → 跨度的 `剧情跨度(data.剧情时间, '')` 返回 null → "跳过（无时间）"；
  //  而 `本轮剧情时刻 = storyTimeHint` 也是空 → `最后剧情时刻` **不写**。
  //
  //  ⚠ 这里断言的是**那个分流的正确性**（用纯逻辑复刻），
  //    不是跑整条 `收集本轮输入`（那要一整套宿主）。
  const 分流 = (提示: 时间提示形状) => ({
    storyTimeHint: 提示.形 === '完整' ? 提示.文本 : '',
    仅时分提示: 提示.形 === '仅时分' ? 提示.文本 : '',
  });

  const 完整结果 = 分流({ 形: '完整', 文本: '2026-01-02 20:30' });
  eq('[完整] storyTimeHint 有值', 完整结果.storyTimeHint, '2026-01-02 20:30');
  eq('[完整] 仅时分提示为空', 完整结果.仅时分提示, '');

  const 仅时分结果 = 分流({ 形: '仅时分', 文本: '20:30' });
  eq('★ [仅时分] storyTimeHint **为空**（→ 跨度跳过、持久字段不写）', 仅时分结果.storyTimeHint, '');
  eq('★ [仅时分] 但 仅时分提示 带着它（供参考）', 仅时分结果.仅时分提示, '20:30');

  const 无结果 = 分流({ 形: '无' });
  eq('[无] 两个都空', [无结果.storyTimeHint, 无结果.仅时分提示], ['', '']);
}

