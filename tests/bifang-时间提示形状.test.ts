console.log('\n[结构] 三处确实落地了');
{
  const { readFileSync } = await import('node:fs');
  const path = await import('node:path');
  const 读 = (f: string) => readFileSync(path.join(process.cwd(), `src/彼方_NPC幕后生命状态系统/${f}`), 'utf8')
    .split('\n').filter(l => !/^\s*(\/\/|\*|\/\*)/.test(l)).join('\n');

  const 取料源 = 读('聊天取料.ts');
  ok('[结构] 导出 时间提示形状 类型', /export type 时间提示形状 =/.test(取料源));
  ok('[结构] 三支都在（完整/仅时分/无）',
     /形: '完整'/.test(取料源) && /形: '仅时分'/.test(取料源) && /形: '无'/.test(取料源));
  ok('[结构] 时间提示 返回类型是 时间提示形状', /时间提示\(_worldbook: string, reply: string, context: string\): 时间提示形状/.test(取料源));
  ok('[结构] 分支 4（time:）返回 仅时分', /形: '仅时分', 文本: `\$\{pad\(h\)\}:\$\{pad\(m\)\}`/.test(取料源));

  const 输入源 = 读('更新输入.ts');
  ok('[结构] 更新输入 只把「完整」当 storyTimeHint',
     /时间提示结果\.形 === '完整' \? 时间提示结果\.文本 : ''/.test(输入源));
  ok('[结构] 仅时分单独带出去', /仅时分提示 = 时间提示结果\.形 === '仅时分'/.test(输入源));
  ok('[结构] 传给了 prompts', /storyTimeHint仅时分: 仅时分提示/.test(输入源));

  const 提示源 = 读('prompts.ts');
  ok('[结构] prompts 有 storyTimeHint仅时分 字段', /storyTimeHint仅时分\?: string/.test(提示源));
  // ── 2026-11-20 Q3 改法（需求方 #531）──
  //
  //  旧断言：`/input\.storyTimeHint \? `【★正文当前时间/` —— 它断言的正是
  //  **段内三元**那个形态，而 Q3 把这支提升成了段级 `当`。
  //
  //  **这不是"测试过时"，是那个判据绑错了对象**：它真正要保证的是
  //  **"权威段只在 storyTimeHint 非空时出现"**（意图），而不是"用三元写的"（形态）。
  //  验收那句话：**绕过新判据需要"故意"，绕过旧判据只需要"插一行注释"。**
  ok('[结构] 权威段只在 storyTimeHint 非空时出现（条件在 `当` 里）',
     /名: '权威时间\(完整\)',\s*\n\s*当: i => !!i\.storyTimeHint,/.test(提示源)
     || /input\.storyTimeHint \? `【★正文当前时间/.test(提示源),
     '既没有段级 `当: i => !!i.storyTimeHint`，也没有段内三元 —— 权威段可能无条件出现了');
  ok('[结构] 仅时分时降级成"不要据此推断日期"', /不要据此推断日期/.test(提示源));

  // **自证**：正则可以抓到"裸字符串"的旧写法
  ok('[自证] 正则能区分"返回裸字符串"的旧签名',
     !/\): 时间提示形状/.test('export function 时间提示(_worldbook: string, reply: string, context: string): string'));
}

