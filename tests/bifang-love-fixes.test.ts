// 彼方 · 恋爱规则改进(docs/彼方-改进方案.md 第 1、7 节): 开局窗口 / 夫妻名分 / 每日上限 / 冷落缓降 / 地板只限时间回落
import { 应用恋爱回合, 名分词表, 好感每日上限, 应用名分事件 } from '../src/彼方_NPC幕后生命状态系统/恋爱规则';

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) { pass++; console.log(`  PASS  ${label}`); }
  else { fail++; console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`); }
}
const 事件 = (轴: string, 类型: string, 强度?: string, 依据 = '正文原文') => ({ 轴, 类型, 强度, 依据 });
const 卡 = (字段: Record<string, any> = {}) => ({ 恋爱对象: '是', 情感倾向: '常规', ...字段 });

console.log('\n[1] 开局窗口只看「恋爱开局」标记: 首轮报了普通事件也不会关窗');
{
  const 首轮 = 应用恋爱回合(卡(), [事件('好感', '交心', '中')], '2026-08-15 20:00');
  check('首轮只有普通事件: 不写开局标记', '恋爱开局' in 首轮, false);
  check('首轮好感 0+3', 首轮['好感值'], '3');
  const 次轮卡 = { ...卡(), ...首轮 };
  const 次轮 = 应用恋爱回合(次轮卡, [{ 轴: '开局', 好感: '挚爱', 名分: '夫妻', 依据: '人设：结婚五年的妻子' }], '2026-08-15 21:00');
  check('次轮开局仍被接受', 次轮['恋爱开局'], '是');
  check('开局把 3 抬到挚爱基线 96', 次轮['好感值'], '96');
  check('开局名分 夫妻(原来是"无")', 次轮['名分'], '夫妻');
  const 高于基线 = 应用恋爱回合(卡({ 好感值: '60', 好感阶段: '朋友' }), [{ 轴: '开局', 好感: '认识', 依据: '人设' }], '');
  check('卡上已高于基线: 不往下压', 高于基线['好感值'], '60');
  check('高于基线也关窗', 高于基线['恋爱开局'], '是');
}

console.log('\n[2] 名分: 夫妻 / 未婚夫 / 结婚 / 离婚');
{
  check('词表含 夫妻 与 未婚夫', ['夫妻', '未婚夫'].every(n => 名分词表.includes(n)), true);
  check('结婚 → 夫妻', 应用名分事件({ 名分: '未婚妻' }, { 类型: '结婚' }), '夫妻');
  check('离婚 → 无', 应用名分事件({ 名分: '夫妻' }, { 类型: '离婚' }), '无');
}

console.log('\n[3] 好感每日上限 12');
{
  check('常量 12', 好感每日上限, 12);
  const 一轮 = 应用恋爱回合(卡({ 好感值: '20', 好感阶段: '认识' }), [事件('好感', '交心', '大'), 事件('好感', '交心', '大')], '2026-08-15 20:00');
  check('第一轮被单轮上限夹到 +8', 一轮['好感值'], '28');
  const 二轮 = 应用恋爱回合({ ...卡({ 好感值: '20', 好感阶段: '认识' }), ...一轮 }, [事件('好感', '交心', '大'), 事件('好感', '交心', '大')], '2026-08-15 21:00');
  check('同日第二轮只剩 +4', 二轮['好感值'], '32');
  const 三轮卡 = { ...卡({ 好感值: '20', 好感阶段: '认识' }), ...一轮, ...二轮 };
  const 三轮 = 应用恋爱回合(三轮卡, [事件('好感', '交心', '大')], '2026-08-15 22:00');
  check('同日第三轮不再涨', 三轮['好感值'], '32');
  const 次日 = 应用恋爱回合(三轮卡, [事件('好感', '交心', '大')], '2026-08-16 09:00');
  check('次日重新计', 次日['好感值'], '38');
}

console.log('\n[4] 冷落缓降: 30 天无好感事件后每天 −0.3, 不跌出当前阶段');
{
  const 基 = 卡({ 好感值: '90', 好感阶段: '恋人', 上次互动日期: '2026-01-01', 恋爱基准日期: '2026-01-01 10:00' });
  const 二十天 = 应用恋爱回合(基, [], '2026-01-21 10:00');
  check('20 天: 不降', 二十天['好感值'], '90');
  const 四十天 = 应用恋爱回合(基, [], '2026-02-10 10:00');
  check('40 天: 降 10×0.3=3', 四十天['好感值'], '87');
  const 一年 = 应用恋爱回合(基, [], '2027-01-01 10:00');
  check('一年: 停在恋人档下界 86', [一年['好感值'], 一年['好感阶段']], ['86', '恋人']);
  const 有事件 = 应用恋爱回合(基, [事件('好感', '交心', '小')], '2026-02-10 10:00');
  check('有好感事件的那轮不降, 且记下今天', [有事件['好感值'], 有事件['上次互动日期']], ['91.5', '2026-02-10']);
}

console.log('\n[5] 情欲地板只截断时间回落, 不截断事后回落');
{
  const 事后 = 应用恋爱回合(卡({ 情欲值: '80', 好感值: '90', 好感阶段: '恋人' }), [事件('情欲', '性行为', '大')], '');
  check('恋人 80 − 性行为 35 = 45', 事后['情欲值'], '45');
  const 挚爱事后 = 应用恋爱回合(卡({ 情欲值: '70', 好感值: '98', 好感阶段: '挚爱' }), [事件('情欲', '性行为', '大')], '');
  check('挚爱 70 − 35 = 35, 低于地板 60 也照落', 挚爱事后['情欲值'], '35');
  const 时间 = 应用恋爱回合(卡({ 情欲值: '50', 好感值: '90', 好感阶段: '恋人', 恋爱基准日期: '2026-08-01 10:00' }), [], '2026-08-11 10:00');
  check('时间回落仍被地板 45 截断', 时间['情欲值'], '45');
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0) process.exit(1);
