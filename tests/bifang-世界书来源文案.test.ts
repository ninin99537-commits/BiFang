// 彼方 · 界面灰字必须与"实际读了哪些世界书"一致 —— 批次 2026-11-19 波3（复查「发现11」P2）。
//
// ── 这个 bug 是什么 ──
//  设置页灰字写着：「不读全局世界书，只读当前角色卡与聊天绑定的世界书。」
//  而 `收集世界书来源` 实际还读了 **persona 绑定的世界书**（主角设定常写在那一本里）。
//
//  后果：persona 绑了世界书时，那段内容**确实进了请求**，
//  用户核对日志页发现多一本，**却无法从 UI 解释**。
//
// ── 为什么这条判据要"两边都读源码" ──
//  只查一边没有意义：灰字写对了但代码没读，或代码读了但灰字没写，都是这个 bug。
//  **必须同时断言"代码读了 persona"和"灰字写了 persona"。**
import { readFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const 页面源 = readFileSync(path.join(ROOT, 'src/彼方_NPC幕后生命状态系统/页面-设置.vue'), 'utf8');
const 世界书源 = readFileSync(path.join(ROOT, 'src/彼方_NPC幕后生命状态系统/worldbook.ts'), 'utf8');

let pass = 0;
let fail = 0;
function ok(名: string, 条件: boolean, 附注?: string) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}${附注 ? `  (${附注})` : ''}`);
  }
}
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}

// ─────────────────────────────────────────────────────────────
console.log('\n[来源] 代码实际读了哪几本');
{
  // ── 先把"实现是什么"钉死 ──
  //  这三条是本判据的地基：如果代码不再读 persona，那灰字也不该提它。
  ok('代码读了角色卡绑定的世界书', /host\.worldbook\.boundNames\(\)/.test(世界书源));
  ok('代码读了聊天世界书', /host\.worldbook\.chatName\(\)/.test(世界书源));
  ok('代码读了 persona 绑定的世界书', /host\.persona\.lorebook\(\)/.test(世界书源));
  ok('代码**没有**读全局世界书', !/getWorldbookNames|全局世界书\s*\(/.test(世界书源));
}

// ─────────────────────────────────────────────────────────────
console.log('\n[灰字] 那条灰字已按用户要求删除（2026-11-19 第三次「清啊」）');
{
  // ── 这里发生了一次冲突，记下来 ──
  //  上一批（发现11）我刚把那条灰字**补上 persona**，判据是"灰字说了 persona"。
  //  这一批用户说「清啊」，把整页说明段落全删了 —— **包括那一条**。
  //
  //  所以判据必须跟着改：**灰字不再存在**，但"代码仍读 persona"这个事实仍要钉住。
  //  ⚠ 这是"两条要求先后到达、后者覆盖前者"的典型 ——
  //    如果我不改这条判据，它就会一直红，而红的原因不是 bug，是需求变了。
  const 命中 = 页面源.match(/<p class="bf-hint">([\s\S]*?)<\/p>/g) ?? [];
  const 世界书那行 = 命中.find(h => /不读全局世界书/.test(h)) ?? '';
  ok('那条灰字已经不在了（用户要求删）', 世界书那行 === '', 世界书那行.slice(0, 60));

  // **代码仍然读 persona** —— 这个事实没变，而且要一直钉住
  ok('代码仍然读 persona 绑定的世界书', /host\.persona\.lorebook\(\)/.test(世界书源));

  // **自证**：这条判据能区分"灰字在"与"灰字没了"
  ok('[自证] 旧文案（含那句）会被判成"还在"',
     /不读全局世界书/.test('不读全局世界书，只读当前角色卡与聊天绑定的世界书。'));
}

// ─────────────────────────────────────────────────────────────
console.log('\n[灰字] 自证：旧文案会红');
{
  // ── 这条防的是"判据太宽，随便一句带'角色卡'的话都能过" ──
  const 旧文案 = '不读全局世界书，只读当前角色卡与聊天绑定的世界书。';
  ok('[自证] 旧文案里没有 persona', !/persona|人设/i.test(旧文案));
  ok('[自证] 但它有角色卡和聊天（所以只查那两条会假绿）',
     /角色卡/.test(旧文案) && /聊天/.test(旧文案));

  const 新文案 = '不读全局世界书，只读当前角色卡、聊天与人设（persona）绑定的世界书。';
  ok('[自证] 新文案里有 persona', /persona|人设/i.test(新文案));
  ok('[自证] 两者确实不同', 旧文案 !== 新文案);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[注释] worldbook.ts 的说明也必须同步');
{
  // ── 灰字改了、注释没改，下一个人读代码时还是会以为只读两本 ──
  //  ⚠ 搜索范围要**覆盖到 `getActiveWorldbookText` 的文档注释** ——
  //    那句「不含全局世界书」在那里，不在 `收集世界书来源` 头上。
  //    （我第一版把范围截到 `收集世界书来源` 之前，于是假红了一条。）
  const 到函数为止 = 世界书源.slice(0, 世界书源.indexOf('async function getActiveWorldbookText'));
  ok('注释里说了 persona', /persona/.test(到函数为止));
  ok('注释里说了「不含全局世界书」', /不含全局世界书/.test(到函数为止));

  // **自证**：范围截错会漏掉那句（证明这条判据对范围敏感）
  const 只到收集来源 = 世界书源.slice(0, 世界书源.indexOf('function 收集世界书来源'));
  ok('[自证] 截到「收集世界书来源」之前会漏掉那句（所以范围要够）',
     !/不含全局世界书/.test(只到收集来源));
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
process.exit(fail > 0 ? 1 : 0);
