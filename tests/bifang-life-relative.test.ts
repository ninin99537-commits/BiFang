// 彼方 · 生活状态注入时的相对时间 + 状态词剥离
import { 拆分生活状态, 规范化生活状态, 生活状态相对化, 生活状态待更新 } from '../src/彼方_NPC幕后生命状态系统/生活状态';
import { buildInjectionPrompt } from '../src/彼方_NPC幕后生命状态系统/prompts';

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) { pass++; console.log(`  PASS  ${label}`); }
  else { fail++; console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`); }
}

console.log('\n[1] 相对时间与提示(顺带剥掉旧卡的「已用/已洗」)');
{
  const 原 = '吃饭(2026-10-17 18:40 已用); 洗漱(2026-10-16 22:10 已洗); 睡眠(2026-10-16 23:00-次日07:00)';
  const 结果 = 生活状态相对化(原, '2026-10-17 22:40');
  check('吃饭 4 小时前', 结果.includes('吃饭(2026-10-17 18:40；约 4 小时前)'), true);
  check('状态词不再出现', /已用|已洗/.test(结果), false);
  check('洗漱 25 小时 → 该洗澡了', 结果.includes('约 25 小时前，该洗澡了'), true);
  check('醒来 16 小时 → 困了', 结果.includes('醒来约 16 小时前，困了'), true);
  check('刚吃过', 生活状态相对化('吃饭(2026-10-17 21:40)', '2026-10-17 22:40'), '吃饭(2026-10-17 21:40；约 1 小时前，刚吃过)');
  check('饿了', 生活状态相对化('吃饭(2026-10-17 12:00)', '2026-10-17 20:00'), '吃饭(2026-10-17 12:00；约 8 小时前，饿了)');
  check('取剧情时间段的结束时刻', 生活状态相对化('吃饭(2026-10-17 18:00)', '2026-10-17 19:00 至 2026-10-17 20:00'), '吃饭(2026-10-17 18:00；约 2 小时前，刚吃过)');
}

console.log('\n[2] 认不出就原样');
{
  check('没有剧情时间', 生活状态相对化('吃饭(2026-10-17 18:40 已用)', ''), '吃饭(2026-10-17 18:40)');
  check('只有状态词、没有时刻 → 整条丢掉', 生活状态相对化('吃饭(没吃)', '2026-10-17 22:40'), '');
  check('还在睡(没有终点)', 生活状态相对化('睡眠(2026-10-17 22:00 已睡)', '2026-10-17 22:40'), '睡眠(2026-10-17 22:00)');
  check('时间在未来', 生活状态相对化('吃饭(2026-10-18 08:00 已用)', '2026-10-17 22:40'), '吃饭(2026-10-18 08:00)');
}

console.log('\n[3] 注入表接上了');
{
  const 卡 = { 当前在做: '看书', 生活状态: '吃饭(2026-10-17 12:00 已用)' };
  check('传剧情时间: 注入带提示', buildInjectionPrompt([['甲', 卡]], undefined, '2026-10-17 20:00').includes('饿了'), true);
  check('不传: 原样', buildInjectionPrompt([['甲', 卡]]).includes('饿了'), false);
}

console.log('\n[4] 更新 AI 的催更(只催时刻, 不再要"吃了没吃")');
{
  const 卡 = '吃饭(2026-10-17 12:00); 洗漱(2026-10-16 22:10); 睡眠(2026-10-16 23:00-次日07:00)';
  check('饭点 + 超时洗漱 + 久醒', 生活状态待更新(卡, '2026-10-18 08:00'), [
    '早餐时间已过, 请返回本轮吃饭的时刻',
    '洗漱已超过一天, 请返回洗漱的时刻',
    '已醒较久, 请返回当前睡眠安排(还在睡就只写起点)',
  ]);
  check('饭点未过两小时不催吃', 生活状态待更新(卡, '2026-10-17 18:00').some(x => x.includes('时间已过')), false);
  check('刚吃过不催', 生活状态待更新('吃饭(2026-10-17 19:00); 洗漱(2026-10-17 20:00); 睡眠(2026-10-17 07:00-12:00)', '2026-10-17 20:00'), []);
}

console.log('\n[5] 规范化生活状态: 只留时刻');
{
  check('旧格式剥掉状态词', 规范化生活状态('吃饭(2026-10-17 18:40 已用); 洗漱(2026-10-17 22:10 已洗)'), '吃饭(2026-10-17 18:40); 洗漱(2026-10-17 22:10)');
  check('顿号/逗号分隔也认', 规范化生活状态('吃饭(2026-10-17 18:40，已吃)'), '吃饭(2026-10-17 18:40)');
  check('只剩状态词的条目丢掉', 规范化生活状态('吃饭(没吃); 洗漱(2026-10-17 22:10 已洗)'), '洗漱(2026-10-17 22:10)');
  check('新格式不动', 规范化生活状态('吃饭(2026-10-17 18:40); 睡眠(2026-10-17 23:00-次日07:00)'), '吃饭(2026-10-17 18:40); 睡眠(2026-10-17 23:00-次日07:00)');
  check('自由文本原样', 规范化生活状态('今天在家休息，没出门'), '今天在家休息，没出门');
  check('空值原样', 规范化生活状态(''), '');
  check('非字符串不炸', 规范化生活状态(undefined), '');
}

console.log('\n[6] 界面拆条: 每条一个「类目 + 时刻 + 距今」');
{
  const 条 = 拆分生活状态('吃饭(2026-10-17 18:40 已用); 洗漱(2026-10-17 20:10); 睡眠(2026-10-16 23:00-次日07:00)', '2026-10-17 22:40');
  check('三条都在', 条.map(x => x.类), ['吃饭', '洗漱', '睡眠']);
  check('时刻已剥掉状态词', 条.map(x => x.时间), ['2026-10-17 18:40', '2026-10-17 20:10', '2026-10-16 23:00-次日07:00']);
  check('距今按剧情时间算(睡眠从醒来算起)', 条.map(x => x.距今), ['约 4 小时前', '约 3 小时前', '约 16 小时前']);
  check('没有剧情时间就没有距今', 拆分生活状态('吃饭(2026-10-17 18:40)', '').map(x => x.距今), ['']);
  check('自由文本没有条目结构 → 空数组', 拆分生活状态('今天在家休息', '2026-10-17 22:40'), []);
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
process.exit(fail === 0 ? 0 : 1);
