// 剧情导演 · 提醒互斥（2026-11-12 P0.8）
//
// 病根：提醒规则表里每条都是平级 `生成()`，**没有组/优先级/互斥**。
// 于是"授权类"（这一幕可以空）与"裁决类"（这一幕该收/该来事）能同时开口，读起来一样重。
// 真机第 68 场（原始账本跑 结构提醒()，8 条里三条在打架）：
//   #2 生活幕  : 节拍优先选「日常」; 这一场"什么都没发生"是对的     ← 授权
//   #3 该收章  : 幕号推不动了, 该收章: 让本章的计划高潮落地         ← 裁决
//   #7 日常拖太久: 最近 5 场都是日常 → 该让它有事发生了            ← 反向授权
// 模型选了顺的那条 → 连续 11 场日常, 到第 78 场没出章。
//
// 裁定：判据不是"是不是最后一幕"，也不是"有没有进收束"，而是**这一章是不是演太久了**。
// 三处共用 `判收章()` 一份表达式（各算一遍就会"一个说超期、一个说没超期"）。
// 让位**不是静默**：要说出来（"本来是生活幕, 但本章已经演太久"），否则导演以为幕型没了。
// 明确**不做**组/优先级体系（YAGNI）：三处让位是同一个判据，抽函数就够。
import { createPinia, setActivePinia } from 'pinia';
import type { 导演账本 } from '../src/剧情导演/schema';
import { emptyData } from '../src/剧情导演/快照';
import { 结构提醒, 判收章, 选收章发言者 } from '../src/剧情导演/取料';

(globalThis as any)._ = {
  clamp: (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), hi),
  cloneDeep: (v: any) => (v === undefined ? undefined : JSON.parse(JSON.stringify(v))),
};
(globalThis as any).localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

/** 一幕里带类型的幕纲行(生活幕规则只认 `类型: 生活` 这种明确写法) */
const 幕 = (类型: string) => `第x幕｜类型: ${类型}｜目标: —｜障碍: —｜转折: —｜代价: —｜结束条件: —`;
const 四幕 = [幕('事件'), 幕('事件'), 幕('事件'), 幕('生活')];
const 账本 = (部分: Partial<导演账本> = {}): 导演账本 => ({ ...emptyData(), ...部分 });
/** 真机第 68 场那份形态：进度=推进、幕号 4/4(最后一幕是生活幕)、章已演 68 场、最近 5 场日常 */
const 真机68 = () =>
  账本({
    已分析轮数: 68,
    章回: { 章号: 1, 主题: '', 计划高潮: '雪停前把门修好', 进度: '推进', 起始场: 1, 幕纲: 四幕, 当前幕号: 4 } as any,
    张力: { 当前: 2, 距上次高潮楼层: 0, 连续低张力: 5, 最近节拍: ['余波', '日常', '日常', '日常', '日常', '日常'] as any },
  });

const 授权 = '节拍优先选「日常」';
const 该来事 = '该让它有事发生了';
const 收紧 = '该收章';
const 改口 = '本章已经演太久';

// ---------------------------------------------------------------------------
console.log('\n[1] 真机第 68 场：授权与裁决不许同轮开口');
{
  const 行 = 结构提醒(真机68(), 68);
  const 文本 = 行.join('\n');
  ok('防空跑: 确实有提醒', 行.length > 0);
  ok('不再授权"优先选日常"', !文本.includes(授权));
  ok('不再催"该让它有事发生了"', !文本.includes(该来事));
  ok('说了"该收章"', 文本.includes(收紧));
  // 裁定 §二-2: 让位不是静默 —— 必须说清"本来是生活幕, 但让位了"
  ok('让位要说话: 含"本章已经演太久"', 文本.includes(改口));
  ok('让位要说话: 仍点名这是生活幕', 文本.includes('本来是生活幕'));
  // 副作用验：不存在"可以空"与"必须收"同时出现
  ok('不存在"授权∩裁决"的组合', !(文本.includes(授权) && 文本.includes(收紧)));
}

console.log('\n[2] 反向验（一票否决）：非最后一幕、且未超期 → 授权照旧');
{
  // 第 2/4 幕是生活幕，章才演 10 场(未超 4×3=12) —— 这是"收束前的正当喘息"
  const 账 = 账本({
    已分析轮数: 10,
    章回: { 章号: 1, 主题: '', 计划高潮: '', 进度: '推进', 起始场: 1, 幕纲: [幕('事件'), 幕('生活'), 幕('事件'), 幕('事件')], 当前幕号: 2 } as any,
    张力: { 当前: 2, 距上次高潮楼层: 0, 连续低张力: 0, 最近节拍: ['小胜'] as any },
  });
  const 文本 = 结构提醒(账, 10).join('\n');
  ok('生活幕照旧响（授权仍在）', 文本.includes(授权));
  ok('不出现"该收章"', !文本.includes(收紧));
  check('判收章: 未超期 → 不该收', 判收章(账).该收, false);
}

console.log('\n[3] 判收章: 三种触发面 + 一个边界');
{
  const 造 = (部分: any) => 账本({ 已分析轮数: 41, 章回: { 章号: 1, 主题: '', 计划高潮: '', 进度: '推进', 起始场: 1, 幕纲: [幕('事件'), 幕('事件')], 当前幕号: 1, ...部分 } as any });
  check('收束 → 该收', 判收章(造({ 进度: '收束' })).该收, true);
  check('已完结 → 该收', 判收章(造({ 进度: '已完结' })).该收, true);
  check('超期(41 场 > max(2×3, 40)) → 该收', 判收章(造({})).该收, true);
  check('超期时 收束=false', 判收章(造({})).收束, false);
  check('超期 = 只由场数触发', 判收章(造({})).超期, true);
  // 边界: 恰好 3N 场 **不算**超期(否则"预算"会提前一场生效)
  const 恰好 = 账本({ 已分析轮数: 40, 章回: { 章号: 1, 主题: '', 计划高潮: '', 进度: '推进', 起始场: 1, 幕纲: [幕('事件'), 幕('事件')], 当前幕号: 1 } as any });
  check('恰好 40 场(= 章长度阈值) → 不超期', 判收章(恰好).超期, false);
  check('演了几场 = 已分析轮数 - 起始场 + 1', 判收章(恰好).演了几场, 40);
  // 无幕纲: 不判超期(没预算可比), 但收束仍算该收
  const 无幕纲 = 账本({ 已分析轮数: 50, 章回: { 章号: 1, 主题: '', 计划高潮: '', 进度: '推进', 起始场: 1 } as any });
  check('无幕纲 → 不超期', 判收章(无幕纲).超期, false);
  check('无幕纲但收束 → 该收', 判收章({ ...无幕纲, 章回: { ...无幕纲.章回!, 进度: '收束' } } as any).该收, true);
  // 老账本没有起始场: 演了几场=0, 不判超期(不猜)
  const 无起点 = 账本({ 已分析轮数: 50, 章回: { 章号: 1, 主题: '', 计划高潮: '', 进度: '推进', 幕纲: [幕('事件')], 当前幕号: 1 } as any });
  check('无起始场 → 演了几场 0', 判收章(无起点).演了几场, 0);
  check('无起始场 → 不超期', 判收章(无起点).超期, false);
}

console.log('\n[4] 收章语义：全轮只许一条（计数，不用"包含"）');
{
  const 计数 = (文本: string, 词: string) => 文本.split(词).length - 1;
  const 收束 = 账本({
    已分析轮数: 72,
    章回: { 章号: 1, 主题: '', 计划高潮: '', 进度: '收束', 起始场: 1, 收束起始场: 60, 幕纲: 四幕, 当前幕号: 4 } as any,
    张力: { 当前: 2, 距上次高潮楼层: 0, 连续低张力: 6, 最近节拍: ['日常', '日常', '日常', '日常', '日常', '日常'] as any },
  });
  const 已完结 = 账本({
    已分析轮数: 80,
    章回: { 章号: 1, 主题: '', 计划高潮: '', 进度: '已完结', 起始场: 1, 收束起始场: 60, 幕纲: 四幕, 当前幕号: 4 } as any,
    张力: { 当前: 2, 距上次高潮楼层: 0, 连续低张力: 6, 最近节拍: ['日常', '日常', '日常', '日常', '日常', '日常'] as any },
  });

  // ① 超期态：幕纲落后 是发言者；章长度(整章阈值) 与 日常拖太久 都要让位
  const 超期文本 = 结构提醒(真机68(), 68).join('\n');
  const 超期合计 = 计数(超期文本, 收紧) + 计数(超期文本, '计划高潮落地');
  ok(`超期态: "该收章"+"计划高潮落地" 合计 ≤ 2（实际 ${超期合计}）`, 超期合计 <= 2);
  check('超期态: "该收章" 恰好 1 次', 计数(超期文本, 收紧), 1);
  ok('超期态: 不出现"开新章"（这一章还没收完）', !超期文本.includes('开新章'));

  // ② 收束态：章长度(收束预算) 是发言者，另外两条闭嘴
  const 收束文本 = 结构提醒(收束, 72).join('\n');
  const 收束合计 = 计数(收束文本, 收紧) + 计数(收束文本, '计划高潮落地');
  check('收束态: "该收章" 恰好 1 次', 计数(收束文本, 收紧), 1);
  ok(`收束态: "该收章"+"计划高潮落地" 合计 ≤ 2（实际 ${收束合计}）`, 收束合计 <= 2);
  ok('收束态: 不再授权"优先选日常"', !收束文本.includes(授权));
  ok('收束态: 不再催"该让它有事发生了"', !收束文本.includes(该来事));

  // ③ 已完结态：该说的只有"开新章"；"让计划高潮落地"是**过时指令**（高潮已经落地了）
  const 完结文本 = 结构提醒(已完结, 80).join('\n');
  check('已完结: "该收章" 0 次', 计数(完结文本, 收紧), 0);
  check('已完结: "开新章" 1 次', 计数(完结文本, '开新章'), 1);
  ok('已完结: 不出现"计划高潮落地"（会诱导导演回去再演一次高潮）', !完结文本.includes('计划高潮落地'));

  // ④ 发言者选择本身可测（三档 + 无）
  check('发言者: 已完结 → 章长度·开新章', 选收章发言者(已完结), '章长度·开新章');
  check('发言者: 收束 → 章长度·收束预算', 选收章发言者(收束), '章长度·收束预算');
  check('发言者: 超期 → 幕纲落后', 选收章发言者(真机68()), '幕纲落后');
  check('发言者: 未超期未收束 → 无', 选收章发言者(账本({ 已分析轮数: 10, 章回: { 章号: 1, 主题: '', 计划高潮: '', 进度: '推进', 起始场: 1, 幕纲: 四幕, 当前幕号: 2 } as any })), '无');
}

console.log('\n[5] 生活幕授权 vs 中点裁决（第三条让位，判据独立）');
{
  const 四幕中 = [幕('事件'), 幕('生活'), 幕('事件'), 幕('事件')];
  const 基章回: any = {
    章号: 1, 主题: '', 计划高潮: '', 进度: '推进', 起始场: 1, 幕纲: 四幕中, 当前幕号: 2,
    中点: { 类型: '假胜利', 内容: '以为赢了其实是陷阱', 过了: false },
  };
  // 10 场 / 4 幕 = 预算 12 → 未超期；幕号 2 >= ceil(4/2)=2 → 中点到期
  const 未兑现 = 账本({ 已分析轮数: 10, 章回: { ...基章回 } });
  const 文本 = 结构提醒(未兑现, 10).join('\n');
  ok('中点到期: 不再说"什么都没发生"（那句许可已撤）', !文本.includes('什么都没发生'));
  ok('中点到期: 中点那条仍在说话（"该让它发生"）', 文本.includes('该让它发生'));
  ok('中点到期: 仍点名"生活幕"（保住幕型信息，不是整条删）', 文本.includes('生活幕'));
  ok('中点到期: 说清"先把中点兑现掉"', 文本.includes('中点到期'));
  ok('中点到期: 不同时出现"可以空"与"该发生"这两个相反许可', !(文本.includes('什么都没发生') && 文本.includes('该让它发生')));

  // 反向：中点已兑现 → 授权必须回来（证明只在中点到期时让位，不是永久关掉）
  const 已兑现 = 账本({ 已分析轮数: 10, 章回: { ...基章回, 中点: { ...基章回.中点, 过了: true } } });
  ok('中点已兑现: 授权回来', 结构提醒(已兑现, 10).join('\n').includes('什么都没发生'));

  // 已超期 → 走"本章已经演太久"那条，不许冒出中点让位的措辞
  const 超期 = 账本({ 已分析轮数: 60, 章回: { ...基章回 } });
  const 超期文本 = 结构提醒(超期, 60).join('\n');
  ok('超期态: 走"本章已经演太久"', 超期文本.includes('本章已经演太久'));
  ok('超期态: 不冒中点让位的措辞', !超期文本.includes('中点到期'));
}

console.log('\n[6] 生活幕授权 vs 日常拖太久（未超期、未收束的那个窗口）');
{
  const 位 = (文本: string, 词: string) => 文本.split(词).length - 1;
  const 幕纲 = [幕('事件'), 幕('生活'), 幕('事件'), 幕('事件')];
  const 日常若干 = (n: number) => Array.from({ length: n }, () => '日常');
  const 造 = (场: number, 幕号: number, 节拍数: number) =>
    账本({
      已分析轮数: 场,
      章回: { 章号: 1, 主题: '', 计划高潮: '', 进度: '推进', 起始场: 1, 幕纲, 当前幕号: 幕号 } as any,
      张力: { 当前: 2, 距上次高潮楼层: 0, 连续低张力: 0, 最近节拍: 日常若干(节拍数) as any },
    });

  // ① A 场景：生活幕 + 5 场日常 + 未超期(10/12) + 未收束
  const A = 造(10, 2, 5);
  const A文本 = 结构提醒(A, 10).join('\n');
  check('A: 「什么都没发生」计数 0', 位(A文本, '什么都没发生'), 0);
  check('A: 「该让它有事发生」计数 0（二选一，只留一句）', 位(A文本, '该让它有事发生'), 0);
  ok('A: 由生活幕那句改口来说（保住幕型信息）', A文本.includes('是生活幕'));
  ok('A: 把可数事实摆出来（连续 5 场空着）', A文本.includes('连续 5 场空着'));
  ok('A: 给出路（一次转折 / 换一个节拍）', A文本.includes('给它一次转折'));

  // ② 边界：4 场 → 授权在；5 场 → 授权不在
  const 四场 = 造(10, 2, 4);
  check('边界: 4 场日常 → 授权句在（计数 1）', 位(结构提醒(四场, 10).join('\n'), '什么都没发生'), 1);
  check('边界: 5 场日常 → 授权句不在（计数 0）', 位(A文本, '什么都没发生'), 0);

  // ③ 反向（一票否决）：事件幕 + 5 场日常 → 拖太久照旧响，且不许冒"生活幕"
  const B = 造(10, 1, 5);
  const B文本 = 结构提醒(B, 10).join('\n');
  ok('B: 拖太久照旧响', B文本.includes('该让它有事发生'));
  ok('B: 不出现"生活幕"', !B文本.includes('生活幕'));

  // ④ 不误伤：超期态仍走"本章已经演太久"，不许冒"连续 N 场空着"
  const C = 造(60, 2, 5);
  const C文本 = 结构提醒(C, 60).join('\n');
  ok('C: 仍是"本来是生活幕…本章已经演太久"', C文本.includes('本章已经演太久'));
  ok('C: 不许冒"连续 N 场空着"', !C文本.includes('场空着'));
}

