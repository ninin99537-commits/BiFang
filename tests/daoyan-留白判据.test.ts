console.log('\n[8] ⑨ 文案三分支（隔天===0 是无人看守区，单独一条）');
{
  const 造行 = (天数: number, 最后行动天: number) => {
    const 账 = 账本({
      章回: { 幕纲: 幕纲('事件'), 当前幕号: 10 } as any,
      世界时间: { 天数, 文本: '' } as any,
      冲突: [冲突({ 最后行动幕: 5, 最后行动天 }) as any],
    });
    return 结构提醒(账, 11).filter(x => x.includes('让对手先动手')).join('');
  };
  const 未催 = 造行(30, 0);
  ok('⑨ 最后行动天=0 → 「还没催过它出手」', 未催.includes('还没催过它出手'));
  ok('⑨ 且不含天数（不许输出「已 30 天」）', !未催.includes('已 30 天') && !未催.includes('天没'));
  ok('⑨ 催过且过了 5 天 → 「已 5 天没催它出手」', 造行(30, 25).includes('已 5 天没催它出手'));
  const 同天 = 造行(30, 30);
  ok('⑨ 同一天刚催过（隔天=0）→ 「仍未出手」，不许「已 0 天」', 同天.includes('仍未出手') && !同天.includes('已 0 天'));
  const 倒流 = 造行(10, 30);
  ok('⑨ 天数倒流（隔天夹到 0）→ 「仍未出手」，不许「已 0 天」', 倒流.includes('仍未出手') && !倒流.includes('已 0 天'));
}

