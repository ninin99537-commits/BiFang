let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) { pass++; console.log('  PASS  ' + label); }
  else { fail++; console.log('  FAIL  ' + label + '\n        期望 ' + JSON.stringify(expected) + '\n        实际 ' + JSON.stringify(actual)); }
}
function ok(label: string, cond: boolean) { check(label, !!cond, true); }

const 幕纲 = (类型: string) => ['第1幕｜类型: ' + 类型 + '｜目标:t'];
const 账本 = (部分: Record<string, any> = {}): 导演账本 =>
  ({
    ...emptyData(),
    已分析轮数: 10,
    章回: { 章号: 1, 主题: 'x', 计划高潮: '', 进度: '推进', 起始场: 1, 幕纲: 幕纲('生活'), 当前幕号: 1, ...(部分.章回 ?? {}) },
    ...部分,
  } as 导演账本);

const 造 = (账: 导演账本, 导演节拍: string) =>
  构造本幕指令({
    旧指令: null,
    下一幕: { 节拍: 导演节拍, 硬性要求: '去集市买盐' },
    账本: 账,
    核验: { 已执行: true, 顶回冲突: '', 说明: '', 主角死亡: false, 核验来源: '明确' } as any,
    档位: 3,
    红线: [],
    楼层: 20,
    暂停注入: false,
  });

// 三种张力状态（张力曲线 / 高潮后代价 的触发条件）
// ⚠️ 尾部**不能**是「高潮」：否则 rule4（高潮后必有代价）同时成立，① 实际测的是 rule4 ——
// 那样删 rule4 会让 ① 和 ③ 一起红，归因就脏了（2026-11-13 需求方实测）。
const 连续高 = { 当前: 9, 距上次高潮楼层: 1, 连续低张力: 0, 最近节拍: ['受挫', '反转', '受挫'] };
const 连续低 = { 当前: 2, 距上次高潮楼层: 9, 连续低张力: 3, 最近节拍: ['小胜', '小胜', '小胜'] };
const 高潮后 = { 当前: 9, 距上次高潮楼层: 0, 连续低张力: 0, 最近节拍: ['小胜', '高潮'] };

// ---------------------------------------------------------------------------
console.log('\n[1] 三条强制改写：生活幕 + 导演要日常 → 节拍必须保住「日常」');
{
  check('① rule1 高（否则会被改成「余波」）', 造(账本({ 张力: 连续高 as any }), '日常').指令?.节拍, '日常');
  check('② rule1 低（否则会被改成「阴影」）', 造(账本({ 张力: 连续低 as any }), '日常').指令?.节拍, '日常');
  check('③ rule4 高潮后（否则会被改成「余波」）', 造(账本({ 张力: 高潮后 as any }), '日常').指令?.节拍, '日常');
  // 对照：同样的账本，导演要的不是日常 → 改写照旧发生（证明上面三条不是"规则失效")
  // 对照必须把幕纲换成「事件」：否则左腿（幕纲生活）仍然要留白，改写本来就不该发生。
  const 事件账 = (张力: any) => 账本({ 张力, 章回: { 幕纲: 幕纲('事件'), 当前幕号: 1 } as any });
  check('对照 ①: 幕纲事件 + 导演要「受挫」→ 仍被改成余波', 造(事件账(连续高), '受挫').指令?.节拍, '余波');
  check('对照 ②: 幕纲事件 + 导演要「受挫」→ 仍被改成阴影', 造(事件账(连续低), '受挫').指令?.节拍, '阴影');
  check('对照 ③: 幕纲事件 + 导演要「受挫」→ 仍被改成余波', 造(事件账(高潮后), '受挫').指令?.节拍, '余波');
}

console.log('\n[2] ④a/④b 两条腿各来一次「只有它为真」（OR 条件必须拆开测）');
{
  // ④a 左腿：幕纲生活 + 导演要【非日常】
  check('④a 幕纲生活 + 导演要「受挫」→ 要留白', 要留白(账本({ 章回: { 幕纲: 幕纲('生活'), 当前幕号: 1 } as any }), '受挫'), true);
  // ④b 右腿：幕纲事件 + 导演要【日常】
  check('④b 幕纲事件 + 导演要「日常」→ 要留白', 要留白(账本({ 章回: { 幕纲: 幕纲('事件'), 当前幕号: 1 } as any }), '日常'), true);
  // 两条腿都不成立
  check('幕纲事件 + 导演要「受挫」→ 不留白', 要留白(账本({ 章回: { 幕纲: 幕纲('事件'), 当前幕号: 1 } as any }), '受挫'), false);
  // 口径：幕纲没标类型 = 腿① 不成立，仍看腿②（老账本行为零变化）
  check('口径: 幕纲未标 + 导演要「受挫」→ 不留白（老账本行为不变）', 要留白(账本({ 章回: { 幕纲: ['第1幕｜目标:t'], 当前幕号: 1 } as any }), '受挫'), false);
  check('口径: 幕纲未标 + 导演要「日常」→ 留白（腿② 仍然成立）', 要留白(账本({ 章回: { 幕纲: ['第1幕｜目标:t'], 当前幕号: 1 } as any }), '日常'), true);
  check('空账本 / null 不炸', 要留白(null), false);
  ok('是生活幕 仍是同一份实现（从 字段表 导出）', typeof 是生活幕 === 'function');
}

console.log('\n[3] ⑫ 收束守卫：**两个夹具各打一条路**（单夹具会让主路径和兜底互相掩盖）');
{
  // 2026-11-13 需求方实测：一个夹具（收束已用 10 ≥ 预算 8）会同时命中
  //   :753 主路径（躲债节拍含「日常」）和 :773 兜底（预算用尽）→ 删任一条，另一条兜住 → 双变异都打不中。
  // 所以拆成两个夹具，并用 收章 作为**路径证据**（它只在兜底那支被置 true）。
  const 收束账 = (已分析轮数: number) =>
    账本({ 已分析轮数, 章回: { 进度: '收束', 收束起始场: 1, 幕纲: 幕纲('生活'), 当前幕号: 1 } as any });

  // ⑫a 主路径：收束已用 = 5 < 8 → 只有 :753 能改（预算没用尽，兜底不跑）
  const 主路 = 造(收束账(5), '日常');
  ok('⑫a 收束 + 导演要日常（预算未用尽）→ 节拍 ∈ {高潮, 兑现伏笔}（实际: ' + 主路.指令?.节拍 + '）', ['高潮', '兑现伏笔'].includes(String(主路.指令?.节拍)));
  check('⑫a 收章 === false（**路径证据**：证明兜底没跑）', (主路 as any).收章, false);

  // ⑫b 兜底：导演要「受挫」不在 躲债节拍['日常','小胜'] 里 → 主路径跳过；预算用尽 → :778 兜底改高潮
  const 兜底 = 造(收束账(10), '受挫');
  ok('⑫b 收束 + 导演要受挫（预算用尽）→ 节拍 ∈ {高潮, 兑现伏笔}（实际: ' + 兜底.指令?.节拍 + '）', ['高潮', '兑现伏笔'].includes(String(兜底.指令?.节拍)));
  check('⑫b 收章 === true（**路径证据**：证明兜底真跑了）', (兜底 as any).收章, true);
}

console.log('\n[4] 属性式穷举：张力 × 幕纲 × 进度 全组合，节拍必须落在允许集合里');
{
  // 允许集合（不是布尔白名单）：收束期 ∈ {高潮,兑现伏笔}；其余必须 === 日常
  const 允许集合 = (组合: { 进度: string }) => (组合.进度 === '收束' ? ['高潮', '兑现伏笔'] : ['日常']);
  // ⚠️ 连续高 与 高潮后 现在是**两条独立路径**（前者的尾部不是高潮 → rule1；后者 → rule4）。
  // 早先两者都以高潮结尾，实际只覆盖了 3 条独立路径（需求方 2026-11-13 指出）。
  const 张力们 = [['无', { 当前: 5, 距上次高潮楼层: 3, 连续低张力: 0, 最近节拍: ['小胜'] }], ['连续高', 连续高], ['连续低', 连续低], ['高潮后', 高潮后]] as [string, any][];
  const 幕型们 = ['事件', '生活', '未标'];
  const 进度们 = ['推进', '收束'];
  let 组数 = 0;
  for (const [张名, 张力] of 张力们) {
    for (const 型 of 幕型们) {
      for (const 进度 of 进度们) {
        const 账 = 账本({
          张力: 张力 as any,
          章回: { 进度, 收束起始场: 1, 幕纲: 型 === '未标' ? ['第1幕｜目标:t'] : 幕纲(型), 当前幕号: 1 } as any,
        });
        const 节拍 = 造(账, '日常').指令?.节拍 ?? '(空)';
        const 允许 = 允许集合({ 进度 });
        组数 += 1;
        ok('[' + 张名 + '×' + 型 + '×' + 进度 + '] 节拍 ' + 节拍 + ' ∈ {' + 允许.join(',') + '}', 允许.includes(节拍));
      }
    }
  }
  check('穷举组数 = 4×3×2', 组数, 24);
}

