/**
 * 两条不变量一起断言。
 * 第 4 行是**防空跑**：如果这个场景根本没触发任何 调整，那么"调整没泄漏"恒真，用例毫无价值。
 */
function 通道隔离(标签: string, r: { 指令: any; 调整: string[] }) {
  const 建议 = String(r.指令?.硬性要求 ?? '');
  const 裁定 = (r.指令?.硬约束 ?? []).join('\n');
  const 正文 = `${裁定}\n${建议}`;
  ok(`${标签}: 本轮确实触发了代码调整(否则本用例空跑)`, r.调整.length > 0);
  check(`${标签}: 调整 一项都没漏进 硬性要求(建议通道)`, r.调整.filter(项 => 建议.includes(项)), []);
  check(`${标签}: 调整 一项都没漏进 硬约束(裁定通道) —— 诊断/裁定/建议 三通道互不串`, r.调整.filter(项 => 裁定.includes(项)), []);
  ok(`${标签}: 正文不带「（代码规则）」前缀`, !正文.includes('（代码规则）'));
}

