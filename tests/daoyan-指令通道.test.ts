// 这种**代码在跟导演对话**的句子 —— 对它零信息。
//
// 修法：删掉 `尾`，把误投的两条（不保送、日常+必演边界）搬回 `块`。
// 观众由**数组**决定（结构性事实），不靠每个 push site 自己判断。
