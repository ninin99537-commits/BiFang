// 这份用例钉两件事（都不依赖词表，只对实际数据做子串比对）：
//   [1] 不泄漏：`调整` 的任何一项都不出现在 `硬性要求` 里；
//   [2] 不丢失：`块` 的产出必须出现在 `硬性要求` 里（搬移时别把演员契约弄丢）。
