// 彼方 · 事实档案(面板「一致性」页的视图逻辑) —— 以前这段活在壳和页面里, 只能点开面板看效果。
//
// 钉住的四件事:
//   ① 所有 NPC × 所有事务 摊平成"一条承诺一行"(含旧格式字符串的迁移);
//   ② 分组与排序(已过期按欠得最久, 进行中按最快到期, 最近了结按存于日期);
//   ③ 紧迫度文案(已过期 N 天 / 今天到期 / 还剩 N 天 / 已挂 N 天);
//   ④ 逐轮变动标记(本轮新增 / 本轮已完成)。
import { 事实档案 } from '../src/彼方_NPC幕后生命状态系统/一致性面板';

let pass = 0;
let fail = 0;
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}
function ok(名: string, 条件: boolean) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}`);
  }
}
/** 只留断言要看的字段, 免得整行快照噪音太大 */
const 摘要 = (行: any[]) => 行.map(x => [x.名, x.编号, x.紧迫, x.逾期, x.标记]);

console.log('\n[1] 摊平: 所有 NPC × 所有事务 → 一条承诺一行');
{
  const 数据 = {
    剧情时间: '2026-01-10 12:00',
    NPC: {
      甲: {
        未完成事项: [
          { 编号: 'T1', 时间: '2026-01-05', 内容: '2026-01-12 交房租', 状态: '进行中' },
          { 编号: 'T2', 时间: '2026-01-06', 内容: '2026-01-08 还书', 状态: '进行中' },
          { 编号: 'T3', 时间: '2026-01-07', 内容: '给女儿买玩偶', 状态: '已完成' },
        ],
        未完成事项变动: 'T3:已完成;T4:新增',
      },
      乙: { 未完成事项: '答应周五同行' }, // 旧格式字符串 → 迁移成一条进行中
      丙: {},
    },
  };
  const 档 = 事实档案(数据);
  eq('总条数(4 条: 甲 3 + 乙 1)', 档.总条数, 4);
  eq('人数(丙 没有账)', 档.人数, 2);
  eq('进行中数', 档.进行中数, 3);
  eq('过期数', 档.过期数, 1);
  eq('分组顺序: 已过期 / 进行中 / 最近了结', 档.分组.map(组 => 组.key), ['late', 'ongoing', 'done']);
  eq('已过期', 摘要(档.分组[0].行), [['甲', 'T2', '已过期 2 天', true, '']]);
  eq('进行中: 有约定日期的按到期排在前', 摘要(档.分组[1].行), [
    ['甲', 'T1', '还剩 2 天', false, ''],
    ['乙', 'T1', '', false, ''],
  ]);
  eq('最近了结带本轮变动标记', 摘要(档.分组[2].行), [['甲', 'T3', '', false, '本轮已完成']]);
  // 行键: 人名 + 编号, 渲染时不会撞
  eq('行键唯一', new Set(档.分组.flatMap(组 => 组.行.map(行 => 行.键))).size, 4);
  // 类名给模板做样式(状态类 的唯一用途)
  eq('已作废/已完成的类名', 档.分组[2].行[0].类, 'is-done');
  eq('进行中的类名', 档.分组[1].行[0].类, 'is-ongoing');
}

console.log('\n[2] 边界: 没有账 / 没有剧情时间 / 缺字段');
{
  eq('空数据', 事实档案({ NPC: {}, 剧情时间: '' }).分组, []);
  eq('null 不炸', 事实档案(null).总条数, 0);
  // 剧情时间缺失: 紧迫度算不出来, 但不能把条目丢掉
  const 无时间 = 事实档案({ NPC: { 甲: { 未完成事项: [{ 编号: 'T1', 内容: '2026-01-12 交房租', 状态: '进行中' }] } } });
  eq('没有剧情时间也照样列出来', 无时间.总条数, 1);
  eq('没有剧情时间就没有紧迫度文案', 无时间.分组[0].行[0].紧迫, '');
  eq('没有剧情时间就不判过期', 无时间.过期数, 0);
  // 今天到期: 约定日期 == 剧情日期
  const 今天 = 事实档案({
    剧情时间: '2026-01-12 09:00',
    NPC: { 甲: { 未完成事项: [{ 编号: 'T1', 时间: '2026-01-01', 内容: '2026-01-12 交房租', 状态: '进行中' }] } },
  });
  eq('今天到期', 今天.分组[0].行[0].紧迫, '今天到期');
  eq('今天到期不算逾期', 今天.分组[0].行[0].逾期, false);
}

console.log('\n[3] 没有约定日期时: 按"挂了多久"提示, 挂满老化天数算逾期');
{
  const 数据 = {
    剧情时间: '2026-01-10 12:00',
    NPC: {
      甲: { 未完成事项: [{ 编号: 'T1', 时间: '2026-01-01', 内容: '洗完澡后把话问清楚', 状态: '进行中' }] },
      乙: { 未完成事项: [{ 编号: 'T1', 时间: '2026-01-09', 内容: '给花浇水', 状态: '进行中' }] },
    },
  };
  const 档 = 事实档案(数据);
  const 行 = (名: string) => 档.分组.flatMap(组 => 组.行).find(x => x.名 === 名)!;
  eq('挂了 9 天', 行('甲').紧迫, '已挂 9 天');
  eq('挂满老化天数(7)算逾期', 行('甲').逾期, true);
  eq('挂 1 天没逾期', 行('乙').逾期, false);
  ok('逾期的那条排在已过期组', 档.分组[0].行.some(x => x.名 === '甲'));
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0)
  process.exit(1);
