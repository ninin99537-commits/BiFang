// 彼方 · 台账老化与近似去重(改进方案第 3 节)
import { 合并台账, 近似重复, 待核对事务, 老化天数, 承诺紧迫度 } from '../src/彼方_NPC幕后生命状态系统/事务台账';

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) { pass++; console.log(`  PASS  ${label}`); }
  else { fail++; console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`); }
}
const 事务 = (编号: string, 时间: string, 内容: string, 状态 = '进行中') => ({ 编号, 时间, 内容, 状态 });

console.log('\n[1] 近似重复');
check('换说法的同一件事', 近似重复('周六带女儿去图书馆还绘本', '周六带女儿去图书馆还那本绘本'), true);
check('包含关系(短的 ≥6 字)', 近似重复('给女儿买生日礼物', '给女儿买生日礼物玩偶'), true);
check('不同的事', 近似重复('给女儿买生日礼物', '交下周的设计稿'), false);
check('日期不同 → 两件事', 近似重复('10-19 带女儿去图书馆', '10-26 带女儿去图书馆'), false);
check('短内容不靠包含', 近似重复('买菜', '买菜刀'), false);

console.log('\n[2] 合并时近似重复不新开条目');
{
  const 库 = [事务('T1', '2026-10-15', '周六带女儿去图书馆还绘本')];
  const 新 = 合并台账(库 as any, [{ 内容: '周六带女儿去图书馆还那本绘本' }], '2026-10-16 10:00');
  check('仍只有一条', 新.length, 1);
  const 收束 = 合并台账(库 as any, [{ 内容: '周六带女儿去图书馆还那本绘本', 状态: '已完成', 结果: '还了' }], '2026-10-19 10:00');
  check('近似命中可收束', [收束.length, 收束[0].状态, 收束[0].结果], [1, '已完成', '还了']);
  const 已办 = [事务('T1', '2026-10-01', '周六带女儿去图书馆还绘本', '已完成')];
  const 再开 = 合并台账(已办 as any, [{ 内容: '周六带女儿去图书馆还那本绘本' }], '2026-10-16 10:00');
  check('近似只比进行中: 已办的不吞新承诺', 再开.length, 2);
}

console.log('\n[3] 待核对');
{
  check('老化天数 7', 老化天数, 7);
  const 账 = [
    事务('T1', '2026-10-15', '10-19 周六带女儿去图书馆还绘本'),
    事务('T2', '2026-10-05', '帮邻居修水管'),
    事务('T3', '2026-10-18', '给女儿买生日礼物'),
    事务('T4', '2026-10-01', '旧的已办', '已完成'),
  ];
  check('约定日期已过 / 挂满 7 天; 已办不算', 待核对事务(账, '2026-10-20 09:00'), [
    { 编号: 'T1', 原因: '约定日期已过 1 天' },
    { 编号: 'T2', 原因: '已挂 15 天' },
  ]);
  check('取剧情时间段的结束日', 待核对事务([事务('T2', '2026-10-05', '帮邻居修水管')], '2026-10-11 22:00 至 2026-10-12 08:00').map(x => x.编号), ['T2']);
  check('没有剧情时间 → 不判', 待核对事务(账, ''), []);
}

console.log('\n[4] 承诺紧迫度(总账用)');
{
  check('还剩 2 天', 承诺紧迫度({ 内容: '10-20 晚 7 点还书', 时间: '2026-10-08' }, '2026-10-18 12:00'), { 约定: '2026-10-20', 剩余天数: 2, 已挂天数: 10 });
  check('已过期 3 天', 承诺紧迫度({ 内容: '10-19 还绘本' }, '2026-10-22 08:00').剩余天数, -3);
  check('今天到期', 承诺紧迫度({ 内容: '10-20 交稿' }, '2026-10-20 09:00').剩余天数, 0);
  check('内容没有日期', 承诺紧迫度({ 内容: '把后窗合页换掉', 时间: '2026-10-09' }, '2026-10-18 12:00'), { 约定: '', 剩余天数: null, 已挂天数: 9 });
  check('没有剧情时间 → 不猜', 承诺紧迫度({ 内容: '10-20 还书', 时间: '2026-10-08' }, ''), { 约定: '', 剩余天数: null, 已挂天数: null });
  check('全年份写法', 承诺紧迫度({ 内容: '2026-10-25 取眼镜' }, '2026-10-18 12:00').剩余天数, 7);
}
console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0) process.exit(1);
