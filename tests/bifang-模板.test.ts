/** 静默跑一遍（不打印清单） */
function 跑(额外: Record<string, any> = {}) {
    const 原I = console.info;
    const 原T = console.table;
    const 原W = console.warn;
    console.info = () => {};
    console.table = () => {};
    console.warn = () => {};
    try {
        return buildUpdateMessages(造输入(额外) as any);
    }
    finally {
        console.info = 原I;
        console.table = 原T;
        console.warn = 原W;
    }
}

