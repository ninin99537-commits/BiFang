console.log('\n[I3] 默认段列表展开后，与**基准快照**逐字节一致');
{
    // ── 这条为什么是刹车 ──
    //  模板化把"规则正文"从零件搬进模板文字。搬家的唯一证明就是
    //  **默认模板展开后与搬家前逐字节相同** —— 否则"只是换了位置"这句话不成立。
    //
    //  ⚠ **基准重采过三次**（每次都是用户裁定的有意行为变更，各自单独 commit）：
    //    ① 去伪装（`bifang-prompt-去伪装后.json`）
    //    ② 模板化（本次改造本身）
    //    ③ **删默认模板里的玩家输入段**（用户 2026-11-19「感觉可以删」）
    //       现在用 `bifang-prompt-模板化后.json`。
    //
    //  第三次的后果（必须写进自测清单）：
    //  **模型从此读不到玩家本轮说的话，只能靠正文（AI 回复）。**
    //  失效场景：玩家说"我把信交给泰丝"，AI 回"她接过信…"——正文没名字，
    //  模型不知道"她"是谁 → 漏认泰丝，她的状态不更新，**而且不报错**。
    //  用户要盯的：跑 5–10 轮，看有没有"玩家明确提到某个名字、但那人这轮没被更新"。
    const 快照 = JSON.parse(快照文本) as Record<string, { messages: { role: string; content: string }[]; 工具说明: string | null }>;
    const 组合们: [string, Record<string, any>][] = [
        ['默认', {}],
        ['带场景判断', { context: '主角走进广场。' }],
        ['全进工具', { 规则进工具: true }],
        ['全进工具带场景', { 规则进工具: true, context: '主角走进广场。' }],
        ['生理开', { physioEnabled: true }],
    ];
    for (const [名, 额外] of 组合们) {
        const 期望 = 快照[名];
        ok(`[I3] 快照里有「${名}」这一组`, !!期望);
        if (!期望)
            continue;
        const 实际 = 跑(额外);
        eq(`[I3] ${名}: messages 条数`, 实际.messages.length, 期望.messages.length);
        const 条数 = Math.min(实际.messages.length, 期望.messages.length);
        for (let i = 0; i < 条数; i++) {
            eq(`[I3] ${名}: 第 ${i + 1} 条 role`, 实际.messages[i].role, 期望.messages[i].role);
            ok(`[I3] ${名}: 第 ${i + 1} 条内容逐字节相同`,
                实际.messages[i].content === 期望.messages[i].content,
                `实际 ${实际.messages[i].content.length} 字 / 期望 ${期望.messages[i].content.length} 字`);
        }
        eq(`[I3] ${名}: 工具说明逐字节相同`, 实际.工具说明 ?? null, 期望.工具说明);
    }
}

