console.log('\n[I3] 默认模板展开后，与现在的产物逐字节一致');
{
    // ── 这条为什么是刹车 ──
    //  模板化把"规则正文"从零件搬进模板文字。搬家的唯一证明就是
    //  **默认模板展开后与搬家前逐字节相同** —— 否则"只是换了位置"这句话不成立。
    //
    //  判据用的是 `buildUpdateMessages` **不给模板**时的产物（= 现在实发的形状），
    //  而不是快照文件。理由：快照是"零件化之前"采的，中间已经过了好几轮有意的行为变更
    //  （去伪装、删登记归档）；拿它比会红在那些变更上，而那不是模板的错。
    //  **模板的判据应该是"与当前的产物相同"** —— 那才是"搬家没搬坏"。
    const 组合们: [string, Record<string, any>][] = [
        ['默认', {}],
        ['带场景判断', { context: '主角走进广场。' }],
        ['有世界书', { worldbook: '世界书内容' }],
        ['有轨迹', { recentTrace: '轨迹内容' }],
        ['生理开', { physioEnabled: true }],
        ['有恋爱对象', { 恋爱对象名单: ['甲'] }],
        ['全开', { physioEnabled: true, 恋爱对象名单: ['甲'], context: '玩家走进广场', worldbook: 'WB', recentTrace: '轨迹' }],
        ['全进工具', { 规则进工具: true }],
        ['全进工具+场景', { 规则进工具: true, context: '玩家走进广场' }],
    ];
    for (const [名, 额外] of 组合们) {
        // ① 不给模板（现在实发的路）
        const 现状 = 跑(额外);
        // ② 给默认模板（模板化之后的路）
        const 用模板 = 跑({ ...额外, 模板: 默认模板 });
        eq(`[I3] ${名}: messages 条数`, 用模板.messages.length, 现状.messages.length);
        const 条数 = Math.min(用模板.messages.length, 现状.messages.length);
        for (let i = 0; i < 条数; i++) {
            eq(`[I3] ${名}: 第 ${i + 1} 条 role`, 用模板.messages[i].role, 现状.messages[i].role);
            ok(`[I3] ${名}: 第 ${i + 1} 条内容逐字节相同`,
                用模板.messages[i].content === 现状.messages[i].content,
                `模板 ${用模板.messages[i].content.length} 字 / 现状 ${现状.messages[i].content.length} 字`);
        }
        eq(`[I3] ${名}: 工具说明一致`, 用模板.工具说明 ?? null, 现状.工具说明 ?? null);
    }
}

