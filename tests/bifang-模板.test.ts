console.log('\n[渲染] 四条规则各自成立');
{
    // ① 整行占位符 → 换成内容，**这一行前面的换行也丢掉**
    {
        const 出 = 渲染段('前一行\n{{彼方:X}}\n后一行', 名 => (名 === 'X' ? '内容' : ''));
        // 内容没有前导 `\n\n` 时，结果是 "前一行内容\n后一行" —— 占位符那一行的换行被吃掉了。
        // 这正是实测出来的行为：真实零件的内容**自带** `\n\n`，所以吃掉模板的换行才对得上。
        eq('[渲染①] 整行占位符吃掉它前面的换行', 出, '前一行内容\n后一行');
        // 自证：若不吃换行会是 "前一行\n内容\n后一行"
        ok('[渲染①/自证] 不吃换行的话会多一个', ('前一行' + '\n' + '内容' + '\n' + '后一行') !== 出);
        // 真实零件的内容自带 \n\n → 接缝正好是两行分隔
        const 真 = 渲染段('前一行\n{{彼方:X}}\n后一行', 名 => (名 === 'X' ? '\n\n内容' : ''));
        eq('[渲染①] 内容自带 \\n\\n 时接缝是两行分隔', 真, '前一行\n\n内容\n后一行');
    }

    // ② 整行占位符展开为空 → 整行消失
    {
        const 出 = 渲染段('前一行\n{{彼方:X}}\n后一行', () => '');
        eq('[渲染②] 空占位符那一整行消失', 出, '前一行\n后一行');
        // 负样本：非空时那一行要在
        const 有 = 渲染段('前一行\n{{彼方:X}}\n后一行', () => '值');
        ok('[渲染②/自证] 非空时那一行在', 有.includes('值'), JSON.stringify(有));
    }

    // ②b 行内占位符为空 → **整行也消失**（连同行内其他文字）
    //     这是需求方 #211 ① 明确要的：标签与占位符写同一行，空时一起消失。
    {
        const 出 = 渲染段('前一行\n标签:{{彼方:X}}\n后一行', () => '');
        eq('[渲染②b] 行内空占位符 → 整行消失（连标签一起）', 出, '前一行\n后一行');
        // 负样本：非空时那一行要在
        const 有 = 渲染段('前一行\n标签:{{彼方:X}}\n后一行', () => '值');
        eq('[渲染②b/自证] 非空时那一行还在', 有, '前一行\n标签:值\n后一行');
    }

    // ③ 行内占位符（非空）→ 直接替换，保留行结构
    {
        const 出 = 渲染段('甲:{{彼方:X}} 乙:{{彼方:Y}}', 名 => (名 === 'X' ? '1' : '2'));
        eq('[渲染③] 行内两个占位符都替换', 出, '甲:1 乙:2');
        // 一行里有多个占位符、其中一个是空 → 整行消失（②b 的推广）
        const 混合 = 渲染段('甲:{{彼方:X}} 乙:{{彼方:Y}}', 名 => (名 === 'X' ? '1' : ''));
        eq('[渲染③] 一行里有一个空的 → 整行消失', 混合, '');
    }
}

