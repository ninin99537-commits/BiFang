    //
    //  两次都是"功能删了，说明留着"。要求给一个**可机检的特征**，不是逐句审：
    //  **界面文案里出现「已移除」「已废弃」「不再使用」这类词 = 不合格。**
    //
    // ── 判据怎么排除注释 ──
    //  源码注释里出现这些词是**正常的**（如"消息伪装已移除"是在解释历史）。
    //  注释不会显示给用户，所以按行跳过"纯注释行"（trim 后以 // * /* <!-- 开头）。
    //  ⚠ 这是**近似**：行尾注释（`foo(); // 已移除`）抓不住。
    //  写下来是因为它决定了这条判据的边界 —— 不然下一个人会以为它覆盖全部。
