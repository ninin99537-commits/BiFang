console.log('\n[占位符] 15 个都在模板里；零件表里每个可搬迁零件都有归宿');
{
    const 模板里的 = 模板里的占位符(默认模板);
    // 系统段 4 + 场景判断 1 + 用户段 8 + 生理任务/恋爱任务 2 = 15
    eq('[占位符] 模板里共 15 个', 模板里的.length, 15);
    eq('[占位符] 系统段 4 个', 段里的占位符(默认模板.系统段).length, 4);
    eq('[占位符] 场景判断 1 个', 段里的占位符(默认模板.场景判断).length, 1);
    eq('[占位符] 用户段 10 个', 段里的占位符(默认模板.用户段).length, 10);

    // 每个名字都能在零件表里找到（否则是拼错了）
    const 名表 = new Set(零件表.map(件 => 件.名));
    const 拼错 = 模板里的.filter(名 => !名表.has(名) && 名 !== '生理任务' && 名 !== '恋爱任务');
    eq('[占位符] 没有拼错的名字', 拼错, []);

    // 生理任务/恋爱任务 不是零件表里的零件（它们是 D14 的切片），要单独确认存在
    ok('[占位符] 有 生理任务', 模板含(默认模板, '生理任务'));
    ok('[占位符] 有 恋爱任务', 模板含(默认模板, '恋爱任务'));

    // R6/R7（12 字特征串）**不许**出现在模板里 —— 它们展开不出真内容
    ok('[占位符] 没有 生理说明（12 字特征串）', !模板含(默认模板, '生理说明'));
    ok('[占位符] 没有 恋爱说明（12 字特征串）', !模板含(默认模板, '恋爱说明'));

    // 每个可搬迁零件要么在模板里、要么被 D14 切片覆盖（生理/恋爱任务）、
    // 要么是**身份句**（R1 —— 它是模板里的字，不是占位符；需求方 #215 裁定）
    //
    // ⚠ R6/R7 **故意不在**这个集合里 —— 它们是不可搬迁零件（`可搬迁: false`），
    //    文字散在 R2/R3/R5/D14 内部，而 12 字特征串按 #217 ① 不许进清单。
    //    它们的真实内容通过 生理任务/恋爱任务 两个占位符出去。
    const 被切片覆盖 = new Set(['D14']);
    const 是模板文字 = new Set(['R1']);
    const 缺 = 零件表
        .filter(件 => 件.可搬迁 && !被切片覆盖.has(件.代号) && !是模板文字.has(件.代号))
        .filter(件 => !模板含(默认模板, 件.名))
        .map(件 => 件.代号 + '/' + 件.名);
    eq('[占位符] 每个可搬迁零件都在模板里（或有切片覆盖 / 是模板文字）', 缺, []);

    // R1 身份句作为**模板文字**出现（不是占位符）—— 需求方 #215：「身份句归模板文字」
    ok('[占位符] 身份句是模板里的字', 默认模板.系统段.includes('你是「彼方'), 默认模板.系统段.slice(0, 40));
    ok('[占位符] 身份句没有做成占位符', !模板含(默认模板, '身份句'));
    // 自证：D14 拆了，所以 D14 自己不该以占位符出现
    ok('[占位符] D14 不以占位符出现（已拆成骨架+两个任务）', !模板含(默认模板, '任务指令'));

    // 不可搬迁的（R6/R7）不该有以它们名字命名的占位符
    const 不可搬迁 = 零件表.filter(件 => !件.可搬迁).map(件 => 件.名);
    const 混进清单 = 不可搬迁.filter(名 => 模板含(默认模板, 名));
    eq('[占位符] 不可搬迁零件不以自己的名字进模板', 混进清单, []);
    // 自证：R6/R7 确实在零件表里且不可搬迁
    ok('[占位符/自证] 零件表里确实有不可搬迁的 R6/R7',
       不可搬迁.includes('生理说明') && 不可搬迁.includes('恋爱说明'), JSON.stringify(不可搬迁));
}

