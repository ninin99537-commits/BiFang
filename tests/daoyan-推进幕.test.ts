// 剧情导演 · `最后推进幕` 写的是楼层号（2026-11-12 缺陷）
//
// 病根（需求方取证 `reviews/缺陷-最后推进幕写楼层号.md`）：
//   `账本数据.ts` 状态**变更**分支 `最后推进幕: Number(规范.最后推进幕) || 楼层` ——
//   `楼层` 是本次分析的锚点楼层（真机几百上千），被当成了"幕"。
// 后果不是数字难看，是**功能失效**：`镜头外.ts` 用 `久 = 当前幕 - 上次幕` 做节流，
//   写进 200 之后 `久 = max(0, 9-200) = 0` 恒小于间隔 → 这个 NPC **再也不会**被选中做镜头外推进。
//   而幕数增长远慢于楼层（78 场 ≈ 几百层），等于"一次状态变更 = 他的镜头外线永久停摆"。
//
// 修三处：① 写侧 `|| 楼层` → `|| 本场`；② 迁移侧把存量里的楼层号洗掉（> 当前幕 → 0）；
// ③ 反向钉：`最后推进幕 = 幕号` 必须能被挑中，`= 楼层号` 必须不被挑中。
import { createPinia, setActivePinia } from 'pinia';
import type { 导演账本 } from '../src/剧情导演/schema';
import { emptyData } from '../src/剧情导演/快照';
import { 应用引擎输出, 规范化命运 } from '../src/剧情导演/账本数据';
import { sanitizeSnapshot } from '../src/剧情导演/账本迁移';
import { 挑镜头外候选 } from '../src/剧情导演/镜头外';

(globalThis as any)._ = {
  clamp: (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), hi),
  cloneDeep: (v: any) => (v === undefined ? undefined : JSON.parse(JSON.stringify(v))),
};
(globalThis as any).localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

const 核验 = { 已执行: true, 顶回冲突: '', 说明: '', 主角死亡: false };
const 账本 = (部分: Partial<导演账本> = {}): 导演账本 => ({ ...emptyData(), 已分析轮数: 9, ...部分 });
const 命运 = (部分: Record<string, any> = {}): any => ({
  角色ID: '艾莉', 状态: '活跃', 位置: '别处', 独立目标: ['找到弟弟'], 当前关系: [], 持久后果: [],
  承诺与债务: [], 未竟计划: [], 已知事实引用: [], 状态证据: [], 最后推进幕: 0, ...部分,
});

// ---------------------------------------------------------------------------
console.log('\n[1] 写侧：状态变更 + 楼层 200、当前幕 9 → 最后推进幕 = 10（不是 200）');
{
  for (const 楼层 of [200, 777]) {
    const 旧 = 账本({ 角色命运: [命运({ 状态: '活跃', 最后推进幕: 0 })] });
    const r = 应用引擎输出(
      旧,
      {
        角色命运: [{ 角色ID: '艾莉', 状态: '受伤', 状态证据: [{ 记忆引用: 'AM0003', 楼层: 8, 公开摘要: '她被咬' }] }],
        上一幕核验: 核验,
        下一幕: { 节拍: '受挫' },
      } as any,
      楼层,
      { 正文楼层: [楼层] },
    );
    const 艾莉 = r.账本.角色命运.find(x => x.角色ID === '艾莉')!;
    check(`楼层 ${楼层} → 最后推进幕 = 本场(10)`, 艾莉.最后推进幕, 10);
    ok(`楼层 ${楼层} → 状态确实变更了（不然这条不成立）`, 艾莉.状态 === '受伤');
  }
}

console.log('\n[2] 写侧：状态**未**变 + 楼层 200 → 保持旧值');
{
  const 旧 = 账本({ 角色命运: [命运({ 最后推进幕: 4 })] });
  const r = 应用引擎输出(旧, { 角色命运: [{ 角色ID: '艾莉', 位置: '西街' }], 上一幕核验: 核验, 下一幕: { 节拍: '受挫' } } as any, 200, {});
  const 艾莉 = r.账本.角色命运.find(x => x.角色ID === '艾莉')!;
  check('状态没变 → 最后推进幕 仍是 4', 艾莉.最后推进幕, 4);
  ok('位置改用新值（证明这一轮确实处理了这一条）', 艾莉.位置 === '西街');
}

console.log('\n[3] 迁移侧：老账本 200（楼层号）→ 读回 0');
{
  const 快照 = { ...emptyData(), 已分析轮数: 9, 角色命运: [命运({ 最后推进幕: 200 })] } as any;
  const 读回 = sanitizeSnapshot(快照);
  check('200 > 当前幕 9 → 置 0（当"从未推进"）', 读回.角色命运[0]?.最后推进幕, 0);
}

console.log('\n[4] 迁移侧（判据要能被违反）：老账本 3（正常幕号）→ 读回仍是 3');
{
  const 快照 = { ...emptyData(), 已分析轮数: 9, 角色命运: [命运({ 最后推进幕: 3 })] } as any;
  const 读回 = sanitizeSnapshot(快照);
  check('3 <= 当前幕 9 → 原样保留（不许误清）', 读回.角色命运[0]?.最后推进幕, 3);
  // 边界：正好等于当前幕
  const 边界 = sanitizeSnapshot({ ...emptyData(), 已分析轮数: 9, 角色命运: [命运({ 最后推进幕: 9 })] } as any);
  check('9 === 当前幕 → 保留', 边界.角色命运[0]?.最后推进幕, 9);
  // 我没给当前幕（老调用点）→ 不清洗，等于旧行为
  check('不传当前幕 → 不清洗（老调用点兼容）', 规范化命运(命运({ 最后推进幕: 200 })).最后推进幕, 200);
}

console.log('\n[5] 反向钉（端到端）：楼层号变更过的 NPC，下一幕仍能被挑中');
{
  // 场景 1：修复前的形态（楼层 200 变更过）→ 读回被洗成 0 → 视为"从未推进" → 该被选中
  const 老账本 = sanitizeSnapshot({ ...emptyData(), 已分析轮数: 14, 角色命运: [命运({ 最后推进幕: 200 })] } as any);
  const 选中 = 挑镜头外候选({ 账本: 老账本, 当前幕: 14, 在场: [] });
  check('楼层号污染洗掉后 → 被挑中', 选中.map((x: any) => x.角色ID), ['艾莉']);

  // 场景 2：正常幕号、间隔够了 → 被选中
  const 正常 = 账本({ 已分析轮数: 14, 角色命运: [命运({ 最后推进幕: 10 })] });
  check('最后推进幕=10（幕号）、当前幕 14 → 间隔 4 <5 不选', 挑镜头外候选({ 账本: 正常, 当前幕: 14, 在场: [] }).length, 0);
  const 够久 = 账本({ 已分析轮数: 15, 角色命运: [命运({ 最后推进幕: 10 })] });
  check('最后推进幕=10、当前幕 15 → 间隔 5 够 → 被选中', 挑镜头外候选({ 账本: 够久, 当前幕: 15, 在场: [] }).map((x: any) => x.角色ID), ['艾莉']);

  // 场景 3：**现状**（楼层号没洗）→ 不被选中（这是修复前的错误行为，用它证明这条钉能失败）
  const 污染 = 账本({ 已分析轮数: 14, 角色命运: [命运({ 最后推进幕: 200 })] });
  check('最后推进幕=200（楼层号）→ 不被选中（证明这条钉能失败）', 挑镜头外候选({ 账本: 污染, 当前幕: 14, 在场: [] }).length, 0);
}

console.log('\n[6] 同族第二例：`持久后果.章号` 不许写楼层号');
{
  const 带章 = 账本({
    章回: { 章号: 5, 主题: 'x', 计划高潮: '', 进度: '推进', 起始场: 1, 幕纲: ['第1幕｜类型: 事件'], 当前幕号: 1 } as any,
    角色命运: [命运({ 持久后果: [] })],
  });
  const r1 = 应用引擎输出(
    带章,
    { 角色命运: [{ 角色ID: '艾莉', 持久后果: [{ ID: 'P9', 内容: '腿断了', 状态: '持续' }] }], 上一幕核验: 核验, 下一幕: { 节拍: '受挫' } } as any,
    200,
    {},
  );
  const 后果1 = r1.账本.角色命运.find(x => x.角色ID === '艾莉')?.持久后果 ?? [];
  check('有章回（第 5 章）→ 新后果 章号 = 5（不被楼层改掉）', 后果1[0]?.章号, 5);

  const 无章 = 账本({ 章回: null, 角色命运: [命运({ 持久后果: [] })] });
  const r2 = 应用引擎输出(
    无章,
    { 角色命运: [{ 角色ID: '艾莉', 持久后果: [{ ID: 'P9', 内容: '腿断了', 状态: '持续' }] }], 上一幕核验: 核验, 下一幕: { 节拍: '受挫' } } as any,
    200,
    {},
  );
  const 后果2 = r2.账本.角色命运.find(x => x.角色ID === '艾莉')?.持久后果 ?? [];
  check('章回 null + 楼层 200 → 章号 = 0（不是 200）', 后果2[0]?.章号, 0);
}

// ---------------------------------------------------------------------------
console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0) process.exit(1);
