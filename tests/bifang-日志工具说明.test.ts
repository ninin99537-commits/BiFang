// 彼方 · 日志页必须能看到「工具说明」—— 批次 2026-11-19 波1（用户报的观测缺陷）。
//
// ── 用户的原话 ──
//   「我打开工具调用开关的时候，日志页看到的发送给 AI 的内容只有一行」
//
// ── 原因（实测）──
//   全进工具模式下：
//       messages: 2 条  [system:17, user:18]
//       工具说明: 14513 字
//   而 `更新输入.ts` 拼「请求体」时**只拼了 messages** → 日志页显示的就是那 35 字。
//
//   **用户看到的完全正确 —— 是日志本身漏了 14513 字。**
//
// ── 这条为什么重要 ──
//   日志是"实际发出去的是什么"的唯一证据。**只记 messages 的日志，在工具模式下等于没有日志。**
//   而且它会让排障往错的方向走：用户以为"是不是只发了这么点"，实际发了一万四。
import { readFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const 输入源 = readFileSync(path.join(ROOT, 'src/彼方_NPC幕后生命状态系统/更新输入.ts'), 'utf8');
const 面板源 = readFileSync(path.join(ROOT, 'src/彼方_NPC幕后生命状态系统/日志面板.ts'), 'utf8');
const 页面源 = readFileSync(path.join(ROOT, 'src/彼方_NPC幕后生命状态系统/页面-日志.vue'), 'utf8');

let pass = 0;
let fail = 0;
function ok(名: string, 条件: boolean, 附注?: string) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}${附注 ? `  (${附注})` : ''}`);
  }
}
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}

// ─────────────────────────────────────────────────────────────
console.log('\n[日志] 请求体必须包含「工具说明」');
{
  // ── 结构判据：更新输入.ts 拼请求体时加了工具说明那一段 ──
  ok('[日志] 请求体里拼了【工具说明】', /【工具说明】/.test(输入源));
  // ⚠ 只在非空时才加 —— 没开工具通道时它本来就是空串，加了会出现一个空的段
  ok('[日志] 只在 工具说明 非空时才加那一段', /工具说明 \? \[/.test(输入源),
     '找不到 `工具说明 ? [`');

  // ── 行为判据：用真实拼法算一遍 ──
  const 拼 = (messages: { role: string; content: string }[], 工具说明: string) => [
    ...messages.map(m => `【${m.role === 'system' ? '系统指令' : m.role === 'user' ? '用户' : '助手'}】\n${m.content}`),
    ...(工具说明 ? [`【工具说明】\n${工具说明}`] : []),
  ].join('\n\n────────\n\n');

  const 短消息 = [{ role: 'system', content: '你是彼方。' }, { role: 'user', content: '开始。' }];
  const 大工具说明 = 'x'.repeat(14513);

  const 有工具 = 拼(短消息, 大工具说明);
  const 无工具 = 拼(短消息, '');

  ok('[日志] 有工具说明时请求体包含它', 有工具.includes('【工具说明】'));
  ok('[日志] 有工具说明时请求体 > 14500 字', 有工具.length > 14500, `${有工具.length} 字`);
  ok('[日志] 无工具说明时请求体不含那一段', !无工具.includes('【工具说明】'));
  ok('[日志] 无工具说明时请求体很短（只有 messages）', 无工具.length < 100, `${无工具.length} 字`);

  // ── 自证：旧版拼法（只有 messages）有多短 ──
  const 旧版 = 短消息.map(m => `【${m.role === 'system' ? '系统指令' : '用户'}】\n${m.content}`).join('\n\n────────\n\n');
  ok('[自证] 旧版拼法不含工具说明（这就是那个 bug）', !旧版.includes('工具说明'));
  ok('[自证] 新版比旧版多出一万多字', 有工具.length > 旧版.length + 14000,
     `旧=${旧版.length} 新=${有工具.length}`);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[日志] 「请求形态」那一行能正确数出来');
{
  // ── 这条防什么 ──
  //  光把内容塞进请求体还不够：用户看到「发送 14564 字」但展开只看两行消息，
  //  仍然会以为日志坏了。所以还要告诉他**字数在哪**。
  ok('[日志] 日志面板有 请求形态', /const 请求形态 = computed/.test(面板源));
  ok('[日志] 它数的是分段标题', /【\(系统指令\|用户\|助手\)】/.test(面板源));
  ok('[日志] 它取【工具说明】之后的内容', /【工具说明】\\n\(\[\\s\\S\]\*\)/.test(面板源));
  ok('[日志] 页面里显示它', /请求形态/.test(页面源) && /\{\{ 请求形态 \}\}/.test(页面源));

  // ── 行为判据：复刻同一套数法 ──
  const 数形态 = (请求: string) => {
    if (!请求)
      return '';
    const 段数 = (请求.match(/【(系统指令|用户|助手)】/g) ?? []).length;
    const 工具段 = 请求.match(/【工具说明】\n([\s\S]*)$/);
    if (!工具段)
      return `${段数} 条消息`;
    return `${段数} 条消息 + 工具说明 ${工具段[1].trim().length} 字`;
  };

  const 带工具 = '【系统指令】\n你是彼方。\n\n────────\n\n【用户】\n开始。\n\n────────\n\n【工具说明】\n' + 'x'.repeat(14513);
  const 无工具 = '【系统指令】\n你是彼方。\n\n────────\n\n【用户】\n开始。';

  eq('[日志] 带工具时数出 2 条消息 + 14513 字', 数形态(带工具), '2 条消息 + 工具说明 14513 字');
  eq('[日志] 无工具时只说 2 条消息', 数形态(无工具), '2 条消息');
  eq('[日志] 空日志返回空串', 数形态(''), '');

  // ── 自证：这个数法能区分"有工具说明"和"没有" ──
  ok('[自证] 两种情况的结果确实不同', 数形态(带工具) !== 数形态(无工具));
}

// ─────────────────────────────────────────────────────────────
console.log('\n[日志] 顺带：`规模` 的请求体字数也跟着修了');
{
  // `规模` 里的「请求体 N 字」是拿同一个 `请求体` 算的 ——
  // 所以修好请求体 = 同时修好规模页那个偏小的数字。
  // **同一个 bug 的两个出口，必须一起好。**
  ok('[日志] 规模 用的是同一个 请求体 变量',
     /计算规模\(\{[\s\S]{0,300}?请求体,/.test(输入源),
     '规模 没有用请求体');
  // 自证：如果规模另算一份，这条会红
  ok('[自证] 规模 里没有另拼一份 messages',
     !/计算规模\(\{[\s\S]{0,400}?messages\.map/.test(输入源));
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
process.exit(fail > 0 ? 1 : 0);
