// 剧情导演 · 熔断(2026-11-08)
//
// 用户看到的日志:「引擎已自动暂停(连败达阈值), 自动路径跳过」, 从 06:12 一直刷到 07:32。
//
// 机制本身是对的(连败 3 次 → 暂停自动推进, 别每轮白烧 token), 但旧实现有三处缺陷:
//   ① **死锁**: 暂停后自动路径直接 return, 而"复位"只认"成功一次" —— 不跑就不会成功, 不成功就不复位。
//      用户唯一的出口是面板上那个按钮, 而自动路径只 console.warn, 不弹提示, 等于没有。
//   ② **静默**: 同上, 只有翻控制台才看得见。
//   ③ **半死**: 注入没停, 正文仍拿着一道越来越过期的指令往下演, 账本却已经停了。
//
// 这一轮的修法: 冷却自动放行一次 / 首次暂停弹一次提示 / 熔断期间只剩红线。
import { createPinia, setActivePinia } from 'pinia';
import { empty离线, 熔断可放行, 熔断冷却毫秒, 熔断阈值 } from '../src/剧情导演/运行状态';
import { 计算运行状态 } from '../src/剧情导演/球状态';
import { 应注入的指令文本 } from '../src/剧情导演/注入';
import { injectHostForTest } from '../src/剧情导演/host';
import { emptyData } from '../src/剧情导演/快照';
import { SettingsSchema } from '../src/剧情导演/schema';
import 索引源 from '../src/剧情导演/index.ts?raw';
import 更新源 from '../src/剧情导演/update.ts?raw';
import 注入源 from '../src/剧情导演/注入.ts?raw';
import 界面vue源 from '../src/剧情导演/悬浮球界面.vue?raw';
(globalThis as any)._ = {
  clamp: (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), hi),
  cloneDeep: (v: any) => (v === undefined ? undefined : JSON.parse(JSON.stringify(v))),
};
(globalThis as any).localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

const 默认设置 = SettingsSchema.parse({});
const 暂停中 = (最后失败时间: number) => ({ ...empty离线(), 连败次数: 3, 自动暂停: true, 最后失败原因: '接口超时', 最后失败时间 });

// ---------------------------------------------------------------------------
// ① 冷却放行: 既不死锁, 也不无限烧
// ---------------------------------------------------------------------------
console.log('\n[1] 熔断冷却: 暂停后过了冷却期就放行一次试探');
{
  check('阈值是 3', 熔断阈值, 3);
  check('冷却期 10 分钟', 熔断冷却毫秒, 10 * 60 * 1000);

  const 现在 = 1_700_000_000_000;
  check('没暂停 → 本来就能跑', 熔断可放行(empty离线(), 现在), true);
  check('刚失败 1 分钟 → 不放行(还在冷却)', 熔断可放行(暂停中(现在 - 60_000), 现在), false);
  check('过了 9 分钟 → 仍不放行', 熔断可放行(暂停中(现在 - 9 * 60_000), 现在), false);
  check('正好 10 分钟 → 放行(边界是 >=)', 熔断可放行(暂停中(现在 - 10 * 60_000), 现在), true);
  check('过了 11 分钟 → 放行', 熔断可放行(暂停中(现在 - 11 * 60_000), 现在), true);
  check('没有时间戳(老数据)→ 放行, 不把人锁死', 熔断可放行(暂停中(0), 现在), true);
  check('时间戳是负数(脏数据)→ 放行', 熔断可放行(暂停中(-5), 现在), true);
}

// ---------------------------------------------------------------------------
// ② 接线: 两处自动推进都必须走同一个冷却判断
// ---------------------------------------------------------------------------
console.log('\n[2] 接线: index 与 update 的熔断判断都读 熔断可放行');
{
  ok('index 用它判断是否放行', 索引源.includes('if (!熔断可放行(离线))'));
  ok('index 有"放行一次试探"的日志', 索引源.includes('熔断冷却已过，放行一次试探'));
  ok('index 首次暂停弹提示条(不是只 console.warn)', 索引源.includes('已提示熔断 = true'));
  ok('index 的提示里给出面板按钮与冷却时间', 索引源.includes('恢复自动接管') && 索引源.includes('熔断冷却毫秒'));
  ok('update 也用它(手点重推之外的路径)', 更新源.includes('if (!熔断可放行(离线))'));
  ok('update 不再每轮 toast(提示交给 index 弹一次)', !更新源.includes('面板可「恢复自动接管」'));
  ok('恢复后重置提示标记(修好又坏还要再弹)', 索引源.includes('if (!离线.自动暂停) 已提示熔断 = false'));
}

// ---------------------------------------------------------------------------
// ③ 熔断期间只剩红线: 别再拿过期指令演
// ---------------------------------------------------------------------------
console.log('\n[3] 熔断期间: 本幕指令撤掉, 红线保留');
{
  // 造一份"已熔断"的 chat meta, 让 读离线状态 真的读到自动暂停
  injectHostForTest({
    vars: {
      get: () => ({
        剧情导演: {
          版本: 1,
          快照楼层: [],
          清空层: 0,
          已剧终: false,
          离线: { 连败次数: 3, 最后失败原因: '接口超时', 最后失败时间: Date.now(), 自动暂停: true },
        },
      }),
    } as any,
  });

  const 账 = { ...emptyData(), 当前指令: { 编号: 3, 节拍: '高潮', 硬性要求: '必须打起来' } as any };
  const 有红线 = { ...默认设置, 导演: { ...默认设置.导演, 红线: ['不写性暴力'] } };

  const 文本 = 应注入的指令文本(账, 有红线, false);
  ok('熔断期红线仍然注入', 文本.includes('不写性暴力'));
  ok('熔断期说明写的是"引擎已暂停推进"', 文本.includes('导演引擎已暂停推进'));
  ok('熔断期不再注入节拍/剧情参考', !/本幕节拍|剧情参考/.test(文本));

  check('熔断 + 没有红线 → 空串', 应注入的指令文本(账, 默认设置, false), '');
  ok('接线: 注入层读的是同一个熔断标记', 注入源.includes('读离线状态().自动暂停'));
}

// ---------------------------------------------------------------------------
// ④ 状态条: 离线态要说清"多久后自动试", 以及平静模式还开着这件事
// ---------------------------------------------------------------------------
console.log('\n[4] 离线态文案: 给出冷却剩余与立刻恢复入口');
{
  const 基 = {
    已停用: false,
    已剧终: false,
    自动暂停: true,
    连败次数: 3,
    最后失败原因: '接口超时',
    最后失败时间: Date.now() - 60_000,
    已分析轮数: 10,
    接管轮数: 4,
    锚点楼层: 9,
    引擎调用次数: 3,
    编排中: false,
  };
  const 离 = 计算运行状态(基);
  check('级别仍是 off', 离.级别, 'off');
  ok('明细带冷却剩余分钟', /约 \d+ 分钟后自动再试一次/.test(离.明细));
  ok('明细给出立刻恢复的入口', 离.明细.includes('恢复自动接管'));
  ok('离线压过平静时说明平静还开着', 计算运行状态({ ...基, 平静: true }).明细.includes('平静模式仍开着'));

  const 到点 = 计算运行状态({ ...基, 最后失败时间: Date.now() - 20 * 60_000 });
  ok('冷却已过 → 明说"下一条正文会先试一次"', 到点.明细.includes('已到冷却点'));
  ok('没有时间戳 → 也说会先试一次', 计算运行状态({ ...基, 最后失败时间: 0 }).明细.includes('下一条正文会先试一次'));
}

// ---------------------------------------------------------------------------
// ⑤ 面板的熔断状态必须会自己刷新(2026-11-11 自查)
// ---------------------------------------------------------------------------
console.log('\n[5] 面板/球上的"离线"要跟着推进结果刷新(以前只在点按钮时刷新)');
{
  const 界面源 = 界面vue源;
  ok('推进结束后刷新离线态', /watch\(更新中,[\s\S]{0,200}离线\.value = 读离线状态\(\)/.test(界面源));
  ok('面板打开时刷新离线态', /watch\(panelOpen,[\s\S]{0,160}离线\.value = 读离线状态\(\)/.test(界面源));
  // 反面对照: 只有一个初始化点的话, 熔断后球会一直写着"运行中"
  ok('不是只初始化一次', (界面源.match(/离线\.value = 读离线状态\(\)/g) ?? []).length >= 2);
}

console.log(`\n${fail === 0 ? '全部通过' : '有失败'}  ${pass} pass / ${fail} fail\n`);
if (fail > 0) process.exit(1);
