// 彼方 · 仪表盘「本轮 N 人有变化」必须真的能显示 —— 批次 2026-11-20（需求方 #421 ①）。
//
// ── 这个 bug 是什么 ──
//  `页面-仪表盘.vue` 的模板写着：
//      <small v-if="本轮有变化人数">{{ `本轮 ${本轮有变化人数} 人有变化` }}</small>
//
//  但**面板接口里没有 `本轮有变化人数`** → 页面解构出来是 `undefined`
//  → `v-if` 永远为假 → **那一行从 11-16 到现在一次都没显示过，也不报错**。
//
//  需求方 #421 说它是「这一整天最典型的低能 bug」：
//  一行 UI 文案挂了一周没人发现 —— 因为判据查的是"模板名字能不能解析"，
//  而这条恰好**没在那条判据覆盖的页面上**（`本轮有变化人数` 定义在壳里，页面看不到）。
//
// ── 修法 ──
//  在 `仪表盘面板.ts` 里定义它（不让页面自己算），页面解构出来。
//
// ── 判据 ──
//  ① 面板接口里有 `本轮有变化人数`（类型 + 实现 + 返回值）
//  ② 页面解构了它
//  ③ **行为**：2 个 NPC 有变化 → 值是 2；0 个变化 → 值是 0（`v-if` 为假是对的）
//  ④ 自证：从面板里抠掉它 → ① 必须红
import { computed, ref } from 'vue';
import { createPinia, setActivePinia } from 'pinia';
import { 建仪表盘面板 } from '../src/彼方_NPC幕后生命状态系统/仪表盘面板';

setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function ok(名: string, 条件: boolean, 附注?: string) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}${附注 ? `  (${附注})` : ''}`);
  }
}
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}

/** 造一份最小可用的面板（其余字段给空实现，只测 本轮有变化人数） */
function 造面板(数据: any) {
  return 建仪表盘面板({
    数据: ref(数据),
    更新中: computed(() => false),
    自动建档: computed(() => true),
    头像色号: () => 0,
    newNpcName: ref(''),
    openAddDialog: () => {},
    removeNpc: () => {},
    openNpc: () => {},
    reload: () => {},
    clearAll: () => {},
    clearing: ref(false),
  });
}

// ─────────────────────────────────────────────────────────────
console.log('\n[行为] 2 个 NPC 有变化 → 值是 2');
{
  // ── 这条是本批的核心 ──
  //  判据口径与壳里那份一致：卡的「最后更新」等于全局「最后更新」时刻
  const 面板 = 造面板({
    名单: ['甲', '乙', '丙'],
    NPC: {
      甲: { 最后更新: 1000 }, // 本轮更新过
      乙: { 最后更新: 1000 }, // 本轮更新过
      丙: { 最后更新: 500 },  // 上一轮的
    },
    统计: { 更新次数: 3, 最后更新: 1000 },
    剧情时间: '2026-01-02 12:30',
  });

  eq('★ 本轮有变化人数 = 2', 面板.本轮有变化人数.value, 2);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[行为] 0 个变化 → 值是 0（v-if 为假是对的，那一行不该出现）');
{
  const 面板 = 造面板({
    名单: ['甲'],
    NPC: { 甲: { 最后更新: 500 } },
    统计: { 更新次数: 3, 最后更新: 1000 }, // 全局时刻是 1000，但没有卡匹配
    剧情时间: '',
  });

  eq('本轮有变化人数 = 0', 面板.本轮有变化人数.value, 0);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[行为] 从没更新过（最后更新 = 0）→ 值是 0，不许把所有卡都算成"有变化"');
{
  // ── 这条防一个具体陷阱 ──
  //  如果实现写成"卡的 最后更新 === 全局 最后更新"，而两者都是 0（新装用户），
  //  那么**所有卡**都会被算成"本轮有变化" —— 那是错的（根本没更新过）。
  const 面板 = 造面板({
    名单: ['甲', '乙'],
    NPC: { 甲: {}, 乙: {} },
    统计: { 更新次数: 0, 最后更新: 0 },
    剧情时间: '',
  });

  eq('从没更新过 → 0（不是 2）', 面板.本轮有变化人数.value, 0);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[行为] NPC 为空 → 0（不报错）');
{
  const 面板 = 造面板({ 名单: [], NPC: {}, 统计: { 更新次数: 0, 最后更新: 0 }, 剧情时间: '' });
  eq('空数据 → 0', 面板.本轮有变化人数.value, 0);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[结构] 面板接口 / 实现 / 页面解构 三处都要有');
{
  const { readFileSync } = await import('node:fs');
  const path = await import('node:path');
  const 面板源 = readFileSync(path.join(process.cwd(), 'src/彼方_NPC幕后生命状态系统/仪表盘面板.ts'), 'utf8');
  const 页面源 = readFileSync(path.join(process.cwd(), 'src/彼方_NPC幕后生命状态系统/页面-仪表盘.vue'), 'utf8');

  ok('[结构] 类型里有 本轮有变化人数', /本轮有变化人数:\s*ComputedRef<number>/.test(面板源));
  ok('[结构] 有 computed 定义', /const 本轮有变化人数 = computed\(/.test(面板源));
  ok('[结构] 返回值里有它', /^\s{4}本轮有变化人数,$/m.test(面板源));
  ok('[结构] 页面解构了它', /^\s{2}本轮有变化人数,$/m.test(页面源));
  ok('[结构] 模板里用了它', /\{\{\s*`本轮 \$\{本轮有变化人数\} 人有变化`\s*\}\}/.test(页面源));

  // **自证**：抠掉接口那一行 → 第一条会红
  const 抠掉 = 面板源.replace(/本轮有变化人数:\s*ComputedRef<number>;/, '');
  ok('[自证] 抠掉类型声明后"类型里有"会红', !/本轮有变化人数:\s*ComputedRef<number>/.test(抠掉));
}

// ─────────────────────────────────────────────────────────────
console.log('\n[结构] 壳里那份重复定义应改成复用（同一个口径，不许两处各算一遍）');
{
  const { readFileSync } = await import('node:fs');
  const path = await import('node:path');
  const 壳源 = readFileSync(path.join(process.cwd(), 'src/彼方_NPC幕后生命状态系统/悬浮球界面.vue'), 'utf8');

  // 壳自己也要用（页签圆点），但**口径必须与面板一致**。
  // 最稳的做法是壳从面板对象里取；如果它还留着自己那份 computed，至少两处的表达式必须相同。
  const 壳有自己那份 = /const 本轮有变化人数 = computed\(/.test(壳源);
  if (壳有自己那份) {
    // 两处都要用「统计?.最后更新」这个口径
    ok('[结构] 壳那份用的是 统计?.最后更新 口径', /Number\(数据?\.?value\.统计\?\.最后更新/.test(壳源) || /Number\(stats\.value\.最后更新/.test(壳源));
  }
  else {
    ok('[结构] 壳不再自己算（从面板取）', /仪表盘面板\.本轮有变化人数|本轮有变化人数\s*=\s*.*\.本轮有变化人数/.test(壳源));
  }
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
process.exit(fail > 0 ? 1 : 0);
