console.log('\n[11] 校验: 旧/约束已有可解析公历时, 拒绝突然非法公历或乱码');
{
  const c = 建立世界时间约束('场景继续。', '2008年5月2日 08:15');
  不抛('同日合法公历放行', () => 校验世界时间('2008年5月2日 22:00', c));
  throws('突然变成"傍晚"这种无公历的写法 → 拒', () => 校验世界时间('傍晚', c));
  throws('非法公历(13月40日) → 拒', () => 校验世界时间('2008年13月40日', c));
  throws('纯乱码 → 拒', () => 校验世界时间('x', c));

  const 绝对 = 建立世界时间约束('【场景时间】2008年5月10日\n出发。', '2008年5月9日');
  不抛('正文给了公历日期时, 合法公历放行', () => 校验世界时间('2008年5月10日 21:00', 绝对));
  throws('正文给了公历日期时, 乱码仍然拒', () => 校验世界时间('夜里', 绝对));
}

console.log('\n[12] 未知历法仍然明确降级(古代卡不许被"更严的公历校验"打死)');
{
  const 古 = 建立世界时间约束('场景继续。', '元和三年·三月初七');
  check('古代世界时间解析不出 → 约束没有公历边界', [古.最早日期, 古.最晚日期], [null, null]);
  不抛('古代卡照旧沿用不可解析时间', () => 校验世界时间('元和三年·三月初八', 古));
  不抛('古代卡写别的历法也不拦(明确降级)', () => 校验世界时间('天亮以后', 古));
  check('古代卡跨日仍归"无法判定"', 算跨世界日(古, '元和三年·三月初七'), null);
  check('日志仍报不可判定', 描述世界日差('元和三年·三月初七', '元和三年·三月初八'), '时间不可解析, 无法判定');

  const 开局 = 建立世界时间约束('场景继续。', '');
  不抛('开局(没有上轮世界时间)不拦任何写法', () => 校验世界时间('元和三年·三月初七', 开局));
  check('开局跨日 = 首次', 算跨世界日(开局, ''), '首次');
}

console.log('\n[13] 时间证据本身可被读取(给上层留结构化材料, 不用再解字符串)');
{
  const 证据 = 提取正文时间证据('【场景时间】2008年5月10日\n“2008年6月1日”');
  ok('有场景标记证据', 证据.some(条 => 条.来源 === '场景标记' && 条.日期 !== null));
  ok('有被排除的引述证据', 证据.some(条 => 条.来源 === '未采纳' && 条.未采纳原因 === '引述'));
  ok('被排除的证据带原因说明', 证据.filter(条 => 条.来源 === '未采纳').every(条 => typeof 条.未采纳原因 === 'string' && 条.未采纳原因 !== ''));
}

console.log('\n[14] 原有导出与口径不许动: 最新正文段、中文/ISO、古代降级、日志三态');
{
  check('只读最新回复段',
    月日(提取正文日期('【较早回复 1】\n2008年5月4日。\n\n【最新回复】\n2008年5月6日。')), [5, 6]);
  check('中文「号」也认', 月日(提取正文日期('【最新回复】\n2008年5月4号, 上午。')), [5, 4]);
  check('ISO 照认', 月日(提取正文日期('【最新回复】\n2008-05-04 上午, 雨停了。')), [5, 4]);
  check('古代日期仍解析不出', 解析日期('元和三年·三月初七'), null);
  check('日志 · 首次推进', 描述世界日差('', '2025-11-15 21:30'), '首次推进（无上轮世界时间, 不计跨日）');
  check('日志 · 跨了 3 世界日', 描述世界日差('2025-09-19 20:00', '2025-09-22 09:00'), '跨了 3 世界日');
  check('日志 · 未跨日', 描述世界日差('2025-09-19 20:00', '2025-09-19 23:40'), '未跨日（沿用上轮日期）');
}

console.log(`\n${fail === 0 ? '全部通过' : `${fail} 项失败`} (${pass} 项通过)`);
