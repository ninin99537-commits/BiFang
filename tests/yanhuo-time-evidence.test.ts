// 烟火 · 时间证据(纯函数) —— 当前场景时间 / 引述 / 回忆 / 未来约定分开
//
// 覆盖 方案文档 第12项 与 链路详审 第10项:
//   - 明确场景时间标记优先; 同一层多个场景时间取**最后一个有效时间终点**;
//   - 没有场景标记时, 不简单取"最后一个日期": 先排掉引述/回忆/未来约定, 再认独立叙述日期;
//   - "他说三天后开会" / "回想三天后发生的事" 不得触发当前跳跃; "几天后, ..." 仍照旧认;
//   - 多条新正文(更新频率 > 1)一起看: 较早一条已跨日时, 不能在最后一条"续写动作"上漏掉;
//   - 旧/约束已有可解析公历时, 拒绝突然变成非法公历或乱码; 真正的未知历法仍明确降级;
//   - 回忆块/AM 编码("AM0256 | 0m"、"185d17h15m")不参与世界时钟, 也不用真实时间。
import {
  建立世界时间约束,
  提取正文日期,
  提取正文时间证据,
  校验世界时间,
  描述世界日差,
  算跨世界日,
  解析日期,
} from '../src/烟火_世界运转/时间校验';

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  }
  else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, condition: unknown) {
  check(label, !!condition, true);
}
function throws(label: string, run: () => void) {
  try {
    run();
    check(label, false, true);
  }
  catch {
    check(label, true, true);
  }
}
function 不抛(label: string, run: () => void) {
  try {
    run();
    check(label, true, true);
  }
  catch (error) {
    check(`${label}(实际抛错: ${error instanceof Error ? error.message : String(error)})`, false, true);
  }
}
const 月日 = (日期: { 月: number; 日: number } | null) => (日期 ? [日期.月, 日期.日] : null);
const 距旧 = (日期: any, 旧: string) => Math.round((日期.天 - 解析日期(旧)!.天) / 86400000);

console.log('\n[1] 明确场景时间标记优先, 同一层多个按最后一个时间终点');
{
  const reply = '【场景时间】2008年5月10日 20:00\n他们出发。\n【场景时间】2008年5月12日 06:30\n到达驿站。';
  const c = 建立世界时间约束(reply, '2008年5月9日');
  check('类型 = 正文绝对时间', c.类型, '正文绝对时间');
  check('取最后一个场景时间终点', 月日(c.正文日期), [5, 12]);
  ok('提示里说明按场景时间标记取终点', c.提示.includes('场景时间'));
  ok('同一天允许', (() => { try { 校验世界时间('2008年5月12日 21:00', c); return true; } catch { return false; } })());
  throws('比终点晚一天仍拒', () => 校验世界时间('2008年5月13日 08:00', c));
}

console.log('\n[1b] 现有卡片常见的行内写法: "时间：2039年7月13日11:35" / "地点：X | 时间：2039-07-13 …"');
{
  const 中文 = 建立世界时间约束('时间：2039年7月13日11:35\n他睁开眼。', '2039年7月12日');
  check('行内"时间：" + 中文绝对日期 → 正文绝对时间', 中文.类型, '正文绝对时间');
  check('日期取 2039-07-13', [中文.正文日期?.年, 中文.正文日期?.月, 中文.正文日期?.日], [2039, 7, 13]);
  ok('同日写法放行', (() => { try { 校验世界时间('2039年7月13日 22:00', 中文); return true; } catch { return false; } })());

  const 字段行 = 建立世界时间约束('地点：西城 | 时间：2039-07-13 11:35\n他睁开眼。', '2039年7月12日');
  check('"地点 | 时间" 字段行 → 正文绝对时间', 字段行.类型, '正文绝对时间');
  check('字段行日期取 2039-07-13', [字段行.正文日期?.年, 字段行.正文日期?.月, 字段行.正文日期?.日], [2039, 7, 13]);

  const 只有跳跃 = 建立世界时间约束('时间：三天后，他回来了。', '2039年7月12日');
  check('"时间：三天后"不是场景日期(正文日期 null)', 只有跳跃.正文日期, null);
  check('它仍按相对跳跃认(3 天)', 月日(只有跳跃.最早日期), [7, 15]);
  check('类型是相对跳跃, 不是被误当绝对日期', 只有跳跃.类型, '正文相对跳跃');
}

