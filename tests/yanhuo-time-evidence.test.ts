console.log('\n[10] 回忆块与 AM 编码不是世界时钟原料("0m" 不是当前动作, "185d" 不是跳跃)');
{
  const reply = '正文继续。\n<recall>\nAM0256 | 0m\nAM0100 | 185d17h15m\n2008年7月1日\n</recall>';
  const c = 建立世界时间约束(reply, '2008年5月2日');
  check('回忆块里的日期不取', c.正文日期, null);
  check('回忆块里的时差不触发跳跃', [c.类型, c.跳跃], ['无正文时间', null]);

  const 裸码 = 建立世界时间约束('AM0310 | 185d17h15m\n正文继续。', '2008年5月2日');
  check('裸 AM 行同样不进时钟', [裸码.类型, 裸码.跳跃], ['无正文时间', null]);
}

console.log('\n[10b] 回忆块未闭合: 整层不做时钟判定(不拿半截层的 prefix 日期推时钟)');
{
  const 未闭合 = 建立世界时间约束('【场景时间】2008年5月10日\n三天后出发。\n<recall>\nAM0256 | 0m', '2008年5月9日');
  check('prefix 里的场景日期不采用', [未闭合.类型, 未闭合.正文日期], ['无正文时间', null]);
  check('prefix 里的跳跃词也不采用', 未闭合.跳跃, null);
  check('世界时间原地不动(不跨日)', 算跨世界日(未闭合, '2008年5月9日'), { 最少: 0, 最多: 0 });
  ok('提示仍在, 且要求沿用上轮日期', 未闭合.提示.includes('沿用上轮日期'));

  const 有正常续写也不救 = 建立世界时间约束([
    '【场景时间】2008年5月10日\n<recall>\nAM0256 | 0m',
    '第二层: 他继续赶路。',
  ], '2008年5月9日');
  check('后面还有一层正常续写, 也不拿前面那半层推日期', [有正常续写也不救.类型, 有正常续写也不救.正文日期], ['无正文时间', null]);
}

