console.log('\n[7] 叙事里的跳跃照旧认(不能因为防误判把正常跨日也挡掉)');
{
  const 几天 = 建立世界时间约束('几天后，他回来了。', '2008年5月1日');
  check('"几天后" → 正文相对跳跃', 几天.类型, '正文相对跳跃');
  check('"几天后" → 2 天起(2008-05-03)', 月日(几天.最早日期), [5, 3]);
  const 三天 = 建立世界时间约束('三天后，城门开了。', '2008年5月1日');
  check('"三天后" → 3 天(2008-05-04)', 月日(三天.最早日期), [5, 4]);
  ok('三天后 → 范围是 3~3 天', 距旧(三天.最早日期, '2008年5月1日') === 3 && 距旧(三天.最晚日期, '2008年5月1日') === 3);
}

console.log('\n[8] 多条新正文一起看: 较早一条已跨日, 不能在最后一条"续写动作"上漏掉');
{
  const 约束 = 建立世界时间约束(['第一层: 两天后，队伍出发。', '第二层: 路上没有异常。'], '2008年5月1日');
  check('类型 = 正文相对跳跃', 约束.类型, '正文相对跳跃');
  check('跨了两天(落在 2008-05-03)', 月日(约束.最早日期), [5, 3]);
  check('跨日事实也按同一份约束算出 2 天', 算跨世界日(约束, '2008年5月1日'), { 最少: 2, 最多: 2 });
  const 两层跳跃 = 建立世界时间约束(['两天后出发。', '三天后到城门。'], '2008年5月1日');
  check('两层各跳一次 → 累计 5 天', 算跨世界日(两层跳跃, '2008年5月1日'), { 最少: 5, 最多: 5 });
  const 先日期后跳跃 = 建立世界时间约束(['2008年5月10日 出发。', '三天后到城门。'], '2008年5月9日');
  check('较早一层给了日期、后一层说"三天后" → 终点是 5 月 13 日', 月日(先日期后跳跃.最晚日期), [5, 13]);
  check('类型仍是正文绝对时间(日期是锚)', 先日期后跳跃.类型, '正文绝对时间');
}

console.log('\n[9] 没有时间线索: 维持旧日期, 并在提示里说明');
