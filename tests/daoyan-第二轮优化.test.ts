  check('RED: 揭光了 + 收尾中 → 不补', 需要生成书纲(揭光 as any, null, 50, 4, true), false);
  check('收尾中但用户请求重写 → 照写', 需要生成书纲(揭光 as any, { 请求重写: true, 否决: {}, 改写: {}, 锁定: [] } as any, 50, 4, true), true);
  check('收尾中但还没有书纲 → 照旧(老聊天倒推)', 需要生成书纲(null, null, 50, 4, true), true);
  const 块 = 渲染书纲块({ 书纲: { ...揭光, 深层真相: [...揭光.深层真相, 真相('T3', '潜藏')] } as any, 伏笔: [], 需要生成: false, 请求重写: false, 否决: {}, 有既有剧情: true });
