let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}
const 人 = (角色ID: string, 状态: string): any => ({
  角色ID, 状态, 状态证据: [], 状态历史: [], 独立目标: [], 当前关系: [], 永久后果: [], 承诺与债务: [], 已知事实引用: [], 未竟计划: [], 最后变化: null, 最后变化楼层: 0,
});
const 账本 = (部分: Partial<导演账本> = {}): 导演账本 => ({ ...emptyData(), 已分析轮数: 10, ...部分 });
const 已执行 = { 已执行: true, 顶回冲突: '', 说明: '', 主角死亡: false };
const 未执行 = { 已执行: false, 顶回冲突: '', 说明: '', 主角死亡: false, 核验来源: '明确' as const };
const 构造 = (下一幕: any, 部分: Record<string, any> = {}) =>
  构造本幕指令({ 旧指令: null, 下一幕, 账本: 账本(), 核验: 已执行, 档位: 3, 红线: [], 楼层: 30, 暂停注入: false, ...部分 });

console.log('\n[1] 命运必演按命运册核对');
{
  const 离开 = { 内容: '林晚离开小镇', 命运: true, 角色ID: '林晚', 镜头外: false, 既成事实: false, 未执行轮: 0 };
  check('在册且还活跃 → 没落地', 命运必演已落地(离开, { 角色命运: [人('林晚', '活跃')] }), false);
  check('状态变成离开 → 落地', 命运必演已落地(离开, { 角色命运: [人('林晚', '离开')] }), true);
  check('离开类写成失踪也算', 命运必演已落地(离开, { 角色命运: [人('林晚', '失踪')] }), true);
  check('不在册 → 核对不了', 命运必演已落地(离开, { 角色命运: [] }), null);
  check('没填角色ID → 核对不了', 命运必演已落地({ ...离开, 角色ID: '' }, { 角色命运: [人('林晚', '活跃')] }), null);
  check('背叛这类没有状态的事 → 核对不了', 命运必演已落地({ ...离开, 内容: '林晚背叛主角' }, { 角色命运: [人('林晚', '活跃')] }), null);
  check('死亡类只认死亡', 命运必演已落地({ ...离开, 内容: '林晚死在雨夜' }, { 角色命运: [人('林晚', '离开')] }), false);

  const 第一轮 = 构造({ 节拍: '受挫', 必演: 离开 });
  // RED: 导演报"已执行", 但命运册里林晚还活跃 → 按没演出来处理, 继续沿用
  const 谎报 = 构造({ 节拍: '阴影' }, { 旧指令: 第一轮.指令, 核验: 已执行, 账本: 账本({ 角色命运: [人('林晚', '活跃')] }) });
  check('RED: 导演报已执行但命运册没变 → 继续沿用', 谎报.指令?.必演?.内容, '林晚离开小镇');
  ok('代码调整里写明原因', 谎报.调整.some(x => x.includes('命运册里 林晚 的状态没变')));
  // 真的走了 → 即便导演报"未执行"也不再沿用
  const 真走 = 构造({ 节拍: '余波' }, { 旧指令: 第一轮.指令, 核验: 未执行, 账本: 账本({ 角色命运: [人('林晚', '离开')] }) });
  check('命运册已离开 → 不再沿用', 真走.指令?.必演 ?? null, null);
  // 核对不了 → 照旧按导演自报
  const 背叛 = 构造({ 节拍: '受挫', 必演: { ...离开, 内容: '林晚背叛主角' } });
  check('核对不了 + 导演报已执行 → 不沿用', 构造({ 节拍: '阴影' }, { 旧指令: 背叛.指令, 核验: 已执行 }).指令?.必演 ?? null, null);
}

console.log('\n[2] 既成事实发出去后仍没落账 → 撤下');
{
  const 活 = 账本({ 角色命运: [人('林晚', '活跃')] });
  const 起 = 构造({ 节拍: '受挫', 必演: { 内容: '林晚离开小镇', 命运: true, 角色ID: '林晚' } }, { 账本: 活 });
  const 二 = 构造({ 节拍: '阴影' }, { 旧指令: 起.指令, 核验: 未执行, 账本: 活 });
  const 三 = 构造({ 节拍: '阴影' }, { 旧指令: 二.指令, 核验: 未执行, 账本: 活 });
  check('第 3 轮: 既成事实', 三.指令?.必演?.既成事实, true);
  const 四 = 构造({ 节拍: '阴影' }, { 旧指令: 三.指令, 核验: 未执行, 账本: 活 });
  check(`第 4 轮(未执行轮到 ${既成事实撤下轮数}) → 撤下`, 四.指令?.必演 ?? null, null);
  ok('撤下写进代码调整(日志可见)', 四.调整.some(x => x.includes('撤下')));
  const 封顶撤下 = 构造({ 节拍: '阴影' }, { 旧指令: { ...三.指令!, 核验升级次数: 2 }, 核验: 未执行, 账本: 活 });
  ok('RED: 封顶那轮撤下 → 不交回玩家', !(封顶撤下.指令?.硬性要求 ?? '').includes('把选择交回玩家'));
  check('撤下后升级次数清零', 封顶撤下.指令?.核验升级次数, 0);
  const 换新 = 构造({ 节拍: '阴影', 必演: { 内容: '老周病逝', 命运: true, 角色ID: '老周' } }, { 旧指令: 三.指令, 核验: 未执行, 账本: 活 });
  check('撤下那轮导演给了新的命运必演 → 用新的', 换新.指令?.必演?.内容, '老周病逝');
}

