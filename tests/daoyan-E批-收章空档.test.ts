// 剧情导演 · 批次 E（2026-11-13）：D-2 只改了一半 —— 阈值那一轮「该收章」两规则同时让位
//
// 病根：`取料.ts` 已经改传 `已分析轮数 + 1`，`章长度提醒` 也接受了这个场号；
// 但 `提醒.ts` 里几个调用点还在调 `判收章(账本)`（不传场号 → 退回 `账本.已分析轮数`，比引擎少 1）。
// 于是同一轮里「谁该说该收章」这个判定用了两套场号：
//   · `章长度提醒` 拿新场号算出「该我说了」→ 去问 `选收章发言者(新场号)` → 得到「幕纲落后」→ 让位；
//   · `幕纲落后` 那条规则自己拿旧场号算 → 还没超期 → 也 return []。
// **两边互相让位，中间漏一个空档 —— 阈值那一轮彻底失声。**
//
// ⚠️ 口径教训（这次差点又栽）：「收章语义」的文本有两种写法 ——
//   `章长度` 说「已经**演了** N 场还没进入收束」，`幕纲落后` 说「本章**已演** N 场」。
// 用 `/演了 \d+ 场/` 去数，会把幕纲落后那条漏掉，得出"没人说话"的假结论。
// 所以这里的正则写成 `演了|已演` 两种都认，并且**同时打印整条提醒列表**当证据。

import { createPinia, setActivePinia } from 'pinia';
import type { 导演账本 } from '../src/剧情导演/schema';
import { emptyData } from '../src/剧情导演/快照';
import { 结构提醒, 判收章 } from '../src/剧情导演/提醒';

(globalThis as any)._ = {
  clamp: (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), hi),
  cloneDeep: (v: any) => (v === undefined ? undefined : JSON.parse(JSON.stringify(v))),
};
(globalThis as any).localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

/** 需求方给的判据账本：已分析轮数 40、起始场 1、幕纲 5 幕、进度推进（幕号由用例指定） */
const 幕纲 = Array.from({ length: 5 }, (_, i) => `第${i + 1}幕｜类型: 事件｜目标:t`);
const 造账 = (轮: number, 当前幕号 = 3): 导演账本 =>
  ({
    ...emptyData(),
    已分析轮数: 轮,
    章回: { 章号: 1, 主题: 'x', 计划高潮: '', 进度: '推进', 起始场: 1, 幕纲, 当前幕号 } as any,
  } as 导演账本);

/** 收章语义的两种说法都要算（`演了` = 章长度 / `已演` = 幕纲落后） */
const 收章语义 = (行: string[]) => 行.filter(x => /该收章|收束预算|开新章|演了 \d+ 场|已演 \d+ 场/.test(x));

// ---------------------------------------------------------------------------
console.log('\n[E-1] 阈值那一轮（场 41）必须有**至少一条**在说收章');
{
  const 账本 = 造账(40);
  const 行 = 结构提醒(账本, 41);
  const 命中 = 收章语义(行);
  console.log('        整条提醒列表：');
  行.forEach((x, i) => console.log(`          ${i + 1}. ${x.slice(0, 64)}`));
  ok('场 41 → 收章语义 条数 >= 1（修复前这里是 0，两边互相让位）', 命中.length >= 1);
  check('同一轮不许两条都在说收章（互斥仍成立）', 命中.length, 1);
  ok('说的那条是「幕纲落后」（它比"演了 N 场"更具体：第几幕/推不动）', 命中.some(x => x.includes('幕纲明显落后') || x.includes('幕号已经推不动了')));
}

console.log('\n[E-2] 相邻三场的矩阵 × 两种幕号（口径一致，不许出现空档）');
{
  /**
   * 2026-11-13 补充（需求方指出的覆盖缺口）：`当前幕号` 会改变"谁在说"。
   *   · 幕号 5/5（**真机状态**）→ 41 场起 `幕纲落后` 走 `到头了` 分支，说的是「该收章」；
   *   · 幕号 3/5 → 它说的是「推幕号」（那是另一件事，需求方已单独立条等用户拍板）。
   * 只钉一种幕号会漏掉另一条分支，所以两种都测。
   * 注意标签口径：`已分析轮数 = 轮` 时，取料传的场号是 `轮 + 1`（D-2 的 +1）。
   */
  for (const 幕号 of [3, 5]) {
    const 矩阵 = [38, 39, 40].map(轮 => {
      const 行 = 结构提醒(造账(轮, 幕号), 轮 + 1);
      return { 轮, 场: 轮 + 1, 条数: 收章语义(行).length };
    });
    console.log(`        幕号 ${幕号}/5: ` + JSON.stringify(矩阵));
    check(`幕号 ${幕号}/5: 场 39（还没到 40）→ 0 条`, 矩阵[0].条数, 0);
    check(`幕号 ${幕号}/5: 场 40（= 章长度阈值）→ 1 条`, 矩阵[1].条数, 1);
    check(`幕号 ${幕号}/5: 场 41（超期）→ 1 条`, 矩阵[2].条数, 1);
  }
}

console.log('\n[E-4] 第 4 个调用点：该收章的那一轮，节奏提醒必须闭嘴（不许说"拖太久/该换节拍"）');
{
  // 真机形态：幕号 5/5、最近 5 场都是日常（节拍拖太久成立）
  const 五场日常 = { 当前: 0, 距上次高潮楼层: 0, 连续低张力: 0, 最近节拍: ['日常', '日常', '日常', '日常', '日常'] };
  const 造 = (轮: number) => {
    const 账: any = 造账(轮, 5);
    return { ...账, 张力: 五场日常 } as 导演账本;
  };
  // 只认**节奏提醒自己那句话**（`同一个节拍拖成流水账`）。
  // 不能用「空着 / 推进」这类泛词 —— 批次 B 加的「幕纲现状」里就有"没有一幕能空着…每幕都得推进"，
  // 用它当标记会把我自己上一批的文案当成节奏提醒（这正是"统计口径也要验"那类错）。
  const 说拖太久 = (行: string[]) => 行.filter(x => x.includes('同一个节拍拖成流水账'));

  // 场 41：该收 = true → 节奏提醒让位（修复前它会说"拖太久"，与「该收章」对撞）
  const 场41 = 结构提醒(造(40), 41);
  check('场 41 → 收章语义 1 条', 收章语义(场41).length, 1);
  check('场 41 → 节奏提醒不说拖太久（让位成立）', 说拖太久(场41).length, 0);

  // 判据能失败：把场号退回旧口径（40），该收=false → 节奏提醒**会**说拖太久
  const 旧口径 = 结构提醒(造(40), 40);
  ok('对照: 场 40（该收=false）→ 节奏提醒会说拖太久（证明上面那条不是空转）', 说拖太久(旧口径).length >= 1);
}

console.log('\n[E-3] 判据能失败：用旧口径（不传场号）算，那条规则确实会沉默');
{
  const 账本 = 造账(40);
  // 修复前的口径：判收章 不收场号 → 用 账本.已分析轮数 = 40 → 超期 = 40 > 40 = false
  check('旧口径 判收章(账本).超期 = false（所以幕纲落后会 return []）', 判收章(账本).超期, false);
  check('新口径 判收章(账本, 41).超期 = true', 判收章(账本, 41).超期, true);
  // 而且必须靠"传场号"才绿：把场号退回 40，幕纲落后那条就不该出现
  const 旧口径行 = 结构提醒(造账(40), 40).filter(x => x.includes('幕纲明显落后'));
  check('场号退回 40 → 幕纲落后不出现（证明绿是场号带来的）', 旧口径行.length, 0);
}

// ---------------------------------------------------------------------------
console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0) process.exit(1);
