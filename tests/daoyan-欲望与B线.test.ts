console.log('\n[5] 提示词: 书纲块摆出欲望/B线, 生成时点名要');
{
  const 纲 = 规范化书纲({ 核心问题: '该不该救人', 欲望: { 想要: '把妹妹带出北区', 输了失去: '妹妹' }, B线: { 谁: 'Joel', 争什么: '救人值不值', 现在到哪: '还没开口' } })!;
  const 块 = 渲染书纲块({ 书纲: 纲, 伏笔: [], 需要生成: false, 请求重写: false, 否决: {}, 有既有剧情: false });
  ok('渲染出主角欲望', 块.includes('主角欲望(全剧脊梁): 把妹妹带出北区'));
  ok('渲染出"输了会失去"', 块.includes('输了会失去: 妹妹'));
  ok('渲染出 B 线', 块.includes('B 线') && 块.includes('Joel') && 块.includes('救人值不值'));

  const 生成 = 渲染书纲块({ 书纲: null, 伏笔: [], 需要生成: true, 请求重写: false, 否决: {}, 有既有剧情: false });
  ok('生成要求里点名「主角欲望」', 生成.includes('主角欲望(全剧脊梁)'));
  ok('生成要求里点名「B 线」', 生成.includes('B 线: 一条**不靠打架推进**的关系线'));
  ok('输出格式带 欲望/B线', 生成.includes('"欲望":{') && 生成.includes('"B线":{'));
}

