// 剧情导演 · 主角欲望 + B 线(2026-11-12)
//
// 来自两个编剧技法:
//   · Truby《故事解剖》: **Desire** 是全剧的脊梁 —— 一场戏要么推进它、要么复杂化它。
//   · Blake Snyder: 主题**不在 A 线里宣布**, 埋在 **B  Story** 的两三个人之间讨论;
//     B 线也是"切出去喘气"的合法去处(日常是空着, B 线是有内容但不打架)。
//
// 为什么必须进账本而不是只写进提示词: 以前每场戏的合法性判据只能是"有没有对手动起来"——
// 一场"买盐"和一场"打杂兵"在账本里地位相同, 导演为了让这一幕"有内容"就只好加敌人。
// 有了欲望, 判据变成"这一幕推进或复杂化它了吗"; 不推进的对手就是杂兵。
import { createPinia, setActivePinia } from 'pinia';
import { 规范化书纲, 规范化书纲覆盖, 叠加覆盖, 合并书纲, 渲染书纲块 } from '../src/剧情导演/书纲';
import { 结构提醒 } from '../src/剧情导演/取料';
import { 类型列表, 故事类型旧名, SettingsSchema } from '../src/剧情导演/schema';
import { 类型标准, build类型块 } from '../src/剧情导演/引擎规则';
import { 迁移故事类型 } from '../src/剧情导演/settings';
import { buildDirectorMessages } from '../src/剧情导演/prompts';
import type { 导演账本 } from '../src/剧情导演/schema';
import { emptyData } from '../src/剧情导演/快照';

(globalThis as any)._ = {
  clamp: (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), hi),
  cloneDeep: (v: any) => (v === undefined ? undefined : JSON.parse(JSON.stringify(v))),
};
(globalThis as any).localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

const 账本 = (部分: Partial<导演账本> = {}): 导演账本 => ({ ...emptyData(), 已分析轮数: 10, ...部分 });

// ---------------------------------------------------------------------------
console.log('\n[1] 规范化: 空就是空, 不造假条目');
{
  const 纲 = 规范化书纲({ 核心问题: '该不该救人', 欲望: { 想要: '把妹妹带出北区', 为什么是现在: '封锁令今晚生效', 输了失去: '妹妹' }, B线: { 谁: 'Joel', 争什么: '救人值不值', 现在到哪: '还没开口' } });
  check('欲望读得回来', 纲?.欲望?.想要, '把妹妹带出北区');
  check('B 线读得回来', 纲?.B线?.谁, 'Joel');
  ok('欲望全空 → null', 规范化书纲({ 核心问题: 'x', 欲望: { 想要: '  ', 为什么是现在: '', 输了失去: '' } })?.欲望 === null);
  ok('B 线全空 → null', 规范化书纲({ 核心问题: 'x', B线: {} })?.B线 === null);
  ok('只有欲望没有别的 → 仍算一份书纲', 规范化书纲({ 欲望: { 想要: '活下去' } }) !== null);
}

// ---------------------------------------------------------------------------
console.log('\n[2] 合并: 欲望是脊梁, 不许每轮换一句');
{
  const 首轮 = 合并书纲(null, { 核心问题: '该不该救人', 欲望: { 想要: '把妹妹带出北区' } }, 4);
  check('首次确立直接写', 首轮.书纲?.欲望?.想要, '把妹妹带出北区');

  const 补全 = 合并书纲(首轮.书纲, { 欲望: { 想要: '把妹妹带出北区', 为什么是现在: '封锁令今晚生效' } }, 6);
  check('主句没变 → 允许补全漏写的项', 补全.书纲?.欲望?.为什么是现在, '封锁令今晚生效');

  const 改写 = 合并书纲(补全.书纲, { 欲望: { 想要: '干脆去南方' } }, 8);
  check('主句改了 → 拒绝', 改写.书纲?.欲望?.想要, '把妹妹带出北区');
  ok('并说明要改在面板改', 改写.拒绝.some(x => x.includes('欲望已确立') && x.includes('面板')));

  const 不覆盖已写项 = 合并书纲(补全.书纲, { 欲望: { 想要: '把妹妹带出北区', 为什么是现在: '另一个理由' } }, 9);
  check('已有的"为什么是现在"不被覆盖', 不覆盖已写项.书纲?.欲望?.为什么是现在, '封锁令今晚生效');
}

// ---------------------------------------------------------------------------
console.log('\n[3] 合并: B 线的人和"在争什么"冻结, 只有"现在到哪"能更新');
{
  const 首轮 = 合并书纲(null, { B线: { 谁: 'Joel', 争什么: '救人值不值', 现在到哪: '还没开口' } }, 4);
  const 推进 = 合并书纲(首轮.书纲, { B线: { 谁: 'Joel', 争什么: '救人值不值', 现在到哪: '第一次吵崩' } }, 6);
  check('"现在到哪"能更新', 推进.书纲?.B线?.现在到哪, '第一次吵崩');
  const 换人 = 合并书纲(首轮.书纲, { B线: { 谁: 'Ellie', 争什么: '救人值不值' } }, 8);
  check('换人 → 拒绝', 换人.书纲?.B线?.谁, 'Joel');
  ok('并说明只有"现在到哪"能更新', 换人.拒绝.some(x => x.includes('B 线') && x.includes('现在到哪')));
  const 换议题 = 合并书纲(首轮.书纲, { B线: { 争什么: '信任值不值' } }, 9);
  check('换议题 → 拒绝', 换议题.书纲?.B线?.争什么, '救人值不值');
}

