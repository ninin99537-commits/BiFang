console.log('\n[4] 用户覆盖: 只换一句, 不清空上下文');
{
  const 纲 = 规范化书纲({ 欲望: { 想要: '导演写的', 为什么是现在: '因为今晚', 输了失去: '妹妹' }, B线: { 谁: 'Joel', 争什么: '导演写的', 现在到哪: '还没开口' } })!;
  const 覆盖 = 规范化书纲覆盖({ 欲望: '我自己写的欲望', B线: '我自己写的议题' });
  const 叠 = 叠加覆盖(纲, 覆盖)!;
  check('覆盖换掉「想要」', 叠.欲望?.想要, '我自己写的欲望');
  check('另外两项保留导演写的', 叠.欲望?.为什么是现在, '因为今晚');
  check('覆盖换掉「争什么」', 叠.B线?.争什么, '我自己写的议题');
  check('B 线的人与进度保留', [叠.B线?.谁, 叠.B线?.现在到哪], ['Joel', '还没开口']);
  ok('覆盖能往返', 规范化书纲覆盖({ 欲望: 'x', B线: 'y' }).欲望 === 'x');
}

