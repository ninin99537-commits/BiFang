console.log('\n[6] 结构提醒: 每轮把"这一场推进欲望了吗"摆到导演面前');
{
  const 有欲望 = 结构提醒(
    账本({ 书纲: 规范化书纲({ 欲望: { 想要: '把妹妹带出北区' } }) }),
    12,
  );
  ok('有欲望 → 问"推进/复杂化/无关"', 有欲望.some(x => x.includes('推进') && x.includes('复杂化') && x.includes('无关')));
  ok('有欲望 → 点明"无关的就是杂兵"', 有欲望.some(x => x.includes('杂兵')));
  ok('有欲望 → 给出替代去向(B 线)', 有欲望.some(x => x.includes('B 线上')));

  const 缺欲望 = 结构提醒(账本({ 书纲: 规范化书纲({ 核心问题: '该不该救人' }) }), 12);
  ok('书纲缺欲望 → 提醒补一条"具体可失败"的目标', 缺欲望.some(x => x.includes('还没有「主角欲望」') && x.includes('可失败')));
  ok('书纲缺 B 线 → 也提醒补(老聊天不走"生成书纲"那条路)', 缺欲望.some(x => x.includes('还没有「B 线」')));
  ok('缺 B 线的提醒说清它的用处(不打架的线/喘气)', 缺欲望.some(x => x.includes('不打架') && x.includes('喘气')));

  const 没书纲 = 结构提醒(账本(), 12);
  ok('没有书纲时不说这件事(避免开局噪音)', !没书纲.some(x => x.includes('主角欲望')));
}

