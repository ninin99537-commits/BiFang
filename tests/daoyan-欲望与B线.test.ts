console.log('\n[7] 类型承诺(2026-11-12): 类型决定"该有什么", 也就决定"该省什么"');
{
  ok('类型列表有「不限」+ 10 类', 类型列表.length === 11 && 类型列表.includes('不限'));
  check('类型标准正好覆盖 10 类(不含不限)', Object.keys(类型标准).length, 10);
  ok('每一类都有一句话与必备', Object.values(类型标准).every(x => x.一句话.length > 0 && x.必备.length > 0));
  check('「不限」不注入任何东西', build类型块('不限'), '');
  check('不传也不注入', build类型块(undefined), '');
  const 块 = build类型块('密室困局');
  ok('块里有标题(新名字)', 块.includes('【故事类型：密室困局】'));
  ok('块里有一句话说明', 块.includes('出不去的地方'));
  ok('块里有必备元素', 块.includes('封闭空间') && 块.includes('过错'));
  ok('块里点明"整章/整本书"不是每场', 块.includes('整章/整本书'));
  ok('块里禁止换掉必备元素', 块.includes('不许把必备元素换掉'));

  // 设置层: 默认不限; 脏值不炸整个设置(否则会关掉写回闸门, 用户看到"设置回默认")
  check('默认 = 不限', SettingsSchema.parse({}).导演.类型, '不限');
  check('脏值回落成不限', SettingsSchema.parse({ 导演: { 类型: '恐怖片' } }).导演.类型, '不限');
  check('合法值照收', SettingsSchema.parse({ 导演: { 类型: '远行寻物' } }).导演.类型, '远行寻物');

  // 接进 SYSTEM_PROMPT 的链条: 选了就进提示词, 不限就一个字都没有
  const 造 = (类型: string) =>
    buildDirectorMessages({
      账本: 账本(),
      reply: '正文',
      replyCount: 1,
      context: '',
      worldbook: '',
      playerName: null,
      playerDesc: '',
      破限: false,
      头部填充: false,
      头部填充文本: '',
      防截断: false,
      预填充: false,
      类型: 类型 as any,
    } as any)
      .map(m => m.content)
      .join('\n');
  ok('选了密室困局 → 提示词带类型块', 造('密室困局').includes('【故事类型：密室困局】'));
  ok('不限 → 提示词里没有这一块', !造('不限').includes('【故事类型'));
}

// ---------------------------------------------------------------------------
console.log('\n[8] 类型名字必须是人话(2026-11-12 改名): 不能让人先读一本书才看懂');
{
  // 用户原话: "这些类型的名字...看不懂, 要不是我问了一下你我都不知道金羊毛是什么"
  const 术语译名 = ['怪物屋', '金羊毛', '愿望成真', '小人物大麻烦', '成人礼', '冤家伙伴', '谁干的', '傻人有傻福', '体制之内', '超级英雄'];
  ok('类型列表里不再出现《救猫咪》的术语译名', !类型列表.some(名 => 术语译名.includes(名)));
  ok('类型标准里也不再出现术语译名', !Object.keys(类型标准).some(名 => 术语译名.includes(名)));
  // 新名字自己就该看懂: 不用副标题也能猜出讲什么(这里只钉"不是术语", 语感靠人 review)
  ok('新名字都是中文白话(不带书名号/引号等借用符号)', 类型列表.every(名 => !/[《》「」""'']/.test(名)));

  // 迁移表: 十个旧名一个都不能漏, 否则老聊天会静默掉成「不限」
  const 旧名们 = Object.keys(故事类型旧名);
  check('迁移表覆盖全部 10 个旧名', 旧名们.length, 10);
  ok('迁移表的每个旧名都在术语译名清单里', 旧名们.every(名 => 术语译名.includes(名)));
  ok('迁移目标都是类型列表里的合法值', Object.values(故事类型旧名).every(名 => (类型列表 as readonly string[]).includes(名)));
  ok('迁移是一一对应(没有两个旧名映到同一个新名)', new Set(Object.values(故事类型旧名)).size === 10);
  ok('新名字本身不参与迁移(避免自我循环)', 旧名们.every(名 => !(类型列表 as readonly string[]).includes(名)));

  // schema 的 catch 是"静默回落": 迁移没做到位, 用户就会一声不响地丢设置
  check('老值不迁移时确实会掉成不限(所以迁移是必须的)', SettingsSchema.parse({ 导演: { 类型: '金羊毛' } }).导演.类型, '不限');

  // 迁移函数本身: 有旧值就换名, 只是名字变了, 选的东西不变
  check('「金羊毛」迁成「远行寻物」', 迁移故事类型({ 导演: { 类型: '金羊毛', 强度档位: 4 } }), '远行寻物');
  ok('十个旧名逐个都能迁', 术语译名.every(名 => 迁移故事类型({ 导演: { 类型: 名 } }) === 故事类型旧名[名]));
  check('已是新名字 → 不迁', 迁移故事类型({ 导演: { 类型: '远行寻物' } }), null);
  check('不认识的脏值 → 不迁(交给 schema 回落)', 迁移故事类型({ 导演: { 类型: '恐怖片' } }), null);
  check('没设过类型 → 不迁', 迁移故事类型({ 导演: {} }), null);
  check('整份存储是脏的 → 不炸', 迁移故事类型('不是对象'), null);
  check('读不到存储 → 不炸', 迁移故事类型(undefined), null);
  // 迁移后的值必须是 schema 认的合法值, 否则等于没迁
  ok('迁出来的名字 schema 全都认', Object.values(故事类型旧名).every(名 => SettingsSchema.parse({ 导演: { 类型: 名 } }).导演.类型 === 名));
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0) process.exit(1);
