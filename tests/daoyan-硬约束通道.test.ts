// 剧情导演 · 硬约束通道（2026-11-12）
//
// 病根（需求方用真实源码跑出来的）：代码写死的裁定，被渲染成了"建议"。
//   `头`(连败让步) 与 `块`(核验纠偏 / 收束出口 / 不保送 / 日常+必演边界)
//   → 以前拼进 `硬性要求` → `prompts.ts` 渲染成「2. 剧情参考」
//   → 落进「第 2~4 项是导演给的演法建议, 不必逐字照做」那把伞。
// 真机原文长这样:
//   「2. 剧情参考：【连败让步】冲突「北坡」本轮必须让玩家赢（玩家体验优先）。」
// 一条"必须"被说成了建议 —— 这就是"注入按建议发、验收按命令判"的同一类错误。
//
// 修法：`硬约束`(代码裁定, 必须遵守) 与 `硬性要求`(导演散文, 演法建议) 分字段。
// 本用例钉四件事：分流正确 / 渲染顺序（裁定先于建议）/ 导演的话没被搬走 / 不是空跑。
import { createPinia, setActivePinia } from 'pinia';
import { readFileSync } from 'node:fs';
import type { 导演账本 } from '../src/剧情导演/schema';
import { SettingsSchema } from '../src/剧情导演/schema';
import { emptyData } from '../src/剧情导演/快照';
import { 构造本幕指令 } from '../src/剧情导演/引擎规则';
import { build本幕指令 } from '../src/剧情导演/prompts';

(globalThis as any)._ = {
  clamp: (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), hi),
  cloneDeep: (v: any) => (v === undefined ? undefined : JSON.parse(JSON.stringify(v))),
};
(globalThis as any).localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

const 账本 = (部分: Partial<导演账本> = {}): 导演账本 => ({ ...emptyData(), 已分析轮数: 20, ...部分 });
const 核验已执行 = { 已执行: true, 顶回冲突: '', 说明: '', 主角死亡: false };
const 章 = (部分: Record<string, any> = {}): any => ({
  章号: 2, 主题: '夺嫡', 计划高潮: '宫门前的对峙', 进度: '收束', 起始场: 1, ...部分,
});
const settings = SettingsSchema.parse({});

// ---------------------------------------------------------------------------
console.log('\n[1] 连败让步：进硬约束，不进建议');
{
  const 导演话 = '刺客在城门口截住主角, 夺走密信';
  const 账 = 账本({
    已分析轮数: 6,
    冲突: [{ 名: '北坡', 对立面: '守军', 赌注: '退路', 强度: 5, 阶段: '僵持', 下一步: '', 顶回次数: 1 }] as any,
  });
  const r = 构造本幕指令({
    旧指令: null, 下一幕: { 节拍: '受挫', 硬性要求: 导演话 },
    账本: 账, 核验: { ...核验已执行, 顶回冲突: '北坡' },
    档位: 2, 红线: [], 楼层: 20, 暂停注入: false,
  });
  const 硬约束 = r.指令?.硬约束 ?? [];
  const 硬性要求 = String(r.指令?.硬性要求 ?? '');

  ok('防空跑: 本轮确实触发了硬约束', 硬约束.length > 0);
  ok('硬约束里有"让玩家赢"', 硬约束.some(项 => 项.includes('让玩家赢')));
  ok('硬性要求里**没有**"让玩家赢"', !硬性要求.includes('让玩家赢'));
  check('硬性要求 = 导演原文（一字不多）', 硬性要求, 导演话);
}

console.log('\n[2] 收束预算用尽：收章裁定进硬约束');
{
  const 账 = 账本({ 已分析轮数: 20, 章回: 章({ 收束起始场: 13 }), 伏笔: [伏笔()] });
  const r = 构造本幕指令({
    旧指令: null, 下一幕: { 节拍: '余波' },
    账本: 账, 核验: 核验已执行, 档位: 3, 红线: [], 楼层: 40, 暂停注入: false,
  });
  const 硬约束 = r.指令?.硬约束 ?? [];
  const 硬性要求 = String(r.指令?.硬性要求 ?? '');
  ok('防空跑: 收章被触发', r.收章 === true);
  ok('硬约束里有"本章必须收章"', 硬约束.some(项 => 项.includes('本章必须收章')));
  ok('硬约束里提到"已完结"', 硬约束.some(项 => 项.includes('已完结')));
  ok('硬性要求里**没有**收章文本', !硬性要求.includes('本章必须收章'));
  check('导演没写要求时 硬性要求 为空串', 硬性要求, '');
}

function 伏笔(): any {
  return {
    编号: 1, 内容: '铜扣', 埋设层: 3, 埋设章: 1, 状态: '发酵', 回收窗口: '', 关联冲突: '',
    公开线头: '她把缺角的铜扣塞进药箱',
  };
}

console.log('\n[3] 渲染顺序：裁定先于建议（防止以后被挪回伞下）');
{
  let 指令: any = null;
  const 账 = 账本({
    已分析轮数: 6,
    冲突: [{ 名: '北坡', 对立面: '守军', 赌注: '退路', 强度: 5, 阶段: '僵持', 下一步: '', 顶回次数: 1 }] as any,
  });
  const r = 构造本幕指令({
    旧指令: null, 下一幕: { 节拍: '受挫', 硬性要求: '让主角在雪里走一夜' },
    账本: 账, 核验: { ...核验已执行, 顶回冲突: '北坡' },
    档位: 2, 红线: [], 楼层: 20, 暂停注入: false,
  });
  指令 = r.指令;
  const 文本 = build本幕指令({ ...账, 当前指令: 指令 } as any, settings);

  // 注意: 「【本幕硬约束】」在**统辖句**里先出现一次(它点名"这几项必须体现"),
  // 所以定位块头必须用标题原文, 不能用 indexOf('【本幕硬约束】') —— 否则量到的是统辖句,
  // 顺序断言会**假绿**(统辖句永远排第一)。这个坑我第一次就踩了。
  const i硬 = 文本.indexOf('【本幕硬约束】（以下由代码裁定');
  const i结构 = 文本.indexOf('1. 这一幕的结构要求');
  const i参考 = 文本.indexOf('2. 剧情参考');
  ok('渲染里有【本幕硬约束】块头', i硬 >= 0);
  ok('块头出现在「1. 结构要求」之前', i硬 >= 0 && i硬 < i结构);
  ok('块头排在「2. 剧情参考」之前', i硬 >= 0 && i硬 < i参考);
  ok('硬约束标题写明"必须遵守"', 文本.slice(i硬, i硬 + 60).includes('必须遵守'));
  // 伞的措辞要点名硬约束，否则读的人又会以为它在第 2~4 项里
  ok('统辖句把硬约束列进"必须体现"', 文本.includes('【本幕硬约束】、第 1 项的结构要求'));
  ok('统辖句仍保留"第 2~3 项是导演给的演法建议"', 文本.includes('第 2~3 项是导演给的演法建议'));
  ok('第 4 项（禁令）已摘出伞外、列进"必须体现"', 文本.includes('第 4 项的禁令'));
}

console.log('\n[4] 导演的话没被搬走：建议仍然完整出现在「2. 剧情参考」');
{
  const 导演话 = '刺客在城门口截住主角, 夺走密信；让他第一次尝到无力的味道';
  const 账 = 账本({
    已分析轮数: 6,
    冲突: [{ 名: '北坡', 对立面: '守军', 赌注: '退路', 强度: 5, 阶段: '僵持', 下一步: '', 顶回次数: 1 }] as any,
  });
  const r = 构造本幕指令({
    旧指令: null, 下一幕: { 节拍: '受挫', 硬性要求: 导演话 },
    账本: 账, 核验: { ...核验已执行, 顶回冲突: '北坡' },
    档位: 2, 红线: [], 楼层: 20, 暂停注入: false,
  });
  const 文本 = build本幕指令({ ...账, 当前指令: r.指令 } as any, settings);
  ok('导演原话完整出现在渲染文本里', 文本.includes(导演话));
  const i参考 = 文本.indexOf('2. 剧情参考');
  ok('导演原话在「2. 剧情参考」那一行之后', i参考 >= 0 && 文本.indexOf(导演话) > i参考);
  ok('导演原话**不**在硬约束块里', !(r.指令?.硬约束 ?? []).some(项 => 项.includes(导演话.slice(0, 8))));
}

console.log('\n[5] 禁止事项：代码的禁令进硬约束，字段只留导演原文');
{
  const 账 = 账本({ 已分析轮数: 20, 章回: 章(), 收官请求: true, 终局步: 2, 伏笔: [伏笔()] });
  const r = 构造本幕指令({
    旧指令: null, 下一幕: { 禁止事项: '不要写雨的拟人化' },
    账本: 账, 核验: 核验已执行, 档位: 3, 红线: [], 楼层: 40, 暂停注入: false,
  });
  const 硬约束 = r.指令?.硬约束 ?? [];
  check('收官幕: 禁止事项 只留导演原文', r.指令?.禁止事项, '不要写雨的拟人化');
  ok('收官幕: 代码那句禁令进了硬约束', 硬约束.some(项 => 项.includes('不新增伏笔')));
  ok('收官幕: 硬约束里带上终局步数', 硬约束.some(项 => 项.includes('终局第 2/5 步')));

  // 导演**没写**禁止事项 → 渲染里不出现「4.」这一行（空就不占位）
  const 无禁止 = 构造本幕指令({
    旧指令: null, 下一幕: { 节拍: '受挫' },
    账本: 账本({ 已分析轮数: 6 }), 核验: 核验已执行, 档位: 3, 红线: [], 楼层: 20, 暂停注入: false,
  });
  check('无禁止事项: 字段是空串', 无禁止.指令?.禁止事项, '');
  const 文本 = build本幕指令({ ...账本({ 已分析轮数: 6 }), 当前指令: 无禁止.指令 } as any, settings);
  ok('无禁止事项时，不渲染「4.」这一行', !文本.includes('4. 导演不建议写'));
}

console.log('\n[6] 快照往返：硬约束不丢（丢 = 删楼回退后放宽规则）');
{
  // 这条是**源码级**断言（与本仓库既有的"面板接线不变"同一种做法）：
  // `规范化指令` 没有导出，真正跑往返要 mock 宿主；这里只钉"迁移层确实收这个键"。
  // 它与 `本幕揭示/必须保留` 同一条纪律 —— 那两个字段丢了会"回退后约束凭空消失"。
  const src = readFileSync('src/剧情导演/账本迁移.ts', 'utf8');
  ok('迁移层收 硬约束', src.includes('硬约束: 文本数组(raw.硬约束)'));
  ok('空值不写键（老快照读回逐字一致）', src.includes("文本数组(raw.硬约束).length > 0 ? { 硬约束"));
}

