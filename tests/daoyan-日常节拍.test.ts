// 剧情导演 · 「日常」节拍(2026-11-12)
//
// 用户原话:「感觉好紧凑，打完一个又来一个，一堆杂兵」。
//
// 病根不是视野, 是**规划词汇里没有"什么都不用发生"这一档**:
//   原来的 7 个节拍**全部**落在高张力(受挫/反转/兑现伏笔/高潮)或低张力(小胜/阴影/余波)两个桶里,
//   没有"零"。于是张力曲线每 3 幕必然推着来一件事 —— 余波("平静但带着代价")或阴影("静中必须埋险"),
//   两者都是事件。再叠上"对手 3 幕没动手就必须动手", 就成了一路打。
//
// 2026-11-08 的 README 明确拒绝过"加一个日常节拍", 理由是"那只是把'被逼着跌宕'换成'被逼着温馨',
// 决定权还在引擎手里", 所以当时做的是平静模式(整段关掉)。这份实现跟那次拒绝**不冲突**:
//   日常是**许可**, 不是义务 —— 代码里**没有任何一条规则会强制把节拍设成"日常"**;
//   它只做三件事: ①不计入连续低/高张力(既不累积也不清零); ②张力增量 0; ③不许被其它规则征用。
//   决定权仍然在导演/玩家手里, 这正是那次拒绝要保住的东西。
