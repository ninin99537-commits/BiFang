console.log('\n[7] 通用话术不许对日常说反话(2026-11-12 自查)');
{
  const 造 = (节拍: string, 部分: Record<string, any> = {}) =>
    构造本幕指令({
      旧指令: null,
      下一幕: { 节拍, 硬性要求: '待着' },
      账本: 账本({ 章回: { 章号: 1, 主题: 'x', 计划高潮: '', 进度: '推进' }, 张力: { 当前: 3, 距上次高潮楼层: 1, 连续低张力: 0, 最近节拍: ['小胜'] } }),
      核验: 已执行 as any,
      档位: 3,
      红线: [],
      楼层: 20,
      暂停注入: false,
      ...部分,
    });
  const 渲染 = (节拍: string) =>
    build本幕指令(
      账本({ 当前指令: ({ ...造(节拍).指令 } as any) }),
      SettingsSchema.parse({}),
    );

  // ① 正文指令里第一项的收束语
  ok('日常: 说"不需要发生事"', 渲染('日常').includes('**这一幕不需要"发生事"**'));
  ok('日常: 不说"这一步要在正文里真的发生"', !渲染('日常').includes('这一步要在正文里真的发生'));
  ok('反面对照: 受挫仍然要求"真的发生"', 渲染('受挫').includes('这一步要在正文里真的发生'));

  // ② 核验升级: 日常要"别再开新线", 而不是"把结果做出来"
  // 2026-11-12 硬约束通道: 日常纠偏是**代码裁定**, 现在住 硬约束; 反向断言要看两个通道(裁定∪建议)。
  const 裁定 = (x: any) => (x?.指令?.硬约束 ?? []).join('\n');
  const 正文可见 = (x: any) => `${裁定(x)}\n${x?.指令?.硬性要求 ?? ''}`;
  const 旧日常 = ({ ...造('日常').指令, 核验升级次数: 0 } as any);
  const 升级 = 造('日常', { 旧指令: 旧日常, 核验: { 已执行: false, 顶回冲突: '', 说明: '', 主角死亡: false, 核验来源: '明确' } as any });
  ok('日常升级: 收回成"别再开新线"', 裁定(升级).includes('【这一幕别再开新线】'));
  ok('日常升级: 不出现"只做一件事"', !正文可见(升级).includes('【这一幕只做一件事】'));
  ok('日常升级: 调整里说清是"只写日常，别开新线"', (升级.调整 ?? []).some(x => x.includes('只写日常')));
  const 封顶 = 造('日常', { 旧指令: { ...旧日常, 核验升级次数: 2 }, 核验: { 已执行: false, 顶回冲突: '', 说明: '', 主角死亡: false, 核验来源: '明确' } as any });
  ok('日常封顶: 同样收成"别再开新线"', 裁定(封顶).includes('【这一幕别再开新线】'));
  ok('日常封顶: 带"禁止连续重复"', 裁定(封顶).includes('禁止连续重复'));

  // ③ 日常 + 必演 = 矛盾的组合, 至少要说出来
  const 带必演 = 造('日常', { 下一幕: { 节拍: '日常', 硬性要求: '待着', 必演: { 内容: '一封信到了', 命运: false } } });
  // 2026-11-12 P0.5 → 硬约束: 这两条是**给正文的边界约束**("必须是生活里会发生的事"), 是代码裁定。
  ok('日常+必演: 硬约束 里点明这个矛盾', 裁定(带必演).includes('却给了必演'));
  ok('日常+必演: 给出边界(不许借它开新对抗)', 裁定(带必演).includes('不许借它开新的对抗'));
}

