console.log('\n[5] 已退休的字段: 下次更新时自动从卡上删掉, 且本轮 AI 再返回它也不复活');
{
  // 退休机制见 卡字段.ts 的 LEGACY_CARD_FIELDS(旧卡里的残留值在合并时被 delete, 历史楼层快照不动)
  const 合并后 = 合并({ 持有物: '黑色折叠伞(2025-09-18 插在书包侧袋)', 当前在做: '做饭' }, { 持有物: '旧运动外套(2025-09-18 身上套着)', 当前在做: '散步' });
  ok('旧卡上的残留被删掉(AI 本轮又返回也不复活)', 合并后['持有物'] === undefined);
  check('同一次合并里其它字段照常更新', 合并后['当前在做'], '散步');
}

