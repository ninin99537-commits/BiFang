// 彼方 · 剧情日期(一个口径) —— 钉住"日期怎么认、怎么比、区间怎么切"。
//
// 这一份存在的理由: 同一个日期格式以前散在 7 个文件 13 个正则里, 区间切分有两份,
// 分隔符还不一样。下面每一条都是当时**真的分叉过**的地方, 尤其是「到」。
import {
  切区间,
  区间末,
  写日期,
  日差,
  日差自时间戳,
  日序,
  日序自时间戳,
  日期键自时间戳,
  读日期,
  读日期文本,
} from '../src/彼方_NPC幕后生命状态系统/剧情日期';
import { parseStoryTime, withStoryDate } from '../src/彼方_NPC幕后生命状态系统/剧情时间';
import { 写当日值, 读当日值 } from '../src/彼方_NPC幕后生命状态系统/日记录';
import { 承诺紧迫度, 待核对事务 } from '../src/彼方_NPC幕后生命状态系统/事务台账';

let pass = 0;
let fail = 0;
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}
function ok(名: string, 条件: boolean) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}`);
  }
}

console.log('\n[1] 认日期: 同一种日期, 四种写法都认; 年份 3~6 位不写死');
{
  eq('连字符', 读日期文本('2025-09-18'), '2025-09-18');
  eq('斜杠', 读日期文本('2025/9/18'), '2025-09-18');
  eq('点号', 读日期文本('2025.9.18'), '2025-09-18');
  eq('中文年月日', 读日期文本('2025年9月18日 06:30'), '2025-09-18');
  eq('三位年份', 读日期文本('137-6-12'), '137-06-12');
  eq('五位年份(世界纪年)', 读日期文本('12640-1-2'), '12640-01-02');
  eq('混在长句里取第一个', 读日期文本('她 2025-09-18 18:40 出门, 2025-09-19 回来'), '2025-09-18');
  eq('认不出就是空串', 读日期文本('天启三年 六月初七'), '');
  eq('空值不炸', 读日期文本(undefined), '');
  eq('读日期返回拆开的年月日', 读日期('2025年9月8日'), { 年: '2025', 月: '09', 日: '08' });
  eq('写日期默认不补年份', 写日期({ 年: '137', 月: '06', 日: '12' }), '137-06-12');
  eq('写日期可补到四位', 写日期({ 年: '137', 月: '06', 日: '12' }, true), '0137-06-12');
  eq('四位年份补年不变', 写日期({ 年: '0137', 月: '06', 日: '12' }, true), '0137-06-12');
  eq('五位年份补年不截断', 写日期({ 年: '12640', 月: '01', 日: '02' }, true), '12640-01-02');
}

console.log('\n[2] 日序 / 日差: 用 UTC 零点算日历日, 0~99 年不被映射到 1900+');
{
  ok('日序认得出', 日序('2025-09-18') !== null);
  eq('日序认不出返回 null', 日序('2025/9/18'), null); // 只认已经写好的 YYYY-MM-DD
  // 0004 年: Date.UTC(4, …) 会落到 1904 —— 旧实现有这个坑, 这里钉住
  const 公元4 = 日序('0004-01-01');
  ok('0004 年不会被算成 1904', 公元4 !== null && new Date(公元4).getUTCFullYear() === 4);
  eq('同日差 0', 日差('2025-09-18', '2025-09-18'), 0);
  eq('差一天', 日差('2025-09-19', '2025-09-18'), 1);
  eq('跨月', 日差('2025-10-01', '2025-09-30'), 1);
  eq('跨年', 日差('2026-01-01', '2025-12-31'), 1);
  eq('反向为负', 日差('2025-09-18', '2025-09-20'), -2);
  eq('任一认不出返回 null', 日差('2025-09-18', '天启三年'), null);
}

console.log('\n[3] 切区间: 「至 / 到 / ~ / —」都得认(少一个就是一天误差)');
{
  eq('至', 切区间('2025-09-19 18:00 至 2025-09-19 20:00'), ['2025-09-19 18:00', '2025-09-19 20:00']);
  eq('到', 切区间('2025-09-19 18:00 到 2025-09-19 20:00'), ['2025-09-19 18:00', '2025-09-19 20:00']);
  eq('波浪号', 切区间('2025-09-19 18:00 ~ 2025-09-19 20:00'), ['2025-09-19 18:00', '2025-09-19 20:00']);
  eq('破折号', 切区间('2025-09-19 18:00 — 2025-09-19 20:00'), ['2025-09-19 18:00', '2025-09-19 20:00']);
  eq('不是区间就整串', 区间末('2025-09-19 18:00'), '2025-09-19 18:00');
  eq('区间取末段', 区间末('2025-09-19 18:00 到 2025-09-20 02:00'), '2025-09-20 02:00');
}

console.log('\n[4] 台账侧: 跨午夜的「到」区间不再差一天(这就是那个真 bug)');
{
  const 事务 = { 内容: '2025-09-21 交房租', 时间: '2025-09-19' };
  // 「今天」取区间末 = 09-20; 约定 09-21 → 还剩 1 天
  eq('至 区间', 承诺紧迫度(事务, '2025-09-19 20:00 至 2025-09-20 02:00').剩余天数, 1);
  eq('到 区间(与「至」同口径)', 承诺紧迫度(事务, '2025-09-19 20:00 到 2025-09-20 02:00').剩余天数, 1);
  // 修之前: 到-区间被当成开始那天(09-19) → 还剩 2 天, 与「至」差一天
  ok('两种写法给同一个答案', 承诺紧迫度(事务, '2025-09-19 20:00 至 2025-09-20 02:00').剩余天数
    === 承诺紧迫度(事务, '2025-09-19 20:00 到 2025-09-20 02:00').剩余天数);
  // 待核对同理: 约定日期已过要能认出来
  const 过期 = 待核对事务([{ 编号: 'T1', 时间: '2025-09-01', 内容: '2025-09-19 交房租', 状态: '进行中' }], '2025-09-19 20:00 到 2025-09-20 02:00');
  eq('到-区间下也能判出"约定日期已过"', 过期.map(x => x.编号), ['T1']);
}

console.log('\n[5] 日记录: "日期键|数值" 只在同一天才算数');
{
  eq('同一天读得出', 读当日值('2025-09-18|0.0421', '2025-09-18'), 0.0421);
  eq('不是同一天归零', 读当日值('2025-09-17|0.0421', '2025-09-18'), null);
  eq('没有记录', 读当日值(undefined, '2025-09-18'), null);
  eq('脏值不炸', 读当日值('乱写的', '2025-09-18'), null);
  eq('键为空直接 null', 读当日值('2025-09-18|1', ''), null);
  eq('写回去', 写当日值('2025-09-18', '0.0421'), '2025-09-18|0.0421');
  eq('写完读得回来', 读当日值(写当日值('0137-06-12', '3.5'), '0137-06-12'), 3.5);
}

console.log('\n[6] 时间戳口径: 日期键不截断年份, 日差按日历日');
{
  const ts = parseStoryTime('12640-03-01 10:19') as number;
  eq('五位年份的日期键不截断', 日期键自时间戳(ts), '12640-03-01');
  ok('日序自时间戳认得出', 日序自时间戳(ts) !== null);
  eq('日序自时间戳: 空值返回 null', 日序自时间戳(null), null);
  eq('日差自时间戳: 差一天', 日差自时间戳(parseStoryTime('2025-09-19 00:20'), parseStoryTime('2025-09-18 23:45')), 1);
  eq('日差自时间戳: 同日 0', 日差自时间戳(parseStoryTime('2025-09-18 01:00'), parseStoryTime('2025-09-18 23:00')), 0);
  eq('日差自时间戳: 任一空返回 null', 日差自时间戳(null, 1), null);
}

console.log('\n[7] 相对时刻补全: 「今天/昨天」用区间末那天, 0~99 年也不跑偏');
{
  eq('今天 → 区间末的日期', withStoryDate('吃饭(今天 18:20)', '2026-08-15 18:41 至 2026-08-15 18:48'), '吃饭(2026-08-15 18:20)');
  eq('昨天 → 前一天', withStoryDate('洗漱(昨天 15:30)', '0137-08-15 06:50 至 0137-08-15 07:10'), '洗漱(0137-08-14 15:30)');
  eq('四位年份的"今天"', withStoryDate('今天 9:05', '0137-08-15 06:50'), '0137-08-15 9:05');
  // 0004 年减一天要落到 0003, 不能因为 Date 把 0~99 年映射到 1900+ 而跑到 1900s
  eq('0004 年的昨天是 0003', withStoryDate('昨天 8:00', '0004-01-01 09:00'), '0003-12-31 8:00');
  eq('认不出日期就原样', withStoryDate('今天 18:20', '天启三年'), '今天 18:20');
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0)
  process.exit(1);
