console.log('\n[1] 副作用验：每字段都不写 → 输出账本与旧账本逐字段相等');
{
  const 旧 = 满账本();
  const r = 跑(旧, 空载荷());
  // 代码自己会写的字段，逐项白名单（不参与"逐字段相等"）：
  //   状态历史/最后推进幕/埋设层/埋设章/埋设场/最后回响场/最后推进章/最近催办章 —— 代码填；
  //   顶回次数 —— **每轮由代码按核验重置**（`核验.顶回冲突` 命中才累加，否则归 0），不是漏写；
  //   证据里的 `定位`、关系里的 `矛盾起始场` —— 代码加的标注（比对前统一剥掉，见 剥代码标注）。
  const 代码写 = new Set(['状态历史', '最后推进幕', '埋设层', '埋设章', '埋设场', '最后回响场', '最后推进章', '最近催办章', '顶回次数']);
  /** 剥掉"代码加的标注"再比 —— 否则修没修漏写都会被这两个键干扰 */
  const 剥代码标注 = (值: any): any => {
    if (Array.isArray(值)) return 值.map(剥代码标注);
    if (值 && typeof 值 === 'object') {
      const 出: any = {};
      for (const [k, v] of Object.entries(值)) {
        if (k === '定位' || k === '矛盾起始场') continue;
        出[k] = 剥代码标注(v);
      }
      return 出;
    }
    return 值;
  };
  const 差异: string[] = [];
  const 比 = (标签: string, 旧条: any, 新条: any) => {
    for (const 键 of Object.keys(旧条 ?? {})) {
      if (代码写.has(键)) continue;
      const a = JSON.stringify(剥代码标注(旧条[键] ?? null));
      const b = JSON.stringify(剥代码标注(新条?.[键] ?? null));
      if (a !== b) 差异.push(`${标签}.${键}: ${a} → ${b}`);
    }
  };
  比('伏笔#1', 旧.伏笔[0], r.账本.伏笔.find(x => x.编号 === 1));
  比('冲突北坡', 旧.冲突[0], r.账本.冲突.find(x => x.名 === '北坡'));
  比('弧线艾莉', 旧.弧线[0], r.账本.弧线.find(x => x.角色 === '艾莉'));
  比('命运艾莉', 旧.角色命运[0], r.账本.角色命运.find(x => x.角色ID === '艾莉'));
  check('漏写的字段一个都没被清空（逐字段比对）', 差异, []);
  ok('防空跑: 真有字段被沿用', r.沿用.length > 0);
}

