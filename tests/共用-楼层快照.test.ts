console.log('\n[#3 平台异常] 末层有效、但楼层在范围内却读不到 → 不清索引');
{
  // ── 同一条 P0 的另一半 ──
  //  末层 >= 0 说明聊天有内容，此时"消息读不到"自相矛盾 → 只能是接口抽风 → 宁可不清
  //
  //  ⚠ **判据必须断言 `已删楼层` 为空**，不能只断言"没写索引" ——
  //    内核的读函数**从不写索引**（只把"该删哪些"交回调用方决定），
  //    所以"没写索引"在任何情况下都成立，那条断言测不到保护。
  const { 存储, 取索引, 取写索引次数 } = 造假存储({
    索引: [3, 5, 7],
    末层: 10,
    消息在: [],   // 3/5/7 都在末层之内，却都读不到
    有快照: [3, 5, 7],
  });

  const 前 = 取索引();
  const 结果 = 取最新有效(存储);

  eq('★ 已删楼层为空（平台异常 → 一条都不许判成已删）', 结果.已删楼层, []);
  eq('索引仍是 3 层', 取索引(), 前);
  eq('没写索引', 取写索引次数(), 0);
}

console.log('\n[#3 平台异常] 只要有一层可疑，本次连"真该删的"也不报');
{
  // ── 代价不对称：判错一次永久丢失，多留一次只是下次再判 ──
  //  索引里有 #20（超出末层 10，本该判已删），也有 #5（在范围内但读不到 → 可疑）。
  //  两者同时存在时，**连 #20 也不报** —— 因为这说明平台状态整体不可信。
  const { 存储 } = 造假存储({
    索引: [3, 5, 20],
    末层: 10,
    消息在: [3],        // 3 在；5 在范围内但读不到 → 可疑
    有快照: [3, 5],
  });

  const 结果 = 取最新有效(存储);

  eq('★ 可疑时不报任何已删（连本该删的 #20 也不报）', 结果.已删楼层, []);
  eq('仍然读到了有效的 #3', 结果.楼层, 3);
}

