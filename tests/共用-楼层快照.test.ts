console.log('\n[#2 自证] 把 `<= 0` 改回 `< 0` → 末层 0 那一档会漏');
{
  // ── 纯逻辑复刻两种判据，证明它们确实不同 ──
  const 旧判据 = (末层: number) => !(末层 >= 0);   // < 0
  const 新判据 = (末层: number) => !(末层 > 0);    // <= 0

  eq('[自证] 末层 0：旧判据说"就绪"（于是会走正常路径去删）', 旧判据(0), false);
  eq('[自证] 末层 0：新判据说"未就绪"', 新判据(0), true);
  ok('[自证] 两者在 0 这一档确实不同', 旧判据(0) !== 新判据(0));

  // 负样本：负数与正数上两者一致（不是"新判据把所有情况都算未就绪"）
  eq('[自证] 末层 -1：两者都说未就绪', [旧判据(-1), 新判据(-1)], [true, true]);
  eq('[自证] 末层 5：两者都说就绪', [旧判据(5), 新判据(5)], [false, false]);
}

