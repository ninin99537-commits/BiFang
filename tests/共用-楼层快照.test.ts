// 共用 · 楼层快照内核 —— 批次 2026-11-20 C1 第 1 步（需求方 #429）。
//
// ── 这个模块从哪来 ──
//  三个插件（彼方 / 烟火 / 剧情导演）各写了一遍「索引 + 有效性判定 + 裁剪 + 清理」。
//  **每一处补丁都只补到一处** —— 这是今天最贵的一类重复。
//
// ── 判据覆盖的不变量（需求方 #429 那张表）──
//  | # | 不变量 |
//  |---|---|
//  | 1 | 索引里只留"楼层存在且快照键匹配"的层 |
//  | 2 | 聊天未就绪（末层 <0 / 抛错）→ **一个字节不写** |
//  | 3 | 层号 ≤ 末层却读不到 = 平台异常 → 不清 |
//  | 4 | 层号 > 末层 = 真被截短 → 删这条 |
//  | 5 | 登记失败 = 这次快照白写 → 返回失败 |
//  | 6 | 裁剪到 K 份，保留最近的 K |
//  | 7 | 删楼后编号重排的认领（内核提供能力，默认不启用） |
import { 取最新有效, 取最近K份, 写一份并登记, 清空 } from '../src/共用/楼层快照';
import type { 快照存储, 快照载荷 } from '../src/共用/楼层快照';

let pass = 0;
let fail = 0;
function ok(名: string, 条件: boolean, 附注?: string) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}${附注 ? `  (${附注})` : ''}`);
  }
}
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}

/**
 * 假存储：把三家平台的"最小形状"做出来。
 *
 * ⚠ 关键：**"楼层还在"与"楼层有快照"是两个独立开关** ——
 *   混成一个会让"重 roll 新 swipe 页"（正常）被误判成"平台异常"。
 */
function 造假存储(选项: {
  索引?: number[];
  末层?: number | '抛错';
  /** 哪些楼层的**消息**还在 */
  消息在?: number[];
  /** 哪些楼层的**变量里有快照** */
  有快照?: number[];
  /** 写索引时返回 false（模拟登记失败） */
  写索引失败?: boolean;
   /** 写楼层时抛错 */
  写楼层失败?: boolean;
}) {
  const 存: any = {
    索引: { 快照楼层: [...(选项.索引 ?? [])], 清空层: 0 },
    楼层: {} as Record<number, 快照载荷>,
  };
  for (const id of 选项.有快照 ?? 选项.索引 ?? []) {
    存.楼层[id] = { 楼层: id, 数据: `第${id}层` };
  }

  const 消息集合 = new Set(选项.消息在 ?? 选项.索引 ?? []);
  let 写索引次数 = 0;
  let 写楼层次数 = 0;
  let 删楼层次数 = 0;

  const 存储: 快照存储 = {
    读索引: () => (存.索引 ? { ...存.索引, 快照楼层: [...存.索引.快照楼层] } : null),
    写索引: (索引) => {
      写索引次数++;
      if (选项.写索引失败)
        return false;
      存.索引 = { ...索引, 快照楼层: [...索引.快照楼层] };
      return true;
    },
    楼层还在: (楼层) => 消息集合.has(楼层),
    读楼层: (楼层) => (存.楼层[楼层] ? { ...存.楼层[楼层] } : null),
    写楼层: (楼层, 载荷) => {
      写楼层次数++;
      if (选项.写楼层失败)
        throw new Error('模拟：写楼层失败');
      存.楼层[楼层] = { ...载荷 };
    },
    删楼层: (楼层) => {
      删楼层次数++;
      delete 存.楼层[楼层];
    },
    末层: () => {
      if (选项.末层 === '抛错')
        throw new Error('模拟：聊天还没就绪');
      return 选项.末层 ?? Math.max(...(选项.索引 ?? [0]), 0);
    },
  };

  return {
    存储,
    存,
    取索引: () => [...存.索引.快照楼层],
    取写索引次数: () => 写索引次数,
    取写楼层次数: () => 写楼层次数,
    取删楼层次数: () => 删楼层次数,
  };
}

