const 验收语言式 = [/第[一二三四五六七八九十0-9]+轮/g, /R[1-9]/g];
// 合法用语(块十八 要求"必须验到不许误伤"): 它们是**指令性**的照抄要求, 不是我们的验收语言。
// 匹配前先把它们从行里抹掉 —— 这三句本身不含任何元词, 所以抹掉**不会掩盖真命中**;
// 它挡住的是"有人日后把 `原样` 这种会撞上豁免项的词列进词表"这种误伤。
const 元词豁免 = ['逐字原样带回', '原样带回', '世界快照'];
/** 命中清单, 形如 `真机@L27` —— **要列出命中的词与位置, 不只报"红"**。 */
function 命中元词(文本: string, 词表: string[] = 验收语言, 式表: RegExp[] = 验收语言式): string[] {
  const 出: string[] = [];
  文本.split('\n').forEach((行, i) => {
    let 净 = 行;
    for (const w of 元词豁免) 净 = 净.split(w).join('\u3000'.repeat(w.length));
    for (const 词 of 词表) if (净.includes(词)) 出.push(`${词}@L${i + 1}`);
    for (const 式 of 式表) for (const 中 of 净.match(式) ?? []) 出.push(`${中}@L${i + 1}`);
  });
  return 出;
}

