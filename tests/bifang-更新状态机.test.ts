// 彼方 · W6 更新状态机 —— 批次: 第二轮(方案 §24 W6 + 复查 P1-11)。
//
// 用户报的现象: 「明明更新成功了，面板却挂红灯 / 按钮变成"重试"」
// 复查 P1-11 报的第二个: 「清空接口地址点更新 → 弹"已更新"绿，而什么都没发生」
//
// 复现方式(不打开酒馆): 按真实日志顺序喂给状态机。
//
// 三条账:
//   发过请求 —— 本轮是否真的发出过一次请求(事实)
//   见过错   —— 本轮是否出现过错误(粘住, 只喂弱提示)
//   最终错误 —— 最后一条日志里的 error(跟随最新)
//
// 覆盖:
//   [A] 复现 W6: 中途失败 + 最终成功 → ok
//   [B] 真失败 → err, 原因可读
//   [C] 用户中断 → idle
//   [D] 弱提示: 重试过 → 状态行多一句, 但不是红灯
//   [E] 上一轮残留不污染本轮
//   [F] **P1-11 新增**: 没发过请求 → idle(既不绿也不红)
import { 吸收日志, 判定本轮收尾, 重试提示, 新建本轮账, 记发过请求 } from '../src/彼方_NPC幕后生命状态系统/更新状态机';

let pass = 0;
let fail = 0;
function ok(名: string, 条件: boolean, 备注?: string) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  FAIL ${名}${备注 ? `  (${备注})` : ''}`);
  }
}
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  FAIL ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}

// ─────────────────────────────────────────────────────────────
console.log('\n[A] 复现 W6: 中途失败、最终成功 → ok(不能是 err)');
{
  // 共用层的真实顺序: 失败一次 → 成功(显式写 error: '')
  let 账 = 记发过请求(新建本轮账());
  账 = 吸收日志(账, { error: '接口调用失败(第 1/3 次): Gateway timeout' });
  eq('[A] 第 1 次失败后: 见过错 = true', 账.见过错, true);
  eq('[A] 第 1 次失败后: 最终错误非空', 账.最终错误 !== '', true);
  // 第 2 次成功: 共用层写一条 error: '' 并带备注
  账 = 吸收日志(账, { error: '', 备注: ['第 1 次接口调用失败, 重试后成功(本轮已正常返回)'] });
  eq('[A] 第 2 次成功后: 最终错误被清空', 账.最终错误, '');
  eq('[A] 第 2 次成功后: 见过错仍为 true(弱提示的依据)', 账.见过错, true);

  const 判定 = 判定本轮收尾({ ...账, 中断: false });
  eq('[A] 收尾状态 = ok(**这是 bug 的判据**)', 判定.状态, 'ok');
  eq('[A] 同时标记"重试过"', 判定.重试过, true);
  eq('[A] 成功时不该有失败原因', 判定.原因, '');

  // 对照: 旧逻辑(只看见过错)会判成 err —— 证明 bug 真实存在过
  const 旧逻辑判定 = 账.见过错 ? 'err' : 'ok';
  ok('[A] 对照: 旧逻辑(只看"见过错")会判成 err', 旧逻辑判定 === 'err');
}

// ─────────────────────────────────────────────────────────────
console.log('\n[B] 真失败: 最终仍失败 → err, 原因可读');
{
  let 账 = 记发过请求(新建本轮账());
  账 = 吸收日志(账, { error: '接口调用失败(第 1/3 次): 500' });
  账 = 吸收日志(账, { error: '接口调用失败(第 2/3 次): 500' });
  账 = 吸收日志(账, { error: '更新失败\n阶段: 接口调用/其他\n错误: 500' });
  const 判定 = 判定本轮收尾({ ...账, 中断: false });
  eq('[B] 三次都失败 → err', 判定.状态, 'err');
  eq('[B] 原因取第一行', 判定.原因, '更新失败');
  eq('[B] 真失败也标记重试过', 判定.重试过, true);

  let 账2 = 记发过请求(新建本轮账());
  账2 = 吸收日志(账2, { error: '接口返回错误: 401 invalid api key' });
  eq('[B] 单行错误的原因', 判定本轮收尾({ ...账2, 中断: false }).原因, '接口返回错误: 401 invalid api key');
  let 账3 = 记发过请求(新建本轮账());
  账3 = 吸收日志(账3, { error: 'x'.repeat(100) });
  eq('[B] 过长原因截断到 40 字', 判定本轮收尾({ ...账3, 中断: false }).原因.length, 40);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[C] 用户中断 → idle, 不挂红灯');
{
  let 账 = 记发过请求(新建本轮账());
  账 = 吸收日志(账, { error: '更新已中断' });
  const 判定 = 判定本轮收尾({ ...账, 中断: true });
  eq('[C] 中断 → idle', 判定.状态, 'idle');
  eq('[C] 中断不算失败(无原因)', 判定.原因, '');

  let 账2 = 记发过请求(新建本轮账());
  账2 = 吸收日志(账2, { error: '接口调用失败: 请求被取消' });
  eq('[C] 中断时即使有错误文案也不挂红灯', 判定本轮收尾({ ...账2, 中断: true }).状态, 'idle');
}

// ─────────────────────────────────────────────────────────────
console.log('\n[D] 弱提示: 重试过 → 状态行多一句, 但不是红灯');
{
  eq('[D] 重试过 → 有提示文案', 重试提示(true), '重试过 1 次');
  eq('[D] 没重试过 → 空串', 重试提示(false), '');
  let 账 = 记发过请求(新建本轮账());
  账 = 吸收日志(账, { error: '第 1 次失败' });
  账 = 吸收日志(账, { error: '' });
  const 判定 = 判定本轮收尾({ ...账, 中断: false });
  eq('[D] 有重试提示时状态仍是 ok', 判定.状态, 'ok');
  ok('[D] 红灯判据只看状态, 不看重试过', 判定.状态 !== 'err');
}

// ─────────────────────────────────────────────────────────────
console.log('\n[E] 上一轮残留不污染本轮');
{
  // 新一轮: 账被重置(界面层在 active 变 true 时做)
  const 新一轮账 = 记发过请求(新建本轮账());
  const 账 = 吸收日志(新一轮账, { error: '' });
  eq('[E] 上一轮的 error 不在本轮账里', 账.最终错误, '');
  eq('[E] 本轮判 ok', 判定本轮收尾({ ...账, 中断: false }).状态, 'ok');

  // 若账没重置(界面层漏了), 残留会不会污染?
  // 不会 —— 最终错误是"跟随最新那条", 新一轮的第一条日志就把它覆盖掉了。
  const 未重置 = { 发过请求: true, 见过错: true, 最终错误: '上一轮的失败' };
  const 覆盖后 = 吸收日志(未重置, { error: '' });
  eq('[E] 即使账没重置, 新日志也会覆盖最终错误', 覆盖后.最终错误, '');
  eq('[E] 所以仍判 ok', 判定本轮收尾({ ...覆盖后, 中断: false }).状态, 'ok');
  eq('[E] 残留只影响弱提示', 覆盖后.见过错, true);
}

// ─────────────────────────────────────────────────────────────
console.log('\n[F] P1-11: 没发过请求 → idle(既不绿也不红)');
{
  // 复现: 清空接口地址点更新 → update.ts 提前 toast return, 一条 error 都没写
  const 空账 = 新建本轮账();
  eq('[F] 新建的账: 发过请求 = false', 空账.发过请求, false);
  const 判定 = 判定本轮收尾({ ...空账, 中断: false });
  eq('[F] 没发过请求 → **idle**(不能是 ok)', 判定.状态, 'idle');
  eq('[F] 也不挂红灯', 判定.状态 !== 'err', true);
  eq('[F] 没有失败原因', 判定.原因, '');
  eq('[F] 也不该说"重试过"', 判定.重试过, false);

  // 对照: 旧逻辑(只看最终错误为空)会判成 ok —— 证明 P1-11 真实存在过
  const 旧逻辑判定 = String(空账.最终错误 ?? '').trim() ? 'err' : 'ok';
  ok('[F] 对照: 旧逻辑(只看最终错误)会判成 ok(弹"已更新"绿)', 旧逻辑判定 === 'ok');

  // 三条提前 return 的路径都一样: 收集本轮输入返回 null / 慢一步只剩一条 / 没填地址
  for (const 场景 of ['没填地址或模型', '没有可分析的 AI 回复', '慢一步但只有一条回复']) {
    const 账 = 吸收日志(新建本轮账(), null);
    eq(`[F] ${场景} → idle`, 判定本轮收尾({ ...账, 中断: false }).状态, 'idle');
  }

  // 一旦发过请求, 判定就回到正常三态
  eq('[F] 发了请求 + 无错 → ok', 判定本轮收尾({ ...记发过请求(新建本轮账()), 中断: false }).状态, 'ok');
  const 失败账 = 吸收日志(记发过请求(新建本轮账()), { error: 'boom' });
  eq('[F] 发了请求 + 有错 → err', 判定本轮收尾({ ...失败账, 中断: false }).状态, 'err');
  // 中断优先级最高(即使没发过请求)
  eq('[F] 中断优先于"没发过请求"', 判定本轮收尾({ ...空账, 中断: true }).状态, 'idle');
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
