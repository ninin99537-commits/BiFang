// 彼方 · 生理规则的随机源可以替换 —— 以前这条规则没法断言。
//
// 周期长度是"首次建档时随机一个、之后锁死"的属性, 受孕是掷骰; 两处都直接调 Math.random(),
// 于是用例只能"蒙住 console 再断言要么怀孕要么没怀", 或者在范围里猜(21~35)。
// 现在随机源是参数: 传固定值就能写出确定断言, 也能钉住"随机只发生一次、之后不再重掷"。
import { 一致化生理, 确保周期长度 } from '../src/彼方_NPC幕后生命状态系统/生理规则';

let pass = 0;
let fail = 0;
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}
function ok(名: string, 条件: boolean) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}`);
  }
}

console.log('\n[1] 周期长度: 固定随机源 → 确定结果(26 + floor((r1+r2)*3.5))');
{
  const 甲 = { 生理周期: '卵泡期 Day 8/28' };
  eq('两个 0 → 26', (确保周期长度(甲, () => 0), 甲['周期长度']), 26);
  const 乙 = { 生理周期: '卵泡期 Day 8/28' };
  eq('两个 0.5 → 29', (确保周期长度(乙, () => 0.5), 乙['周期长度']), 29);
  const 丙 = { 生理周期: '卵泡期 Day 8/28' };
  eq('两个 1 → 33(最大值)', (确保周期长度(丙, () => 0.999), 丙['周期长度']), 26 + Math.floor(0.999 * 2 * 3.5));
  // 已经有周期长度: 永不重掷(哪怕随机源每次都变)
  let 叫了几次 = 0;
  const 丁 = { 生理周期: '卵泡期 Day 8/28', 周期长度: 31 };
  eq('已有值就不写', (确保周期长度(丁, () => { 叫了几次++; return 0; }), 丁['周期长度']), 31);
  eq('连随机源都没碰', 叫了几次, 0);
  // 没有生理字段(男性/未开生理) → 不生成
  const 戊: Record<string, any> = {};
  eq('无生理字段不写', (确保周期长度(戊, () => 0.5), 戊['周期长度']), undefined);
}

console.log('\n[2] 一致化生理: 随机源从参数进来(不再自己去调 Math.random)');
{
  const 卡: Record<string, any> = { 生理周期: '卵泡期 Day 8/28', 是否怀孕: 'false' };
  一致化生理({ 卡, 旧卡: null, 剧情时间: '2026-01-02 12:00', 本轮更新: {}, 随机: () => 0.5 });
  eq('随机 0.5 → 周期长度 29', 卡['周期长度'], 29);

  const 卡2: Record<string, any> = { 生理周期: '卵泡期 Day 8/28', 是否怀孕: 'false' };
  一致化生理({ 卡: 卡2, 旧卡: null, 剧情时间: '2026-01-02 12:00', 本轮更新: {}, 随机: () => 0 });
  eq('随机 0 → 周期长度 26', 卡2['周期长度'], 26);

  // 已经锁死的卡: 换个随机源也不动
  const 卡3: Record<string, any> = { 生理周期: '卵泡期 Day 8/28', 是否怀孕: 'false', 周期长度: 33 };
  一致化生理({ 卡: 卡3, 旧卡: null, 剧情时间: '2026-01-02 12:00', 本轮更新: {}, 随机: () => 0 });
  eq('锁死的周期长度不被重掷', 卡3['周期长度'], 33);
}

console.log('\n[3] 不传随机源时行为不变(默认 Math.random, 仍落在 26~32)');
{
  const 卡: Record<string, any> = { 生理周期: '卵泡期 Day 8/28' };
  确保周期长度(卡);
  ok('落在历史范围 26~32', typeof 卡['周期长度'] === 'number' && 卡['周期长度'] >= 26 && 卡['周期长度'] <= 32);
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0)
  process.exit(1);
