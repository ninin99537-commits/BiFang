console.log('\n[3] 五步终局: 每步一个节拍, 一步只做一步');
{
  const 造 = (步: number) => {
    const 账 = 账本({ 章回: 章({ 进度: '收束' }), 收官请求: true, 终局步: 步 });
    return 构造本幕指令({
      旧指令: null,
      下一幕: { 节拍: '高潮', 硬性要求: '把新反派引进来' },
      账本: 账,
      核验: 已执行 as any,
      档位: 3,
      红线: [],
      楼层: 20,
      暂停注入: false,
    });
  };
  const 节拍序 = [1, 2, 3, 4, 5].map(步 => 造(步).指令?.节拍);
  check('五步的节拍序: 阴影/受挫/余波/高潮/余波', 节拍序, ['阴影', '受挫', '余波', '高潮', '余波']);
  // 2026-11-12 硬约束通道: 五步要求全是**代码裁定** → 现在住 硬约束(以前住 硬性要求, 被渲染成"建议")。
  // 反向断言(某句不该出现)看两个通道: 裁定 ∪ 建议 —— 漏到哪一边都是漏。
  const 裁定 = (步: number) => (造(步).指令?.硬约束 ?? []).join('\n');
  const 正文可见 = (步: number) => `${裁定(步)}\n${造(步).指令?.硬性要求 ?? ''}`;
  ok('第 1 步点名"召集"', 裁定(1).includes('终局第 1/5 步：召集'));
  ok('第 2 步要求计划失败, 且失败原因与主角缺口有关', 裁定(2).includes('让计划**失败**') && 裁定(2).includes('缺口'));
  ok('第 3 步要求"不要讲道理"', 裁定(3).includes('不要讲道理'));
  ok('第 4 步要求价值观分胜负', 裁定(4).includes('价值观'));
  ok('第 5 步不总结不升华', 裁定(5).includes('不总结、不升华'));
  ok('每步都写明"只做这一步"', [1, 2, 3, 4, 5].every(步 => 裁定(步).includes('这一幕只做这一步')));
  // 2026-11-12 需求方抓到的重复投递: 禁令曾在 硬约束 里出现两条(收束要求的「全程禁止」+ 字面量又拼一条)。
  // 这里同时钉住"有"与"只一条" —— 以后再加一条同义禁令就会红。
  ok('每步都禁止开新伏笔', [1, 2, 3, 4, 5].every(步 => 裁定(步).includes('不新增伏笔')));
  check('每步的"不新增伏笔"只能有一条(防重复投递)', [1, 2, 3, 4, 5].map(步 => (造(步).指令?.硬约束 ?? []).filter(项 => 项.includes('不新增伏笔')).length), [1, 1, 1, 1, 1]);

  check('终局步缺省(0) → 当作第 1 步', 造(0).指令?.节拍, '阴影');
  check('终局步越界(6) → 收到第 5 步', 造(6).指令?.节拍, '余波');
  ok('AI 报的"引进新反派"不会混进收束幕', !正文可见(1).includes('把新反派引进来'));
}

