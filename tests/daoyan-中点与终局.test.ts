setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

const 账本 = (部分: Partial<导演账本> = {}): 导演账本 => ({ ...emptyData(), 已分析轮数: 10, ...部分 });
const 已执行 = { 已执行: true, 顶回冲突: '', 说明: '', 主角死亡: false, 核验来源: '明确' as const };
const 章 = (部分: Record<string, any> = {}) => ({ 章号: 1, 主题: 'x', 计划高潮: '', 进度: '推进', 幕纲: ['a', 'b', 'c', 'd'], 当前幕号: 2, ...部分 }) as any;

// ---------------------------------------------------------------------------
console.log('\n[1] 中点: 类型只认两个值, 漏写沿用旧值, 没内容不留空壳');
{
  const 一 = 应用引擎输出(账本({ 章回: 章() }), { 章回: 章({ 中点: { 类型: '假失败', 内容: '他彻底失去通行权', 过了: false } }) }, 12);
  check('类型读得回来', 一.账本.章回?.中点?.类型, '假失败');
  check('过了读得回来', 一.账本.章回?.中点?.过了, false);

  const 乱写 = 应用引擎输出(账本({ 章回: 章() }), { 章回: 章({ 中点: { 类型: '大逆转', 内容: '他以为是胜利' } }) }, 12);
  check('怪类型 → 按假胜利处理', 乱写.账本.章回?.中点?.类型, '假胜利');
  ok('并记一笔拒绝', 乱写.拒绝.some(x => x.includes('中点没写类型')));

  const 漏写 = 应用引擎输出(账本({ 章回: 章({ 中点: { 类型: '假胜利', 内容: '他以为赢了', 过了: false } }) }), { 章回: 章() }, 12);
  check('这一轮漏写中点 → 沿用旧的(不静默清掉)', 漏写.账本.章回?.中点?.内容, '他以为赢了');

  const 空壳 = 应用引擎输出(账本({ 章回: 章() }), { 章回: 章() }, 12);
  ok('从没写过 → 不留空壳(老账本读回逐字一致)', !('中点' in (空壳.账本.章回 ?? {})));

  const 迁移 = sanitizeSnapshot({ 章回: 章({ 中点: { 类型: '假失败', 内容: '全完了' } }) });
  check('快照装载也认这条', 迁移.章回?.中点?.类型, '假失败');
  check('快照装载: 没写过了 → false', 迁移.章回?.中点?.过了, false);

  // 换章了还沿用 = 把上一章的中点搬到新章头上, 比没有中点更糟(2026-11-12 自查)
  const 换章 = 应用引擎输出(
    账本({ 章回: 章({ 章号: 1, 中点: { 类型: '假胜利', 内容: '第一章的中点', 过了: false } }) }),
    { 章回: 章({ 章号: 2 }) },
    12,
  );
  check('换章 → 不沿用上一章的中点', 换章.账本.章回?.章号, 2);
  ok('上一章的中点没有搬过来', !('中点' in (换章.账本.章回 ?? {})));
}

