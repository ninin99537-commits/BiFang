console.log('\n[4] 终局步的存亡: 随快照走, 解除剧终时清零');
{
  const 存 = sanitizeSnapshot({ 终局步: 3 });
  check('快照装载读回步数', 存.终局步, 3);
  check('越界值被夹住', sanitizeSnapshot({ 终局步: 99 }).终局步, 5);
  check('负值夹到 0', sanitizeSnapshot({ 终局步: -2 }).终局步, 0);
  check('老账本没有 → 0', sanitizeSnapshot({}).终局步, 0);

  const 账 = 账本({ 已剧终: true, 收官请求: true, 终局步: 4 });
  解除剧终(账);
  check('解除剧终 → 步数清零(再剧终要重走五步)', 账.终局步, 0);
  check('解除剧终也清收官请求', 账.收官请求, false);

  const 请求后 = 账本();
  请求收官(请求后);
  check('刚请求收官时步数还没动(下一轮推进才 +1)', 请求后.终局步, 0);
}

