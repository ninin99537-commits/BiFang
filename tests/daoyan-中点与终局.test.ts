// 剧情导演 · 中点 + 五步终局(2026-11-12)
//
// 两个技法各补一个**结构节点**:
//   · Midpoint(BS2): 半程的假胜利/假失败 —— 而且必须让 A 线(欲望)与 B 线(关系)交汇, 之后赌注升级。
//     原来只有一句"中点要有反转", 靠 `幕号 === ceil(总幕/2)` 猜; 现在有 章回.中点 这个显式锚点。
//   · 五步终局(BS2): 召集 → 执行计划并失败 → 挖心 → 新方案 → 落幕。
//     终局是**一串戏**, 不是一场戏: 以前每轮收束幕都把"回收伏笔+收束主线+不总结+落幕"整段发一遍,
//     演出来就是"什么都想在一场里完成"。现在按 账本.终局步 每轮只做一步, 节拍也跟着这一步走。
