console.log('\n[5] 终局步的推进口径: 只有真产出收束幕才算走一步');
{
  // 步数跑在戏前面, 真开演时只剩半步可演。判据用 `构造.指令` —— 平静(空构造)/冷启动/暂停注入
  // 那三种情况 构造 返回 null, 步数自然不动; 自己再抄一遍三个前提一定会漂。
  const 源 = updateSource;
  ok('推进判据挂在"有没有产出指令"上', /账本\.终局步 = 构造\.指令 && 新楼层 \? Math\.min\(5, 已走 \+ 1\) : 已走;/.test(源));
  ok('不再自己抄"非平静/非暂停"的副本', !/该走 = 新楼层 && !平静 && !暂停注入/.test(源));
  ok('同一个"暂停注入"只算一次(构造与死亡分支共用)', (源.match(/真实命运 \? 新死亡 && !续演视角 : 新死亡/g) ?? []).length === 1);
  ok('构造时复用同一个暂停标志', /暂停注入,\n/.test(源));
  ok('重推同一楼不走步(新楼层 才算)', 源.includes('anchorFloor > (Number(data.处理到楼层) || 0)'));
}

