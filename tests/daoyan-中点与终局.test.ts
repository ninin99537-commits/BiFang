console.log('\n[2] 结构提醒: 中点没计划就催计划, 到位置没兑现就催兑现');
{
  const 无 = 结构提醒(账本({ 章回: 章() }), 12);
  ok('没有中点 → 催安排(并说明假胜利/假失败)', 无.some(x => x.includes('「中点」') && x.includes('假胜利') && x.includes('假失败')));

  const 未到 = 结构提醒(账本({ 章回: 章({ 当前幕号: 1, 中点: { 类型: '假胜利', 内容: '他以为赢了', 过了: false } }) }), 12);
  ok('还没演到半程 → 不催兑现', !未到.some(x => x.includes('中点位置')));

  const 到点 = 结构提醒(账本({ 章回: 章({ 当前幕号: 2, 中点: { 类型: '假胜利', 内容: '他以为赢了', 过了: false } }) }), 12);
  ok('演到半程还没兑现 → 催', 到点.some(x => x.includes('中点位置') && x.includes('他以为赢了')));
  ok('并点明 A 线欲望与 B 线要交汇', 到点.some(x => x.includes('A 线') && x.includes('B 线') && x.includes('交汇')));
  ok('并要求兑现后赌注升级', 到点.some(x => x.includes('能不能不失去')));

  const 过了 = 结构提醒(账本({ 章回: 章({ 当前幕号: 2, 中点: { 类型: '假胜利', 内容: '他以为赢了', 过了: true } }) }), 12);
  ok('已兑现 → 不再催', !过了.some(x => x.includes('中点位置')));
}

