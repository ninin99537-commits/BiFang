// 剧情导演 · 批次 F（提示词九条）—— 2026-11-13
//
// 九条里八条是文案，只有一条是**行为**（#1 严格贴合档下不再要求"把对应伏笔改为已消亡"）。
// 判据按需求方的口径：只改文案的 → 旧说法清零、新说法在；改行为的 → 直接调函数看输出。
import { readFileSync } from 'node:fs';
import { build原著约束 } from '../src/剧情导演/prompts';

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

const 提示 = readFileSync('src/剧情导演/prompts.ts', 'utf8');
const 提醒 = readFileSync('src/剧情导演/提醒.ts', 'utf8');
const 计数 = (源: string, 词: string) => 源.split(词).length - 1;

// ---------------------------------------------------------------------------
console.log('\n[F#1] 严格贴合档：不许再教它"把伏笔改为已消亡"（行为，直接调函数）');
{
  const 严格 = build原著约束('严格贴合');
  const 允许 = build原著约束('允许偏离');
  ok('严格贴合 → 含有"节点结果不可改写"', 严格.includes('节点结果不可改写'));
  check('严格贴合 → **不出现**"改为「已消亡」"（这条能失败：改回去就红）', 计数(严格, '改为「已消亡」'), 0);
  ok('严格贴合 → 保留"不再要求剧情回拽"（不回拽但要保留正文事实）', 严格.includes('不再要求剧情回拽'));
  // 反向：允许偏离档仍要保留原语义
  check('允许偏离 → 仍有"改为「已消亡」"', 计数(允许, '改为「已消亡」'), 1);
  ok('允许偏离 → 仍有"按已发生的结果重算"', 允许.includes('按已发生的结果重算'));
  // 关闭档什么都不拼
  check('关闭档 → 空串', build原著约束('关闭'), '');
}

console.log('\n[F#2] 对手出手：与代码一致（只催一条、排除铺垫与杂兵）');
{
  check('旧说法"每个未收档的冲突"清零', 计数(提示, '每个未收档的冲突'), 0);
  ok('新说法在（一轮只点名最逾期的一条）', 提示.includes('一轮只点名最逾期的一条'));
  ok('新说法点明只催 升级/僵持/决战', 提示.includes('「升级/僵持/决战」阶段的未收档冲突'));
  ok('新说法排除铺垫与杂兵', 提示.includes('「铺垫」阶段、以及强度 ≤3 又没伏笔挂着的小麻烦不催'));
}

console.log('\n[F#3] 催办节流 vs 兑现条件自检（前者节流、后者每轮自检）');
{
  check('旧说法"同一章只会被催一次"清零', 计数(提示, '同一章只会被催一次'), 0);
  ok('写明按 最近催办章 节流', 提示.includes('代码按') && 提示.includes('最近催办章') && 提示.includes('节流'));
  ok('写明「兑现条件自检」不受此限', 提示.includes('「兑现条件自检」不受此限'));
}

console.log('\n[F#4] 回收窗口只写它时 = 同时当最早与最迟');
{
  ok('写明"同时被当作最早章与最迟章"', 提示.includes('同时被当作最早章与最迟章'));
  ok('并给出做法（想早点可催就写 目标窗口.最早章）', 提示.includes('想让它早点可催就必须写'));
}

console.log('\n[F#5] 幕型 vs 节拍：措辞改正（代码里没有"日常就不提醒"的门）');
{
  check('旧措辞"若这一幕是事件幕"清零（提醒.ts）', 计数(提醒, '若这一幕是事件幕'), 0);
  ok('新措辞在（若这一幕的节拍不是「日常」）', 提醒.includes('若这一幕的节拍不是「日常」'));
  // 说明：这条是**纯文案**，代码没有 gate —— 见交付报告里的口径确认请求
  ok('确认：该规则函数体里没有"节拍===日常 → return []"这类门', !/若这一幕的节拍不是[\s\S]{0,200}return \[\]/.test(提醒.slice(提醒.indexOf("名: '对手该出手'"), 提醒.indexOf("名: '对手该出手'") + 700)));
}

console.log('\n[F#6] 两处静默截断，提示词要说出来');
{
  ok('读者领先上限 12 条已写明', 提示.includes('最多 12 条') && 提示.includes('最久没更新'));
  ok('知情核对上限 8 条已写明', 提示.includes('「知情核对」最多 8 条'));
  ok('并点明是静默丢弃', 提示.includes('静默丢弃'));
}

console.log('\n[F#7] 累积事实：整份替换 + 命运册三字段例外');
{
  check('"只增不减"清零（与"少了的就没了"互斥）', 计数(提示, '只增不减'), 0);
  ok('写成整份替换', 提示.includes('它们按**整份替换**'));
  ok('命运册三字段的例外写明（空数组会被判无证据复原）', 提示.includes('无证据复原') && 提示.includes('整体保留旧值'));
  // 代码侧也补了注释说明两边语义不同
  const 账本数据 = readFileSync('src/剧情导演/账本数据.ts', 'utf8');
  ok('账本数据.累积事实字段 旁有"两边语义不同"的注释', 账本数据.includes('不是同一套合并语义'));
}

console.log('\n[F#8] 下一幕.揭示：模板里有、提示词教它怎么写');
{
  ok('模板里出现 "揭示":[]', 提示.includes('"揭示":[]'));
  ok('有说明条目（原样进指令 / 幕后真相不自动透传）', 提示.includes('原样进指令') && 提示.includes('幕后真相不自动透传'));
}

console.log('\n[F#9] 阈值措辞与判据同口径（>= 6 就说"到 6 条/满 6 场"）');
{
  check('"超过 6 条"清零', 计数(提示, '超过 6 条'), 0);
  ok('改成"到 6 条就告警"', 提示.includes('到 6 条就告警'));
  check('"6 场以上"清零', 计数(提醒, '6 场以上'), 0);
  ok('改成"满 6 场没动过"', 提醒.includes('满 6 场没动过'));
}

// ---------------------------------------------------------------------------
console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0) process.exit(1);
