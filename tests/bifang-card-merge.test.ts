// 彼方 · 字段协议的表驱动用例 —— 钉的是"表被遵守", 不是某一条规则的口径。
//
// 逐字段用例(update-pipeline / bifang-backstage-ledger / bifang-love-rules …)钉的是"这条规则的具体口径",
// 这一份钉的是另一件事: 字段表里**每一行的 合并方式 都真的被执行**, 两条写入路径(增量 / 整份)
// 的差别**只由语境决定**。加一个字段只要在表里标了列, 这里自动开始管它。
import { 合并 } from '../src/彼方_NPC幕后生命状态系统/卡合并';
import { CARD_FIELDS, 字段表, 扩展编辑字段, 合并方式表 } from '../src/彼方_NPC幕后生命状态系统/卡字段';

// 卡合并 的判定型尾部会用到酒馆注入的 `_`(lodash), 用例里给一个最小替身
(globalThis as any)._ = {
  clamp: (value: number, lower: number, upper: number) => Math.min(Math.max(value, lower), upper),
  cloneDeep: (value: any) => (value === undefined ? undefined : JSON.parse(JSON.stringify(value))),
};

let pass = 0;
let fail = 0;
function ok(名: string, 条件: boolean) {
  if (条件) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}`);
  }
}
function eq(名: string, 实际: any, 期望: any) {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a === b) {
    pass++;
  }
  else {
    fail++;
    console.log(`  ✗ ${名}\n      期望 ${b}\n      实际 ${a}`);
  }
}

/** 剧情时间固定: 相对时刻补全 / 台账紧迫度都按它算 */
const 剧情时间 = '2026-01-02 12:00';
const AI = { 剧情时间, 写入: '增量', 空值: '跳过', 钩子: '仅清理' } as const;
const 玩家 = { 剧情时间, 写入: '整份', 空值: '删除', 钩子: '仅清理' } as const;

console.log('\n[1] 每一种 合并方式 都真的被执行');
{
  // 覆盖: 有值就换, 没给就不动
  eq('覆盖 · 有值替换', 合并({ 位置: '旧地' }, { 位置: '新地' }, AI)['位置'], '新地');
  eq('覆盖 · 没给不动', 合并({ 位置: '旧地' }, {}, AI)['位置'], '旧地');
  eq('覆盖 · 增量里空串=没给', 合并({ 位置: '旧地' }, { 位置: '  ' }, AI)['位置'], '旧地');

  // 追加: 增量往后加, FIFO 3 条
  eq('追加 · 增量并进去', 合并({ 近期关键事件: '2026-01-01 甲' }, { 近期关键事件: '2026-01-02 乙' }, AI)['近期关键事件'], '2026-01-01 甲；2026-01-02 乙');
  ok('追加 · 最多 3 条', String(合并({ 近期关键事件: '2026-01-01 甲；2026-01-02 乙；2026-01-03 丙' }, { 近期关键事件: '2026-01-04 丁' }, AI)['近期关键事件']).split('；').length === 3);
  eq('追加 · 整份是替换', 合并({ 近期关键事件: '2026-01-01 甲' }, { 近期关键事件: '2026-01-02 乙' }, 玩家)['近期关键事件'], '2026-01-02 乙');

  // 按类目: 增量按类目并(缺的类目保留旧值), 整份是替换
  const 旧生活 = '吃饭(2026-01-01 08:00); 洗漱(2026-01-01 09:00)';
  const 增量生活 = String(合并({ 生活状态: 旧生活 }, { 生活状态: '睡眠(2026-01-02 23:00-次日07:00)' }, AI)['生活状态']);
  ok('按类目 · 增量保留旧类目', 增量生活.includes('吃饭') && 增量生活.includes('洗漱') && 增量生活.includes('睡眠'));
  const 整份生活 = String(合并({ 生活状态: 旧生活 }, { 生活状态: '吃饭(2026-01-02 12:00)' }, 玩家)['生活状态']);
  ok('按类目 · 整份只留新的一条', 整份生活.includes('吃饭') && !整份生活.includes('洗漱'));
  // 状态词(已用/已洗)两条路径都剥掉
  ok('按类目 · 剥掉状态词', !String(合并({}, { 生活状态: '洗漱(2026-01-02 09:00 已洗)' }, AI)['生活状态']).includes('已洗'));

  // 台账: 增量并进去, 整份换掉; 旧格式字符串两条路径都自愈成数组
  const 旧账 = [{ 编号: 'T1', 时间: '2026-01-01', 内容: '给女儿买玩偶', 状态: '进行中' }];
  const 增量账 = 合并({ 未完成事项: 旧账 }, { 未完成事项: [{ 内容: '答应周五同行' }] }, AI)['未完成事项'];
  eq('台账 · 增量并成两条', (增量账 as any[]).length, 2);
  const 整份账 = 合并({ 未完成事项: 旧账 }, { 未完成事项: [{ 内容: '答应周五同行' }] }, 玩家)['未完成事项'];
  eq('台账 · 整份只留一条', (整份账 as any[]).length, 1);
  eq('台账 · 没给也自愈成数组', (合并({ 未完成事项: '给女儿买玩偶' }, {}, AI)['未完成事项'] as any[])[0].编号, 'T1');
  eq('台账 · 整句"无"自愈成空账', 合并({ 未完成事项: '无' }, {}, AI)['未完成事项'], []);

  // 词表: 合法词落库, 全非法保留旧值
  eq('词表 · 只留词表内的词', 合并({}, { 恋爱标签: '青梅竹马、瞎编的词' }, AI)['恋爱标签'], '青梅竹马');
  eq('词表 · 全非法保留旧值', 合并({ 恋爱标签: '单恋' }, { 恋爱标签: '瞎编的词' }, AI)['恋爱标签'], '单恋');
  eq('词表 · 最多 5 个', String(合并({}, { 恋爱标签: '青梅竹马/主仆/单恋/冷战/心结/猜忌' }, AI)['恋爱标签']).split('、').length <= 5, true);
}

console.log('\n[2] 表里每一行都声明了 合并方式(缺省=覆盖也算声明)');
{
  // 合并方式表 覆盖全部字段: 新加一个字段忘了这一列, 这里会立刻显形
  eq('字段数 = 合并方式表条目数', 字段表.length, Object.keys(合并方式表).length);
  const 允许 = ['覆盖', '追加', '按类目', '台账', '词表'];
  ok('每行的合并方式都在那五种里', 字段表.every(f => 允许.includes(合并方式表[f.名])));
  // 每个字段都真的能被"合"一次: 不抛错, 且结果是个对象
  for (const 字段 of 字段表) {
    const 结果 = 合并({ [字段.名]: '旧值' }, { [字段.名]: '新值' }, AI);
    ok(`${字段.名} 合并不抛错`, !!结果 && typeof 结果 === 'object');
  }
}

console.log('\n[3] 整份(玩家)路径: 每个可编辑字段都落得下、清得掉');
{
  const 可编辑 = [...CARD_FIELDS, ...扩展编辑字段];
  /** 每个字段都要用**它自己那种形态**的样值: 台账是数组/旧串, 词表得是词表里的词 */
  const 样值 = (名: string) => (合并方式表[名] === '词表' ? '单恋' : '手写的值');
  for (const 名 of 可编辑) {
    const 值 = 样值(名);
    const 写入 = 合并({}, { [名]: 值 }, 玩家, undefined, [名]);
    if (合并方式表[名] === '台账')
      ok(`${名} 能写进去`, Array.isArray(写入[名]) && (写入[名] as any[]).length === 1);
    else
      eq(`${名} 能写进去`, 写入[名], 值);
    // 清空 = 删字段(台账除外: 它的"清空"是传空数组)
    const 清空 = 合并({ [名]: '旧值' }, { [名]: 合并方式表[名] === '台账' ? [] : '' }, 玩家, undefined, [名]);
    ok(`${名} 清空即删字段`, 清空[名] === undefined);
  }
  // 加 NPC 那条路(整份 + 跳过): 没填的格子不许把已有值抹掉
  const 加档 = 合并({ 位置: '已有' }, { 位置: '' }, { ...玩家, 空值: '跳过' });
  eq('整份+跳过: 空格子不删', 加档['位置'], '已有');
}

console.log('\n[4] 不该留在卡上的键: 两条路径都清');
{
  for (const 语境 of [AI, 玩家]) {
    const 卡 = 合并({ 持有物: '旧清单', 可能偶遇: 'true', 剧情时间: '2026-01-01', 人设参考: '别人的设定' }, {}, 语境);
    ok(`${语境.写入} · 清掉废弃键`, 卡['持有物'] === undefined && 卡['可能偶遇'] === undefined && 卡['剧情时间'] === undefined && 卡['人设参考'] === undefined);
  }
}

console.log('\n[5] 批2·B1: 内心三件套改名 + 旧键迁移(V15/V7/V8)');
{
  // V7: 两份清单同步 —— 旧名必须两边都不在了
  for (const 旧名 of ['心里惦记', '秘密想法', '隐藏目标'])
    ok(`旧名「${旧名}」不在 CARD_FIELDS`, !CARD_FIELDS.includes(旧名));
  for (const 旧名 of ['心里惦记', '秘密想法', '隐藏目标'])
    ok(`旧名「${旧名}」不在 字段表`, !字段表.some(f => f.名 === 旧名));
  // 新名必须两边都在(否则模型写不了 / 界面看不见)
  for (const 新名 of ['心事', '藏起来的打算']) {
    ok(`新名「${新名}」在 CARD_FIELDS`, CARD_FIELDS.includes(新名));
    ok(`新名「${新名}」在 字段表`, 字段表.some(f => f.名 === 新名));
  }

  // V8: 把"改名"与"校验失败"区分开 —— 这两个错误长得像, 但原因完全不同。
  // 改名导致的症状: 旧键在卡上但不在 字段表 → 读出来看不见。
  // 校验失败的症状: 新卡缺 建档必填 → checkCard 判不合格。
  {
    const 旧卡 = { 心里惦记: '弟弟的学费', 秘密想法: '想离开这座城', 隐藏目标: '查清真相' };
    const 迁移后 = 合并(旧卡, {}, AI);
    eq('V8: 旧键迁移后 心事 拿到两个旧值(用；连接)', 迁移后['心事'], '弟弟的学费；想离开这座城');
    eq('V8: 旧键迁移后 藏起来的打算 拿到隐藏目标', 迁移后['藏起来的打算'], '查清真相');
    ok('V8: 旧键已清(不再留在卡上)', !('心里惦记' in 迁移后) && !('秘密想法' in 迁移后) && !('隐藏目标' in 迁移后));
  }

  // 新旧都有时: 新值优先, 旧值追加
  {
    const 卡 = { 心事: '新惦记', 心里惦记: '旧惦记' };
    const 迁移后 = 合并(卡, {}, AI);
    eq('新旧都有: 新值在前、旧值追加', 迁移后['心事'], '新惦记；旧惦记');
    ok('新旧都有: 旧键被清掉', !('心里惦记' in 迁移后));
  }

  // 幂等: 迁过一次之后再合一次, 结果不变
  {
    const 一次 = 合并({ 心里惦记: '弟弟的学费' }, {}, AI);
    const 两次 = 合并(一次, {}, AI);
    eq('迁移幂等(再合一次结果不变)', 两次['心事'], 一次['心事']);
  }

  // 只有旧键、新键为空: 旧值搬过去
  {
    const 迁移后 = 合并({ 心里惦记: '只有旧的' }, {}, AI);
    eq('只有旧键时旧值搬到新键', 迁移后['心事'], '只有旧的');
  }

  // 旧键为空串: 清掉旧键, 不写新键
  {
    const 迁移后 = 合并({ 心里惦记: '   ', 当前在做: '做饭' }, {}, AI);
    ok('旧键是空串: 旧键被清掉', !('心里惦记' in 迁移后));
    ok('旧键是空串: 不写新键(不给每张卡新增恒空字段)', 迁移后['心事'] === undefined);
  }
}

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
if (fail > 0)
  process.exit(1);
