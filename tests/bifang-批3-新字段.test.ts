// ---------------------------------------------------------------- [7] 新字段不会被迁移误判
console.log('\n[7] 新字段不会被 迁移旧字段名 误判搬走');
{
  const 映射键 = Object.keys(改名字段);
  console.log(`  改名字段表共 ${映射键.length} 条: ${映射键.join(' / ')}`);
  for (const 新字段 of ['衣物/随身物', '伤势/体力']) {
    ok(`「${新字段}」不在映射表的键里`, !映射键.includes(新字段));
    ok(`「${新字段}」不在映射表的值里`, !Object.values(改名字段).includes(新字段));
  }
  const 卡 = { '衣物/随身物': '深灰工装外套', '伤势/体力': '左小臂绷带渗血', 当前在做: '修发电机' };
  const 迁移后 = 迁移旧字段名(卡);
  check('迁移后 衣物/随身物 原样保留', 迁移后?.['衣物/随身物'], 卡['衣物/随身物']);
  check('迁移后 伤势/体力 原样保留', 迁移后?.['伤势/体力'], 卡['伤势/体力']);
  ok('迁移函数返回原对象引用（无旧键时不复制 = 零开销）', 迁移后 === 卡);
}

