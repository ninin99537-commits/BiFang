// ---------------------------------------------------------------- [3] 注入表两列（V1 短字段逐字）
console.log('\n[3] 注入表两列：存在、逐字一致、无值时不出现');
{
  const 卡 = {
    当前在做: '在车库里修发电机',
    当前状态: '专注, 眉头皱着',
    位置: '车库',
    '衣物/随身物': '深灰工装外套、腰侧别着对讲机、肩上挎帆布包',
    '伤势/体力': '左小臂绷带渗血, 抬臂吃力',
    心事: '蒂娜还在生气',
  };
  const 注入 = buildInjectionPrompt([['艾莉', 卡]], { 剧情时间: '2039-09-17 11:35', 生理监测: false });
  const 表头 = 注入.split('\n').find(l => l.startsWith('名字')) ?? '';
  const 数据 = 注入.split('\n').find(l => l.startsWith('艾莉')) ?? '';
  const 列们 = 表头.split(' | ');
  const 值们 = 数据.split(' | ');
  const 取列 = (名: string) => { const i = 列们.indexOf(名); return i < 0 ? null : 值们[i]; };

  ok('注入表有「衣着」列', 列们.includes('衣着'), 列们.join(','));
  ok('注入表有「伤情」列', 列们.includes('伤情'));
  check('衣着列逐字一致（V1 短字段）', 取列('衣着'), 卡['衣物/随身物']);
  check('伤情列逐字一致（V1 短字段）', 取列('伤情'), 卡['伤势/体力']);

  const 空注入 = buildInjectionPrompt([['甲', { 当前在做: '坐着', 当前状态: '平静', 位置: '家' }]], { 剧情时间: '2039-09-17 11:35', 生理监测: false });
  const 空表头 = 空注入.split('\n').find(l => l.startsWith('名字')) ?? '';
  ok('无值时「衣着」列不出现（动态列）', !空表头.includes('衣着'), 空表头);
  ok('无值时「伤情」列不出现（动态列）', !空表头.includes('伤情'), 空表头);
}

// ---------------------------------------------------------------- [4] 分工互斥（只能靠样例证明）
console.log('\n[4] 分工互斥：当前状态 vs 伤势/体力 不写同一件事');
{
  const 伤情关键词 = ['绷带', '渗血', '抬臂'];

  const 好 = { 当前状态: '烦躁, 说话带刺', '伤势/体力': '左小臂绷带渗血, 抬臂吃力' };
  ok('好样例：当前状态 不含伤情关键词', !伤情关键词.some(k => 好.当前状态.includes(k)), 好.当前状态);
  ok('好样例：伤势/体力 含伤情关键词', 伤情关键词.some(k => 好['伤势/体力'].includes(k)));

  // 反例必须真的能触发判据 —— 否则这条断言是空转（这是我在批3 踩过的坑）
  const 坏 = { 当前状态: '左小臂绷带渗血, 抬臂吃力, 因为这样很烦躁', '伤势/体力': '左小臂绷带渗血, 抬臂吃力' };
  ok('坏样例：当前状态 确实含伤情（证明判据能抓到重复）', 伤情关键词.some(k => 坏.当前状态.includes(k)), 坏.当前状态);

  // 提示词里必须写死这条分工
  const 文本 = buildUpdateMessages({
    reply: '【最新回复】\n2039-09-17 11:35 车库里很安静。',
    replyCount: 1,
    tracked: ['艾莉'],
    inSceneHint: ['艾莉'],
    currentCards: { 艾莉: { 当前在做: '修发电机', 当前状态: '专注', 位置: '车库' } },
    currentStoryTime: '2039-09-17 10:00',
    storyTimeHint: '2039-09-17 11:35',
    storySpan: '约 2 小时（按正文时刻估算）(≤6 小时, 同一段生活内)',
    physioEnabled: false,
  }).messages.map(m => m.content).join('\n');

  ok('提示词：伤势/体力 只写身体客观状况', 文本.includes('只写身体客观状况'));
  ok('提示词：两边不许重复同一件事', 文本.includes('两边不许重复同一件事'));
  ok('提示词：无伤无累留空', 文本.includes('无伤无累就留空'));
  ok('提示词：衣物/随身物 只写此刻这一身', 文本.includes('只写此刻'));
  ok('提示词：当前状态不写身体伤情', 文本.includes('也不写身体伤情'));
}

