console.log('\n[3] 三处旧方言的差异只剩两条: 快照不认别名、不填缺省');
{
  const ai = 规范化事件字段({ 标题: 'x' }, 'AI', { 世界时间: '2008年5月2日' });
  check('AI · 时间回落世界时间', ai?.时间, '2008年5月2日');
  check('AI · 空描述填默认', ai?.描述, '（无描述）');

  const 手 = 规范化事件字段({ 标题: 'x' }, '手改', { 世界时间: '2008-05-02' });
  check('手改 · 时间回落世界时间', 手?.时间, '2008-05-02');
  check('手改 · 空描述填默认', 手?.描述, '（无描述）');

  const 快 = 规范化事件字段({ 标题: 'x' }, '快照');
  check('快照 · 时间不回落', 快?.时间, '');
  check('快照 · 空描述保持空', 快?.描述, '');

  const 快别名 = 规范化事件字段({ 标题: 'x', 经过: '旧快照不该认别名' }, '快照');
  check('快照 · 忽略 AI 别名', 快别名?.描述, '');
}

