// 烟火 · 事件字段收口
//
// 症状: WorldEvent 的 14 个字段被手抄六份(schema / 提示词 JSON / 提示词规则 / 注入行 /
// 三个规范化器 / 面板模板), 而且三处方言已经不同 —— normalizeEvent 时间缺省回落 worldTime、
// 认「经过/详情/概述」别名; 重建事件 时间缺省是 ''、不认别名; 保存事件 逐字段字面构造。
// 加一个字段要改六个文件, 漏一处就在读回或手改保存时静默丢字段。
//
// 现在字段知识只有 世界字段表.事件层 一份, 三种模式走同一个 规范化事件字段, 差异只剩两条:
//   ① 快照模式不认别名; ② 快照模式不填缺省(时间也不回落世界时间)。
import { 事件层, 规范化事件字段, 事件JSON示例, 注入表头, 注入行 } from '../src/烟火_世界运转/世界字段表';
import { EVENT_STAGE } from '../src/烟火_世界运转/schema';

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  }
  else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, condition: boolean) {
  check(label, condition, true);
}

console.log('\n[1] 事件层是字段清单的唯一来源');
{
  check('字段与顺序(= WorldEvent 声明顺序, 去掉 id/演变)', 事件层.字段.map(字段 => 字段.键), [
    '标题', '描述', '地点', '时间', '规模', '传播',
    '渠道', '势力', '阶段', '隐秘', '代表人物', '前情',
  ]);
  check('名称键', 事件层.名称键, '标题');
  check('容量沿用 EVENT_LIMIT', 事件层.容量, 30);
  // 阶段 的"枚举 + 兜底"只有这一处: 管线(世界数据.ts)不再决定它, 见 world-data.test.ts [21]
  const 阶段 = 事件层.字段.find(字段 => 字段.键 === '阶段');
  check('阶段的枚举与兜底在事件层', [阶段?.枚举, 阶段?.兜底], [EVENT_STAGE, '进行']);
}

