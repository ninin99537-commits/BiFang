// 测试 · 源码扫描工具（2026-11-20 抽出）
//
// ── 为什么要有这个文件 ──
//
//  今天有**三次**断言被注释干扰：
//
//  | 位置 | 注释里写了什么 | 断言误判成 |
//  |---|---|---|
//  | `daoyan-spoiler-finale` | "落盘由调用方 `saveData` 负责" | 平台调用 |
//  | `bifang-prompt-逐字节` | "原来是 `${physioEnabled ? PHYSIO_AUTHORITY_BLOCK : ''}`" | 段内三元还在 |
//  | （同类第三次） | — | — |
//
//  三次都是同一个形状：**断言扫全文，而注释里在"说明"某件事，被当成了"做"那件事。**
//
//  > 规矩：**任何"源码里有没有 X"的断言，都必须先剥注释。**
//  > 否则你测的是"这个文件提没提过 X"，不是"代码里有没有 X"。
//
// ── 绑的形态（必须写明，否则会被当成"扫过就没事"）──
//
//  本模块的 `剥注释` 用正则处理四种形态：
//    · `/* ... */`（含 JSDoc）
//    · `// ...`（行注释 / 行尾注释）
//    · `<!-- ... -->`（Vue 模板注释）
//
//  **它漏的形态**（写在这里，免得下次有人以为它万能）：
//    · 字符串字面量里的 `//` 或 `/*`（如 `const s = 'http://x'`）—— 会被误剥
//    · 正则字面量里的 `//`
//    · 模板字符串里的注释样文本
//
//  当前三个用途的文件里都没有这几种写法。**换文件前要先确认。**
//
// ── ⚠⚠ 最要命的一条：**不要用 `\b` / `\w` 匹配中文标识符** ──
//
//  JS 的 `\b` 只认 **ASCII 单词字符**（`[A-Za-z0-9_]`）。中文两侧**永远不算边界**，
//  于是 `/\b球矩形\b/` 对 `球矩形` 这个标识符 **永远 0 命中** ——
//  **而且它不报错、不警告，只是静默地什么都不匹配。**
//
//  2026-11-20 这一天它出现 **三次**：
//
//  | 次 | 位置 | 表现 |
//  |---|---|---|
//  | 1 | 某条判据用 `\b` | 期望"有"，实际恒 false |
//  | 2 | 某条判据用 `\w` | 同上 |
//  | 3 | 本文件的作者写探针统计彼方内核符号 | 报出 `球矩形: 0 / 量球: 0 / 球锚点: 0` —— **差点据此得出"内核代码已经不存在"的结论** |
//
//  **第 3 次最危险**：它不是"判据失败"，而是"探针给出了看起来很确定的错答案"。
//  如果那天我信了它，会得出"彼方已经没有内核代码，C7 无事可做"的结论。
//
//  ✅ 正确做法（二选一）：
//    · **裸 `includes`**（最省事，也是本模块推荐的方式）
//    · 真要边界判断，用 `(?<![\p{L}\p{N}_])` / `(?![\p{L}\p{N}_])` 配合 `u` 标志
//
//  ⚠ 这条**不能只写在文档里** —— 它是"写的时候不会想起来"的东西。
//    所以 `代码里有()` 只接受 `includes` 式的字符串匹配，不给你传正则的入口。

/**
 * 剥掉源码里的注释，只留代码。
 *
 * @param 源 源码文本
 * @returns 去掉 `/* *\/`、`//`、`<!-- -->` 之后的文本
 *
 * ⚠ 行号会变（多行注释被删掉后行数减少）。**不要用它的结果去报行号。**
 */
export function 剥注释(源: string): string {
  return 源
    // 块注释（含 JSDoc）
    .replace(/\/\*[\s\S]*?\*\//g, '')
    // 行注释（不跨行）
    .replace(/^\s*\/\/.*$/gm, '')
    // 行尾注释（代码后面的 `// ...`）
    .replace(/([^:])\/\/.*$/gm, '$1')
    // Vue 模板注释
    .replace(/<!--[\s\S]*?-->/g, '');
}

/**
 * 源码里**代码部分**是否包含某段文本。
 *
 * 这是给"代码里有没有 X"类断言用的标准入口 —— 它内部先剥注释。
 *
 * ⚠ **只收字符串，不收正则** —— 这是有意的。
 *   中文标识符用 `/\bX\b/` 会**静默 0 命中**（`\b` 只认 ASCII 单词字符），
 *   而那种失败看起来像"代码里没有 X"，不是"我的正则写错了"。
 *   参见本文件顶部那条"不要用 `\b`/`\w` 匹配中文标识符"。
 */
export function 代码里有(源: string, 文本: string): boolean {
  return 剥注释(源).includes(文本);
}

/**
 * 断言"这条判据能抓到真问题"的最小自证工具。
 *
 * 用法：给一段**必然包含目标**的代码，断言 `代码里有` 为 true；
 * 再给一段**只在注释里提到目标**的代码，断言 `代码里有` 为 false。
 *
 * 两条都过，才说明"剥注释 + 匹配"这对组合是真的。
 */
export function 自证剥注释有效(文本: string, 代码样本: string, 注释样本: string): { 代码命中: boolean; 注释不命中: boolean } {
  return {
    代码命中: 代码里有(代码样本, 文本),
    注释不命中: !代码里有(注释样本, 文本),
  };
}
