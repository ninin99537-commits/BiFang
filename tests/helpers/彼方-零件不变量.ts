// 彼方 · 零件化的**性质校验函数**(I1–I10)。
//
// 为什么单独一个文件、为什么不是"21 条用例各写断言"(验收框架 §二 的明确要求):
//   21 个零件 × 开关/引用/全进工具/伪装 的组合是天文数字, 穷举没有意义。
//   正确的形状是:**性质(不变量)写成函数, 随机生成配置喂给它**。
//   这样"组合覆盖"由随机性提供, "正确性"由不变量保证 —— 两者各司其职。
//
// 本文件只做判定, 不产生副作用(除了报告)。它被两处调用:
//   ① tests/bifang-零件化.test.ts —— 手工枚举的边界用例(B 系列)
//   ② 同一个文件的随机 200 组 —— 每组的产物都过一遍
//
// **每个不变量都返回"违反项列表"而不是布尔**: 布尔只能说"坏了", 列表能说"坏在哪一条"。
// 这是 V3(配错可指认)在测试侧的对应物 —— 判据本身也要能指认。

import { 零件表 } from '../../src/彼方_NPC幕后生命状态系统/零件表';

export interface 拼装结果 {
  messages: { role: string; content: string }[];
  工具说明?: string;
  /** 这次拼装用了哪些配置 —— 违反报告里要能复现 */
  配置: {
    关闭: string[];
    引用: string[];
    全进工具: boolean;
    伪装: boolean;
    输入: Record<string, any>;
  };
  /** 每个零件"若不看关闭/引用, 它本来有什么内容" —— 判定"内容零丢失"要用 */
  零件原始内容: Record<string, string>;
}

export interface 违反 {
  不变量: string;
  说明: string;
}

/** 全部零件内容在产物里的出现次数(按"原始内容"数, 空内容跳过) */
function 出现次数(结果: 拼装结果): Map<string, number> {
  const 全文 = [
    ...结果.messages.map(m => m.content),
    结果.工具说明 ?? '',
  ].join('\n');
  const 次数 = new Map<string, number>();
  for (const [代号, 内容] of Object.entries(结果.零件原始内容)) {
    if (!内容.trim()) {
      次数.set(代号, 0);
      continue;
    }
    // 用 split 数出现次数。内容本身可能含正则元字符, 所以不用正则。
    次数.set(代号, 全文.split(内容).length - 1);
  }
  return 次数;
}

/** 用户段里引用了的零件代号(从配置里读, 不猜) */
function 被引用集合(结果: 拼装结果): Set<string> {
  return new Set(结果.配置.引用);
}

/** 例外清单: 这些零件在特定模式下**允许出现两次**, 理由逐条写明。
 *
 *  为什么要有例外表而不是"改 I1": I1 是"任何零件至多一次"的硬不变量,
 *  改它等于把整条判据废掉。而这一处是**既有的、与 I3 冲突的**行为 ——
 *  两者不能同时满足, 必须有一个显式让步, 并且让步要留痕(规矩 §十二 #17:
 *  例外表里每一项都要能回答"为什么它可以跳过整条链")。
 *
 *  唯一一条:
 *    · R1 身份句, 在「全进工具」模式下 —— **既有行为**, 不是本批引入。
 *      改造前的快照里(动代码之前采的)messages[0] 是身份句, 工具说明也以它开头。
 *      所以 I3(与改造前逐字节相同)要求它留在 messages[0], 而"全进工具"的语义
 *      又要求工具说明自带身份句。两个要求都成立 → 它必然出现两次。
 *      **这一条要不要改是需求/验收的裁定, 不是实现能自己决定的。**
 *      在裁定之前, I1 对 R1 在全进工具模式下不判违反。 */
const I1例外: { 代号: string; 条件: (结果: 拼装结果) => boolean; 理由: string }[] = [
  {
    代号: 'R1',
    条件: 结果 => 结果.配置.全进工具,
    理由: '全进工具时身份句既在 messages[0](既有行为, I3 要求)又在工具说明里(该模式语义要求)',
  },
];

function 在I1例外里(代号: string, 结果: 拼装结果): boolean {
  return I1例外.some(例外 => 例外.代号 === 代号 && 例外.条件(结果));
}

/**
 * I1 · 不重复: 任何零件在任何组合下**至多出现一次**。
 *
 * 例外见 `I1例外`(目前只有一条: R1 在全进工具模式下)。
 *
 * 注意"空零件"与"内容恰好是另一零件子串"这两种情况:
 *  · 空零件不参与(它本来就不该出现)
 *  · 若 A 的内容包含 B 的内容, 数 B 的次数会把 A 里的那部分也算进去 —— 所以
 *    这条判定只对"内容互不包含"的零件可靠。这里用的输入是受控的(见 tests 的 造输入),
 *    且零件内容来自实现(`零件内容`), 边界准确。
 */
function 查I1(结果: 拼装结果): 违反[] {
  const 违反们: 违反[] = [];
  const 关闭 = new Set(结果.配置.关闭);
  for (const [代号, 次数] of 出现次数(结果)) {
    if (关闭.has(代号))
      continue;
    if (!结果.零件原始内容[代号].trim())
      continue;
    if (在I1例外里(代号, 结果))
      continue;
    if (次数 > 1) {
      违反们.push({
        不变量: 'I1',
        说明: `零件 ${代号} 出现了 ${次数} 次(至多 1 次)`,
      });
    }
  }
  return 违反们;
}

/**
 * I2 · 不凭空: 拼装结果里不含任何**既未被引用、也未被默认放置**的零件内容。
 *
 * 反面断言 —— 防"顺手留一份"。与 I1 互补: I1 管"多了", I2 管"多了不该有的"。
 * 实操上 I1 已经覆盖大部分, 但两者不是同一件事:
 * I1 说的是"同一个零件不超过一次", I2 说的是"这个零件根本不该出现"。
 * 一个被关闭的零件如果被错误地塞进产物, I1 抓不到(它只出现一次), I2 能抓到。
 */
function 查I2(结果: 拼装结果): 违反[] {
  const 违反们: 违反[] = [];
  const 关闭 = new Set(结果.配置.关闭);
  const 被引用 = 被引用集合(结果);
  /** 与 I6/I7 同一份名单：**D14 / R1 是模板文字**（2026-11-19 模板化）。
   *
   *  「关闭 D14」在模板路径下**没有意义** —— 模板里没有 `{{彼方:任务指令}}` 这个占位符，
   *  D14 的骨架是用户可编辑的模板文字。用户想"关掉任务指令"就是**删掉那几行字**，
   *  而不是勾一个"关闭零件"。所以 `关闭零件` 里出现 D14 时，产物里仍会有那 446 字
   *  （那是模板里的字，不是"凭空塞进来的"）。
   *
   *  同理 R1：身份句是模板第一行，`关闭零件: ['R1']` 不会让它消失。 */
  const 模板文字 = new Set(['D14', 'R1']);
  for (const [代号, 次数] of 出现次数(结果)) {
    if (!结果.零件原始内容[代号].trim())
      continue;
    if (次数 === 0)
      continue;
    if (模板文字.has(代号))
      continue;
    // 被关闭的零件不该出现在任何地方
    if (关闭.has(代号)) {
      违反们.push({ 不变量: 'I2', 说明: `零件 ${代号} 已被关闭, 但仍出现在产物里` });
    }
  }
  void 被引用;
  return 违反们;
}

/**
 * I4 · 关闭不移序: 任何零件关闭后, 其余零件的**相对顺序**不变。
 *
 * **这条只在"同一路径 + 同一条件"内比较才成立。** 两个坑(都是第一批踩的):
 *   ① 伪装开/关是**两条不同的排布路径** —— 伪装会把规则拆成"规则段1 → 确认 → 规则段2
 *      → … → 剧情 → 输出要求", 于是 R5 从"紧跟 R4"变成"在剧情之后"。那是伪装的
 *      既定设计(§29 ②), 不是"关闭导致的移序"。
 *   ② 条件段(生理开/关)会让 R6 出现或消失, 而它的位置夹在 R2 与 R3 之间 ——
 *      基线若用"生理关", 当前用"生理开", 顺序差异来自**条件**不是**关闭**。
 *
 * 所以调用方必须传**同一路径、同一条件**的基线。这里再加一道自检:
 * 若基线与当前的路径/条件不同, 直接跳过并说明(不许静默判违反)。
 */
function 查I4(结果: 拼装结果, 基线?: 拼装结果): { 违反: 违反[]; 跳过原因?: string } {
  if (!基线)
    return { 违反: [], 跳过原因: '没有基线(需要同路径的全默认产物才能判相对顺序)' };
  if (基线.配置.伪装 !== 结果.配置.伪装 || 基线.配置.全进工具 !== 结果.配置.全进工具)
    return { 违反: [], 跳过原因: '基线与当前不是同一条排布路径(伪装/全进工具不同), I4 不适用' };
  // 条件不同(生理/恋爱/登记归档/自动建档)也不可比 —— 那会让条件段出现或消失
  const 条件键 = (r: 拼装结果) => JSON.stringify({
    生理: !!r.配置.输入.physioEnabled,
    恋爱: (r.配置.输入.恋爱对象名单 ?? []).length > 0,
    归档: !!r.配置.输入.登记归档,
    建档: r.配置.输入.autoTrackEnabled !== false,
  });
  if (条件键(基线) !== 条件键(结果))
    return { 违反: [], 跳过原因: '基线与当前的条件开关不同(生理/恋爱/归档/建档), 条件段会增减, I4 不适用' };
  const 取顺序 = (r: 拼装结果) => {
    const 全文 = [...r.messages.map(m => m.content), r.工具说明 ?? ''].join('\n');
    return Object.entries(r.零件原始内容)
      .filter(([, 内容]) => 内容.trim())
      .map(([代号, 内容]) => ({ 代号, 位置: 全文.indexOf(内容) }))
      .filter(项 => 项.位置 >= 0)
      .sort((a, b) => a.位置 - b.位置)
      .map(项 => 项.代号);
  };
  const 基线顺序 = 取顺序(基线);
  const 当前顺序 = 取顺序(结果);
  // 当前顺序必须是基线顺序的子序列
  let j = 0;
  for (const 代号 of 当前顺序) {
    while (j < 基线顺序.length && 基线顺序[j] !== 代号)
      j++;
    if (j >= 基线顺序.length) {
      return {
        违反: [{
          不变量: 'I4',
          说明: `零件 ${代号} 的相对顺序变了(当前 ${当前顺序.join(',')} / 基线 ${基线顺序.join(',')})`,
        }],
      };
    }
    j++;
  }
  return { 违反: [] };
}

/**
 * I5 · 引用必展开: 启用的自定义段里, 每个**合法**占位符都必须展开 ——
 * 不许出现"占位符原样发给了模型"(模型会照抄 `{{彼方:世界书}}` 字面量)。
 */
function 查I5(结果: 拼装结果): 违反[] {
  const 全文 = [...结果.messages.map(m => m.content), 结果.工具说明 ?? ''].join('\n');
  const 违反们: 违反[] = [];
  // 允许留下的只有"未知占位符"——但按 C2 那些也该被忽略(换成空串), 所以一个都不该留。
  const 残留 = 全文.match(/\{\{\s*彼方\s*[:：][^{}]*\}\}/g) ?? [];
  for (const 命中 of new Set(残留)) {
    违反们.push({ 不变量: 'I5', 说明: `占位符 ${命中} 原样留在了产物里` });
  }
  return 违反们;
}

/**
 * I6 · 内容零丢失: 全开配置下, 任何零件的内容在最终输出中**逐字存在**
 * (引用的在新位置、未引用的在默认位置) —— 防"搬迁时截断/转义损坏"。
 *
 * 只对"没关闭"的零件生效。两种跳过(都要留痕, 不许静默放行):
 *  · 内容为空的零件(它们本来就没有内容可丢)
 *  · **宿主被关闭的条件段**: R6 寄生在 R2/D14, R7 寄生在 D14。宿主关了,
 *    条件段随之消失是**必然结果**, 不是"内容丢了"。随机 200 组的组#82/#136
 *    报的正是这个 —— 把嵌套行为判成缺陷。
 */
function 查I6(结果: 拼装结果): 违反[] {
  const 违反们: 违反[] = [];
  const 关闭 = new Set(结果.配置.关闭);
  // 与 I9 同一份宿主表（2026-11-19：D14 拆成了 `D14-生理` / `D14-恋爱` 两个独立零件）
  const 宿主: Record<string, string[]> = { R6: ['R2', 'D14-生理'], R7: ['D14-恋爱'] };
  /** **已拆成切片/模板文字的零件**（2026-11-19 模板化）。
   *
   *  · `D14` 任务指令：它的骨架**已经是模板文字**（不在 `零件内容` 里逐字出现），
   *    而它的两个条件切片是独立零件（`D14-生理` / `D14-恋爱`）。
   *    所以"D14 的完整内容必须逐字出现在产物里"这条**不再成立** ——
   *    产物里是"骨架 + 两个切片"，不是"D14 的原始整块"。
   *  · `R1` 身份句：它也是模板文字（需求方 #215），`零件内容.R1` 只在
   *    `取零件内容` 里给清单用，不保证逐字出现在产物里（用户可能改了模板第一行）。
   *
   *  **为什么要列成显式名单而不是"跳过所有"**：这两条跳过是有理由的，
   *  而理由要能被人看见 —— 否则下一个人会以为 I6 坏了。 */
  const 已拆或模板文字 = new Set(['D14', 'R1']);
  for (const [代号, 次数] of 出现次数(结果)) {
    const 原始 = 结果.零件原始内容[代号];
    if (关闭.has(代号))
      continue;
    if (!原始.trim())
      continue;
    if (已拆或模板文字.has(代号))
      continue;
    // 条件段的宿主被关掉时, 它跟着消失是正确行为
    if (宿主[代号] && !宿主[代号].every(号 => !关闭.has(号)))
      continue;
    if (次数 === 0) {
      违反们.push({ 不变量: 'I6', 说明: `零件 ${代号} 没被关闭, 但内容在产物里找不到` });
    }
  }
  return 违反们;
}

/**
 * I7 · 承重件完备: 无论怎么组合, R5 输出要求 + D14 任务指令
 * **要么在原位、要么在引用处、要么带强警告** —— 三者必居其一,
 * 绝不允许"静默消失导致 JSON 指令没了"。
 *
 * 判定方式: 若某个承重件被关闭, 必须能从 `警告们` 里找到它(带后果说明);
 * 若没被关闭, 它的内容必须出现在产物里。
 */
function 查I7(结果: 拼装结果, 警告们: string[]): 违反[] {
  const 违反们: 违反[] = [];
  const 关闭 = new Set(结果.配置.关闭);
  const 次数 = 出现次数(结果);
  /** 与 I6 同一份名单：D14 已拆（骨架是模板文字）、R1 是模板文字。
   *  "内容必须逐字出现在产物里"对它们不再成立 —— 见 I6 的注释。 */
  const 已拆或模板文字 = new Set(['D14', 'R1']);
  for (const 零件 of 零件表.filter(件 => 件.承重)) {
    if (关闭.has(零件.代号)) {
      const 有警告 = 警告们.some(句 => 句.includes(零件.名) && !!零件.关掉后果 && 句.includes('已关闭'));
      if (!有警告)
        违反们.push({ 不变量: 'I7', 说明: `承重件 ${零件.代号}(${零件.名})被关闭但没有强警告` });
      continue;
    }
    if (已拆或模板文字.has(零件.代号))
      continue;
    if (!结果.零件原始内容[零件.代号].trim())
      continue; // 本来为空(理论上承重件不会空)
    if ((次数.get(零件.代号) ?? 0) === 0)
      违反们.push({ 不变量: 'I7', 说明: `承重件 ${零件.代号}(${零件.名})既不在产物里也没被关闭` });
  }
  return 违反们;
}

/**
 * I8 · 单一拼装点: 工具说明与 messages 必须从**同一次拼装结果**派生 ——
 * 同一测试输入下, 两处的内容集合满足 I1/I2
 * (不存在"messages 里搬走了、工具说明里还是默认顺序")。
 *
 * 判定: 每个零件在 (messages + 工具说明) 的合并全文里至多一次 —— 这就是 I1,
 * 但 I8 的要点是**跨两处**。单看 messages 或单看工具说明都可能各自"正常",
 * 合起来才是真相。所以 I8 单独查一遍合并后的计数。
 */
function 查I8(结果: 拼装结果): 违反[] {
  const 违反们: 违反[] = [];
  const 关闭 = new Set(结果.配置.关闭);
  const 全进工具 = 结果.配置.全进工具;
  if (!全进工具)
    return []; // 没有工具说明时 I8 不适用
  const 消息全文 = 结果.messages.map(m => m.content).join('\n');
  const 工具全文 = 结果.工具说明 ?? '';
  for (const [代号, 内容] of Object.entries(结果.零件原始内容)) {
    if (!内容.trim() || 关闭.has(代号))
      continue;
    if (在I1例外里(代号, 结果))
      continue; // 与 I1 同一条例外(它们是同一个现象的两面)
    const 在消息 = 消息全文.includes(内容);
    const 在工具 = 工具全文.includes(内容);
    if (在消息 && 在工具) {
      违反们.push({
        不变量: 'I8',
        说明: `零件 ${代号} 同时在 messages 与工具说明里(搬走后应只剩一处)`,
      });
    }
  }
  return 违反们;
}

/**
 * I9 · 条件段与开关合取: R6/R7 这类条件零件, 最终出现 =
 * **条件成立 且 未被关闭 且 (默认位置 或 被引用)** —— 三条件的与,
 * 任何一条不满足就不出现。
 *
 * **正向("该出现")只在宿主零件都在时才判。** 为什么(随机 200 组抓出来的):
 *   R6/R7 的内容是**寄生在别的零件里的**(physioInstruction 在 D14 任务段里,
 *   生理权威段在 R2 前)。所以"关掉 D14"会连带把 R6 的那一段一起丢掉 ——
 *   那不是"R6 没出现"的缺陷, 是"宿主被关了"的必然结果。
 *   组#82(关 D11+D14)与组#136(关 D14)报的正是这个, 两组都**不是**缺陷。
 *   把正向断言写成"无条件必须出现", 就会把正确的嵌套行为判成违反。
 *
 * 反向("不该出现")无条件成立: 关了 R6/R7 就不该在任何地方看到它。
 */
function 查I9(结果: 拼装结果): 违反[] {
  const 违反们: 违反[] = [];
  const 关闭 = new Set(结果.配置.关闭);
  const 次数 = 出现次数(结果);
  // R6/R7 的宿主: R6 寄生在 R2(生理权威段) 与 **D14-生理**(任务尾部的 physioInstruction);
  // R7 寄生在 **D14-恋爱**(恋爱Instruction)。
  //
  // ⚠ 2026-11-19 模板化：宿主从 `D14` 改成了 `D14-生理` / `D14-恋爱` ——
  //   因为 D14 尾部那两段现在是**独立零件**（用户可单独关掉它们）。
  //   若还用 `D14` 当宿主，会出现"关掉 D14-生理 但宿主没关 → 判 R6 违反"这种假红
  //   （随机 200 组里的组#46/#84/#87/#141 报的正是这个）。
  const 宿主: Record<string, string[]> = { R6: ['R2', 'D14-生理'], R7: ['D14-恋爱'] };
  for (const 代号 of ['R6', 'R7']) {
    const 原始 = 结果.零件原始内容[代号] ?? '';
    const 条件成立 = 原始.trim().length > 0;
    const 该出现 = 条件成立 && !关闭.has(代号);
    const 宿主都在 = 宿主[代号].every(号 => !关闭.has(号));
    const 实际 = 次数.get(代号) ?? 0;
    if (该出现 && 宿主都在 && 实际 === 0) {
      违反们.push({
        不变量: 'I9',
        说明: `${代号} 条件成立、未关闭、宿主(${宿主[代号].join('/')})都在, 但没出现`,
      });
    }
    // 反向无条件
    if (!该出现 && 实际 > 0)
      违反们.push({ 不变量: 'I9', 说明: `${代号} 条件不成立或已关闭, 却出现了 ${实际} 次` });
  }
  return 违反们;
}

/**
 * I10 · 禁词与痕迹: 拼装逻辑不引入任何随机量/别家痕迹 ——
 * 打散标记只能进 messages 的既定位置, 零件拼装不影响 P2-7(标记不进工具说明)。
 *
 * 判定: 两次同样配置的拼装必须**逐字节相同**(没有随机量);
 * 且工具说明里不出现打散标记的形状(本文件不负责打散, 所以只查"没有请求标识字样")。
 */
function 查I10(结果: 拼装结果, 再拼一次: () => 拼装结果): 违反[] {
  const 违反们: 违反[] = [];
  const 再 = 再拼一次();
  if (JSON.stringify(再.messages) !== JSON.stringify(结果.messages))
    违反们.push({ 不变量: 'I10', 说明: '同配置两次拼装的 messages 不同(引入了随机量)' });
  if ((再.工具说明 ?? '') !== (结果.工具说明 ?? ''))
    违反们.push({ 不变量: 'I10', 说明: '同配置两次拼装的工具说明不同(引入了随机量)' });
  if ((结果.工具说明 ?? '').includes('请求标识'))
    违反们.push({ 不变量: 'I10', 说明: '工具说明里出现了打散标记的痕迹(P2-7)' });
  return 违反们;
}

/**
 * I3 · 全默认逐字节: 不引用、不关闭任何零件时, 输出与改造前逐字节一致。
 *
 * 这条的判据不在本函数里(它要一份外部快照), 所以这里只做"是否为全默认配置"的判定,
 * 真正的比对在 tests 里。把"是否默认"收在这里, 是为了让随机 200 组能自动跳过非默认的组。
 */
export function 是全默认配置(关闭: string[], 引用: string[]): boolean {
  return 关闭.length === 0 && 引用.length === 0;
}

/** 跑全部不变量, 返回违反项。**调用方只关心这个函数。** */
export function 校验全部(
  结果: 拼装结果,
  选项: { 警告们?: string[]; 基线?: 拼装结果; 再拼一次?: () => 拼装结果 } = {},
): 违反[] {
  const 警告们 = 选项.警告们 ?? [];
  const 违反们: 违反[] = [
    ...查I1(结果),
    ...查I2(结果),
    ...查I5(结果),
    ...查I6(结果),
    ...查I7(结果, 警告们),
    ...查I8(结果),
    ...查I9(结果),
  ];
  const i4 = 查I4(结果, 选项.基线);
  if (i4.跳过原因) {
    // skip 必须打原因, 且不许静默放行(规矩 §十二 #3 ④)
    console.info(`  [I4] 跳过: ${i4.跳过原因}`);
  }
  else {
    违反们.push(...i4.违反);
  }
  if (选项.再拼一次)
    违反们.push(...查I10(结果, 选项.再拼一次));
  return 违反们;
}
