// 彼方 · 台账的界面层操作(「未完成事项」接上悬浮球面板) —— 纯函数 + 数据变更通道 + 源码守卫
//
// 背景: 台账(事务台账.ts)是数据层的事, 这个用例管的是**它接上界面之后的那一层**:
//   1 界面显示: 卡里可能是旧格式字符串也可能是数组, 都要能显示; 进行中排前面, 已办压后面;
//   2 改一条: 玩家在详情页按一下把某条事务收束成 已完成/已作废(顺带写结果)——状态合不合法、
//     编号在不在、进行中要不要留结果, 口径只有一份(台账操作.ts), 这里钉住它;
//   3 改完真的落库: 走 数据变更.ts 的既有通道(写快照 + 重同步世界书), 而且"改不成"时
//     **一个字段都不动、也不写快照**, 界面据此提示——绝不允许"改完没生效还没有反馈";
//   4 表单侧不再把这个字段当字符串写回(以前数组草稿会被 合并草稿 整段跳过 = 静默丢改动)。
