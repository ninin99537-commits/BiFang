//
// 用户原话:「开了插件之后就会一直强制高潮、低谷之类的, 不能有平淡的生活了」
//         「要是让他写的话, 剧情岂不是又会和她写的一样了?」
//
// 设计: 平静模式 = **只记账, 不下令**。引擎照跑、账本照更新, 但不生成也不注入本幕指令。
