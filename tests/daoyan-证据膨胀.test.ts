console.log('\n[1] 平静期: 不催办、不调档(省下每轮四万字)');
{
  const 账 = 账本();
  const 平时 = 唯引用(账, false);
  const 平静 = 唯引用(账, true);
  ok('非平静: 到期伏笔的整条证据链都被选(1 埋设 + 8 回响)', 平时.includes('AM0244') && 平时.includes('AM0252'));
  check('非平静: 正好 9 条(1 埋设 + 8 回响)', 平时.length, 9);
  check('平静: 一条伏笔证据都不选', 平静.length, 0);

  // 但"正确性"那两样照读: 待读队列(导演自己申请的) + 待核命运证据(谁死了是否成立)
  const 有正确性 = 账本({
    待读队列: [{ 记忆引用: 'AM0999', 理由: '导演补读', 目标: '导演申请', 入队楼层: 10, 已读次数: 0 }] as any,
    角色命运: [
      {
        角色ID: 'Joel',
        状态: '死亡',
        状态证据: [证('AM0777', 30, '待核')],
        位置: '',
        独立目标: [],
        当前关系: [],
        持久后果: [],
        承诺与债务: [],
        已知事实引用: [],
        未竟计划: [],
        最后变化: null,
      } as any,
    ],
  });
  const 平静选 = 引用们(有正确性, true);
  ok('平静: 待读队列照读(导演自己的判断)', 平静选.includes('AM0999'));
  ok('平静: 待核的命运证据照读(这是正确性, 不是催办)', 平静选.includes('AM0777'));
  ok('平静: 但伏笔证据仍然一条不选', !平静选.includes('AM0244'));

  // 平静期那条"伏笔现场"是**平静之前**留下的旧编排 —— 拿它调档等于为没演过的命令付钱
  const 留旧指令 = 账本({
    当前指令: { 编号: 5, 伏笔现场: '把 #2 再顶一次', 硬性要求: [], 必演: [] } as any,
  });
  ok('非平静: 上一幕任务指到的伏笔会去调档', 引用们(留旧指令, false).includes('AM0244'));
  ok('平静: 旧编排的"伏笔现场"不再调档', !引用们(留旧指令, true).includes('AM0244'));
}

