// 剧情导演 · 证据膨胀(2026-11-12)
//
// 起因是一次真机取证(聊天 `最后生还者`, 第 1517 层):
//   · 账本 JSON 18,929 字符, 其中**一条**伏笔的证据链占 5,902(31%);
//   · 那条伏笔有 **1 条埋设 + 53 条回响**, 覆盖楼层 15→66, 平均**每 1.0 场记一条**;
//   · 记忆审计写着「请求 52 条 / 读到 52 条 / 纪要正文 41,796 字」—— 每一轮都把这整条链
//     的**完整纪要**调进导演提示词, 而那 58 场正好开着平静模式(不产出任何指令);
//   · 更糟的是它的兑现条件「在医疗站完成晨尿试纸检测」**在第 28 场就演过了**, 账本却没兑现,
//     于是后面 25 场继续往上叠回响。
//
// 三条修法(用户选的 ①②④):
//   ① 平静期不催办不调档 —— 但要配套改掉"没查等于查无"的盖章规则, 否则一次平静就把整条链刷成待核;
//   ② 回响配额 + 收紧"什么才算一条回响";
//   ④ 兑现条件自检 —— 代码判不了"算不算发生了", 只能把条件原文顶到导演面前。
import { createPinia, setActivePinia } from 'pinia';
