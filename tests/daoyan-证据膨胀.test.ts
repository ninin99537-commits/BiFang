console.log('\n[5] 补登记的配套: 待核的兑现证据必须下一轮真去读');
{
  // 模型"补登记"一条早年的兑现证据时, 那条 AM 那一轮还没被读过 → 待核 → 兑现被拒。
  // 所以收集必需引用要把"待核的兑现证据"也排进去, 否则补登记永远成功不了。
  const 补登记 = 账本({
    伏笔: [长伏笔({ 状态: '待兑现', 兑现证据: [证('AM0272', 40, '待核')] })],
  });
  ok('待核的兑现证据被排进选证', 唯引用(补登记, false).includes('AM0272'));
  ok('理由写明是"待核的兑现证据"', 收集必需引用(补登记, { 平静: false }).some(项 => 项.理由.includes('待核的兑现证据')));
  // 已核的兑现证据不再重复调档(省字)
  const 已核 = 账本({ 伏笔: [长伏笔({ 状态: '待兑现', 兑现证据: [证('AM0272', 40, '已核')] })] });
  ok('已核的兑现证据不重复调档', !收集必需引用(已核, { 平静: false }).some(项 => 项.理由.includes('待核的兑现证据')));
  // 这条属于"正确性", 平静期也照读(否则平静一轮下来补登记就丢了)
  ok('平静期也读待核的兑现证据', 收集必需引用(补登记, { 平静: true }).some(项 => 项.引用 === 'AM0272'));
}

