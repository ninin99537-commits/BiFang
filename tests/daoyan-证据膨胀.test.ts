console.log('\n[3] 回响配额: 堆到 6 条就把"别再追加"摆到导演面前');
{
  check('告警线是 6 条', 回响条数告警, 6);
  check('5 条不提(还在正常范围)', 回响配额提醒(账本({ 伏笔: [长伏笔({ 中间回响: [1, 2, 3, 4, 5].map(i => 证(`AM024${4 + i}`, 14 + i)) })] })).length, 0);
  const 提 = 回响配额提醒(账本({ 伏笔: [长伏笔({ 中间回响: [1, 2, 3, 4, 5, 6].map(i => 证(`AM024${4 + i}`, 14 + i)) })] }));
  check('6 条就提', 提.length, 1);
  ok('点出编号与条数', 提[0]?.includes('#2(6 条)'));
  ok('说清什么才算一条回响(换形式/换人/换场合)', 提[0]?.includes('换个') || 提[0]?.includes('换了一种表面形式'));
  ok('明说"同一情境反复提不算新回响"', 提[0]?.includes('不算新回响'));
  ok('给出的出路是兑现或消亡, 不是继续记', 提[0]?.includes('已消亡'));

  // 已经兑现/消亡的线不再提(它们不会再长)
  ok('终态伏笔不提', 回响配额提醒(账本({ 伏笔: [长伏笔({ 状态: '已引爆', 中间回响: [1, 2, 3, 4, 5, 6, 7].map(i => 证(`AM025${4 + i}`, 20 + i)) })] })).length === 0);
  // 最多提 2 条最病态的(都要先过 6 条这条线)
  const 三条 = 账本({
    伏笔: [7, 9, 12].map((n, i) => 长伏笔({ 编号: 10 + i, 中间回响: Array.from({ length: n }, (_, k) => 证(`AM0${300 + k}`, 20 + k)) })),
  });
  const 提三条 = 回响配额提醒(三条);
  check('最多提 2 条', 提三条.length, 1);
  ok('挑最病态的两条(12 条与 9 条)', 提三条[0]?.includes('#12(12 条)') && 提三条[0]?.includes('#11(9 条)'));
  ok('7 条那条排不进前两名就不提', !提三条[0]?.includes('#10('));
}

