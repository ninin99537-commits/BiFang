console.log('\n[4] 兑现条件自检: 条件写着却没人核对, 线就永远悬着');
{
  const 提 = 兑现条件提醒(账本());
  check('窗口已开 + 有条件 → 提两条(自检 + 判定依据)', 提.length, 2);
  ok('把条件原文整句摆出来(零截断, 不摘要)', 提[0]?.includes('艾莉在医疗站完成晨尿试纸检测确认结果'));
  ok('给出两条出路: 已发生就当场兑现', 提[0]?.includes('当场兑现'));
  ok('**可以直接引用当初那条 AM**, 不必重演', 提[0]?.includes('不必重演'));
  ok('没发生就安排或改写条件', 提[0]?.includes('改写'));
  ok('点名编号', 提[0]?.includes('#2'));
  // 第二条: 把最近的回响摘要摆出来, 让它看得见"条件其实已经满足了"
  ok('判定依据里给出最近的回响(带 AM 与摘要)', 提[1]?.includes('AM0252') && 提[1]?.includes('的公开摘要'));
  ok('说明"已经出现条件被满足的那一刻就该兑现"', 提[1]?.includes('该兑现'));

  // 没写条件 → 没什么可自检的
  check('没有兑现条件就不提', 兑现条件提醒(账本({ 伏笔: [长伏笔({ 兑现条件: [] })] })).length, 0);
  // 窗口没开(最早章 5) → 不催, 免得发酵早期的线每轮被念
  check(
    '窗口未开 → 不提',
    兑现条件提醒(账本({ 伏笔: [长伏笔({ 目标窗口: { 最早章: 5, 最迟章: 7 }, 回收窗口: '第7章收束前' })] })).length,
    0,
  );
  // 待兑现的线即使窗口没开也要自检(它已经在等落地了)
  ok(
    '待兑现 + 有条件 → 即使窗口没开也提',
    兑现条件提醒(账本({ 伏笔: [长伏笔({ 状态: '待兑现', 目标窗口: { 最早章: 5, 最迟章: 7 }, 回收窗口: '第7章收束前' })] })).length > 0,
  );
  // 自查发现: 判"临期"不能借用 取到期伏笔 的节流, 否则同一章催过一次之后整章失声
  ok(
    '本章已经催办过(最近催办章=当前章)也照样自检',
    兑现条件提醒(账本({ 伏笔: [长伏笔({ 最近催办章: 1 })] })).length > 0,
  );
  // 最多 2 条, 免得提醒本身变成噪音
  const 三条 = 账本({
    伏笔: [1, 2, 3].map(i => 长伏笔({ 编号: 20 + i, 状态: '待兑现' as const })),
  });
  const 多处 = 兑现条件提醒(三条);
  check('最多提 2 条线', (多处[0] ?? '').match(/#\d+「/g)?.length, 2);
}

