console.log('\n[6] 手动了结: 改成终态 = 当场收档(否则下一轮被安静地回滚掉)');
{
  // 只改状态没用: 合并以候选为准, 而"状态回滚"本身是允许的(纠正误标用) —— 模型下一轮照抄
  // 账本还会写「发酵」, 一次回滚就抹掉手动结账。所以终态必须离开活动集。
  const 账 = 账本();
  账.历史档案 = { 伏笔: [], 冲突: [], 弧线: [], 命运: [], 归档记录: [] } as any;
  ok('手动了结返回 true', 手动了结伏笔(账, 2, '已引爆', 1517));
  check('活动集里已经没有它', (账.伏笔 ?? []).length, 0);
  check('进了历史档案', 账.历史档案?.伏笔?.[0]?.编号, 2);
  check('档案里状态是已引爆', 账.历史档案?.伏笔?.[0]?.状态, '已引爆');
  check('证据链一条不少(54 条回响原样保留)', (账.历史档案?.伏笔?.[0]?.中间回响 ?? []).length, 8);
  ok('归档记录写明是谁动的', (账.历史档案?.归档记录 ?? []).some((x: any) => String(x.原因).includes('面板手动')));
  ok('编号不存在 → 什么都不做', 手动了结伏笔(账, 999, '已引爆') === false);
  // 收档之后, 它再也不会被选证盯上(这才是省下四万字的地方)
  check('收档后不再产生伏笔证据调档', 收集必需引用(账, { 平静: false }).length, 0);
}

