import { 盖章证据 } from '../src/剧情导演/证据链';
import { 手动了结伏笔 } from '../src/剧情导演/账本数据';
import { emptyData } from '../src/剧情导演/快照';
import type { 导演账本, 伏笔 } from '../src/剧情导演/schema';

(globalThis as any)._ = {
  clamp: (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), hi),
  cloneDeep: (v: any) => (v === undefined ? undefined : JSON.parse(JSON.stringify(v))),
};
(globalThis as any).localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

const 证 = (引用: string, 楼层: number, 定位: '已核' | '待核' = '已核') => ({
  记忆引用: 引用,
  楼层,
  公开摘要: `${引用} 的公开摘要`,
  定位,
  待核原因: '',
});

/** 一条"病态"的伏笔: 1 埋设 + 8 回响, 窗口已开、兑现条件早就该核对了 */
const 长伏笔 = (部分: Partial<伏笔> = {}): 伏笔 => ({
  编号: 2,
  内容: '艾莉停经两月且伴随乳房胀痛敏感与嗜睡反常',
  公开线头: '她最近总说胸口发胀',
  幕后真相: '',
  真相修订原因: [],
  状态: '发酵',
  回收窗口: '第2章收束前',
  关联冲突: '',
  埋设证据: [证('AM0244', 14)],
  中间回响: [1, 2, 3, 4, 5, 6, 7, 8].map(i => 证(`AM0${244 + i}`, 14 + i)),
  知情角色: [],
  关联角色: [],
  目标窗口: { 最早章: 1, 最迟章: 2 },
  兑现条件: ['艾莉在医疗站完成晨尿试纸检测确认结果'],
  候选兑现: [],
  兑现证据: [],
  消亡原因: '',
  跨度: '中',
  书纲ID: '',
  埋设场: 1,
  最后回响场: 9,
  ...部分,
} as 伏笔);

const 账本 = (部分: Partial<导演账本> = {}): 导演账本 => ({
  ...emptyData(),
  已分析轮数: 10,
  章回: { ...(emptyData().章回 as any), 章号: 1, 进度: '推进', 当前幕号: 2 },
  伏笔: [长伏笔()],
  ...部分,
});

const 引用们 = (账: 导演账本, 平静: boolean) => 收集必需引用(账, { 平静 }).map(项 => 项.引用);
/** 去重后再比: 收集必需引用会为同一个 AM 给出多个理由(选证那一层才去重) */
const 唯引用 = (账: 导演账本, 平静: boolean) => [...new Set(引用们(账, 平静))];

