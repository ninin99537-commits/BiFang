console.log('\n[2] 盖章: "没查"不等于"查无"(否则一次平静把整条链刷成待核)');
{
  const 造 = () => 账本();
  // ① 不传 本轮请求(老行为): 没读到的一律降级
  const 老行为 = 造();
  盖章证据(老行为, ['AM0244'], [], '', []);
  check('不传请求集: 没读到的降成待核', 老行为.伏笔[0].中间回响?.[0].定位, '待核');
  ok('不传请求集: 原因写明"本轮未读到"', String(老行为.伏笔[0].中间回响?.[0].待核原因 ?? '').includes('本轮未读到'));

  // ② 传了请求集, 但这一轮根本没去查 → 保留原判定
  const 没查 = 造();
  盖章证据(没查, [], [], '', [], []);
  check('请求集为空: 原已核保留成已核', 没查.伏笔[0].中间回响?.[0].定位, '已核');
  check('请求集为空: 埋设也保留', 没查.伏笔[0].埋设证据?.[0].定位, '已核');
  check('请求集为空: 不带旧待核原因', 没查.伏笔[0].埋设证据?.[0].待核原因, '');

  // ③ 查了但没查到 → 仍然是待核(这条不能被"没查"的宽宥顺手放过)
  const 查无 = 造();
  盖章证据(查无, [], [], '', [], ['AM0244', 'AM0245']);
  check('查了缺失: 埋设降成待核', 查无.伏笔[0].埋设证据?.[0].定位, '待核');
  check('查了缺失: 回响 0245 也降成待核', 查无.伏笔[0].中间回响?.[0].定位, '待核');
  check('没查的 0246 保留已核', 查无.伏笔[0].中间回响?.[1].定位, '已核');

  // ④ 读取整体失败: 只影响本轮请求过的, 没请求的不误伤
  const 失败 = 造();
  盖章证据(失败, [], [], '世界书不可读', [], ['AM0244']);
  check('读取失败: 请求过的降级', 失败.伏笔[0].埋设证据?.[0].定位, '待核');
  check('读取失败: 没请求的保留', 失败.伏笔[0].中间回响?.[0].定位, '已核');

  // ⑤ 本轮正文里的证据永远算已核(与"有没有纪要"无关)
  const 正文 = 造();
  盖章证据(正文, [], [], '', [15], []);
  check('正文楼层命中 → 已核(即使没调档)', 正文.伏笔[0].中间回响?.[0].定位, '已核');
}

