console.log('\n[2] 取差异: 只收集真正改过的叶子');
{
  const 基线 = { 启用: true, 接口: { 地址: 'A', 密钥: 'K' }, 预设: { 甲: { 地址: 'A' } } };
  check('完全没改 → 有:false', 取差异(基线, { ...基线, 接口: { ...基线.接口 } }).有, false);
  check('改了一个叶子 → 只有那一片', 取差异(基线, { ...基线, 接口: { 地址: 'B', 密钥: 'K' } }).值, { 接口: { 地址: 'B' } });
  check('没有改动时 值 是空对象', 取差异(基线, { ...基线, 接口: { ...基线.接口 } }).值, {});
  // 默认**不收**集删除: 剧情导演那一份就是这语义(它的面板没有"删某个键"的动作)
  check('默认不收集删除', 取差异({ a: 1, b: 2 }, { a: 1 }).删, []);
  check('默认也不把"变少"算成有改动', 取差异({ a: 1, b: 2 }, { a: 1 }).有, false);
  // 显式打开才收集
  const 带删 = 取差异({ a: 1, b: 2 }, { a: 1 }, { 收集删除: true });
  check('打开后收集到删键路径', 带删.删, [['b']]);
  ok('删键也算改动', 带删.有);
  check(
    '嵌套删键按路径记',
    取差异({ 预设: { 甲: 1, 乙: 2 } }, { 预设: { 甲: 1 } }, { 收集删除: true }).删,
    [['预设', '乙']],
  );
  check('基线是 undefined(新装用户) → 整份都算改动', 取差异(undefined, { a: 1 }).值, { a: 1 });
}

