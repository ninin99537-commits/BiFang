console.log('\n[5] 闸门: 没读到过就不写; 有基线就只写改动');
{
  /** 一个假的存储 */
  function 假存储(初值: any = undefined) {
    const 状态 = { 值: 初值, 写入次数: 0 };
    return {
      状态,
      端口: {
        读: () => 状态.值,
        写: (份: any) => {
          状态.写入次数 += 1;
          状态.值 = 份;
        },
      },
    };
  }

  // ① 从没读到过 → 一个字节都不写
  const 未读到 = 假存储({ 接口: { 地址: '远端', 密钥: 'K' } });
  const 闸1 = 建写回闸门(未读到.端口);
  check('没基线时 可写回 = false', 闸1.可写回(), false);
  check('没基线时 立即写 返回 false', 闸1.立即写({ 接口: { 地址: '本地' } }), false);
  check('没基线时一个字节都没写(默认值不许覆盖用户密钥)', 未读到.状态.写入次数, 0);
  check('存储原样', 未读到.状态.值, { 接口: { 地址: '远端', 密钥: 'K' } });

  // ② 有基线: 只写改动, 远端别的字段(别的窗口刚改的)保留
  const 有基线 = 假存储({ 接口: { 地址: 'A', 密钥: 'K' }, 别人刚改的: 42 });
  const 闸2 = 建写回闸门(有基线.端口);
  闸2.记录基线({ 接口: { 地址: 'A', 密钥: 'K' }, 别人刚改的: 42 });
  check('有基线时 可写回 = true', 闸2.可写回(), true);
  check('改一个字段 → 写了', 闸2.立即写({ 接口: { 地址: 'B', 密钥: 'K' }, 别人刚改的: 42 }), true);
  check('远端: 改动生效', 有基线.状态.值.接口.地址, 'B');
  check('远端: 子对象里没提到的字段还在', 有基线.状态.值.接口.密钥, 'K');
  check('远端: 别人刚改的字段没被冲掉', 有基线.状态.值.别人刚改的, 42);

  // ③ 没改动 → 不写(避免无意义落盘与"最后写入者赢")
  const 次数前 = 有基线.状态.写入次数;
  check('同一份再写一次 → 返回 false', 闸2.立即写({ 接口: { 地址: 'B', 密钥: 'K' }, 别人刚改的: 42 }), false);
  check('也没有真的落盘', 有基线.状态.写入次数, 次数前);
  check('基线已推进到当前', 闸2.当前基线(), { 接口: { 地址: 'B', 密钥: 'K' }, 别人刚改的: 42 });

  // ④ 删键: 基线里有、现在没了 → 远端真删
  const 删 = 假存储({ 预设: { 甲: { 地址: 'A' }, 乙: { 地址: 'B' } } });
  const 闸3 = 建写回闸门(删.端口);
  闸3.记录基线({ 预设: { 甲: { 地址: 'A' }, 乙: { 地址: 'B' } } });
  check('删掉一项预设 → 写了', 闸3.立即写({ 预设: { 甲: { 地址: 'A' } } }), true);
  check('远端真的少了一项', Object.keys(删.状态.值.预设), ['甲']);

  // ⑤ 首次落盘(迁移专用): 不经过差异, 直接写并成为基线
  const 迁移 = 假存储(undefined);
  const 闸4 = 建写回闸门(迁移.端口);
  check('首次落盘 返回 true', 闸4.首次落盘({ 接口: { 地址: '迁来的' } }), true);
  check('远端拿到了整份', 迁移.状态.值, { 接口: { 地址: '迁来的' } });
  check('落盘后可写回', 闸4.可写回(), true);

  // ⑥ 写失败不许吞掉: 抛给调用方去记日志(静默失败比报错更难查)
  const 会炸 = 建写回闸门({
    读: () => undefined,
    写: () => {
      throw new Error('存储满了');
    },
  });
  会炸.记录基线({ a: 1 });
  let 抛了 = false;
  try {
    会炸.立即写({ a: 2 });
  } catch {
    抛了 = true;
  }
  ok('写失败时异常向上抛', 抛了);
  check('失败后基线不动(下次还会重试这一片)', 会炸.当前基线(), { a: 1 });
}

