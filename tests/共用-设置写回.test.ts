let pass = 0;
let fail = 0;
let 跳过 = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

// ---------------------------------------------------------------------------
console.log('\n[1] 深合并: 本次没提到的子字段原样保留');
{
  ok('普通对象判定', 是普通对象({}) && !是普通对象([]) && !是普通对象(null));
  ok('同一份: 数组按整体比', 同一份([1, 2], [1, 2]) && !同一份([1, 2], [2, 1]));

  // 关键: `{ ...prev, ...next }` 会把整个「接口」子对象覆盖掉(地址与密钥一起没)
  const 远端 = { 接口: { 地址: 'A', 密钥: 'K' }, 更新: { 开关: true } };
  const 本次 = { 接口: { 地址: 'B' } };
  check('子对象是深合并, 不是整块覆盖', 深合并(远端, 本次), { 接口: { 地址: 'B', 密钥: 'K' }, 更新: { 开关: true } });
  check('undefined = 本次不涉及, 不清存储里的值', 深合并({ a: 1 }, { a: undefined }), { a: 1 });
  check('数组整体替换(用户删掉一项后不许被合并回来)', 深合并({ 列: [1, 2, 3] }, { 列: [1] }), { 列: [1] });
  check('远端是空/坏值时按整份接受', 深合并(undefined, { a: 1 }), { a: 1 });
  // 不许改到入参
  const 原 = { 接口: { 地址: 'A' } };
  const 合 = 深合并(原, { 接口: { 地址: 'B' } });
  check('不改入参', 原.接口.地址, 'A');
  check('返回的是新对象', 合 === 原, false);
}

