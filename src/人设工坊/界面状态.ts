import { ref } from 'vue';

// ---------------------------------------------------------------------------
// 人设工坊 · 界面状态(跨「脚本入口」与「面板组件」的共享信号)
//
// 为什么需要独立模块: 入口 index.ts 跑在**脚本 realm**(魔法棒按钮事件在那注册),
// 面板组件跑在**嵌套 iframe** 里(Vue 挂在那)。两者是同一份 bundle、同一个 JS realm,
// 所以模块级 ref 是共享的 —— 入口点按钮改它, 面板 watch 它即可开合。
// 这比再引一层事件总线简单得多, 也不涉及跨文档通信。
// ---------------------------------------------------------------------------

/** 面板开合(魔法棒点一下开、再点一下关) */
export const 面板开 = ref(false);
/** 设置面板可见 */
export const 显示设置 = ref(false);
/** 草稿箱可见 */
export const 显示草稿 = ref(false);

/**
 * 设置 / 草稿箱 **互斥**(2026-10-14 #84 用户实测: 两个抽屉同时开会堆叠、把底栏挤没)。
 *
 * 用**同步的切换函数**而不是 watch: watch 是异步的(下一 tick 才跑),
 * 同一 tick 里先开设置再开草稿, 两个 watch 都会读到对方的旧值, 可能**双双关掉**。
 * 切换函数里当场把另一个置 false, 任何调用顺序都不会留两个开着的。
 * 入口只该调这两个函数, 不直接改 ref(直接改就绕过了互斥)。
 */
export function 切换设置() {
  显示设置.value = !显示设置.value;
  if (显示设置.value) 显示草稿.value = false;
}

export function 切换草稿() {
  显示草稿.value = !显示草稿.value;
  if (显示草稿.value) 显示设置.value = false;
}

/** 待载入结果区的草稿文本(草稿箱在面板里点「载入」时写入, 结果面板 watch 它) */
export const 待载入文本 = ref('');
