import { 从结果取介绍, 从结果取姓名, 净化角色名 } from './取名';

// ---------------------------------------------------------------------------
// 人设工坊 · 生成文档拆分(#124 1.2)
//
// NPC 模式下一次会生成**多个角色**, 每个角色一节, 节之间用只含 --- 的一行分隔。
// 以前这个约定只有人写、没人读: N 个角色挤进同一个世界书条目, 而且 keys 全是第一个
// 人的名字(selective 绿灯) —— 那些角色在对话里永远不会被触发。
//
// 把"拆分"收到这个深模块里: 调用方(写入世界书)只管传 模式, 不必知道
// "一份文档里可能有 N 个角色"。拆分规则属于落地, 不属于调用方。
//
// 切分锚点(#141/#139 kimicode 找茬后修正):
//   · **主锚点 = `# 角色：{名}` 标题行** —— 它是提示词**强制要求**的, 可靠;
//   · `---` 只作**次级**信号(没有角色标题时才用), 且**跳过 fenced code block** ——
//     否则角色内容里随手画的一条 markdown 水平线/台词里的 `---` 会把角色劈成两半。
//   · CRLF 统一成 LF 后再处理(以前 分隔行 不认 \r, 会拆不开 → 又退回一块)。
//
// 已知取舍(dsh #147 追认, **我们选择不修**, 留痕以免变成没人知道的坑):
//   ① **无角色标题 + 内容里出现 `---`** —— 主锚点 `# 角色：` 一个都没有时, 才退回按 `---` 切;
//      此时若角色台词/正文里恰好有一行 `---`, 会被误切。**这条不修**: 走到这一步说明模型
//      已经违反了「每节第一行必须是 `# 角色：`」的强制格式要求, 退回 `---` 只是兼容旧格式的
//      善意兜底, 不是主路径。
//   ② **混合格式**(部分角色带 `# 角色：`、部分不带) —— 现在的逻辑是「整篇有角色标题就按标题切」,
//      所以只要有一个标题, 其余没标题的块会被并进相邻角色。**这条不修**: prompt 强制每个角色
//      都有 `# 角色：`, 混合格式意味着模型半途改了格式, 为它做鲁棒性收益远小于成本。
// ---------------------------------------------------------------------------

/** 一个角色的人设块 */
export type 人设块 = { 名: string; 正文: string; 介绍: string };

/** `# 角色：X` / `# 角色: X` 标题行(整行) */
const 角色标题行 = /^[ \t]*#\s*角色\s*[:：]\s*(.+?)[ \t]*$/;
/** 只含 `---` 的一行(次级分隔信号) */
const 分隔行 = /^[ \t]*---[ \t]*$/;
/** ``` 或 ~~~ 围栏 */
const 围栏行 = /^[ \t]*(```|~~~)/;

/** 取一块里 `# 角色：X` 的角色名; 找不到返回空串。名字走**与从结果取姓名同一套归一化**。 */
function 取角色行(块: string): string {
  for (const 行 of 块.split('\n')) {
    const 匹配 = 行.match(角色标题行);
    const 值 = 匹配?.[1];
    if (值) {
      const 名 = 净化角色名(值);
      if (名) return 名;
    }
  }
  return '';
}

/**
 * 按 `# 角色：` 标题切: 每块从它的标题行开始(标题行之前的内容丢弃, 那不属于任何角色)。
 *
 * ★ #219 缺陷修复: 这里以前**没有围栏跟踪**, 而 `按分隔线切` 有 —— 于是**主锚点比次级信号
 *   更不鲁棒**: 模型把 `# 角色：X` 放进 ``` 围栏里(比如引用一段示例), 会被当成真的角色分隔,
 *   多切出一个条目。围栏在 markdown 里就是「这段别当结构读」, 两条信号行为必须一致。
 *   未闭合围栏的处理与 `按分隔线切` 相同: 一旦进入围栏, 其后所有标题都算围栏内。
 */
function 按角色标题切(行们: string[]): string[][] {
  const 块们: string[][] = [];
  let 当前: string[] | null = null;
  let 围栏: string | null = null;
  for (const 行 of 行们) {
    const 围 = 行.match(围栏行);
    if (围) {
      const 标记 = 围[1];
      if (围栏 === null) 围栏 = 标记;
      else if (标记 === 围栏) 围栏 = null;
      if (当前) 当前.push(行);
      continue;
    }
    if (围栏 === null && 角色标题行.test(行)) {
      if (当前) 块们.push(当前);
      当前 = [行];
    } else if (当前) {
      当前.push(行);
    }
  }
  if (当前) 块们.push(当前);
  return 块们;
}

/** 按只含 `---` 的一行切; **fenced code block 内不切** */
function 按分隔线切(行们: string[]): string[][] {
  const 块们: string[][] = [];
  let 当前: string[] = [];
  let 围栏: string | null = null;
  for (const 行 of 行们) {
    const 围 = 行.match(围栏行);
    if (围) {
      const 标记 = 围[1];
      if (围栏 === null) 围栏 = 标记;
      else if (标记 === 围栏) 围栏 = null;
      当前.push(行);
      continue;
    }
    if (围栏 === null && 分隔行.test(行)) {
      if (当前.length) 块们.push(当前);
      当前 = [];
      continue;
    }
    当前.push(行);
  }
  if (当前.length) 块们.push(当前);
  return 块们;
}

/**
 * 把生成结果拆成角色块。
 *
 * - `user` 模式 → 一块;
 * - `npc` 模式 → 优先按 `# 角色：` 标题切; 没有角色标题时才按 `---` 切(跳过代码块);
 *   **切不出多块时退回一块**(模型没按格式写也不能丢内容);
 * - 每块的名字: 先找 `# 角色：X`(走归一化), 找不到再退回 `从结果取姓名(该块)`;
 * - 每块的介绍: `从结果取介绍(该块)`。
 */
export function 拆分人设(文本: string, 模式: 'user' | 'npc'): 人设块[] {
  const 全文 = String(文本 ?? '').replace(/\r\n?/g, '\n').trim();
  if (!全文) return [];

  if (模式 === 'user') {
    return [{ 名: 从结果取姓名(全文), 正文: 全文, 介绍: 从结果取介绍(全文) }];
  }

  const 行们 = 全文.split('\n');
  // 主锚点: `# 角色：` 标题(提示词强制要求, 可靠)
  let 切出 = 按角色标题切(行们);
  // 次级: 没有角色标题时, 才用 `---` 分隔(跳过代码块围栏)
  if (切出.length <= 1) 切出 = 按分隔线切(行们);

  const 块们 = 切出
    .map(行组 => 行组.join('\n').trim())
    .filter(Boolean);
  const 采用 = 块们.length > 1 ? 块们 : [全文];

  return 采用.map(块 => ({
    名: 取角色行(块) || 从结果取姓名(块),
    正文: 块,
    介绍: 从结果取介绍(块),
  }));
}
