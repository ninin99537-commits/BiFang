// 人设工坊 · 名字收口(按语义边界, 不硬切字符)
//
// 用户能写很长的创作方向, 拿它派生"人设名/世界书条目标题"时**不能从字符位置硬切** ——
// 切在句子中间会很难看(与"任何截断都不要"同一条纪律)。
// 收口顺序:
//   ① 取第一行(用户换行即分段);
//   ② 第一行仍超长 → 在**句末标点**处收;
//   ③ 没有标点 → 退到**空白处**;
//   ④ 都没有 → 才硬切(名字终究要有上限)。
// 2026-10-14 #51。

/** 句末标点(中英文): 收口要落在这类字符之后 */
const 句末标点 = /[。！？；…!?;.]/;

/**
 * 按语义边界取短名。
 * @param 文本 原始文本(可为多行)
 * @param 上限 字符上限(硬上限, 返回长度不超过它)
 */
export function 取短名(文本: string, 上限: number): string {
  const 净 = String(文本 ?? '').replace(/\r\n?/g, '\n').trim();
  if (!净 || 上限 <= 0) return '';

  // ① 第一行(跳过空行)
  const 首行 = (净.split('\n').find(行 => 行.trim()) ?? '').trim();
  if (!首行) return '';
  if (首行.length <= 上限) return 首行;

  const 头段 = 首行.slice(0, 上限);

  // ② 句末标点处收(取范围内最后一个, 含标点)
  for (let i = 头段.length - 1; i >= 0; i--) {
    if (句末标点.test(头段[i])) return 首行.slice(0, i + 1);
  }

  // ③ 退到空白处(不把半个词切掉)
  const 空白位 = 头段.lastIndexOf(' ');
  if (空白位 > 0) return 首行.slice(0, 空白位);

  // ④ 实在没有边界, 才硬切
  return 头段;
}

// ── 角色名识别(2026-10-14 #78) ──────────────────────────────────────────────
//
// 世界书条目标题要用**角色名**(用户: "标题应该是角色名字，这样好辨认")。
// 角色名从**生成结果**里取 —— 「基础信息与外貌」模块的「姓名」字段。
// 取不到就让调用方走兜底并提示(别静默用一个认不出来的标题)。

/** 模块标题归一: 与 sanitize 的归一一致(去标点与连接词), 用来在结果里定位模块 */
function 归一标题(名: string): string {
  return 名.replace(/[#\s:：（）()/、·—-]/g, '').replace(/[与和及]/g, '');
}

/** 一行里的 `姓名: 值`。容忍列表符号、加粗标记、全角冒号(AI 常这么写) */
const 姓名行 = /^[\s\-*•>\d.]*[*_]*姓名[*_]*\s*[:：]\s*(.+)$/;

/** 名字外层的成对包裹符号: 剥掉才是名字本身 */
const 包裹对: [string, string][] = [
  ['「', '」'], ['『', '』'], ['“', '”'], ['《', '》'], ['〈', '〉'], ['"', '"'], ["'", "'"],
];

/** 取第一个括号补充的位置(如 `155cm(敢嘲笑我的话就咬死你！)` 里的括号); 没有返回 -1 */
function 找括号(名: string): number {
  let 位 = -1;
  for (const 标 of ['（', '(']) {
    const 当前 = 名.indexOf(标);
    if (当前 > 0 && (位 < 0 || 当前 < 位)) 位 = 当前;
  }
  return 位;
}

// ── 介绍**不截断**(2026-10-15 用户报"写入索引条目的介绍被截断了") ──────────────
//
// 这里曾经有两道收口: 收首句(砍到第一个句末标点) + 取短名(再砍到 40 字)。
// 结果是**合法的单句介绍也会被硬切** ——
//   `他是这条街上开了二十年书店的人，话少，记性好，对旧书比对人耐心`
// 一句话, 52 字, 句中无句末标点 → 第一道收不到, 第二道从中间切掉。
//
// 用户要的是**原样写入**: 索引里的介绍是认识这个角色的第一眼,
// 砍掉的那半句往往正是最有信息量的部分。
// 所以 `从结果取介绍` 现在只做 trim 与列表符号剥离, **不做任何长度或句子收口**。
// 写多长交给模块提示词(`基础信息与外貌`: "「介绍」一栏必须写：一句话说清这个人是谁"),
// 不由代码替用户决定。

/**
 * 净化角色名: 去外层包裹的引号/书名号、去括号补充, 再按语义边界收口限长。
 * 收敛但不切到半个词 —— 长度收口交回 取短名。
 */
export function 净化角色名(原始: string): string {
  // 名字永远只有一行: 换行是格式错误, 取第一行
  let 名 = String(原始 ?? '').replace(/\r\n?/g, '\n').split('\n')[0].trim();
  名 = 名.replace(/^\*+|\*+$/g, '').trim();
  for (const [头, 尾] of 包裹对) {
    if (名.length > 头.length + 尾.length && 名.startsWith(头) && 名.endsWith(尾)) {
      名 = 名.slice(头.length, 名.length - 尾.length).trim();
      break;
    }
  }
  const 括号 = 找括号(名);
  if (括号 > 0) 名 = 名.slice(0, 括号).trim();
  return 取短名(名, 24);
}

/**
 * 从生成结果里取角色名。
 * @param 文本     生成结果
 * @param 段落标题 承载姓名的模块标题(默认「基础信息与外貌」)
 * @returns 收敛后的名字; 没勾该模块 / 模型没按格式写 → 空串(调用方据此走兜底)
 */
export function 从结果取姓名(文本: string, 段落标题 = '基础信息与外貌'): string {
  const 目标 = 归一标题(段落标题);
  let 命中段 = false;
  for (const 行 of String(文本 ?? '').replace(/\r\n?/g, '\n').split('\n')) {
    const 净 = 行.trim();
    if (净.startsWith('##') && !净.startsWith('###')) {
      命中段 = 归一标题(净) === 目标;
      continue;
    }
    if (!命中段) continue;
    const 匹配 = 净.match(姓名行);
    const 值 = 匹配?.[1];
    if (值) {
      const 名 = 净化角色名(值);
      if (名) return 名;
    }
  }
  return '';
}

/** 一行里的 `介绍: 值`(与姓名行同构: 容忍列表符号 / 加粗 / 全角冒号) */
const 介绍行 = /^[\s\-*•>\d.]*[*_]*介绍[*_]*\s*[:：]\s*(.+)$/;

/** 在某个模块段里找 `介绍:` 那一行的值; 找不到返回空串 */
function 段内取介绍行(文本: string, 段落标题: string): string {
  const 目标 = 归一标题(段落标题);
  let 命中段 = false;
  for (const 行 of String(文本 ?? '').replace(/\r\n?/g, '\n').split('\n')) {
    const 净 = 行.trim();
    if (净.startsWith('##') && !净.startsWith('###')) {
      命中段 = 归一标题(净) === 目标;
      continue;
    }
    if (!命中段) continue;
    const 值 = 净.match(介绍行)?.[1];
    if (值) {
      const 句 = 值.trim();
      if (句) return 句;
    }
  }
  return '';
}

/**
 * 从生成结果里取「介绍」。
 *
 * #124 1.4: **优先**读 AI 在「基础信息与外貌」里显式产出的「介绍」字段 ——
 * 那是「这是谁」的说明, 比锚定句更贴切; 读不到才退回「锚定段首行」。
 *
 * ★ 2026-10-15: **整句原样返回, 不截断**(见上方"介绍不截断"注释)。
 * 以前这里会砍到第一句 / 40 字, 把合法的长单句切掉半截。
 * 两处都没有 → 空串(调用方报错让用户手填, 不瞎编)。
 */
export function 从结果取介绍(文本: string, 段落标题 = '性格锚定'): string {
  const 显式 = 段内取介绍行(文本, '基础信息与外貌');
  if (显式) return 显式;

  const 目标 = 归一标题(段落标题);
  let 命中段 = false;
  for (const 行 of String(文本 ?? '').replace(/\r\n?/g, '\n').split('\n')) {
    const 净 = 行.trim();
    if (净.startsWith('##') && !净.startsWith('###')) {
      命中段 = 归一标题(净) === 目标;
      continue;
    }
    if (!命中段 || !净) continue;
    return 净;
  }
  return '';
}

/** 人设条目标题: 名字 + 是否走了兜底(界面要据此提示用户) */
export type 标题线索 = { 名: string; 兜底: boolean };

/**
 * 人设条目(=该角色人设)的标题。
 *
 * 优先用生成结果里的角色名; 取不到就退回创作方向短名(用户能看懂自己在写谁),
 * 并标记 兜底=true —— 界面必须提示, 不能静默用一个认不出来的标题。
 */
export function 取人设条目标题(
  结果文本: string,
  brief: string,
  mode: 'user' | 'npc' = 'user',
  段落标题?: string,
): 标题线索 {
  const 识别 = 从结果取姓名(结果文本, 段落标题);
  if (识别) return { 名: 识别, 兜底: false };
  const 提示 = 取短名(String(brief ?? ''), 16);
  return { 名: 提示 || (mode === 'npc' ? '未命名NPC' : '玩家'), 兜底: true };
}
