// 人设工坊 · 提示词预览折叠(#124 批次3 / dsh #162)
//
// 为什么要独立成纯函数: 折叠的**不变量是「字符数有上限」**, 而这个不变量曾经写错成
// 「行数有上限」—— 行数只是字符数的**代理指标, 会脱钩**。脱钩时的表现是:
// **修复静默失效, 不报错, 只是变慢**, 比报错更难发现。
// 抽出来才能用「行数很少但字符很多」这种**专门构造的对抗输入**钉住它。
//
// 只影响**显示** —— 复制/发送走的始终是全文(调用方拿 props.提示词)。

/** 折叠态预览的字符上限。★ 判据是字符不是行 —— 行数与开销会脱钩 */
export const 预览上限 = 12000;

/**
 * 是否值得折叠: **按字符数**判, 不看行数。
 */
export function 需要折叠(全文: string, 上限 = 预览上限): boolean {
  return String(全文 ?? '').length > 上限;
}

/**
 * 折叠态实际绑给 textarea 的文本。
 *
 * 按**字符预算累行**, 保证返回值长度被 `上限` 封顶(加尾巴几十字), 与行结构无关 ——
 * 这样"行数与开销脱钩"的两个漏洞都不存在:
 *   · 3 行 × 5 万字的文本: 按行切片会返回全文, 按字符预算才会截短;
 *   · 第一行就超上限的超长单行: 累行会一行都放不下 → 走硬截兜底, 不返回全文。
 */
export function 折叠预览(全文: string, 上限 = 预览上限): string {
  const 源 = String(全文 ?? '');
  const 行们 = 源.split('\n');
  const 取: string[] = [];
  let 已用 = 0;
  for (const 行 of 行们) {
    // +1 是换行符; 留出尾巴的空间, 保证总长不超上限
    if (已用 + 行.length + 1 > 上限) break;
    取.push(行);
    已用 += 行.length + 1;
  }
  // 极端情况: 第一行就超上限(超长单行) → 硬截到上限, 否则会原样返回全文
  const 头 = 取.length ? 取.join('\n') : 源.slice(0, 上限);
  return `${头}\n\n… （预览到此为止 / 共 ${源.length} 字，点上方「展开全文」查看）`;
}
