// 人设工坊 · 自动填充判据(2026-10-15 用户报「文本框内容不会自动变」)
//
// 背景: 结果区有两个框(角色名 / 索引介绍)会从生成结果里**自动带出**内容,
// 同时允许用户手改。旧写法用「框里是不是空的」来决定要不要填:
//
//     if (框.value.trim()) return;      // ← 只在为空时填
//
// **这个判据是错的**: 自动填进去的值也是非空的, 所以它从第二次起把自己挡住了 ——
// 生成第二个人设, 框里还停着第一个人的名字/介绍。
//
// 它想说的是「用户手改过就别覆盖」。要区分「自动填的」和「用户改的」,
// 必须记住**上一次自动填进去的值**, 而不是看「空不空」。
//
// 抽成纯函数是为了**可测** —— 三种状态(空 / 还是自动值 / 用户改过)必须都测,
// 只测「空的时候会填」的话, 这个 bug 会原样通过。

/**
 * 该不该用新的自动值覆盖框里的当前值?
 *
 * @param 当前       框里现在的值
 * @param 上次自动值 上一次**自动**填进去的值(用户手改后它不变)
 * @returns 该覆盖 → true; 用户改过、别动 → false
 */
export function 该自动填(当前: string, 上次自动值: string): boolean {
  const 净 = String(当前 ?? '').trim();
  if (!净) return true; // 空的: 填
  return 净 === String(上次自动值 ?? '').trim(); // 还是上次自动填的那个 → 用户没动过
}
