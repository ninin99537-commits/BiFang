/** 一条字段的全部知识: 数据里的键、表单标签、枚举、旧快照名与 AI 别名、是否多行 */
export interface 字段定义 {
  键: string;
  /** 表单/展示里的标签(缺省=键) */
  标签?: string;
  /** 枚举白名单: 表单下拉用它, 越界值按 兜底 纠偏 */
  枚举?: readonly string[];
  /** 枚举越界时的兜底值(缺省=枚举第一项) */
  兜底?: string;
  /** 旧快照里的旧字段名(读到就迁移过来, 如 势力范围 ← 领地) */
  旧名?: string[];
  /** AI 载荷里的别名(提示词之外模型自己换的名字, 如 头面人物 ← 首领) */
  别名?: string[];
  /** 滚动总结字段: AI 填"无变化/同上"这类占位词时沿用旧值 */
  占位沿用?: boolean;
  /** 表单里用多行输入 */
  多行?: boolean;
  /** 所有文本值完整保留；长度只在写作建议与诊断中使用。 */
  /** 缺值时的兜底文本(优先于空串; 快照模式不填, 保持"旧数据原样") */
  缺省?: string;
  /** 提示词 JSON 模板里的示例值(缺省 "..."; 空串表示模板里就该是 "") */
  示例值?: string;
}

/** 五层常驻档案的层名(世界数据变更.ts 那道门收的"层") */
