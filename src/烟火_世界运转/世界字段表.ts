export type 事件规范化模式 = '快照' | 'AI' | '手改';

export interface 事件规范化选项 {
  /** AI 与手改模式: 时间字段缺省时回落到这个世界时间; 快照模式不回落(它自己的时间就是历史) */
  世界时间?: string;
}

/**
 * 一条事件的字段规范化 —— 快照 / AI 载荷 / 面板手改 三种模式共用这一把尺。
 *
 * 三种模式**只有两处方言差异**, 其余(枚举纠偏、别名、完整文本、缺省)完全一致:
 *   ① 快照模式不认别名: 旧快照的字段名只走 旧名 迁移, AI 换过的说法不该在那里生效;
 *   ② 快照模式不填缺省: 旧数据缺什么就留空串, 不被「（无描述）」这类新默认值污染。
 * 时间字段的回落也是模式差异: AI/手改回落到当前世界时间, 快照留空。
 *
 * 标题为空返回 null(与以前一样, 无标题的事件直接丢弃)。
 * id 与「演变」不在这里: 前者由脚本签发, 后者由脚本累积, 都不是用户可见字段。
 */
export function 规范化事件字段(
  源: Record<string, unknown> | null | undefined,
  模式: 事件规范化模式,
  选项: 事件规范化选项 = {},
): Record<string, string> | null {
  const 原 = 源 ?? {};
  const 认别名 = 模式 !== '快照';
  const 填缺省 = 模式 !== '快照';
  const 取值 = (字段: 字段定义): unknown => {
    if (原[字段.键] != null) return 原[字段.键];
    for (const 名 of 字段.旧名 ?? []) if (原[名] != null) return 原[名];
    if (认别名) for (const 名 of 字段.别名 ?? []) if (原[名] != null) return 原[名];
    return undefined;
  };
  const 条目: Record<string, string> = {};
  for (const 字段 of 事件层.字段) {
    const 原值 = 取值(字段);
    if (原值 != null && typeof 原值 === 'object') throw Error(`事件「${字段.键}」应为文本，不接受对象或数组`);
    let 值 = 文本(原值);
    if (字段.键 === '时间' && !值 && 模式 !== '快照') 值 = 文本(选项.世界时间);
    if (!值 && 填缺省 && 字段.缺省) 值 = 字段.缺省;
    条目[字段.键] = 字段.枚举 ? 字段值(字段, 值) : 值;
  }
  return 条目.标题 ? 条目 : null;
}

/** 提示词模板里事件对象的键序: 与 v2.5 起的模板逐字一致(只是顺序, 字段与示例值仍来自 事件层) */
const 事件提示词键序 = ['id', '标题', '描述', '前情', '变化', '地点', '时间', '规模', '传播', '渠道', '势力', '代表人物', '阶段', '隐秘'];

/**
 * 提示词 JSON 模板里的事件对象。键序单独钉住 —— 提示词是冻结红线(见 tests/yanhuo-prompt-freeze.test.ts),
 * 换序会让请求体逐行差分翻红; 但每个键的示例值仍从 事件层 取, 所以"加一个事件字段"只要改表。
 */
export function 事件JSON示例(): string {
  const 按名 = new Map(事件层.字段.map(字段 => [字段.键, 字段]));
  return 事件提示词键序
    .map(键 => {
      if (键 === 'id') return '"id":""';
      if (键 === '变化') return '"变化":"..."';
      const 字段 = 按名.get(键);
      if (!字段) throw new Error(`[烟火] 事件提示词键序里有事件层没有的键: ${键}`);
      return JSON字段(字段);
    })
    .join(',');
}
