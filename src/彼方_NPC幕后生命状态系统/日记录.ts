// 彼方 · 日记录: 卡上那些 "YYYY-MM-DD|数值" 形状的**当日累计**。
//
// 为什么单独一个 module: 生理的「受孕判定记录」与恋爱的「好感日涨」是同一种东西 ——
// 一个日期键 + 当天的累计值, 只在**同一天**才认, 跨天就归零重开。以前两处各写一份
// 一模一样的正则 `^(\d{3,6}-\d{2}-\d{2})\|([\d.]+)$`, 连"不能 slice(0,10)"的坑都各写一遍。
//
// 数值的格式由调用方给(受孕率要 4 位小数、好感要 1 位), 这里只管"日期键 + 分隔符"的形状。

/** 日记录的形状: "2025-09-18|0.0421" */
const 日记录模式 = /^(\d{3,6}-\d{2}-\d{2})\|([\d.]+)$/;

/** 读出**同一天**的累计值; 不是同一天 / 没有记录 / 认不出 → null(调用方按 0 处理) */
export function 读当日值(原值: unknown, 日期键: string): number | null {
    if (!日期键)
        return null;
    const m = String(原值 ?? '').match(日记录模式);
    if (!m || m[1] !== 日期键)
        return null;
    const 值 = Number(m[2]);
    return Number.isFinite(值) ? 值 : null;
}

/** 写回一条日记录; 数值由调用方格式化好(小数位数是各字段自己的事) */
export function 写当日值(日期键: string, 数值: string): string {
    return `${日期键}|${数值}`;
}
