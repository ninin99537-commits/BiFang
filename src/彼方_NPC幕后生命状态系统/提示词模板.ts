/** 模板里的一段。
 *
 *  ── 为什么是"段列表"而不是"固定的三段"（2026-11-19 改）──
 *  最初做成「系统段 / 场景判断 / 用户段」三个固定字段。用户看到参考实现后指出：
 *  **那是把"消息结构"当成了"编辑结构"**。他要的是可增删的段，段按顺序排，每段自己选 role。
 *
 *  ── **一段 = 一条消息**（2026-11-19 定稿）──
 *  中间试过"相邻同 role 自动合并"，还为此加过 `独立` 维度（普通段/独立段）。
 *  **那个维度被砍了** —— 用户问「独立段是干嘛的」，而答案是"为了保留合并能力硬造的概念"。
 *
 *  现在的规则只有一条：**一段就是一条消息，不合并**。
 *    · 想要一条消息 → 写在一段里
 *    · 想要三条 → 写三段
 *
 *  于是 I3 天然成立（默认 3 段 = 3 条消息），场景判断天然单独一条（防全知设计保住），
 *  而"合并会把 158 字并进 12980 字"那个冲突**不存在了**。
 *
 *  ── `id` 为什么必须存在 ──
 *  删/拖要靠它定位。**不能靠下标**：删了第 2 段之后，原来的第 3 段下标变成 2，
 *  任何"记住下标"的操作都会打到错的那一段。
 */
export interface 模板段 {
    /** 段的身份。默认段用固定字符串（`默认-1`），用户新建的用 uuid。 */
    id: string;
    /** 这条消息的身份 */
    role: 'system' | 'user' | 'assistant';
    /** 段文本（含占位符） */
    content: string;
}

