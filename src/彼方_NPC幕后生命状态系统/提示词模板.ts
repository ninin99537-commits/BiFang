/** 一个段里出现过的占位符名（去重，按出现顺序）。用于 V1 清单与"未出现在模板里"。 */
export function 段里的占位符(文本: string): string[] {
    const 见 = new Set<string>();
    for (const 命中 of 扫占位符(文本)) 见.add(命中.写的名);
    return [...见];
}

/** 整份模板里出现过的占位符名（去重）。 */
export function 模板里的占位符(模板: 提示词模板): string[] {
    const 见 = new Set<string>();
    for (const 段 of 段名表) for (const 名 of 段里的占位符(模板[段])) 见.add(名);
    return [...见];
}

/** **渲染一段模板。这是唯一一处渲染实现。**
 *
 *  @param 文本  模板里的一段（含占位符）
 *  @param 取内容 按占位符名取内容。**未知名字必须返回空串**（C2：未知忽略 + warn 由调用方打）
 *
 *  @returns 渲染后的文本
 *
 *  ── 为什么这里不自己扫占位符 ──
 *  用 `扫占位符` 会把"拼错的名字"也扫出来（它的 `零件` 字段是 undefined）。
 *  本函数**不做判断**，只按名字取内容 —— 拼错的名字取不到内容就是空串，
 *  于是那一行整行消失。这是 C2 的既有行为（未知忽略），不是这里新定的。
 */
export function 渲染段(文本: string, 取内容: (名: string) => string): string {
    if (!文本)
        return '';
    /** 渲染后的项。`是整行占位符` 决定它前面要不要补换行。 */
    const 项们: { 文: string; 是整行占位符: boolean }[] = [];
    for (const 行 of 文本.split('\n')) {
        // ① 整行只有一个占位符 → 换成它的内容，**这一行前面的换行也丢掉**
        //
        // 为什么丢：除 R1 与 D1 外，**所有零件内容都以 `\n\n` 开头**（实测）。
        // 所以"占位符自带分隔"是它们的固有属性 —— 模板再补一个换行就是三个。
        // 这条错了两次才量出来：v1 无条件补 `\n`（多一个）；v2 只在上一行不是占位符时补
        // （身份句与 R2 之间多一个）。
        const 整行 = 行.match(/^\{\{\s*彼方\s*[:：]\s*([^{}]+?)\s*\}\}$/);
        if (整行) {
            const 值 = 取内容(整行[1]) ?? '';
            // ② 展开为空 → 整行消失（连这一行也不产生换行）
            if (!值)
                continue;
            项们.push({ 文: 值, 是整行占位符: true });
            continue;
        }
        // ②b 行内占位符里有空的 → **整行消失（连同行内其他文字）**
        //
        // 这条是无条件的（需求方 #211 ①）。为什么：默认模板里标签与占位符写在同一行
        // （`世界书/设定(与主AI相同…):{{彼方:世界书}}`），世界书为空时那一整行必须
        // 一起消失，否则留下孤立标签 —— 默认产物就变了。
        const 命中们 = [...行.matchAll(/\{\{\s*彼方\s*[:：]\s*([^{}]+?)\s*\}\}/g)];
        if (命中们.some(m => !(取内容(m[1]) ?? '')))
            continue;
        // ③ 行内占位符 → 直接替换，保留行结构
        const 替换后 = 行.replace(/\{\{\s*彼方\s*[:：]\s*([^{}]+?)\s*\}\}/g, (_, 名) => 取内容(名) ?? '');
        项们.push({ 文: 替换后, 是整行占位符: false });
    }
    let 结果 = '';
    for (let i = 0; i < 项们.length; i++) {
        // ④ 普通行前面补换行；整行占位符前面不补（它自己带 `\n\n`）
        if (i > 0 && !项们[i].是整行占位符)
            结果 += '\n';
        结果 += 项们[i].文;
    }
    return 结果;
}

/** 渲染整份模板（三段各自渲染，**不合并** —— 段与段之间是消息边界）。 */
export function 渲染模板(模板: 提示词模板, 取内容: (名: string) => string): Record<段名, string> {
    const 出 = {} as Record<段名, string>;
    for (const 段 of 段名表) 出[段] = 渲染段(模板[段] ?? '', 取内容);
    return 出;
}

/** 模板里有没有这个占位符（用于"未出现在模板里"的清单）。 */
export function 模板含(模板: 提示词模板, 名: string): boolean {
    return 段名表.some(段 => 扫占位符(模板[段] ?? '').some(命中 => 命中.写的名 === 名));
}

/** 从一份**旧数据**（条目列表 / 旧锚点段）生成模板文本。
 *
 *  ── 为什么要这个（迁移）──
 *  用户之前把提示词写成"条目列表"（可拖顺序、可增删）。模板化之后那些条目要变成
 *  三段文本里的字。**按当前生效顺序拼**，用户写的正文原样保留（里面的占位符也原样）。
 *
 *  ── 为什么按"块"分配到三段 ──
 *  条目的 `role` 决定它进哪条消息（C18 的块划分），而消息 → 段是固定映射
 *  （`段块表`）。所以 `role: system` 的条目进系统段，`user`/`assistant` 进用户段。
 *  **场景判断段不接收任何条目** —— 它是 D13 的专用位置（防全知设计）。
 *
 *  @param 条目们 已排好序的条目（每项 `{ role, content, 启用 }`）
 *  @param 默认  默认模板（迁移时以它为底，把条目按位置插进去）
 */
export function 由条目生成模板(
    条目们: { role?: string; content?: string; 启用?: boolean }[],
    默认: 提示词模板 = 默认模板,
): 提示词模板 {
    const 系统段: string[] = [];
    const 用户段: string[] = [];
    for (const 条 of 条目们) {
        if (!条 || 条.启用 === false)
            continue;
        const 正文 = String(条.content ?? '');
        if (!正文.trim())
            continue;
        // `assistant` 与 `user` 都进用户段 —— 它们都是"对话侧"，而三段里只有用户段是对话侧。
        // （`assistant` 条目本来就是用户手写的"预填充式"内容，放用户段语义最接近。）
        if (String(条.role ?? 'system') === 'system')
            系统段.push(正文);
        else
            用户段.push(正文);
    }
    return {
        // 系统段：默认模板在前，用户条目在后（用户写的是"补充"，不是"替换"）
        系统段: [默认.系统段, ...系统段].join('\n'),
        // 场景判断：**不接收条目**（它是 D13 专用位）
        场景判断: 默认.场景判断,
        用户段: [...用户段, 默认.用户段].join('\n'),
    };
}
