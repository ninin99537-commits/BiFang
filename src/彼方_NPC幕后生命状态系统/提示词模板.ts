// 彼方 · 提示词模板（2026-11-19 模板化）
//
// ── 这是什么 ─────────────────────────────────────────────────────────
// 用户看到的「三段可编辑文本 + 占位符」。默认模板由**当前产物挖洞**生成（不是手写），
// 所以 I3（默认模板展开后与现在的产物逐字节一致）在结构上成立，不靠断言维持。
//
// ── 三段为什么是三段 ──────────────────────────────────────────────────
// 现在的产物是三条消息：system（规则）/ system（场景判断）/ user（剧情与状态）。
// 那个"三条"是**块归属**决定的（见 零件表.ts 的 `块` 字段），不是文本能表达的。
// 所以模板必须分三段 —— 一段文本做不到"这里断成两条消息"。
//
// 实测依据（2026-11-19）：17 个零件全放一起渲染 14883 字，现在全文 14884 字，
// 差的 1 字正好在 R5 与 D1 之间 —— 那是**消息拼接时加的** `\n`，不是任何零件的内容。
//
// ── 渲染规则（四条，全是量出来的）────────────────────────────────────
//   ① 独占一行的占位符 → 换成它的内容，**这一行不再有自己的换行**
//   ② 展开为空 → **整行消失**（连同行内其他文字）
//   ③ 行内占位符 → 直接替换，保留行结构
//   ④ 换行只在「两个普通文字行相邻」时补
//
// ── 第 ④ 条为什么是这样（不是设计，是实测）──────────────────────────
// 除 R1 与 D1 外，**所有零件内容都以 `\n\n` 开头**（R2–R5、D2、D-T、D-N、D9、
// D10、D12、D14 都是）。所以"占位符自己带分隔"是它们的固有属性 ——
// 模板再加换行就是三个。
//
// 我在这条上错了两次：v1 无条件加 `\n`（多一个）；v2 只在上一行不吃换行时加
// （身份句与 R2 之间多一个）。第三次才量出"占位符自带分隔"这个事实。
//
// ── 空则整行消失为什么必要 ────────────────────────────────────────────
// 有 7 个零件是**条件性的**：数据为空时现在连包装一起消失（整段空串）。
// 实测：世界书为空时 `零件内容.D2 === ''`，连"世界书/设定(与主AI相同…):"一起没有。
// 若包装搬进模板而数据为空，就会留下一行孤立标签 —— 默认产物变了。
// "空则整行消失"让两者同生共死，I3 因此保住。
//
// 代价（用户要接受的）：想让"空时也保留那句说明"做不到 —— 那一行会连说明一起消失。
import { 扫占位符, type 块名 } from './零件表';

/** 三段模板。**顺序固定**：系统段 / 场景判断 / 用户段。 */
