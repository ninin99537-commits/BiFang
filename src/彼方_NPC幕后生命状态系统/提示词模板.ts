/** 渲染结果的一项：一段文字 + 它是不是"整行占位符"。
 *  规则 ④ 需要这个信息（整行占位符前面不补换行）。 */
interface 渲染项 {
    文: string;
    是整行占位符: boolean;
}

/** 一段里出现过的占位符名（去重，按出现顺序）。用于 V1 清单与"未出现在模板里"。 */
export function 段里的占位符(文本: string): string[] {
    const 见 = new Set<string>();
    for (const 命中 of 扫占位符(文本)) 见.add(命中.写的名);
    return [...见];
}

/** 整份模板里出现过的占位符名（去重）。 */
export function 模板里的占位符(模板: 提示词模板): string[] {
    const 见 = new Set<string>();
    for (const 段 of 模板) for (const 名 of 段里的占位符(段.content)) 见.add(名);
    return [...见];
}

/** **渲染一段模板。这是唯一一处渲染实现。**
 *
 *  @param 文本  模板里的一段（含占位符）
 *  @param 取内容 按占位符名取内容。**未知名字必须返回空串**（C2：未知忽略 + warn 由调用方打）
 *
 *  ── 为什么这里不自己扫占位符 ──
 *  用 `扫占位符` 会把"拼错的名字"也扫出来（它的 `零件` 字段是 undefined）。
 *  本函数**不做判断**，只按名字取内容 —— 拼错的名字取不到内容就是空串，
 *  于是那一行整行消失。这是 C2 的既有行为（未知忽略），不是这里新定的。
 */
export function 渲染段(文本: string, 取内容: (名: string) => string): string {
    if (!文本)
        return '';
    const 项们: 渲染项[] = [];
    /** 缓存本段内每个占位符的取值 —— **一次渲染里同一个名字只问一次**。
     *
     *  ── 为什么必须有这个缓存（2026-11-19 实测）──
     *  `取内容` 在模板路径下带**副作用**（"首处生效"的 `已展开` 集合）。
     *  而本函数对同一个占位符会问两次：一次判断"是否为空"（规则 ②b），一次取替换值（规则 ③）。
     *  没有缓存的话，第二次会拿到空串（因为第一次已经把它标记成"已展开"）——
     *  症状是**占位符全部展开成空**（实测：世界书展开 0 次，20 种组合全红）。
     *
     *  缓存之后：同一个名字在本段内只问一次，副作用只发生一次。 */
    const 缓存 = new Map<string, string>();
    const 问 = (名: string): string => {
        if (!缓存.has(名))
            缓存.set(名, 取内容(名) ?? '');
        return 缓存.get(名)!;
    };
    for (const 行 of 文本.split('\n')) {
        // ① 整行只有一个占位符 → 换成它的内容，**这一行前面的换行也丢掉**
        //
        // 为什么丢：除 R1 与 D1 外，**所有零件内容都以 `\n\n` 开头**（实测）。
        // 所以"占位符自带分隔"是它们的固有属性 —— 模板再补一个换行就是三个。
        const 整行 = 行.match(/^\{\{\s*彼方\s*[:：]\s*([^{}]+?)\s*\}\}$/);
        if (整行) {
            const 值 = 问(整行[1]);
            // ② 展开为空 → 整行消失（连这一行也不产生换行）
            if (!值)
                continue;
            项们.push({ 文: 值, 是整行占位符: true });
            continue;
        }
        // ②b 行内占位符里有空的 → **整行消失（连同行内其他文字）**
        //
        // 这条是无条件的（需求方 #211 ①）。为什么：默认模板里标签与占位符写在同一行
        // （`世界书/设定(与主AI相同…):{{彼方:世界书}}`），世界书为空时那一整行必须
        // 一起消失，否则留下孤立标签 —— 默认产物就变了。
        const 命中们 = [...行.matchAll(/\{\{\s*彼方\s*[:：]\s*([^{}]+?)\s*\}\}/g)];
        if (命中们.some(m => !问(m[1])))
            continue;
        // ③ 行内占位符 → 直接替换，保留行结构
        const 替换后 = 行.replace(/\{\{\s*彼方\s*[:：]\s*([^{}]+?)\s*\}\}/g, (_, 名) => 问(名));
        项们.push({ 文: 替换后, 是整行占位符: false });
    }
    let 结果 = '';
    for (let i = 0; i < 项们.length; i++) {
        // ④ 普通行前面补换行；整行占位符前面不补（它自己带 `\n\n`）
        if (i > 0 && !项们[i].是整行占位符)
            结果 += '\n';
        结果 += 项们[i].文;
    }
    return 结果;
}

/** 把段列表变成消息（**这一步决定"几条消息"**）。
 *
 *  ── 规则只有一条：一段 = 一条消息 ──
 *  不合并、不加维度（2026-11-19 定稿，见 `模板段` 的注释）。
 *  渲染后为空的段**整段不出现**（不是发一条空消息）——
 *  这是"条件性内容为空时整段消失"的落点（需求方 #211 ②）。
 *
 *  @returns 消息列表（role + content）
 */
export function 段列表变消息(
    模板: 提示词模板,
    取内容: (名: string) => string,
): { role: 模板role; content: string }[] {
    const 出: { role: 模板role; content: string }[] = [];
    // **防御**：调用方可能传了旧格式（对象）或 undefined —— 一律当空列表处理，
    // 而不是抛错。理由：这是渲染路径，抛错会让整条消息发不出去；
    // 而空列表最坏是"这条消息为空"，用户立刻能从预览看出来。
    const 段们 = Array.isArray(模板) ? 模板 : [];

    /** **C4 首处生效**（2026-11-19 补）。
     *
     *  ── 为什么必须在这一层做 ──
     *  `渲染段` 是**逐段独立**的（它只知道自己那一段），所以它无法判断
     *  "这个占位符在别的段里已经展开过"。而 C4 要求"同一零件在产物里只能出现一次"——
     *  那是**跨段**的性质，只能在把段拼成消息的这一层做。
     *
     *  ── 为什么必须做（实测）──
     *  `bifang-零件化.test.ts` 的 `[L]` 段穷举了 20 种"两段各写一次同一个占位符"：
     *  不补这一层的话，世界书会**展开 2 次**（20 种组合全部 2 次）。
     *  而 I1（至多出现一次）就是这个性质。
     *
     *  ── 不展开的那一处变成什么 ──
     *  **空串**（不是原样保留）—— 与锚点路径的既有约定一致：
     *  原样保留会把 `{{彼方:X}}` 这种语法发给模型，比丢掉更糟。
     *  空串会让那一行"整行消失"（渲染规则 ②），所以用户看到的是"那一行没了"，
     *  而不是"那里有个奇怪的占位符"。 */
    const 已展开 = new Set<string>();
    const 只展开一次 = (名: string, role: 模板role): string => {
        if (已展开.has(名))
            return '';
        // **C5：场景判断只能被 system 段引用**（2026-11-19 补进模板路径）。
        //
        // 为什么这条必须在这里：它守的是**防全知设计**（需求方 #211 ②）——
        // 场景判断那段是"玩家最近一次输入"，只用来判断谁与玩家同场景。
        // 若它出现在 user 段里，就与"剧情"混在一起，模型会把它当成 NPC 能知道的事。
        //
        // 实测依据：`bifang-拼装页.test.ts` 的 `[U4]` —— user 段写
        // `{{彼方:场景判断}}` 时，不补这条判据的话它会照常展开（26 通过 1 失败）。
        if (名 === '场景判断' && role !== 'system')
            return '';
        已展开.add(名);
        return 取内容(名);
    };

    for (const 段 of 段们) {
        const 正文 = 渲染段(段?.content ?? '', 名 => 只展开一次(名, 段.role));
        // 空段整段不出现（不是发一条空消息）
        if (!正文.trim())
            continue;
        出.push({ role: 段.role, content: 正文 });
    }
    return 出;
}

/** 段列表里**至少要有一段 user**（需求方 #230）。
 *
 *  ── 为什么是硬约束 ──
 *  `api.ts` 取**最后一条 user** 当 `user_input`；没有 user 段就是空串 ——
 *  请求发不出去，而用户看不出为什么（他只是删了一段）。
 *
 *  ── 为什么返回文案而不是布尔 ──
 *  要报错就得说人话。返回布尔的话，调用方得自己编一句话，
 *  而"每个调用方各编一句"就是同一件事的多份实现（§十二 #1）。
 *
 *  @returns null = 没问题；字符串 = 错误文案（直接给用户看）
 */
export function 校验模板(模板: 提示词模板): string | null {
    const 段们 = Array.isArray(模板) ? 模板 : [];
    if (段们.length === 0)
        return '提示词是空的 —— 至少要有一段 USER。';
    const 有user = 段们.some(段 => 段?.role === 'user' && String(段?.content ?? '').trim());
    if (!有user)
        return '至少要有一段 USER —— 彼方要把它当成本轮的输入发出去；没有它，请求发不出去。';
    return null;
}

/** 模板里有没有这个占位符（用于"未出现在模板里"的清单）。 */
export function 模板含(模板: 提示词模板, 名: string): boolean {
    return 模板.some(段 => 扫占位符(段.content ?? '').some(命中 => 命中.写的名 === 名));
}

/** 新建一段（uuid）。**为什么不是自增序号**：模块级序号在页面重挂时归零，
 *  新段会拿到与旧段相同的 id —— 而删除是按 id 定位的，撞 id = 删一条删两条。 */
export function 新段id(): string {
    const 原生 = (globalThis as any).crypto?.randomUUID;
    if (typeof 原生 === 'function')
        return `段-${原生.call((globalThis as any).crypto)}`;
    const 随机 = () => Math.random().toString(36).slice(2, 10);
    return `段-${Date.now().toString(36)}-${随机()}-${随机()}`;
}

/** 从一份**旧数据**（条目列表）生成段列表。
 *
 *  ── 为什么按 role 分段而不是"一条目一段" ──
 *  用户之前写的条目本来就是"一段话"，而且它们有 role。一条目一段最忠实，
 *  但那样默认模板的 3 段会被拆开重排 —— 用户看到的与他原来的不一样。
 *  所以：**默认段列表在前，用户的条目按 role 追加到对应位置**。
 *
 *  ── 内容一字不改 ──
 *  `role` / 正文原样；禁用的与空的跳过。
 *
 *  @param 条目们 已排好序的条目（每项 `{ role, content, 启用 }`）
 *  @param 默认  默认段列表（迁移时以它为底）
 */
export function 由条目生成模板(
    条目们: { role?: string; content?: string; 启用?: boolean }[],
    默认: 提示词模板 = 默认模板,
): 提示词模板 {
    // 深拷贝一份（默认模板是常量，改了会污染全局）
    const 段们: 提示词模板 = 默认.map(段 => ({ ...段 }));    /** 追加到哪：系统条目插在第 1 段之后，其余追加到末尾 */
    const 系统追加: 模板段[] = [];
    const 用户追加: 模板段[] = [];
    for (const 条 of 条目们) {
        if (!条 || 条.启用 === false)
            continue;
        const 正文 = String(条.content ?? '');
        if (!正文.trim())
            continue;
        const role = (条.role === 'user' || 条.role === 'assistant') ? 条.role : 'system';
        const 新段: 模板段 = { id: 新段id(), role, content: 正文 };
        if (role === 'system')
            系统追加.push(新段);
        else
            用户追加.push(新段);
    }
    // 系统条目插在"最后一段 system 之后"（保持 system 段聚在一起，符合"同 role 相邻"的直觉）
    if (系统追加.length > 0) {
        let 位 = 0;
        for (let i = 0; i < 段们.length; i++) if (段们[i].role === 'system') 位 = i + 1;
        段们.splice(位, 0, ...系统追加);
    }
    return [...段们, ...用户追加];
}
