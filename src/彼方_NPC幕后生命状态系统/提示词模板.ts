// 彼方 · 提示词模板（2026-11-19 模板化 —— 段列表形态）
//
// ── 这是什么 ─────────────────────────────────────────────────────────
// 用户看到的「可增删的段列表 + 占位符」。默认段列表由**当前产物挖洞**生成（不是手写），
// 所以 I3（默认模板展开后与现在的产物逐字节一致）在结构上成立，不靠断言维持。
//
// ── 为什么是"段列表"而不是"三个固定字段"（2026-11-19 改）──
// 最初做成「系统段 / 场景判断 / 用户段」三个固定字段。用户看到参考实现后指出：
// **那是把"消息结构"当成了"编辑结构"**。他要的是可增删的段，段按顺序排，每段自己选 role。
//
// ── 段怎么变成消息：**一段 = 一条消息**（2026-11-19 定稿）──────────
// 中间试过"相邻同 role 自动合并"，还为此加过 `独立` 维度（普通段/独立段）。
// **那个维度被砍了** —— 用户问「独立段是干嘛的」，答案是"为了保留合并能力硬造的概念"。
//
// 为什么当初会想合并（实测数据，留着备查）：
// 默认段列表是 `[system(12980), system(158), user]`。若一律合并：
//   合并后 = system 13140 / user 1580（两条），现在 = 三条。
//   ① I3 破（13140 ≠ 12980 + 158 分两条）
//   ② 防全知设计破 —— 场景判断那 158 字并进 13k 里就"消失"了
//
// **正解不是"给每段一个合并开关"，而是根本不合并。**
// 一段 = 一条消息之后：I3 天然成立、场景判断天然单独一条、那个冲突不存在了。
//
// ── 渲染规则（四条，全是量出来的）────────────────────────────────────
//   ① 整行占位符 → 换成它的内容，**这一行前面的换行也丢掉**
//   ② 展开为空 → **整行消失**（连同行内其他文字）
//   ③ 行内占位符 → 直接替换，保留行结构
//   ④ 换行只在「两个普通文字行相邻」时补
//
// ── 第 ① 条为什么是这样（不是设计，是实测）──────────────────────────
// 除 R1 与 D1 外，**所有零件内容都以 `\n\n` 开头**（R2–R5、D2、D-T、D-N、D9、
// D10、D12、D14 都是）。所以"占位符自己带分隔"是它们的固有属性 ——
// 模板再加换行就是三个。
//
// 我在这条上错了两次：v1 无条件加 `\n`（多一个）；v2 只在上一行不吃换行时加
// （身份句与 R2 之间多一个）。第三次才量出"占位符自带分隔"这个事实。
//
// ── 空则整行消失为什么必要 ────────────────────────────────────────────
// 有 7 个零件是**条件性的**：数据为空时现在连包装一起消失（整段空串）。
// 实测：世界书为空时 `零件内容.D2 === ''`，连"世界书/设定(与主AI相同…):"一起没有。
// 若包装搬进模板而数据为空，就会留下一行孤立标签 —— 默认产物变了。
// "空则整行消失"让两者同生共死，I3 因此保住。
//
// 代价（用户要接受的）：想让"空时也保留那句说明"做不到 —— 那一行会连说明一起消失。
