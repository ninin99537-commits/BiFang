// 彼方 · NPC 名字归一守卫 —— 纯逻辑, 不碰平台, 可单独测。
//
// 为什么要有它(用户真机测出来的真问题, 方案 §23 W1):
//   模型会为同一个人输出两个只差一个字的名字, 比如
//     "埃莉": {...}, "杰西": {...}, "艾莉": {...同一个人, 内容一字不差...}
//   而**错名字一旦进了名单, 之后每轮提示词都带着它**(「本聊天已追踪的重要NPC: …、杰西、埃莉」),
//   模型照着输出 —— 等于自己给自己喂毒, 是一条**自激回路**: 错误不会自己消失, 只会越滚越硬。
//
// 2026-11-18 需求方改判(方案 §25): **合并的条件必须是"证据", 不是"相似"。**
//   相似只配换来一行提示, 不配换来一张卡的消失。
//
// 所以判据分两桶:
//
//   【确定 → 自动合并】
//     1. 完全同名(简繁归一后一致)
//     2. 去姓前缀包含(「乔尔·米勒」→「乔尔」、「林淑仪」→「淑仪」, 被包含方 ≥2 字)
//        —— 这条**允许跨轮次**, 因为"名字是另一个的前缀"是包含关系, 不是猜
//     3. **同一回复内**的近名 + 内容高度相似(字段重合度高)
//        —— 正好覆盖用户实测的「埃莉/艾莉 内容一字不差」
//
//   【不确定 → 不合并, 只报告】
//     跨轮次的近名(同长度单字替换, 如已有「艾莉」遇到新的「埃莉」)
//     —— 照常建卡, 但在日志留一行「疑似重复: 艾莉 / 埃莉(未合并, 请手动确认)」
//
// 为什么这条线画在这里: 同长度单字替换这个判据会把「张三/张四」判成同一人
// (两个都是 2 字、距离 1、都不是单字名字)。那是两个真不同的人 —— 误伤比漏判贵得多。
// 而「埃莉/艾莉」之所以能合并, 靠的不是名字像, 是**同一回复内内容一字不差**这个证据。

