/** 归一化: 去首尾空白、去零宽字符、繁转简。**保留中间的分隔符**(·、空格) —— 它们在"去姓"里要用到 */
function 归一(名字: string): string {
    let 结果 = '';
    for (const 字 of String(名字 ?? '').trim()) {
        if (字 === '\u200b' || 字 === '\ufeff')
            continue;
        结果 += 繁简表[字] ?? 字;
    }
    return 结果;
}

/** 编辑距离(Levenshtein), 只用于 ≤1 的快速判定。 */
function 编辑距离(甲: string, 乙: string): number {
    if (甲 === 乙)
        return 0;
    const a = [...甲];
    const b = [...乙];
    if (Math.abs(a.length - b.length) > 1)
        return 2; // 超过 1 就没必要精确算, 调用方只关心 ≤1
    const [短, 长] = a.length <= b.length ? [a, b] : [b, a];
    if (短.length === 长.length) {
        let 差 = 0;
        for (let i = 0; i < 短.length; i++)
            if (短[i] !== 长[i])
                差++;
        return 差;
    }
    let i = 0;
    let j = 0;
    let 跳过 = 0;
    while (i < 短.length && j < 长.length) {
        if (短[i] === 长[j]) {
            i++;
            j++;
            continue;
        }
        if (跳过 > 0)
            return 2;
        跳过++;
        j++;
    }
    return 1;
}

/** 去姓: **只对带分隔符的名字生效**(「乔尔·米勒」→「乔尔」、「乔尔 米勒」→「乔尔」)。
 *
 *  2026-11-18 复查 P1-13 改: 原来对中文三字名也砍首字(「林淑仪」→「淑仪」), 那只是猜 ——
 *  「张三丰」会变成「三丰」, 若真有个叫「三丰」的, 跨轮次就被自动合并掉。
 *  带分隔符的西式名不一样: "·"后面那段就是姓, 去掉是**确定操作**。
 *  猜只配换提示, 不配换一张卡消失。 */
function 去姓(名字: string): string {
    const 归一后 = 归一(名字);
    const 分隔 = 归一后.split(/[·•・.\s]+/).filter(Boolean);
    if (分隔.length > 1)
        return 分隔[0];
    return 归一后;
}

/** 去姓前缀关系(证据级): 一方是另一方的去姓形式, 且被包含方 ≥2 字。
 *  **只认"去姓后等于"**, 不认模糊包含 —— 后者会让「艾莉」被「艾莉丝」吞掉。 */
function 是去姓前缀(甲: string, 乙: string): boolean {
    const a = 归一(甲);
    const b = 归一(乙);
    if (!a || !b || a === b)
        return false;
    const a去姓 = 去姓(a);
    const b去姓 = 去姓(b);
    if (a去姓.length >= 2 && a去姓 === b)
        return true;
    if (b去姓.length >= 2 && b去姓 === a)
        return true;
    return false;
}

/** 两张卡的内容重合度。
 *
 *  **分母是"两边字段数的较大值", 不是交集**(2026-11-18 复查 P1-12 改):
 *  用交集时, 模型给新人写 2 个字段、恰好和旧人这两个字段相同 → 2/2 = 1.0 → 旧人被并掉、卡消失。
 *  那是**静默合并**, 比"多一张卡"危险得多。
 *  改成较大值后: 张三 10 字段 vs 张四 2 字段 → 2/10 = 0.2, 不会合并。 */
export function 内容重合度(甲: Record<string, any>, 乙: Record<string, any>): number {
    const 甲键 = Object.keys(甲).filter(k => 甲[k] !== undefined);
    const 乙键 = Object.keys(乙).filter(k => 乙[k] !== undefined);
    const 分母 = Math.max(甲键.length, 乙键.length);
    if (分母 === 0)
        return 0;
    let 同 = 0;
    for (const k of 甲键) {
        if (!(k in 乙) || 乙[k] === undefined)
            continue;
        if (JSON.stringify(甲[k]) === JSON.stringify(乙[k]))
            同++;
    }
    return 同 / 分母;
}

/** 共有字段数 —— 内容判据的另一个下限(复查 P1-12)。
 *  只有 2 个字段恰好相同时, 即便分母改大了, 2/2 这种小样本也不该被当成"一字不差"。 */
export function 共有字段数(甲: Record<string, any>, 乙: Record<string, any>): number {
    return Object.keys(甲).filter(k => k in 乙 && 甲[k] !== undefined && 乙[k] !== undefined).length;
}

/** 内容重合度达到这个值才算"一字不差"级的证据。用户实测的那个 case 是 100%。 */
const 内容证据线 = 0.8;
/** 共有字段至少这么多个才允许用内容做判据(复查 P1-12: 不足 3 个直接不合并) */
const 内容最少共有字段 = 3;

/** 归一结果: 名字 → 最终采用的名字 */
export type 归一结果 = {
    /** 归一后要用的名字 */
    名: string;
    /** 因为与哪个名字判成同一人而合并; 没合并时为 null */
    合并到: string | null;
    /** 合并的依据(证据名); 没合并时为 null */
    理由: '同名' | '去姓前缀' | '同回复内容一致' | null;
    /** 不确定但疑似重复的名字(只报告, **不合并**)。没怀疑时为 null */
    疑似重复: string | null;
};

/**
 * 把一个新名字归一到"应该用哪个名字"。
 *
 * 合并只走三条**证据**判据, 其余一律只报告:
 *   1. 完全同名(简繁归一后一致)
 *   2. 去姓前缀包含(允许跨轮次)
 *   3. 同一回复内(本轮新名)的近名 + 内容重合度 ≥ 0.8
 *
 * 跨轮次的近名(如已有「艾莉」遇到新的「埃莉」)**不合并**, 只填 `疑似重复`。
 * 理由: 同长度单字替换会把「张三/张四」判成同一人 —— 那是两个真不同的人。
 *
 * @param 新名     模型这轮给出的名字
 * @param 已有名   已有的名字们(名单 + 已有卡键)
 * @param 本轮新名 本轮已经处理过的其它新名字 —— **只有这一桶能做"内容一致"合并**
 * @param 新卡     新名字对应的卡(用于内容判定; 不传就不做内容合并)
 * @param 已有卡   名字 → 卡
 */
export function 归一名(
    新名: string,
    已有名: string[],
    本轮新名: string[] = [],
    新卡?: Record<string, any>,
    已有卡: Record<string, Record<string, any>> = {},
): 归一结果 {
    // 证据 1: 完全同名(含简繁归一后一致) → 直接用已有那个的写法
    for (const 名 of [...已有名, ...本轮新名]) {
        if (归一(名) === 归一(新名))
            return { 名, 合并到: 名 === 新名 ? null : 名, 理由: 名 === 新名 ? null : '同名', 疑似重复: null };
    }
    // 证据 2: 去姓前缀包含 —— 允许跨轮次(这不是猜, 是同一个名字的完整版与简写版)
    for (const 名 of [...已有名, ...本轮新名]) {
        if (是去姓前缀(新名, 名))
            return { 名, 合并到: 名, 理由: '去姓前缀', 疑似重复: null };
    }
    // 证据 3: **同一回复内**的近名 + 内容重合度高
    // 只查本轮新名, 不查已有名单 —— 跨轮次的"像"不构成证据(张三/张四)
    if (新卡) {
        for (const 名 of 本轮新名) {
            if (编辑距离(归一(新名), 归一(名)) > 1)
                continue;
            const 对方卡 = 已有卡[名];
            if (!对方卡)
                continue;
            // 共有字段太少时不做内容判定(复查 P1-12): 2 个字段恰好相同不叫"一字不差"
            if (共有字段数(新卡, 对方卡) < 内容最少共有字段)
                continue;
            const 重合 = 内容重合度(新卡, 对方卡);
            if (重合 >= 内容证据线) {
                console.info(`[彼方] 同一条回复里「${新名}」与「${名}」名字相近且内容重合 ${(重合 * 100).toFixed(0)}%, 判为同一人`);
                return { 名, 合并到: 名, 理由: '同回复内容一致', 疑似重复: null };
            }
        }
    }
    // 不确定: 跨轮次近名 → 只报告, 不合并
    // 单字名字同样不判(否则「甲」/「乙」会被报成疑似重复 —— 那是纯噪音)
    if ([...归一(新名)].length >= 2) {
        for (const 名 of 已有名) {
            if ([...归一(名)].length < 2)
                continue;
            if (编辑距离(归一(新名), 归一(名)) <= 1)
                return { 名: 新名, 合并到: null, 理由: null, 疑似重复: 名 };
        }
    }
    return { 名: 新名, 合并到: null, 理由: null, 疑似重复: null };
}

/** 面板/日志用的疑似重复提示(没有就不调) */
export function 疑似重复提示(新名: string, 疑似: string): string {
    return `疑似重复：${疑似} / ${新名}（未合并，请手动确认）`;
}
