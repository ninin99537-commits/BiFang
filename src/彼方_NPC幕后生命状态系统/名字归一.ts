/** 归一化: 去首尾空白、去零宽字符、繁转简。**保留中间的分隔符**(·、空格) —— 它们在"去姓包含"里要用到 */
function 归一(名字: string): string {
    let 结果 = '';
    for (const 字 of String(名字 ?? '').trim()) {
        if (字 === '\u200b' || 字 === '\ufeff')
            continue;
        结果 += 繁简表[字] ?? 字;
    }
    return 结果;
}

/** 编辑距离(Levenshtein), 只用于 ≤1 的快速判定。 */
function 编辑距离(甲: string, 乙: string): number {
    if (甲 === 乙)
        return 0;
    const a = [...甲];
    const b = [...乙];
    if (Math.abs(a.length - b.length) > 1)
        return 2; // 超过 1 就没必要精确算, 调用方只关心 ≤1
    // 短的在前, 便于下面统一处理
    const [短, 长] = a.length <= b.length ? [a, b] : [b, a];
    if (短.length === 长.length) {
        let 差 = 0;
        for (let i = 0; i < 短.length; i++)
            if (短[i] !== 长[i])
                差++;
        return 差;
    }
    // 长度差 1: 允许"长的多一个字"(增/删)
    let i = 0;
    let j = 0;
    let 跳过 = 0;
    while (i < 短.length && j < 长.length) {
        if (短[i] === 长[j]) {
            i++;
            j++;
            continue;
        }
        if (跳过 > 0)
            return 2;
        跳过++;
        j++;
    }
    return 1;
}

/** 去掉姓氏: 「林淑仪」→「淑仪」、「乔尔·米勒」→「乔尔」(取第一个分隔符之前)、「艾莉」→「艾莉」(两字不去) */
function 去姓(名字: string): string {
    const 归一后 = 归一(名字);
    // 带分隔符的(音译名/西式名): 取第一段
    const 分隔 = 归一后.split(/[·•.\s]+/).filter(Boolean);
    if (分隔.length > 1)
        return 分隔[0];
    // 中文三字及以上: 去掉第一个字(姓)
    const 字们 = [...归一后];
    if (字们.length >= 3)
        return 字们.slice(1).join('');
    return 归一后;
}

/**
 * 这两个名字看起来是不是同一个人。
 *
 * 判据(任一成立):
 *   1. 归一后完全相同(简繁/零宽字符差异)
 *   2. 编辑距离 ≤ 1, 且两者长度都 ≥ 2(单字名字不比, 否则"甲/乙"会被判成同一人)
 *   3. 去姓后一方包含另一方, 且被包含的那一方长度 ≥ 2
 *
 * **刻意不做的事**: 不比对内容相似度(那是调用方的事 —— 它才知道两张卡的字段),
 * 不做拼音/谐音匹配(误判成本高于漏判)。
 */
export function 疑似同一人(甲: string, 乙: string): boolean {
    const a = 归一(甲);
    const b = 归一(乙);
    if (!a || !b || a === b)
        return !!a && a === b;
    // 判据 1 已在上面处理
    const a字 = [...a];
    const b字 = [...b];
    // 判据 2: 编辑距离 ≤ 1, 双方都 ≥ 2 字
    if (a字.length >= 2 && b字.length >= 2 && 编辑距离(a, b) <= 1)
        return true;
    // 判据 3: 去姓后包含
    const a去姓 = 去姓(a);
    const b去姓 = 去姓(b);
    if (a去姓.length >= 2 && b去姓.length >= 2) {
        if (a去姓 === b去姓)
            return true;
        if (a去姓.includes(b去姓) || b去姓.includes(a去姓))
            return true;
    }
    // 一方是另一方的"去姓形式"(「林淑仪」vs「淑仪」)
    if (a去姓.length >= 2 && a去姓 === b)
        return true;
    if (b去姓.length >= 2 && b去姓 === a)
        return true;
    return false;
}

/** 两张卡的内容相似度: 只看**两边都有的字段**里值相同的比例。
 *  为什么需要它: 光靠名字近似不够 —— "乔尔"和"乔"可能是两个人。
 *  内容一字不差 + 名字只差一个字 → 几乎可以确定是同一个人被写了两遍。 */
function 内容相似度(甲: Record<string, any>, 乙: Record<string, any>): number {
    const 键 = Object.keys(甲).filter(k => k in 乙 && 甲[k] !== undefined && 乙[k] !== undefined);
    if (键.length === 0)
        return 0;
    let 同 = 0;
    for (const k of 键) {
        const a = 甲[k];
        const b = 乙[k];
        // 台账数组这类结构化值走 JSON 比对
        if (JSON.stringify(a) === JSON.stringify(b))
            同++;
    }
    return 同 / 键.length;
}

/** 归一结果: 名字 → 最终采用的名字(已有名字优先) */
export type 归一结果 = {
    /** 归一后的名字(可能被改写成已有名字) */
    名: string;
    /** 因为与哪个已有名字近似而被合并; 没合并时为 null */
    合并到: string | null;
    /** 为什么判成同一人(写进日志用) */
    理由: '简繁' | '近名' | '去姓' | '内容一致' | null;
};

/**
 * 把一个新名字归一到"应该用哪个名字"。
 *
 * @param 新名     模型这轮给出的名字
 * @param 已有名   已有的名字们(名单 + 已有卡键)。**顺序有意义**: 先命中的胜出
 * @param 本轮新名 本轮已经处理过的其它新名字(同层去重: 一条回复里出现两个近名, 只留先到的那个)
 * @param 新卡     新名字对应的卡(用于"内容一致"判定; 不传就只按名字判)
 * @param 已有卡   名字 → 卡, 用于内容比对
 */
export function 归一名(
    新名: string,
    已有名: string[],
    本轮新名: string[] = [],
    新卡?: Record<string, any>,
    已有卡: Record<string, Record<string, any>> = {},
): 归一结果 {
    // 完全一致(含简繁归一后一致) → 直接用已有那个的写法
    for (const 名 of [...已有名, ...本轮新名]) {
        if (归一(名) === 归一(新名))
            return { 名, 合并到: 名 === 新名 ? null : 名, 理由: 名 === 新名 ? null : '简繁' };
    }
    // 近似判定: 先比已有名字, 再比本轮新名字(先来的赢)
    for (const [池, 标签] of [[已有名, '已有'], [本轮新名, '本轮']] as Array<[string[], string]>) {
        for (const 名 of 池) {
            if (!疑似同一人(新名, 名))
                continue;
            // 名字近似还要看内容: 两边都有卡且内容差异大 → 不当同一人
            // (否则"乔尔"和"乔"这种真的可能被误并)
            if (新卡 && 已有卡[名]) {
                const 相似 = 内容相似度(新卡, 已有卡[名]);
                if (相似 < 0.5) {
                    console.info(`[彼方] 名字近似但内容差异大, 按两个人处理: 「${新名}」vs「${名}」(字段相同率 ${(相似 * 100).toFixed(0)}%, 来自${标签})`);
                    continue;
                }
            }
            const 理由 = 编辑距离(归一(新名), 归一(名)) <= 1 ? '近名' : '去姓';
            return { 名, 合并到: 名, 理由 };
        }
    }
    return { 名: 新名, 合并到: null, 理由: null };
}
