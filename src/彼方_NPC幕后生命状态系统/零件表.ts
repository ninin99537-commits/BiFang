/** 查一个零件属于哪个块。**这是唯一的查法** —— 不要在别处按代号前缀推断。 */
export function 查块(代号: string): 块名 | undefined {
    return 零件表.find(件 => 件.代号 === 代号)?.块;
}

/** 占位符写法: `{{彼方:零件名}}`。
 *
 *  **为什么这个语法安全**(2026-11-19 真机实测 + 代码侧证据):
 *    ① 酒馆旧引擎 `evaluateMacros` 只做"替换已注册的正则", 没匹配就原样 —— 没有兜底清空分支
 *    ② 新引擎 `MacroEngine.#resolveMacro` 显式写着 `Unknown macro: keep macro syntax`
 *    ③ 宏标识符的首字符必须是 ASCII 字母(见 MacroLexer 的 IDENTIFIER_LEXER_PATTERN),
 *       而 `彼方` 是中文 —— 连"被识别成一个宏"都进不去
 *    ④ 全链路只有 substituteParams 一个替换器(generateRaw / JS-Slash-Runner 都走它)
 */
const 占位符正则 = /\{\{\s*彼方\s*[:：]\s*([^{}]+?)\s*\}\}/g;

export interface 占位符命中 {
    /** 完整原文(报错时原样回显给用户) */
    原文: string;
    /** 里面写的零件名(可能拼错) */
    写的名: string;
    /** 命中的零件定义; 拼错时为 undefined */
    零件?: 零件定义;
}

/** 扫一段文本里的全部占位符。**只扫不换** —— 换由调用方按"首处生效"决定。 */
export function 扫占位符(文本: string): 占位符命中[] {
    const 结果: 占位符命中[] = [];
    if (!文本 || !文本.includes('彼方'))
        return 结果;
    for (const 匹配 of 文本.matchAll(占位符正则)) {
        结果.push({
            原文: 匹配[0],
            写的名: 匹配[1],
            零件: 零件表.find(零件 => 零件.名 === 匹配[1]),
        });
    }
    return 结果;
}

/** 拼装清单的一项(V1: 每个零件进了哪、多少字、为什么没进)。 */
export interface 清单项 {
    代号: string;
    名: string;
    状态: '进对话' | '进工具说明' | '被引用' | '已关闭' | '空';
    /** 人看的位置描述: `第 2 条 user` / `工具说明` / `—`
     *  **序号来自实际输出**, 不是拼装意图 —— 见 prompts.ts `生成清单` 的注释。 */
    位置: string;
    /** 实际进了提示词的字数(被关闭/空时为 0) */
    字数: number;
    /** 需要额外说一句的时候。目前两种:
     *   · 被关闭的零件: `被关闭(12840 字)` / `被关闭(空)` ——
     *     **这两者必须分开**: "关掉一个有内容的零件"与"关掉一个本来就空的零件"
     *     后果完全不同, 混成一句就把它们掩盖了(验收 2026-11-19 点名要的)。
     *   · 被忽略的重复引用: `第 2 处重复引用已忽略` */
    备注?: string;
}

/** 清单的一句话摘要(V1 的 console 形态)。
 *
 *  只在**非默认配置**时打 —— 全默认时不产生噪音(V2)。默认 = 没关任何零件、没引用任何零件。 */
export function 清单摘要(清单: 清单项[]): string {
    const 数 = (状态: 清单项['状态']) => 清单.filter(项 => 项.状态 === 状态).length;
    const 合计 = 清单.reduce((和, 项) => 和 + 项.字数, 0);
    const 段 = [`${清单.length} 件`, `${数('进对话')} 在对话`, `${数('进工具说明')} 进表`];
    for (const 状态 of ['被引用', '已关闭', '空'] as const) {
        if (数(状态) > 0)
            段.push(`${数(状态)} ${状态}`);
    }
    段.push(`合计 ${合计} 字`);
    return `[彼方] 拼装: ${段.join(' / ')}`;
}

/** 是否是默认配置(没关、没引用) —— 决定要不要打清单日志。
 *
 *  **"空"不算非默认**: 一个零件现在没内容(世界书没激活 / 台账空 / 轨迹不足)
 *  是**数据状态**, 不是用户的配置动作。把它算成"非默认"会让每次请求都打清单 ——
 *  那正是 V2 要避免的噪音。 */
export function 是默认配置(清单: 清单项[]): boolean {
    return 清单.every(项 => 项.状态 === '进对话' || 项.状态 === '进工具说明' || 项.状态 === '空');
}

