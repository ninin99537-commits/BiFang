// 彼方 · 提示词零件表（自定义提示词 v2）
//
// 目标: 把内置提示词拆成具名零件, 让用户能**引用**(搬到自己写的位置)与**关闭**。
//
// 铁律 C7 / I3: **不引用、不关闭时, 拼装结果与改造前逐字节相同。**
//   这条是"不迁移、不改默认"的底线, 由 tests/bifang-零件化.test.ts 对着
//   fixtures/bifang-prompt-改造前.json 逐字节比对(那份快照是**动代码之前**采的)。
//
// 为什么零件是"切片视图"而不是新的字符串常量:
//   规则正文只存在于 SYSTEM_PROMPT_BODY 一处 —— 这是上一轮花力气保住的结构
//   (见 prompts.ts `SYSTEM_PROMPT_BODY` 上方的注释: "不是断言保证, 是结构上不可能不相等")。
//   零件化若把它退化成"两份文本 + 一条断言", 就是**用纪律换结构**, 而纪律会失效。
//   所以 R2–R5 全部由 SYSTEM_PROMPT_BODY() 切片得到, 不新增任何一个字的规则文本。
//
// 顺序(C9, 2026-11-19 需求方裁定): **零件展开在前, 酒馆宏展开在后。**
//   理由不是偏好, 是递归风险: 用户会在自己世界书里写「本插件支持 {{彼方:世界书}}」——
//   那是**我们会在文档里教他写的**。若宏先展开, 世界书文本先进拼装结果, 再扫零件时
//   就会撞见它自己体内的占位符 → 把世界书注入进世界书自己, 而且递归。
//   反过来则无害: 零件插进来时宏替换器已走完, 世界书里那个字面量原样留着(模型看到的是语法示例)。

/** 承重级(C1b): 分两级, 依据不是"严重程度", 是**用户多久能发现**。
 *  一级 = 关掉当场不是 JSON, 5 秒就知道; 二级 = 输出仍是合法 JSON 但内容是编的, 要过几轮才发现。
 *  二级比一级更该警告 —— 静默坏比响亮坏危险。 */
export type 承重级 = '一级' | '二级';

/** 一个零件属于哪个**块**（C18 的"块"定义见 条目列表.ts 的 `合并成块`）。
 *
 *  ── 为什么它是零件表里的字段，而不是按代号前缀推断 ──
 *  按前缀推断（`R*` → 规则 / `D13` → 场景判断 / 其余 `D*` → 任务）把
 *  "哪些零件存在、属于哪块"这个事实**放在了第二处** ——
 *  而"零件有哪些"在零件表里。同一个事实两处，就是漂移点（§十二 #1）。
 *  更具体的失效场景：把 D13 挪到 R2 前面，按前缀推断仍会说"3 块"，
 *  只有内容位置变了 —— 测试抓不到。改成字段之后，**结构上不存在"一份映射没跟上"**。
 *
 *  ── 三个块的含义 ──
 *    · 规则：身份句 + 规则正文（R1–R7），一条 system 消息
 *    · 场景判断：D13，**单独一条 system**（防全知设计：混进 13k 字正文里，
 *      模型就会把玩家的行动渗进 NPC 的认知）
 *    · 任务：剧情 + 状态卡 + 任务指令（D1–D14 其余），一条 user 消息
 */
export type 块名 = '规则' | '场景判断' | '任务';

export interface 零件定义 {
    /** 内部代号(日志/清单用, 用户不写) */
    代号: string;
    /** 用户写的名字: `{{彼方:世界书}}` */
    名: string;
    /** 一句话说明(面板与清单显示) */
    说明: string;
    /** **属于哪个块** —— 决定它进哪一条消息。唯一来源就是这里。 */
    块: 块名;
    承重?: 承重级;
    /** 关掉时的后果(承重件必须有, 非承重件为空) */
    关掉后果?: string;
    /** 可搬迁: false = 清单里可见, 但只能由**现有开关**控制, 不支持 `{{彼方:X}}` 引用。
     *  只有 R6/R7 是 false —— 它们的文字分散在 4 处(R2/R3/R5 与 userContent 各一段)且
     *  互相指代(自检段引用了"三、受孕判定"), 搬迁会拆散一个概念。见 §2.1 ④ 同一类理由。 */
    可搬迁: boolean;
}

