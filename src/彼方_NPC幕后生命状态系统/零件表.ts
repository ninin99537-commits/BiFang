/** 规则正文的四个切点。找不到时(理论上不会)整段归 R2 —— 降级而不是切坏。 */
const 规则切点 = ['\n核心原则:', '\nNPC 判定:', '\n状态卡字段(', '\n输出要求:'] as const;

/** 把规则正文切成 R2/R3/R4/R5 四段。
 *
 *  切点用 indexOf 而不是写死数字: physio 开关会让前面的生理权威段增减 301 字,
 *  写死位置会在开关一开就切错。
 *
 *  四段拼回去 === 原文, 这是**结构上**成立的(纯切片), 不靠断言。 */
export function 切规则零件(正文: string): { 代号: string; 内容: string }[] {
    const 位置 = 规则切点.map(标 => 正文.indexOf(标));
    const 有效 = 位置.every((位, i) => 位 >= 0 && (i === 0 || 位 > 位置[i - 1]));
    if (!有效) {
        // 降级: 整体当一个零件(找不到切点时不许切坏 —— 宁可不拆)
        return [{ 代号: 'R2', 内容: 正文 }, { 代号: 'R3', 内容: '' }, { 代号: 'R4', 内容: '' }, { 代号: 'R5', 内容: '' }];
    }
    return [
        { 代号: 'R2', 内容: 正文.slice(0, 位置[1]) },
        { 代号: 'R3', 内容: 正文.slice(位置[1], 位置[2]) },
        { 代号: 'R4', 内容: 正文.slice(位置[2], 位置[3]) },
        { 代号: 'R5', 内容: 正文.slice(位置[3]) },
    ];
}
