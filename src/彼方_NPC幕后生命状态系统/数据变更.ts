// 彼方的数据变更入口: 加 NPC / 移除 NPC / 改状态卡 / 改事务状态 / 清空。
//
// 这几段协议(草稿合并 → 最后更新 → 写快照 → 重同步世界书)以前摊在界面里: 几段几乎逐字重复的
// 内联序列, 清空是另一个变体(绕过闸门、写死"不写入"), 闸门口径三处两种, 清空之后界面还要
// 重读存储用启发式判断"到底清干净没有"——持久层的不变式被界面断言。现在收在这里, 界面只消费返回值。
// 「改事务状态」是事务台账上线后加进来的第五个入口: 玩家在详情页按一下就能把某条事务收束成
// 已完成/已作废(顺带写结果), 走的是和「改状态卡」**同一条**通道, 所以改动一样落进楼层快照。
//
// 依赖走 变更环境: 生产环境(建变更环境)连接真实的 快照.ts / worldbook-inject.ts,
// 测试里换成假的就能把四种变更各跑一遍, 不需要酒馆。
