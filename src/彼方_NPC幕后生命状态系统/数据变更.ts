/** 生产环境需要的平台能力: 写快照(变量/楼层) + 重同步世界书 */
type 变更宿主 = Pick<Host, 'vars' | 'chat' | 'worldbook' | 'toast'>;

export type { 彼方数据 };

/** 状态卡里可手动编辑、但不在 CARD_FIELDS 中的字段(由彼方/AI 维护, 玩家可手动覆盖) */
export { 扩展编辑字段 };

export interface 变更环境 {
    /** 写进哪本世界书——变更后要不要重同步世界书、同步到哪本, 只由这一处决定 */
    世界书写入: 世界书写入目标;
    /**
     * 写快照; 返回是否落盘。**返回 false 时不得提交给界面** ——
     * 提交了就等于"界面显示的是没存下来的那份", 玩家下一次刷新才发现丢了。
     * 生产实现(建变更环境)必返回 boolean; 允许 `void` 只是为了用例里"记一笔就算"的假环境。
     */
    保存: (数据: 彼方数据) => boolean | void;
    /** 物理删除所有楼层的快照 + 重置元数据（记录清空层）; 生产环境同时把空数据提交给界面。
     *  允许 `void` 只是为了用例里"不参与判据"的假环境 —— 生产实现必须返回 清空结果。 */
    清空: () => 清空结果 | void;
    /** 重同步世界书条目: 写入=true 表示"照这份数据写成条目", false 表示"删掉条目" */
    同步世界书: (数据: 彼方数据, 写入: boolean) => unknown;
    /** 取当前时间戳(草稿合并写「最后更新」用) */
    现在: () => number;
}

/** 真实环境: 闸门取当前设置, 其余用 快照.ts / worldbook-inject.ts 的实现; 宿主由边界传入 */
export function 建变更环境(host: 变更宿主): 变更环境 {
    const 目标 = getSettings(host).更新.世界书写入;
    return {
        世界书写入: 目标,
        // 保存 = 写快照 + 提交给界面: "界面看到的就是刚落盘的那份"这条不变量只在这里维护。
        // 写不进去就**不提交**: 否则 store 里那份是假的, 而界面已经按它渲染了。
        保存: (数据: 彼方数据) => {
            if (!saveData(host, 数据))
                return false;
            useStateStore().data = 数据;
            return true;
        },
        // 清空 = 物理删除快照 + 把空数据提交给界面(返回给 清空彼方数据 复用)
        清空: () => {
            const 结果 = clearAllData(host);
            if (!结果.成功)
                return 结果;
            useStateStore().data = emptyData();
            return 结果;
        },
        // 手改也要带上生理开关: 否则关着生理时, 改个名字就会把生理六列重新写回世界书条目
        同步世界书: (数据, 写入) => syncNpcStatesWorldbook(host, 数据, 写入 ? 目标 : '关闭', undefined, getSettings(host).更新.生理监测),
        现在: Date.now,
    };
}

/** 变更结果: `数据` 是"界面现在该显示的"那份; 失败时它就是入参原引用(界面据此知道没变) */
export interface 变更返回 {
    /** 改完的数据: 界面直接渲染它, 不再重读存储去猜结果 */
    数据: 彼方数据;
    /** 一句话说明发生了什么(界面拿去做提示) */
    说明: string;
    /** 有值 = **没落盘**; 内容是原因本体(界面据此弹失败, 且不得弹成功) */
    失败?: string;
}

/**
 * 保存并判结果: 成功返回 null, 失败返回给界面看的原因。
 *
 * 只把**显式 false** 当失败: 用例里的假环境是"记一笔就返回"的 void 函数,
 * 它们的语义是"这一步不参与判据", 不该被当成落盘失败。真实现由类型强制返回 boolean。
 */
function 保存并报告(数据: 彼方数据, 环境: 变更环境): string | null {
    return 环境.保存(数据) === false ? '快照没能写进楼层' : null;
}

/** 统一的失败返回: `数据` 必须是原引用 —— 界面靠 `结果.数据 === data` 判断"这次没变" */
function 保存失败(原数据: 彼方数据, 原因: string): 变更返回 {
    return { 数据: 原数据, 说明: `未保存: ${原因}`, 失败: 原因 };
}

/**
 * 草稿 → 卡: 走与 AI 路径**同一个**合并入口(卡合并.合并), 差别只在交给它的几样东西:
 *   - 写入: '整份' —— 表单传回来的是整格内容, 不是增量(所以台账是换而不是并)
 *   - 空值: 玩家清空输入框 = 删掉该字段('删除'); 加 NPC 时没填的格子不该有副作用('跳过')
 *   - 钩子: '仅清理' —— 玩家手改就是在说"这次我裁决", 不拿掷骰 / 生理自洽去覆盖它
 *   - 字段们: 卡上**可编辑的全部**(CARD_FIELDS + 可手编), 而模型只写 CARD_FIELDS
 * 于是「未完成事项」的台账口径、「恋爱标签」的闭合词表、「生活状态」的归一都只有一份实现,
 * 玩家这条路也不会再悄悄少走一步(以前这里只认字符串, 数组草稿会被整段跳过)。
 */
function 套用草稿(数据: 彼方数据, 旧卡: Record<string, any> | undefined, 草稿: Record<string, any>, 空值: 空值语义) {
    return 合并(旧卡, 草稿 ?? {}, { 剧情时间: String(数据?.剧情时间 ?? ''), 写入: '整份', 空值, 钩子: '仅清理' }, undefined, [...CARD_FIELDS, ...扩展编辑字段]);
}

/**
 * 变更后重同步世界书: 空数据 = 删条目; 关着写入时完全不碰世界书(唯一闸门)。
 *
 * 世界书是**派生视图**: 它失败不改变"数据已落盘"这个结论, 所以不并进 `变更返回.失败`
 * (那会让界面把"存好了"报成"没存")。但也不能像以前那样只 `console.error` ——
 * 玩家看到的状态卡与世界书里的条目会静默分叉, 于是这里报一条警告。
 * 文案走 `世界书失败文案`, 与 `报告世界书失败` 同一句: 同一种失败, 玩家读到的话该一样。
 */
function 同步世界书(数据: 彼方数据, 环境: 变更环境) {
    if (环境.世界书写入 === '关闭')
        return;
    const 有NPC = Object.keys(数据.NPC ?? {}).length > 0;
    const 报错 = (error: unknown) => {
        console.error('[彼方] 同步世界书条目失败:', error);
        toastWarning(世界书失败文案(error), '彼方');
    };
    try {
        const 结果: any = 环境.同步世界书(数据, 有NPC);
        if (结果 && typeof 结果.catch === 'function')
            结果.catch(报错);
    }
    catch (error) {
        报错(error);
    }
}

/** 加 NPC: 名单补名 + 用草稿建卡(已有卡则合并) */
export function 加NPC(数据: 彼方数据, 名字: string, 草稿: Record<string, any>, 环境: 变更环境): 变更返回 {
    const 新数据: 彼方数据 = { ...数据, 名单: [...(数据.名单 ?? [])], NPC: { ...(数据.NPC ?? {}) } };
    if (!新数据.名单.includes(名字))
        新数据.名单.push(名字);
    const 卡 = 套用草稿(数据, 新数据.NPC[名字], 草稿, '跳过');
    卡['最后更新'] = 环境.现在();
    新数据.NPC[名字] = 卡;
    const 失败 = 保存并报告(新数据, 环境);
    if (失败)
        return 保存失败(数据, 失败);
    同步世界书(新数据, 环境);
    return { 数据: 新数据, 说明: `已添加 NPC: ${名字}` };
}

/** 移除 NPC: 名单与状态卡一起去掉 */
export function 移除NPC(数据: 彼方数据, 名字: string, 环境: 变更环境): 变更返回 {
    const 新数据: 彼方数据 = {
        ...数据,
        名单: (数据.名单 ?? []).filter(名 => 名 !== 名字),
        NPC: { ...(数据.NPC ?? {}) },
    };
    delete 新数据.NPC[名字];
    const 失败 = 保存并报告(新数据, 环境);
    if (失败)
        return 保存失败(数据, 失败);
    同步世界书(新数据, 环境);
    return { 数据: 新数据, 说明: `已移除 NPC: ${名字}` };
}

/** 改状态卡: 草稿里空的字符串字段 = 删掉该字段(玩家清空输入框即清字段) */
export function 更新状态卡(数据: 彼方数据, 名字: string, 草稿: Record<string, any>, 环境: 变更环境): 变更返回 {
    const 新数据: 彼方数据 = { ...数据, 名单: [...(数据.名单 ?? [])], NPC: { ...(数据.NPC ?? {}) } };
    const 卡 = 套用草稿(数据, 新数据.NPC[名字], 草稿, '删除');
    卡['最后更新'] = 环境.现在();
    新数据.NPC[名字] = 卡;
    const 失败 = 保存并报告(新数据, 环境);
    if (失败)
        return 保存失败(数据, 失败);
    同步世界书(新数据, 环境);
    return { 数据: 新数据, 说明: `已保存 ${名字} 的状态` };
}

/**
 * 改事务状态: 把某个 NPC 台账里的**一条**事务改成 进行中/已完成/已作废, 顺带写入或清掉它的结果。
 *
 * 这是玩家在详情页那排状态按钮背后做的事, 走的是和「改状态卡」同一条通道(改数据 → 最后更新 →
 * 写快照 → 重同步世界书), 所以改动一样落进楼层变量, 后续轮次读到的就是改过的台账;
 * 内容/时间/编号一律不动(内容写下即冻结, 要改内容就作废旧条另开新条, 见 事务台账.ts)。
 *
 * 改不成时(编号不在台账里 / 状态不是三个枚举之一)**一个字段都不动、也不写快照**, 并把原数据对象
 * 原样返回(界面靠 `结果.数据 === 原数据` 就能知道"这次没改", 于是提示而不是假装成功)。
 */
export function 改事务状态(数据: 彼方数据, 名字: string, 编号: string, 新状态: unknown, 结果: string, 环境: 变更环境): 变更返回 {
    const 卡 = 数据?.NPC?.[名字];
    if (!卡)
        return { 数据, 说明: `未改动: 找不到 ${名字} 的状态卡` };
    const 状态 = 合法状态(新状态);
    if (!状态)
        return { 数据, 说明: `未改动: ${String(新状态 ?? '') || '(空)'} 不是合法状态` };
    const 新台账 = 改一条事务(读取台账(卡[台账字段]), 编号, 状态, 结果);
    if (!新台账)
        return { 数据, 说明: `未改动: ${名字} 的台账里没有 ${编号}` };
    const 新数据: 彼方数据 = { ...数据, 名单: [...(数据.名单 ?? [])], NPC: { ...(数据.NPC ?? {}) } };
    const 新卡: 彼方数据['NPC'][string] = { ...卡, [台账字段]: 新台账 };
    新卡['最后更新'] = 环境.现在();
    新数据.NPC[名字] = 新卡;
    const 失败 = 保存并报告(新数据, 环境);
    if (失败)
        return 保存失败(数据, 失败);
    同步世界书(新数据, 环境);
    return { 数据: 新数据, 说明: `${名字} ${编号} → ${状态}` };
}

/**
 * 手动**新增一条事务**(详情页台账区块的"新增")。
 *
 * 走的是与 AI 完全相同的 合并台账(规则1: 载荷没有编号 → 当作新事务, **编号与时间由代码分配**),
 * 所以"内容写下即冻结""编号不复用""进行中不受淘汰"这些口径与 AI 路径逐字一致, 不需要第二套规则。
 * 为什么玩家路径需要它: 面板此前只能改已有条目的状态/结果,**不能新增**——于是"作废旧条 + 另开新条"
 * 这条唯一的改内容路径在人这一侧只通一半(L3 兜底缺的那一半)。
 *
 * 内容与账上某条"去掉空白标点后"相同时, 合并台账 不会新增(它认作命中那条已有事务), 此时**不静默**:
 * 比对长度后返回未改动 + 说明(与 改事务状态 同一套"改不成要说清"的做法)。
 */
export function 新增事务(数据: 彼方数据, 名字: string, 内容: string, 环境: 变更环境): 变更返回 {
    const 卡 = 数据?.NPC?.[名字];
    if (!卡)
        return { 数据, 说明: `未改动: 找不到 ${名字} 的状态卡` };
    const 文本 = String(内容 ?? '').trim();
    if (!文本)
        return { 数据, 说明: '未改动: 内容是空的' };
    const 旧台账 = 读取台账(卡[台账字段]);
    const 新台账 = 合并台账(旧台账, [{ 内容: 文本 }], 数据.剧情时间 ?? '');
    const 新增的 = 新台账.find(事务 => !旧台账.some(旧 => 旧.编号 === 事务.编号));
    if (!新增的)
        return { 数据, 说明: `未新增: 账上已有内容相同的事务(${文本})` };
    const 新数据: 彼方数据 = { ...数据, 名单: [...(数据.名单 ?? [])], NPC: { ...(数据.NPC ?? {}) } };
    const 新卡: 彼方数据['NPC'][string] = { ...卡, [台账字段]: 新台账 };
    新卡['最后更新'] = 环境.现在();
    新数据.NPC[名字] = 新卡;
    const 失败 = 保存并报告(新数据, 环境);
    if (失败)
        return 保存失败(数据, 失败);
    同步世界书(新数据, 环境);
    return { 数据: 新数据, 说明: `${名字} 新增 ${新增的.编号}: ${文本}` };
}

/** 清空所有 NPC 的生理字段(开关关掉后想彻底不要这些数据时用); 不碰其他任何字段 */
export function 清空生理数据(数据: 彼方数据, 环境: 变更环境): 变更返回 {
    const 生理字段 = 字段分组表['生理'] ?? [];
    let 清了几张 = 0;
    const NPC = Object.fromEntries(Object.entries(数据.NPC ?? {}).map(([名, 卡]) => {
        const 副本 = { ...(卡 ?? {}) };
        if (生理字段.some(键 => 键 in 副本))
            清了几张 += 1;
        for (const 键 of 生理字段)
            delete 副本[键];
        return [名, 副本];
    }));
    const 新数据 = { ...数据, NPC };
    const 失败 = 保存并报告(新数据, 环境);
    if (失败)
        return 保存失败(数据, 失败);
    同步世界书(新数据, 环境);
    return { 数据: 新数据, 说明: 清了几张 > 0 ? `已清空 ${清了几张} 个 NPC 的生理数据` : '没有可清的生理数据' };
}

/**
 * 清空: 物理删除所有楼层的快照 + 重置元数据(记录清空层), 开启注入时顺手删掉世界书条目。
 * 这里**不写快照**——清空后应当一份快照都不剩。
 * 失败时返回入参原引用: 界面靠 `结果.数据 === 数据` 判断"没清成", 于是提示而不是假装成功。
 */
export function 清空彼方数据(数据: 彼方数据, 环境: 变更环境): 变更返回 {
    const 清空返回 = 环境.清空();
    // 假环境不返回结果 = 这一步不参与判据; 生产实现必返回 清空结果
    if (清空返回 && !清空返回.成功) {
        const 原因 = 清空返回.失败原因 ?? '清空没生效';
        return { 数据, 说明: `未清空: ${原因}`, 失败: 原因 };
    }
    const 空数据 = emptyData();
    同步世界书(空数据, 环境);
    return { 数据: 空数据, 说明: '彼方: 数据已清空，清空后只分析清空之后的新楼层' };
}

/** 备份封套的版本(与快照的数据版本各自独立: 它只描述"这份文本长什么样") */
const 备份版本 = 1;

/** 导出: 把当前数据序列化成一段可粘贴的文本(设置页"复制"用) */
export function 导出数据(数据: 彼方数据): string {
    return JSON.stringify({
        备份版本,
        导出时间: new Date().toISOString(),
        数据: {
            名单: 数据?.名单 ?? [],
            NPC: 数据?.NPC ?? {},
            卡字段计数: 数据?.卡字段计数 ?? {},
            统计: 数据?.统计 ?? { 更新次数: 0, 最后更新: 0 },
            剧情时间: 数据?.剧情时间 ?? '',
        },
    }, null, 2);
}

/**
 * 导入: 从导出的文本恢复状态。
 * 只认"名单 + NPC"这两个必需项, 其余缺就用缺省 —— 备份是给人手工搬的, 缺字段不该整份作废。
 * 走的是和手动编辑同一条通道(保存 = 写快照 + 提交界面), 写完立刻重同步世界书。
 */
export function 导入数据(文本: string, 数据: 彼方数据, 环境: 变更环境): 变更返回 {
    let 解析: any;
    try {
        解析 = JSON.parse(String(文本 ?? ''));
    }
    catch {
        return { 数据, 说明: '未导入: 不是合法的 JSON', 失败: '不是合法的 JSON' };
    }
    // 兼容"带封套的导出文本"与"直接一份数据"
    const 载荷 = 解析 && typeof 解析 === 'object' && !Array.isArray(解析) && 解析.数据 ? 解析.数据 : 解析;
    if (!载荷 || typeof 载荷 !== 'object' || Array.isArray(载荷))
        return { 数据, 说明: '未导入: 内容不是一份数据', 失败: '内容不是一份数据' };
    if (!Array.isArray(载荷.名单) || !载荷.NPC || typeof 载荷.NPC !== 'object' || Array.isArray(载荷.NPC))
        return { 数据, 说明: '未导入: 缺少「名单」或「NPC」', 失败: '缺少「名单」或「NPC」' };
    const 新数据: 彼方数据 = {
        ...数据,
        名单: 载荷.名单.map((名: unknown) => String(名 ?? '').trim()).filter(Boolean),
        NPC: 载荷.NPC,
        卡字段计数: 载荷.卡字段计数 && typeof 载荷.卡字段计数 === 'object' ? 载荷.卡字段计数 : {},
        统计: 载荷.统计 && typeof 载荷.统计 === 'object' ? 载荷.统计 : { 更新次数: 0, 最后更新: 0 },
        剧情时间: typeof 载荷.剧情时间 === 'string' ? 载荷.剧情时间 : '',
    };
    const 失败 = 保存并报告(新数据, 环境);
    if (失败)
        return 保存失败(数据, 失败);
    同步世界书(新数据, 环境);
    return { 数据: 新数据, 说明: `已导入 ${新数据.名单.length} 个人物` };
}

