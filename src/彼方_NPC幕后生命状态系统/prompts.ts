function buildInjectionPrompt(npcEntries, inSceneNames = []) {
    const formatCard = ([name, card], isInScene) => {
        const parts = [];
        if (card['当前在做'])
            parts.push(`正在: ${card['当前在做']}`);
        if (card['生活状态'])
            parts.push(`生活状态: ${card['生活状态']}`);
        if (card['接下来想做'])
            parts.push(`将要做: ${card['接下来想做']}`);
        if (card['当前目标'])
            parts.push(`目标: ${card['当前目标']}`);
        if (card['未完成事项'])
            parts.push(`未完成: ${card['未完成事项']}`);
        if (card['当前状态'])
            parts.push(`状态: ${card['当前状态']}`);
        if (card['位置'])
            parts.push(`位置: ${card['位置']}`);
        // 在场 NPC 已在场景中, 不显示"可能偶遇"; 仅不在场 NPC 显示
        if (!isInScene && card['可能偶遇'] !== undefined)
            parts.push(`可能偶遇: ${card['可能偶遇'] ? '是' : '否'}`);
        if (card['生理周期'])
            parts.push(`生理周期: ${card['生理周期']}`);
        // 防全知: 孕期 NPC 向主 AI 标注其本人对怀孕的知晓程度, 避免扮演时超前知情
        const isPregnant = String(card['是否怀孕'] ?? '') === 'true' || String(card['是否怀孕']) === '是' || String(card['生理周期'] ?? '').includes('孕期');
        if (isPregnant) {
            const known = String(card['怀孕知晓'] ?? '').trim();
            const knownNote = known === '已确认'
                ? '(该NPC本人已确认自己怀孕)'
                : known === '疑似'
                    ? '(该NPC怀疑自己可能怀孕, 尚未确认——言行最多体现停经疑虑)'
                    : '(该NPC本人尚不知晓自己怀孕——其言行不得体现任何知情表现)';
            parts.push(`是否怀孕: true${knownNote}`);
        }
        else if (card['是否怀孕'] !== undefined) {
            parts.push(`是否怀孕: ${card['是否怀孕']}`);
        }
        if (card['周期影响'])
            parts.push(`周期影响: ${card['周期影响']}`);
        if (card['当前防护'])
            parts.push(`当前防护: ${card['当前防护']}`);
        if (card['近期性行为'])
            parts.push(`近期性行为: ${card['近期性行为']}`);
        if (parts.length === 0)
            parts.push('状态未知');
        return `- ${name}: ${parts.join('; ')}`;
    };
    const inSceneSet = new Set(inSceneNames);
    const inSceneLines = [];
    const offSceneLines = [];
    for (const entry of npcEntries) {
        if (inSceneSet.has(entry[0]))
            inSceneLines.push(formatCard(entry, true));
        else
            offSceneLines.push(formatCard(entry, false));
    }
    const sections = ['[彼方 · 幕后NPC状态]'];
    if (offSceneLines.length > 0) {
        sections.push(`【不在场的NPC】以下NPC此刻不在玩家视野中, 但仍在继续生活。**他们不知道正文中正在发生的任何事**(主角的行踪、当前发生的事件、其他角色的互动等)——当你的剧情中提到他们时, 只让他们表现出自己日常生活该有的样子, 绝不让其言行、想法、反应体现任何他们不可能知道的信息, 除非剧情中明确安排了告知渠道(通讯/传信/他人转述)。除非他们重新登场或剧情需要, 不要在叙述中直接暴露这些幕后信息。`, offSceneLines.join('\n'));
    }
    if (inSceneLines.length > 0) {
        sections.push(`【当前在场的NPC】以下NPC此刻正在玩家所在场景中, 其状态卡供你保持行为与场景一致(不要按幕后推演, 以剧情当前进展为准)。`, inSceneLines.join('\n'));
    }
    return sections.join('\n');
}
