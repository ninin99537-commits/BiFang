/** 详情页里的分组名; "核心" 的三个字段在详情页顶部单独显示, 不跟其它字段排在一起 */
export type 字段分组 = '核心' | '生活' | '内心' | '生理' | '恋爱';

/** 值怎么进卡（见 卡合并.ts 的执行侧）:
 *  - 覆盖: 新值替换旧值（绝大多数）
 *  - 追加: 追加到列表型字段末尾（带 FIFO 与去重），如 近期关键事件
 *  - 按类目: 按类目合并、缺的类目保留旧值，再归一（如 生活状态 的 吃饭/洗漱/睡眠）
 *  - 台账: 交给 事务台账.合并台账（内容写下即冻结、只改状态、封顶）
 *  - 词表: 先过闭合词表归一，再整体替换，如 恋爱标签 */
export type 合并方式 = '覆盖' | '追加' | '按类目' | '台账' | '词表';
/** 值的形态。'台账数组' 的空数组也算合法返回；其余按"非空字符串"判定 */
export type 值形态 = '字符串' | '台账数组';

/** 一个字段的全部描述 */
export type 字段描述 = {
    /** 写进卡里的键名 */
    名: string;
    /** 详情页里的分组 */
    组: 字段分组;
    /** 一句话说明: 字段是什么意思(界面悬停提示用, 也说明它为什么存在) */
    说明: string;
    /** 值怎么进卡（缺省 = 覆盖） */
    合并方式?: 合并方式;
    /** 值的形态（缺省 = 字符串） */
    值形态?: 值形态;
    /** 新建 NPC 建档时这一格是否必须返回。
     *  true = 缺了就告警；'性别相关' = 只对可怀孕角色要求(男性没有这些字段)；false = 不要求 */
    建档必填: boolean | '性别相关';
    /** 已有 NPC 的增量更新里是否每次都必返（缺省 = false，未返回就沿用旧值） */
    每次必返?: boolean;
    /** 由彼方代码维护、不在 CARD_FIELDS 里的字段(玩家可手动覆盖) —— 扩展编辑字段 由它派生 */
    可手编?: boolean;
    /** "添加 NPC"弹窗里是否直接可填 */
    可建档?: boolean;
    /** 弹窗里的输入形态(默认文本域) */
    输入?: 'input' | 'textarea';
    /** 弹窗里的占位提示(缺省用说明) */
    占位?: string;
};
