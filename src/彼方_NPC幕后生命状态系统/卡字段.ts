// 这里管五件事，其它地方不许再抄一遍：
//   - 有哪些字段、什么顺序（CARD_FIELDS，合并/校验/提示词都按这个顺序走）
//   - 每个字段属于哪个分组、一句话是什么（界面详情页与"添加 NPC"弹窗都从这里生成）
