//  同一个问题"这个键该不该出现在 X 里"原来在**四处各答一遍**：
//
//  | 问题 | 原来答在哪 |
//  |---|---|
//  | 该不该进楼层快照？ | `快照.ts` 的 `delete cleaned['…']` 三行 |
