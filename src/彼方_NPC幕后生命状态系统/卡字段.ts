//  | 该不该发给更新 AI？ | `更新输入.ts` 的 `delete card['…']` |
//  | 该不该被当成 NPC 名字？ | `模型请求.ts` 的 `isReservedTopLevelKey` 六个 `===` |
//
//  四处口径**互不一致**，复查查出五处矛盾：
//    · `未完成事项变动` 注释说"不该入库"，但快照清理表里没它 → **每层都存**（半持久化孤儿）
//    · `最后剧情时刻` / `人设参考` 的身份在"禁入库 / 发AI / 保留键"之间来回切
//    · `APPEND_CARD_FIELDS` / `LEGACY_CARD_FIELDS` / `隐藏键` **三份清单没有任何运行时消费者**
//
//  > **同一个事实有 N 份清单，就一定会漂 N-1 次。**
//
// ── 怎么用 ──
//
//  给每个键在这里声明一次角色，然后：
//    · `快照.ts`  → `该进快照的键()` / `不该进快照的键()`
//    · `轨迹.ts`  → `不进轨迹diff的键()`
//    · `更新输入.ts` → `不发模型的键()`
//    · `模型请求.ts` → `顶层保留键()`
//
//  ⚠ **这张表是唯一权威**。新增一个键时只改这里；
//    如果哪个消费方还留着手写清单，判据会红（见 `tests/bifang-卡字段角色.test.ts`）。

/**
 * 一个卡键的全部角色。
 *
 * 缺省语义：**`持久化: true`，其余全 false** —— 即"这是一个普通的、看得见的状态字段"。
 * 只有需要例外时才写，所以绝大多数条目只有 `{ 持久化: true }`。
 */
export type 卡键角色 = {
    /**
     * 进不进楼层快照。
     *
     * `false` = 运行时/临时键：每轮都变、或只是给某一环传递用，存下来只会让快照膨胀。
     */
    持久化: boolean;
    /**
     * 进不进「近期轨迹」的逐轮 diff。
     *
     * `false` = 它每轮都变但**不是"生活轨迹"**（时间戳、数字、运行时载荷）。
     * 硬比会得出"整个字段都变了"的假 diff。
     */
    进轨迹diff: boolean;
    /**
     * 发不发**更新 AI**（`更新输入.ts` 组装给模型的卡副本）。
     *
     * ⚠ 这与 `持久化` **不是同一件事**：
     *   · `最后剧情时刻` 持久化但**不发**（模型没有可靠口径，发了它会自己编）
     *   · `周期长度` 不发（模型不该返回），但 AI **要读**它 —— 那条走提示词里的显式播种
     */
    发模型: boolean;
    /**
     * 是不是**模型输出的顶层元数据键**（不是 NPC 名字）。
     *
     * 这些键出现在模型 JSON 的顶层时，`模型请求.ts` 不该把它们当成 NPC 名去建档。
     */
    顶层保留: boolean;
};

/** 表里不写时的缺省：普通状态字段 */
const 普通状态字段: 卡键角色 = { 持久化: true, 进轨迹diff: true, 发模型: true, 顶层保留: false };

/**
 * 卡键 → 角色。
 *
 * 只列**需要例外**的键（与 `普通状态字段` 不同的）。查表请用下面的函数，不要直接读这张表 ——
 * 函数会补上缺省值，直接读会漏掉所有普通字段。
 *
 * ⚠ **校准原则：忠实于当前行为。**
 *   这张表是从"四处手写清单实际在做什么"倒推出来的，**不是**从"我觉得应该怎样"写的。
 *   唯一的例外是 `未完成事项变动`（下面单独说明）—— 那一处是修 bug，不是改设计。
 */
const 角色例外: Record<string, Partial<卡键角色>> = {
    // ── 运行时 / 临时键：不进快照 ──────────────────────────────────
    /** 现实时间戳，每次更新都变；恢复状态时毫无意义 */
    最后更新: { 持久化: false, 进轨迹diff: false },
    /** 每轮按 NPC 名字动态激活的世界书人设，只是发给模型看的；存下来会让快照膨胀 */
    人设参考: { 持久化: false, 进轨迹diff: false, 顶层保留: true },
    /** 临时的结构化事件载荷（合并时已被消费删除）；防御性清理，绝不入库 */
    恋爱事件: { 持久化: false, 进轨迹diff: false, 顶层保留: true },
    /** 同上：受孕事件由 生理规则 消费后删除 */
    受孕事件: { 持久化: false, 进轨迹diff: false, 顶层保留: true },
    /**
     * 逐轮"这条事务有没有表态"的标记（`应用更新.ts` 写）。
     *
     * ⚠ **这一条是本批唯一的「行为修正」**（复查查出的「半持久化孤儿」）：
     *   `更新输入.ts` 的注释写着"不是状态字段，发给模型只会让它照抄"，并且从发模型的副本里
     *   delete 了它 —— **但快照清理表里没有它**，于是它照样整包进楼层快照，**每层都存**。
     *
     *   现在按它自己的注释定角色：**不进快照**、不进轨迹、不发模型。
     *   这是本批唯一会改变磁盘上快照内容的一处 —— 旧快照里已有的这个键会在下次写入时消失。
     */
    未完成事项变动: { 持久化: false, 进轨迹diff: false, 发模型: false },
    /** 只加在"发给 AI 的副本"上的催更标记，从不写回卡 */
    生活状态待更新: { 持久化: false, 进轨迹diff: false },

    // ── 持久化、但不进轨迹 diff ─────────────────────────────────────
    /**
     * 逐 NPC 的"上次被更新时的剧情时刻"。
     *
     * ⚠ **身份漂移（复查矛盾 1），本批只记录不修**：
     *   `卡合并.ts` 注释写"不是给模型看的字段…模型没有可靠口径"，
     *   而 `更新输入.ts` 却把它写进发更新 AI 的卡副本。
     *   这里**保持当前行为**（`发模型: true`，即它照旧会出现在卡副本里），
     *   因为改成不发会改变模型看到的输入 —— 那是另一件事，要单独一批。
     *
     *   它在轨迹里必须排除：它是代码每轮写的时刻戳，必然"变化"，但那是记账不是生活。
     */
    最后剧情时刻: { 持久化: true, 进轨迹diff: false },

    // ── 顶层元数据键（不是 NPC 名字）──────────────────────────────
    在场NPC: { 持久化: false, 进轨迹diff: false, 顶层保留: true },
    后台互动: { 持久化: false, 进轨迹diff: false, 顶层保留: true },
    移除NPC: { 持久化: false, 进轨迹diff: false, 顶层保留: true },
    剧情时间: { 持久化: false, 进轨迹diff: false, 顶层保留: true },
};

/** 查一个键的完整角色（缺省值已补齐） */
export function 键角色(键: string): 卡键角色 {
    const 例外 = 角色例外[键];
    return 例外 ? { ...普通状态字段, ...例外 } : 普通状态字段;
}

/** 该进楼层快照的键（= 全部普通字段，除运行时键） */
export function 该进快照的键(): string[] {
    return 字段表.map(f => f.名).filter(名 => 键角色(名).持久化);
}

/**
 * 不该进楼层快照的键。
 *
 * 消费方：`快照.ts` 的 `buildSnapshotPayload` —— 它原来写的是三行
 * `delete cleaned['最后更新'/'人设参考'/'恋爱事件']`，现在从这张表派生。
 */
export function 不进快照的键(): string[] {
    return 所有已声明键().filter(名 => !键角色(名).持久化);
}

/**
 * 不进「近期轨迹」diff 的键。
 *
 * 消费方：`轨迹.ts` 的 `运行时键` Set（原来五个字面量）。
 */
export function 不进轨迹的键(): string[] {
    return 所有已声明键().filter(名 => !键角色(名).进轨迹diff);
}

/**
 * 不发**更新 AI** 的键。
 *
 * 消费方：`更新输入.ts`（原来只有一行 `delete card['未完成事项变动']`）。
 *
 * ⚠ **本批只声明了一个 `发模型: false`**（`未完成事项变动`）—— 因为它就是那唯一一处
 *   已被注释写死"不是状态字段"、却仍在发/在存的键。
 *   其余键（`周期长度`、`好感阶段`…）**当前确实会发给更新 AI**，所以它们的 `发模型` 是 true。
 *   要不要收窄是**另一件事**（改了会改变模型看到的输入），不在本批。
 */
export function 不发模型的键(): string[] {
    return 所有已声明键().filter(名 => !键角色(名).发模型);
}

/**
 * 顶层保留键（模型输出的顶层里，这些不是 NPC 名字）。
 *
 * 消费方：`模型请求.ts` 的 `isReservedTopLevelKey`（原来六个 `===`）。
 */
export function 顶层保留键(): string[] {
    return 所有已声明键().filter(名 => 键角色(名).顶层保留);
}

/** 表里声明过的全部键（字段表 + 例外表），去重 */
function 所有已声明键(): string[] {
    return [...new Set([...字段表.map(f => f.名), ...Object.keys(角色例外)])];
}

/** 给判据/诊断看：整张角色表（含缺省值） */
export function 全部角色(): Record<string, 卡键角色> {
    return Object.fromEntries(所有已声明键().map(名 => [名, 键角色(名)]));
}

export { APPEND_CARD_FIELDS, CARD_FIELDS, LEGACY_CARD_FIELDS, 废弃键, 改名字段, 隐藏键 };
