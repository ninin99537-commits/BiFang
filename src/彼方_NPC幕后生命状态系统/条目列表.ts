// 唯一的位置解析入口
// ─────────────────────────────────────────────────────────────

/** 解析后的一段：谁提供内容、什么 role、是否被引用展开 */
export interface 解析段 {
    /** 来源 id（内置=代号，用户条目=条目 id） */
    id: string;
    来源: '内置' | '用户';
    代号?: string;
    role: 'system' | 'user' | 'assistant';
    /** 该段最终要写进消息的文本（用户条目已展开占位符；内置项留空，由调用方按代号取内容） */
    文本: string;
}

export interface 解析输入 {
    /** 完整列表（内置 + 用户），顺序即拼装顺序 */
    列表: 列表项[];
    /** 被关闭的零件代号 */
    关闭零件?: string[];
    /** 内置内容提供者：代号 → 内容。**由调用方注入**，本文件不碰 prompts.ts
     *  （否则会形成循环依赖，而且"内容从哪来"不该由位置解析决定）。 */
    取内置内容: (代号: string) => string;
}

export interface 解析结果 {
    /** 最终的段序。**这就是拼装的唯一依据** —— 调用方按它逐段取文本。 */
    段们: 解析段[];
    /** 被引用到用户条目里的零件代号（它们要从默认位置移除） */
    被引用: Set<string>;
    /** 需要 warn 的问题（配错可指认） */
    问题: string[];
}

/**
 * **把「列表顺序 + 引用表」解析成「最终段序」。这是唯一一处。**
 *
 * 两条输入路径在这里汇合：
 *   · 拖动 → 体现在 `列表` 的顺序里
 *   · 占位符 → 体现在用户条目的 `内容` 里，在这里被扫描并展开
 *
 * 所以"我把世界书拖到最后"与"我在自己的条目里引用世界书"走的是同一段解析：
 * 前者改变 `列表` 顺序，后者产生 `被引用`，两者都作用在同一个 `段们` 上。
 *
 * C4（首处生效）：按**列表顺序**扫，第一次遇到某零件的引用就展开，其余忽略。
 * C5（D13 只许 system）：用户条目的 role 不是 system 时，D13 的引用不展开。
 * C15（引用即搬迁）：被引用的零件从默认位置移除。
 */
export function 解析位置(输入: 解析输入): 解析结果 {
    const 关闭 = new Set<string>(输入.关闭零件 ?? []);
    const 被引用 = new Set<string>();
    const 问题: string[] = [];
    const 段们: 解析段[] = [];

    // ① 先按列表顺序走一遍，处理**用户条目里的占位符**。
    //    为什么先扫再拼(而不是边扫边拼)：C4 的"首处"取决于列表顺序，
    //    而列表顺序是确定的 —— 所以扫出来的结论与"谁先被拼"无关，可以先算。
    //    (与上一版 `扫零件引用` 同一条理由：I8 单一拼装点。)
    const 用户条目 = 输入.列表.filter(项 => 项.来源 === '用户' && 项.启用);
    for (const 项 of 用户条目) {
        const 命中们 = 扫占位符(String(项.内容 ?? ''));
        for (const 命中 of 命中们) {
            if (!命中.零件) {
                问题.push(`占位符 ${命中.原文} 不是已知零件名, 已忽略(它不会出现在提示词里)`);
                continue;
            }
            if (!命中.零件.可搬迁) {
                问题.push(`零件「${命中.零件.名}」不支持引用(它由自己的开关控制), 已忽略`);
                continue;
            }
            if (命中.零件.代号 === 'D13' && 项.role !== 'system') {
                问题.push(`零件「场景判断」只能被 system 身份的条目引用(当前是 ${项.role}), 已忽略`);
                continue;
            }
            if (关闭.has(命中.零件.代号)) {
                被引用.add(命中.零件.代号);
                问题.push(`零件「${命中.零件.名}」已被关闭, 引用处留空`);
                continue;
            }
            if (被引用.has(命中.零件.代号)) {
                问题.push(`零件「${命中.零件.名}」重复引用, 只有第一次生效(这一处已忽略)`);
                continue;
            }
            被引用.add(命中.零件.代号);
        }
    }

    // ② 按列表顺序产出段序。
    for (const 项 of 输入.列表) {
        if (!项.启用)
            continue;
        if (项.来源 === '内置') {
            const 代号 = String(项.代号 ?? '');
            // 被关闭 / 被引用搬走 → 不在默认位置出现
            if (关闭.has(代号) || 被引用.has(代号))
                continue;
            段们.push({ id: 项.id, 来源: '内置', 代号, role: 项.role ?? 零件默认role(代号), 文本: '' });
            continue;
        }
        // 用户条目：展开占位符（首处生效，其余换空串）
        const 原文 = String(项.内容 ?? '');
        const 命中们 = 扫占位符(原文);
        let 文本 = 原文;
        if (命中们.length > 0) {
            const 片段: string[] = [];
            let 游标 = 0;
            let 已用 = new Set<string>();
            for (const 命中 of 命中们) {
                const 位置 = 原文.indexOf(命中.原文, 游标);
                if (位置 < 0)
                    continue;
                片段.push(原文.slice(游标, 位置));
                // 这一处该不该展开：与上面第 ① 步的判据一致（同一套规则）
                const 可展开 = !!命中.零件
                    && 命中.零件.可搬迁
                    && !关闭.has(命中.零件.代号)
                    && !(命中.零件.代号 === 'D13' && 项.role !== 'system')
                    && !已用.has(命中.零件.代号);
                if (可展开) {
                    已用.add(命中.零件!.代号);
                    片段.push(输入.取内置内容(命中.零件!.代号));
                }
                else {
                    // 不展开一律换成空串：原样保留会把 `{{彼方:X}}` 发给模型，比丢掉更糟
                    片段.push('');
                }
                游标 = 位置 + 命中.原文.length;
            }
            片段.push(原文.slice(游标));
            文本 = 片段.join('');
        }
        if (文本.trim().length === 0)
            continue; // 空条目不出现在结果里(与"空段不占位"一致)
        段们.push({ id: 项.id, 来源: '用户', role: 项.role ?? 'system', 文本 });
    }

    return { 段们, 被引用, 问题 };
}

/** C13: 相邻同 role 合并成一条消息。
 *
 *  **分隔符统一 `\n\n`**（需求方 2026-11-19 裁定）：不按 role 用不同分隔符 ——
 *  否则会有人问"为什么 user 合并用换行、assistant 用空行"。
 *
 *  实测依据（`fixtures/bifang-probe-merge.mjs` 量的 5 条路径）：**默认路径下
 *  0 处相邻同 role**，所以这条在默认配置下是空操作 —— 与 C14/I3 不冲突。 */
export function 合并相邻同role(段们: 解析段[]): 解析段[] {
    const 结果: 解析段[] = [];
    for (const 段 of 段们) {
        const 上一条 = 结果[结果.length - 1];
        if (上一条 && 上一条.role === 段.role && 上一条.来源 === '用户' && 段.来源 === '用户') {
            结果[结果.length - 1] = { ...上一条, 文本: `${上一条.文本}\n\n${段.文本}` };
            continue;
        }
        结果.push(段);
    }
    return 结果;
}
