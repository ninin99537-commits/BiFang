/** 一个**内置**条目。内容不可写 —— 这是"内置只读"的结构保证。
 *
 *  ── 为什么用 `内容: () => string` 而不是 `内容: string` ──
 *  字符串字段可以被赋值：`条目.内容 = '我的规则'`。函数字段不能：`条目.内容 = ...` 类型上就错。
 *  所以"内置内容不可改"不是"UI 不给编辑框"，而是**代码里没有那条路**。
 *  （这与 `静默` 搬进不导出类型是同一招：把约束做成类型，而不是做成约定。）
 *
 *  ── 为什么内容要由外部注入，不在这里硬编码 ──
 *  内置内容来自 `SYSTEM_PROMPT_BODY()` 的切片（在 prompts.ts 里），
 *  本文件若去 import prompts.ts 会形成循环依赖（prompts.ts 要 import 本文件）。
 *  所以 `解析位置()` 接收一个 `取内置内容` 回调 —— **但那是"读"，不是"写"**：
 *  回调的签名是 `(代号) => string`，调用方拿不到任何 setter。 */
export interface 内置条目 {
    readonly id: string;
    readonly 来源: '内置';
    readonly 代号: string;
    readonly role: 'system' | 'user' | 'assistant';
    /** 只读派生：调用它得到内容。**没有对应的赋值入口**。 */
    readonly 内容: () => string;
    /** 开关仍然可改（C11：可移动、可开关，只是内容不可改） */
    启用: boolean;
}

/** 一个**用户**条目。内容可写（C12）。 */
export interface 用户条目 {
    id: string;
    来源: '用户';
    role: 'system' | 'user' | 'assistant';
    /** 用户写的正文。可写 —— 与 `内置条目.内容` 的类型刻意不同。
     *  **键名用 `content` 而不是 `内容`**: 它是外部输入(settings/UI)的字段,
     *  与其余配置项(`关闭零件` 之外)保持 ASCII 命名一致; 而 `内置条目.内容` 是内部派生的,
     *  用中文名区分两者 —— 一个是"用户给的字符串", 一个是"代码算出来的函数"。 */
    content: string;
    启用: boolean;
    /** 这一条是**从旧设置迁移来的**（`自定义段` 或 `零件位置`）。
     *  V1 清单用它常驻标「（来自旧设置迁移）」——
     *  只喊一次 warn 等于没有：用户当时没在看，之后想查就查不到。
     *  **不进 `用户条目键`**: 它不是用户能编辑的字段，是迁移留下的印记。 */
    来自旧设置?: boolean;
}

/** 用户条目的**键集** —— 外部输入形状从这一份派生。
 *
 *  ── 为什么要有这个常量（需求方 2026-11-19 裁定）──
 *  外部输入（`更新提示词入参.条目`）允许字段缺省，内部规范（`用户条目`）全部必填。
 *  两者**层不同**，但"层不同"不能成为"形状各写一遍"的理由 ——
 *  加一个字段时两处都要改，那就是两处知识（§十二 #1）。
 *
 *  做法：把"用户条目有哪些键"声明成这一个常量，外部输入用
 *  `Partial<Pick<用户条目, 键>>` 派生。**加字段时只改 `用户条目` 与这个常量**，
 *  外部形状自动跟上；若有人只改一处，`[形状]` 段的键集全等断言会红。
 *
 *  ⚠ 这个常量**不含 `来源`**: 外部输入不该指定来源（它一定是"用户"）。
 *  那是转换时填的，不是用户给的。 */
export const 用户条目键 = ['id', 'role', 'content', '启用'] as const;

/** 外部输入的形状：允许缺省、**不允许 `来源`**。由 `用户条目键` 派生。
 *
 *  为什么用 `Partial<Pick<...>>` 而不是手写一遍：那样加字段时编译器不会提醒改另一处。
 *  这样写之后，`用户条目` 加了字段 → 这里自动多一个可选键；外部传了 `来源` → 类型报错。 */
export type 条目输入 = Partial<Pick<用户条目, (typeof 用户条目键)[number]>>;

/** 把外部输入规范化成内部形状（补默认值）。**唯一一处做这个转换。** */
export function 规范条目(输入: 条目输入, i: number): 用户条目 {
    return {
        id: String(输入.id ?? `用户-${i}`),
        来源: '用户',
        role: 输入.role === 'user' || 输入.role === 'assistant' ? 输入.role : 'system',
        content: String(输入.content ?? ''),
        启用: 输入.启用 !== false,
    };
}

/** 列表项 = 内置 | 用户。**两者类型不同，所以不会互相误用**：
 *  想把用户条目当内置项写回去，`来源` 对不上、`内容` 的类型也对不上。 */
export type 列表项 = 内置条目 | 用户条目;

/** 生成一个新的用户条目 id。
 *
 *  ── 为什么是 uuid，而不是 `Date.now()` 加自增后缀（需求方 2026-11-19 裁定）──
 *  两个原因，第二个是决定性的：
 *    ① 自增序号若是**模块级变量**，页面重挂会归零 → 新条目可能拿到与旧条目相同的 id
 *    ② id 相同的后果不只是"撞" —— `删除条目` 用 `filter(id !== ...)`，
 *       **删一条会把两条都删掉**。那是数据丢失，不是显示问题。
 *
 *  所以不"算同毫秒概率多低"，而是把整类问题消掉：uuid 不依赖时间、不依赖进程内状态、
 *  重挂不归零。浏览器环境原生有（酒馆跑在现代 Chromium/Firefox 上）。
 *
 *  ── 为什么这个函数在这里，而不在 UI 里 ──
 *  它有两处用处：**新增条目**（UI）与 **存量重复 id 去重**（settings 迁移）。
 *  两处各写一遍就是两份实现（规矩 §十二 #1）。放在这里，两边都调它。
 *
 *  @param 已用 可选的"已被占用的 id"集合 —— 去重时用它保证新 id 不再撞
 */
export function 生成条目id(已用?: Set<string>): string {
    const 原生 = (globalThis as any).crypto?.randomUUID;
    for (let 尝试 = 0; 尝试 < 8; 尝试++) {
        const id = typeof 原生 === 'function'
            ? `用户-${原生.call((globalThis as any).crypto)}`
            // 兜底: 时间戳 + 两段随机。极老浏览器没有 randomUUID 时走这条。
            : `用户-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}-${Math.random().toString(36).slice(2, 10)}`;
        if (!已用 || !已用.has(id))
            return id;
    }
    // 连撞 8 次（uuid 下不可能；兜底分支理论上也可能）—— 用时间戳兜到底
    return `用户-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
}

/** 存量条目的**重复 id 去重**（2026-11-19）。
 *
 *  ── 为什么必须做，不能"只防新增" ──
 *  旧版 id 是 `用户-<时间戳>-<模块级自增>`，而那个自增变量在页面重挂时归零，
 *  所以**存量数据里可能已经存在两条同 id 的条目**。
 *  而 `删除条目` 用 `filter(id !== ...)` —— 两条共用一个 id 时，**删一条会把两条都删掉**。
 *  那不是"显示问题"，是**数据丢失**。用户的数据已经坏了，只是还没删到那一条。
 *
 *  ── 行为 ──
 *  · 保留第一个，其余重新分配（只动重复的那些，正常的不重编号）
 *  · 顺序表里指向被改 id 的项也跟着改；顺序表自身的重复项一并清掉
 *  · **幂等**：没有重复时什么都不做（所以不需要迁移版本号，每次加载跑一遍）
 *
 *  ── 为什么不在这里 warn ──
 *  这个函数是纯的（不改外部状态、不打日志），方便直接测。
 *  调用方（settings 迁移）负责按返回条数打 warn —— C8：静默零降级。
 *
 *  @returns 重新分配的条数（0 = 没有重复）
 */
export function 去重条目id(提示词: any): number {
    if (!提示词 || typeof 提示词 !== 'object' || Array.isArray(提示词))
        return 0;
    const 条目们 = 提示词.条目;
    if (!Array.isArray(条目们))
        return 0;
    const 已见 = new Set<string>();
    const 映射: { 旧: string; 新: string }[] = [];
    for (const 条 of 条目们) {
        if (!条 || typeof 条 !== 'object')
            continue;
        const 原id = String(条.id ?? '');
        if (!原id)
            continue;
        if (!已见.has(原id)) {
            已见.add(原id);
            continue;
        }
        const 新id = 生成条目id(已见);
        已见.add(新id);
        条.id = 新id;
        映射.push({ 旧: 原id, 新: 新id });
    }
    if (映射.length === 0)
        return 0;
    // 顺序表：把指向被改 id 的项换成新 id，并清掉重复项。
    // 注意第一条同 id 的保留原 id —— 所以映射是"用掉一个旧 id，换一个新 id"。
    const 顺序 = 提示词.条目顺序;
    if (Array.isArray(顺序)) {
        const 已用 = new Set<string>();
        提示词.条目顺序 = 顺序
            .map((id: any) => {
            const 串 = String(id ?? '');
            const 可用 = 映射.find(m => m.旧 === 串 && !已用.has(m.新));
            if (!可用)
                return 串;
            已用.add(可用.新);
            return 可用.新;
        })
            .filter((id: string, i: number, 全: string[]) => !!id && 全.indexOf(id) === i);
    }
    return 映射.length;
}

/** 把旧版「按锚点存的自定义段」迁成条目（2026-11-19）。
 *
 *  ── 为什么现在可以自动迁移了（C16 原来说"不迁移"）──
 *  C16 拒绝迁移的理由是: **按序号迁会把某一刻的开关状态固化** ——
 *  同一锚点在不同开关下落在不同序号上，之后用户改开关，他的段就跑偏。
 *  那个理由现在不成立了: 列表有了**块**，5 个锚点正好落在块边界上:
 *
 *      最前        → 规则块之前（列表最前）
 *      主提示词之后 → 规则块之后、场景判断之前
 *      任务之前     → 场景判断之后、任务块之前
 *      任务之后     → 任务块之后
 *      最后        → 全末
 *
 *  按块边界插，就与"当时开了哪些开关"无关 —— 那正是 C16 担心的东西。
 *
 *  ── 幂等 ──
 *  迁完把 `自定义段` 清空（内容已经进了 `条目`）。第二次跑时它已是空数组，
 *  什么都不做。**不清空就不能幂等** —— 那样每次加载都会再插一遍。
 *
 *  ── 用户能认出自己的段 ──
 *  `role` / `content` / `启用` 原样保留，一个字不改；只是多了个 id 与位置。
 *
 *  @returns 迁移的段数（0 = 没有旧段）
 */
export function 迁移旧段(提示词: any): number {
    if (!提示词 || typeof 提示词 !== 'object' || Array.isArray(提示词))
        return 0;
    const 旧段 = 提示词.自定义段;
    const 旧位置 = 提示词.零件位置;
    const 有旧段 = Array.isArray(旧段) && 旧段.length > 0;
    const 有旧位置 = !!旧位置 && typeof 旧位置 === 'object' && Object.keys(旧位置).length > 0;
    if (!有旧段 && !有旧位置)
        return 0;
    const 条目们: any[] = Array.isArray(提示词.条目) ? 提示词.条目 : [];
    // **顺序表为空时要先铺上默认列表** —— 否则"插在 R5 之后"算出来的下标
    // 是在 15 项上的位置，而空数组 splice 到那个下标等于直接追加（第一版就这么错的）。
    const 顺序: string[] = Array.isArray(提示词.条目顺序) && 提示词.条目顺序.length > 0
        ? [...提示词.条目顺序]
        : [...默认列表顺序];
    const 已用 = new Set<string>([
        ...条目们.map((条: any) => String(条?.id ?? '')),
        ...顺序,
    ]);

    /** 锚点 → 插在顺序表的哪个位置。
     *  返回的是**在顺序表里的下标**（不是零件代号）——
     *  因为顺序表可以含用户条目 id，按零件找位置更稳。 */
    const 插入位置 = (锚点: string): number => {
        // 每次现算（顺序表在插入过程中变长）
        const 现序 = 顺序;
        const 找 = (代号: string) => 现序.indexOf(代号);
        switch (锚点) {
            case '最前':
                return 0;
            case '主提示词之后':
                // 规则块之后 = 最后一个 R* 之后
                return 最后一个(现序, 代 => 代.startsWith('R')) + 1;
            case '任务之前':
                // 场景判断之后、任务块之前 = D13 之后（没有 D13 就退到规则块之后）
                return 找('D13') >= 0 ? 找('D13') + 1 : 最后一个(现序, 代 => 代.startsWith('R')) + 1;
            case '任务之后':
                // 任务块之后 = 最后一个数据零件之后
                return 最后一个(现序, 代 => 代.startsWith('D')) + 1;
            case '最后':
                return 现序.length;
            default:
                // 认不出的锚点当「任务之后」（旧版的默认值就是它）
                return 最后一个(现序, 代 => 代.startsWith('D')) + 1;
        }
    };
    /** 顺序表里最后一个满足条件的下标；找不到返回 -1 */
    const 最后一个 = (序: string[], 判: (代: string) => boolean): number => {
        for (let i = 序.length - 1; i >= 0; i--) {
            if (判(序[i]))
                return i;
        }
        return -1;
    };

    // 按锚点表顺序迁（保证同锚点内的相对顺序与原书写顺序一致）
    const 锚点序 = ['最前', '主提示词之后', '任务之前', '任务之后', '最后'];
    let 迁了 = 0;
    for (const 锚点 of 锚点序) {
        for (const 段 of (Array.isArray(旧段) ? 旧段 : [])) {
            if (!段 || typeof 段 !== 'object')
                continue;
            const 段锚点 = String(段.锚点 ?? '任务之后');
            if (段锚点 !== 锚点)
                continue;
            const id = 生成条目id(已用);
            已用.add(id);
            条目们.push({
                id,
                role: 段.role === 'user' || 段.role === 'assistant' ? 段.role : 'system',
                // **内容一个字不改** —— 迁移不是"改写"，是"换个地方存"
                content: String(段.content ?? ''),
                启用: 段.启用 !== false,
                // 保留旧锚点，但不再生效（C16: 字段留着，要还原随时可以）
                锚点,
                // **标记来源**：V1 清单要常驻显示「来自旧设置迁移」。
                // 只喊一次 warn 等于没有 —— 用户当时没在看，之后想查就查不到。
                // 留痕要留在他能回头查的地方。
                来自旧设置: true,
            });
            // 插到块边界上。注意：每次插入后顺序表变长，所以**当场插**再继续。
            const 位 = 插入位置(锚点);
            顺序.splice(位 < 0 ? 顺序.length : 位, 0, id);
            迁了++;
        }
    }
    // ── 旧的「零件位置」也一并迁成条目（2026-11-19）──
    // 那个字段是"表格 + 下拉搬家"那一版的产物，界面已经不写它了。
    // 但旧数据里若有值，它**仍会静默搬动零件**（走 `零件位置转段`）——
    // 那就是第二条搬迁路径，正是 C17 要消掉的东西。
    // 迁成"只含占位符的条目"后，它走的是与拖动/手写占位符**同一条**路。
    // 用 `零件名` 而不是代号（占位符语法认名字）。
    if (有旧位置) {
        for (const [代号, 锚点] of Object.entries(旧位置 as Record<string, string>)) {
            const 零件 = 零件表.find(件 => 件.代号 === 代号);
            if (!零件 || !零件.可搬迁)
                continue;
            const id = 生成条目id(已用);
            已用.add(id);
            条目们.push({
                id,
                role: 'system',
                // 只含一个占位符 —— 与用户手写 `{{彼方:世界书}}` 完全等价
                content: `{{彼方:${零件.名}}}`,
                启用: true,
                // 同上：标出来源，让用户在清单里能查到
                来自旧设置: true,
            });
            const 位 = 插入位置(String(锚点 ?? '任务之后'));
            顺序.splice(位 < 0 ? 顺序.length : 位, 0, id);
            迁了++;
        }
    }
    if (迁了 === 0)
        return 0;
    提示词.条目 = 条目们;
    提示词.条目顺序 = 顺序;
    // **清空旧字段** —— 不清空就不能幂等（每次加载都会再插一遍）。
    // 内容已经原样进了 `条目`，所以这不是删除数据。
    提示词.自定义段 = [];
    提示词.零件位置 = {};
    return 迁了;
}

/** 一个零件在默认列表里的 role。
 *
 *  C18 要求"相邻同 role 合并成一条消息"，所以内置项也要有 role。
 *  内置项的 role 与现在拼装的承载位置一致 —— 这样"默认列表 = 现在的拼装顺序"才是真的(C14)。
 *
 *  ⚠ **实测依据**(2026-11-19，去伪装后量的)：
 *    默认路径 messages = [system(身份句+规则), user(剧情)]
 *    带场景判断    = [system(身份句+规则), system(场景判断), user(剧情)]
 *  所以规则(R1–R7)与场景判断(D13)都是 **system**，数据(D*)是 **user**。
 */
export function 零件默认role(代号: string): 'system' | 'user' | 'assistant' {
    if (代号.startsWith('R') || 代号 === 'D13')
        return 'system';
    return 'user';
}

/** 一个零件属于哪个**块**（C18 的"块"定义见 `合并成块`）。
 *
 *  **实现只做查表** —— 块归属是 `零件表` 里每个零件自带的字段（`零件定义.块`）。
 *  为什么不在这里按代号前缀推断（`R*` → 规则 / `D13` → 场景判断 / 其余 → 任务）：
 *  那会把"某零件属于哪块"这个事实放在第二处，而"零件有哪些"在零件表里 ——
 *  同一个事实两处就是漂移点（§十二 #1）。更具体的失效场景：把 D13 挪到 R2 前面，
 *  按前缀推断仍会说"3 块"，只有内容位置变了，测试抓不到。
 *  改成查表之后，**结构上不存在"一份映射没跟上"**（需求方 2026-11-19 裁定）。
 *
 *  ── 兜底为什么要留痕（C8/V4：静默零降级）──
 *  代号不在零件表里时兜底成"任务"，**不抛错**（抛错会让"零件表与默认顺序不一致"
 *  变成运行时崩溃，代价大于收益 —— 需求方 2026-11-19 认了这个取舍）。
 *  但**静默兜底违反"静默零降级"**：用户不会崩，但我们得查得出来。
 *  所以：兜底 + `console.warn` + 调用方在清单里标「未知代号」。
 *  这与"宁可响亮地失败，不要安静地假装成功"是同一条 —— 只不过这里"响亮"的成本太高，
 *  换成"安静但留痕"。
 */
export function 零件所在块(代号: string): 块名 {
    const 块 = 查块(代号);
    if (!块) {
        // 留痕：这条 warn 是"我们查得出来"的唯一入口，不要删
        console.warn(`[彼方] 零件代号「${代号}」不在零件表里，已按「任务」块兜底（这可能意味着零件表与默认顺序不一致）`);
        return '任务';
    }
    return 块;
}

/** 默认列表顺序 —— **必须等于去伪装后的拼装顺序**(C14)。
 *
 *  改动这个数组 = 改动默认行为 = 破坏 I3。基准是
 *  `fixtures/bifang-prompt-去伪装后.json`（2026-11-19 移除伪装后重采）。
 *
 *  ── 顺序的来历 ──
 *    1. R1 身份句（主 system 开头）
 *    2. R2–R5 规则四段（按原文顺序 —— **R5 在这里，不在最末**）
 *    3. D13 场景判断（独立 system，在规则之后、任务之前）
 *    4. D1–D14 数据（进 user）
 *
 *  ⚠ **R5 的位置是这批最容易搞错的一处**：
 *    伪装还在时，R5 被搬到最末（§29 ② 的裁定）。伪装移除后它**回到 R4 之后** ——
 *    因为它本来就在 SYSTEM_PROMPT_BODY 的末尾，是"规则正文的第四段"。
 *    需求方 2026-11-19 特别提醒过"接进去时确认 R5 的位置对得上新基准"。
 */
export const 默认列表顺序: string[] = [
    'R1', 'R2', 'R3', 'R4', 'R5',
    'D13',
    'D1', 'D2', 'D-T', 'D-N', 'D9', 'D10', 'D11', 'D12', 'D14',
];

/** 由默认顺序造一份内置条目列表（用户条目另加）。
 *
 *  `取内容` 由调用方注入（见 `内置条目` 的注释：避免循环依赖）。
 *  **注意这个函数的返回值里 `内容` 是函数** —— 调用方拿到它也没法赋值。 */
export function 造内置列表(取内容: (代号: string) => string): 内置条目[] {
    return 默认列表顺序.map(代号 => ({
        id: 代号,
        来源: '内置' as const,
        代号,
        role: 零件默认role(代号),
        内容: () => 取内容(代号),
        启用: true,
    }));
}

