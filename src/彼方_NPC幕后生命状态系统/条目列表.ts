// 所以能一起删干净，不留半截。

export function 生成条目id(已用?: Set<string>): string {
    const 原生 = (globalThis as any).crypto?.randomUUID;
    for (let 尝试 = 0; 尝试 < 8; 尝试++) {
        const id = typeof 原生 === 'function'
            ? `用户-${原生.call((globalThis as any).crypto)}`
            // 兜底: 时间戳 + 两段随机。极老浏览器没有 randomUUID 时走这条。
            : `用户-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}-${Math.random().toString(36).slice(2, 10)}`;
        if (!已用 || !已用.has(id))
            return id;
    }
    // 连撞 8 次（uuid 下不可能；兜底分支理论上也可能）—— 用时间戳兜到底
    return `用户-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
}

/** 存量条目的**重复 id 去重**（2026-11-19）。
 *
 *  ── 为什么必须做，不能"只防新增" ──
 *  旧版 id 是 `用户-<时间戳>-<模块级自增>`，而那个自增变量在页面重挂时归零，
 *  所以**存量数据里可能已经存在两条同 id 的条目**。
 *  而 `删除条目` 用 `filter(id !== ...)` —— 两条共用一个 id 时，**删一条会把两条都删掉**。
 *  那不是"显示问题"，是**数据丢失**。用户的数据已经坏了，只是还没删到那一条。
 *
 *  ── 行为 ──
 *  · 保留第一个，其余重新分配（只动重复的那些，正常的不重编号）
 *  · 顺序表里指向被改 id 的项也跟着改；顺序表自身的重复项一并清掉
 *  · **幂等**：没有重复时什么都不做（所以不需要迁移版本号，每次加载跑一遍）
 *
 *  ── 为什么不在这里 warn ──
 *  这个函数是纯的（不改外部状态、不打日志），方便直接测。
 *  调用方（settings 迁移）负责按返回条数打 warn —— C8：静默零降级。
 *
 *  @returns 重新分配的条数（0 = 没有重复）
 */
export function 去重条目id(提示词: any): number {
    if (!提示词 || typeof 提示词 !== 'object' || Array.isArray(提示词))
        return 0;
    const 条目们 = 提示词.条目;
    if (!Array.isArray(条目们))
        return 0;
    const 已见 = new Set<string>();
    const 映射: { 旧: string; 新: string }[] = [];
    for (const 条 of 条目们) {
        if (!条 || typeof 条 !== 'object')
            continue;
        const 原id = String(条.id ?? '');
        if (!原id)
            continue;
        if (!已见.has(原id)) {
            已见.add(原id);
            continue;
        }
        const 新id = 生成条目id(已见);
        已见.add(新id);
        条.id = 新id;
        映射.push({ 旧: 原id, 新: 新id });
    }
    if (映射.length === 0)
        return 0;
    // 顺序表：把指向被改 id 的项换成新 id，并清掉重复项。
    // 注意第一条同 id 的保留原 id —— 所以映射是"用掉一个旧 id，换一个新 id"。
    const 顺序 = 提示词.条目顺序;
    if (Array.isArray(顺序)) {
        const 已用 = new Set<string>();
        提示词.条目顺序 = 顺序
            .map((id: any) => {
            const 串 = String(id ?? '');
            const 可用 = 映射.find(m => m.旧 === 串 && !已用.has(m.新));
            if (!可用)
                return 串;
            已用.add(可用.新);
            return 可用.新;
        })
            .filter((id: string, i: number, 全: string[]) => !!id && 全.indexOf(id) === i);
    }
    return 映射.length;
}

/** 把旧版「按锚点存的自定义段」迁成条目（2026-11-19）。
 *
 *  ── 为什么现在可以自动迁移了（C16 原来说"不迁移"）──
 *  C16 拒绝迁移的理由是: **按序号迁会把某一刻的开关状态固化** ——
 *  同一锚点在不同开关下落在不同序号上，之后用户改开关，他的段就跑偏。
 *  那个理由现在不成立了: 列表有了**块**，5 个锚点正好落在块边界上:
 *
 *      最前        → 规则块之前（列表最前）
 *      主提示词之后 → 规则块之后、场景判断之前
 *      任务之前     → 场景判断之后、任务块之前
 *      任务之后     → 任务块之后
 *      最后        → 全末
 *
 *  按块边界插，就与"当时开了哪些开关"无关 —— 那正是 C16 担心的东西。
 *
 *  ── 幂等 ──
 *  迁完把 `自定义段` 清空（内容已经进了 `条目`）。第二次跑时它已是空数组，
 *  什么都不做。**不清空就不能幂等** —— 那样每次加载都会再插一遍。
 *
 *  ── 用户能认出自己的段 ──
 *  内容、`role`、`启用` 都**尽量原样保留**，但**不是"一个字不改"**（2026-11-19 发现10）：
 *
 *  | 字段 | 实际行为 |
 *  |---|---|
 *  | `content` | 原样保留（`String(段.content ?? '')` —— 非字符串会被转成字符串） |
 *  | `role` | **非法值归一成 `'system'`**（只接受 `user` / `assistant`） |
 *  | `启用` | **归一成布尔**（`段.启用 !== false`） |
 *  | `锚点` | 保留原值，但**不再生效**（没有任何代码读它） |
 *  | `来自旧设置` | **新增** `true` 标记 |
 *
 *  ⚠ 原来这里写的是「`role` / `content` / `启用` 原样保留，一个字不改」——
 *    **那是假的**。用户排查"我的段角色怎么变了"时会被这句话带偏。
 *    **迁移不是"不改"，是"不改内容"**：形状必须归一，否则下游要处理各种脏值。
 *
 *  @returns 迁移的段数（0 = 没有旧段）
 */
export function 迁移旧段(提示词: any): number {
    if (!提示词 || typeof 提示词 !== 'object' || Array.isArray(提示词))
        return 0;
    const 旧段 = 提示词.自定义段;
    const 有旧段 = Array.isArray(旧段) && 旧段.length > 0;
    if (!有旧段)
        return 0;
    const 条目们: any[] = Array.isArray(提示词.条目) ? 提示词.条目 : [];
    const 已用 = new Set<string>(条目们.map((条: any) => String(条?.id ?? '')));

    // ── 2026-11-19：删掉"按锚点插入位置"那套（它是**白算的**）─────────────
    //
    // 原来这里有一个 `插入位置(锚点)` 的 switch：按 5 个锚点算出"该插在顺序表第几位"，
    // 结果写进 `提示词.条目顺序`。实测（`bifang-probe-ordering.mjs`）：
    //
    //   ① 换不同的 `条目顺序` 初始值 → 最终模板**完全相同**
    //   ③ `条目顺序` 故意写成 ['b','a']（与条目数组相反）→ 模板仍按条目数组顺序
    //
    // 原因（时间线）：
    //   t1  迁移旧段()：按锚点算位置 → 写进 条目顺序
    //   t2  条目转模板()：**只读 条目 数组** → 写进 模板      ← 条目顺序 在这里被丢
    //   t3  拼装：只读 模板
    //
    // 所以那套计算在认真做一件不影响任何结果的事。
    //
    // ⚠ **必须记下的事实**：迁移后，旧段是按**数组顺序追加**的，**不按锚点**。
    //   而这件事**删之前就已经如此** —— 这批不改变任何用户可见行为。
    //   留这句话是因为：一句假话留在文档里（"迁移保留了锚点位置"）比留在代码里更难查 ——
    //   代码还能跑给人看，文档只能被相信。
    //
    // 保留下来的：**内容一字不改**、`role` 原样、`启用` 原样、`锚点` 字段留着（要还原随时可以）。
    let 迁了 = 0;
    for (const 段 of (Array.isArray(旧段) ? 旧段 : [])) {
        if (!段 || typeof 段 !== 'object')
            continue;
        const id = 生成条目id(已用);
        已用.add(id);
        条目们.push({
            id,
            role: 段.role === 'user' || 段.role === 'assistant' ? 段.role : 'system',
            // **内容一个字不改** —— 迁移不是"改写"，是"换个地方存"
            content: String(段.content ?? ''),
            启用: 段.启用 !== false,
            // 保留旧锚点字段，但**不再生效**（要还原随时可以 —— 数据留着，只是没人读它）
            锚点: String(段.锚点 ?? '任务之后'),
            来自旧设置: true,
        });
        迁了++;
    }
    if (迁了 === 0)
        return 0;
    提示词.条目 = 条目们;
    // **清空旧字段** —— 不清空就不能幂等（每次加载都会再插一遍）。
    // 内容已经原样进了 `条目`，所以这不是删除数据。
    提示词.自定义段 = [];
    return 迁了;
}

/** 把旧的「条目列表」并进**三段模板**（2026-11-19 模板化）。
 *
 *  ── 为什么必须有这一步 ──
 *  模板化之后"用户改的东西"只有一处 —— 模板。若只把旧段迁成条目、不迁成模板，
 *  老用户会看到"模板是默认的，但我的条目还在生效"。
 *  那**不叫"不会丢数据"**，那叫"他看到的和他发出去的不是一件事"。
 *
 *  ── 幂等 ──
 *  迁完清空 `条目` 与 `条目顺序`，第二次跑什么都不做。
 *
 *  ── 只在还没有模板时做 ──
 *  用户若已经改过模板（`模板` 非空），再把条目拼进去会**盖掉他的编辑**。
 *  那种情况留着他原来的模板，条目保持原样 —— 不迁比迁错好。
 *
 *  ── 内容一字不改 ──
 *  `role` 决定进哪一段（`system` → 系统段，其余 → 用户段），正文原样。
 *  场景判断段**不接收条目**（它是 D13 专用位，防全知设计）。
 *
 *  @returns 并入的条目数（0 = 没有条目 / 已有模板）
 */
export function 条目转模板(提示词: any): number {
    if (!提示词 || typeof 提示词 !== 'object' || Array.isArray(提示词))
        return 0;
    const 条目们 = 提示词.条目;
    if (!Array.isArray(条目们) || 条目们.length === 0)
        return 0;
    // 已有模板 → 不动（迁错比不迁更糟：会盖掉用户手改的东西）
    const 已有 = 提示词.模板;
    if (Array.isArray(已有) && 已有.length > 0)
        return 0;
    const 可迁 = 条目们.filter((条: any) => 条 && typeof 条 === 'object'
        && 条.启用 !== false
        && String(条.content ?? '').trim());
    if (可迁.length === 0) {
        // 全是空的/全禁用 —— 仍然清空，否则每次都白跑一遍
        提示词.条目 = [];
        提示词.条目顺序 = [];
        return 0;
    }
    const 模板 = 由条目生成模板(可迁);
    提示词.模板 = 模板;
    提示词.条目 = [];
    提示词.条目顺序 = [];
    return 可迁.length;
}


