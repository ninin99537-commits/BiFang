/** 解析后的一段：谁提供内容、什么 role。 */
export interface 解析段 {
    /** 来源 id（内置=代号，用户条目=条目 id） */
    id: string;
    来源: '内置' | '用户';
    代号?: string;
    role: 'system' | 'user' | 'assistant';
    /** 该段最终要写进消息的文本。
     *  用户条目：已展开占位符的正文。
     *  内置项：**空串** —— 内容由调用方按 `代号` 现取（本文件不持有内容，只排位置）。 */
    文本: string;
    /** 这一段是**从旧设置迁移来的**（条目侧）。V1 清单要标出来源。 */
    来自旧设置?: boolean;
}

export interface 解析输入 {
    /** 完整列表（内置 + 用户），顺序即拼装顺序 */
    列表: 列表项[];
    /** 被关闭的零件代号 */
    关闭零件?: string[];
    /** **别处已经引用走的零件**（锚点段侧）。这些也要从默认位置移除。
     *
     *  ── 为什么需要这个参数（2026-11-19 补）──
     *  C16 说旧锚点段不迁移，所以它们仍走 `锚点段()` 那条路径，由 `扫零件引用` 扫。
     *  那两侧就可能**各引用同一个零件**。若 `解析位置` 不知道锚点侧已经引用了它，
     *  列表里还会再拼一份 —— 产物里出现两次（I1 破）。
     *
     *  所以调用方把锚点侧的结果传进来，`解析位置` 把它并进"要从默认位置移除"的集合。
     *  **这不是"算两遍"**：锚点侧由 `扫零件引用` 算、列表侧由本函数算，
     *  各扫自己的输入；这里只是把两侧的结论合起来用。 */
    别处已引用?: string[];
}

export interface 解析结果 {
    /** 最终的段序。**这就是拼装的唯一依据** —— 调用方按它逐段取文本。 */
    段们: 解析段[];
    /** 被引用到用户条目里的零件代号（它们要从默认位置移除） */
    被引用: Set<string>;
    /** 被**旧设置迁移来的条目**引用走的零件代号。
     *  V1 清单要给它们标「（来自旧设置迁移）」——
     *  只喊一次 warn 等于没有：用户当时没在看，之后想查就查不到。 */
    来自旧设置: Set<string>;
    /** 需要 warn 的问题（配错可指认） */
    问题: string[];
}

/**
 * **把「列表顺序 + 引用表」解析成「最终段序」。这是唯一一处。**
 *
 * 两条输入路径在这里汇合：
 *   · 拖动 → 体现在 `列表` 的顺序里
 *   · 占位符 → 体现在用户条目的 `内容` 里，在这里被扫描并展开
 *
 * 所以"我把世界书拖到最后"与"我在自己的条目里引用世界书"走的是同一段解析：
 * 前者改变 `列表` 顺序，后者产生 `被引用`，两者都作用在同一个 `段们` 上。
 *
 * C4（首处生效）：按**列表顺序**扫，第一次遇到某零件的引用就展开，其余忽略。
 * C5（D13 只许 system）：用户条目的 role 不是 system 时，D13 的引用不展开。
 * C15（引用即搬迁）：被引用的零件从默认位置移除。
 */
export function 解析位置(输入: 解析输入): 解析结果 {
    const 关闭 = new Set<string>(输入.关闭零件 ?? []);
    // 别处（锚点段侧）已经引用走的零件 —— 它们也要从默认位置移除
    const 别处已引用 = new Set<string>(输入.别处已引用 ?? []);
    const 被引用 = new Set<string>();
    /** 被**旧设置迁移来的条目**引用走的零件（清单要标来源） */
    const 来自旧设置 = new Set<string>();
    const 问题: string[] = [];
    const 段们: 解析段[] = [];

    // ① 先按列表顺序扫一遍，处理**用户条目里的占位符**。
    //    为什么先扫再拼(而不是边扫边拼)：C4 的"首处"取决于列表顺序，
    //    而列表顺序是确定的 —— 所以扫出来的结论与"谁先被拼"无关，可以先算。
    //
    //    **`别处已引用` 里的零件算"已经被用掉"** —— 锚点段先扫（`扫零件引用` 在
    //    本函数之前跑），所以锚点侧拿"首处"。若这里不把它算进 `已用`，
    //    用户条目会再展开一次 → 产物里两份（I1 破）。这条是 `[并集]` 用例抓出来的。
    const 用户项 = 输入.列表.filter(项 => 项.来源 === '用户' && 项.启用);
    for (const 项 of 用户项) {
        if (项.来源 !== '用户')
            continue;
        const 命中们 = 扫占位符(项.content);
        for (const 命中 of 命中们) {
            if (!命中.零件) {
                问题.push(`占位符 ${命中.原文} 不是已知零件名, 已忽略(它不会出现在提示词里)`);
                continue;
            }
            if (!命中.零件.可搬迁) {
                问题.push(`零件「${命中.零件.名}」不支持引用(它由自己的开关控制), 已忽略`);
                continue;
            }
            if (命中.零件.代号 === 'D13' && 项.role !== 'system') {
                问题.push(`零件「场景判断」只能被 system 身份的条目引用(当前是 ${项.role}), 已忽略`);
                continue;
            }
            if (关闭.has(命中.零件.代号)) {
                被引用.add(命中.零件.代号);
                问题.push(`零件「${命中.零件.名}」已被关闭, 引用处留空`);
                continue;
            }
            if (别处已引用.has(命中.零件.代号)) {
                // 锚点段已经引用走了它 —— 这一处不展开，但要留痕（C8）
                问题.push(`零件「${命中.零件.名}」已被锚点段引用, 这一处留空`);
                continue;
            }
            if (被引用.has(命中.零件.代号)) {
                问题.push(`零件「${命中.零件.名}」重复引用, 只有第一次生效(这一处已忽略)`);
                continue;
            }
            被引用.add(命中.零件.代号);
        }
    }

    // ② 按列表顺序产出段序。
    // `已用` **必须在循环外**: C4 的"首处生效"是**跨条目**的 ——
    // 放在条目内部就等于每条目各算一次，同一个零件会在多个条目里各展开一份（I1 破）。
    // （这条是第一版写错的地方，被 [C4] 用例抓出来。）
    const 已用 = new Set<string>();
    for (const 项 of 输入.列表) {
        if (!项.启用)
            continue;
        if (项.来源 === '内置') {
            const 代号 = 项.代号;
            // 被关闭 / 被引用搬走（本侧或锚点侧）→ 不在默认位置出现
            if (关闭.has(代号) || 被引用.has(代号) || 别处已引用.has(代号))
                continue;
            段们.push({ id: 项.id, 来源: '内置', 代号, role: 项.role, 文本: '' });
            continue;
        }
        // 用户条目：展开占位符（首处生效，其余换空串）
        const 原文 = 项.content;
        const 命中们 = 扫占位符(原文);
        let 文本 = 原文;
        if (命中们.length > 0) {
            const 片段: string[] = [];
            let 游标 = 0;
            for (const 命中 of 命中们) {
                const 位置 = 原文.indexOf(命中.原文, 游标);
                if (位置 < 0)
                    continue;
                片段.push(原文.slice(游标, 位置));
                // 这一处该不该展开：与上面第 ① 步的判据一致（同一套规则）
                const 可展开 = !!命中.零件
                    && 命中.零件.可搬迁
                    && !关闭.has(命中.零件.代号)
                    && !别处已引用.has(命中.零件.代号)
                    && !(命中.零件.代号 === 'D13' && 项.role !== 'system')
                    && !已用.has(命中.零件.代号);
                if (可展开) {
                    已用.add(命中.零件!.代号);
                    // 这一条是从旧设置迁移来的 → 它引用的零件在清单里要标出处
                    if (项.来自旧设置)
                        来自旧设置.add(命中.零件!.代号);
                    // 内容从内置项派生 —— 用户条目里拿到的是**展开后的文本**，不是可写的副本
                    const 源 = 输入.列表.find(x => x.来源 === '内置' && x.代号 === 命中.零件!.代号);
                    片段.push(源 && 源.来源 === '内置' ? 源.内容() : '');
                }
                else {
                    // 不展开一律换成空串：原样保留会把 `{{彼方:X}}` 发给模型，比丢掉更糟
                    片段.push('');
                }
                游标 = 位置 + 命中.原文.length;
            }
            片段.push(原文.slice(游标));
            文本 = 片段.join('');
        }
        if (文本.trim().length === 0)
            continue; // 空条目不出现在结果里(与"空段不占位"一致)
        段们.push({ id: 项.id, 来源: '用户', role: 项.role, 文本, ...(项.来自旧设置 ? { 来自旧设置: true } : {}) });
    }

    return { 段们, 被引用, 来自旧设置, 问题 };
}

/** C18: **块**的划分。
 *
 *  ── 块的定义（需求方 2026-11-19 裁定 + 实测修正）──
 *    块 = 一个内置项所在的**语义块**，或一串相邻同 role 的用户条目。
 *
 *  ── 为什么不能按"每个内置项一条"或"role 相同就合" ──
 *  实测（2026-11-19，去伪装后量的）：
 *    · "每个内置项各成一块" → **15 条消息**，而实发是 2 条
 *    · "role 相同就合"      → 无场景时 2 条（对），有场景时 2 条（**错**，实发是 3 条）
 *  第二种错法的原因：R1–R5 与 D13 都是 system，按 role 合会把场景判断并进 13k 字的规则正文 ——
 *  而那是防全知的设计（混进去模型就会把玩家的行动渗进 NPC 的认知）。
 *
 *  所以真实规则是**语义块**：见 `零件所在块()`。
 *
 *  ── 边界模糊处（需求方定了）──
 *  用户条目紧挨着内置项且同 role —— **不合并，自成一条**。
 *  因为内置项是块边界，用户条目只能在自己那一串里合并。
 *
 *  分隔符统一 `\n\n`（不按 role 分，否则会有人问"为什么不一样"）。
 */
export function 合并成块(段们: 解析段[]): 解析段[][] {
    /** 这一段的"块键"：内置项按语义块，用户条目按"用户条目 + role"。
     *  相邻两段块键相同才能并进同一块。
     *
     *  为什么用户条目的键要带 `用户` 前缀：它保证"用户条目永远不会与内置项合" ——
     *  即使 role 与块名碰巧一样（需求方裁定的边界模糊处：不合并，自成一条）。 */
    const 块键 = (段: 解析段): string => 段.来源 === '内置' && 段.代号
        ? `内置:${零件所在块(段.代号)}`
        : `用户:${段.role}`;

    const 块们: 解析段[][] = [];
    let 当前: 解析段[] = [];
    for (const 段 of 段们) {
        const 上一条 = 当前[当前.length - 1];
        if (上一条 && 块键(上一条) === 块键(段)) {
            当前.push(段);
            continue;
        }
        if (当前.length > 0)
            块们.push(当前);
        当前 = [段];
    }
    if (当前.length > 0)
        块们.push(当前);
    return 块们;
}

/** 把一块拼成一条消息的文本。
 *
 *  用户条目之间用 `\n\n` 连接；内置项的文本是空串（内容由调用方按 `代号` 现取），
 *  所以这个函数对内置块返回空串 —— 调用方要按块里的代号自己取内容再拼。
 *
 *  **为什么内置块的内容不在这里拼**：本文件不持有内置内容（它来自 SYSTEM_PROMPT_BODY，
 *  在这里 import 会形成循环依赖）。所以这里只负责"哪些段属于同一块、顺序如何"。 */
export function 块内用户文本(块: 解析段[]): string {
    return 块.filter(段 => 段.来源 === '用户').map(段 => 段.文本).join('\n\n');
}

/** C19 · 原位记号：每个内置项在默认顺序里的序号。
 *
 *  用途：列表 UI 要显示"这是它的原位"，用户拖走后记号留在原处 ——
 *  否则用户会问"我把这条拖回去了，为什么不在原来的位置？"
 *
 *  **关闭的项也要显示原位**（需求方 2026-11-19 裁定）：
 *  原位是"它本来在哪"，与开关无关。用户看到"已关闭 + 原位 #3"，
 *  才知道他关掉的是哪个位置的哪一条；不显示等于关掉之后就失忆了。
 *
 *  为什么用"序号"而不是"当前第几行"：序号是**稳定的**（不随拖动变化），
 *  而"当前第几行"就是它的当前位置 —— 那正是用户想对比的两件事。
 *
 *  返回 `undefined` 表示它不是内置项（用户条目没有"原位"）。
 */
export function 原位序号(代号: string): number | undefined {
    const 位 = 默认列表顺序.indexOf(代号);
    return 位 < 0 ? undefined : 位;
}
