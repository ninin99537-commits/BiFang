// 彼方 · 条目列表（自定义提示词 v3）—— 唯一的**位置解析**入口。
//
// ── 这个文件存在的理由（需求方 2026-11-19 的裁定） ──────────────────
// 「两条路不可怕，两个实现才可怕。」
//
// 条目可以因为两种原因换位置：
//   ① **拖动**：改列表顺序（用户把「世界书」拖到最后）
//   ② **占位符**：用户在自己的条目里写 `{{彼方:世界书}}`（把零件嵌进自己的文字里）
//
// 这两件事语义不同（一个是"换个地方放"，一个是"嵌进我的话里"），所以**都要有**。
// 但它们的"位置解析"必须是同一段代码 —— 否则拖动的顺序与引用的展开各算各的，
// 迟早出现"我把它拖到最后了，但它还是出现在中间"。
//
// 所以：**本文件是唯一一处把「顺序 + 引用」解析成「最终段序」的地方。**
// `buildUpdateMessages` 只调 `解析位置()`，不自己算。
//
// 怎么证明只有一个（交付要给的）：
//   `tests/bifang-条目列表.test.ts` 的 [位置] 段扫源码，断言
//   "把列表顺序与引用合成段序"这个动作只出现在本文件里。
//   并且用变异证明那条扫描抓得住（写一个假的第二实现喂给它）。

import { 零件表, 扫占位符 } from './零件表';

/** 列表里的一项。**内置项与用户条目共处一个列表**，但两者类型不同：
 *  - 内置项的内容由 `取内置内容` 派生（**只读**，结构上没有写入口）
 *  - 用户条目的内容来自 settings（可写）
 *
 *  为什么用"一个列表、两种来源"而不是"两个列表再拼"：用户要在**同一个视觉序列**里
 *  拖来拖去，两个列表拼起来的话，"把内置项拖到用户条目之后"就要跨列表搬 —— 那是
 *  另一种复杂度，而且顺序信息会分成两处存。 */
export interface 列表项 {
    /** 列表项 id。内置项 = 零件代号(R1/D2…)；用户条目 = 用户条目自己的 id。 */
    id: string;
    /** '内置' = 内容由代码派生且只读；'用户' = 内容来自 settings */
    来源: '内置' | '用户';
    /** 内置项对应的零件代号；用户条目没有 */
    代号?: string;
    /** 用户条目的 role。内置项的 role 由零件本身决定(见 零件默认role) */
    role?: 'system' | 'user' | 'assistant';
    /** 用户条目的正文。**内置项没有这个字段** —— 它的内容只能从 取内置内容 派生。
     *  这就是"内置只读"在类型上的表达: 想改内置内容, 这里没有地方可写。 */
    内容?: string;
    /** 关掉 = 不参与拼装(内置项与用户条目都有) */
    启用: boolean;
}

/** 一个零件在默认列表里的 role。
 *
 *  为什么内置项也要有 role：C13 要求"相邻同 role 合并成一条消息"。
 *  内置项的 role 与现在拼装的承载位置一致（规则进 system、剧情进 user…），
 *  这样"默认列表 = 现在的拼装顺序"才是真的（C14）。 */
export function 零件默认role(代号: string): 'system' | 'user' | 'assistant' {
    // 规则类(R1–R7)与场景判断(D13)进 system；数据类进 user
    if (代号.startsWith('R') || 代号 === 'D13')
        return 'system';
    return 'user';
}

/** 默认列表顺序 —— **必须等于现在的拼装顺序**(C14)。
 *
 *  改动这个数组 = 改动默认行为 = 破坏 I3。所以它有一份快照对照
 *  (`fixtures/bifang-prompt-改造前.json`) 钉着。
 *
 *  ── 为什么 R5(输出要求) 排在**最末**(C14 选项 2, 需求方 2026-11-19 裁定) ──
 *  实测两条路径的内容顺序**不同**, 差别只有一处:
 *    伪装(实发):   R1 R2 R3 R4 D13 D1 … D14 **R5**
 *    非伪装(理论): R1 R2 R3 R4 **R5** D13 D1 … D14
 *  伪装把 R5 搬到最末(§29 ②: 承重指令贴末条 user 尾部, 离生成最近)。
 *
 *  选"跟伪装排"的三条理由:
 *    ① **列表存在的意义是让用户看见"实际会发什么"**。排成非伪装顺序, 列表说的与实发
 *       不一样 —— 那这个页面就自相矛盾。
 *    ② "输出要求在最后"一句话能说清(模型对最后的内容记得最牢), 不需要三条解释。
 *    ③ 对齐实发, I3 才对得上。否则"默认列表"其实是"非伪装顺序 + 伪装再搬一次", 两层。
 *
 *  顺序的来历：
 *    1. R1 身份句（主 system 开头）
 *    2. R2–R4 规则三段（按原文顺序）
 *    3. D13 场景判断（独立 system，在规则之后、任务之前）
 *    4. D1–D14 数据（进 user）
 *    5. R5 输出要求（**最末** —— 见上）
 */
export const 默认列表顺序: string[] = [
    'R1', 'R2', 'R3', 'R4',
    'D13',
    'D1', 'D2', 'D-T', 'D-N', 'D9', 'D10', 'D11', 'D12', 'D14',
    'R5',
];

/** 由默认顺序造一份内置项列表（用户条目另加） */
export function 造内置列表(): 列表项[] {
    return 默认列表顺序.map(代号 => {
        const 零件 = 零件表.find(件 => 件.代号 === 代号);
        return {
            id: 代号,
            来源: '内置' as const,
            代号,
            role: 零件默认role(代号),
            启用: true,
            // **刻意不填 内容** —— 内置内容只能派生, 见 列表项 的注释
            ...(零件 ? {} : {}),
        };
    });
}

