// 彼方 · 条目列表（自定义提示词 v3）—— 唯一的**位置解析**入口。
//
// ── 这个文件存在的理由（需求方 2026-11-19 的裁定 C17） ──────────────
// 「两条路不可怕，两个实现才可怕。」
//
// 条目可以因为两种原因换位置：
//   ① **拖动**：改列表顺序（用户把「世界书」拖到最后）
//   ② **占位符**：用户在自己的条目里写 `{{彼方:世界书}}`（把零件嵌进自己的文字里）
//
// 这两件事语义不同（一个是"换个地方放"，一个是"嵌进我的话里"），所以**都要有**。
// 但它们的"位置解析"必须是同一段代码 —— 否则拖动的顺序与引用的展开各算各的，
// 迟早出现"我把它拖到最后了，但它还是出现在中间"。
//
// 所以：**本文件是唯一一处把「顺序 + 引用」解析成「最终段序」的地方。**
// `buildUpdateMessages` 只调 `解析位置()`，不自己算。
//
// 怎么证明只有一个（交付要给的）：
//   `tests/bifang-条目列表.test.ts` 的 [位置] 段扫源码，断言
//   "把列表顺序与引用合成段序"这个动作只出现在本文件里。
//   并且用变异证明那条扫描抓得住（写一个假的第二实现喂给它）。

import { 扫占位符, 查块, type 块名 } from './零件表';
export type { 块名 };

// ─────────────────────────────────────────────────────────────
// C11 · 内置只读：靠类型，不靠 UI
// ─────────────────────────────────────────────────────────────

/** 一个**内置**条目。内容不可写 —— 这是"内置只读"的结构保证。
 *
 *  ── 为什么用 `内容: () => string` 而不是 `内容: string` ──
 *  字符串字段可以被赋值：`条目.内容 = '我的规则'`。函数字段不能：`条目.内容 = ...` 类型上就错。
 *  所以"内置内容不可改"不是"UI 不给编辑框"，而是**代码里没有那条路**。
 *  （这与 `静默` 搬进不导出类型是同一招：把约束做成类型，而不是做成约定。）
 *
 *  ── 为什么内容要由外部注入，不在这里硬编码 ──
 *  内置内容来自 `SYSTEM_PROMPT_BODY()` 的切片（在 prompts.ts 里），
 *  本文件若去 import prompts.ts 会形成循环依赖（prompts.ts 要 import 本文件）。
 *  所以 `解析位置()` 接收一个 `取内置内容` 回调 —— **但那是"读"，不是"写"**：
 *  回调的签名是 `(代号) => string`，调用方拿不到任何 setter。 */
export interface 内置条目 {
    readonly id: string;
    readonly 来源: '内置';
    readonly 代号: string;
    readonly role: 'system' | 'user' | 'assistant';
    /** 只读派生：调用它得到内容。**没有对应的赋值入口**。 */
    readonly 内容: () => string;
    /** 开关仍然可改（C11：可移动、可开关，只是内容不可改） */
    启用: boolean;
}

/** 一个**用户**条目。内容可写（C12）。 */
export interface 用户条目 {
    id: string;
    来源: '用户';
    role: 'system' | 'user' | 'assistant';
    /** 用户写的正文。可写 —— 与 `内置条目.内容` 的类型刻意不同。 */
    内容: string;
    启用: boolean;
}

/** 列表项 = 内置 | 用户。**两者类型不同，所以不会互相误用**：
 *  想把用户条目当内置项写回去，`来源` 对不上、`内容` 的类型也对不上。 */
export type 列表项 = 内置条目 | 用户条目;

/** 一个零件在默认列表里的 role。
 *
 *  C18 要求"相邻同 role 合并成一条消息"，所以内置项也要有 role。
 *  内置项的 role 与现在拼装的承载位置一致 —— 这样"默认列表 = 现在的拼装顺序"才是真的(C14)。
 *
 *  ⚠ **实测依据**(2026-11-19，去伪装后量的)：
 *    默认路径 messages = [system(身份句+规则), user(剧情)]
 *    带场景判断    = [system(身份句+规则), system(场景判断), user(剧情)]
 *  所以规则(R1–R7)与场景判断(D13)都是 **system**，数据(D*)是 **user**。
 */
export function 零件默认role(代号: string): 'system' | 'user' | 'assistant' {
    if (代号.startsWith('R') || 代号 === 'D13')
        return 'system';
    return 'user';
}

/** 一个零件属于哪个**块**（C18 的"块"定义见 `合并成块`）。
 *
 *  **实现只做查表** —— 块归属是 `零件表` 里每个零件自带的字段（`零件定义.块`）。
 *  为什么不在这里按代号前缀推断（`R*` → 规则 / `D13` → 场景判断 / 其余 → 任务）：
 *  那会把"某零件属于哪块"这个事实放在第二处，而"零件有哪些"在零件表里 ——
 *  同一个事实两处就是漂移点（§十二 #1）。更具体的失效场景：把 D13 挪到 R2 前面，
 *  按前缀推断仍会说"3 块"，只有内容位置变了，测试抓不到。
 *  改成查表之后，**结构上不存在"一份映射没跟上"**（需求方 2026-11-19 裁定）。
 *
 *  返回 `undefined` 表示代号不在零件表里（理论上不该发生；调用方按"任务"兜底）。
 */
export function 零件所在块(代号: string): 块名 {
    return 查块(代号) ?? '任务';
}

/** 默认列表顺序 —— **必须等于去伪装后的拼装顺序**(C14)。
 *
 *  改动这个数组 = 改动默认行为 = 破坏 I3。基准是
 *  `fixtures/bifang-prompt-去伪装后.json`（2026-11-19 移除伪装后重采）。
 *
 *  ── 顺序的来历 ──
 *    1. R1 身份句（主 system 开头）
 *    2. R2–R5 规则四段（按原文顺序 —— **R5 在这里，不在最末**）
 *    3. D13 场景判断（独立 system，在规则之后、任务之前）
 *    4. D1–D14 数据（进 user）
 *
 *  ⚠ **R5 的位置是这批最容易搞错的一处**：
 *    伪装还在时，R5 被搬到最末（§29 ② 的裁定）。伪装移除后它**回到 R4 之后** ——
 *    因为它本来就在 SYSTEM_PROMPT_BODY 的末尾，是"规则正文的第四段"。
 *    需求方 2026-11-19 特别提醒过"接进去时确认 R5 的位置对得上新基准"。
 */
export const 默认列表顺序: string[] = [
    'R1', 'R2', 'R3', 'R4', 'R5',
    'D13',
    'D1', 'D2', 'D-T', 'D-N', 'D9', 'D10', 'D11', 'D12', 'D14',
];

/** 由默认顺序造一份内置条目列表（用户条目另加）。
 *
 *  `取内容` 由调用方注入（见 `内置条目` 的注释：避免循环依赖）。
 *  **注意这个函数的返回值里 `内容` 是函数** —— 调用方拿到它也没法赋值。 */
export function 造内置列表(取内容: (代号: string) => string): 内置条目[] {
    return 默认列表顺序.map(代号 => ({
        id: 代号,
        来源: '内置' as const,
        代号,
        role: 零件默认role(代号),
        内容: () => 取内容(代号),
        启用: true,
    }));
}

// ─────────────────────────────────────────────────────────────
// 唯一的位置解析入口
// ─────────────────────────────────────────────────────────────

/** 解析后的一段：谁提供内容、什么 role。 */
export interface 解析段 {
    /** 来源 id（内置=代号，用户条目=条目 id） */
    id: string;
    来源: '内置' | '用户';
    代号?: string;
    role: 'system' | 'user' | 'assistant';
    /** 该段最终要写进消息的文本。
     *  用户条目：已展开占位符的正文。
     *  内置项：**空串** —— 内容由调用方按 `代号` 现取（本文件不持有内容，只排位置）。 */
    文本: string;
}

export interface 解析输入 {
    /** 完整列表（内置 + 用户），顺序即拼装顺序 */
    列表: 列表项[];
    /** 被关闭的零件代号 */
    关闭零件?: string[];
}

export interface 解析结果 {
    /** 最终的段序。**这就是拼装的唯一依据** —— 调用方按它逐段取文本。 */
    段们: 解析段[];
    /** 被引用到用户条目里的零件代号（它们要从默认位置移除） */
    被引用: Set<string>;
    /** 需要 warn 的问题（配错可指认） */
    问题: string[];
}

/**
 * **把「列表顺序 + 引用表」解析成「最终段序」。这是唯一一处。**
 *
 * 两条输入路径在这里汇合：
 *   · 拖动 → 体现在 `列表` 的顺序里
 *   · 占位符 → 体现在用户条目的 `内容` 里，在这里被扫描并展开
 *
 * 所以"我把世界书拖到最后"与"我在自己的条目里引用世界书"走的是同一段解析：
 * 前者改变 `列表` 顺序，后者产生 `被引用`，两者都作用在同一个 `段们` 上。
 *
 * C4（首处生效）：按**列表顺序**扫，第一次遇到某零件的引用就展开，其余忽略。
 * C5（D13 只许 system）：用户条目的 role 不是 system 时，D13 的引用不展开。
 * C15（引用即搬迁）：被引用的零件从默认位置移除。
 */
export function 解析位置(输入: 解析输入): 解析结果 {
    const 关闭 = new Set<string>(输入.关闭零件 ?? []);
    const 被引用 = new Set<string>();
    const 问题: string[] = [];
    const 段们: 解析段[] = [];

    // ① 先按列表顺序扫一遍，处理**用户条目里的占位符**。
    //    为什么先扫再拼(而不是边扫边拼)：C4 的"首处"取决于列表顺序，
    //    而列表顺序是确定的 —— 所以扫出来的结论与"谁先被拼"无关，可以先算。
    const 用户项 = 输入.列表.filter(项 => 项.来源 === '用户' && 项.启用);
    for (const 项 of 用户项) {
        if (项.来源 !== '用户')
            continue;
        const 命中们 = 扫占位符(项.内容);
        for (const 命中 of 命中们) {
            if (!命中.零件) {
                问题.push(`占位符 ${命中.原文} 不是已知零件名, 已忽略(它不会出现在提示词里)`);
                continue;
            }
            if (!命中.零件.可搬迁) {
                问题.push(`零件「${命中.零件.名}」不支持引用(它由自己的开关控制), 已忽略`);
                continue;
            }
            if (命中.零件.代号 === 'D13' && 项.role !== 'system') {
                问题.push(`零件「场景判断」只能被 system 身份的条目引用(当前是 ${项.role}), 已忽略`);
                continue;
            }
            if (关闭.has(命中.零件.代号)) {
                被引用.add(命中.零件.代号);
                问题.push(`零件「${命中.零件.名}」已被关闭, 引用处留空`);
                continue;
            }
            if (被引用.has(命中.零件.代号)) {
                问题.push(`零件「${命中.零件.名}」重复引用, 只有第一次生效(这一处已忽略)`);
                continue;
            }
            被引用.add(命中.零件.代号);
        }
    }

    // ② 按列表顺序产出段序。
    // `已用` **必须在循环外**: C4 的"首处生效"是**跨条目**的 ——
    // 放在条目内部就等于每条目各算一次，同一个零件会在多个条目里各展开一份（I1 破）。
    // （这条是第一版写错的地方，被 [C4] 用例抓出来。）
    const 已用 = new Set<string>();
    for (const 项 of 输入.列表) {
        if (!项.启用)
            continue;
        if (项.来源 === '内置') {
            const 代号 = 项.代号;
            // 被关闭 / 被引用搬走 → 不在默认位置出现
            if (关闭.has(代号) || 被引用.has(代号))
                continue;
            段们.push({ id: 项.id, 来源: '内置', 代号, role: 项.role, 文本: '' });
            continue;
        }
        // 用户条目：展开占位符（首处生效，其余换空串）
        const 原文 = 项.内容;
        const 命中们 = 扫占位符(原文);
        let 文本 = 原文;
        if (命中们.length > 0) {
            const 片段: string[] = [];
            let 游标 = 0;
            for (const 命中 of 命中们) {
                const 位置 = 原文.indexOf(命中.原文, 游标);
                if (位置 < 0)
                    continue;
                片段.push(原文.slice(游标, 位置));
                // 这一处该不该展开：与上面第 ① 步的判据一致（同一套规则）
                const 可展开 = !!命中.零件
                    && 命中.零件.可搬迁
                    && !关闭.has(命中.零件.代号)
                    && !(命中.零件.代号 === 'D13' && 项.role !== 'system')
                    && !已用.has(命中.零件.代号);
                if (可展开) {
                    已用.add(命中.零件!.代号);
                    // 内容从内置项派生 —— 用户条目里拿到的是**展开后的文本**，不是可写的副本
                    const 源 = 输入.列表.find(x => x.来源 === '内置' && x.代号 === 命中.零件!.代号);
                    片段.push(源 && 源.来源 === '内置' ? 源.内容() : '');
                }
                else {
                    // 不展开一律换成空串：原样保留会把 `{{彼方:X}}` 发给模型，比丢掉更糟
                    片段.push('');
                }
                游标 = 位置 + 命中.原文.length;
            }
            片段.push(原文.slice(游标));
            文本 = 片段.join('');
        }
        if (文本.trim().length === 0)
            continue; // 空条目不出现在结果里(与"空段不占位"一致)
        段们.push({ id: 项.id, 来源: '用户', role: 项.role, 文本 });
    }

    return { 段们, 被引用, 问题 };
}

/** C18: **块**的划分。
 *
 *  ── 块的定义（需求方 2026-11-19 裁定 + 实测修正）──
 *    块 = 一个内置项所在的**语义块**，或一串相邻同 role 的用户条目。
 *
 *  ── 为什么不能按"每个内置项一条"或"role 相同就合" ──
 *  实测（2026-11-19，去伪装后量的）：
 *    · "每个内置项各成一块" → **15 条消息**，而实发是 2 条
 *    · "role 相同就合"      → 无场景时 2 条（对），有场景时 2 条（**错**，实发是 3 条）
 *  第二种错法的原因：R1–R5 与 D13 都是 system，按 role 合会把场景判断并进 13k 字的规则正文 ——
 *  而那是防全知的设计（混进去模型就会把玩家的行动渗进 NPC 的认知）。
 *
 *  所以真实规则是**语义块**：见 `零件所在块()`。
 *
 *  ── 边界模糊处（需求方定了）──
 *  用户条目紧挨着内置项且同 role —— **不合并，自成一条**。
 *  因为内置项是块边界，用户条目只能在自己那一串里合并。
 *
 *  分隔符统一 `\n\n`（不按 role 分，否则会有人问"为什么不一样"）。
 */
export function 合并成块(段们: 解析段[]): 解析段[][] {
    /** 这一段的"块键"：内置项按语义块，用户条目按"用户条目 + role"。
     *  相邻两段块键相同才能并进同一块。
     *
     *  为什么用户条目的键要带 `用户` 前缀：它保证"用户条目永远不会与内置项合" ——
     *  即使 role 与块名碰巧一样（需求方裁定的边界模糊处：不合并，自成一条）。 */
    const 块键 = (段: 解析段): string => 段.来源 === '内置' && 段.代号
        ? `内置:${零件所在块(段.代号)}`
        : `用户:${段.role}`;

    const 块们: 解析段[][] = [];
    let 当前: 解析段[] = [];
    for (const 段 of 段们) {
        const 上一条 = 当前[当前.length - 1];
        if (上一条 && 块键(上一条) === 块键(段)) {
            当前.push(段);
            continue;
        }
        if (当前.length > 0)
            块们.push(当前);
        当前 = [段];
    }
    if (当前.length > 0)
        块们.push(当前);
    return 块们;
}

/** 把一块拼成一条消息的文本。
 *
 *  用户条目之间用 `\n\n` 连接；内置项的文本是空串（内容由调用方按 `代号` 现取），
 *  所以这个函数对内置块返回空串 —— 调用方要按块里的代号自己取内容再拼。
 *
 *  **为什么内置块的内容不在这里拼**：本文件不持有内置内容（它来自 SYSTEM_PROMPT_BODY，
 *  在这里 import 会形成循环依赖）。所以这里只负责"哪些段属于同一块、顺序如何"。 */
export function 块内用户文本(块: 解析段[]): string {
    return 块.filter(段 => 段.来源 === '用户').map(段 => 段.文本).join('\n\n');
}

/** C19 · 原位记号：每个内置项在默认顺序里的序号。
 *
 *  用途：列表 UI 要显示"这是它的原位"，用户拖走后记号留在原处 ——
 *  否则用户会问"我把这条拖回去了，为什么不在原来的位置？"
 *
 *  **关闭的项也要显示原位**（需求方 2026-11-19 裁定）：
 *  原位是"它本来在哪"，与开关无关。用户看到"已关闭 + 原位 #3"，
 *  才知道他关掉的是哪个位置的哪一条；不显示等于关掉之后就失忆了。
 *
 *  为什么用"序号"而不是"当前第几行"：序号是**稳定的**（不随拖动变化），
 *  而"当前第几行"就是它的当前位置 —— 那正是用户想对比的两件事。
 *
 *  返回 `undefined` 表示它不是内置项（用户条目没有"原位"）。
 */
export function 原位序号(代号: string): number | undefined {
    const 位 = 默认列表顺序.indexOf(代号);
    return 位 < 0 ? undefined : 位;
}
