// 彼方 · 当前状态（C2：界面所见 == 落盘那份的唯一入口）
// ---------------------------------------------------------------------------
// ── 这个模块解决什么 ──
//
//  「界面当前显示的那份」与「落盘那份」是**两份数据**：
//    · `数据仓.ts` 的 `data`（pinia ref）= 界面渲染的那份
//    · `快照.ts` 的楼层快照        = 刷新后还能读回来的那份
//
//  两者本来该相等，但**没有任何模块拥有这条不变量**：
//
//  | 谁 | 原来做什么 | 对不对 |
//  |---|---|---|
//  | `数据变更.ts` | 保存成功才赋 store | ✅ 对 |
//  | `update.ts` | **失败也赋 store** | ❌ **这是 bug** |
//  | `clearAllData` | 清 + 空 store | ✅ 对 |
//  | `更新输入.ts` / `worldbook-inject.ts` | 直接 `loadData` | 各读各的 |
//  | `数据仓.ts` | `reload` | 又一条路 |
//
//  六条路，三条规则。**配对规则只写在注释里**，没人强制。
//
// ── 接口只有三件事 ──
//
//   读当前()                    -> 状态
//   提交下一份(新状态, 说明, 落盘选项) -> { ok:true } | { ok:false, 原因 }
//   从存储重读()                 -> 状态
//
//  （`host` 是平台句柄，与三家其它模块一致：这一层不自己取宿主。）
//
// ── 失败语义（**接口的一部分，不是实现细节**）──
//
//  **提交失败时，界面显示"上一次落盘成功的那份"，不是这次没存下的那份。**
//
//  为什么：
//    · 显示没存下的那份 → 用户看到"更新成功"的样子，刷新后没了 → **他会以为丢了数据**
//    · 显示上一次落盘的那份 → 界面与存储始终一致，刷新前后一样 → **他只会觉得"这次没更新"**
//
//  两种都让用户不满意，但**只有第二种是可解释的**。
//
//  ⚠ 这意味着 `提交下一份` 失败时**要回滚 store**，而不是留着新数据。
//    回滚的代价是"用户看不到这次算出来的结果"，收益是"他永远不会被一份不存在的状态骗"。
//
// ── 为什么不做"落盘 + 更新界面"的原子化 ──
//
//  做不到。平台没有事务。能做的只有**顺序**：
//    ① 先落盘；② 成功了才更新界面。
//  这样最坏情况是"落盘成功但界面没更新"（下次 `从存储重读` 就对了），
//  而不是"界面更新了但没落盘"（那是**假的**，刷新就消失）。
//
//  > **宁可界面落后于存储，不许界面超前于存储。**
//
// ── 落盘策略由调用方给（模块不替它猜）──
//
//  两种调用方要的落盘语义**本来就不一样**，硬统一会改变行为：
//
//  | 调用方 | 锚点 | 允许覆盖更新快照 | 消费清空层 |
//  |---|---|---|---|
//  | `update.ts`（自动更新） | 本次分析的最后一条楼层 | **false**（锚点之后已有手动保存的快照就不写） | true |
//  | `数据变更.ts`（手动保存） | 最新楼层 | true | false |
//
//  所以 `提交下一份` 收一个 `落盘选项`，默认值 = 手动保存语义。
//  **统一的是"先落盘、成功才更新界面"这条顺序，不是落盘参数。**

import { emptyData, loadData, saveData, writeStateSnapshot, clearAllData } from './快照';
import type { 彼方数据, 清空结果, 快照宿主 } from './快照';
import { useStateStore } from './数据仓';

/** 提交结果 —— 失败时带原因，调用方**必须**把它报给用户（不能静默） */
export type 提交结果 =
    | { ok: true }
    | { ok: false; 原因: string };

/**
 * 落盘选项（决定"这份新状态按哪种语义写进楼层"）。
 *
 * 不传 = 手动保存语义（锚最新楼层、允许覆盖、不清空层）。
 */
export type 落盘选项 = {
    /**
     * 锚点楼层（快照随该楼层存亡）。
     *
     * 不传 = 最新楼层（`saveData` 的手动保存语义）。
     * 自动更新传"本次分析的最后一条楼层"—— 那一轮读过的东西都到那里为止。
     */
    锚点楼层?: number;
    /** 「已分析到哪条楼层」；不传 = 沿用 `新状态.处理到楼层` */
    处理到楼层?: number;
    /**
     * 写入成功后是否把「清空层」清零。
     *
     * 自动更新传 `true`（清空层只在清空后的首次更新生效）；手动保存不传。
     */
    消费清空层?: boolean;
    /**
     * 锚点之后若已有更新的快照（通常来自手动保存），是否允许覆盖写入。
     *
     * 自动更新传 `false`：写进去了也会被读侧按最大层号忽略 → **静默丢弃**，
     * 所以宁可不写，由调用方告诉玩家"这轮结果因手动修改未保存"。
     */
    允许覆盖更新快照?: boolean;
};

/**
 * 读当前状态（界面正在显示的那份）。
 *
 * ⚠ **它读的是 store，不是存储**。要读"盘上那份"用 `从存储重读`。
 *   两者可能不同（上次提交失败时），这正是本模块要暴露的事实。
 */
export function 读当前(): 彼方数据 {
    return useStateStore().data;
}

/**
 * 提交下一份：**先落盘，成功了才更新界面**。
 *
 * @param host   平台句柄
 * @param 新状态 这次算出来/改出来的完整状态
 * @param 说明   失败时给用户看的一句话（说清"这次没存下"，不要说"已保存"）
 * @param 选项   落盘语义；不传 = 手动保存语义（见 `落盘选项`）
 *
 * @returns `{ ok: true }` 或 `{ ok: false, 原因 }`
 *
 * ── 失败时界面拿什么 ──
 *  **回滚成上一次落盘成功的那份**（从存储重读），不是这次没存下的那份。
 *  见文件头的"失败语义"。
 */
export function 提交下一份(
    host: 快照宿主,
    新状态: 彼方数据,
    说明: string,
    选项: 落盘选项 = {},
): 提交结果 {
    const store = useStateStore();

    // ① 先落盘
    let 落盘成功 = false;
    try {
        落盘成功 = 落盘(host, 新状态, 选项);
    }
    catch (error) {
        落盘成功 = false;
        console.error('[彼方] 提交状态时落盘抛错:', error);
    }

    if (!落盘成功) {
        // ② 落盘失败 → **回滚界面**，让它与存储一致
        //
        //  ⚠ 这里是本模块存在的理由。原来的 `update.ts` 在这一支写的是
        //    `stateStore.data = newData` —— **把没存下的那份交给了界面**。
        //    用户看到"已更新 N 个NPC"，刷新后全没了。
        //
        //  回滚而不是保留，是因为"界面超前于存储"必然导致用户被骗一次；
        //  而"界面落后于存储"最多让他觉得"这次没更新"。
        try {
            store.data = loadData(host);
        }
        catch (error) {
            // 连重读都失败 → 退到空状态（至少不是"假的成功"）
            console.error('[彼方] 提交失败后重读也失败, 退到空状态:', error);
            store.data = emptyData();
        }
        return { ok: false, 原因: 说明 };
    }

    // ③ 落盘成功 → 更新界面
    store.data = { ...新状态, 锚点楼层: 新状态.锚点楼层 };
    return { ok: true };
}

/**
 * 按选项决定调哪个落盘函数。
 *
 * ⚠ **只有这一处知道"落盘"有两种语义**。调用方不需要知道 `writeStateSnapshot`
 *   与 `saveData` 的差别，也不需要自己判断"我该不该传哪个参数"。
 */
function 落盘(host: 快照宿主, 新状态: 彼方数据, 选项: 落盘选项): boolean {
    const 用手动保存语义 = 选项.锚点楼层 === undefined;
    if (用手动保存语义)
        return saveData(host, 新状态);

    const 锚点 = 选项.锚点楼层 as number;
    const 处理到 = typeof 选项.处理到楼层 === 'number'
        ? 选项.处理到楼层
        : (typeof 新状态.处理到楼层 === 'number' ? 新状态.处理到楼层 : 0);
    return writeStateSnapshot(
        host,
        新状态,
        锚点,
        处理到,
        !!选项.消费清空层,
        null,
        选项.允许覆盖更新快照 !== false,
    );
}

/**
 * 从存储重读（把界面拉回"盘上那份"）。
 *
 * 用途：
 *  · 切聊天 / 删楼后重新载入
 *  · 提交失败后由调用方主动拉回（`提交下一份` 内部已经做过一次）
 */
export function 从存储重读(host: 快照宿主): 彼方数据 {
    const store = useStateStore();
    const 数据 = loadData(host);
    store.data = 数据;
    return 数据;
}

/**
 * 清空：物理删快照 + 把空状态提交给界面。
 *
 * ⚠ 顺序与 `提交下一份` 同一条原则：**先动存储，成功了才动界面**。
 *   `clearAllData` 内部已经是"先写元数据、再删快照"（2026-11-19 发现8），
 *   这里只负责"成功了才提交给界面"。
 *
 * ── 2026-11-20 C2 补 B：**失败时也要从存储重读**（需求方 #445）──
 *
 *  原来失败时"界面不动"。但 `clearAllData` 的失败**不一定什么都没做**：
 *  它是"先删楼层快照 → 再写元数据"，如果**楼层删掉了、元数据没写进去**，
 *  盘上已经变了（快照没了、索引还是旧的）而界面还是清空前那份 ——
 *  **这正是 C2 要消灭的那种不一致，只是方向反过来。**
 *
 *  所以语义统一成：**盘上是什么，界面就显示什么** —— 哪怕盘上是"半清空"的残状态。
 *  残状态至少是**真实的**；界面显示一份盘上已经不存在的状态，才是骗人。
 */
export function 清空全部(host: 快照宿主): 清空结果 {
    const store = useStateStore();
    const 结果 = clearAllData(host);
    if (!结果.成功) {
        // 失败 → 不假装什么都没发生，把界面拉回**盘上真实的样子**
        try {
            store.data = loadData(host);
        }
        catch (error) {
            // 连重读都失败 → 不动界面（总比清成空白强：至少用户还看得到内容）
            console.error('[彼方] 清空失败后重读也失败, 界面保持不动:', error);
        }
        return 结果;
    }
    store.data = emptyData();
    return 结果;
}
