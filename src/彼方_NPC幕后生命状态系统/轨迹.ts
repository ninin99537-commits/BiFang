// 彼方 · 近期轨迹(批1.5 方案0): 从最近几份楼层快照里 diff 出"谁变过什么", 拼成一段可注入的文本。
//
// 为什么要有它(需求 #310):
//   旧卡告诉模型"现在是什么样", 但**不告诉它"最近怎么变过来的"** —— 模型每轮只看到最近 N 条正文,
//   它不知道"这个 NPC 上一轮在巡逻道, 这一轮在医疗站", 于是容易写回原地、或前后矛盾。
//   轨迹补的就是这一层: **过去几层的变化方向**。
//
// **它是独立注入段, 不是注入表的列**(需求 §五): 轨迹是多行文本, 塞进表格单元格会把一行数据撕成两行。
// (与「未完成事项」踩过的是同一个坑, 见 prompts.ts 里 渲染注入表 那段注释。)
//
// 四个必须挡的口子(需求 §二), 每一条在下面都有一道门, 各自有注释:
//   ① 快照上限 10 / 新聊天只有 1-2 份 → 允许"无轨迹", 返回空串, 不报错
//   ② 中间会缺(删楼层/re-roll/覆盖关闭) → **只比相邻两份都在的配对**, 不假设连续
//   ③ 跨清空层不能比 → 按清空层截断(清空前的快照属于上一段剧情)
//   ④ 字段结构跨版本不一致 → **只对同形状字段做 diff**, 形状不同就跳过并计数
//
// 这个文件**不碰平台**(不读宿主的 chat/vars): 快照由调用方取好传进来, 所以能纯函数测试。
import { CARD_FIELDS, 改名字段 } from './卡字段';
import { 迁移旧字段名 } from './卡合并';

/** 一份快照里"某个人某时的状态"(轨迹只需要 NPC 名 → 卡) */
export interface 轨迹快照 {
    /** 这份快照锚在哪个楼层(用于判断相邻与截断) */
    楼层: number;
    /** NPC 名 → 状态卡 */
    NPC: Record<string, Record<string, any>>;
}

/** 轨迹产出的结果: 文本 + 诊断计数(计数是为了让"为什么没出轨迹"可查, 而不是静默空着) */
export interface 轨迹结果 {
    /** 可直接注入的文本(含表头与数据行, **不含**段外的定位包装); 空串 = 没有轨迹 */
    文本: string;
    /** 实际参与 diff 的快照份数 */
    用了快照数: number;
    /** 因为楼层顺序不成立被跳过的配对(口子②的防御分支) */
    跳过不连续: number;
    /** 被清空层截掉的快照数(口子③) */
    截掉清空层前: number;
    /** 形状不一致被跳过的字段数(口子④) */
    跳过形状不一致: number;
    /** 输出里写了多少条字段变化(降级后) */
    写出条数: number;
    /** 因为超长而降级省略的 NPC 数(降级是"整人减", 不是"断半句"); 0 = 没省略 */
    省略人数?: number;
}

/** 硬上限(需求 §三): 防 prompt 线性膨胀 */
const K层上限 = 6;
/** 一段轨迹里最多写几个 NPC(轨迹是**汇总**后的, 没有"每层几个"这个概念) */
const NPC上限 = 6;
const 每NPC字段上限 = 3;
/** 目标注入量上限(字符)。
 *  对照需求 §三的"0.6–1.2 KB": 中文一字约 3 字节, 1200 字 ≈ 3.6 KB 字节,
 *  但**字符口径**才是"模型要读多少字"的口径 —— 交付里两个数都报。
 *  **超限时降级而不是截断**: 逐档减字段(3→2→1)→ 减人 + 写明省略人数;
 *  任何一级都不切半句话(截断会改语义, 见 规范值 的注释)。 */
const 文本上限 = 1200;

/** 某个字段的值是否"可比" —— 形状不一致的口子④就在这里挡。
 *
 *  为什么需要: `未完成事项` 从旧格式字符串变成了台账数组, `最后更新` 是数字,
 *  旧快照里可能还留着 `人设参考`/`恋爱事件` 这类运行时键。硬比会得出"整个字段都变了"的假 diff。
 *  判据: **只有字符串与字符串才比**; 其它形状(数组/对象/数字/undefined)一律跳过。 */
function 可比字段值(v: unknown): string | null {
    if (typeof v === 'string')
        return v.trim();
    return null;
}

/** 需要排除的运行时键: 它们每轮都变, 但不是"生活轨迹"(口子④的另一半)。
 *  `最后剧情时刻` 也排除: 它是代码每轮写的时刻戳, 必然"变化", 但那是记账不是生活。 */
const 运行时键 = new Set(['最后更新', '人设参考', '恋爱事件', '受孕事件', '最后剧情时刻']);

/** 把一段值规范成单行(只压空白, **不截断**)。
 *
 *  为什么不截断(2026-11-16 真机复盘): 截断会**改语义**, 而且会制造**假的"未变化"结论**。
 *  真实数据里 `位置` 是 `杰克逊社区·西街尽头独立木屋·一楼开放式厨房` 这种长路径,
 *  砍到 24 字后, "厨房"与"壁炉旁"两轮的前半段**完全相同** —— 模型看到的是"她没动",
 *  而事实是她动了。同理 `当前在做` 砍半句会得到"翻挑一…"这种读不出意思的残句。
 *  正确做法见 渲染序列(): 剥离公共前缀, 只显示**差异段** —— 天然短, 且语义完整。 */
function 规范值(v: string): string {
    return v.replace(/\s+/g, ' ').trim();
}

/** 一组值的公共前缀(字符级), 用于"剥离重复部分、只显示差异段" */
function 公共前缀(值们: string[]): string {
    if (值们.length === 0)
        return '';
    let p = 值们[0];
    for (let k = 1; k < 值们.length; k++) {
        const v = 值们[k];
        const n = Math.min(p.length, v.length);
        let i = 0;
        while (i < n && p[i] === v[i])
            i++;
        p = p.slice(0, i);
        if (p.length === 0)
            break;
    }
    return p;
}

/** 把一个字段的变化序列渲染成"方向"字符串。
 *
 *  规则:
 *  1. **不截断任何值**(理由见 规范值);
 *  2. 各值若有**足够长的公共前缀**(≥6 字, 典型是 `位置` 的 "杰克逊社区·西街…·一楼"),
 *     就把它提出来放在冒号前, 冒号后只写**差异段** —— 真正变化的部分(厨房/壁炉旁)因此露出来;
 *  3. 段太多(>4)就不像轨迹像日志: 保留首段与末段, 中间用 … 表示。
 *
 *  例: `杰克逊社区·西街尽头独立木屋·一楼开放式厨房` → `杰克逊社区·西街尽头独立木屋·一楼壁炉旁`
 *      得到 `…独立木屋·一楼：开放式厨房→壁炉旁`(约 26 字) —— 比原来"两个 24 字截断"(48 字、
 *      且两段看起来一样)更短、也更准。 */
function 渲染序列(序列: string[]): string {
    const 压缩 = 序列.length > 4;
    const 真值 = 压缩 ? [序列[0], 序列[序列.length - 1]] : [...序列];
    const 连起来 = (段: string[]) => (压缩 ? `${段[0]}→…→${段[段.length - 1]}` : 段.join('→'));

    const 前 = 公共前缀(真值);
    const 段们 = 真值.map(v => v.slice(前.length));
    // 剥离门槛 10 字: 太短的前缀(如 `杰克逊社区·`)剥了也省不了几个字, 反而把"共同部分是哪一段"搞乱。
    // 另: 只要有一个值的差异段为空(值本身就等于公共前缀 —— 典型是她离开房间, 位置退化成房间本身),
    // 也别剥离 —— 那一格会变成空的, 读起来像缺数据。
    if (前.length < 10 || 段们.some(s => s.length === 0))
        return 连起来(真值);

    const 前短 = 前.length > 12 ? `…${前.slice(-12)}` : 前;
    // 共同部分用括号括起来: `（…独立木屋·一楼）开放式厨房→起居室窗边`
    // —— 前缀常以 `·` 结尾, 直接接冒号会写成 `杰克逊社区·：西街…` 这种别扭样子。
    return `（${前短}）${连起来(段们)}`;
}

/** 把一份快照载荷的 NPC 卡先过一遍旧字段名迁移(需求 §四: 用迁移后的字段名再 diff)。
 *
 *  不迁移会怎样: 存量卡的旧键(`心里惦记`)在 `CARD_FIELDS` 里根本不存在(那里只有 `心事`),
 *  于是**旧键上的变化一条都 diff 不到** —— 轨迹会漏掉"她心里惦记的事变了"这类最要紧的变化。 */
export function 迁移快照NPC(NPC: Record<string, Record<string, any>> | undefined): Record<string, Record<string, any>> {
    const 结果: Record<string, Record<string, any>> = {};
    for (const [名, 卡] of Object.entries(NPC ?? {}))
        结果[名] = (迁移旧字段名(卡) ?? 卡) as Record<string, any>;
    return 结果;
}

/**
 * 从快照序列里 diff 出近期轨迹。
 *
 * @param 快照们 调用方按**楼层升序**传进来(旧 → 新); 传乱序也没关系(本函数会再排一次)
 * @param 清空层 聊天级清空层; **小于等于**它的快照属于上一段剧情, 一律截掉
 */
export function 生成近期轨迹(快照们: 轨迹快照[], 清空层 = 0): 轨迹结果 {
    const 空结果: 轨迹结果 = { 文本: '', 用了快照数: 0, 跳过不连续: 0, 截掉清空层前: 0, 跳过形状不一致: 0, 写出条数: 0 };
    const 输入 = Array.isArray(快照们) ? 快照们 : [];

    // ---- 口子③: 跨清空层不能比 ----
    // 清空前的快照属于"上一段剧情", 拿它 diff 会得出"NPC 复活""位置从旧世界跳回来"这类假轨迹。
    const 有效 = 输入.filter(s => s && typeof s.楼层 === 'number' && s.楼层 > 清空层);
    const 截掉清空层前 = 输入.length - 有效.length;

    // ---- 口子①: 快照不够就允许"无轨迹" ----
    // 轨迹需要**至少两份**才有"变化"; 一份只能描述状态, 那是旧卡已经做的事。
    // 新聊天只有 1-2 份是常态, 这里**不报错、不告警**, 只是安静地不出这一段。
    if (有效.length < 2)
        return { ...空结果, 截掉清空层前 };

    // 只取最近 K 份(按楼层升序的尾部) —— K 固定, 所以注入量天然有界, 不随楼层数增长
    const 用 = [...有效].sort((a, b) => a.楼层 - b.楼层).slice(-K层上限);

    // ---- 口子②: 中间会缺 ----
    // 删楼层/re-roll/覆盖关闭都会在链上留洞。**只比"相邻两份"**, 不假设连续 ——
    // 所以这里不是"拿首尾两份比", 而是逐对相邻比, 每对独立。
    // (楼层号本身不要求差 1: 中间可能隔了几层没更新的, 那仍然是"相邻的两份有效快照";
    //  真正的"洞"在读取侧就已经消失了, 到这里看不见也不需要看见。)

    /** NPC 名 → 字段名 → 变化序列(旧值, 新值, …) */
    const 变化表 = new Map<string, Map<string, string[]>>();
    let 跳过形状不一致 = 0;
    let 跳过不连续 = 0;

    // 旧字段名先迁一遍(需求 §四): 每份快照只迁一次, 不是每对配对都迁 —— 否则同一张卡会被反复复制。
    const 迁过的 = 用.map(s => ({ 楼层: s.楼层, NPC: 迁移快照NPC(s.NPC) }));

    for (let i = 1; i < 迁过的.length; i++) {
        const 前 = 迁过的[i - 1];
        const 后 = 迁过的[i];
        // 防御: 排序后不该出现"后楼层 ≤ 前楼层", 真出现说明数据坏了 —— 跳过这一对, 不硬比
        if (后.楼层 <= 前.楼层) {
            跳过不连续++;
            continue;
        }

        // 名字只看后一份: 只在前一份里出现的说明这一轮被移除/改名了, 那是"移除"不是"生活变化";
        // 只在后一份里出现的是新建卡,"从无到有"也不是变化方向(旧卡里已经能看到它现在的样子)。
        for (const 名 of Object.keys(后.NPC)) {
            const 前卡 = 前.NPC[名];
            const 后卡 = 后.NPC[名];
            if (!前卡 || !后卡)
                continue;

            // 字段顺序固定(需求 §四: 按 CARD_FIELDS 序) —— 保证同一聊天每次输出稳定、便于人工对照
            for (const 字段 of CARD_FIELDS) {
                if (运行时键.has(字段))
                    continue;
                const 前值 = 可比字段值(前卡[字段]);
                const 后值 = 可比字段值(后卡[字段]);
                // ---- 口子④: 只对同形状字段做 diff ----
                // 两边都不是字符串(数组/对象/undefined) → 形状不可比, 跳过并计数。
                // 一边有一边没有也算"不可比"(例如旧卡没有这个字段) —— 那不是"变化", 是"数据不全"。
                if (前值 === null || 后值 === null) {
                    // 计数口径: **两边都有值但形状不同**(典型: 未完成事项 从字符串变数组)才算"形状不一致";
                    // "一边有一边没有"是数据不全(旧卡没这个字段), 不是形状问题 ——
                    // 把它算进形状不一致会让计数虚高, 掩盖真正需要关注的跨版本形状变化。
                    if (前卡[字段] !== undefined && 后卡[字段] !== undefined)
                        跳过形状不一致++;
                    continue;
                }
                if (前值 === 后值)
                    continue;

                let 该人 = 变化表.get(名);
                if (!该人) {
                    该人 = new Map();
                    变化表.set(名, 该人);
                }
                let 序列 = 该人.get(字段);
                if (!序列) {
                    序列 = [规范值(前值)];
                    该人.set(字段, 序列);
                }
                // 连续相同不重复追加(A→B→B→C 记 A→B→C)
                const 本条 = 规范值(后值);
                if (序列[序列.length - 1] !== 本条)
                    序列.push(本条);
            }
        }
    }

    if (变化表.size === 0)
        return { ...空结果, 用了快照数: 用.length, 跳过不连续, 截掉清空层前, 跳过形状不一致 };

    // ---- 截断: 按"变化字段数多的优先"(需求 §三) ----
    // 变化多的 NPC 说明它这一段时间在动, 比"只换了个位置"的更值得模型看到。
    // 同分时保持插入序(JS sort 稳定), 于是输出仍可复现。
    const 排序后 = [...变化表.entries()]
        .sort((a, b) => b[1].size - a[1].size)
        .slice(0, NPC上限);

    // 选择顺序(每 NPC 只留 N 个字段, 留谁是个判断, 理由写在这):
    //
    // 轨迹要防的是两件事 —— **原地打转**(同一个动作换个说法又写一遍)与**前后矛盾**
    // (位置/伤势/衣物忽然倒退)。所以优先留**外部可观察、最容易自相矛盾**的字段:
    //   当前在做(打转最容易发生在这) > 位置(最常被写错) > 伤势/体力 > 衣物/随身物 > 当前状态
    // **内心类(心事/藏起来的打算)排在后面**: 它们重要, 但不是"打转/矛盾"的来源 ——
    // 而且它们的变化往往已经通过 当前在做/当前状态 体现出来了。
    //
    // 为什么不用纯 CARD_FIELDS 序取前 3: `位置` 排第 11 位、`伤势/体力` 排第 10 位,
    // 纯按序取前 3 会把它们**系统性挤掉**, 留下的全是"在做的事"和"情绪" —— 那恰好是最不容易矛盾的两项。
    // (输出顺序仍按 CARD_FIELDS 序, 保证可复现 —— 需求 §四约束的是输出顺序。)
    const 优先序 = ['当前在做', '位置', '伤势/体力', '衣物/随身物', '当前状态'];

    /** 按"每人最多 N 个字段"组装行。N 越小注入量越小 —— 降级就靠它逐档重算。 */
    function 组装行(每人字段数: number): { 行们: string[]; 行条数: number[] } {
        const 行们: string[] = [];
        const 行条数: number[] = [];
        for (const [名, 字段们] of 排序后) {
            const 选中: string[] = [];
            for (const f of 优先序) {
                if (字段们.has(f) && 选中.length < 每人字段数)
                    选中.push(f);
            }
            for (const f of CARD_FIELDS) {
                if (选中.length >= 每人字段数)
                    break;
                if (字段们.has(f) && !选中.includes(f))
                    选中.push(f);
            }
            if (选中.length === 0)
                continue;
            // 输出按 CARD_FIELDS 序(不是按上面的选择序), 保证同一聊天每次输出稳定
            选中.sort((a, b) => CARD_FIELDS.indexOf(a) - CARD_FIELDS.indexOf(b));
            const 段 = 选中.map(f => `${f} ${渲染序列(字段们.get(f)!)}`);
            行们.push(`${名}：${段.join('；')}`);
            行条数.push(选中.length);
        }
        return { 行们, 行条数 };
    }

    // 表头只写"这是什么"(多少层、变化方向), **定位句不在这里** ——
    // 那句"它不是新发生的事"由 prompts.ts 的 轨迹段() 统一加, 免得两处各写一遍、措辞漂。
    const 头 = `近期轨迹（最近 ${用.length} 层快照的变化方向）:`;

    // ---- 降级而不是丢弃(2026-11-16 真机复盘第二处) ----
    // 旧做法: 超过上限就 break —— **排在后面的 NPC 整行消失**, 而且模型不知道少看了几个人,
    // 会把"她不在轨迹里"误读成"她没变化"。现在按 **整字段 → 整人** 逐级减, 原则是
    // **宁可少一条, 不可断一句**(任何一级都不切半句话):
    //   ① 每人 3 字段(全量) ② 每人 2 字段 ③ 每人 1 字段 ④ 减人 + 末尾写明省略人数
    let 行们: string[] = [];
    let 行条数: number[] = [];
    let 文本 = '';
    let 写出条数 = 0;
    let 省略人数 = 0;
    for (const 每人字段数 of [每NPC字段上限, 2, 1]) {
        const 组装 = 组装行(每人字段数);
        if (组装.行们.length === 0)
            break;
        行们 = 组装.行们;
        行条数 = 组装.行条数;
        文本 = [头, ...行们].join('\n');
        写出条数 = 行条数.reduce((a, b) => a + b, 0);
        if (文本.length <= 文本上限 || 每人字段数 === 1)
            break;
    }

    if (行们.length === 0)
        return { ...空结果, 用了快照数: 用.length, 跳过不连续, 截掉清空层前, 跳过形状不一致 };

    if (文本.length > 文本上限) {
        // 最后一级: 减人(保头部)。**必须把省略人数说出来** —— 静默省略会被读成"她们没变化"。
        const 总数 = 行们.length;
        const 后缀 = (n: number) => `（另有 ${n} 人轨迹略）`;
        let 保留 = 总数;
        while (保留 > 1 && [头, ...行们.slice(0, 保留), 后缀(总数 - 保留)].join('\n').length > 文本上限)
            保留--;
        省略人数 = 总数 - 保留;
        行们 = 行们.slice(0, 保留);
        写出条数 = 行条数.slice(0, 保留).reduce((a, b) => a + b, 0);
        文本 = [头, ...行们, 后缀(省略人数)].join('\n');
    }

    return {
        文本,
        用了快照数: 用.length,
        跳过不连续,
        截掉清空层前,
        跳过形状不一致,
        写出条数,
        省略人数,
    };
}

