// 彼方 · 请求通道的**归属信息**(错误可归因 / 请求日志)。
//
// 为什么单独一个文件: 它被"请求打散"(K1)与"工具通道"(K2)共用, 而这两个功能要能独立提交、
// 独立回退 —— 所以共用部分不能挂在任何一边。
//
// 用户原话(方案 §17.3): **「你们要记得做好报错，到时候出现报错就能知道是不是这两个出的问题」**
//
// 铁律: **开关全关时, 归属标记必须返回空串。** 那是"老报错逐字节不变"的底线(验收 G2) ——
// 加功能不许让老报错变样, 否则用户排查自己的老问题时会被新噪音干扰。

/** 本次请求开了哪些功能。只用于归属文案与日志, 不参与任何业务判断 */
export type 功能状态 = { 工具通道: boolean; 请求打散: boolean };

/** 一次更新里的可变请求态。**只活在内存里, 一轮更新一个**:
 *  绝不进 pinia / 绝不进 localStorage / 绝不写回设置 —— 一个请求的计数不该影响并发的另一条。 */
export type 请求态 = {
    /** 本次更新已经真实发出过几次请求(只用于归属文案与日志, 不参与业务判断) */
    请求序号: number;
};

export function 新建请求态(): 请求态 {
    return { 请求序号: 0 };
}

/**
 * 对外可见的归属文案。**开关全关时必须返回空串**(验收 G2)。
 *
 * 三个问题(用户原话):
 *   开了哪些功能 / 走了哪条路 / 第几次请求
 */
export function 归属标记(功能: 功能状态, 路径: '转发' | '直连', 请求态: 请求态): string {
    if (!功能.工具通道 && !功能.请求打散)
        return '';
    const 开了: string[] = [];
    if (功能.工具通道)
        开了.push('工具通道=开');
    if (功能.请求打散)
        开了.push('请求打散=开');
    return `\n【功能归属】${开了.join('；')}；路径=${路径}；第 ${Math.max(1, 请求态.请求序号)} 次请求`;
}

/** 每次**实际请求**一条日志(不是每次更新一条): 重试时才能定位"哪一发出了问题"。
 *  两个功能全关时返回 null —— 不开功能就别往控制台加噪音。 */
export function 请求日志(功能: 功能状态, 路径: '转发' | '直连', 请求态: 请求态, 工具数: number): string | null {
    if (!功能.工具通道 && !功能.请求打散)
        return null;
    const 工具项 = 功能.工具通道 ? `带 tools（${工具数} 个）` : '未带 tools';
    return `[彼方] 本次请求${工具项}，路径=${路径}，第 ${请求态.请求序号} 次请求，请求打散=${功能.请求打散 ? '开' : '关'}`;
}
