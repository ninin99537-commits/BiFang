// 彼方 · 更新状态机 —— 面板顶栏/底栏那套 idle/running/ok/err 的**判定逻辑**。
//
// 为什么从 .vue 里抽出来: 它是纯逻辑(不碰 DOM、不碰定时器), 而 .vue 里的东西跑不进用例,
// 于是"明明成功了却挂红灯"这类判定 bug 只能靠人手点。抽出来之后, 每个出口都能断言。
// 界面层只管两件真正属于 UI 的事: 秒表(200ms 刷新)与成功后 4.5s 回落。
//
// 2026-11-18 修的 bug(方案 §24 W6, 用户可见):
//   请求失败会记日志再重试, 可能第 3 次成功 —— 但中途那次失败已经把"本轮出错"置成 true,
//   而**没有任何东西在成功时把它清回来**, 于是收尾判成失败: 明明成了, 挂红灯。
//
// 三条账, 各管一件事(这是修法的核心):
//   · `发过请求` —— 本轮**是否真的发出过一次请求**(事实, 不是从日志推的)
//   · `见过错`   —— 本轮**是否出现过**错误(粘住, 只用于"重试过 N 次"这种弱提示)
//   · `最终错误` —— **最后一条**日志里的 error(跟随最新状态)
//
// 为什么必须有"发过请求"这一账(复查 P1-11):
//   提前 return 的路径(没填接口地址 / 没有可分析的回复 / 慢一步只剩一条)一条 error 都不写。
//   只看"最终错误为空 → ok", 这些路径会被判成**成功**, 面板弹"已更新"绿 —— 而什么都没发生。
//   所以判据不能是"有没有错误"(日志是副产品), 必须是"有没有真的发过请求"(事实)。
//
// 只看"见过错" → 重试成功也红灯(原来的 bug);
// 只看"最终错误" → 上一轮残留污染这一轮, 且提前 return 被误判成成功;
// 三条一起看才对。

/** 面板的四种状态: 待机 / 正在跑 / 刚成功 / 上次失败 */
export type 运行状态 = 'idle' | 'running' | 'ok' | 'err';

/** 一条日志里本状态机关心的两项(其余字段与判定无关) */
export type 日志快照 = { error?: string; 备注?: string[] } | null;

/** 本轮账: 三样事实 */
export type 本轮账 = {
    /** 本轮是否真的发出过一次请求 —— 由调用方在**实际发请求时**置真, 不从日志推 */
    发过请求: boolean;
    /** 本轮是否出现过错误(粘住; 只喂"重试过"弱提示) */
    见过错: boolean;
    /** 最后一条日志里的 error(跟随最新; 决定红绿) */
    最终错误: string;
};

export function 新建本轮账(): 本轮账 {
    return { 发过请求: false, 见过错: false, 最终错误: '' };
}

/** 记一次"真的发了请求"。调用点在 `chatCompletionInner` 里 —— 那里才是请求真正发出去的地方。 */
export function 记发过请求(账: 本轮账): 本轮账 {
    return { ...账, 发过请求: true };
}

/** 吸收一条新日志。返回更新后的"本轮账"。
 *
 *  `最终错误` **跟随最新那条**而不是"见过就粘住": 共用层在"失败过但重试成功"时会
 *  显式写一条 `error: ''`(见 共用/模型往返.ts 的收尾), 那条一到就说明本轮已经恢复正常。
 */
export function 吸收日志(前一账: 本轮账, 日志: 日志快照): 本轮账 {
    const 本条错误 = String(日志?.error ?? '').trim();
    return {
        ...前一账,
        见过错: 前一账.见过错 || 本条错误 !== '',
        最终错误: 本条错误,
    };
}

/** 收尾判定: 这一轮到底算成功、失败、用户中断, 还是"根本没开始"。 */
export type 收尾判定 = {
    /** 收尾后应该进入的状态 */
    状态: 'idle' | 'ok' | 'err';
    /** 中途失败过但又成功了 —— 界面上给一句弱提示, **不能挂红灯** */
    重试过: boolean;
    /** 失败原因(成功时为空串); 界面状态行只取第一行前 40 字 */
    原因: string;
};

/**
 * 判定本轮收尾。四个出口(顺序有意义):
 *
 * 1. **用户主动中断** → `idle`。中断是用户动作, 不是失败 —— 挂红灯会让"我点了取消"看起来像出错。
 * 2. **没发过请求** → `idle`。提前 return 的路径(没填地址/没有可分析的回复)什么都干不了,
 *    既不该挂绿灯说"已更新"(什么都没发生), 也不该挂红灯(不是失败)。
 *    这些路径各自已经有 toast 说明原因, 状态机不重复说。
 * 3. **发过请求 + 最终错误非空** → `err`。按**最终结果**判, 不被中途重试污染。
 * 4. **发过请求 + 最终错误为空** → `ok`; 若中途见过错, 额外给 `重试过: true`(弱提示, 不是红灯)。
 */
export function 判定本轮收尾(输入: 本轮账 & { 中断: boolean }): 收尾判定 {
    if (输入.中断)
        return { 状态: 'idle', 重试过: 输入.见过错, 原因: '' };
    if (!输入.发过请求)
        return { 状态: 'idle', 重试过: false, 原因: '' };
    const 错误 = String(输入.最终错误 ?? '').trim();
    if (错误)
        return { 状态: 'err', 重试过: 输入.见过错, 原因: 错误.split('\n')[0].slice(0, 40) };
    return { 状态: 'ok', 重试过: 输入.见过错, 原因: '' };
}

/** 状态行里"重试过"那一段(没有就返回空串, 让调用方直接 filter(Boolean) 拼) */
export function 重试提示(重试过: boolean): string {
    return 重试过 ? '重试过 1 次' : '';
}
