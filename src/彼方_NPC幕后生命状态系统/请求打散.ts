// 彼方 · 请求打散(K1) —— 纯逻辑, 不碰任何平台符号, 所以能脱离酒馆单独测。
//
// 做什么: 每次请求在 system **最前面**插一段固定长度的随机标记, 让同一份提示词不再逐字节相同。
// 动机: 用户观察到"官方 key 请求某些模型时输出异常快而质量差", 怀疑服务端按提示词字节判定是否
// 降级到更低档的模型。逐字节相同的提示词是这类判定的最好素材, 打散就是把它抹掉。
//
// 2026-11-18 改向(方案 §27): 标记从 system **末尾**移到**头部**。
//   当初放末尾是为了保住"system 段稳定、至少那段能命中前缀缓存"。
//   但服务端的前缀哈希缓存是**从头比**的 —— 标记在末尾, 前面几千 token 仍然逐字节相同,
//   缓存照样命中, 指纹也就没打散。用户看了另一套公开预设(明确写"首包注入动态会话指纹
//   打破 Prefix Hash 缓存")后拍板:**破坏缓存也没事**, 于是改到头部。
//   代价是真的: 每轮全量重算, 更慢更费 token。用户已明确接受, 面板灰字里也写了。
//   **只保留头部一处** —— 两处都放等于末尾那份白加(它还让尾部也变, 却对缓存毫无作用)。
//
// 不变量(改位置不许碰): 标记**不参与任何解析**。它只进 messages, 绝不进 tools 的说明或参数
// (P2-7 专门断言这条), 也不被宏展开、不改变请求的其他任何字节。

/** 打散标记: 固定 12 位 base36, 包在明确标记里(便于在抓包里一眼认出, 也便于断言) */
export function 生成打散标记(): string {
    let 串 = '';
    while (串.length < 12)
        串 += Math.random().toString(36).slice(2);
    return `[请求标识 ${串.slice(0, 12)}]`;
}

/**
 * 把打散标记放到第一条 system 消息的**最前面**(第一字节之前); 没有 system 消息时在最前面插一条。
 *
 * 为什么是"第一条 system"而不是"最后一条": 服务端的前缀哈希从头比,
 * 要打散就必须让**第一字节**就不同 —— 放到后面几条 system 上, 前面那段照样能命中缓存。
 *
 * 返回新数组、新消息对象 —— **不改入参**。重试时每次都拿同一份 messages 重新打散,
 * 所以每次请求的字节都不同(这正是 K1 要的效果), 而基线消息本身不会被越改越长。
 */
export function 加打散标记(messages: any[], 标记: string): any[] {
    const 副本 = messages.map(消息 => ({ ...消息 }));
    const 目标 = 副本.findIndex(消息 => 消息?.role === 'system');
    if (目标 >= 0) {
        副本[目标].content = `${标记}\n\n${String(副本[目标].content ?? '')}`;
        return 副本;
    }
    副本.unshift({ role: 'system', content: 标记 });
    return 副本;
}
