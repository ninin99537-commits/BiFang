/** 选证时的运行上下文(目前只有一个开关: 平静期) */
export interface 选证上下文 {
  /**
   * 平静期(2026-11-12): **不催办、不调档**。
   *
   * 真机代价: 平静 58 场的那一轮, 引擎照样把某条伏笔的全部 54 条证据读回来
   * —— 记忆审计写着「请求 52 条 / 纪要 41,796 字」。而平静期**不产出本幕指令**,
   * 这四万字换来的只是一个"什么都没发生"的记账。
   *
   * 平静期仍然要记账, 所以**待读队列**(导演自己申请的补充材料)和**待核命运证据**
   * (关系到谁死了谁走了是否成立)照读 —— 那两样是正确性, 不是催办。
   */
  平静?: boolean;
}

/** 从账本里收集"这一轮确实需要的"引用与理由。**不设条数上限** —— 需要多少就选多少。 */
export function 收集必需引用(账本: 导演账本, 上下文: 选证上下文 = {}): 选证理由[] {
  const out: 选证理由[] = [];
  const push = (引用: string, 理由: string) => {
    const ref = String(引用 ?? '').trim().toUpperCase();
    if (ref) out.push({ 引用: ref, 理由 });
  };

  // ① 到期/逾期伏笔: 独立于语义相似度被选中(设计文档 §9)
  //    平静期跳过: 不催办的地方也就不需要把它整条链的纪要读进来
  if (!上下文.平静) {
    for (const 到期 of 取到期伏笔(账本)) {
      const 条 = 到期.伏笔;
      const 标签 = `伏笔#${条.编号}(${到期.原因}${到期.逾期章数 > 0 ? `, 逾期 ${到期.逾期章数} 章` : ''})`;
      // 兑现前要把这条线的**全部既有证据**读回来: 埋设 + 回响 + 已记的兑现证据
      for (const 证 of 条.埋设证据 ?? []) push(证.记忆引用, `${标签} 埋设证据`);
      for (const 证 of 条.中间回响 ?? []) push(证.记忆引用, `${标签} 中间回响`);
      for (const 证 of 条.兑现证据 ?? []) push(证.记忆引用, `${标签} 兑现证据`);
    }
  }

  // ② 状态待核的命运条目: 死亡/离场/关系破裂的证据必须核过才能约束后续剧情
  //    平静期照读: 这是"谁死了谁走了"是否成立, 属于正确性, 不是催办
  for (const 命 of 账本.角色命运 ?? []) {
    if (命.状态 === '活跃') continue;
    for (const 证 of 命.状态证据 ?? []) {
      if (证.定位 !== '已核') push(证.记忆引用, `命运「${命.角色ID}」状态证据待核(${命.状态})`);
    }
  }

  // ②bis 待核的兑现证据(2026-11-12): 模型可能"补登记"一条早年的兑现证据(条件早满足了, 现在才记)。
  //   那一轮它还没被读过 → 盖章判成待核 → 兑现被门槛拒。下一轮必须真把它读回来, 否则补登记永远
  //   成功不了, 那条线就只能永远挂在「发酵」上。
  for (const 条 of 账本.伏笔 ?? []) {
    if (是终态.伏笔(条)) continue;
    for (const 证 of 条.兑现证据 ?? []) {
      if (证.定位 !== '已核') push(证.记忆引用, `伏笔#${条.编号} 待核的兑现证据`);
    }
  }

  // ③ 上一幕任务(当前指令的伏笔现场)提到的编号: 下一轮核验要能对着证据看
  //    平静期跳过: 平静期没有下发过本幕指令, 那条"伏笔现场"是**平静之前**留下的旧编排,
  //    拿它去调档等于为一道没演过的命令付钱。
  const 现场 = String(账本.当前指令?.伏笔现场 ?? '');
  if (!上下文.平静) {
    for (const m of 现场.matchAll(/#(\d+)/g)) {
      const 编号 = Number(m[1]);
      const 条 = (账本.伏笔 ?? []).find(项 => 项.编号 === 编号);
      if (!条 || 是终态.伏笔(条)) continue;
      for (const 证 of [...(条.埋设证据 ?? []), ...(条.中间回响 ?? [])]) push(证.记忆引用, `上一幕任务指向伏笔#${编号}`);
    }
  }

  // ④ 待读队列(上一轮导演新选中、留到本轮完整读取的 AM) —— 队列多长就读多长
  //    平静期照读: 这是导演自己申请的, 属于它当下的判断
  for (const 项 of 账本.待读队列 ?? []) {
    push(项.记忆引用, `待读队列${项.目标 ? `(${项.目标})` : ''}${项.理由 ? `: ${项.理由}` : ''}`);
  }

  // ⑤ 休眠伏笔: 低频提醒(只取最久没推进的两条, 避免每轮把所有休眠线都翻出来 ——
  //    这是"选哪些条目"层面的克制, 不是对条目内容截断)
  //    平静期跳过: 这是催办
  if (!上下文.平静) {
    const 休眠 = 取休眠伏笔(账本).slice(0, 2);
    for (const 项 of 休眠) {
      for (const 证 of 项.伏笔.埋设证据 ?? []) push(证.记忆引用, `休眠伏笔#${项.伏笔.编号}(休眠 ${项.休眠章数} 章)`);
    }
  }

  // ⑥ 临近窗口(下一章就到期)的伏笔: 提前把证据备好, 免得到期那轮才第一次调档
  //    平静期跳过: 这是催办
  if (!上下文.平静) {
    const 当前章 = Number(账本.章回?.章号) || 0;
    for (const 条 of 账本.伏笔 ?? []) {
      if (!是未结束伏笔(条)) continue;
      const m = String(条.回收窗口 ?? '').match(/第\s*(\d+)\s*章/);
      if (!m) continue;
      const 窗口章 = Number(m[1]);
      if (窗口章 !== 当前章 + 1) continue;
      for (const 证 of [...(条.埋设证据 ?? []), ...(条.中间回响 ?? [])]) push(证.记忆引用, `临近窗口伏笔#${条.编号}(第 ${窗口章} 章到期)`);
    }
  }

  // ⑦ 导演本轮从当前索引申请补充的(账本.待读队列已覆盖历史; 这里是**上一轮**的结果, 由 update 追加)
  return out;
}

/** 从账本里取"导演上一轮从索引申请的候选证据" */
export function 导演申请(账本: 导演账本): string[] {
  // 待读队列里的引用就是导演申请过的(入队时带理由); 这里只挑"还没读过"的那部分由 选证 统一处理,
  // 所以不再重复列出。保留函数是为了将来区分"代码选"与"导演选"(审计口径)。
  return (账本.待读队列 ?? []).filter(项 => 项.已读次数 === 0).map(项 => 项.记忆引用);
}

