// **零宿主依赖**：只吃账本。真正挑条目的是 记忆检索.选证，这里只产"申请清单 + 理由"。
import type { 导演账本 } from './schema';
import type { 选证理由 } from './记忆检索';
import { 取到期伏笔, 取休眠伏笔 } from './证据链';
import { 是终态, 是未结束伏笔 } from './字段表';

// ---------------------------------------------------------------------------
// 选证: 代码按"本幕回收 / 上一幕核验 / 命运冲突 / 临近窗口"决定这一轮要完整读哪些 AM
