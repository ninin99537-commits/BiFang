// 代码预检: 到期/休眠伏笔独立调度
// ---------------------------------------------------------------------------

export interface 到期伏笔 {
  伏笔: 伏笔;
  /** 到期原因 */
  原因: string;
  /** 逾期多少章(0 = 刚好到期) */
  逾期章数: number;
  /** 窗口语义(纠偏): 什么时候允许催办 —— 只有「可催办」/「已过最迟」才进调度 */
  窗口: 窗口状态;
}

/** 从"回收窗口"里解析章号(如"第3章收束前" → 3); 解析不出给 null(不猜) */
export function 解析窗口章号(回收窗口: string): number | null {
  const m = String(回收窗口 ?? '').match(/第\s*(\d+)\s*章/);
  if (!m) return null;
  const n = Number(m[1]);
  return Number.isFinite(n) && n > 0 ? n : null;
}

/**
 * 窗口状态(纠偏, 语义唯一入口):
 *
 *   '未到'      —— 最早章还没到。**代码不得强制兑现, 连催办都不催**。
 *                  这条修的是用户报告的"刚埋下的伏笔下一轮就要求回收"。
 *   '可催办'    —— 最早章已到、最迟章未过。允许**评估/催办**, 但只是"请导演考虑",
 *                  不是"下一幕必须引爆"; 且受 最近催办章 节流。
 *   '已过最迟'  —— 超过最迟章。催办但同样只是评估, 仍受节流; 且必须给世界内延期理由或安排兑现。
 *   '无窗口'    —— 没写窗口, 永不因窗口被催办(交给休眠线那条低频通道)。
 */
export type 窗口状态 = '未到' | '可催办' | '已过最迟' | '无窗口';

export interface 窗口评估 {
  状态: 窗口状态;
  /** 最早章(目标窗口.最早章 优先; 否则取回收窗口章号; 都没有 null) */
  最早章: number | null;
  /** 最迟章(目标窗口.最迟章; 没有 null) */
  最迟章: number | null;
  /** 人类的解释(写进代码调整) */
  说明: string;
}

/**
 * 评估一条伏笔的窗口。**`目标窗口.最早章/最迟章` 优先于旧的 `回收窗口` 文本** ——
 * `回收窗口` 只是向后兼容的"最迟回收提示", 解析出的章号按最迟处理。
 */
export function 评估窗口(条: 伏笔, 当前章: number): 窗口评估 {
  const 最早 = Number(条.目标窗口?.最早章) > 0 ? Number(条.目标窗口?.最早章) : null;
  const 显式最迟 = typeof 条.目标窗口?.最迟章 === 'number' && Number(条.目标窗口?.最迟章) > 0 ? Number(条.目标窗口?.最迟章) : null;
  const 旧窗口 = 解析窗口章号(条.回收窗口);
  // 旧字段"回收窗口"是**最迟**提示(向后兼容); 没有目标窗口时, 它同时充当最早与最迟的锚点。
  const 最迟 = 显式最迟 ?? 旧窗口;
  const 最早最终 = 最早 ?? 旧窗口;

  if (最早最终 === null && 最迟 === null) {
    return { 状态: '无窗口', 最早章: null, 最迟章: null, 说明: '没有窗口(交给休眠/评估通道)' };
  }
  // 明确延期: 未到延期章之前一律不催
  const 延期到 = Number(条.延期到章) > 0 ? Number(条.延期到章) : null;
  if (延期到 !== null && 当前章 < 延期到) {
    return {
      状态: '未到',
      最早章: 最早最终,
      最迟章: 最迟,
      说明: `已明确延期到第 ${延期到} 章(${条.延期原因 || '未写原因'}), 未到之前不催办`,
    };
  }
  if (最早最终 !== null && 当前章 < 最早最终) {
    return { 状态: '未到', 最早章: 最早最终, 最迟章: 最迟, 说明: `最早章 ${最早最终} 未到(当前第 ${当前章} 章), 不得催办/兑现` };
  }
  if (最迟 !== null && 当前章 > 最迟) {
    return { 状态: '已过最迟', 最早章: 最早最终, 最迟章: 最迟, 说明: `已过最迟章 ${最迟}(当前第 ${当前章} 章): 需要评估/催办, 仍不等于必须引爆` };
  }
  return { 状态: '可催办', 最早章: 最早最终, 最迟章: 最迟, 说明: `窗口已开(最早 ${最早最终 ?? '—'} / 最迟 ${最迟 ?? '—'}, 当前第 ${当前章} 章): 可评估, 不等于必须引爆` };
}

/**
 * 到期/催办伏笔的**独立调度**: 不依赖语义相似度, 纯按窗口算。
 *
 * 三条纠偏:
 *   ① `最早章` 未到 → **完全不进调度**(用户报告的核心 bug);
 *   ② 同一章内**已催办过的线不再催**(`最近催办章 === 当前章` 跳过), 否则节拍会被反复改写;
 *   ③ 到最迟章只表示"该评估了", **不表示必须下一幕引爆** —— 调用方据此催办而非强制。
 */
export function 取到期伏笔(账本: 导演账本): 到期伏笔[] {
  const 当前章 = Number(账本.章回?.章号) || 0;
  const out: 到期伏笔[] = [];
  for (const 条 of 账本.伏笔 ?? []) {
    if (!是未结束伏笔(条)) continue;
    const 窗口 = 评估窗口(条, 当前章);
    if (窗口.状态 !== '可催办' && 窗口.状态 !== '已过最迟') continue;
    // ② 节流: 这一章已经催过就不再催
    if (Number(条.最近催办章) === 当前章) continue;
    const 期限 = 窗口.状态 === '已过最迟' ? (窗口.最迟章 ?? 当前章) : (窗口.最早章 ?? 当前章);
    out.push({
      伏笔: 条,
      原因: 窗口.说明,
      逾期章数: Math.max(0, 当前章 - 期限),
      窗口: 窗口.状态,
    });
  }
  return out;
}

export interface 休眠伏笔 {
  伏笔: 伏笔;
  休眠章数: number;
  /** 为什么进休眠提醒(纠偏: 区分"久未推进"与"窗口已开却停滞") */
  原因: string;
}

/**
 * 休眠伏笔(纠偏): 长期没有推进的未结束线。
 *
 * 上一版有个**反向 bug**: `if (有窗口) continue` 把所有写了窗口的线排除在休眠之外 ——
 * 结果**真正超长**的伏笔反而收不到任何提醒(用户报告的"超长伏笔没有休眠提醒")。
 *
 * 现在的口径:
 *   ① 久未推进: `当前章 - max(最后推进章, 最近催办章, 埋设章) >= 阈值章`;
 *   ② **窗口已开却仍在原地**(状态还是 埋下/潜伏/发酵, 且窗口已可催办) —— 这条专门兜住
 *      有窗口的长线: 它可能因为节流当轮没被催办, 但仍应作为**低频评估**被提醒。
 * 两者都只产生"回响/评估"提示, **不强迫提前兑现**; 排序按停滞时长降序。
 */
export function 取休眠伏笔(账本: 导演账本, 阈值章 = 3): 休眠伏笔[] {
  const 当前章 = Number(账本.章回?.章号) || 0;
  const out: 休眠伏笔[] = [];
  for (const 条 of 账本.伏笔 ?? []) {
    if (!是未结束伏笔(条)) continue;
    const 基准 = Math.max(Number(条.最后推进章) || 0, Number(条.最近催办章) || 0, Number(条.埋设章) || 0);
    const 休眠 = Math.max(0, 当前章 - 基准);
    const 窗口 = 评估窗口(条, 当前章);
    // 阈值口径 = "这条线已经存在 ≥ N 章没有进展"。存在的那一章也算一章, 所以比较时减 1
    // (否则默认阈值 3 实际要等 4 章; 而 阈值=1 永远不可能成立 —— 那等于把休眠通道关死)。
    const 久未推进 = 休眠 >= Math.max(0, 阈值章 - 1);
    // ② 有窗口的长线: 窗口已开(但不是"未到"), 状态还停在前三档 → 也算"该评估了"
    const 窗口停滞 =
      窗口.状态 !== '无窗口' &&
      窗口.状态 !== '未到' &&
      (条.状态 === '埋下' || 条.状态 === '潜伏' || 条.状态 === '发酵');
    if (!久未推进 && !窗口停滞) continue;
    out.push({
      伏笔: 条,
      休眠章数: 休眠,
      原因: 久未推进
        ? `已 ${休眠} 章没有推进(最后推进/催办/埋设章最大 = 第 ${基准} 章)`
        : `窗口已开但状态仍是「${条.状态}」(当前第 ${当前章} 章): 该评估了, 不必提前兑现`,
    });
  }
  return out.sort((a, b) => b.休眠章数 - a.休眠章数);
}

// ---------------------------------------------------------------------------
// 兑现候选(纠偏): 收束调度与契诃夫之枪都必须从这里挑, 不许从数组里随手取第一条
// ---------------------------------------------------------------------------

export interface 兑现候选 {
  伏笔: 伏笔;
  窗口: 窗口状态;
  理由: string;
  /** 紧迫度: 越大越先处理。已过最迟 > 待兑现 > 窗口已开 */
  紧迫度: number;
  /**
   * 最迟章是否已到(纠偏): 只有它到了才允许"安排兑现"。
   * 窗口刚开(最早章到、最迟章还没到)时**只做低强度评估**, 不改写节拍 ——
   * 否则一条第 2 章最早 / 第 8 章最迟的线会在第 2 章就被催着引爆。
   */
  最迟已到: boolean;
}

/**
 * 挑出**允许被催办/安排兑现**的伏笔候选。
 *
 * 这是"最早章未到绝不强制兑现"的唯一落点 —— 引擎规则不再自己解析窗口文本。
 * 入选条件:
 *   ① 未结束;
 *   ② 窗口状态是「可催办」或「已过最迟」(`未到` 一律不入选; `无窗口` 交给休眠通道);
 *   ③ 本章**还没催办过**(`最近催办章 !== 当前章`) —— 否则节拍会被同一条线反复改写。
 * 排序: 已过最迟 → 待兑现 → 发酵 → 潜伏; 同级按"最早章更早 / 逾期更久"。
 *
 * 注意: 入选 ≠ 必须下一幕引爆。候选只是"该评估/可以安排", 兑现仍要满足证据门槛与场景适配,
 * 导演完全可以给延期理由继续发酵(见 提示词里的 延期/休眠 输出格式)。
 */
export function 取兑现候选(账本: 导演账本, 当前章?: number): 兑现候选[] {
  const 章 = Number.isFinite(Number(当前章)) ? Number(当前章) : Number(账本.章回?.章号) || 0;
  const out: 兑现候选[] = [];
  for (const 条 of 账本.伏笔 ?? []) {
    if (!是未结束伏笔(条)) continue;
    const 窗口 = 评估窗口(条, 章);
    if (窗口.状态 !== '可催办' && 窗口.状态 !== '已过最迟') continue;
    if (Number(条.最近催办章) === 章) continue;
    const 状态权重 = 条.状态 === '待兑现' ? 2 : 条.状态 === '发酵' ? 1 : 0;
    const 窗口权重 = 窗口.状态 === '已过最迟' ? 10 : 0;
    const 逾期 = 窗口.状态 === '已过最迟' ? Math.max(0, 章 - (窗口.最迟章 ?? 章)) : 0;
    // 最迟章到没到: 有最迟章就按它判断; 没写最迟章(只有回收窗口之外的模糊描述)则视为"已到"
    // D-5(2026-11-13): 用 `>` 而不是 `>=` —— 与 `:184` 的 `已过最迟 = 当前章 > 最迟` 对齐。
    // 以前"正好到点"就算 `最迟已到`, 于是 `引擎规则` 一命中就把节拍改成「兑现伏笔」**当轮强制引爆**;
    // 而 `:196` 的注释自己写着"到最迟章只表示该评估了, 不表示必须下一幕引爆"。
    // 正好到点的催办交给 `取到期伏笔`（它的 `可催办` 已覆盖到点这一档）。
    const 最迟已到 = 窗口.最迟章 === null ? true : 章 > 窗口.最迟章;
    out.push({
      伏笔: 条,
      窗口: 窗口.状态,
      理由: `${窗口.说明}${条.状态 === '待兑现' ? '; 证据链已备齐' : ''}`,
      紧迫度: 窗口权重 + 状态权重 + 逾期,
      最迟已到,
    });
  }
  return out.sort((a, b) => b.紧迫度 - a.紧迫度 || a.伏笔.编号 - b.伏笔.编号);
}

/**
 * 把一条候选渲染成"本幕现场 + 揭示"的三件套(纠偏: 指令目标不许脱节)。
 *
 * 用户报告的问题: 代码把节拍改成「兑现伏笔」, 却没把**哪一条**写进 `伏笔现场`,
 * 也没给任何揭示 —— 演员只能自己猜要回收哪条线。
 * 这里统一产出: 现场指认(编号 + 公开线头) + 允许公开的方向 + 禁止提前揭晓的部分。
 */
export function 渲染兑现现场(条: 伏笔): { 现场: string; 揭示: string[] } {
  const 线头 = String(条.公开线头 ?? '').trim() || String(条.内容 ?? '').trim();
  const 现场 = `#${条.编号}${线头 ? `「${线头}」` : ''}`;
  const 揭示: string[] = [];
  if (线头) {
    揭示.push(`伏笔 #${条.编号} 到了可以推进的时候: 读者之前已经看到「${线头}」, 这一幕要让它的意义往前推进一步`);
  }
  // 候选兑现是**方向建议**, 不是必须选其中一条; 也绝不能把幕后真相透传出去
  const 方向 = (条.候选兑现 ?? []).map(x => String(x ?? '').trim()).filter(Boolean);
  if (方向.length > 0) {
    揭示.push(`可用的推进方向(挑一个与世界因果相符的, 不要求全部兑现): ${方向.join('；')}`);
  }
  if (方向.length === 0 && (条.兑现条件 ?? []).some(x => String(x ?? '').trim())) {
    揭示.push(`推进时需要满足的世界内条件: ${(条.兑现条件 ?? []).map(x => String(x ?? '').trim()).filter(Boolean).join('；')}`);
  }
  return { 现场, 揭示 };
}

/**
 * 兑现包的「前情」(第二轮方案 2.3): 把当初埋设/回响时**已经公开**的摘要原样递给主 AI。
 *
 * 为什么: 主 AI 只看得到最近几层 + 记忆插件挑的 20~40 条概要, 第 5 场埋的东西到第 60 场兑现时,
 * 那条概要被挑中的概率不可控。导演手里有证据链, 所以由它亲手递过去。
 *   - 只用 `公开摘要`(读者见过), **不带幕后真相**;
 *   - 摘要**一律附上**(优化 3): 读得到的召回是**上一条用户消息**的, 记忆插件每条消息都重挑,
 *     下一轮未必还召回同一条 —— 拿它省略前情等于赌主 AI 看得到。一条摘要几十字, 不值得赌。
 *     `已召回` 只用来在没有摘要时补一个 AM 编号(总比什么都没有强)。
 */
/** 前情里每条伏笔最多带几条回响(最近的) */
export const 前情回响上限 = 3;

export function 渲染前情(条: 伏笔, 已召回?: Set<string>): string[] {
  const out: string[] = [];
  // 有界(2026-11-01): 长线伏笔跑上百场后回响会有十几条, 一次全吐进本幕指令会淹没正文 AI。
  // 埋设是"读者第一次看到它"必须保留; 回响只给最近 前情回响上限 条(完整证据链在账本页)。
  const 回响 = [...(条.中间回响 ?? [])].sort((a, b) => (Number(a.楼层) || 0) - (Number(b.楼层) || 0)).slice(-前情回响上限);
  const 证据们 = [
    ...(条.埋设证据 ?? []).map(证 => ({ 证, 类: '埋下' })),
    ...回响.map(证 => ({ 证, 类: '回响' })),
  ].sort((a, b) => (Number(a.证.楼层) || 0) - (Number(b.证.楼层) || 0));
  for (const { 证, 类 } of 证据们) {
    const 摘要 = String(证.公开摘要 ?? '').trim();
    const 引用 = String(证.记忆引用 ?? '').trim().toUpperCase();
    if (!摘要 && !引用) continue;
    const 层 = Number(证.楼层) > 0 ? `第 ${证.楼层} 层` : '';
    if (摘要) {
      out.push(`#${条.编号}（${类}）${层}：${摘要}`);
    } else if (引用 && 已召回?.has(引用)) {
      out.push(`#${条.编号}（${类}）${层}：见记忆 ${引用}`);
    }
  }
  return out;
}

/** 从记忆插件的召回原文里解析 `<recall>AM0001, AM0002</recall>` → AM 集合(解析不了 → 空集) */
export function 解析召回(原文: string): Set<string> {
  const 段 = String(原文 ?? '').match(/<recall>([\s\S]*?)<\/recall>/i)?.[1] ?? '';
  return new Set((段.match(/AM\d+/gi) ?? []).map(x => x.toUpperCase()));
}

