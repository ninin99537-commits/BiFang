export interface 伏笔审计 {
  未结束: number;
  已引爆: number;
  已消亡: number;
  /** 证据缺失(待核)的伏笔数 */
  证据待核: number;
  /** 逾期未回收 */
  逾期: number;
  /** 休眠超过阈值的条数 */
  休眠: number;
  /** 平均休眠章数(未结束的那些) */
  平均休眠章数: number;
  /** 无埋设证据的条数(老账本迁移形态) */
  无证埋设: number;
  /** 命运冲突数 */
  命运冲突: number;
  /** 死亡/离场角色数 */
  不可逆角色: number;
}

/** 把审计指标算出来(纯读; 面板与日志共用一份口径) */
export function 审计伏笔(账本: 导演账本, 休眠阈值章 = 3): 伏笔审计 {
  const 全部 = 账本.伏笔 ?? [];
  const 当前章 = Number(账本.章回?.章号) || 0;
  const 未结束 = 全部.filter(是未结束伏笔);
  const 休眠列表 = 取休眠伏笔(账本, 休眠阈值章);
  const 休眠和 = 未结束.reduce((s, 条) => {
    const 最后 = Number(条.最后推进章) || Number(条.埋设章) || 0;
    return s + Math.max(0, 当前章 - 最后);
  }, 0);
  const 待核 = 全部.filter(条 => {
    const 全 = [...(条.埋设证据 ?? []), ...(条.中间回响 ?? []), ...(条.兑现证据 ?? [])];
    return 全.some(证 => !证据可用(证));
  }).length;
  const 命运 = 账本.角色命运 ?? [];
  return {
    未结束: 未结束.length,
    已引爆: 全部.filter(条 => 条.状态 === '已引爆').length,
    已消亡: 全部.filter(条 => 条.状态 === '已消亡').length,
    证据待核: 待核,
    逾期: 取到期伏笔(账本).length,
    休眠: 休眠列表.length,
    平均休眠章数: 未结束.length > 0 ? Math.round((休眠和 / 未结束.length) * 10) / 10 : 0,
    无证埋设: 全部.filter(条 => (条.埋设证据 ?? []).length === 0).length,
    命运冲突: 取命运冲突(账本).length,
    不可逆角色: 命运.filter(项 => 项.状态 === '死亡' || 项.状态 === '离开' || 项.状态 === '失踪').length,
  };
}

