/**
 * 把一条伏笔的候选状态**降级**到代码允许的状态。
 *
 * 这是"模型不得单方面改状态"的落点: 候选说 `已引爆` 但没有可用兑现证据 → 降级为 `待兑现`
 * (不是静默通过, 也不是丢弃整份候选), 并把拒绝原因交给调用方记进日志/代码调整。
 * 已消亡**不要求**兑现证据(消亡是世界内原因, 不是回收), 但要求写明原因。
 */
export function 守卫伏笔状态(旧: 伏笔, 候选: 伏笔): { 伏笔: 伏笔; 降级: string[] } {
  const 降级: string[] = [];
  const 结果: 伏笔 = { ...候选 };
  const 想引爆 = 候选.状态 === '已引爆';
  const 已经终态 = 是终态.伏笔(旧);
  if (想引爆) {
    // 已经是终态的条目原样带回: 不重复走门槛(否则删楼回退重推会反复降级)
    if (!已经终态) {
      const 门槛 = 判定可回收(旧, 候选.兑现证据 ?? []);
      if (!门槛.可引爆) {
        结果.状态 = '待兑现';
        降级.push(`#${旧.编号} 拟转「已引爆」但证据不足 → 降为「待兑现」: ${门槛.拒绝原因.join('；')}`);
      }
    }
  }
  if (候选.状态 === '已消亡' && !String(候选.消亡原因 ?? '').trim()) {
    // 消亡必须写明世界内原因(设计文档 §5.1)。但**不因此回退状态**: 老账本/老提示词下模型不会填这个字段,
    // 硬回退会让"允许自然消亡"这条既有能力整体失效。所以放行 + 显式记录(审计里看得见"这条没写原因")。
    降级.push(`#${旧.编号} 转「已消亡」但没写消亡原因 —— 已放行, 但这是审计缺口(消亡必须有世界内原因, 不许用"队列满了")`);
  }
  return { 伏笔: 结果, 降级 };
}

/** 未结束伏笔的完整性校验: 容量/漏返回都不得丢条目(阶段 A 的验收点之一) */
export function 校验未结束伏笔未丢(旧列表: 伏笔[], 新列表: 伏笔[]): { 丢失: number[] } {
  const 新编号 = new Set(新列表.map(条 => 条.编号));
  const 丢失 = 旧列表.filter(条 => 是未结束伏笔(条) && !新编号.has(条.编号)).map(条 => 条.编号);
  return { 丢失 };
}
