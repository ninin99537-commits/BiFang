// ---------------------------------------------------------------------------

/**
 * 给账本里所有证据重新盖章。
 *
 * 为什么必须由代码盖: 模型完全可以在 JSON 里写 `"定位": "已核"` 来自证"这条 AM 我核对过了"。
 * 但"能不能定位"是**检索结果**, 不是模型的判断。所以:
 *   - AM 在本轮**实际读到且不歧义**的集合里 → `已核`;
 *   - 否则 → `待核` + 写明原因(缺失/歧义/本轮未读/读取失败)。
 * 旧账本里标着已核但本轮**去读了却没读到**的引用**会被降回待核** —— 这正是"旧账本已核引用要可复核"。
 *
 * @param 已核引用 本轮代码检索确认可定位的 AM
 * @param 歧义引用 本轮确认歧义的 AM(即使读到了也不算已核)
 * @param 失败原因 本轮记忆读取的失败原因(非空时**本轮请求过**的全部降级)
 * @param 正文楼层 本轮**读过的正文楼层**
 * @param 本轮请求 本轮**实际去调过档**的 AM(可选)。传了它就只对这些引用做降级判定 ——
 *   **没去查不等于查无**: 不传 = 老行为(凡未读到的都降级); 传了 = 只有"查了没查到"才降级。
 *   为什么需要(2026-11-12): 平静期不再把整条证据链调档(省 4 万字/轮), 老规则会把没请求过的
 *   引用一律判「待核」—— 一次平静下来, 所有证据全变待核, 解禁后兑现门槛反而因为
 *   "埋设证据全部待核"拒收。复核 ≠ 每轮全查。
 *
 * 为什么需要 `正文楼层`(2026-10-29 真机修复): 伏笔常在**刚发生的这一幕**被兑现(砸掉电台、当场死亡),
 * 而那一楼的 AM 纪要还没生成。按"必须读到 AM"判定, 兑现证据永远是待核 → 状态被降回「待兑现」,
 * 下一轮又催兑现, 于是出现"电台已经砸了却还写待兑现"的荒谬循环。
 * 现在: 证据的楼层落在本轮正文里 → 直接算可用(它就在我们刚读的正文里, 不需要纪要转述)。
 */
export function 盖章证据(
  账本: 导演账本,
  已核引用: string[],
  歧义引用: string[] = [],
  失败原因 = '',
  正文楼层: number[] = [],
  本轮请求?: string[],
): 导演账本 {
  const 已核 = new Set(已核引用.map(x => String(x ?? '').trim().toUpperCase()).filter(Boolean));
  const 歧义 = new Set(歧义引用.map(x => String(x ?? '').trim().toUpperCase()).filter(Boolean));
  const 正文集 = new Set(正文楼层.map(Number).filter(号 => Number.isFinite(号) && 号 > 0));
  // 「没查」不等于「查无」(2026-11-12): 传了 `本轮请求` 就只对**这一轮真去查过**的引用降级。
  // 起因: 平静期不再把整条证据链调档(省 4 万字/轮), 而原来的规则会把没请求过的引用一律判「待核」
  // —— 一次平静下来, 所有证据都变成"待核", 解禁后兑现门槛反而因为"埋设证据全部待核"拒收。
  // 那正好是这条函数自己注释里写过的坑("旧账本已核引用要可复核")的另一面: 复核 ≠ 每轮全查。
  const 请求集 = 本轮请求 ? new Set(本轮请求.map(x => String(x ?? '').trim().toUpperCase()).filter(Boolean)) : null;
  const 盖 = (证: 证据引用): 证据引用 => {
    const ref = String(证.记忆引用 ?? '').trim().toUpperCase();
    // 正文证据优先: 它就在本轮读过的正文里, 与"纪要有没有生成"无关
    if (正文集.has(Number(证.楼层))) return { ...证, 定位: '已核', 待核原因: '' };
    if (!ref) return { ...证, 定位: '待核', 待核原因: '证据没有 AM 引用, 无法定位' };
    // 这一轮根本没去调它的档 → **保留原判定**(连"读取失败"也不会误伤没请求过的引用)
    if (请求集 && !请求集.has(ref)) return 证;
    if (失败原因) return { ...证, 定位: '待核', 待核原因: `本轮记忆读取失败: ${失败原因}` };
    if (歧义.has(ref)) return { ...证, 定位: '待核', 待核原因: `引用歧义: ${ref} 在世界书里命中多条纪要, 代码未解决唯一性` };
    if (!已核.has(ref)) return { ...证, 定位: '待核', 待核原因: `本轮未读到 ${ref}(缺失或尚未生成纪要)` };
    return { ...证, 定位: '已核', 待核原因: '' };
  };
  const 盖数组 = (列表: 证据引用[] | undefined): 证据引用[] | undefined =>
    列表 ? 列表.map(盖) : 列表;
  for (const 条 of 账本.伏笔 ?? []) {
    条.埋设证据 = 盖数组(条.埋设证据);
    条.中间回响 = 盖数组(条.中间回响);
    条.兑现证据 = 盖数组(条.兑现证据);
    条.兑现尝试 = (条.兑现尝试 ?? []).map(尝 => ({ ...尝, 证据: 盖数组(尝.证据) ?? [] }));
  }
  for (const 命 of 账本.角色命运 ?? []) {
    命.状态证据 = 盖数组(命.状态证据) ?? [];
    命.持久后果 = (命.持久后果 ?? []).map(后 => ({
      ...后,
      来源证据: 盖数组(后.来源证据) ?? [],
      ...(后.消退证据 ? { 消退证据: 盖数组(后.消退证据) } : {}),
    }));
  }
  return 账本;
}

