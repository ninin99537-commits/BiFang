// 剧情导演 · 证据链(阶段 A): "回收必须有证据" 的**代码**判据。
// ---------------------------------------------------------------------------
// 设计文档 §5.1 / §9 的硬要求:
//   - `已引爆` 必须有**本幕正文证据**, 并且与既有埋设证据对应;
//   - 缺失证据 → 进 `证据待核`, **不得冒充已引爆**;
//   - 未结束伏笔与角色命运不得因容量上限、AI 漏返回或上下文裁剪被静默删除;
//   - 回收质量不由"回收率 100%"代表: 另算休眠时长/逾期原因/证据缺失/误回收/命运冲突。
//
// 这个模块是**纯函数**: 账本进、判据出。不碰平台、不碰 Vue、不调模型 ——
// "AI 声称已回收"永远不算证据(实施提示词 §CONSTRAINT)。
import type { 导演账本, 伏笔, 证据引用, 角色命运 } from './schema';
import { 是终态, 是未结束伏笔 } from './字段表';

// ---------------------------------------------------------------------------
// 证据的可用性
// ---------------------------------------------------------------------------

/** 一条证据是否"可用": 有 AM 引用、且定位状态不是待核 */
export function 证据可用(证据: 证据引用 | null | undefined): boolean {
  if (!证据) return false;
  if (!String(证据.记忆引用 ?? '').trim()) return false;
  return 证据.定位 !== '待核';
}

/**
 * 把'楼层落在本轮正文里'的证据直接标成已核(2026-10-29)。
 *
 * 必须在**状态守卫之前**跑: 刚发生的事(砸电台/当场死亡)还没有 AM 纪要, 若等盖章(在守卫之后)
 * 再标就已经晚了 —— 那一轮已经被降级成'待兑现'了。
 */
export function 标正文证据(列表: 证据引用[] | undefined, 正文楼层: number[] = []): 证据引用[] | undefined {
  if (!列表) return 列表;
  const 集 = new Set(正文楼层.map(Number).filter(号 => Number.isFinite(号) && 号 > 0));
  if (集.size === 0) return 列表;
  return 列表.map(证 => (集.has(Number(证.楼层)) ? { ...证, 定位: '已核', 待核原因: '' } : 证));
}

/** 统计一组证据里可用/待核各几条(审计指标用) */
export function 证据统计(列表: 证据引用[] | undefined): { 可用: number; 待核: number; 总数: number } {
  const 全部 = 列表 ?? [];
  const 可用 = 全部.filter(证据可用).length;
  return { 可用, 待核: 全部.length - 可用, 总数: 全部.length };
}

// ---------------------------------------------------------------------------
// 回收门槛: 关键反转至少要有埋设证据 + 一条推进证据
// ---------------------------------------------------------------------------

/** 短篇简单伏笔的放宽阈值: 证据少于这个数就不强求"两次提及"(设计文档 §5.1 明确允许放宽) */
export const 简单伏笔字数阈值 = 40;

export interface 回收门槛 {
  /** 是否可以认定为已引爆 */
  可引爆: boolean;
  /** 拒绝原因(可观察的拒绝路径; 空 = 通过) */
  拒绝原因: string[];
  /** 已满足的条件说明 */
  满足: string[];
}

/**
 * 判定一条伏笔**能不能**从非终态转为 `已引爆`。
 *
 * 规则(代码先做确定性检查, 语义留给模型):
 *   1. 必须有 `兑现证据` —— 没有本幕正文证据, 一律不许记已引爆;
 *   2. 兑现证据必须**至少一条可用**(定位=已核), 否则是"假引用";
 *   3. 关键反转(内容较长/带幕后真相/带目标窗口)至少再检查一条埋设或回响证据 ——
 *      短篇简单伏笔可放宽(不能一律机械要求"两次提及");
 *   4. 必须与既有埋设证据**对应**: 埋设证据里至少有一条可用(否则这条伏笔本来就没根)。
 */
export function 判定可回收(伏笔条: 伏笔, 兑现证据: 证据引用[]): 回收门槛 {
  const 拒绝原因: string[] = [];
  const 满足: string[] = [];
  const 埋设 = 伏笔条.埋设证据 ?? [];
  const 回响 = 伏笔条.中间回响 ?? [];
  const 埋设统计 = 证据统计(埋设);
  const 兑现统计 = 证据统计(兑现证据);

  if (兑现统计.总数 === 0) {
    拒绝原因.push('没有兑现证据: 已引爆必须有本幕正文证据, 不接受模型单方面声明');
  } else if (兑现统计.可用 === 0) {
    拒绝原因.push(`兑现证据 ${兑现统计.总数} 条全部待核(引用不可定位), 不能当证据用`);
  } else {
    满足.push(`兑现证据 ${兑现统计.可用}/${兑现统计.总数} 条可定位`);
  }

  // "关键反转"的判定: 有幕后真相、有目标窗口、或内容较长 —— 这类不能只凭一条证据就引爆
  const 是关键反转 = !!String(伏笔条.幕后真相 ?? '').trim() || !!伏笔条.目标窗口 || String(伏笔条.内容 ?? '').length > 简单伏笔字数阈值;
  if (是关键反转) {
    const 推进可用 = 证据统计([...埋设, ...回响]).可用;
    if (推进可用 === 0) {
      拒绝原因.push('关键反转缺少埋设/回响证据: 至少要有 1 条早期线索能在回看时解释它(禁止临时编造动机)');
    } else {
      满足.push(`关键反转另有 ${推进可用} 条埋设/回响证据`);
    }
  } else {
    满足.push('短篇简单伏笔: 放宽为"兑现证据可定位"即可');
  }

  if (埋设统计.总数 > 0 && 埋设统计.可用 === 0) {
    拒绝原因.push(`埋设证据 ${埋设统计.总数} 条全部待核: 这条伏笔没有可回溯的根, 先补证再兑现`);
  } else if (埋设统计.总数 === 0) {
    // 老账本(v1.0 之前)没有证据链: 不因此拒绝(否则所有旧伏笔永远收不了), 但记进"满足"里说明
    满足.push('老账本无埋设证据(迁移前形态): 不因此拒绝, 但计入审计的"无证埋设"');
  } else {
    满足.push(`埋设证据 ${埋设统计.可用}/${埋设统计.总数} 条可定位`);
  }

  return { 可引爆: 拒绝原因.length === 0, 拒绝原因, 满足 };
}

