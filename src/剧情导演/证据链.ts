export interface 命运冲突 {
  角色ID: string;
  类别: '已死亡仍行动' | '已离场未回归' | '关系破裂未处理' | '无证据状态';
  说明: string;
}

/**
 * 命运约束预检: 找出账本里**自相矛盾**的命运条目。
 *
 * 它只报"账本内部就不成立"的情况(例如状态是死亡却没有任何状态证据), 不去猜正文 ——
 * 正文层面的"死者又活了"由 校验() 在应用候选之前拦(见 账本数据.ts 的 预检候选)。
 */
export function 取命运冲突(账本: 导演账本): 命运冲突[] {
  const out: 命运冲突[] = [];
  for (const 命 of 账本.角色命运 ?? []) {
    if (!String(命.角色ID ?? '').trim()) continue;
    const 证据 = 证据统计(命.状态证据);
    if (命.状态 !== '活跃' && 证据.总数 === 0) {
      out.push({
        角色ID: 命.角色ID,
        类别: '无证据状态',
        说明: `状态为「${命.状态}」却没有任何状态证据: 不可逆状态必须有正文证据, 否则不得写入`,
      });
      continue;
    }
    if (命.状态 !== '活跃' && 证据.可用 === 0) {
      out.push({
        角色ID: 命.角色ID,
        类别: '无证据状态',
        说明: `状态为「${命.状态}」的 ${证据.总数} 条证据全部待核: 先补证, 不得据此约束后续剧情`,
      });
    }
  }
  return out;
}

/** 取某个角色的命运(按稳定 ID; 找不到给 null) */
export function 取命运(账本: 导演账本, 角色ID: string): 角色命运 | null {
  const key = String(角色ID ?? '').trim();
  if (!key) return null;
  return (账本.角色命运 ?? []).find(项 => 项.角色ID === key) ?? null;
}

/**
 * 角色此刻能不能**作为活人在场**行动。
 * 死亡: 不能(回忆/记录/幻觉/设定内复活属显式例外, 必须新记账);
 * 离开/失踪: 不能无回归事件回到原场景。
 * 返回 null = 可以行动; 否则给出拦截原因(可观察的拒绝路径)。
 */
export function 拦截行动(账本: 导演账本, 角色ID: string): string | null {
  const 命 = 取命运(账本, 角色ID);
  if (!命) return null;
  if (命.状态 === '死亡') {
    return `${角色ID} 已死亡: 不得作为活人行动(回忆/记录/幻觉/设定内复活属显式例外, 需新记账且不抹掉死亡后果)`;
  }
  if (命.状态 === '离开' || 命.状态 === '失踪') {
    return `${角色ID} 处于「${命.状态}」: 不得无回归事件就回到原场景`;
  }
  return null;
}

