// 剧情导演 · 角色知识边界(材料层)
// ---------------------------------------------------------------------------
// 症状(用户报告): 导演是全知的(书纲/幕后真相/整本账本), 角色不是 —— 于是出现
//   "角色 A 汇报了一件 A 没参与、也没听说的事"。
//
// 分工(2026-11-06 定): **判断不给代码**。同一件事有无数种说法("汇报/知会/提了一嘴/顺口说了"),
// 关键词查不出来; 硬拦还会把本来正确的必演一起丢掉。所以:
//   - 语义判断 → 导演自己写「知情核对」那一步(见 schema.知情核对条 / prompts 的自查规则);
//   - 代码只做材料: 把 <cb> 拆成"谁不知道什么", 在该被看见的地方原样贴上
//     (镜头外推进块里那个 NPC 自己的清单)。
//
// 早期版本这里有一个 检查全知() 的关键词闸门, 已按用户要求删除 —— 留个说明, 免得后人再加回来。
import type { 导演账本 } from './schema';

/** 名册: 角色 → 他不知道的事(原句) */
export type 不知情表 = Map<string, string[]>;

/**
 * 从记忆插件的 `<cb>` 正文解析出名册: 角色 → 他不知道的事(原句, 一个字不裁)。
 * 格式: 每行 `【角色】不知道 A…，不能确认 B…` —— 行内按逗号切成一条一条。
 * 解析不出的直接跳过: 读不到不等于清白, 只是这一层帮不上忙。
 */
export function 解析不知情(信息边界: string): 不知情表 {
  const 表: 不知情表 = new Map();
  for (const 行 of String(信息边界 ?? '').split('\n')) {
    const 匹配 = 行.match(/^【([^】]{1,24})】\s*(.+)$/);
    if (!匹配) continue;
    const 角色 = 匹配[1].trim();
    const 句们 = 匹配[2]
      .split(/[，,。；;]/)
      .map(句 => 句.trim())
      .filter(句 => 句.length >= 3);
    if (句们.length === 0) continue;
    const 已有 = 表.get(角色);
    if (已有) 已有.push(...句们);
    else 表.set(角色, 句们);
  }
  return 表;
}

/** 名册里这个人的清单: 先按整名, 再按去掉括注的主干名(写法常是「Lim（旅人）」) */
export function 取不知情说法(表: 不知情表 | undefined, 角色ID: string): string[] {
  if (!表) return [];
  const 人 = String(角色ID ?? '').trim();
  if (!人) return [];
  const 直 = 表.get(人);
  if (直) return 直;
  const 主干 = 人.replace(/[（(][^）)]*[）)]/g, '').trim();
  if (!主干) return [];
  for (const [键, 值] of 表) {
    const 键主干 = 键.replace(/[（(][^）)]*[）)]/g, '').trim();
    if (键 === 主干 || 键主干 === 主干 || 键主干 === 人) return 值;
  }
  return [];
}


/**
 * 「证据去哪找」——自查要用到的**材料清单**，不替模型判断谁该知道什么。
 *
 * 用户问过(2026-11-06): 自查写"证据是什么", 可证据到底上哪儿找?
 * 插件里能当证据的就这几处, 按可靠程度排: 本轮正文 > 记忆纪要(带 AM 编号) > 账本自己的记录 > <cb>。
 * 所以这里把它们**摊开**给导演看, 并把"空着"这件事说出来(空 = 没有可查的已知事实, 不是清白)。
 */
export function 渲染证据来源(
  账本: Pick<导演账本, '角色命运' | '伏笔' | '读者领先'>,
  已召回?: Set<string>,
): string {
  const 行: string[] = [];
  行.push('【自查"这件事他知道吗" —— 证据去哪找】');
  行.push('按顺序找, 找到一条就够; 一条都没有 → 按「不知道」算, 不要编。');
  行.push('1. 本轮正文(上面最近的回复): 他本人说过、做过、在场吗?');
  行.push(
    `2. 记忆纪要里的 AM 条目(见上文): 哪一条写着他在场或被告知 —— 引用编号最有力${
      已召回 && 已召回.size > 0 ? `（本轮主 AI 已召回 ${已召回.size} 条）` : ''
    }。`,
  );
  const 事实 = (账本.角色命运 ?? [])
    .map(人 => ({ 名: String(人.角色ID ?? '').trim(), 条: (人.已知事实引用 ?? []).filter(Boolean) }))
    .filter(项 => 项.名);
  if (事实.length > 0) {
    const 有 = 事实.filter(项 => 项.条.length > 0);
    const 空着 = 事实.filter(项 => 项.条.length === 0).map(项 => 项.名);
    const 描述 = [
      有.length > 0
        ? 有
            .slice(0, 6)
            .map(项 => `${项.名} ${项.条.length} 条（${项.条.slice(0, 2).join('；')}）`)
            .join('；')
        : '',
      空着.length > 0
        ? `${空着.slice(0, 6).join('、')} 这一栏还空着（空 = 没记下"已知事实"，不等于清白）`
        : '',
    ]
      .filter(Boolean)
      .join('；');
    行.push(`3. 账本里你已经记下的「角色命运.已知事实引用」: ${描述}`);
  }
  const 知情 = (账本.伏笔 ?? [])
    .filter(条 => (条.知情角色 ?? []).length > 0)
    .slice(0, 3);
  if (知情.length > 0) {
    行.push(`   伏笔.知情角色（谁已经知道这条线的真相）: ${知情.map(条 => `#${条.编号} ${(条.知情角色 ?? []).join('、')}`).join('；')}`);
  }
  const 领先 = (账本.读者领先 ?? []).length;
  if (领先 > 0) 行.push(`   读者领先.哪些角色还不知道: 已经标明了 ${领先} 条（逐条看上面），那上面写的人就是"不知道"`);
  行.push('   前情: 这条线当初埋下时的公开摘要 —— 里面常写着谁在场、谁听见了。');
  行.push('4. <cb> 信息边界（这一轮有的话）: 直接写着谁不知道什么。有就以它为准; 没有也不能跳过前三步。');
  行.push('证据要写成**能回查**的东西: AM 编号 / 第几场 / 账本里哪一栏。写「他应该知道」「这么久了肯定听说了」不算证据。');
  return 行.join('\n');
}