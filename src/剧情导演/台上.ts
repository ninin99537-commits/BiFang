/** 判定顺序(测试与文档共用同一份, 别在别处再抄一遍闸名) */
export const 台上判定顺序: readonly string[] = 闸们.map(闸 => 闸.名);

/** 此刻台上是什么。纯函数: 不读宿主、不读 store、不拼文本。 */
export function 判定台上(输入: 台上输入): 台上结论 {
  for (const 闸 of 闸们) {
    if (闸.命中(输入)) return { 种类: 闸.种类, 原因: 闸.原因, 说明: 闸.说明(输入), 短原因: 闸.短原因 ?? '' };
  }
  return { 种类: '下令', 原因: '', 说明: '', 短原因: '' };
}

/** 默认输入: 什么都没挡着(用例与"只想改一个开关"的调用方用) */
export function 空台上输入(): 台上输入 {
  return {
    启用导演: true,
    已剧终: false,
    群聊: false,
    自动接管: true,
    暂停注入: false,
    待决死亡: false,
    平静模式: false,
    引擎暂停: false,
    有指令: true,
    指令已跳过: false,
    平静前作废: false,
    平静场数: 0,
  };
}
