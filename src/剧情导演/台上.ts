// 剧情导演 · 台上判定(2026-11-12 架构深化 ④)
// ---------------------------------------------------------------------------
// 起因: 「这一轮到底下不下令」原本有五份抄本 ——
//   · 注入层 `应注入的指令文本`(7 道闸, 是事实上的权威)
//   · `index.ts` 的 暂停注入(群聊 + 待决死亡)
//   · `update.ts` 里另一份 暂停注入(新死亡)
//   · 面板的 `指令预览`(只查了 平静 / 平静刚结束 **两道**)
//   · 球状态 `计算运行状态`(14 项输入)
// 后果是真机可见的: **熔断期面板摊开一整段本幕指令, 而正文一个字节都拿不到** ——
// 面板上那句"这一场要演什么"是一条不会发生的命令。同文件里早就记过一次同类事故
// ("状态条说离线、指令预览说冷启动"), 那次修好了症状, 没修掉"同一个判断抄五份"这件事。
//
// 这个模块只做一件事: **给出此刻台上是什么**。它不读宿主、不读 store、不拼文本 ——
// 输入是一组布尔量, 输出是一个结论。注入层、面板、球都读同一份结论, 谁也不许再自己数一遍闸。
//
// 闸的顺序是**语义**, 不是实现细节(测试按这个顺序钉):
//   总开关 → 已剧终 → 群聊 → 自动接管 → 暂停/待决死亡 → 平静 → 熔断 → 无指令/已跳过 → 平静前作废 → 下令
// 为什么是这个序(逐条都有理由, 见下面每道闸的注释), 挪动任何一条都会改变真机行为。

/** 台上此刻的种类 */
export type 台上种类 =
  /** 正常下令: 注入本幕指令 */
  | '下令'
  /** 只出红线块: 撤掉的是"这一场要演什么", 不是用户钉死的「不许写什么」 */
  | '只红线'
  /** 什么都不出 */
  | '空';

export interface 台上结论 {
  种类: 台上种类;
  /** 机器可读的原因标识(空串 = 下单) —— 面板/球/日志按它分支, 不要按文案分支 */
  原因: string;
  /** 给用户看的一句话(下令时为空)。面板与球共用这一句, 不许各写一份 */
  说明: string;
  /**
   * 短原因: 塞进注入文本的括号里那一小句(`（${短原因}，只有这些约束仍然有效）`)。
   * 与 `说明` 分开: 前者进提示词, 后者进界面 —— 同一个事实两种语域, 但都来自这张表。
   */
  短原因: string;
}

/**
 * 判定所需的全部事实。**刻意不是一个"账本 + 设置"的大对象**:
 * 那样调用方仍要知道"里面哪几个字段算数", 接口就和实现一样宽了。
 */
export interface 台上输入 {
  /** 设置.启用导演 —— 总开关, 压过一切 */
  启用导演: boolean;
  /** 账本.已剧终 —— 剧终后连红线也不再往上下文里塞 */
  已剧终: boolean;
  /** 宿主: 当前聊天是不是群聊 */
  群聊: boolean;
  /** 设置.导演.自动接管 —— 关 = 用户说"别管了", 压过平静模式(否则"完全撒手"会被红线块悄悄打破) */
  自动接管: boolean;
  /** 调用方算出的"这一刻暂停注入"(待决死亡 / 本轮检测到新死亡) */
  暂停注入: boolean;
  /** 账本.待决死亡(与 暂停注入 同口径, 分开是为了让调用方不必知道这个等价关系) */
  待决死亡: boolean;
  /** 设置.导演.平静模式 */
  平静模式: boolean;
  /** 熔断: 引擎已自动暂停推进 */
  引擎暂停: boolean;
  /** 账本里有没有当前指令 */
  有指令: boolean;
  /** 当前指令被「跳过本幕」作废 */
  指令已跳过: boolean;
  /** 平静刚结束: 手上那道是平静前的旧编排, 一场都没下发过 */
  平静前作废: boolean;
  /** 平静场数(只用于说明文案, 不参与判定) */
  平静场数?: number;
}

interface 闸 {
  /** 名字(测试与文档用) */
  名: string;
  命中: (输入: 台上输入) => boolean;
  种类: Exclude<台上种类, '下令'>;
  /** 机器可读原因 */
  原因: string;
  说明: (输入: 台上输入) => string;
  /** 只在 只红线 时有意义: 注入块括号里那一小句 */
  短原因?: string;
}

