// 剧情导演 · 悬浮球状态机: 把"外部编剧此刻在干什么"变成**不用打开面板也看得见**的主通道。
//
// 用户原话(2026-10-07): "插件没弹窗, 我不知道什么时候更新、什么时候更新完了、什么时候更新出错了,
// 我还要进插件里看。" —— 提示条设施本来是好的(成功/失败会弹), 缺的是**常驻通道**:
//   **状态用球(常驻、安静), 事件用条(短暂、可关)**。提示条 8 秒就消失, 而"上次失败了"这件事应当一直可见。
// 规格: docs/剧情导演-可观测性-提示条规格-v1.md §3。
//
// 这里是**纯函数**(不碰平台、不碰 Vue): 五态优先级是本轮最容易写错的地方, 必须能脱离酒馆单测。
// 球的呈现见 悬浮球界面.vue 的 `.dj-orb[data-态=…]`(环画在球内, 直径与层序不变)。

import { 熔断阈值 } from './快照';
import { 熔断冷却毫秒 } from './运行状态';

/** 五态(优先级从高到低就是这个顺序) */
export const 球状态列表 = ['剧终', '离线', '出错', '编排中', '待命'] as const;
export type 球状态 = (typeof 球状态列表)[number];

export interface 球状态输入 {
  /** 账本.已剧终: 剧终后引擎整体停摆 */
  已剧终: boolean;
  /** 熔断: 连败达阈值 → 自动暂停自动接管(比单次失败更重, 所以压过"出错") */
  自动暂停: boolean;
  /** 连败次数 > 0 = 上次推进失败且还没成功过(存在 chat meta, 不在账本快照里) */
  连败次数: number;
  /** 引擎调用进行中(pinia `updatingStore.active`, 面板与球同一份) */
  编排中: boolean;
}

/**
 * 优先级 **剧终 > 离线 > 出错 > 编排中 > 待命**(规格钉死)。
 *
 * `出错` 压在 `编排中` 之上是**有意**的: 用户点「重新推进」时, 红环继续显示"上次失败",
 * 直到**下一次成功**才清 —— 否则一按按钮红环就变成呼吸, 失败线索又被藏回面板里(正是用户抱怨的那件事)。
 */
export function 计算球状态(输入: 球状态输入): 球状态 {
  return 计算运行状态({
    已剧终: 输入.已剧终,
    自动暂停: 输入.自动暂停,
    连败次数: 输入.连败次数,
    最后失败原因: '',
    最后失败时间: 0,
    已分析轮数: 0,
    接管轮数: 0,
    锚点楼层: -1,
    引擎调用次数: 0,
    编排中: 输入.编排中,
  }).球态;
}

// ---------------------------------------------------------------------------
// 运行状态: 面板顶部那条状态条与悬浮球的五态, 是**同一条阶梯**
// ---------------------------------------------------------------------------
// 以前是两条: 状态条的判断写在 悬浮球界面.vue 的 computed 里(五个分支, 只能用字符串断言验),
// 球状态是这里的纯函数(242 行用例钉住)。输入几乎相同, 却只有后者可测 ——
// README v1.2 D 记的正是这两处曾经互相矛盾。现在一个结果, 两个消费者。

export type 运行级别 = 'stop' | 'over' | 'off' | 'warn' | 'calm' | 'cold' | 'on';

export interface 运行状态输入 {
  /** 设置.启用导演 === false(总开关关): 压过一切 —— 关了还显示"运行中"会让人以为在跑 */
  已停用?: boolean;
  /**
   * 设置.导演.平静模式(2026-11-08): 只记账不下令。
   * 它压过冷启动 —— 平静期本来就不下令, 再显示"再攒 N 轮"只会让人以为哪里坏了。
   */
  平静?: boolean;
  /** 已经平静了多少场(纯显示) */
  平静场数?: number;
  /** 设置.导演.自动接管: 平静 + 这个也关着时, 连记账都要手点, 文案要说清 */
  自动接管?: boolean;
  /** 账本.已剧终: 剧终后引擎整体停摆 */
  已剧终: boolean;
  /** 熔断: 连败达阈值 → 自动暂停自动接管 */
  自动暂停: boolean;
  连败次数: number;
  最后失败原因: string;
  /** 最后一次失败的时间戳(0/负数 = 未知) */
  最后失败时间: number;
  已分析轮数: number;
  /** 接管轮数: 前 N-1 轮只记账不编排 */
  接管轮数: number;
  锚点楼层: number;
  引擎调用次数: number;
  /** 引擎调用进行中(pinia `updatingStore.active`) */
  编排中: boolean;
}

export interface 运行状态 {
  级别: 运行级别;
  标题: string;
  明细: string;
  /** 与状态条同一个结果: 悬浮球只读这一项, 不再自己算一遍 */
  球态: 球状态;
}

/** 时间戳 → 一句人话(0/负数 = 未知) */
function 时间文本(时间戳: number): string {
  return 时间戳 > 0 ? new Date(时间戳).toLocaleTimeString() : '时间未知';
}

/**
 * 唯一的运行状态阶梯: **剧终 > 离线(自动暂停) > 离线(连败) > 冷启动 > 运行中**。
 * 离线/剧终必须压过冷启动 —— R0 的教训就是冷启动把故障伪装成了正常特性。
 */
export function 计算运行状态(输入: 运行状态输入): 运行状态 {
  const 空转球态: 球状态 = 输入.编排中 ? '编排中' : '待命';
  if (输入.已停用) {
    return {
      级别: 'stop',
      标题: '导演已停用',
      明细: '总开关关着：不调引擎、不注入，正文 AI 看不到任何导演内容。到「设置」页最上面打开。',
      球态: '离线',
    };
  }
  if (输入.已剧终) {
    return {
      级别: 'over',
      标题: '已剧终',
      明细: '剧终结算后自动路径整体停摆：不调引擎、不注入。想继续请点下方「清除已剧终」。',
      球态: '剧终',
    };
  }
  if (输入.自动暂停) {
    // 冷却重试(2026-11-08): 让用户知道"不用永远等人来点按钮"
    const 上次 = Number(输入.最后失败时间) || 0;
    const 剩余毫秒 = 上次 > 0 ? 熔断冷却毫秒 - (Date.now() - 上次) : 0;
    const 冷却 =
      上次 <= 0
        ? '下一条正文会先试一次'
        : 剩余毫秒 > 0
          ? `约 ${Math.max(1, Math.ceil(剩余毫秒 / 60000))} 分钟后自动再试一次（点上方「恢复自动接管」可立刻恢复）`
          : '已到冷却点，下一条正文会先试一次';
    return {
      级别: 'off',
      标题: '引擎离线（已自动暂停）',
      明细:
        `上次失败原因：${输入.最后失败原因 || '未知'}（${时间文本(输入.最后失败时间)}）· 连败 ${输入.连败次数}/${熔断阈值} 次 · ${冷却}` +
        // 平静模式也开着时要说一句: 否则用户会以为"平静模式坏了"(它确实因为引擎停了而不记账)
        (输入.平静 ? '。平静模式仍开着：恢复后继续只记账、不下令' : ''),
      球态: '离线',
    };
  }
  if (输入.连败次数 > 0) {
    return {
      级别: 'warn',
      标题: '引擎离线（链路不稳）',
      明细: `上次失败原因：${输入.最后失败原因 || '未知'}（${时间文本(输入.最后失败时间)}）· 连败 ${输入.连败次数}/${熔断阈值} 次`,
      球态: '出错',
    };
  }
  if (输入.平静) {
    const 场 = Math.max(0, Number(输入.平静场数) || 0);
    const 楼 = 输入.锚点楼层 >= 0 ? `#${输入.锚点楼层}` : '—';
    // 自动接管也关着时, 连"记账"都不会自动发生 —— 不说清楚会让人以为账在涨
    const 兜底 = 输入.自动接管 === false ? '（「自动接管」也关着：连记账都要手点「重新推进」）' : '';
    return {
      级别: 'calm',
      标题: '平静中 · 只记账不下令',
      明细: `已平静 ${场} 场 · 上次记账 ${楼} 楼${兜底}。正文 AI 拿不到本幕指令，只从「编剧备忘」看到公开后果；红线仍然有效。关掉开关就回到跌宕起伏。`,
      球态: 空转球态,
    };
  }
  if (输入.已分析轮数 < 输入.接管轮数) {
    return {
      级别: 'cold',
      标题: '冷启动攒轮',
      明细: `第 ${输入.已分析轮数}/${输入.接管轮数 - 1} 轮 · 第 ${输入.接管轮数} 轮起编排本幕`,
      球态: 空转球态,
    };
  }
  const 楼 = 输入.锚点楼层;
  return {
    级别: 'on',
    标题: '运行中',
    明细: `上次编排成功于 #${楼 >= 0 ? 楼 : '—'} 楼 · 已调用引擎 ${输入.引擎调用次数} 次`,
    球态: 空转球态,
  };
}

export interface 球悬停细节 {
  最后失败原因?: string;
  连败次数?: number;
  /** 熔断阈值(默认 3), 只用于文案 */
  熔断阈值?: number;
  上次节拍?: string;
  /** 距上次成功编排多少分钟; 未知给 undefined, 负数表示"还没成功过" */
  上次成功分钟前?: number;
  接管轮数?: number;
  已分析轮数?: number;
  /** 第二轮方案 5.3: 当前章号 / 幕号 / 本幕是否有必演事件 */
  章号?: number;
  幕号?: number;
  有必演?: boolean;
  /** 平静模式(2026-11-08): 只记账不下令 */
  平静?: boolean;
  平静场数?: number;
}

/**
 * hover 文案: 一眼说清"为什么是这个态"、以及**下一步去哪儿**。
 * 用原生 `title`, 不新开弹层(规格 §3 明确要求)。
 */
export function 球悬停文案(状态: 球状态, 细节: 球悬停细节 = {}): string {
  switch (状态) {
    case '剧终':
      return '剧情导演：已剧终（不调引擎、不注入）——想继续请在面板里点「清除已剧终」';
    case '离线':
      return `剧情导演：引擎已自动暂停（连败 ${细节.连败次数 ?? 0}/${细节.熔断阈值 ?? 3} 次：${细节.最后失败原因 || '原因未知'}）——面板可「恢复自动接管」`;
    case '出错':
      return `剧情导演：上次编排失败（${细节.最后失败原因 || '原因未知'}）——红环保持到下次成功`;
    case '编排中':
      // 平静期调引擎只是为了记账, 说"编排本幕"会让人以为马上要下令
      return 细节.平静 ? '剧情导演：正在记账…（平静模式，不下令）' : '剧情导演：正在编排本幕…';
    default: {
      if (细节.平静) {
        return `剧情导演：平静中（只记账、不下令，已 ${Math.max(0, Number(细节.平静场数) || 0)} 场）——想回到跌宕起伏就把设置里的「平静模式」关掉`;
      }
      const 轮数 = 细节.接管轮数 ?? 0;
      const 已读 = 细节.已分析轮数 ?? 0;
      if (轮数 > 1 && 已读 < 轮数) return `剧情导演：冷启动记账中（第 ${已读}/${轮数 - 1} 轮，第 ${轮数} 轮起编排本幕）`;
      const 最近 = 细节.上次节拍 ? `最近：本幕节拍=${细节.上次节拍}` : '最近：还没编排过本幕';
      const 分钟 = 细节.上次成功分钟前;
      const 尾 = typeof 分钟 === 'number' && 分钟 >= 0 ? ` · ${Math.round(分钟)} 分钟前` : '';
      // 第二轮方案 5.3: 有章回时把"演到哪了"放最前(第3章 · 第2幕), 不打开面板也知道进度
      const 章幕 = 细节.章号 ? `第${细节.章号}章${细节.幕号 ? ` · 第${细节.幕号}幕` : ''} · ` : '';
      const 必演 = 细节.有必演 ? ' · 本幕有确定事件' : '';
      return `剧情导演：待命 · ${章幕}${最近}${尾}${必演}`;
    }
  }
}
