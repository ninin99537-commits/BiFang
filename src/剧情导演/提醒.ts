export function 按组裁决(命中: { 规则: 提醒规则; 行: string[] }[]): string[] {
  const 组内胜者 = new Map<string, 提醒规则>();
  for (const { 规则 } of 命中) {
    if (!规则.组) continue;
    const 现有 = 组内胜者.get(规则.组);
    if (!现有 || (规则.优先级 ?? 0) > (现有.优先级 ?? 0)) 组内胜者.set(规则.组, 规则);
  }
  return 命中
    .filter(({ 规则 }) => !规则.组 || 组内胜者.get(规则.组) === 规则)
    .flatMap(({ 行 }) => 行);
}

export function 结构提醒(账本: 导演账本, 当前幕: number, 阈值?: { 高?: number; 低?: number }): string[] {
  // 2026-11-13 批 C: 阈值三层贯通（settings → 取料 → 结构提醒 → 上下文 → 节奏提醒）。
  // 不传 = 老行为（退回默认常量），既有用例零变化。
  const 上下文: 提醒上下文 = { 当前幕, 阈值 };
  const 命中: { 规则: 提醒规则; 行: string[] }[] = [];
  for (const 规则 of 提醒规则表) {
    const 行 = 规则.生成(账本, 上下文);
    if (行.length > 0) 命中.push({ 规则, 行 });
  }
  return 按组裁决(命中);
}

/** 矛盾悬了多少场就提醒"对方会主动行动" */
export const 矛盾久悬阈值 = 6;

/**
 * 矛盾久悬(第二轮方案 2.7): "恋爱对象从不离开"的根源是对方没有自己的目标、也从不主动。
 * 代码只数事实(哪段未解矛盾悬了几场), 让对方怎么动由导演决定。最多提 2 段。
 */
export function 矛盾久悬提醒(账本: 导演账本, 当前场: number): string[] {
  const 悬: { 谁: string; 对方: string; 矛盾: string; 场: number; 目标: string }[] = [];
  for (const 命 of 账本.角色命运 ?? []) {
    if (命.状态 === '死亡') continue;
    for (const 关 of 命.当前关系 ?? []) {
      const 矛盾 = String(关?.未解矛盾 ?? '').trim();
      const 起 = Number(关?.矛盾起始场) || 0;
      if (!矛盾 || !起) continue;
      const 场 = 当前场 - 起;
      if (场 >= 矛盾久悬阈值) 悬.push({ 谁: 命.角色ID, 对方: 关.对方ID, 矛盾, 场, 目标: (命.独立目标 ?? []).join('；') });
    }
  }
  if (悬.length === 0) return [];
  return 悬
    .sort((a, b) => b.场 - a.场)
    .slice(0, 2)
    .map(
      项 =>
        `${项.谁} 与 ${项.对方} 的矛盾「${项.矛盾}」已经悬了 ${项.场} 场没人处理 —— ${项.谁}不会一直等着被哄: ` +
        `按 ta 自己的目标(${项.目标 || '命运册里还没写, 请补上'})主动行动(摊牌 / 做出选择 / 离开), 不一定是主角希望的方向。`,
    );
}

/** 反转同招(第二轮方案 2.8): 最近 3 次反转里有重复类型 → 提醒换一招 */
export function 反转重复提醒(账本: 导演账本): string[] {
  const 近 = (账本.反转记录 ?? []).slice(-3).map(项 => 项.类型);
  if (近.length < 2) return [];
  const 计数 = new Map<string, number>();
  for (const 类 of 近) 计数.set(类, (计数.get(类) ?? 0) + 1);
  const 重复 = [...计数.entries()].filter(([, n]) => n >= 2).map(([类]) => 类);
  if (重复.length === 0) return [];
  return [`最近 ${近.length} 次反转里「${重复.join('、')}」用了不止一次(最近: ${近.join(' → ')}) —— 下一次反转换一种类型。`];
}

/** 回响间隔(场): 中线 / 长线多少场没露面就提醒一次; 短线不提醒(本章内自然会碰到) */
export const 回响间隔 = { 中: 10, 长: 15 } as const;
/** 章长度提醒阈值(场) */
export const 章长度阈值 = 40;

/**
 * 回响提醒(第二轮方案 2.2, 三次法则: 埋 → 回响 → 兑现)。
 * 只数事实: 某条中/长线已经 N 场没露面。怎么回响(换个表面形式让它出现一次)由导演决定。
 * 每轮最多提 2 条(最久的), 免得提醒淹没本幕。
 */
export function 回响提醒(账本: 导演账本, 当前场: number): string[] {
  const 候选 = (账本.伏笔 ?? [])
    .filter(是未结束伏笔)
    .map(条 => {
      const 跨度 = 条.书纲ID ? '长' : (条.跨度 ?? '中');
      if (跨度 === '短') return null;
      const 基准 = Math.max(Number(条.最后回响场) || 0, Number(条.埋设场) || 0);
      if (!基准) return null; // 老账本没有场号: 不猜(下一轮合并时会补上)
      const 隔 = 当前场 - 基准;
      return 隔 >= 回响间隔[跨度] ? { 条, 隔, 跨度 } : null;
    })
    .filter((x): x is { 条: (typeof 账本.伏笔)[number]; 隔: number; 跨度: '中' | '长' } => !!x)
    .sort((a, b) => b.隔 - a.隔)
    .slice(0, 2);
  if (候选.length === 0) return [];
  return [
    `这些${候选.some(x => x.跨度 === '长') ? '长线' : ''}伏笔已经很久没露面: ${候选
      .map(x => `#${x.条.编号}「${x.条.公开线头 || x.条.内容}」(${x.隔} 场${x.条.书纲ID ? `, 挂 ${x.条.书纲ID}` : ''})`)
      .join('；')} —— ` +
      '可以安排一次**轻回响**: 让同一个物件/同一句话/同一个人名换个场合出现一次, 不推进、不揭示; 演出来后记进「中间回响」。不合适就延后, 不要硬塞。',
  ];
}

/**
 * 一条伏笔的「中间回响」超过这个条数就算病态(2026-11-12)。
 *
 * 为什么是 6: 三次法则(埋 → 回响 → 兑现)里回响只是中间那一步, 一条中/短线通常 1~3 条就够;
 * 长线按章算, 一章 2~3 条也够了。真机数据: 有一条伏笔堆到 **53 条**, 平均每 1.0 场一条 ——
 * 那不是回响, 是日记, 而且它每轮都被当成"该读的旧证据"整条调档(52 条完整纪要 / 41,796 字)。
 */
export const 回响条数告警 = 6;

/**
 * 回响配额提醒(2026-11-12): 某条线的回响已经堆到不正常的条数时, 把事实摆回给导演。
 *
 * 代码**不删**任何一条回响(证据是内容), 只负责说清两件事:
 *   ① 什么才算"一条回响"(换个表面形式/换人/换场合; 同一件事在同一情境里反复提不算);
 *   ② 堆到这个条数说明这条线该兑现了, 不是该继续记日记。
 * 最多提 2 条(最病态的), 免得提醒本身变成噪音。
 */
export function 回响配额提醒(账本: 导演账本): string[] {
  const 超 = (账本.伏笔 ?? [])
    .filter(是未结束伏笔)
    .map(条 => ({ 条, 条数: (条.中间回响 ?? []).length }))
    .filter(项 => 项.条数 >= 回响条数告警)
    .sort((a, b) => b.条数 - a.条数)
    .slice(0, 2);
  if (超.length === 0) return [];
  return [
    `这些线的「中间回响」已经堆得太多: ${超.map(项 => `#${项.条.编号}(${项.条数} 条)`).join('；')} —— ` +
      '**不要再往上追加了**。「回响」只有换了一种表面形式、换了人、或换了场合再出现才算一条; ' +
      '同一件事在同一情境下被反复提及(同一个人反复抱怨同一个症状、同一场里说两遍)**不算新回响**。' +
      '堆到这个条数说明这条线该兑现了 —— 或者该写「已消亡」并给原因, 而不是继续记日记。',
  ];
}

/**
 * 兑现条件自检(2026-11-12): 条件写着却没人核对, 这条线就会永远停在「发酵」。
 *
 * 真机例子: 某条伏笔的兑现条件是「在医疗站完成晨尿试纸检测确认结果」, 而那一场(AM0272)
 * **早就演过了**(两道红杠确诊早孕) —— 账本却没兑现, 于是之后 25 场每场又记一条回响。
 * 代码判不了"正文里这件事算不算发生了"(那要语义), 只能把条件原文 + 它最近的回响摆到
 * 导演面前, 让它自己对照。只对**临期**的线说(待兑现 / 窗口已开), 且最多 2 条。
 *
 * 判"临期"时**不看催办节流**(`最近催办章`): 那是对"该演了"的节流, 而这条是**记账核对**。
 * 早先版本借用了 `取到期伏笔`, 于是同一章催过一次之后, 这条自检整章都不再出现 —— 正好在本该
 * 核对的时候失声(2026-11-12 自查发现)。
 */
export function 兑现条件提醒(账本: 导演账本): string[] {
  const 当前章 = Number(账本.章回?.章号) || 0;
  const 候选项 = (账本.伏笔 ?? [])
    .filter(是未结束伏笔)
    .map(条 => ({ 条, 窗口: 评估窗口(条, 当前章) }))
    .filter(项 => 项.条.状态 === '待兑现' || 项.窗口.状态 === '可催办' || 项.窗口.状态 === '已过最迟')
    .map(项 => ({
      条: 项.条,
      条件: (项.条.兑现条件 ?? []).map(x => String(x ?? '').trim()).filter(Boolean),
      // 最近 3 条回响就在账本里, 摆出来它才看得见"这件事其实已经发生了"
      最近: [...(项.条.中间回响 ?? [])]
        .sort((a, b) => (Number(a.楼层) || 0) - (Number(b.楼层) || 0))
        .slice(-3)
        .map(证 => `${String(证.记忆引用 ?? '').trim() || `第 ${证.楼层} 楼`}「${String(证.公开摘要 ?? '').trim()}」`),
    }))
    .filter(项 => 项.条件.length > 0)
    .slice(0, 2);
  if (候选项.length === 0) return [];
  return [
    `**先核对兑现条件是不是已经发生了**: ${候选项
      .map(项 => `#${项.条.编号}「${项.条件.join('；')}」`)
      .join('；')} —— ` +
      '已经发生过的, 就当场兑现(**可以直接引用当初那条 AM 作为兑现证据**, 不必重演一遍); 还没发生的, 安排这一幕去做, 或把条件改写成更准确的那一句。' +
      '条件写着从不核对, 这条线会永远卡在「发酵」, 每一场还在往上叠回响。',
    `判定依据: 这条线最近几次露面是 ${候选项
      .map(项 => `#${项.条.编号}${项.最近.length > 0 ? ` → ${项.最近.join(' / ')}` : '(还没有回响)'}`)
      .join('；')} —— 如果上面已经出现了"条件被满足"的那一刻, 那就是它该兑现的地方。`,
  ];
}

/**
 * 账本页的伏笔时间轴(优化 6): 埋在第几场、最后一次露面、隔了多久、到没到回响线。
 * 与 回响提醒 同一口径(书纲ID → 长线; 基准 = max(埋设场, 最后回响场)), 面板不另算一套。
 * 老账本没有场号 → null(面板不画)。
 */
export function 伏笔时间轴(条: 伏笔, 当前场: number): {
  跨度: '短' | '中' | '长';
  埋设场: number;
  最后回响场: number;
  隔: number;
  回响线: number | null;
  该回响: boolean;
  /** 进度条: 隔 / 回响线(短线按 10 场画), 0~100 */
  比例: number;
} | null {
  const 埋设场 = Number(条.埋设场) || 0;
  if (!埋设场) return null;
  const 跨度 = 条.书纲ID ? '长' : (条.跨度 ?? '中');
  const 最后回响场 = Number(条.最后回响场) || 0;
  const 隔 = Math.max(0, 当前场 - Math.max(埋设场, 最后回响场));
  const 回响线 = 跨度 === '短' ? null : 回响间隔[跨度];
  return {
    跨度,
    埋设场,
    最后回响场,
    隔,
    回响线,
    该回响: 回响线 !== null && 隔 >= 回响线 && 是未结束伏笔(条),
    比例: Math.min(100, Math.round((隔 / (回响线 ?? 10)) * 100)),
  };
}

/**
 * 章长度提醒(第二轮方案 2.9): 伏笔窗口按章锚定, 导演一直不收章, 所有「最早章」都永远不会到。
 *
 * 2026-11-12 P0.7: 这个函数以前在 `进度 === '收束'` 时**直接 return** ——
 * 也就是说它恰好在"该收章"的那一刻闭嘴（唯一的例外是"早就该收"）。真机上 78 场不出章,
 * 它一声没响。现在分三种状态说话:
 *   · 推进中 → 整章超 `章长度阈值` 就提醒"该进收束了";
 *   · 收束中 → 按**收束预算**计量("收束已 N 场 / 预算 8"), 用尽就催收章;
 *   · 已完结 → 每轮催"开新章"(章号 +1、重写幕纲), 直到它滚起来。
 *     最后这条是"代码只关不开"的必要配套: 关由代码做, 开只能由模型做, 但**不许它悄悄不做**。
 */
export function 章长度提醒(账本: 导演账本, 当前场: number): string[] {
  const 章回 = 账本.章回;
  if (!章回) return [];
  // 已完结: 这一章已经关了, 现在缺的是"开下一章" —— 章不滚动, 伏笔窗口就永远不到
  if (章回.进度 === '已完结') {
    return [
      `第 ${章回.章号} 章已完结, 但还没有下一章: **下一步要开新章** —— 章号 +1、进度回「铺垫」, ` +
        `写主题 / 计划高潮 / 幕纲(3~5 幕)。章不滚动, 伏笔的「最早章 / 最迟章」就永远不会到。`,
    ];
  }
  const 起 = Number(章回.起始场) || 0;
  if (!起) return [];
  // 2026-11-12 口径统一: **必须 +1** —— 起始场本身就算第一场。
  // 以前这里写 `当前场 - 起`，而 `判收章`/`收束已用场数` 都是 `… + 1`：
  // 起始场=1、当前场=41 时一个说 41 场、一个说 40 场。后果是**推进态**的阈值晚判一场、文案少 1
  // （真机: 第 41 场才提醒"已经演了 40 场"）。收束态走 `收束已用场数()`，本来就是对的。
  // 2026-11-14（kimi 复查 #516）：收拢到 本章已演场数 —— 原先这里自己写 `当前场 - 起 + 1`（不判 >=）。
  // ⚠️ 唯一行为差异：`当前场` 为 NaN 时原来会一路走到「已经演了 NaN 场」，现在按 0 处理 → 直接返回 []。
  const 长 = 本章已演场数(账本, 当前场);
  // 收束中: 换成"收束段预算"口径。没有起始场(老账本/本轮刚进)就不猜, 下一轮 账本数据 会补上
  if (章回.进度 === '收束') {
    const 收束已用 = 收束已用场数(账本, 当前场);
    if (!收束已用) return [];
    if (收束已用 < 收束预算场) return [];
    return [
      `第 ${章回.章号} 章已进入「收束」${收束已用} 场(预算 ${收束预算场}), 整章 ${长} 场 —— **该收章了**: ` +
        `让本章的计划高潮落地、把该收的线收掉, 然后开下一章(章号 +1、进度回「铺垫」、重写幕纲)。` +
        `停在收束里不出章, 整章会一直重复同一种节奏。`,
    ];
  }
  if (长 < 章长度阈值) return [];
  // 2026-11-12 P0.8 复验: 本章已经超期时, "该收章"这件事由 `幕纲落后或该收章` 说（它更具体：
  // 会说清第几幕/推不动了）。本条在这时候闭嘴, 否则同一句"该收章"会说两遍。
  if (选收章发言者(账本, 当前场) === '幕纲落后') return [];
  return [`第 ${章回.章号} 章已经演了 ${长} 场还没进入收束 —— 请评估是否推进到本章高潮并收章(伏笔窗口按章计, 章不结束, 长伏笔就永远等不到窗口)。`];
}

/**
 * 节奏提醒(2026-10-29 P1 第二段): 只数节拍, 不判断好坏。
 *
 * 三个可数事实:
 *   ① 连着几幕停在高点(高潮/兑现) → 该给余波与代价;
 *   ② 连着几幕低张力 → 该给真正的压力;
 *   ③ 最近 6 幕里没有低谷(受挫/阴影) → 这一章还缺一次"全线崩塌"。
 * 外加两个落点: 中点该有反转、结局前一幕该有崩塌 —— 只有写了幕纲才算得出来。
 */
export function 节奏提醒(账本: 导演账本, 当前幕?: number, 阈值?: { 高?: number; 低?: number }): string[] {
  const out: string[] = [];
  const 节拍 = 账本.张力?.最近节拍 ?? [];
  const 尾连续 = (集合: string[]) => {
    let n = 0;
    for (let i = 节拍.length - 1; i >= 0 && 集合.includes(节拍[i]); i--) n += 1;
    return n;
  };
  /**
   * D-4(2026-11-13): 与引擎同一套判据。
   *
   * 以前这里用 `['高潮','兑现伏笔']` + 阈值 2，引擎用 `高张力节拍`（受挫/反转/兑现/高潮）+ 阈值 3 ——
   * 后果: `受挫×3` 引擎强制余波、提醒**一声不响**; `高潮×2` 提醒喊"别再堆高潮"、引擎认为还没到阈值。
   * 现在两处共用 `高张力节拍` 与 `连续高阈值默认`（都从既有常量导入，不写字面量）。
   */
  // 2026-11-13 批 C: 阈值从上下文来（老调用点不传 → 退回默认常量，行为零变化）
  const 高阈 = Number.isFinite(Number(阈值?.高)) ? Number(阈值?.高) : 连续高阈值默认;
  const 低阈 = Number.isFinite(Number(阈值?.低)) ? Number(阈值?.低) : 连续低阈值默认;
  const 连高 = 尾连续(高张力节拍 as unknown as string[]);
  if (连高 >= 高阈) {
    out.push(`已经连续 ${连高} 场停在高点(受挫/反转/兑现/高潮都算高张力) —— 这一幕请给余波与代价, 不要继续往上堆。`);
  }
  const 连低 = Math.max(0, Number(账本.张力?.连续低张力) || 0);
  if (连低 >= 低阈) {
    // 2026-11-12: 措辞不许再说"这一场" —— 有了「日常」之后, 这一场完全可以是空的。
    // 2026-11-12(续) 去掉那句豁免"若这一幕就是「日常」那就留着, 别硬塞":
    //   那句话把这条提醒变成了**许可**。真机上 `连续低张力` 在开始日常之后会**冻结**
    //   (日常是中性: 既不 +1 也不清零), 于是它每轮都喊"已经连续 54 场低张力", 又每轮都
    //   自己给自己开门 —— 一条永远在响、永远不用管的提醒, 等于没有。
    //   现在它只陈述事实并给出落点: 压力该落在**下一场事件幕**上(而不是"这一场必须来事",
    //   那样会和「日常」的契约打架)。空场不算压力, 这一点也写清楚。
    const 尾日常 = 尾部同节拍(节拍);
    const 空场 = 尾日常 && 尾日常.节拍 === '日常' ? 尾日常.场数 : 0;
    out.push(
      `已经连续 ${连低} 场低张力 —— 也就是 ${连低} 场没有真正的压力(小胜/阴影/余波都算喘气, 空着的「日常」更不算压力` +
        `${空场 > 0 ? `; 这中间还有 ${空场} 场是空的` : ''}) —— ` +
        `**下一场事件幕**必须来一次真正的压力: 让对手先动手、让代价落地、让计划失败, 三选一。` +
        `再空下去, 这一章就没有"值得失去的东西"可言了。`,
    );
  }
  const 近六 = 节拍.slice(-6);
  if (近六.length >= 4 && !近六.some(x => x === '受挫' || x === '阴影')) {
    out.push('这一章还没有真正的低谷 —— 需要一次"全线崩塌"(失去、失败、被夺走), 别让主线一路平推。');
  }
  const 幕纲 = 账本.章回?.幕纲 ?? [];
  const 总幕 = 幕纲.length;
  const 当前幕号 = Number(账本.章回?.当前幕号) || 0;
  // 有章回却没有幕纲(2026-11-12 自查): 幕纲是整章的骨架, 没有它「幕型」「中点」「幕号落后」
  // 三套机制一起失效 —— 而且不会有人告诉你。所以先催骨架本身。
  if (账本.章回 && 总幕 === 0) {
    out.push(
      '这一章还没有「幕纲」: 补 3~5 幕, 每幕一行 `第N幕｜类型: 事件/生活/收束｜目标:…｜障碍:…｜转折:…｜代价:…｜结束条件:…`。' +
        '没有幕纲, 整章只能靠"下一场该演什么"临时想 —— 那正是节奏忽紧忽松的根源。',
    );
  }
  // 节拍是戏剧功能单位, 不是楼层: 同一个节拍拖太久也该提醒
  // 中点(2026-11-12): 以前这里靠"幕号 === ceil(总幕/2)"猜, 猜不到就漏 —— 现在有 章回.中点 这个
  // 显式锚点(类型/内容/过了), 由下面的 中点提醒 负责; 这里只留"结局前全线崩塌"。
  if (总幕 >= 3 && 当前幕号 === 总幕 - 1 && !节拍.slice(-3).some(x => x === '受挫' || x === '阴影')) {
    out.push('进入结局前需要一个**全线崩塌**: 让主角先失去最重要的东西, 再进最后一幕。');
  }
  // 节拍拖太久(2026-11-12 修): 以前数 `当前节拍.已持续轮`, 而那个计数**只在模型写 `节拍结束: false`
  // 时才 +1**; 真机上模型几乎每轮都写 `节拍结束: true`, 于是计数每轮重置成 1 —— 这条提醒从上线起
  // 一次都没触发过(真机数据: 连续 6 场日常, 已持续轮 显示 2)。
  // 现在直接数「最近节拍」尾部连续值: 那份历史**每轮都会追加一格**(节拍结束 true 时), 不受那个计数器影响。
  const 拖 = 尾部同节拍(节拍);
  // 2026-11-12 P0.8: 本章已经该收了的时候，本条**整条让位**（收章语义由 选收章发言者() 指定的人说）。
  // 2026-11-12 P0.9: 还有一个小窗口 —— **未超期、未收束** 但"日常久空"：
  //   那时 判收章().该收=false，本条会照常喊"该让它有事发生了"，而 生活幕 同时授权"什么都没发生是对的"。
  //   生活幕 + 5 场日常 就是这个对撞（真机实测）。
  //   裁定：让 `生活幕` 那条改口去说（它还保得住幕型信息），本条在**当前幕是生活幕**时让位。
  //   二选一只能留一句 —— 两句都在就等于没改（需求方 2026-11-12）。
  const 日常生活幕 = 拖?.节拍 === '日常' && 是生活幕(账本);
  if (拖 && 拖.场数 >= 节拍拖太久阈值 && !判收章(账本, 当前幕).该收 && !日常生活幕) {
    out.push(
      `最近 ${拖.场数} 场都是「${拖.节拍}」—— 同一个节拍拖成流水账就该推进: 要么给它一次转折, 要么换一个节拍。` +
        (拖.节拍 === '日常'
          ? '「日常」是"允许空着", 不是"必须一直空着"; 连着几场空过之后, 该让它有事发生了。'
          : ''),
    );
  }
  return out;
}

/** 同一个节拍连续多少场就该催换(数「最近节拍」的尾部连续值) */
export const 节拍拖太久阈值 = 5;

/** 「最近节拍」尾部连续相同的那一段 → { 节拍, 场数 }; 空史返回 null */
export function 尾部同节拍(节拍: string[]): { 节拍: string; 场数: number } | null {
  if (!节拍 || 节拍.length === 0) return null;
  const 末 = 节拍[节拍.length - 1];
  let 场数 = 0;
  for (let i = 节拍.length - 1; i >= 0 && 节拍[i] === 末; i--) 场数 += 1;
  return { 节拍: 末, 场数 };
}

/* ---------------------------------------------------------------------------
 * P0 可观测性（2026-11-13）：面板要显示的「世界过了几天 / 本章演了多久」。
 *
 * 三个函数放在同一个地方，因为它们是**同一件事的三面**：天数是故事时间、
 * 场数是代码的计量单位 —— 两者会背离（40 场可能只过半天，也可能过 40 天）。
 * ------------------------------------------------------------------------- */

/**
 * 面板/提醒共用的「故事内已过去几天」（**取整**）。
 *
 * 真机 天数 = 67.32200000000002（每轮加小数、浮点累加误差），裸插值上屏就是那一串原文；
 * 而 提醒 早就在用 Math.round。面板若自己再写一份，又是一条「同一事实两份格式化」。
 *
 * ⚠️ 只用于「天数本身」；「两个天数之差」仍用原值相减再取整（对手提醒里的 隔天），语义不同。
 */
export function 世界时间天数(账本: 导演账本): number {
  return Math.max(0, Math.round(Number(账本.世界时间?.天数) || 0));
}

/**
 * 「本章已演多少场」（**整章口径**，基点 = 章回.起始场，含 +1）。
 *
 * 收拢 判收章 / 本章进度文本 / 章长度提醒 三处 —— 它们原来各写一遍
 * `当前场 - 起 + 1`。**不含 收束已用场数**：那个基点是 `收束起始场` 且多一道
 * Math.max(1,…) 夹取，是「收束段」场数，与整章不是同一个量。
 *
 * ⚠️ 2026-11-14 之前这句是**假话**：只有 本章进度文本 真的调了它，
 * 判收章 / 章长度提醒 各自留着一份字面算式（kimi 复查 #516 抓出）。现已真收拢，
 * 硬证据：删掉本函数里的 `+ 1` → 判收章 / 章长度提醒 / 面板 **三处同时红**。
 */
export function 本章已演场数(账本: 导演账本, 当前场: number): number {
  const 起 = Number(账本.章回?.起始场) || 0;
  return 起 > 0 && 当前场 >= 起 ? 当前场 - 起 + 1 : 0;
}

/**
 * 面板要显示的「本章演到哪」——算式与 章长度提醒 / 收束预算 同源。
 *
 * @returns null = 缺 `起始场`（此时面板不显示，不能显示 0 或负数）
 *
 * ⚠️ A 方案（2026-11-13）：收束态但 `收束起始场` 缺失时（真机 113 份快照全缺），
 * 收束段场数不可知 —— **不能显示「收束已用 0/8」**，那是假话（这一章可能已经演了 78 场）。
 * 退回整章口径，宁可显示真的「78 场」。
 */
export function 本章进度文本(账本: 导演账本, 当前场: number): string | null {
  const 起 = Number(账本.章回?.起始场) || 0;
  if (!起) return null;
  // 2026-11-14（kimi 复查 #516）：`已演 === 0` 时也不许显示。
  // 脏数据（当前场号回退到起始场之前）下原实现会说「本章已演 0 场」—— 而这一章明明演过东西，
  // 只是场号回退了。0 场是假话，宁可整行不显示。
  // ⚠️ 当前场 === 起始场 时 已演 = 1，不受影响（仍是「本章已演 1 场」）。
  const 已演 = 本章已演场数(账本, 当前场);
  if (已演 <= 0) return null;
  if (账本.章回?.进度 === '收束') {
    const 收束已用 = 收束已用场数(账本, 当前场);
    if (收束已用 > 0) return `收束已用 ${收束已用}/${收束预算场} 场`;
    return `本章已演 ${已演} 场（收束中）`;
  }
  return `本章已演 ${已演} 场`;
}
