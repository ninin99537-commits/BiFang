/**
 * 「这一章是不是已经该收了」—— **三处共用的一份判据**（2026-11-12 P0.8 提醒互斥）。
 *
 * 为什么抽函数：「生活幕」（授权"可以空"）、「幕纲落后或该收章」（裁决"该收了"）、
 * 「节奏·日常拖太久」（催"别空着"）三条各自都合理，但**授权能盖住裁决**。真机第 68 场：
 * 进度=推进、幕号 4/4（最后一幕是生活幕），同一轮里三声齐发 ——
 *   · 生活幕：「节拍优先选日常……这一场什么都没发生是对的」
 *   · 该收章：「让本章的计划高潮落地」
 *   · 日常拖太久：「该让它有事发生了」
 * 模型选了顺的那条，连演 11 场日常、到第 78 场没出章。
 *
 * 判据只有一句：**这一章演太久了吗**。
 *   ① 进度已「收束」/「已完结」 → 该收；
 *   ② 或 `演了几场 > 幕纲.length × 3` → 该收（这就是「幕纲落后」原本在用的那条）。
 * P0.7 只堵了 ①，理由是"怕误伤最后一幕的正当喘息"—— 那个判断在**演 3 场**时对，在**演 68 场**时错。
 * 所以判据换成**场数**，不是幕号: 喘息可以，一直喘息不行。
 *
 * 三处必须调这同一个函数：各算一遍就会出现"一个说超期、一个说没超期"（需求方 2026-11-12 裁定 §四-1）。
 */
export interface 收章判据 {
  /** 有效幕号(夹在 1..幕纲数; 无幕纲时为 0) */
  有效幕号: number;
  幕纲数: number;
  /** 本章演了几场(从 起始场 起算; 老账本没有起始场 → 0) */
  演了几场: number;
  收束: boolean;
  已完结: boolean;
  /** 只由场数触发的那一半(用于措辞:"本来是生活幕, 但本章演太久了") */
  超期: boolean;
  /** 该不要再授权"空着": 收束 或 已完结 或 超期 */
  该收: boolean;
}

/**
 * 收章判据。
 *
 * `当前场`（2026-11-13 D-2）: 提醒侧以前固定读 `账本.已分析轮数`，而引擎侧（`引擎规则`）
 * 用的是 **+1 之后**的场号（`update.ts` 先 +1 再构造指令）—— 同一轮里两个「收束已用」差 1，
 * 于是「已进入收束 N 场(预算 8)」这句话**永远不会出现**。
 * 现在接受外部传入的场号；不传就退回旧口径（老调用点行为不变）。
 */
export function 判收章(账本: 导演账本, 当前场?: number): 收章判据 {
  const 章回 = 账本.章回;
  const 幕纲 = 章回?.幕纲 ?? [];
  const 幕纲数 = 幕纲.length;
  const 有效幕号 = 幕纲数 === 0 ? 0 : Math.min(Math.max(1, Number(章回?.当前幕号) || 1), 幕纲数);
  const 现 = Number.isFinite(Number(当前场)) && Number(当前场) > 0 ? Number(当前场) : Number(账本.已分析轮数) || 0;
  // 2026-11-14（kimi 复查 #516）：这里原来是自己写一遍 `现 - 起始场 + 1`。
  // 注释说「收拢三处」，实际只收拢了 本章进度文本 —— 今天两份算式恰好逐字相同所以看不出来，
  // 但任何一处改 +1 或守卫，面板与收章判定就会分叉。现在真收拢。
  const 演了几场 = 本章已演场数(账本, 现);
  const 收束 = 章回?.进度 === '收束';
  const 已完结 = 章回?.进度 === '已完结';
  /**
   * D-3(2026-11-13): 超期阈值取 `max(幕纲数*3, 章长度阈值)`。
   *
   * 原来是 `幕纲数 * 3` 判超期，而提示词要求幕纲 3~5 幕 → 5 幕时第 16 场就算超期；
   * 于是「超期」先成立 → 选收章发言者 变成 `幕纲落后` → `章长度` 的 40 场那句
   * （`:689`「已经演了 N 场还没进入收束」）**在幕纲 ≤13 时永远不可达**。
   * 加上 章长度阈值 这一项，40 场那条才真的能出现；没有调小任何阈值（产品判断不动）。
   */
  const 超期 = 幕纲数 > 0 && 演了几场 > Math.max(幕纲数 * 3, 章长度阈值);
  return { 有效幕号, 幕纲数, 演了几场, 收束, 已完结, 超期, 该收: 收束 || 已完结 || 超期 };
}

/**
 * 「收章语义」这一轮由谁说话（2026-11-12 P0.8 复验产物）。
 *
 * 需求方复验抓到三处残留：超期态里「计划高潮落地」说了 3 次（生活幕里一次、幕纲落后一次、
 * 日常拖太久一次），收束态里「该收章」说了 3 次，已完结态还在喊"让计划高潮落地"——而那一章已经收完了。
 * **三句话说的是同一件事，三种措辞**；导演读到的是"三个人都在催我收章"，而它只需要读到一次。
 *
 * 所以不是"三条各自判断要不要响"，而是**先选一个发言者，其余闭嘴**：
 *   已完结 → `章长度`(说"开新章")；收束中 → `章长度`(说收束预算)；超期 → `幕纲落后或该收章`。
 * 注意「生活幕让位」**不是**发言者 —— 它解释的是"为什么幕型不生效", 不是催收章, 所以它可以说。
 */
export type 收章发言者 = '章长度·开新章' | '章长度·收束预算' | '幕纲落后' | '无';

/** 收束段已经演了几场（`收束起始场` 缺失 → 0 = 不判，老账本不猜） */
export function 收束已用场数(账本: 导演账本, 当前场?: number): number {
  const 起 = Number(账本.章回?.收束起始场) || 0;
  if (!起) return 0;
  const 现 = Number.isFinite(Number(当前场)) && Number(当前场) > 0 ? Number(当前场) : Number(账本.已分析轮数) || 0;
  return Math.max(1, 现 - 起 + 1);
}

export function 选收章发言者(账本: 导演账本, 当前场?: number): 收章发言者 {
  const 判 = 判收章(账本, 当前场);
  if (判.已完结) return '章长度·开新章';
  if (判.收束) {
    // 收束预算还没用完 → `章长度` 无话可说（它只在预算用尽时开口）。
    // 这时候**不能就没人说话**：老账本没有 `收束起始场`（真机 113 份快照全缺），
    // 否则第 69~78 场会变成"三条都让位、一条都不响"—— 比重复投递更糟。
    // 所以让 `幕纲落后` 兜底（它说的是"幕号推不动了，该收章"，仍然只有**一条**在说）。
    if (收束已用场数(账本, 当前场) >= 收束预算场) return '章长度·收束预算';
    return 判.超期 ? '幕纲落后' : '无';
  }
  if (判.超期) return '幕纲落后';
  return '无';
}

/** 中点到期了吗（2026-11-12：生活幕让位要用同一份判据，别在生活幕里再写一遍幕号算术） */
export function 判中点到期(账本: 导演账本): { 到期: boolean; 中点: any; 有效幕号: number; 幕纲数: number } {
  const 幕纲 = 账本.章回?.幕纲 ?? [];
  const 幕纲数 = 幕纲.length;
  const 有效幕号 = 幕纲数 === 0 ? 0 : Math.min(Math.max(1, Number(账本.章回?.当前幕号) || 1), 幕纲数);
  const 中点 = 账本.章回?.中点;
  const 到期 = !!(中点 && String(中点.内容 ?? '').trim() && !中点.过了 && 有效幕号 >= Math.ceil(幕纲数 / 2));
  return { 到期, 中点, 有效幕号, 幕纲数 };
}

