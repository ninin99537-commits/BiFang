// 「留白」判据（2026-11-13 P1 高位·紧凑）
//
// 病根：用户说"剧情太紧凑"——每一场都在推进正事，没有闲笔。技术来源是：
//   「日常」是唯一允许"什么都不发生"的节拍，但 rule1/rule4 会在连续高张力或高潮后
//   把它强制改成「余波/阴影」（两者都带一件事），**越需要喘气越被推着来一件事**。
//
// 所以要有**一份**判据回答"这一幕要不要留白"，引擎与提醒共用 —— 分开写就会漂
// （今天已经抓到过一次：提醒层有条件、写入层无条件）。
//
// 为什么住在 字段表 而不是 提醒：这里是纯判据层，引擎与提醒**都**已在 import 它。
// 放进 提醒 会让 引擎 → 提醒 形成反向依赖（P5 拆分的依赖方向用例正是防这个）。
// ---------------------------------------------------------------------------

/** 当前这一幕是不是"生活幕"（幕纲当前幕号那一行标着 `类型: 生活`） */
export function 是生活幕(账本: 导演账本 | null | undefined): boolean {
  const 幕纲 = 账本?.章回?.幕纲 ?? [];
  if (幕纲.length === 0) return false;
  const 号 = Math.min(Math.max(1, Number(账本?.章回?.当前幕号) || 1), 幕纲.length);
  return /类型\s*[:：]\s*生活/.test(幕纲[号 - 1] ?? '');
}

/**
 * 「这一幕要不要留白」—— **唯一判据**，四条路径共用（引擎三处豁免 + 提醒一处 + 写入层）。
 *
 * 腿① 幕纲标了「类型: 生活」（作者上一轮的规划）
 * 腿② 导演本幕原拟节拍是「日常」（这一轮的明示）
 *
 * 两者是 **OR**：任一成立就要留白。⚠️ 测试必须每条腿各来一次"只有它为真"——
 * 两条腿同时为真的用例会让"只实现了一条腿"照样绿（2026-11-13 定）。
 *
 * 口径：幕纲没标类型 **不等于** 留白，只是腿① 不成立，仍要看腿②；
 * 所以老账本（幕纲多半没标）行为零变化。
 */
export function 要留白(账本: 导演账本 | null | undefined, 导演节拍?: string | null): boolean {
  if (是生活幕(账本)) return true;
  return String(导演节拍 ?? '').trim() === '日常';
}
