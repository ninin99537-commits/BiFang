// 对手主动性(2026-11-12 节奏修订): "谁该出手"只能有**一个**答案
// ---------------------------------------------------------------------------
/**
 * 一轮最多催**一个**对手出手。
 *
 * 用户的体感是"打完一个又来一个、一堆杂兵"。查下来有两个 3 幕节律在叠着推: 张力曲线(二值, 没有"零")
 * + 这条"对手 N 幕没动手就必须动手"。而旧实现是**一次催全部逾期冲突** —— 一轮塞三个对手出手,
 * 正文只能写成一串遭遇战; 且多是强度 3 的小麻烦(主线推不动就塞小的)。
 *
 * 现在的口径:
 *   ① 只在**会出手**的阶段催(升级/僵持/决战)。铺垫阶段催动手 = 提前引爆主线; 收束阶段该收尾。
 *   ② **杂兵不催**: 强度 ≤ 3 且没有任何未收档伏笔挂在它名下 —— 那种冲突本来就该自己淡掉。
 *   ③ 间隔 5 幕(原 3 幕): 有了"日常"这一幕之后, 连着几场没动手是正常的。
 *   ④ 一次只催**最逾期的一条**, 且引擎记账与导演提醒共用同一个选择 —— 两边各算一遍就会出现
 *      "提醒点名 A、账本记到 B"。
 */
export const 对手行动间隔幕 = 5;
/** 这些阶段才谈得上"对手主动出手" */
export const 会出手的阶段: 冲突阶段[] = ['升级', '僵持', '决战'];
/** 强度到这个数以下, 且没有伏笔挂着 → 视为杂兵 */
const 杂兵强度上限 = 3;

/**
 * 收束段预算（场）—— 2026-11-12 P0.7 收束出口。
 *
 * 进了「收束」之后最多再演这么多场，然后**由代码**把章回进度写成「已完结」。
 * 它是**保护性上限，不是目标值**：模型通常在 1~3 场就收完；触发这个数说明它卡住了。
 *
 * 为什么是 8：
 *  ① 它不是整章阈值。`章长度阈值 = 40`（取料.ts）管的是"整章太长"，管不了"收束了多久"；
 *    拿 40 当收束预算等于允许章长走到 109 场 —— 真机就是 78 场不出章。
 *  ② **收束段不该长过一幕。** 真机 78 场 / 5 幕 ≈ 15.6 场每幕，收束按戏剧惯例占最后一幕，
 *    所以预算必须 < 15.6。8 ≈ 半幕多一点：够演"高潮落地 + 代价 + 余味"，又不至于拖出第二条主线。
 *  ③ `40 / 5 = 8` 与"半幕"两个口径同时落在 8 附近 —— 可解释，不玄学。
 *  ④ 上界的意义：最坏情况下"连续日常"只烧 8 场（真机烧了 10+ 场、整章 78 场）。
 *
 * 取值区间 5~12 都合理；改成别的值之前先看一眼上面第 ② 条。
 */
export const 收束预算场 = 8;

/** 这条冲突的对手现在该主动出手吗(纯判断, 不管排序) */
export function 该催对手行动(条: 冲突, 账本: Pick<导演账本, '伏笔'>, 当前幕: number): boolean {
  if (!条 || 条.阶段 === '已收档') return false;
  if (!会出手的阶段.includes(条.阶段)) return false;
  const 逾期 = 当前幕 - (Number(条.最后行动幕) || 0);
  if (逾期 < 对手行动间隔幕) return false;
  // 强度缺失(规范化后是 0)不当杂兵: "不知道多强"不等于"小麻烦", 宁可让它被催一次
  const 强度 = Number(条.强度) || 0;
  if (强度 > 杂兵强度上限 || 强度 === 0) return true;
  // 强度低, 但有未收档的伏笔挂在它名下 → 它不是杂兵(那条线要靠它兑现)
  const 名 = String(条.名 ?? '').trim();
  return (账本.伏笔 ?? []).some(项 => !是终态.伏笔(项) && String(项.关联冲突 ?? '').trim() === 名);
}

/** 这一轮**唯一**该出手的对手(最逾期的; 同逾期按名字稳定排序); 没有 → null */
export function 取该出手的对手(账本: 导演账本, 当前幕: number): 冲突 | null {
  const 逾期 = (条: 冲突) => 当前幕 - (Number(条.最后行动幕) || 0);
  const 候选 = (账本.冲突 ?? []).filter(条 => 该催对手行动(条, 账本, 当前幕));
  if (候选.length === 0) return null;
  return [...候选].sort((a, b) => 逾期(b) - 逾期(a) || String(a.名 ?? '').localeCompare(String(b.名 ?? '')))[0];
}

/** 规范化字符串数组(内容型: 只 trim 掉空项, 不裁条目、不裁字) */
function 规范化文本数组(raw: any): string[] {
  if (raw === undefined || raw === null || raw === '') return [];
  const 列表 = Array.isArray(raw) ? raw : [raw];
  // 只做"去空 + 去重"; **不裁条目、不裁字**(2026-11-11: 条目数上限也取消了)
  return [...new Set(列表.map(项 => String(项 ?? '').trim()).filter(项 => 项 !== ''))];
}

/** 规范化一个自由对象(保留全部键; 值为字符串的 trim, 不裁字) */
function 规范化对象(raw: any): any {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return null;
  const out: Record<string, any> = {};
  for (const [键, 值] of Object.entries(raw)) {
    if (值 === undefined || 值 === null) continue;
    if (Array.isArray(值)) out[键] = 规范化对象数组(值);
    else if (typeof 值 === 'object') out[键] = 规范化对象(值);
    else if (typeof 值 === 'number') out[键] = 值;
    else out[键] = String(值);
  }
  return Object.keys(out).length > 0 ? out : null;
}

/** 规范化对象数组(关系[]/状态历史[] 这类) */
function 规范化对象数组(raw: any): any[] {
  if (!Array.isArray(raw)) return [];
  const out: any[] = [];
  for (const 项 of raw) {
    const 规范 = 规范化对象(项);
    if (规范) out.push(规范);
  }
  return out;
}

/** 规范化一条条目: **一个字段都不裁**(零截断), 只 trim + 枚举校验 + 兜底
 *
 * 2026-11-12 P0.95「字段级漏写保护」—— 这里是整个漏洞的所在地，也是修复点：
 *
 * 以前它对每个字段**无条件赋值**：`raw?.[键]` 取不到就写兜底（枚举给 `字段.兜底`、数组给 `[]`、
 * 对象给 `null`、文本给 `''`）。于是"模型没写这个字段"和"模型写了空值"在**同一个表达式里被合并**，
 * 代码永远分不出来。后果是真机上 17 个字段被静默清空（`回收窗口`/`知情角色`/`目标窗口`/`强度`/
 * `顶回次数`/`弧线.阶段`…），而 `拒绝` 里一条都没提——因为代码根本不知道发生过什么。
 *
 * 现在的三态：
 *   ① **缺席**（`raw` 里没这个键 / 值是 `undefined` / 枚举字段给空串）→ **沿用旧值**（`旧` 给了就用它）；
 *   ② **显式空值**（`''` / `[]` / `null`，且不是枚举）→ **真的清空** ——
 *      这是模型表达"这件事结束了"的唯一方式，一律沿旧值会让它再也没法清空；
 *   ③ **有值** → 照常规范化。
 *
 * ⚠️ 为什么用"传 `旧`"而不是全局默认：每个调用点**必须显式**决定"这条要不要沿用旧值"。
 *    给默认值会让"我忘了改这个调用点"变成静默行为 —— 而这一批修的正是静默行为。
 */
export function 规范化条目<T extends Record<string, any>>(
  定义: 账本层定义,
  raw: Record<string, any>,
  旧?: Record<string, any>,
  沿用出参?: string[],
): T {
  const out: Record<string, any> = {};
  for (const 字段 of 定义.字段) {
    const 有键 = !!raw && typeof raw === 'object' && Object.prototype.hasOwnProperty.call(raw, 字段.键);
    const value = 有键 ? raw[字段.键] : undefined;
    // 枚举字段的"空串/空值"算**缺席**：空串不是合法枚举值，走兜底会造成**状态机倒退**
    // （真机: 弧线「低谷」→「初始」、伏笔「发酵」→「埋下」，而且不可逆 —— 下一轮写回原值也没用）。
    const 枚举空 = !!字段.枚举 && (value === '' || value === null);
    const 缺席 = !有键 || value === undefined || 枚举空;
    if (缺席) {
      const 旧值 = 旧 ? 旧[字段.键] : undefined;
      if (旧 && 旧值 !== undefined) {
        out[字段.键] = 旧值;
        // 只在"旧值本身有内容"时记录 —— 否则每个可选空字段（兑现证据/消亡原因/延期到章…）
        // 都会报一条"沿用"，真正的信号（模型系统性漏了某类字段）就被噪音淹没了。
        const 有内容 = Array.isArray(旧值) ? 旧值.length > 0 : typeof 旧值 === 'object' ? 旧值 !== null : String(旧值 ?? '').trim() !== '';
        if (沿用出参 && 有内容) 沿用出参.push(字段.键);
        continue; // 沿用旧值：连"空值本身是合法状态"的字段也保持旧样
      }
      // 没有旧值（新条目 / 快照还原）→ 落到下面的兜底，与旧行为一致
    }
    // 形状优先: 嵌套结构不能被当成标量拍平(那会静默损坏数据)
    switch (字段.形状) {
      case '数字': {
        const n = Number(value);
        out[字段.键] = Number.isFinite(n) ? n : 0;
        continue;
      }
      case '证据数组':
        out[字段.键] = 规范化证据数组(value);
        continue;
      case '文本数组':
        out[字段.键] = 规范化文本数组(value);
        continue;
      case '对象':
        // 对象/对象数组: 由调用方决定空值是 null 还是 [](见各层的具体读取)
        out[字段.键] = Array.isArray(value) ? 规范化对象数组(value) : 规范化对象(value);
        continue;
      default:
        break;
    }
    if (字段.数值) {
      const n = Number(value);
      out[字段.键] = Number.isFinite(n) ? n : 0;
      continue;
    }
    let text = String(value ?? '');
    if (字段.属性 === '结构') {
      // 结构字段也**只 trim, 不切字** —— 切了之后面板按全名 find 会找不到那一条(静默失效)
      text = text.trim();
    }
    if (字段.枚举) {
      // 枚举校验: 命中即留; 未命中先按 归一 把老账本的自由文本映射进枚举; 再不行才走兜底
      const 归一后 = 字段.枚举.includes(text) ? text : 字段.归一 ? 字段.归一(text) : '';
      out[字段.键] = 字段.枚举.includes(归一后) ? 归一后 : (字段.兜底 ?? 字段.枚举[0]);
    } else {
      out[字段.键] = text;
    }
  }
  return out as T;
}

// ---------------------------------------------------------------------------
// 归档(阶段 A/B): 终态条目进历史档案, **未结束条目一条都不许丢**
// ---------------------------------------------------------------------------

export interface 归档结果<T> {
  /** 留在活跃工作集里的条目(未结束的 + 按工作集预算保留的终态) */
  活跃: T[];
  /** 移进历史档案的终态条目 */
  归档: T[];
  /** 因为超出**工作集候选容量**而没有进入活跃集、但也**没有被删除**的条目(仍在账本里) */
  超出工作集: T[];
}

/**
 * 按"活跃工作集 vs 历史档案"切分一层。
 *
 * 与旧的 `淘汰()` 的根本区别:
 *   - 旧实现 `while (out.length > 容量 + 1) out.shift()` 会**静默删除活动条目** —— 未结束伏笔
 *     就这样消失, 编号还在、内容没了(设计文档 §1 缺口 1 与 §5.3 明令禁止);
 *   - 现在**只归档终态**, 未结束条目全部留在 `活跃`(哪怕远超容量); 终态条目移进 `归档`
 *     (它们是"已了结的历史", 留着可回溯, 不占活动工作集)。
 * 返回值里三条都不丢: 调用方把 活跃 + 超出工作集 一起写回账本, 归档写进 历史档案。
 */
export function 归档终态<T extends Record<string, any>>(列表: T[], 定义: 账本层定义): 归档结果<T> {
  const 活跃: T[] = [];
  const 归档: T[] = [];
  for (const 条目 of 列表) {
    if (定义.终态(条目)) 归档.push(条目);
    else 活跃.push(条目);
  }
  return { 活跃, 归档, 超出工作集: [] };
}

/**
 * 兼容旧调用点的**淘汰**: 语义已改为"归档终态", 不再删除任何活动条目。
 * 保留这个名字是因为 账本数据.ts/账本迁移.ts 与既有用例都在用; 但**返回的列表永不因容量变短**
 * (历史档案的收纳由调用方通过 归档终态 显式完成)。
 */
export function 淘汰<T extends Record<string, any>>(列表: T[], 定义: 账本层定义): T[] {
  const { 活跃, 归档 } = 归档终态(列表, 定义);
  // 活动在前、归档在后: 与旧实现的"顺序保持"一致, 且一条都不少
  return [...活跃, ...归档];
}

