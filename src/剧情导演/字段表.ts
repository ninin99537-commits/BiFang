export type 字段属性 = '结构' | '内容';

/**
 * 字段的取值形状。默认 `文本`(标量与旧账本兼容)。
 * 加形状是因为阶段 A/B 引入了嵌套结构(证据引用[]/关系[]/窗口{}), 纯字符串规范化会把它们拍平成
 * `"[object Object]"` —— 那是**静默的数据损坏**, 比丢掉字段更糟。
 */
export type 字段形状 = '文本' | '数字' | '文本数组' | '证据数组' | '对象' | '命运状态';

export interface 字段定义 {
  键: string;
  属性: 字段属性;
  // 2026-11-11: 原来的「结构字段写入上限 / 数组条目数上限」两个格式守卫**已删掉**。
  // 理由: 它是**静默的**内容损失 —— 冲突名被切到 30 字之后, 面板按全名 `find` 就再也找不到那一条
  // (手改/状态修正静默失效); 条目名被切到 12 字, 导演看到的和账本里的就不是同一句话。
  // 现在账本、提示词、注入三处都是零截断; 有界保留只发生在**保留多少条**上(历史档案/最近 N 条),
  // 那不是"把一条切掉"。
  枚举?: readonly string[];
  兜底?: string;
  /**
   * 老账本迁移用: 值不在枚举内时先按此函数把自由文本归一(返回空串则走 兜底)。
   * 只在"写歪了的历史值"上生效 —— 新写入由提示词钉在枚举内(批次二 弧线终态枚举化)。
   */
  归一?: (文本: string) => string;
  /** 数值型(用 Number 规范化) */
  数值?: boolean;
  /** 取值形状(默认 文本) */
  形状?: 字段形状;
}

export interface 账本层定义 {
  名: string;
  /**
   * **活跃工作集**的候选容量: 只决定"单次发给模型多少条候选", 不再决定"账本里存多少条"。
   * 超出的条目由 归档终态 移进历史档案或保留在账本里, **绝不静默删除**(阶段 A/B 的核心修正)。
   */
  容量: number;
  /** 名称键: ''=条目无名字(伏笔按编号); 否则是该层用于对账的名字字段 */
  名称键: string;
  字段: 字段定义[];
  /** 终态判定(终态=可归档) */
  终态: (条目: Record<string, any>) => boolean;
}

