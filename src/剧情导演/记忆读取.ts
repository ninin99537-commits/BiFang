// ① 完整读蓝灯索引（目录给导演"发现新联系"）；② 按账本登记的 AM 直接调档绿灯纪要。
// 依赖 记忆检索 + 选证入口；不碰世界书/楼层（那是 取料.ts 的宿主侧编排）。
import type { Host } from './host';
import type { Settings, 导演账本, 记忆审计 } from './schema';
import { 建记忆检索器, 选证, 渲染索引块, 渲染纪要块, type 检索诊断 } from './记忆检索';
import { 收集必需引用, 导演申请 } from './选证入口';

// ---------------------------------------------------------------------------
// 记忆读取(两级)
// ---------------------------------------------------------------------------

export interface 记忆读取结果 {
  索引块: string;
  纪要块: string;
  审计: 记忆审计;
  已读引用: string[];
  选证理由: Record<string, string>;
  诊断: 检索诊断;
  /** 本轮真实解析出的索引项(纠偏: 校验导演「候选证据」申请用) */
  索引项: { 记忆引用: string; 时间跨度: string; 概览: string }[];
}

/**
 * 读这一轮的记忆: 先整篇读索引, 再按 AM 直接调档。
 *
 * **失败纪律**(实施提示词 §INSTRUCTION / §CONSTRAINT): 如果世界书读取或解析出了问题,
 * 审计里写明 `失败原因`, 待读队列与账本**原样保留** —— 绝不"静默删条目、截正文或减少证据后宣称成功"。
 */
export async function 读取记忆(
  host: Pick<Host, 'worldbook'>,
  账本: 导演账本,
  设置: Settings,
  楼层: number,
): Promise<记忆读取结果> {
  const 审计: 记忆审计 = {
    楼层,
    请求条数: 0,
    读到条数: 0,
    缺失: [],
    歧义: [],
    索引外: [],
    扫描书: [],
    索引条数: 0,
    纪要字数: 0,
    失败原因: '',
    时间: Date.now(),
  };
  // 设置「引擎读世界书」关闭时, 连记忆也不读(用户明确要求不读世界书)
  if (!设置.导演.读取世界书) {
    return {
      索引块: '',
      纪要块: '',
      审计,
      已读引用: [],
      选证理由: {},
      索引项: [],
      诊断: { 扫描书: [], 索引来源: [], 索引原文长度: 0, 索引条数: 0, 看过条目数: 0, 歧义引用: [], 无关键词条目: [], 读取失败: [] },
    };
  }

  const 检索器 = 建记忆检索器(host, { includeGlobal: 设置.导演.读取全局世界书 });
  let 索引项: { 记忆引用: string; 时间跨度: string; 概览: string }[] = [];
  let 诊断: 检索诊断 = { 扫描书: [], 索引来源: [], 索引原文长度: 0, 索引条数: 0, 看过条目数: 0, 歧义引用: [], 无关键词条目: [], 读取失败: [] };
  try {
    const 索引结果 = await 检索器.读当前索引();
    索引项 = 索引结果.索引;
    诊断 = 索引结果.诊断;
  } catch (error) {
    审计.失败原因 = `读取记忆索引失败: ${error instanceof Error ? error.message : String(error)}`;
  }

  const 选 = 选证({ 必需: 收集必需引用(账本, { 平静: !!设置.导演.平静模式 }), 导演申请: 导演申请(账本), 索引: 索引项 });
  审计.请求条数 = 选.引用.length;
  审计.扫描书 = 诊断.扫描书;
  审计.索引条数 = 索引项.length;
  审计.索引外 = 选.索引外申请;

  let 纪要结果: Awaited<ReturnType<typeof 检索器.按引用读取>> | null = null;
  if (选.引用.length > 0) {
    try {
      纪要结果 = await 检索器.按引用读取(选.引用);
    } catch (error) {
      审计.失败原因 = `按 AM 调档失败: ${error instanceof Error ? error.message : String(error)}`;
    }
  }

  if (纪要结果) {
    审计.读到条数 = 纪要结果.已找到.length;
    审计.缺失 = 纪要结果.缺失.map(项 => 项.引用);
    审计.歧义 = 纪要结果.诊断.歧义引用;
    // 零截断的规模证据: 实际发给导演的纪要正文总字数
    审计.纪要字数 = 纪要结果.已找到.reduce((s, 纪要) => s + 纪要.正文.length, 0);
  }
  // 纠偏 · 证据盖章: **只有本轮真的读到、且不是歧义**的引用才算"已核"。
  // 歧义(同一 AM 命中多条)一律不算 —— 代码层没解决唯一性之前, 模型挑一条不构成证明。
  const 歧义集 = new Set([
    ...(纪要结果?.诊断.歧义引用 ?? []),
    ...(纪要结果?.已找到 ?? []).filter(纪要 => (纪要结果?.诊断.歧义引用 ?? []).includes(纪要.记忆引用)).map(纪要 => 纪要.记忆引用),
  ]);
  const 已核引用 = [...new Set((纪要结果?.已找到 ?? []).map(纪要 => 纪要.记忆引用))].filter(ref => !歧义集.has(ref));
  // 索引与纪要都可能因为"世界书里根本没有"而为空 —— 那不是失败, 是"这个聊天没装记忆插件"
  if (诊断.扫描书.length === 0 && !审计.失败原因) {
    审计.失败原因 = '没有可扫描的世界书(角色卡未绑定世界书且无聊天世界书)';
  }

  return {
    索引块: 渲染索引块(索引项, 诊断),
    纪要块: 纪要结果 ? 渲染纪要块(纪要结果, 诊断) : '',
    审计,
    已读引用: 已核引用,
    索引项,
    选证理由: 选.理由,
    诊断,
  };
}

