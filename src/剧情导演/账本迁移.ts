function 规范化章回(raw: any): 章回 | null {
  if (!raw || typeof raw !== 'object') return null;
  const 条 = 规范化条目<章回>(取层('章回'), raw);
  // P1: 没写幕纲/当前幕号时不要留空壳(老账本与老用例保持逐字一致)
  if (!Array.isArray(条.幕纲) || 条.幕纲.length === 0) delete 条.幕纲;
  if (!Number(条.当前幕号)) delete 条.当前幕号;
  if (!Number(条.起始场)) delete 条.起始场;
  // 中点(2026-11-12): 同上 —— 没有内容就不留空壳, 老账本读回仍然逐字一致
  const 中点 = (条 as any).中点;
  const 中点内容 = 中点 && typeof 中点 === 'object' ? String(中点.内容 ?? '').trim() : '';
  if (!中点内容) delete (条 as any).中点;
  else {
    (条 as any).中点 = {
      类型: 中点.类型 === '假失败' ? '假失败' : '假胜利',
      内容: 中点内容,
      过了: !!中点.过了,
    };
  }
  return 条;
}

/**
 * 历史档案迁移: 老账本没有这个结构 → 给空档案。
 * **不回填**: v1.0 的终态条目当年就是被容量删掉的, 无从恢复; 伪造一份"归档"反而是编造历史。
 */
function 规范化历史档案(raw: any): 历史档案 {
  const 空 = 空历史档案();
  if (!raw || typeof raw !== 'object') return 空;
  const 伏笔列表 = Array.isArray(raw.伏笔) ? raw.伏笔.filter(Boolean).map((x: any) => 规范化条目<伏笔>(取层('伏笔'), x)) : [];
  const 冲突列表 = Array.isArray(raw.冲突) ? raw.冲突.filter(Boolean).map((x: any) => 规范化条目<冲突>(取层('冲突'), x)) : [];
  const 弧线列表 = Array.isArray(raw.弧线) ? raw.弧线.filter(Boolean).map((x: any) => 规范化条目<弧线>(取层('弧线'), x)) : [];
  const 章回列表 = Array.isArray(raw.章回) ? raw.章回.filter(Boolean).map(规范化章回).filter((x: 章回 | null): x is 章回 => !!x) : [];
  const 记录 = Array.isArray(raw.归档记录)
    ? raw.归档记录
        .filter((x: any) => x && typeof x === 'object')
        .map((x: any) => ({ 类型: String(x.类型 ?? ''), 名称: String(x.名称 ?? ''), 楼层: Number(x.楼层) || 0, 原因: String(x.原因 ?? '') }))
        .slice(-200)
    : [];
  return { 伏笔: 伏笔列表, 冲突: 冲突列表, 弧线: 弧线列表, 章回: 章回列表, 归档记录: 记录 };
}

/** 待读队列迁移: 老账本没有 → 空数组。**不裁条目**(队列长度是调度, 不是上限) */
function 规范化待读队列(raw: any): 待读项[] {
  if (!Array.isArray(raw)) return [];
  const out: 待读项[] = [];
  for (const 项 of raw) {
    if (!项 || typeof 项 !== 'object') continue;
    const 引用 = String(项.记忆引用 ?? '').trim().toUpperCase();
    if (!引用) continue;
    out.push({
      记忆引用: 引用,
      理由: String(项.理由 ?? ''),
      目标: String(项.目标 ?? ''),
      入队楼层: Number(项.入队楼层) || 0,
      已读次数: Number(项.已读次数) || 0,
    });
  }
  return out;
}

