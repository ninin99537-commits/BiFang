// 为什么单独一个 module: 这是 **schema 一改最先坏的地方** —— 老账本没有 指标 / 已剧终 / 收官请求 /
// 埋设章, 读回来必须补默认值而不是清空, 否则一次升级就把用户的账本洗白。
