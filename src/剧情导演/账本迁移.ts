/**
 * 账本顶层字段的**唯一声明处**(2026-11-12 架构深化 ①)。
 *
 * 此前同一个事实有六份名单: zod 声明、`字段表` 的键表、这份文件里 `sanitizeSnapshot` 的逐个赋值、
 * `快照.buildSnapshotPayload` 的逐个键、`prompts.引擎用账本` 的白名单、面板的显示。
 * 加一个字段(终局步/中点)要同时改六处, 漏一处就是**静默丢字段** —— 那时唯一的保险是一个
 * 用正则扫源码的用例(`daoyan-snapshot` 的 C11)。
 *
 * 现在: 每一行 = 一个字段 + **两个方向的转换**(怎么存 / 怎么读回) + 要不要发给模型。
 * 三个消费者都从这张表派生, 所以"存了没读"和"读了没存"在结构上就不可能了。
 *
 * 为什么住在 `账本迁移` 而不是新开一个文件: 它同时定义"空账本"与"旧快照怎么重建",
 * 字段的形状本来就由这两端夹出来 —— 挪走反而把"同一个字段的两种形状"拆到两个模块。
 */
export interface 账本字段行 {
  /** 顶层键 */
  键: keyof 导演账本 & string;
  /** 写进楼层快照时取什么值(可以缩成该存的样子) */
  存: (账本: 导演账本) => any;
  /**
   * 从快照读回来怎么修。第二参是**已经填好的前面那些字段** ——
   * 少数几行要用到(伏笔的埋设章回填要当前章号; 指标的队列计数器要现存伏笔)。
   */
  读回: (快照: Record<string, any>, 已填: 导演账本) => any;
  /** 要不要发给导演模型; 函数形式用于"空数组就不发"这类条件 */
  进引擎?: boolean | ((账本: 导演账本) => boolean);
  /** 发给模型时换个名字(已分析轮数 → 当前场) */
  引擎键?: string;
  /** 发给模型时换个值(默认原样)。只给"存的是字符串、模型该看数字"这类用 */
  引擎值?: (账本: 导演账本) => any;
}

const 是数组 = (值: unknown): any[] => (Array.isArray(值) ? 值.filter(Boolean) : []);

/** 一行的"存"用同一个套路: 克隆(避免快照与活账本共享引用) */
const 克隆 = (值: any) => klona(值 ?? null);

