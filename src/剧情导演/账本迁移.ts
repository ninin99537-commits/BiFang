/**
 * 把一份楼层快照(可能是旧格式)按当前结构重建。
 *
 * 2026-11-12(架构深化 ①): 函数体只剩"遍历那张表" —— 每一行自己说清"怎么读回",
 * 不再在这里逐个赋值(以前那份 120 行的赋值清单是六份字段名单中的一份)。
 *
 * 三种"老账本没有这个字段"的处理仍然各有理由, 现在写在对应那行的 `读回` 里:
 *   - 指标: 用 `规范化指标(快照.指标, 已填.伏笔)` —— 没有队列计数器时要用**现存伏笔**播种;
 *   - 伏笔.埋设章: 老账本(v1.0)只有 埋设层 → 回填当前章号, 不清空(指标账要靠它);
 *   - 已剧终/收官请求/待决死亡: 默认 false, 不伪造。
 */
export function sanitizeSnapshot(snapshot: Record<string, any>): 导演账本 {
  const data = emptyData();
  const 源 = snapshot && typeof snapshot === 'object' ? snapshot : {};
  for (const 行 of 账本字段表) (data as any)[行.键] = 行.读回(源, data);
  return data;
}