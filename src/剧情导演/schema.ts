/**
 * 证据引用(阶段 A): 一条伏笔/命运与**记忆插件详细纪要**之间的锚点。
 *
 * 为什么不只存 AM: 详细纪要可能后来被删。保留"当时书名 + 条目名 + 极短公开摘要",
 * 即使调档失败也**知道损失了什么**, 不会静默遗忘(设计文档 §4 定位与失败纪律)。
 */
export interface 证据引用 {
  /** AM 编码(如 AM0001) —— 这才是事件引用 */
  记忆引用: string;
  /** 当时的楼层号(0 = 未知) */
  楼层: number;
  /** 极短的公开摘要(当时正文里公开演了什么); 只作诊断与失忆兜底, **不替代详细纪要** */
  公开摘要: string;
  /** 当时的书名(诊断用; 书改名/换绑定后仍能看出它原本在哪) */
  书名?: string;
  /** 当时的条目标题(诊断用; 标题数字与 AM 数字**不假定相等**) */
  条目名?: string;
  /** 定位状态: 已核 = 调档成功过; 待核 = 缺失/歧义, 不得冒充已兑现 */
  定位?: '已核' | '待核';
  /** 待核原因(缺失/歧义/未读) */
  待核原因?: string;
}

