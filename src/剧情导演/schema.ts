/** 一套完整的接口配置(当前配置与预设共用同一结构) */
export const ApiConfigSchema = z
  .object({
    地址: z.string().default(''),
    密钥: z.string().default(''),
    模型: z.string().default(''),
    模型列表: z.array(z.string()).default([]),
    流式: z.boolean().default(false),
    /**
     * 直连(2026-11-07, 学彼方): 开 = 导演自己在脚本里 fetch `{地址}/chat/completions`,
     * **完全不经过酒馆的生成管线** —— 预设、世界书、其他扩展都碰不到请求体; 需要接口允许浏览器跨域。
     * 关 = 照旧交给酒馆服务器转发(浏览器不碰跨域)。
     * 默认开: 转发那条路要过酒馆那一层(预设/超时/钩子都可能改请求), 导演的提示词是自己拼的, 不该被改。
     * 直连连不上时 api.ts 会自动降级成转发并只提醒一次, 所以默认开不会让人卡死。
     */
    直连: z.boolean().default(true),
    温度: z.coerce
      .number()
      .default(0.8)
      .transform(value => _.clamp(value, 0, 2)),
    /**
     * 对账温度（2026-11-12 P3）: **同一个键不该管两件事**。
     *
     * 这一次导演调用同时做两件事——核验上一幕 / 报账本变化（要确定），
     * 以及给下一幕（要随机）。以前两者共用 `温度`（默认 0.8），
     * 结果是"账本抄错"和"编排呆板"这对矛盾只能二选一。
     *
     * 现在 `温度` 仍给 0.8（编排用），实际那次调用取 `对账温度`（默认 0.2）——
     * 因为那一次调用的**主要产物是账本**，"下一幕"只是附带（方案 A：一次调用，不改请求数）。
     */
    对账温度: z.coerce
      .number()
      .default(0.2)
      .transform(value => _.clamp(value, 0, 2)),
    最大token: z.coerce
      .number()
      .default(60000)
      .transform(value => Math.max(1, Math.min(131072, Math.round(value)))),
  })
  .prefault({});
