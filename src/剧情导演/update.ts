/**
 * 更新待读队列(纯函数, 可单测):
 *   ① 本轮**实际完整读到**的引用 → 出队(义务已履行), 并在出队前把 `已读次数` +1 记进审计;
 *   ② 导演本轮从索引新申请的 `候选证据` → 入队, 下一轮完整读取;
 *   ③ 其余条目原样保留 —— **队列长度不是上限**, 绝不因为"太长"截断或丢弃(设计文档 §4)。
 *
 * 纠偏(用户报告"索引外的 AM 也会入队"):
 *   导演申请必须**在本轮真实索引里存在**才入队 —— 否则代码会为一个根本不存在的引用伪造出一项
 *   "必须去读"的义务, 下一轮读不到又变成一条假的"证据缺失"。
 *   索引外的申请仍然**可见**(返回在 索引外申请 里, 进审计与面板), 但不入队、不构成调档义务。
 */

export function 更新待读队列(
  旧队列: 待读项[] | undefined,
  已读引用: string[],
  载荷: any,
  楼层: number,
  本轮索引?: { 记忆引用: string }[],
): 待读项[] {
  const 读过 = new Set((已读引用 ?? []).map(ref => String(ref).trim().toUpperCase()));
  const 索引集 = new Set((本轮索引 ?? []).map(项 => String(项.记忆引用 ?? '').trim().toUpperCase()).filter(Boolean));
  const out: 待读项[] = [];
  for (const 项 of 旧队列 ?? []) {
    const ref = String(项.记忆引用 ?? '').trim().toUpperCase();
    if (!ref) continue;
    if (读过.has(ref)) continue; // ① 已履行
    out.push({ ...项, 记忆引用: ref });
  }
  // ② 导演新申请: 必须在**本轮真实索引**里出现过(否则不构成调档义务)
  const 申请 = Array.isArray(载荷?.候选证据) ? 载荷.候选证据 : [];
  for (const raw of 申请) {
    const ref = String(raw ?? '').trim().toUpperCase();
    if (!ref) continue;
    if (!索引集.has(ref)) continue; // 索引外/无索引: 不入队(只作诊断, 见 筛索引外申请)
    const 已有 = out.find(项 => 项.记忆引用 === ref);
    if (已有) {
      已有.理由 = '导演再次从当前索引申请';
      已有.目标 = 已有.目标 || '导演申请补充';
      continue;
    }
    // 已读次数: 这个引用历史上被完整读过几次(旧队列里读过的条目已经出队, 用它的计数接上)
    const 历史次数 = (旧队列 ?? []).find(项 => String(项.记忆引用).toUpperCase() === ref)?.已读次数 ?? 0;
    out.push({
      记忆引用: ref,
      理由: '导演从当前索引申请补充',
      目标: '导演申请补充',
      入队楼层: 楼层,
      已读次数: 读过.has(ref) ? 历史次数 + 1 : 历史次数,
    });
  }
  return out;
}

/**
 * 导演申请里**不在本轮真实索引**中的引用(纠偏)。
 *
 * 它们**不入队**(不伪造调档义务), 但要作为可见诊断进审计与面板 ——
 * 否则"导演瞎编了一个 AM"会被静默吞掉, 看起来像一切正常。
 */
export function 筛索引外申请(载荷: any, 本轮索引?: { 记忆引用: string }[]): string[] {
  const 索引集 = new Set((本轮索引 ?? []).map(项 => String(项.记忆引用 ?? '').trim().toUpperCase()).filter(Boolean));
  const 申请 = Array.isArray(载荷?.候选证据) ? 载荷.候选证据 : [];
  const out: string[] = [];
  for (const raw of 申请) {
    const ref = String(raw ?? '').trim().toUpperCase();
    if (!ref) continue;
    if (索引集.has(ref)) continue;
    if (!out.includes(ref)) out.push(ref);
  }
  return out;
}

