export function 校验导演载荷(候选: any): any {
  if (!候选 || typeof 候选 !== 'object' || Array.isArray(候选)) throw Error('AI 返回的不是 JSON 对象');
  // 2026-11-12 P3（补丁协议）: 补丁形态下"什么都没给"和"什么都没变"长得一样，
  // 所以必须有一个**锚点**区分。每轮唯一必须有的是这两样：
  //   ① `上一幕核验` —— 核验上一道指令是导演的核心职责；
  //   ② `下一幕`     —— 每轮都要给下一幕。
  // 四本账（章回/伏笔/冲突/弧线）**一个都可以不给** —— 那就是"这一轮账本没变"。
  // ⚠️ 注意 `解析.ts` 的别名映射（verification / next_act）也算，别在这里自己再判英文键。
  const 缺 = ['上一幕核验', '下一幕'].filter(键 => !(键 in 候选));
  if (缺.length > 0) throw Error(`AI 返回的 JSON 缺少必需的键: ${缺.join(' / ')}（补丁协议下这两个是锚点，每轮都要有）`);
  return 候选;
}

