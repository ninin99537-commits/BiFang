/**
 * 决定主角死亡后**由谁接着演**(真实命运模式)。
 *
 * 纠偏(用户报告"续演视角会选任意路人/不存在的人"):
 *   ① 导演给的视角**必须**是命运册里已知、且当前可行动(活跃/受伤)的角色 ——
 *      写一个不存在的名字过去会让正文 AI 凭空造人, 也会悄悄把路人升成主角;
 *   ② 导演没给时, 只在**能承接未竟线**的角色里挑(有未竟计划或独立目标),
 *      而不是"命运册里第一个活人" —— 路人没有自己的线, 接不住故事;
 *   ③ 一个都没有 → 返回空串, 由调用方暂停并请玩家裁决(或安排明确的新视角)。
 * 返回空串 ≠ 失败, 它表示"代码找不到合规的续演者, 这需要人拍板"。
 */
export function 决定续演视角(账本: 导演账本, 载荷: any, 当前视角: string): string {
  const 命运 = 账本.角色命运 ?? [];
  const 取命 = (名: string) => 命运.find(项 => 项.角色ID === 名) ?? null;
  const 可行动 = (名: string): boolean => {
    const 命 = 取命(名);
    if (!命) return false; // 不存在的人一律不接受
    return 命.状态 === '活跃' || 命.状态 === '受伤';
  };
  /** 能接住故事: 有自己的未竟计划或独立目标(路人没有) */
  const 能承接 = (名: string): boolean => {
    const 命 = 取命(名);
    if (!命) return false;
    const 目标 = [...(命.独立目标 ?? []), ...(命.未竟计划 ?? [])].filter(x => String(x ?? '').trim() !== '');
    return 目标.length > 0;
  };
  // ① 导演显式指定: 必须已知且可行动
  const 导演指定 = String(载荷?.续演视角 ?? '').trim();
  if (导演指定 && 导演指定 !== 当前视角 && 可行动(导演指定)) return 导演指定;
  // ② 上一轮定过的续演视角: 仍要校验它还能行动、还能承接
  const 既有 = String(账本.续演视角 ?? '').trim();
  if (既有 && 既有 !== 当前视角 && 可行动(既有) && 能承接(既有)) return 既有;
  // ③ 从命运册里挑"能承接未竟线"的, 未竟计划多的优先
  const 候选 = 命运
    .filter(命 => 命.角色ID && 命.角色ID !== 当前视角 && 可行动(命.角色ID) && 能承接(命.角色ID))
    .sort(
      (a, b) =>
        (b.未竟计划 ?? []).length + (b.独立目标 ?? []).length - ((a.未竟计划 ?? []).length + (a.独立目标 ?? []).length),
    );
  return 候选[0]?.角色ID ?? '';
}

