//
// 症状: 面板上每个"改账本"的按钮都跟着一组**必须同时成立**的动作, 而它们以前各自手写在
// 悬浮球界面.vue 的 handler 里, 没有一处能被断言 —— 测试只能用 `vueSource.includes('确认剧终结算')`
// 这种字符串匹配。四条终局路径尤其明显:
//   确认剧终 = 落定剧终 + 结算死亡 + 写已剧终(true) + 终值日志 + 提交({重写备忘:false, 重注本幕:true})
//   清除剧终 = 解除剧终 + 写已剧终(false) + 提交({重写备忘:注入开关, 重注本幕:false})
//   清空     = clearAllData + reload + 撤备忘 + 撤指令   ← 完全绕过 提交账本变更
//   总开关   = 写/撤备忘 + 撤/重注指令                  ← 同样绕过
// 任何一条漏一个动作都是静默失效(备忘没撤、meta 没写、指令还在注入), 而 a0a2766 是同一根因的
// 另一面: 视图是唯一知道全接线的地方, 删掉四行 import 后五个 store 全 undefined, 构建还是绿的。
//
// 现在一条命令 = 一组不变量, 全在这个文件里; 视图只声明"点哪个按钮", 平台动作走 命令依赖。
// 这样 Node 里用一份记录型假依赖就能断言顺序与次数(见 tests/daoyan-commands.test.ts)。

