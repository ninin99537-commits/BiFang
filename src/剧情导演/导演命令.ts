/**
 * 只放**真正影响演出**的三个字段。编号 / 生成楼层 / 核验升级次数 / 代码调整 都归代码所有,
 * 手改它们只会让核验与统计对不上(比如改编号会让"第 N 道"和日志错位)。
 */
export interface 指令补丁 {
  节拍?: string;
  硬性要求?: string;
  /** undefined = 不动; '' = 删掉「本幕已确定」 */
  必演内容?: string;
  必演镜头外?: boolean;
  必演既成事实?: boolean;
}

/**
 * 把补丁就地应用到指令上(纯函数, 返回"改了什么"的中文清单; 空数组 = 一个字都没变)。
 *
 * 三条边界刻意收在这里, 而不是散在视图里:
 *   ① 节拍必须落在枚举内 —— 手填/旧存档带进来的怪值会让注入文本出现不存在的节拍;
 *   ② 「本幕已确定」清空 = 删掉整条(留空壳会让注入里出现光秃秃的「【本幕已确定】」);
 *   ③ 被「跳过本幕」作废的指令, 用户一改就要**恢复生效** —— 否则"改完什么都不变"看着就是坏了。
 */
export function 应用指令补丁(指令: 本幕指令, 补丁: 指令补丁): string[] {
  const 说明: string[] = [];
  if (补丁.节拍 !== undefined && 补丁.节拍 !== 指令.节拍 && 节拍列表.includes(补丁.节拍 as 节拍)) {
    指令.节拍 = 补丁.节拍 as 节拍;
    说明.push(`节拍 → ${补丁.节拍}`);
  }
  if (补丁.硬性要求 !== undefined && 补丁.硬性要求 !== 指令.硬性要求) {
    指令.硬性要求 = 补丁.硬性要求;
    说明.push('改了硬性要求');
  }
  const 碰了必演 = 补丁.必演内容 !== undefined || 补丁.必演镜头外 !== undefined || 补丁.必演既成事实 !== undefined;
  // 2026-11-13 P2 2.5: '无' 与 null 在"手改"这一层等价（都表示没有具体事件）
  const 现有必演 = 指令.必演 === '无' ? null : 指令.必演;
  if (碰了必演) {
    const 内容 = (补丁.必演内容 ?? 现有必演?.内容 ?? '').trim();
    if (!内容) {
      if (现有必演) {
        指令.必演 = null;
        说明.push('删掉了「本幕已确定」');
      }
    } else if (!现有必演) {
      // 手写出来的必演不是命运事件(没有角色ID、也没有核验封顶), 所以命运一律 false
      指令.必演 = { 内容, 命运: false, 角色ID: '', 镜头外: !!补丁.必演镜头外, 既成事实: !!补丁.必演既成事实, 未执行轮: 0 };
      说明.push('新增了「本幕已确定」');
    } else {
      // 2026-11-13 P2 2.5: 这里用收窄后的 现有必演（'无' 已在上面收成 null）
      if (现有必演.内容 !== 内容) {
        现有必演.内容 = 内容;
        说明.push('改了「本幕已确定」');
      }
      if (补丁.必演镜头外 !== undefined && 现有必演.镜头外 !== 补丁.必演镜头外) {
        现有必演.镜头外 = 补丁.必演镜头外;
        说明.push(补丁.必演镜头外 ? '改成镜头外发生' : '改成正面演');
      }
      if (补丁.必演既成事实 !== undefined && 现有必演.既成事实 !== 补丁.必演既成事实) {
        现有必演.既成事实 = 补丁.必演既成事实;
        说明.push(补丁.必演既成事实 ? '改成按既成事实写' : '改回当场发生');
      }
    }
  }
  if (说明.length > 0 && 指令.已跳过) {
    指令.已跳过 = false;
    说明.push('恢复生效(原来是「跳过本幕」)');
  }
  return 说明;
}

export function 建导演命令(依赖: 命令依赖) {
  const 账本 = () => 依赖.账本();
  const 设置 = () => 依赖.设置();
  /** 「注入编剧备忘」开关: 修笔与清剧终重写备忘时都用它 */
  const 备忘开关 = () => 设置().导演.注入世界书条目;

  /**
   * 三条「修笔」共用这一条: 改一个字段 → 提交(按需重写备忘) → 日志。
   * 以前这三段在视图里各抄一遍, 连"找不到那一条就什么都不做"的分支都是重复的。
   *
   * ── 2026-11-20：落盘失败要**回滚**（需求方 #507 ② / #510 ①）──
   *
   *  `改()` 是**就地改响应式对象**（`账本() === stateStore.data`），改完界面上就已经变了。
   *  落盘失败时原来只打一行日志（"内存里仍生效, 删楼回退会丢"）—— **无回滚**。
   *
   *  于是用户看到"改成功了"，刷新后改动没了。与彼方 C2 同型。
   *
   *  现在：**改之前深拷贝一份快照**，失败后恢复它。
   *
   *  ⚠ 必须是**深拷贝**，不能存引用 —— `改()` 就地改的正是那个对象，
   *    存引用等于"快照跟着一起变"，恢复时拿到的是改后的值。
   */
  function 修一笔(改: (账本: 导演账本) => boolean, 说明: string, 副作用?: 变更副作用): boolean {
    const 改前 = klona(账本());
    if (!改(账本())) return false;
    if (!依赖.提交(副作用)) {
      // 落盘失败 → 把账本恢复成改前那份（深拷贝快照）
      const 恢复 = 依赖.恢复账本;
      if (恢复)
        恢复(改前);
      依赖.日志(`${说明} · 落盘失败(已恢复改前的账本)`);
      return false;
    }
    依赖.日志(说明);
    return true;
  }

  return {
    /** 账本修笔: 伏笔状态(删中段楼后纠正用; 改成终态 = 手动了结, 会当场收档) */
    改伏笔状态(编号: number, 值: string): boolean {
      const 终态 = 值 === '已引爆' || 值 === '已消亡';
      return 修一笔(
        账本 => {
          // 改成终态走"手动了结"(改状态 + 收进历史档案): 只改状态的话, 下一轮模型照抄账本
          // 还会写回「发酵」, 一个安静的回滚就把手动结账抹掉(见 账本数据.手动了结伏笔)。
          if (终态) return 手动了结伏笔(账本, 编号, 值 as 伏笔状态);
          const 条 = 账本.伏笔.find(item => item.编号 === 编号);
          if (!条) return false;
          条.状态 = 值 as 伏笔状态;
          return true;
        },
        终态 ? `手动了结：伏笔 #${编号} → ${值}（已收进历史档案，证据链完整保留）` : `修笔：伏笔 #${编号} → ${值}`,
        { 重写备忘: 备忘开关() },
      );
    },

    改冲突阶段(名: string, 值: string): boolean {
      return 修一笔(
        账本 => {
          const 条 = 账本.冲突.find(item => item.名 === 名);
          if (!条) return false;
          条.阶段 = 值 as 冲突阶段;
          return true;
        },
        `修笔：冲突「${名}」→ ${值}`,
        { 重写备忘: 备忘开关() },
      );
    },

    改弧线阶段(角色: string, 值: string): boolean {
      // 弧线不改写备忘(与原实现一致: 它不影响事实层)
      return 修一笔(
        账本 => {
          const 条 = 账本.弧线.find(item => item.角色 === 角色);
          if (!条) return false;
          // 枚举守卫: 面板/手改传进来的自由文本先归一(旧实现直接赋值, 写出枚举外的值会让终态判定永远不成立)
          条.阶段 = 弧线阶段列表.includes(值 as any) ? (值 as 弧线阶段) : (归一弧线阶段(值) as 弧线阶段);
          return true;
        },
        `修笔：弧线「${角色}」→ ${值}`,
      );
    },

    /**
     * 手改当前这一层的指令(节拍 / 本幕已确定 / 硬性要求), 改完**立刻重注** ——
     * 下一段正文就按改后的演。这是"导演台能改"的唯一出口:
     * 面板上展示的字段全是引擎产物, 不经过这里就改不动, 改了也不会进注入。
     */
    改当前指令(补丁: 指令补丁): boolean {
      const 当前 = 账本();
      const 指令 = 当前.当前指令;
      if (!指令) return false;
      const 说明 = 应用指令补丁(指令, 补丁);
      if (说明.length === 0) return false;
      if (!依赖.提交({ 重注本幕: !!当前.待决死亡 })) 依赖.日志(`修笔：${说明.join('、')} · 落盘失败(内存里仍生效)`);
      依赖.日志(`修笔：本幕指令 · ${说明.join('、')}`);
      // 改完到底会不会真的注入, 取决于三件事 —— 说清楚, 免得用户以为"改了没效果"
      const 会注入 = 设置().启用导演 && 设置().导演.自动接管 && !当前.待决死亡 && !当前.已剧终;
      依赖.提示(
        会注入
          ? `已改：下一段正文按改后的指令演（${说明.join('、')}）`
          : `已改（${说明.join('、')}），但现在不会注入：总开关/自动接管关着，或正在等死亡抉择`,
      );
      return true;
    },

    /** 跳过本幕: 作废当前指令并重注(死亡待决时只记不注), 由下一轮重新生成 */
    跳过本幕(): boolean {
      const 当前 = 账本();
      if (!当前.当前指令) return false;
      // 平静模式(2026-11-08): 不下令, 也就没有"这一幕的指令"可跳过。
      // 更要紧的是数据: 标成 已跳过 之后, `装配必演` 读旧指令时会被 `!旧指令.已跳过` 挡掉 ——
      // 那条命运必演就**静默丢了**。所以这里直接拒绝, 而不是"跳过一道本来就不会注入的指令"。
      if (设置().导演.平静模式) {
        依赖.日志('平静模式：没有可跳过的指令（跳过会把那条命运必演丢掉，所以不允许）');
        return false;
      }
      跳过本幕规则(当前);
      if (!依赖.提交({ 重注本幕: !!当前.待决死亡 })) 依赖.日志('跳过本幕 · 落盘失败(内存里仍生效)');
      依赖.日志('用户跳过本幕');
      return true;
    },

    /**
     * 总开关(OFF 必须真零影响): 关 → 撤备忘 + 撤本幕指令; 开 → 按设置写回备忘 + 重注指令。
     * 两条分支都必须**同时**做这两件事, 少一件就是"关了还在注入"或"开了没恢复"。
     */
    切换总开关(): void {
      const 当前 = 账本();
      if (!设置().启用导演) {
        依赖.同步备忘(false);
        // 关键: 关掉要**删条目**, 不是写一条空内容 —— 否则标题和占位文本还在, 主 AI 照样读得到
        依赖.清世界书条目?.();
        依赖.撤本幕指令();
        依赖.日志('总开关已关：不调引擎、不注入，并删除世界书里的导演条目');
        return;
      }
      依赖.同步备忘(备忘开关());
      依赖.重注本幕(!!当前.待决死亡);
      依赖.日志('总开关已开：按「注入编剧备忘」设置写回世界书');
    },

    /** 清空: 数据清掉之后还要把两层注入一起撤掉(否则世界书里留着上一局的备忘与指令) */
    清空(): 导演账本 {
      const 重载 = 依赖.清空并重载();
      依赖.同步备忘(false);
      依赖.重注本幕(false);
      依赖.日志('已清空全部数据(含备忘与本幕指令)');
      return 重载;
    },

    /**
     * 死亡抉择: 剧终结算不可逆, 先让视图弹二次确认; 其余三项当场记账,
     * 抉择交给下一轮引擎消费(消费前仍暂停注入)。
     */
    做死亡抉择(项: 死亡抉择): 死亡抉择结果 {
      if (项 === '剧终结算') return '需二次确认';
      const 当前 = 账本();
      当前.死亡抉择 = 项;
      依赖.结算死亡();
      if (!依赖.提交({ 重注本幕: true })) 依赖.日志('死亡抉择落盘失败(内存里仍生效)');
      依赖.日志(`死亡抉择：${项}(待下一轮引擎消费)`);
      return '已记录';
    },

    /** 全书结算第一段: 请求收官(幂等, 重复点击不产生第二道收束幕) */
    做全书结算(): boolean {
      const 当前 = 账本();
      if (!请求收官(当前)) {
        依赖.日志('收官请求已存在或已剧终, 忽略重复点击(不产生第二道收束幕)');
        return false;
      }
      if (!依赖.提交({ 重注本幕: !!当前.待决死亡 })) 依赖.日志('收官请求落盘失败(内存里仍生效, 但删楼回退会丢)');
      依赖.日志('用户请求全书结算：下一道指令将编排为收束幕');
      依赖.提示('剧情导演: 已请求全书结算——下一道指令改为收束幕（回收剩余伏笔、收束主线）；演完这一幕后请在账本页点「确认剧终」');
      return true;
    },

    /**
     * 剧终落定: **三处写口**(账本 + chat meta + death store) + 成绩单进日志。
     * 落定剧终 是纯函数(已剧终/清收官请求/终值快照), meta 与落盘在这里。
     *
     * ── 2026-11-20：**按依赖顺序排，失败时后面的没跑过**（需求方 #536）──
     *
     *  修了一个双写，又露出第三个写口。原顺序是：
     *    ① 结算死亡() ② 写 meta ③ 落盘账本
     *  于是落盘失败时 → 账本回滚了，**但 meta 与 death store 都已写** → 三处不一致。
     *
     *  两次修补都是"把某一处挪到后面"（先修 meta、再修 death）——
     *  **那不是两次补丁，是同一个结构问题被分两次看见**：
     *  三个写口应当按依赖顺序排，失败时**后面的根本没执行过**，就不需要回滚。
     *
     *  现在：
     *    ① 账本落盘（唯一的"可能失败"步骤）
     *    ② 成功 → 写 meta「已剧终」
     *    ③ 成功 → 结算死亡()
     *    ④ 任一步失败 → 回滚账本内存，②③ 一个字都不写
     *
     *  ⚠ `结算死亡()` 现在是**幂等**的（`settle()` 只是 `pending.value = false`），
     *    所以用户重试确认剧终不会"重复结算"。这一条在判据里钉住了。
     */
    确认剧终(): void {
      const 当前 = 账本();
      const 改前 = klona(当前);
      当前.死亡抉择 = '剧终结算';
      落定剧终(当前);
      依赖.日志(终值日志行(当前.指标?.终值));

      // ── ① 账本落盘：唯一可能失败的步骤，放最前 ──
      if (!依赖.提交({ 重写备忘: false, 重注本幕: true })) {
        // 账本没落盘 → 回滚内存里的剧终改动；meta 与 death store **一个字都不写**
        if (依赖.恢复账本)
          依赖.恢复账本(改前);
        依赖.日志('剧终落盘失败(楼层写不进去), 已回滚 —— chat meta 与 death store **都没有**改动');
        return;
      }
      // ── ② 账本已落盘 → 写 meta ──
      依赖.写已剧终(true);
      // ── ③ meta 已写 → 结算死亡（幂等，重试安全）──
      依赖.结算死亡();
      依赖.日志('剧终结算: 已停引擎(账本 + chat meta + death store 三处一致)');
    },

    /** 清除剧终: 两边都清 + 连收官请求与终值一起清(否则会一直出收束幕) */
    清除剧终(): void {
      const 当前 = 账本();
      const 改前 = klona(当前);
      解除剧终(当前);
      // 与 `确认剧终` 同一条顺序：**账本先落盘，成功了才写 meta**
      if (!依赖.提交({ 重写备忘: 备忘开关(), 重注本幕: false })) {
        if (依赖.恢复账本)
          依赖.恢复账本(改前);
        依赖.日志('清除剧终落盘失败(楼层写不进去), 已回滚 —— chat meta 侧**没有**改动');
        return;
      }
      依赖.写已剧终(false);
      依赖.日志('已清除「已剧终」(含收官请求与结算快照), 自动路径恢复');
    },

    /** 手动恢复自动接管: 连败计数清零 + 解除自动暂停 */
    恢复自动接管(): 离线状态 {
      return 依赖.设自动暂停(false);
    },

    清空离线计数(): 离线状态 {
      return 依赖.清推进失败();
    },
  };
}

export type 导演命令 = ReturnType<typeof 建导演命令>;
