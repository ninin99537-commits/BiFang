/**
 * 命令要用到的**全部**外界动作。每一项在视图里都是一行适配(见 悬浮球界面.vue 末尾),
 * 在用例里是一个记录调用顺序的假实现 —— 接口窄到只有这些, 命令因此不碰 Vue 也不碰平台单例。
 */
export interface 命令依赖 {
  /** 当前账本(活对象: 命令就地改它, 与视图原写法一致) */
  账本(): 导演账本;
  /**
   * 把账本**整体恢复**成给定那份（落盘失败时回滚用）。
   *
   * 2026-11-20 新增（#507 ②）：`修一笔` 是就地改响应式对象，改完界面就变了；
   * 落盘失败时要把界面拉回改前那份 —— 否则用户看到"改成功了"，刷新后没了。
   *
   * 可选：不给时 `修一笔` 只记日志不回滚（旧行为）。
   */
  恢复账本?(账本: 导演账本): void;
  /** 当前设置 */
  设置(): Settings;
  /** 提交一次账本变更(落盘 + 按副作用重写备忘/重注指令); 返回是否落盘成功 */
  提交(副作用?: 变更副作用): boolean;
  /** 写 chat meta 侧的「已剧终」(与账本双写) */
  写已剧终(值: boolean): boolean;
  /** 重写 / 撤掉「编剧备忘」世界书条目 */
  同步备忘(要写: boolean): void;
  /**
   * 彻底删掉世界书里的**所有**导演条目(2026-10-30)。
   *
   * 总开关关闭时用: 正确做法不是"写一条空条目", 而是**让条目消失** ——
   * 否则主 AI 仍会读到「导演指令 · 近期写作要求…」这个标题和占位文本, 等于插件还在施加影响。
   */
  清世界书条目?(): void;
  /** 撤掉本幕指令(生成前不再注入) */
  撤本幕指令(): void;
  /** 重新注入本幕指令; 暂停=true 时只记不注(死亡待决 / 群聊) */
  重注本幕(暂停: boolean): void;
  /** 清空全部数据并返回重载后的账本 */
  清空并重载(): 导演账本;
  /** 死亡抉择已被消费(清掉 pending) */
  结算死亡(): void;
  /** 设自动暂停(离线熔断) */
  设自动暂停(值: boolean): 离线状态;
  /** 清推进失败计数 */
  清推进失败(): 离线状态;
  /** 给用户看的提示(只有需要告知结果的命令用) */
  提示(消息: string): void;
  /** 调试日志 */
  日志(消息: string): void;
}

