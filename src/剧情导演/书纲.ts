// 剧情导演 · 书纲(第二轮方案 2.1): 全书级的顶层计划 —— "这本书最终要揭开什么"。
// ---------------------------------------------------------------------------
// 为什么要有: 伏笔原来全是"边演边从正文里提"的, 没有终点, 所以埋不深、也收不回来。
// 书纲先定 2~3 条**深层真相**(只有导演知道), 长伏笔挂在它们下面, 分几次、换几种表面形式埋。
//
// 两份数据, 两种回滚语义:
//   - 账本里的 `书纲`(导演写的): 随楼层快照回滚 —— 删楼就回到那一楼时的书纲;
//   - 聊天变量里的 `书纲覆盖`(用户写的: 编辑 / 锁定 / 否决): **不随删楼回滚** ——
//     用户亲手改的东西不能因为删了一楼就没了。每次装载/推进都把覆盖叠到账本书纲上。
//
// 书纲**永不注入主 AI**(编剧备忘与本幕指令都不读它), 只出现在导演提示词里。
// 纯函数, 不碰平台。
import type { 伏笔 } from './schema';

export const 真相状态列表 = ['潜藏', '逼近', '已揭晓', '已废弃'] as const;
export type 真相状态 = (typeof 真相状态列表)[number];

/** 活跃(未揭晓/未废弃)真相的上限: 格式守卫, 挡"模型一口气写十条" */
export const 活跃真相上限 = 5;

export interface 深层真相 {
  ID: string;
  /** 真相本身(只有导演知道) */
  真相: string;
  /** 揭晓时机: 剧情节点("主线崩塌之后"), 不写楼层 */
  揭晓时机: string;
  /** 打算分几次、以什么表面形式埋 */
  线索计划: string[];
  状态: 真相状态;
  /** 改写真相必须给理由(每次追加一条) */
  修订原因: string[];
  /** 来源: 用户改过的条目, 导演之后不得改它的 真相/揭晓时机 */
  来源: '导演' | '用户';
  /** 用户锁定: 导演不得改写、不得废弃, 只能往里挂伏笔 */
  锁定: boolean;
}

export interface 人物暗线 {
  角色ID: string;
  /** 这个角色自己的秘密, 或与主角利益冲突的目标 */
  暗线: string;
}

/**
 * 主角的欲望(2026-11-12, 取自 Truby 的 Desire: 全剧的**脊梁**)。
 *
 * 为什么单独立这一项: 以前账本里跟"主角想要什么"最接近的是「冲突」(对抗面) 和「计划高潮」(本章爆点),
 * 两个都是**对抗**, 不是**目标**。结果是每场戏的合法性判据只能是"有没有对手动起来" ——
 * 一场"买盐"和一场"打杂兵"在账本里地位相同, 导演为了让这一幕"有内容"就只能加敌人。
 * 有了欲望, 判据变成"这一幕推进或复杂化它了吗": 不推进的对手就是杂兵。
 */
export interface 书纲欲望 {
  /** 具体、可失败的目标(不是"变强", 要能判断成没成) */
  想要: string;
  /** 为什么是现在(不做的代价) */
  为什么是现在: string;
  /** 输了会失去什么 */
  输了失去: string;
}

/**
 * B 故事线(2026-11-12, 取自 BS2 的 B Story: 主题不在 A 线里宣布, 埋在两个人的关系里讨论)。
 *
 * 它也是"切出去喘气"的合法去处: 日常是**空着**, B 线是**有内容但不打架**。
 */
export interface 书纲B线 {
  /** 关系对象(配角 ID) */
  谁: string;
  /** 这条线在讨论主题的两种态度(两句话各站一边) */
  争什么: string;
  /** 现在到哪(导演可以每轮更新) */
  现在到哪: string;
}

export interface 书纲 {
  核心问题: string;
  欲望: 书纲欲望 | null;
  B线: 书纲B线 | null;
  深层真相: 深层真相[];
  人物暗线: 人物暗线[];
  /** 下一个真相 ID 的序号(T1, T2 …), 只增不减 */
  下一真相序号: number;
  /** 生成于第几场 */
  生成场: number;
}

/** 用户覆盖(存聊天变量, 不随删楼回滚) */
export interface 书纲覆盖 {
  /** 按真相 ID: 用户改过的字段 + 锁定 */
  真相: Record<string, { 真相?: string; 揭晓时机?: string; 线索计划?: string[]; 锁定?: boolean }>;
  /** 用户否决的真相 ID → 原因(可空) */
  否决: Record<string, string>;
  /** 用户改过的核心问题(空 = 没改) */
  核心问题?: string;
  /** 用户手写的欲望主句(空 = 没改; 只覆盖「想要」, 另外两项保留导演写的) */
  欲望?: string;
  /** 用户手写的 B 线"在争什么"(空 = 没改) */
  B线?: string;
  /** 用户要求整份重写(下一轮导演按现有伏笔重新生成; 生成后清掉) */
  请求重写?: boolean;
}

export function 空书纲覆盖(): 书纲覆盖 {
  return { 真相: {}, 否决: {} };
}

const 文本 = (v: unknown) => String(v ?? '').trim();
const 文本数组 = (v: unknown): string[] => (Array.isArray(v) ? v.map(文本).filter(Boolean) : []);

function 规范化真相(raw: any): 深层真相 | null {
  if (!raw || typeof raw !== 'object') return null;
  const 真相 = 文本(raw.真相);
  if (!真相) return null;
  const 状态 = (真相状态列表 as readonly string[]).includes(raw.状态) ? (raw.状态 as 真相状态) : '潜藏';
  return {
    ID: 文本(raw.ID),
    真相,
    揭晓时机: 文本(raw.揭晓时机),
    线索计划: 文本数组(raw.线索计划),
    状态,
    修订原因: 文本数组(raw.修订原因),
    来源: raw.来源 === '用户' ? '用户' : '导演',
    锁定: raw.锁定 === true,
  };
}

/** 规范化欲望(空 → null; 只 trim 不裁字) */
export function 规范化欲望(raw: any): 书纲欲望 | null {
  if (!raw || typeof raw !== 'object') return null;
  const 想要 = 文本(raw.想要);
  const 为什么是现在 = 文本(raw.为什么是现在);
  const 输了失去 = 文本(raw.输了失去);
  if (!想要 && !为什么是现在 && !输了失去) return null;
  return { 想要, 为什么是现在, 输了失去 };
}

/** 规范化 B 线(空 → null) */
export function 规范化B线(raw: any): 书纲B线 | null {
  if (!raw || typeof raw !== 'object') return null;
  const 谁 = 文本(raw.谁);
  const 争什么 = 文本(raw.争什么);
  const 现在到哪 = 文本(raw.现在到哪);
  if (!谁 && !争什么 && !现在到哪) return null;
  return { 谁, 争什么, 现在到哪 };
}

/** 规范化(快照装载 / 模型输出共用)。无内容 → null */
export function 规范化书纲(raw: any): 书纲 | null {
  if (!raw || typeof raw !== 'object') return null;
  const 深层真相 = (Array.isArray(raw.深层真相) ? raw.深层真相 : []).map(规范化真相).filter((x: 深层真相 | null): x is 深层真相 => !!x);
  const 人物暗线 = (Array.isArray(raw.人物暗线) ? raw.人物暗线 : [])
    .filter((x: any) => x && typeof x === 'object')
    .map((x: any) => ({ 角色ID: 文本(x.角色ID), 暗线: 文本(x.暗线) }))
    .filter((x: 人物暗线) => x.角色ID && x.暗线);
  const 核心问题 = 文本(raw.核心问题);
  const 欲望 = 规范化欲望(raw.欲望);
  const B线 = 规范化B线(raw.B线);
  if (!核心问题 && !欲望 && !B线 && 深层真相.length === 0 && 人物暗线.length === 0) return null;
  return {
    核心问题,
    欲望,
    B线,
    深层真相,
    人物暗线,
    下一真相序号: Math.max(1, Number(raw.下一真相序号) || 1),
    生成场: Math.max(0, Number(raw.生成场) || 0),
  };
}

export function 规范化书纲覆盖(raw: any): 书纲覆盖 {
  const out = 空书纲覆盖();
  if (!raw || typeof raw !== 'object') return out;
  if (raw.真相 && typeof raw.真相 === 'object') {
    for (const [ID, 值] of Object.entries<any>(raw.真相)) {
      if (!值 || typeof 值 !== 'object') continue;
      const 项: 书纲覆盖['真相'][string] = {};
      if (typeof 值.真相 === 'string' && 值.真相.trim()) 项.真相 = 值.真相.trim();
      if (typeof 值.揭晓时机 === 'string') 项.揭晓时机 = 值.揭晓时机.trim();
      if (Array.isArray(值.线索计划)) 项.线索计划 = 文本数组(值.线索计划);
      // 锁定是三态: true=锁 / false=用户显式解锁(要能盖掉已经存进快照的 true) / 缺省=不管
      if (值.锁定 === true || 值.锁定 === false) 项.锁定 = 值.锁定;
      if (Object.keys(项).length > 0) out.真相[ID] = 项;
    }
  }
  if (raw.否决 && typeof raw.否决 === 'object') {
    for (const [ID, 原因] of Object.entries(raw.否决)) out.否决[ID] = 文本(原因);
  }
  if (typeof raw.核心问题 === 'string' && raw.核心问题.trim()) out.核心问题 = raw.核心问题.trim();
  if (typeof raw.欲望 === 'string' && raw.欲望.trim()) out.欲望 = raw.欲望.trim();
  if (typeof raw.B线 === 'string' && raw.B线.trim()) out.B线 = raw.B线.trim();
  if (raw.请求重写 === true) out.请求重写 = true;
  return out;
}

/**
 * 把用户覆盖叠到导演书纲上(装载与推进都调它)。
 *   - 改过的字段替换, 条目标「来源: 用户」;
 *   - 锁定 → `锁定: true`;
 *   - 否决 → 状态「已废弃」, 修订原因记一笔(导演下一轮会看到并另起一条)。
 */
export function 叠加覆盖(纲: 书纲 | null, 覆盖: 书纲覆盖 | null | undefined): 书纲 | null {
  if (!纲) return null;
  if (!覆盖) return 纲;
  const out: 书纲 = { ...纲, 深层真相: 纲.深层真相.map(项 => ({ ...项, 线索计划: [...项.线索计划], 修订原因: [...项.修订原因] })) };
  if (覆盖.核心问题) out.核心问题 = 覆盖.核心问题;
  // 用户手写的欲望主句(整段文本): 只覆盖「想要」, 另外两项保留导演写的, 免得覆盖一次把上下文清空
  if (覆盖.欲望) {
    const 旧 = out.欲望;
    out.欲望 = { 想要: 覆盖.欲望, 为什么是现在: 旧?.为什么是现在 ?? '', 输了失去: 旧?.输了失去 ?? '' };
  }
  if (覆盖.B线) {
    const 旧 = out.B线;
    out.B线 = { 谁: 旧?.谁 ?? '', 争什么: 覆盖.B线, 现在到哪: 旧?.现在到哪 ?? '' };
  }
  for (const 项 of out.深层真相) {
    const 改 = 覆盖.真相[项.ID];
    if (改) {
      if (改.真相 !== undefined && 改.真相 !== 项.真相) {
        项.真相 = 改.真相;
        项.来源 = '用户';
      }
      if (改.揭晓时机 !== undefined && 改.揭晓时机 !== 项.揭晓时机) {
        项.揭晓时机 = 改.揭晓时机;
        项.来源 = '用户';
      }
      if (改.线索计划 !== undefined) 项.线索计划 = 改.线索计划;
      if (改.锁定 === true) 项.锁定 = true;
      else if (改.锁定 === false) 项.锁定 = false;
    }
    if (Object.prototype.hasOwnProperty.call(覆盖.否决, 项.ID) && 项.状态 !== '已废弃') {
      项.状态 = '已废弃';
      项.锁定 = false;
      项.修订原因.push(`用户否决${覆盖.否决[项.ID] ? `: ${覆盖.否决[项.ID]}` : ''}`);
    }
  }
  return out;
}

export interface 书纲合并结果 {
  书纲: 书纲 | null;
  拒绝: string[];
  /** 本轮是否真的产生/改动了书纲(用于日志) */
  有变化: boolean;
}

/**
 * 合并导演本轮给的书纲(纯函数)。
 *
 * 规则(与伏笔"幕后真相修订守卫"同一思路):
 *   - 没给 → 原样保留(漏输出 ≠ 删除);
 *   - 已有真相按 ID 对齐; 没带回的旧真相**保留**;
 *   - 锁定或「来源: 用户」的真相: 导演不得改 真相/揭晓时机, 锁定的还不得废弃; 线索计划可以补充;
 *   - 导演自己的真相改写必须带**新的**修订原因, 否则保留原文;
 *   - 新真相(没有 ID 或 ID 不认识)由代码签发 T{n};
 *   - 活跃真相最多 活跃真相上限 条, 多出来的拒收(并说明)。
 */
export function 合并书纲(旧: 书纲 | null, 候选raw: any, 当前场: number, 选项: { 重写?: boolean } = {}): 书纲合并结果 {
  const 拒绝: string[] = [];
  const 候选 = 规范化书纲(候选raw);
  if (!候选) return { 书纲: 旧, 拒绝, 有变化: false };
  const 基 = 旧 ?? { 核心问题: '', 欲望: null, B线: null, 深层真相: [], 人物暗线: [], 下一真相序号: 1, 生成场: 当前场 };
  let 序号 = Math.max(基.下一真相序号, 1);
  const 结果真相: 深层真相[] = 基.深层真相.map(项 => ({ ...项 }));
  // 用户要求整份重写: 导演自己写的、这次没带回的真相作废(用户锁定/改过的一律保留)
  if (选项.重写) {
    const 带回 = new Set(候选.深层真相.map(项 => 项.ID).filter(Boolean));
    for (const 项 of 结果真相) {
      if (项.锁定 || 项.来源 === '用户' || 带回.has(项.ID) || 项.状态 === '已废弃' || 项.状态 === '已揭晓') continue;
      项.状态 = '已废弃';
      项.修订原因 = [...项.修订原因, '用户要求整份重写'];
    }
  }
  const 按ID = new Map(结果真相.map(项 => [项.ID, 项]));

  /** 比对用: 去掉空白与标点, 防"换个 ID 原样交回一条被否决的真相" */
  const 归一 = (文: string) => String(文 ?? '').replace(/[\s\p{P}\p{S}]/gu, '');
  for (const 新 of 候选.深层真相) {
    const 旧条 = 新.ID ? 按ID.get(新.ID) : undefined;
    if (!旧条) {
      const 撞废 = 结果真相.find(项 => 项.状态 === '已废弃' && 归一(项.真相) !== '' && 归一(项.真相) === 归一(新.真相));
      if (撞废) {
        拒绝.push(`书纲: 新真相和已废弃的 ${撞废.ID} 是同一条 → 不收(已废弃的真相不能换个编号复活)`);
        continue;
      }
      const 活跃数 = 结果真相.filter(项 => 项.状态 !== '已废弃' && 项.状态 !== '已揭晓').length;
      if (活跃数 >= 活跃真相上限) {
        拒绝.push(`书纲: 活跃真相已有 ${活跃数} 条(上限 ${活跃真相上限}), 新真相「${新.真相}」未收`);
        continue;
      }
      const 条: 深层真相 = { ...新, ID: `T${序号++}`, 来源: '导演', 锁定: false };
      结果真相.push(条);
      按ID.set(条.ID, 条);
      continue;
    }
    const 受保护 = 旧条.锁定 || 旧条.来源 === '用户';
    const 改了文本 = 新.真相 !== 旧条.真相 || (新.揭晓时机 && 新.揭晓时机 !== 旧条.揭晓时机);
    if (改了文本) {
      if (受保护) {
        拒绝.push(`书纲 ${旧条.ID}: ${旧条.锁定 ? '已锁定' : '用户改过'}, 导演不得改写真相/揭晓时机 → 保留原文`);
      } else if (新.修订原因.some(原因 => !旧条.修订原因.includes(原因))) {
        旧条.真相 = 新.真相;
        if (新.揭晓时机) 旧条.揭晓时机 = 新.揭晓时机;
        旧条.修订原因 = [...new Set([...旧条.修订原因, ...新.修订原因])];
      } else {
        拒绝.push(`书纲 ${旧条.ID}: 真相被改写但没给新的修订原因 → 保留原文(真相不得无理由改写)`);
      }
    }
    // 线索计划: 补充(锁定的也可以补, 只要不删掉用户写的)
    旧条.线索计划 = [...new Set([...旧条.线索计划, ...新.线索计划])];
    // 状态
    if (新.状态 !== 旧条.状态) {
      if (旧条.锁定 && 新.状态 === '已废弃') {
        拒绝.push(`书纲 ${旧条.ID}: 已锁定, 不得废弃`);
      } else if (旧条.状态 === '已废弃' && 新.状态 !== '已废弃') {
        拒绝.push(`书纲 ${旧条.ID}: 已废弃的真相不能复活(要用就另起一条)`);
      } else {
        旧条.状态 = 新.状态;
      }
    }
  }

  // 核心问题: 首次确立直接写; 之后改写要有理由 —— 这里没有专门的理由字段, 所以只在原来为空时接受
  let 核心问题 = 基.核心问题;
  if (候选.核心问题 && 候选.核心问题 !== 基.核心问题) {
    if (!基.核心问题) 核心问题 = 候选.核心问题;
    else 拒绝.push('书纲: 核心问题已确立, 不随单轮输出改写(要改请在面板里改)');
  }

  // 欲望(2026-11-12): 全剧的脊梁 —— 首次确立就直接写; 之后**不许随单轮输出改写**
  // (否则它每轮换一句, "这一幕推进欲望了吗"这个判据就废了)。想改在面板里改。
  let 欲望 = 基.欲望 ?? null;
  if (候选.欲望) {
    if (!欲望) {
      欲望 = 候选.欲望;
    } else if (候选.欲望.想要 && 候选.欲望.想要 !== 欲望.想要) {
      拒绝.push('书纲: 主角欲望已确立, 不随单轮输出改写(要改请在面板里改「欲望」)');
    } else {
      // 主句没变 → 允许把首轮漏写的两项补上(不覆盖已有的)
      欲望 = {
        想要: 欲望.想要,
        为什么是现在: 欲望.为什么是现在 || 候选.欲望.为什么是现在,
        输了失去: 欲望.输了失去 || 候选.欲望.输了失去,
      };
    }
  }

  // B 线(2026-11-12): 谁 / 争什么 一旦确立就冻结 —— 它是主题的两端, 每轮换一次等于没主题;
  // 「现在到哪」是导演的推进账, 每轮都可以更新。
  let B线 = 基.B线 ?? null;
  if (候选.B线) {
    if (!B线) {
      B线 = 候选.B线;
    } else {
      const 谁变 = !!候选.B线.谁 && 候选.B线.谁 !== B线.谁;
      const 争变 = !!候选.B线.争什么 && 候选.B线.争什么 !== B线.争什么;
      if (谁变 || 争变) 拒绝.push('书纲: B 线的人和"在争什么"已确立, 不随单轮改写(只有「现在到哪」可以更新)');
      B线 = {
        谁: 谁变 ? B线.谁 : 候选.B线.谁 || B线.谁,
        争什么: 争变 ? B线.争什么 : 候选.B线.争什么 || B线.争什么,
        现在到哪: 候选.B线.现在到哪 || B线.现在到哪,
      };
    }
  }

  // 人物暗线: 按角色合并, 候选覆盖同一角色
  const 暗线表 = new Map(基.人物暗线.map(项 => [项.角色ID, 项]));
  for (const 项 of 候选.人物暗线) 暗线表.set(项.角色ID, 项);

  return {
    书纲: {
      核心问题,
      欲望,
      B线,
      深层真相: 结果真相,
      人物暗线: [...暗线表.values()],
      下一真相序号: 序号,
      生成场: 旧?.生成场 || 当前场,
    },
    拒绝,
    有变化: true,
  };
}

/** 每条真相下已挂了哪些伏笔(代码算, 不信模型自报) */
export function 挂靠伏笔(纲: 书纲 | null, 伏笔们: 伏笔[]): Record<string, number[]> {
  const out: Record<string, number[]> = {};
  if (!纲) return out;
  for (const 项 of 纲.深层真相) out[项.ID] = [];
  for (const 条 of 伏笔们) {
    const ID = 文本(条.书纲ID);
    if (ID && out[ID]) out[ID].push(条.编号);
  }
  return out;
}

/** 该不该在本轮要求导演生成书纲 */
export function 需要生成书纲(
  纲: 书纲 | null,
  覆盖: 书纲覆盖 | null | undefined,
  已分析轮数: number,
  接管轮数: number,
  /** 优化 4: 章回在收束 / 已请求收官 / 已剧终 → 不催补新真相(收尾时硬加谜团只会拖长结局) */
  收尾中 = false,
): boolean {
  if (覆盖?.请求重写) return true;
  // 有书纲时: 只要还有活跃真相(未揭晓/未废弃)就不催; 被否决/揭晓光了才再要
  if (纲 && 纲.深层真相.some(项 => 项.状态 !== '已废弃' && 项.状态 !== '已揭晓')) return false;
  if (纲 && 纲.深层真相.length > 0) return !收尾中;
  // 第 接管轮数 轮(= 第一道本幕指令那一轮)起; 已分析轮数是**本轮之前**的计数
  return 已分析轮数 + 1 >= 接管轮数;
}

/** 导演提示词里的书纲块(只给导演; 零截断) */
export function 渲染书纲块(参数: {
  书纲: 书纲 | null;
  伏笔: 伏笔[];
  需要生成: boolean;
  请求重写: boolean;
  否决: Record<string, string>;
  有既有剧情: boolean;
}): string {
  const lines: string[] = [];
  const { 书纲: 纲 } = 参数;
  if (纲) {
    const 挂靠 = 挂靠伏笔(纲, 参数.伏笔);
    lines.push('【书纲(只有你知道; 永不下发给演员)】');
    if (纲.核心问题) lines.push(`核心问题: ${纲.核心问题}`);
    // 欲望 = 全剧脊梁(2026-11-12): 摆在最前面, 每轮都看得见 —— 它是"这一幕该不该演"的判据
    if (纲.欲望?.想要) {
      lines.push(
        `主角欲望(全剧脊梁): ${纲.欲望.想要}` +
          (纲.欲望.为什么是现在 ? `；为什么是现在: ${纲.欲望.为什么是现在}` : '') +
          (纲.欲望.输了失去 ? `；输了会失去: ${纲.欲望.输了失去}` : ''),
      );
    }
    if (纲.B线?.谁 || 纲.B线?.争什么) {
      lines.push(
        `B 线(主题在这条线上被讨论, 不在主线上宣布): ${纲.B线?.谁 || '(没写)'} —— ${纲.B线?.争什么 || '(没写在争什么)'}` +
          (纲.B线?.现在到哪 ? `；现在到哪: ${纲.B线.现在到哪}` : ''),
      );
    }
    // 优化 4: 已废弃的真相不再每轮进提示词(只留"用户否决、还等着替代"的那几条, 下面单独提);
    // 已揭晓的只留一行(导演要知道它已经揭开, 不用再看线索计划)
    const 已揭晓: string[] = [];
    for (const 项 of 纲.深层真相) {
      if (项.状态 === '已废弃') continue;
      if (项.状态 === '已揭晓') {
        已揭晓.push(`${项.ID} ${项.真相}`);
        continue;
      }
      const 标 = [项.状态, 项.锁定 ? '用户锁定' : '', 项.来源 === '用户' ? '用户改过' : ''].filter(Boolean).join('·');
      lines.push(`- ${项.ID}【${标}】${项.真相}`);
      if (项.揭晓时机) lines.push(`  揭晓时机: ${项.揭晓时机}`);
      if (项.线索计划.length > 0) lines.push(`  线索计划: ${项.线索计划.join('；')}`);
      lines.push(`  已挂伏笔: ${(挂靠[项.ID] ?? []).length > 0 ? (挂靠[项.ID] ?? []).map(n => `#${n}`).join('、') : '还没有'}`);
    }
    if (已揭晓.length > 0) lines.push(`已揭晓(不要再当谜团写): ${已揭晓.join('；')}`);
    if (纲.人物暗线.length > 0) {
      lines.push('人物暗线:');
      for (const 项 of 纲.人物暗线) lines.push(`- ${项.角色ID}: ${项.暗线}`);
    }
    lines.push(
      '用法: 新伏笔若服务于某条真相, 在伏笔上写「书纲ID」(如 "T1"), 并把「跨度」写成"长"; 每条活跃真相都应陆续挂上 2~4 条伏笔, 用不同的表面形式埋。' +
        '「用户锁定 / 用户改过」的真相你不能改写, 只能往里挂伏笔、补线索计划。不需要改书纲时, 输出里可以不带「书纲」字段。',
    );
  }
  const 否决项 = Object.entries(参数.否决);
  const 活跃数 = (纲?.深层真相 ?? []).filter(项 => 项.状态 !== '已废弃' && 项.状态 !== '已揭晓').length;
  // 只在"否决之后还没补够"时提醒(活跃真相 < 2), 否则旧否决会一直挂在提示词里
  if (否决项.length > 0 && 活跃数 < 2 && 纲?.深层真相.some(项 => Object.prototype.hasOwnProperty.call(参数.否决, 项.ID) && 项.状态 === '已废弃')) {
    lines.push(`用户否决过的真相: ${否决项.map(([ID, 原因]) => `${ID}${原因 ? `(原因: ${原因})` : ''}`).join('、')} —— 请另写一条替代它(不要换汤不换药), 已挂在旧真相下的伏笔可以改挂或自然消亡。`);
  }
  if (参数.需要生成) {
    lines.push('');
    lines.push(参数.请求重写 ? '【请重写书纲】用户要求整份重写。' : '【请生成书纲】这一轮请在输出里带上「书纲」字段。');
    lines.push(
      '- 核心问题: 一句话, 这本书最终回答什么。\n' +
        '- 主角欲望(全剧脊梁): 「想要」必须是**具体、可失败**的目标(不是"变强", 是"把妹妹从北区带出来"——能判断成没成); 「为什么是现在」写不做的代价; 「输了失去」写最疼的那一样。\n' +
        '- B 线: 一条**不靠打架推进**的关系线(选一个重要配角), 「争什么」写这条线在讨论主题的两种态度(两句话各站一边); 之后每轮把「现在到哪」更新一下。\n' +
        '- 深层真相 2~3 条: 读者和主角现在都不知道、到中后段才揭开的事; 每条写「揭晓时机」(剧情节点, 如"主角第一次失去重要的人之后", 不写楼层)与「线索计划」(打算分几次、以什么表面形式埋, 2~4 条)。真相必须来自已有设定与人物的合理延伸, 不得与已公开的事实矛盾。\n' +
        '- 人物暗线: 每个重要配角(尤其恋爱对象)至少一条**自己的**秘密或与主角利益冲突的目标 —— 他们不是只围着主角转的人。\n' +
        '- 不要提前在正文里揭开任何一条; 第一条线索可以从这一幕开始埋。',
    );
    if (参数.有既有剧情) {
      lines.push('- 这是已经演了一段的故事: 请**从现有伏笔、冲突与命运册反推**书纲, 让已埋的伏笔尽量挂到某条真相上(在对应伏笔上写「书纲ID」)。');
    }
    lines.push(
      '输出格式: "书纲":{"核心问题":"...","欲望":{"想要":"...","为什么是现在":"...","输了失去":"..."},"B线":{"谁":"角色ID","争什么":"...","现在到哪":"..."},"深层真相":[{"ID":"","真相":"...","揭晓时机":"...","线索计划":["..."],"状态":"潜藏","修订原因":[]}],"人物暗线":[{"角色ID":"...","暗线":"..."}]}  (新真相 ID 留空, 由脚本签发)',
    );
  }
  return lines.join('\n');
}
