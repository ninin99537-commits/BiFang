  // 重置累计器**。先让导演的章号进指标、再在外面盖回旧值 → 指标结算了不该结算的章, 下一轮章号又"回落",
  // 统计就乱了。在入口替换, 章回/指标/伏笔埋设章 全流程用同一个值。
  const 载荷 = 选项.平静 ? { ...(载荷原始 ?? {}), 章回: 旧.章回 } : 载荷原始;
