    const 声明编号 = Number(String(raw?.编号 ?? '').match(/\d+/)?.[0]) || 0;
    // 2026-11-12 P0.95: 先把旧条找出来（按编号，退一步按内容），再规范化 ——
    // 这样"模型漏写的字段"能沿用旧值，而不是被兜底清成空（真机: 9 个字段被静默清空）。
    let 旧条: 伏笔 | undefined;
    if (声明编号 > 0) 旧条 = 旧伏笔.get(声明编号);
    if (!旧条) {
      const 内容0 = String(raw?.内容 ?? '').trim();
      if (内容0) 旧条 = 旧内容索引.get(内容0);
    }
    const 沿用字段: string[] = [];
    const 规范 = 规范化条目<伏笔>(取层('伏笔'), raw, 旧条, 沿用字段);
    if (旧条) 记沿用(沿用, `#${旧条.编号}`, 沿用字段);
