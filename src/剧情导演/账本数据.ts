  // 指标里的"指令执行率"虚高, 也让"上一幕没被演出来"这件事永远发现不了。
  // 现在的三态: 明确 true → 已执行; 明确 false → 未执行; 缺失 → 未执行但标注来源为缺省
  // (来源会进 说明, 让日志看得出这是"没说"而不是"说了没做")。
  const raw核验 = 载荷?.上一幕核验 && typeof 载荷.上一幕核验 === 'object' ? 载荷.上一幕核验 : {};
