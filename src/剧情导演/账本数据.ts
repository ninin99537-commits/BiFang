      // 漏输出 ≠ 删除: 旧中点还在**这一章**里, 继续沿用(否则中点会被一轮漏写悄悄清掉)。
      // 必须比章号: 换章了还沿用就是把上一章的中点搬到新章头上 —— 那比没有中点更糟。
