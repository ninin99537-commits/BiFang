  // 于是"代码为什么这么决定"成了正文的一部分(真机占 43%~51%), 演员每场有一半篇幅在读代码自言自语。
  // 「调整」照旧写进 `指令.代码调整`(:710 附近), 面板与日志仍可回看 —— 可观测性一点没少。
  const 头: string[] = [];
  if (让步冲突) 头.push(`【连败让步】冲突「${让步冲突}」本轮必须让玩家赢（玩家体验优先）。`);

  // 反舔改造(2026-10-29 二次): **不在正文指令里下强制命令** ——
  // 代码判断不了"酒馆 AI 有没有舔用户", 那是语义判断, 只能由导演模型做。
  // 所以这里只保留"记账与节流"需要的计算, 提醒文本由 取料.结构提醒 塞进导演输入。
  // 2026-11-12: 一次只催**一个**最逾期的对手, 且与提醒**共用** 字段表.取该出手的对手 ——
  // 两边各算一遍就会出现"提醒点名 A、账本记到 B"; 杂兵(强度≤3 且无伏笔)与铺垫阶段的冲突都不催。
