/**
 * 装配「本幕揭示」: 这一幕必须让读者看到/明白的少量内容。
 *
 * 来源只有两处, 都是**已经由代码确认**的:
 *   ① 本幕要兑现/逼近的伏笔里, 允许公开的那一部分(公开线头 + 兑现条件里"已经到了"的部分);
 *   ② 导演自己写进「下一幕.揭示」的少量内容(它会原样进指令, 但**幕后真相不自动透传**)。
 * **幕后真相默认不进这里** —— 只有当演员确实需要表现"知情者行为"时, 由导演写进硬性要求的必要部分。
 */
/**
 * 本幕被点名的伏笔编号: 导演在「伏笔现场」或「硬性要求」里写了 `#N` 的那几条。
 * 第二轮方案 4.1: 只有被点名的「待兑现」才进揭示 —— 否则每一轮都会把**所有**待兑现线
 * 写成"到了兑现的时候", 而证据不足的引爆又会被降回待兑现, 这类线越积越多、一起被催。
 */
export function 取点名伏笔(下一幕: any): number[] {
  const 文本 = `${String(下一幕?.伏笔现场 ?? '')}\n${String(下一幕?.硬性要求 ?? '')}`;
  const out = new Set<number>();
  for (const m of 文本.matchAll(/#(\d+)/g)) out.add(Number(m[1]));
  return [...out];
}

export function 装配本幕揭示(账本: 导演账本, 下一幕: any, 选项: { 点名?: number[]; 排除?: number[] } = {}): string[] {
  const out: string[] = [];
  // ① 导演显式声明的本幕揭示(原样保留, 零截断)
  for (const 项 of Array.isArray(下一幕?.揭示) ? 下一幕.揭示 : []) {
    const 文本 = String(项 ?? '').trim();
    if (文本) out.push(文本);
  }
  // ② 本幕**点名要兑现**的伏笔: 只把"公开线头"给它(那是读者已经看到的), 不带幕后真相。
  //    未被点名的待兑现线不进来(备忘里写的就是"未被指定的不要主动收束")。
  const 点名 = new Set(选项.点名 ?? 取点名伏笔(下一幕));
  const 排除 = new Set(选项.排除 ?? []);
  const 待兑现 = (账本.伏笔 ?? []).filter(条 => 条.状态 === '待兑现' && 点名.has(条.编号) && !排除.has(条.编号));
  for (const 条 of 待兑现) {
    const 线头 = String(条.公开线头 ?? '').trim();
    if (线头) out.push(`伏笔 #${条.编号} 到了兑现的时候: 读者之前已经看到「${线头}」, 这一幕要把它的意义揭示出来`);
  }
  return out;
}

/**
 * 装配「必须保留的后果」: 死亡/离场/永久损失/关系破裂这些**这一幕尤其不能违反**的硬约束。
 *
 * 它与常驻备忘不重复: 备忘是"一直要知道", 这里是"这一幕不能踩线"。
 * **红线最高**: 红线内容先列出, 并标明高于一切。
 *
 * 纠偏(用户报告"挨打一拳也会记录成永久后果不可复原"):
 *   - 只有**死亡**这类不可逆状态才写"不得…";
 *   - 其余持久后果按**当前状态**措辞: 「持续」写"不会无事件自动消失, 但可经治疗/赎还/和解/修笔有证据地改变";
 *     「已缓解/已解除/误记撤销」根本不进"必须保留"(它们已经不是约束了);
 *   - 关系未解矛盾同样给和解路径, 不再一律写"一句道歉不得自动复原"。
 */
export function 装配必须保留(账本: 导演账本, 红线: string[]): string[] {
  const out: string[] = [];
  for (const 项 of 红线) {
    const 文本 = String(项 ?? '').trim();
    if (文本) out.push(`【红线】${文本}(高于一切, 不得触碰)`);
  }
  for (const 命 of 账本.角色命运 ?? []) {
    if (命.状态 === '死亡') {
      out.push(`${命.角色ID} 已死亡: 不得作为活人出场或行动(回忆/记录/幻觉/设定内复活属显式例外, 且不得抹掉死亡后果)`);
    } else if (命.状态 === '离开' || 命.状态 === '失踪') {
      out.push(`${命.角色ID} 已「${命.状态}」: 不得无回归事件就出现在原场景`);
    }
    // 结构化持久后果: 只有「持续」才是约束; 其余状态已不成立, 不进本幕硬约束
    const 持续后果 = (命.持久后果 ?? []).filter(x => x?.状态 === '持续' && String(x?.内容 ?? '').trim());
    const 缓解后果 = (命.持久后果 ?? []).filter(x => x?.状态 === '已缓解' && String(x?.内容 ?? '').trim());
    for (const 后果 of 持续后果) {
      out.push(
        `${命.角色ID} 的持久后果: ${后果.内容}(仍有效, **不会因无事件而自动消失**; 但可经治疗、赎还、和解或剧情修笔有证据地缓解/解除)`,
      );
    }
    for (const 后果 of 缓解后果) {
      out.push(`${命.角色ID} 的旧后果已缓解(未消失): ${后果.内容}(仍可感知, 不要当成完全痊愈)`);
    }
    // 兼容: 老账本里只有字符串形式的 永久后果, 且还没有结构化条目时, 按"持久但不绝对"措辞
    if ((命.持久后果 ?? []).length === 0) {
      for (const 后果 of 命.永久后果 ?? []) {
        const 文本 = String(后果 ?? '').trim();
        if (文本) out.push(`${命.角色ID} 的持久后果: ${文本}(不会无事件自动消失, 可经治疗/赎还/和解等有证据地改变)`);
      }
    }
    for (const 关系 of 命.当前关系 ?? []) {
      const 矛盾 = String(关系?.未解矛盾 ?? '').trim();
      if (矛盾) out.push(`与 ${关系.对方ID} 的关系未解: ${矛盾}(不会因一句道歉自动复原; 但真正的和解事件可以让它消退)`);
    }
  }
  return out;
}

/** 跳过本幕: 作废当前指令(下一幕重新生成), 并**重置核验升级计数**(D2/G: 跳过本幕重置) */
export function 跳过本幕(账本: 导演账本): void {
  if (!账本.当前指令) return;
  账本.当前指令.已跳过 = true;
  账本.当前指令.核验升级次数 = 0;
}
