    // 2026-11-12 P0.5: 这句注释以前是**错的** —— 那时 `尾` 会把「调整」逐条拼进 硬性要求,
    // 于是"搬进调整 = 不再塞给正文"并不成立, 正文每场都在读"第 N/M 次"这种记账话。
