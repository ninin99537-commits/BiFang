    节拍,
    // 2026-11-12 硬约束通道: `头` 与 `块` 全是**代码写死的裁定**, 走 硬约束 ——
    // 不能让它们落进「第 2~4 项是演法建议, 不必逐字照做」那把伞下(真机上"必须让玩家赢"曾被渲染成建议)。
    // `ai硬性` 是导演自己的散文, 留在 硬性要求(渲染成「2. 剧情参考」)。
    硬约束: [...头, ...块],
