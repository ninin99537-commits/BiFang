/** 类型承诺块(默认「不限」→ 空串, 一个字节都不注入) */
export function build类型块(类型?: 故事类型): string {
  if (!类型 || 类型 === '不限') return '';
  const 标准 = 类型标准[类型];
  if (!标准) return '';
  return `【故事类型：${类型}】
- 这类故事讲的是: ${标准.一句话}
- 必须具备(缺一个都会"不对劲"): ${标准.必备}
- 这是**整章/整本书**的骨架, 不是"每一场都要有"; 具体落在哪一幕由你安排。
- 允许在骨架内创新, 但**不许把必备元素换掉** —— 那是换了类型, 不是创新。
`;
}

