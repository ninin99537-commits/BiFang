/**
 * 生成编剧备忘文本 —— **只写正文 AI 必须持续遵守的少量公开后果**(阶段 B 的选择性注入)。
 *
 * 与旧实现的根本区别(实施提示词 §CONSTRAINT 明令):
 *   - **不再**常驻"全部未引爆伏笔 / 计划高潮 / 幕后真相 / 秘密目标" —— 那会提前兑现、剧透、刻意反转;
 *   - 只留: 当前视角、公开死亡与永久损失、在场/离场关系、必要的当前承诺;
 *   - 伏笔只给"已经公开的线头"(不带幕后真相), 且不带计划与候选走向;
 *   - 本幕必须演出来的少量揭示走「本幕指令」(build本幕指令), 不进常驻备忘。
 *
 * 零截断: 这里挑的是**条目**(选哪些进备忘), 选中之后每一句都是原文, 不裁字。
 */
export function buildInjectionPrompt(账本: 导演账本, 选项: { 平静?: boolean } = {}): string {
  const 平静 = !!选项.平静;
  const lines: string[] = ['[剧情导演 · 编剧备忘]'];
  lines.push('以下是本场戏**已经公开**的剧情状态(外部编剧维护; 供你把握长线与连续性。它是剧情编排, 不是世界设定, 也不要整段向读者播报)。');
  lines.push('注意: 本备忘**不含**未揭晓的真相与后续计划 —— 那些只在对应的一幕里按需下发。');
  if (平静) {
    // 平静期(2026-11-08): 没有本幕指令, 不能让它去找一个不存在的「本幕剧本」
    // 自愈条款(2026-11-11): 备忘是按当时的开关状态写进世界书的, 而重写时机有限(推进/切聊天/删楼/总开关)。
    // 万一漏了一次重写, 这条备忘就会在"已经开始下令"的那一轮里继续叫演员别执行指令 ——
    // 所以让它自带失效条件: 一旦上下文里出现【本幕参考】, 以那份为准。
    lines.push(
      '**当前是平静期**: 外部编剧只记账、不下令。这一段怎么演由你决定 —— 不必推进主线、不必制造冲突, 上一条指令提到的东西也不必执行。' +
        '(这条只在"这一段确实没有本幕剧本"时有效: 一旦上下文里出现【本幕参考】, 说明平静已经结束, **以它为准**, 本条作废。)',
    );
  }

  // ① 当前视角(视角人物变了必须让正文 AI 知道)
  if (账本.当前视角) {
    lines.push(`【当前视角】${账本.当前视角}`);
  }
  if (账本.续演视角) {
    lines.push(`【续演视角】${账本.续演视角}(原视角已经无法继续, 由这个视角接着演; 旧角色留下的承诺、债务与误解仍然有效)`);
  }

  // ② 章回: 只给章号/主题/进度 —— **不给"计划高潮"**(那是导演私密的未来计划)
  const 章回 = 账本.章回;
  if (章回) {
    lines.push(`【章回】第 ${章回.章号} 章《${章回.主题}》｜进度：${章回.进度}`);
  }

  // ③ 公开死亡与永久损失、离场关系 —— 这是正文 AI **必须持续遵守**的硬约束
  const 命运 = [...(账本.角色命运 ?? [])].sort((a, b) => (命运权重[a.状态] ?? 9) - (命运权重[b.状态] ?? 9));
  // 进备忘的条件: 状态不是活跃 **或** 有仍在生效的持久后果 **或** 有未解矛盾。
  // 最后一条不能漏: 一个"活跃"的角色也可能与主角关系破裂且矛盾未解 —— 那同样是不可自动复原的公开后果。
  // 纠偏: 「已缓解/已解除/误记撤销」的后果**不再**进备忘(它们已经不是约束了, 挂着只会让演员以为还在)。
  const 有持续后果 = (项: (typeof 命运)[number]) =>
    (项.持久后果 ?? []).some(后 => 后?.状态 === '持续' || 后?.状态 === '已缓解') ||
    ((项.持久后果 ?? []).length === 0 && (项.永久后果 ?? []).length > 0);
  const 有后果 = 命运.filter(
    项 => 项.状态 !== '活跃' || 有持续后果(项) || (项.当前关系 ?? []).some(关 => String(关?.未解矛盾 ?? '').trim() !== ''),
  );
  if (有后果.length > 0) {
    lines.push('【已生效的持久后果】(这些**不会无事件自动消失**; 回忆/记录/幻觉/设定内复活属显式例外)');
    for (const 项 of 有后果) {
      const 片段: string[] = [`${项.角色ID}：${项.状态}`];
      const 持续 = (项.持久后果 ?? []).filter(后 => 后?.状态 === '持续' && String(后?.内容 ?? '').trim());
      const 缓解 = (项.持久后果 ?? []).filter(后 => 后?.状态 === '已缓解' && String(后?.内容 ?? '').trim());
      if (持续.length > 0) 片段.push(`持久后果：${持续.map(后 => 后.内容).join('；')}`);
      if (缓解.length > 0) 片段.push(`已缓解(未痊愈)：${缓解.map(后 => 后.内容).join('；')}`);
      // 兼容老账本: 还没有结构化条目时才退回字符串
      if ((项.持久后果 ?? []).length === 0 && (项.永久后果 ?? []).length > 0) {
        片段.push(`持久后果：${项.永久后果.join('；')}`);
      }
      // 关系破裂必须让演员知道"还没解决" —— 未解矛盾是**已经公开演出过**的冲突, 属于公开后果, 原样保留
      // (它和"幕后真相"不同: 读者已经看到了那场争执, 不告诉演员反而会让下一幕把它当成没发生过)
      const 破裂 = (项.当前关系 ?? []).filter(关 => String(关?.未解矛盾 ?? '').trim() !== '');
      if (破裂.length > 0) {
        片段.push(
          `未解关系：${破裂.map(关 => `${关.对方ID}(${关.关系 || '关系紧张'}·矛盾未解: ${关.未解矛盾})`).join('；')}`,
        );
      }
      // 离场者仍有未竟计划: 只给"这个人还在世界某处做自己的事", 不给具体计划内容
      if ((项.状态 === '离开' || 项.状态 === '失踪') && (项.未竟计划 ?? []).length > 0) {
        片段.push('仍在外活动(有未竟之事), 未经回归事件不得回到本场景');
      }
      lines.push(`- ${片段.join('｜')}`);
    }
  }

  // ④ 冲突/弧线: **不再常驻**。
  //    纠偏: 这两样是"未来的编排原料"——把冲突名/赌注/阶段与弧线阶段一直挂在演员眼前,
  //    等于提前提示他"往这个秘密冲突上凑""往这个成长结局演", 这属于导演私密信息。
  //    需要用到它们时, 由代码在**本幕指令**里给出本幕需要的那一小块(见 引擎规则.装配本幕揭示)。
  //    这里只给一行"有未收档的对抗存在"的**极简连续性提示**, 不给任何名称与走向。
  const 活跃冲突数 = (账本.冲突 ?? []).filter(item => !是终态.冲突(item)).length;
  if (活跃冲突数 > 0) {
    lines.push(`【进行中的对抗】${活跃冲突数} 组未收档(具体是哪一组、赌注与阶段按本幕指令下发, 不要自行猜测并推进未被下发的冲突)`);
  }

  // ⑤ 伏笔: **不在常驻备忘里罗列线头**。
  //    纠偏: 读者公开 ≠ 正文 AI 每轮都需要。把全部公开线头常驻, 会让演员在错误的时机
  //    反复碰这些线(提前兑现), 也让备忘被无关线头淹没。本幕该碰哪条由「本幕指令」指认。
  const 未结束伏笔数 = (账本.伏笔 ?? []).filter(item => !是终态.伏笔(item)).length;
  if (未结束伏笔数 > 0) {
    lines.push(
      平静
        ? `【未结束的线头】${未结束伏笔数} 条(这一段没有指定要推进哪一条 —— 你按自己觉得合适的节奏演, 不要为了收线硬塞)`
        : `【未结束的线头】${未结束伏笔数} 条(本幕需要推进哪一条由「本幕指令」指定; 未被指定的不要主动收束)`,
    );
  }

  // ⑥ 角色弧线: 同样**不常驻**(阶段是导演的编排进度, 不是演员每轮都要看的连续事实)

  lines.push(
    平静
      ? '(以上是**连续性与公开后果**的备忘: 你按它把握后果, 本幕演什么完全由你决定 —— 没有「本幕剧本」。)'
      : '(以上是**连续性与公开后果**的备忘: 你按它把握后果, 具体如何演出由你决定。本幕要推进什么, 见「本幕剧本」。)',
  );
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// 指令层注入: 本幕导演指令(易变的即时命令, 生成前注入, 不进共享世界书)
// ---------------------------------------------------------------------------

/**
 * 生成本幕指令文本(§3.3 五块 + 阶段 B 的"本幕揭示/必须保留的后果")。
 * 指令有效期 = 至下一次引擎调用。
 * 档位与红线用**指令下发时冻结的值**(无则回退当前设置), 防"新档渲染旧指令"(C6)。
 */
export function build本幕指令(账本: 导演账本, settings: Settings): string {
  const 指令 = 账本.当前指令;
  if (!指令) return '';
  const 档位 = 指令.档位 || settings.导演.强度档位;
  const 红线 = (指令.红线 && 指令.红线.length > 0) ? 指令.红线 : (settings.导演.红线 ?? []);
  const 低档 = 档位 <= 2;
  const 玩家冲突处理 = 低档
    ? '低档(1/2)：玩家行动**正常生效**，本幕指令让位——玩家体验优先，不要为了剧本强行否定玩家。'
    : '高档(3/4)：玩家行动可以**以戏剧方式失败或变形**——玩家说"我道歉"≠冲突必须化解，道歉可以被误解、被利用。';
  const blocks: string[] = [];
  // 硬性要求已改为**参考**(2026-10-29 用户要求): 它是导演给的**演法建议**, 不是逐字命令。
  // 但"参考"只放宽**怎么演**, **不放宽后果**: 玩家不喜欢也照样可以失败/失去/死亡/离开 —— 否则就是舔用户。
  // 第二轮方案 3.7: "不必逐字照做"只修饰**演法**(剧情参考/伏笔现场); 已经发生的后果与
  // 第 5/6 项(本幕揭示 / 必须保留的后果)是这一幕已经确定的事, 不在"可以不照做"的范围里。
  // 2026-11-11: **节拍也从豁免里摘出来了**(它是第 1 项) —— 理由见下面 1. 那条的注释。
  blocks.push('【本幕参考】（第 2~3 项是导演给的演法建议, 怎么演由你决定, 不必逐字照做; **【本幕硬约束】、第 1 项的结构要求、【本幕已确定】、第 4 项的禁令、第 5、6 项都是必须体现的** —— 它们只能换写法, 不能换结果。**不要迎合玩家** —— 玩家的意愿不决定结果, 失败、失去、被拒绝、角色死亡或离开都可以发生; 你可以换表达方式, 但不能取消后果）');
  // 第二轮方案 2.4/2.5: 必演事件 —— 写成"已经发生/这一幕确定发生", 不写成"请你让它发生"
  // 2026-11-13 P2 2.5: 三态里的 '无'（明确声明没有）在这里等同"没有事件" —— 三态只对提醒有意义。
  const 必演 = 指令.必演 === '无' ? null : 指令.必演;
  if (必演 && 必演.内容) {
    const 写法 = 必演.既成事实
      ? '本幕开场时这件事**已经发生**，从它之后写起，写角色怎么面对：'
      : 必演.镜头外
        ? '这件事在镜头外完成，正文只演角色**得知**它（一封信、一条消息、空了的房间、别人转述）：'
        : '这一幕确定发生：';
    blocks.push(`【本幕已确定】${写法}${必演.内容}`);
  }
  // 反全知: 导演自己过关的三问(他知道吗/证据/怎么办)一起下发 —— 正文只许用到那份证据带来的信息
  const 知情 = 指令.知情核对 ?? [];
  if (知情.length > 0) {
    const 行 = 知情.map(条 => {
      const 判 =
        条.知道吗 === '知道'
          ? `知道, 凭${条.证据 || '(证据没写)'}`
          : `${条.知道吗}${条.处理 ? ` → ${条.处理}` : ''}`;
      return `${条.角色}：${条.事}『${判}』`;
    });
    blocks.push(
      `【本幕知情核对】${行.join('；')}\n（导演自查的结果, 不是给你的新命令。写的时候: 标"知道"的只能用到那个证据带来的信息, 不要顺手扩写他还知道别的; ` +
        `标"不知道/不确定"的, 别让他说出、也别让他据此行动 —— 按箭头后面的处理写。）`,
    );
    const 缺口 = 知情.filter(条 => 条.知道吗 !== '知道' && !条.处理);
    if (缺口.length > 0) {
      blocks.push(
        `【自查没写完】${缺口.map(条 => 条.角色).join('、')} 写着"不知道/不确定", 却没写这一幕怎么办 —— 不要让他们接触这件事: 换成知道的人说, 或先演"得知"那一场。`,
      );
    }
  }
  blocks.push(`0. 当前设定：强度档位=第 ${档位} 档（${档位标准[档位] ?? ''}）；红线=${红线.length > 0 ? 红线.join('；') : '无'}${红线.length > 0 ? '（高于一切，不得触碰）' : ''}`);
  // 【本幕硬约束】(2026-11-12): 代码装配的裁定, 不是建议。
  // 以前它们拼在 硬性要求 里 → 渲染成「2. 剧情参考」→ 落进下面那句"第 2~4 项是演法建议, 不必逐字照做"的伞。
  // 真机原文: 「2. 剧情参考：【连败让步】冲突「北坡」本轮必须让玩家赢（玩家体验优先）。」—— "必须"被说成了建议。
  // **顺序是语义**: 裁定排在结构要求之前, 且标题自带"必须遵守"。
  const 硬约束 = (指令.硬约束 ?? []).map(项 => String(项 ?? '').trim()).filter(Boolean);
  if (硬约束.length > 0) {
    blocks.push('【本幕硬约束】（以下由代码裁定, **不是建议, 必须遵守** —— 你可以换写法, 但不得取消它）');
    for (const 项 of 硬约束) blocks.push(`   - ${项}`);
  }
  // 节拍(2026-11-11): 从"演法建议"里**摘出来**。它回答的是"这一段要让玩家付出什么",
  // 不是"该怎么写" —— 而核验正是按它判执行(要求受挫、实际又赢了 = 未执行)。
  // 以前它叫「本幕节拍参考」并落在"第 1~4 项不必逐字照做"的伞下, 于是注入按建议发、验收按命令判。
  const 节拍说明 = 节拍结构[指令.节拍] ?? '';
  // 「日常」是唯一一个"不许发生事"的节拍 —— 通用的"这一步要在正文里真的发生"对它是**反话**,
  // 会把正文又推回"必须来一件事"。所以单独给一句收束。
  const 是日常 = 指令.节拍 === '日常';
  blocks.push(
    `1. 这一幕的结构要求：${指令.节拍}${节拍说明 ? ` —— ${节拍说明}` : ''}。` +
      (是日常
        ? '**这一幕不需要"发生事"**: 不加新对抗、不加新角色、不加新麻烦, 也可以写得很淡。' +
          '唯一的硬要求是**已经发生的代价要出现在生活里**(伤、债、失去、关系裂缝), 不能像没发生过。'
        : '这一步要在正文里真的发生; 写法随你换, 但**结果不能换成相反**(写了受挫却让主角其实全赢 = 没做到)'),
  );
  blocks.push(`2. 剧情参考：${指令.硬性要求 || '(见节拍)'}`);
  blocks.push(`3. 伏笔现场：${指令.伏笔现场 || '无'}`);
  // 4. 导演的建议(2026-11-12): ①空就不渲染(不留一行"无"占位); ②措辞明确是**导演**的意见 ——
  // 以前叫「不建议写」, 读起来像平台的偏好, 而代码自己写的那句禁令已经移进 硬约束 了。
  const 禁止 = String(指令.禁止事项 ?? '').trim();
  // 2026-11-12 通道边界（需求方裁定）: 第 4 项**摘出伞外** —— 它没有"写法"可换。
  // 「硬性要求」是演法建议, 理由是"导演专排剧情、正文不如正文 AI 写得好"; 那个理由只对**散文**成立。
  // 「不许本轮和解 / 不许主角死」这种是**结构约束**, 留在伞下等于告诉演员"这条禁令你可以不做"。
  if (禁止) blocks.push(`4. 导演的禁令：${禁止}`);
  // 5. 本幕揭示(阶段 B): 代码从导演结果装配的"这一幕必须让演员演出来的少量线索/后果/限制"。
  //    幕后真相默认**不**在这里 —— 只有当本幕确实需要表现"知情者行为"时, 由导演写进 硬性要求 的必要部分。
  if ((指令.本幕揭示 ?? []).length > 0) {
    blocks.push(`5. 本幕揭示（这一幕必须让读者看到/明白的内容，只此一次，不要提前也不要延后）：`);
    for (const 揭示 of 指令.本幕揭示 ?? []) blocks.push(`   - ${揭示}`);
  }
  // 6. 必须保留的后果(阶段 B/C): 死亡/离场/永久损失/关系破裂的硬约束。
  //    它与常驻备忘**不重复**: 备忘是"一直要知道", 这里是"这一幕尤其不能违反"。
  if ((指令.必须保留 ?? []).length > 0) {
    blocks.push(`6. 必须保留的后果（违反即出戏；这些**不得**被这一幕自动抹平）：`);
    for (const 后果 of 指令.必须保留 ?? []) blocks.push(`   - ${后果}`);
  }
  // 7. 前情(第二轮方案 2.3): 读者早已见过、这一幕要接上的旧线索 —— 主 AI 可能已经看不到那几层了
  if ((指令.前情 ?? []).length > 0) {
    blocks.push('7. 前情（读者早已见过的旧线索，这一幕要接上；按这里的细节写，不要另编）：');
    for (const 行 of 指令.前情 ?? []) blocks.push(`   - ${行}`);
  }
  blocks.push(`玩家冲突处理：${玩家冲突处理}`);
  return blocks.join('\n');
}
