// 剧情导演 · 镜头外推进(阶段 D): 只为**少数关键 NPC**做低频独立推进。
// ---------------------------------------------------------------------------
// 设计文档 §10 阶段 D / §12 参考取舍:
//   - 借 AGARS / Generative Agents 的"独立角色目标 + 镜头外行动 + 位置与知识约束";
//   - 但**不引入逐 NPC 每轮调用**(酒馆里那太重, 也违反"每轮默认一次导演调用");
//   - 变化必须有证据、位置与知识约束, 并能对主角线产生后续影响。
//
// 实现方式:**纯函数挑人选 + 复用同一次导演调用**。
// 不在这里额外发请求 —— 镜头外的推进写进"本幕指令"的一个可选块, 由导演在同一次编排里一并处理;
// 代码只负责决定"这一轮轮到谁、为什么轮到它", 并做节流。
import type { 导演账本, 角色命运 } from './schema';
import { 离场命运状态 } from './schema';
import { 取命运, 证据统计 } from './证据链';
import { 取不知情说法, type 不知情表 } from './知情';

/** 低频节流: 同一个 NPC 至少隔这么多幕才被推进一次 */
export const 镜头外间隔幕数 = 5;
/** 单次最多推进几个 NPC(这是"选哪些条目"的克制, 不是内容截断) */
export const 单次镜头外上限 = 2;

export interface 镜头外候选 {
  角色ID: string;
  理由: string;
  /** 这个 NPC 自己的目标(推进要围绕它, 不围绕主角) */
  独立目标: string[];
  /** 位置/知识约束: 离场者只能在"别处"行动 */
  约束: string[];
  /** 当前位置(空 = 未知, 由导演在推进时补) */
  位置?: string;
}

export interface 镜头外输入 {
  账本: 导演账本;
  /** 当前幕序号(用已分析轮数, 它是单调递增的幕计数) */
  当前幕: number;
  /** 这一轮主场景里已经出场的人(不重复推进在场者) */
  在场?: string[];
}

/**
 * 挑出这一轮适合做**镜头外推进**的关键 NPC。
 *
 * 入选条件(全部满足才选):
 *   ① 在命运册里(它是有长线状态的关键角色, 不是路人);
 *   ② 有独立目标或未竟计划(没有自己的事, 推也推不出什么);
 *   ③ 距上次推进 ≥ 镜头外间隔幕数(**按幕计数**);
 *   ④ 不在当前场景里(在场的人由本幕指令直接处理, 不需要"镜头外");
 *   ⑤ 状态允许行动: 死亡不能行动; 离开/失踪**可以**在别处行动(这正是"离开不是删除")。
 *
 * 纠偏(用户报告"镜头外节流用楼层当幕数"): 节流必须用 `最后推进幕`(幕计数), 不能拿
 * `最后变化楼层`(楼层号) 与 `已分析轮数` 相减 —— 一个 100 楼出现过的角色会被判成"刚推进过",
 * 于是永远轮不到镜头外推进。老账本没有 `最后推进幕` 时按"从未推进"处理(立即可以推一次)。
 */
export function 挑镜头外候选(输入: 镜头外输入): 镜头外候选[] {
  const { 账本, 当前幕 } = 输入;
  const 在场 = new Set((输入.在场 ?? []).map(名 => String(名 ?? '').trim()).filter(Boolean));
  const 候选: { 项: 镜头外候选; 离场: boolean; 久: number }[] = [];
  for (const 命 of 账本.角色命运 ?? []) {
    const id = String(命.角色ID ?? '').trim();
    if (!id) continue;
    if (命.状态 === '死亡') continue; // ① 死者不能行动(回忆/记录/幻觉属显式例外, 不走这条线)
    if (在场.has(id)) continue; // ④ 在场者由本幕指令处理
    const 目标 = [...(命.独立目标 ?? []), ...(命.未竟计划 ?? [])].filter(x => String(x ?? '').trim() !== '');
    if (目标.length === 0) continue; // ② 没有自己的事
    const 上次幕 = Number(命.最后推进幕) || 0; // ③ **幕计数**, 不是楼层号
    const 久 = Math.max(0, 当前幕 - 上次幕);
    if (上次幕 > 0 && 久 < 镜头外间隔幕数) continue;
    const 离场 = 离场命运状态.includes(命.状态);
    const 约束: string[] = [];
    if (离场) 约束.push(`处于「${命.状态}」: 只能在别处行动, 不能无回归事件出现在主角场景`);
    if (命.状态 === '受伤') 约束.push('带伤行动: 能力受限, 不能做需要完好的事');
    const 位置 = String(命.位置 ?? '').trim();
    if (位置) 约束.push(`当前位置: ${位置}(行动必须从这个位置出发, 不得瞬移)`);
    // 知识约束: 只知道自己经历过/被告知的 —— 由 已知事实引用 表达
    const 知识 = (命.已知事实引用 ?? []).length;
    if (知识 > 0) 约束.push(`只知道 ${知识} 条已记录的关键事实, 不得凭空知道主角的私下行动`);
    候选.push({
      项: {
        角色ID: id,
        理由: 离场 ? `已${命.状态}, 靠镜头外推进维持其独立行动` : '有独立目标, 镜头外自行推进',
        独立目标: 目标,
        约束,
        位置,
      },
      离场,
      久,
    });
  }
  // 离场者优先, 其次"最久没动"的
  候选.sort((a, b) => (a.离场 === b.离场 ? b.久 - a.久 : a.离场 ? -1 : 1));
  return 候选.slice(0, 单次镜头外上限).map(项 => 项.项);
}

/**
 * 把镜头外候选渲染成**导演提示词里的一段**(不是额外请求)。
 * 导演在同一次编排里据此更新这些 NPC 的目标/计划, 并决定它对主角线的后续影响。
 * 零截断: 目标与约束都是原文。
 */
export function 渲染镜头外块(候选: 镜头外候选[], 不知情?: 不知情表): string {
  if (候选.length === 0) return '';
  const lines: string[] = [];
  lines.push('【镜头外推进(少量关键 NPC, 低频)】');
  lines.push('下面这些角色不在当前场景, 但他们有自己的目标, 世界不围着主角转。请在本轮顺带推进他们的计划(不必给他们写台词, 只需更新账本里他们的目标/计划/位置状态), 并说明**这些变化之后可能怎样影响主角线**:');
  for (const 项 of 候选) {
    lines.push(`- ${项.角色ID}（${项.理由}）`);
    if (项.独立目标.length > 0) lines.push(`  自己的目标: ${项.独立目标.join('；')}`);
    for (const 约束 of 项.约束) lines.push(`  约束: ${约束}`);
    // 反全知: 这个人自己不知道什么(记忆插件的 <cb>) —— 镜头外推进不能让他凭空知道这些
    const 不知道 = 不知情 ? 取不知情说法(不知情, 项.角色ID) : [];
    if (不知道.length > 0) lines.push(`  他不知道(他自己不知道, 别让他据此行动): ${不知道.join('；')}`);
  }
  lines.push('注意: 他们的行动必须有世界内依据(能力/位置/知识/此前选择), 不得为了给主角制造麻烦而临时降智或瞬移。');
  return lines.join('\n');
}

/**
 * 镜头外推进的**写回守卫**: 候选对某个 NPC 的改动是否合规。
 * 拒绝路径要可观察(设计文档 §9: 校验器的拒绝路径也要测, 不能只测成功样例)。
 */
export function 校验镜头外改动(账本: 导演账本, 角色ID: string, 新目标: string[]): string | null {
  const 命 = 取命运(账本, 角色ID);
  if (!命) return `${角色ID} 不在命运册里: 镜头外推进只针对关键 NPC`;
  if (命.状态 === '死亡') return `${角色ID} 已死亡: 不得推进其行动计划(只能记录其遗产/影响)`;
  const 证据 = 证据统计(命.状态证据);
  if (命.状态 !== '活跃' && 证据.可用 === 0) {
    return `${角色ID} 的状态「${命.状态}」没有可用证据: 先补证再推进(否则等于凭空给离场者安排行动)`;
  }
  if (新目标.length === 0) return `${角色ID} 没有任何目标: 镜头外推进无内容可推`;
  return null;
}

/** 镜头外推进的审计行(写进日志, 让"这一轮谁在镜头外动了"可见) */
export function 镜头外审计行(候选: 镜头外候选[]): string {
  if (候选.length === 0) return '镜头外推进: 本轮无候选(节流或没有带目标的关键 NPC)';
  return `镜头外推进: ${候选.map(项 => 项.角色ID).join('、')}`;
}

/** 某个 NPC 是否"该被推进了"(面板显示与用例共用同一口径; **按幕计数**) */
export function 该推进了(命: 角色命运, 当前幕: number): boolean {
  if (命.状态 === '死亡') return false;
  const 目标 = [...(命.独立目标 ?? []), ...(命.未竟计划 ?? [])].filter(x => String(x ?? '').trim() !== '');
  if (目标.length === 0) return false;
  const 上次幕 = Number(命.最后推进幕) || 0;
  return 上次幕 === 0 || 当前幕 - 上次幕 >= 镜头外间隔幕数;
}
