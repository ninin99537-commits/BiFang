// ---------------------------------------------------------------------------
// 去信封: 剥掉上游注入的「工具调用信封」, 让解析层看到原本的载荷文本。
//
// 2026-10-16 真机(烟火): 模型吐出来的不是裸 JSON, 而是
//     emit_complete_response_ff5b24e854bfad63f26efccd{content:{"世界":{…}}}
// 上游中转为了"逼模型把话说完"塞了一个工具, 模型就把这次调用**当文本**吐了出来 —— 那串十六进制
// 是每次请求现生成的 nonce。真载荷因此从"顶层对象"降级成"别人的一个值":
//   · 最外那个 `{` 没闭合时, 括号配平切分一个候选都切不出来 → 报"AI 没有返回 JSON 对象";
//   · 最外那个 `{` 闭合时, 收下的就是信封本身(顶层键只剩 content) → 校验层再说结构不符。
// 三个插件的解析器都会被打中(各自的扫描器不同、报错不同, 但都救不回真载荷)。
//
// 这一层只做一件事: 把信封连前缀一起切掉。剩下的文本就是原本的载荷, 后面的括号配平、载荷识别、
// 双解析器择优一个字都不用改。
//
// 注意: **不要**为此放宽各解析器里"值位置的 `{` 不算新候选"那条规则 —— 它是承重的
// (防"截断被从内层 { 切出半截对象、误判成解析成功", 见 烟火/解析.ts 的说明与用例 [10])。
// 去信封加在它**之前**, 是两件不同的事。
// ---------------------------------------------------------------------------

/** 信封 = 标识符 + `{` + 键 `content`(可带引号) + `:`。键名是上游定的, 就这一个。
 *  不锚定行首: 模型常在信封前面先说一句("好的, 结果如下: …"), 那截散文一起丢掉即可。
 *  也不怕误伤合法载荷 —— 判据要求 `{` 前面有个标识符, 而 `{"content": …}` 这种合法载荷没有。 */
const 信封 = /[A-Za-z_$][\w$.-]*\s*\{\s*["']?content["']?\s*:\s*/;

/**
 * 有信封就剥掉, 没有就**原样返回**(一个字节都不改, 连首尾空白也不动)。
 *
 * 两种形状都收:
 *  1. 载荷**内联**在信封里(`{content:{"世界":…}}`) —— 真机见到的就是这个;
 *  2. 载荷被当成**字符串**传(`{content:"{\"世界\":…}"}`) —— 真工具调用(arguments 是 JSON 串)的样子。
 */
export function 去信封(文本: string): string {
  let 命中 = 信封.exec(文本);
  if (!命中) return 文本;
  let 余下 = 文本.slice(命中.index + 命中[0].length);
  // 套了两层信封的也认(上游偶尔会再包一次)
  while ((命中 = 信封.exec(余下))) 余下 = 余下.slice(命中.index + 命中[0].length);
  余下 = 余下.trim();
  if (!余下.startsWith('"')) return 余下;
  // 形状 2: 值是字符串 —— 取出字符串本体再交回去(末尾可能还挂着信封自己的 `}`)
  for (const 候选 of [余下, 余下.replace(/\}\s*$/, '')]) {
    try {
      const 值 = JSON.parse(候选);
      if (typeof 值 === 'string') return 值;
    } catch {
      // 不是"载荷当字符串"的形状, 交给后面的解析层按原文处理
    }
  }
  return 余下;
}
